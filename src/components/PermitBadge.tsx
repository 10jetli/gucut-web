import { ป้ายลซ2, type ขอบเขตป้าย } from "@/lib/permit-label";

/* 🏷️ ป้าย 【ต้องขอ ลซ.2 ก่อน】 — ท่านประธานสั่ง 10 ต.ค. 2569 "จัดการ ทุกที่ · ที่เว็บ gucut ด้วย"
 *
 * 🔑 เป็น **ป้ายที่คิดสดจากข้อมูล** ไม่ใช่ข้อความที่ไปต่อหัวชื่อสินค้าใน products.json
 *    เหตุผลอยู่ในหัว `src/lib/permit-label-core.mjs` — สรุปสั้น: บาร์ใบเดียวมีทั้งของที่
 *    ต้องขอและของที่ยกเว้น ⇒ ต่อหัวชื่อ = บอกคนซื้อ 12″ ว่าต้องขอใบทั้งที่ไม่ต้อง
 *
 * ⚠️ ข้อความต้องเป็น `【 】` ปีกกาหนา ไม่ใช่ `[ ]` (ท่านสั่งเจาะจง) ⇒ อ่านจาก `ป้ายลซ2` ที่เดียว
 * ⚠️ สีต้องไม่ใช่สีส้มแบรนด์ — ส้มในเว็บนี้หมายถึง "ราคา/ลดราคา" ทั้งหมด
 *    ป้ายนี้เป็น **เงื่อนไขก่อนซื้อ** ไม่ใช่โปรโมชัน ⇒ ใช้พื้นเข้มตัวขาวให้อ่านออกชัดบนรูปขาว
 */
export default function PermitBadge({
  ขอบเขต,
  className = "",
}: {
  ขอบเขต: ขอบเขตป้าย;
  className?: string;
}) {
  if (!ขอบเขต) return null;
  return (
    <span
      className={`inline-flex items-center rounded-sm bg-[#1a1a1a] px-1.5 py-0.5 text-[10px] font-semibold leading-tight text-white ${className}`}
    >
      {ป้ายลซ2}
      {/* 🔴 "บางตัวเลือก" ต้องเขียนว่า **บางขนาด** — เหมารวมทั้งใบคือการติดป้ายผิดตัว
          ซึ่งท่านห้ามเองในใบสั่ง ("ติดผิดตัว = เสียลูกค้าฟรี ๆ") */}
      {ขอบเขต === "บางตัวเลือก" && <span className="ml-1 font-normal opacity-90">(บางขนาด)</span>}
    </span>
  );
}
