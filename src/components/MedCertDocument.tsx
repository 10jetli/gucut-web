//    แต่สำนักงานขอจริง และมีข้อความที่ต้องรับรอง 4 ข้อเฉพาะเจาะจง
//    ข้อความทั้งหมดมาจากเจ้าของร้าน (25 ส.ค. 2569) ซึ่งส่งลูกค้าไปยื่นมาแล้ว
//
// ⚠️ ทำไมต้องพิมพ์ให้ — คลินิกทั่วไปไม่รู้ว่าต้องรับรองอะไรบ้างสำหรับเรื่องนี้
//    ถ้าลูกค้าไปมือเปล่าแล้วหมอออกใบรับรองแพทย์แบบทั่วไปมา สำนักงานตีกลับ
//    ลูกค้าเสียทั้งค่าตรวจและเสียเที่ยว แล้วต้องไปหาหมอใหม่
//    พิมพ์ข้อความให้เสร็จแล้วยื่นให้หมอกรอกผลตรวจกับเซ็น จบในรอบเดียว
//
// ⚠️ ห้ามกรอกวันที่ตรวจหรือผลตรวจให้ล่วงหน้าเด็ดขาด
//    สองช่องนั้นเป็นคำรับรองของแพทย์ ไม่ใช่ของลูกค้าหรือของร้าน
//    เติมให้ = ปลอมเอกสารทางการแพทย์
//    ที่เติมได้คือข้อมูลตัวตนของลูกค้าเท่านั้น (ชื่อ อายุ เลขบัตร)
// ---------------------------------------------------------------------------

import { thaiDigits } from "@/lib/permit";

/** ผลตรวจ 4 ข้อที่สำนักงานขอให้แพทย์รับรอง */
export const MED_ITEMS = [
  "มีสุขภาพร่างกายแข็งแรงสมบูรณ์ สามารถประกอบอาชีพและใช้เครื่องจักรกล (เลื่อยโซ่ยนต์) ได้ตามปกติ",
  "ไม่เป็นคนวิกลจริต หรือจิตฟั่นเฟือนไม่สมประกอบ ไม่ปรากฏภาวะที่ทำให้เป็นคนไร้ความสามารถหรือเสมือนไร้ความสามารถ",
  "ไม่เป็นผู้ติดยาเสพติดให้โทษ และไม่เป็นผู้ติดสุราเรื้อรัง",
  "ไม่เป็นโรคติดต่อร้ายแรงหรือโรคที่เป็นอุปสรรคต่อการปฏิบัติงาน",
] as const;

function Fill({ v, w, grow }: { v?: string; w?: string; grow?: boolean }) {
  return (
    <span
      className={"lz-fill" + (grow ? " lz-grow" : "")}
      style={w && !grow ? { minWidth: w } : undefined}
    >
      {v || ""}
    </span>
  );
}

export default function MedCertDocument({
  name, age, idNumber,
}: { name: string; age: string; idNumber: string }) {
  const t = thaiDigits;
  // คำนำหน้าอยู่ในชื่ออยู่แล้ว (มาจากบัตร) จึงตัดออกจากช่องชื่อไม่ให้ซ้ำกับที่ฟอร์มพิมพ์ไว้
  const bare = name.replace(/^(นาย|นางสาว|นาง|น\.ส\.)\s*/, "").trim();

  return (
    <section className="lz-page">
      {/* ⚠️ ต้องบอกให้ชัดว่าหน้านี้เอาไปโรงพยาบาล ไม่ใช่เอาไปสำนักงาน
          ลูกค้าที่เอาปึกกระดาษไปยื่นทั้งหมดโดยยังไม่ได้ให้หมอเซ็น จะโดนตีกลับ */}
      <p className="lz-hand">✂ หน้านี้เอาไปให้แพทย์ที่โรงพยาบาลหรือคลินิกกรอกและเซ็น</p>

      <h1 className="lz-title">ใบรับรองแพทย์</h1>

      <p className="lz-right2">
        สถานพยาบาล<Fill grow />
      </p>
      <p className="lz-right2">
        วันที่<Fill w="14mm" />เดือน<Fill w="28mm" />พ.ศ.<Fill w="18mm" />
      </p>

      <p className="lz-line lz-mt">
        ขอรับรองว่า นาย/นาง/นางสาว<Fill v={bare} grow />
      </p>
      <p className="lz-line">
        อายุ<Fill v={t(age)} w="16mm" />ปี&ensp;เลขประจำตัวประชาชน
        <Fill v={t(String(idNumber || "").replace(/\D/g, ""))} grow />
      </p>
      <p className="lz-line">
        ได้รับการตรวจร่างกายเมื่อวันที่<Fill w="46mm" />ผลการตรวจปรากฏว่า
      </p>

      <ol className="lz-med">
        {MED_ITEMS.map((x, i) => (
          <li key={i}>
            <span className="lz-medno">{t(String(i + 1))}.</span>
            <span>{x}</span>
          </li>
        ))}
      </ol>

      <p className="lz-note lz-mt">
        ใบรับรองนี้ออกให้เพื่อใช้ประกอบคำขอรับใบอนุญาตให้มีเลื่อยโซ่ยนต์ (แบบ ลซ.๑)
        ตามพระราชบัญญัติเลื่อยโซ่ยนต์ พ.ศ. ๒๕๔๕
      </p>

      <div className="lz-sign">
        <p>(ลงชื่อ)<Fill w="56mm" />แพทย์ผู้ตรวจ</p>
        <p className="lz-signname">(<Fill w="56mm" />)</p>
        <p className="lz-signname">ใบอนุญาตประกอบวิชาชีพเวชกรรมเลขที่<Fill w="42mm" /></p>
      </div>
    </section>
  );
}
