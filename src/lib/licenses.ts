/** ยังใช้ได้อยู่ไหม — คิดจากวันที่เสมอ ห้ามเขียนตายตัว */
export const isActive = (l: License, now = new Date()) =>
  l.expires === null || new Date(l.expires) >= now;

export const activeLicenses = (now = new Date()) => LICENSES.filter((l) => isActive(l, now));

/** วันที่แบบไทย เช่น "4 ธันวาคม 2567" */
export function thaiDate(iso: string) {
  const d = new Date(iso);
  const month = [
    "มกราคม", "กุมภาพันธ์", "มีนาคม", "เมษายน", "พฤษภาคม", "มิถุนายน",
    "กรกฎาคม", "สิงหาคม", "กันยายน", "ตุลาคม", "พฤศจิกายน", "ธันวาคม",
  ][d.getUTCMonth()];
  return `${d.getUTCDate()} ${month} ${d.getUTCFullYear() + 543}`;
}

/**
 * ประโยคสรุปสั้น ๆ สำหรับให้ผู้ช่วย AI หยิบไปตอบลูกค้า
 * ⚠️ สร้างจากใบที่ "ยังใช้ได้จริง" เท่านั้น ใบที่หมดอายุไม่ถูกนับ
 */
export function summaryLine(now = new Date()) {
  const active = activeLicenses(now);
  const kinds = active.map((l) => l.kind.replace(/^ใบอนุญาตให้/, "").replace(/\s*\(.*\)$/, "").trim());
  if (!kinds.length) return "";
  return `${LICENSEE.name} (เลขนิติบุคคล ${LICENSEE.taxId}) ได้รับใบอนุญาตจาก${REGISTRAR} ` +
    `ให้${kinds.join(" และ")} ตามพระราชบัญญัติเลื่อยโซ่ยนต์ พ.ศ. 2545`;
}
