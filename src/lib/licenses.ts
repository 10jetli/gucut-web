export interface Trademark {
  /** ชื่อเครื่องหมายตามที่ปรากฏบนหนังสือสำคัญ */
  mark: string;
  /** ทะเบียนเลขที่ */
  regNo: string;
  /** คำขอเลขที่ */
  appNo: string;
  owner: string;
  /** จำพวกสินค้า (Nice Classification) */
  niceClass: number;
  goods: string;
  /** วันจดทะเบียน — วันที่เริ่มนับอายุ 10 ปี */
  registered: string;
  /** วันที่ออกหนังสือสำคัญ */
  issued: string;
  /** วันสิ้นอายุ (ต่ออายุได้ทุก 10 ปี) */
  expires: string;
}

