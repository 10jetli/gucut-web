//   public/parts/<รุ่น>.json      ← กลุ่ม + ตารางอะไหล่ + พิกัดจุดกด
//   public/parts/<รุ่น>/<id>.webp ← ภาพลายเส้นที่ตัดหัว/ท้าย/ลายน้ำออกแล้ว
//
// 🔑 จุดกดในภาพ "สร้างอัตโนมัติ" ไม่ได้วางมือ — เลขชี้ในคู่มือเป็นข้อความจริง
//    ที่มีพิกัดอยู่ใน PDF จึงดึงมาแปลงเป็นพิกัด 0–1 เทียบกรอบภาพได้ตรง ๆ
//
// ⚠️ ภาพลายเส้นเป็นงานของ STIHL — ยังไม่ได้ข้อสรุปเรื่องสิทธิ์การใช้
//    หน้าจึงตั้ง noindex ไว้ก่อน (ดู src/app/parts/[model]/page.tsx)

/** หนึ่งบรรทัดในตารางอะไหล่ */
export type PartRow = {
  /** เลขชี้ในภาพ เช่น "7" — ซ้ำกันได้ถ้าชิ้นเดียวกันมีหลายรหัสให้เลือก */
  เลข: string;
  /** รหัสอะไหล่ เช่น "1123 020 1209" */
  รหัส: string;
  จำนวน: string;
  /** ชื่อภาษาอังกฤษจากคู่มือ — เจ้าของร้านสั่งให้เอาแต่อังกฤษ */
  ชื่อ: string;
};

/** จุดกดบนภาพ — x/y เป็นสัดส่วน 0–1 เทียบความกว้าง/สูงของภาพ */
export type PartDot = { เลข: string; x: number; y: number };

export type PartGroup = {
  id: string;
  ตัวอักษร: string;
  ชื่อ: string;
  ภาพ: string;
  w: number;
  h: number;
  จุด: PartDot[];
  อะไหล่: PartRow[];
};

export type PartsDoc = {
  รหัสรุ่น: string;
  ชื่อรุ่น: string;
  ที่มา: string;
  กลุ่ม: PartGroup[];
};

export type PartsModel = {
  /** ใช้เป็น URL: /parts/f250/ */
  slug: string;
  /** ชื่อที่ลูกค้าเห็น */
  ชื่อ: string;
  /** คำที่ร้านใช้เรียกรุ่นนี้ในชื่อสินค้า — ใช้ค้นของในคลังตอนจับคู่ */
  คำค้นร้าน: string;
};

// ⚠️ เพิ่มรุ่นใหม่ต้องทำสองอย่างคู่กันเสมอ: ใส่ในรายการนี้ **และ** วางไฟล์
//    public/parts/<slug>.json + public/parts/<slug>/ ให้ครบ
//    ใส่ชื่อแต่ไม่มีไฟล์ = หน้าเปิดมาว่าง ไม่มีอะไรฟ้อง
export const PARTS_MODELS: PartsModel[] = [
  { slug: "f250", ชื่อ: "F 250", คำค้นร้าน: "MS250" },
  { slug: "f381", ชื่อ: "F 381", คำค้นร้าน: "MS381" },
  { slug: "f440", ชื่อ: "F 440", คำค้นร้าน: "MS440" },
  { slug: "f660", ชื่อ: "F 660", คำค้นร้าน: "MS660" },
  { slug: "f070", ชื่อ: "F 070", คำค้นร้าน: "MS070" },
  { slug: "f090", ชื่อ: "F 090", คำค้นร้าน: "MS070" },
];

export function หารุ่น(slug: string): PartsModel | undefined {
  return PARTS_MODELS.find((m) => m.slug === slug);
}

/** คีย์ของอะไหล่หนึ่งชิ้น — ใช้เป็นคีย์ตารางจับคู่รหัสร้าน */
export function คีย์อะไหล่(รหัส: string): string {
  return รหัส.replace(/\s+/g, "");
}
