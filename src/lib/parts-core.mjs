/** สรุปของที่เลือกไว้ สำหรับแถบลอยล่างจอ
 *  ⚠️ คืน **สองเลข** คือจำนวนชิ้นกับจำนวนรายการ เพราะ "เลือก 3 รายการ 12 ชิ้น"
 *     ไม่ใช่เลขเดียวกัน · โชว์เลขเดียวแล้วคนอ่านจะเข้าใจผิดทันที
 *
 *  🔒 ด่าน `check-num-helpers` ตีกลับ `Number(x) || 0` ที่นี่ (จุดที่ 24 เพดาน 23 · 12 ต.ค. 2569)
 *     ⇒ **ไม่ยกเพดาน** เพราะเพดานนี้ลดได้ห้ามเพิ่ม — แก้ที่ตัวเองแทน
 *     ⚠️ และท่าที่แก้ **ไม่ใช่แค่ปลดด่าน** — ของเดิมปล่อย `Infinity` ผ่าน (truthy ⇒ `|| 0` ไม่ทำงาน)
 *        📏 วัดจริง: ของเก่า `{รายการ:1, ชิ้น:Infinity, เงิน:Infinity}` ⇒ บนจอเป็น
 *           "เลือก 1 รายการ · `Infinity` ชิ้น · `฿∞`" (ช่องชิ้นเป็น JSX ดิบ · ช่องเงินผ่าน toLocaleString)
 *        ⇒ สองช่องเรนเดอร์คนละทาง ⇒ **ห้ามตามหาอาการด้วยการ grep ตัวอักษรที่เห็นบนจอ**
 *     🔑 บนจอจริงจำนวนถูกจำกัดด้วย `ของ.st` อยู่แล้ว ⇒ ตัวเช็คนี้เป็น **เกราะ ไม่ใช่หนี้**
 *        แต่ฟังก์ชันนี้เป็น export ใครเรียกก็ได้ ⇒ **ห้ามถอดด้วยเหตุผลว่า "เกิดไม่ได้จากหน้าจอ"**
 *        (เหตุที่ทำให้เกิดไม่ได้อยู่คนละไฟล์กับเกราะ)
 *
 *  @param {Record<string, number>} เลือก
 *  @param {Record<string, { price?: number | null } | null | undefined>} ของทั้งหมด
 *  @returns {{ รายการ: number, ชิ้น: number, เงิน: number }} */
export function สรุปที่เลือก(เลือก, ของทั้งหมด) {
  let รายการ = 0;
  let ชิ้น = 0;
  let เงิน = 0;
  for (const [คีย์, จำนวน] of Object.entries(เลือก)) {
    const จำนวนดิบ = Number(จำนวน);
    if (!Number.isFinite(จำนวนดิบ)) continue;   // "อ่านค่าไม่ได้" กับ "เลือก 0 ชิ้น" คนละเรื่อง
    const n = Math.max(0, Math.floor(จำนวนดิบ));
    if (!n) continue;
    const ของ = ของทั้งหมด[คีย์];
    if (!ของ || typeof ของ.price !== "number") continue;
    รายการ += 1;
    ชิ้น += n;
    เงิน += ของ.price * n;
  }
  return { รายการ, ชิ้น, เงิน };
}
