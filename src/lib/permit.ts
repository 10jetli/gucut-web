/**
 * แปลงเลขอารบิกเป็นเลขไทย
 *
 * ⚠️ ใบที่ยื่นผ่านแล้วกรอกด้วยเลขไทยทั้งหมด (๘๘๐๐ · ๕.๕ · ๒๘) เจ้าของร้านยืนยัน
 *    แต่ตัวอักษรโรมันคงไว้เหมือนเดิม (NEWWAVE / SUPER-S ไม่ได้แปลง)
 *    จุดทศนิยมกับขีดกลางก็คงไว้ — แปลงเฉพาะ 0-9 เท่านั้น
 */
export const thaiDigits = (s: string | number) =>
  String(s).replace(/[0-9]/g, (d) => "๐๑๒๓๔๕๖๗๘๙"[Number(d)]);

/**
 * ข้อความที่กรอกลงช่อง "ประเภทเครื่องจักรกลต้นกำลัง"
 *
 * ⚠️ ฟอร์มมีสองเวอร์ชันในมือ และช่องไม่เหมือนกัน
 *      PDF ที่ได้มา (8 หน้าแรก) : "ประเภทเครื่องจักรกลต้นกำลัง...........กำลังเครื่องจักรกล"
 *      ใบที่ยื่นผ่านแล้ว        : "ประเภทเครื่องจักรกลต้นกำลัง....ยี่ห้อ/รุ่น....กำลังเครื่องจักรกล"
 *    ซูมดูใบที่ผ่านแล้วชัดเจนว่า "ยี่ห้อ/รุ่น" เป็นตัวพิมพ์สีดำของฟอร์ม ไม่ใช่ที่คนเขียนเติม
 *
 *    จึงเขียนยี่ห้อ/รุ่นต่อท้ายประเภทเครื่องไปเลย — ได้เนื้อความตรงกับใบที่นายทะเบียน
 *    รับไปแล้วทุกตัวอักษร และใช้ได้กับฟอร์มทั้งสองเวอร์ชันโดยไม่ต้องเดาว่าจะเจอเวอร์ชันไหน
 *    (ถ้าเจอเวอร์ชันที่มีป้ายอยู่แล้วจะอ่านซ้ำนิดหน่อย แต่ข้อมูลถูกต้อง ดีกว่าเว้นว่าง)
 */
export const engineField = (m: Pick<SawModel, "brand" | "model">) =>
  `${ENGINE_TYPE} ยี่ห้อ/รุ่น ${m.brand}/${thaiDigits(m.model)}`;

