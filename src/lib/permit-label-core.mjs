/** ค่านี้ขึ้นต้นด้วยรหัสนั้นแบบมีขอบเขตไหม — เท่ากันเป๊ะ หรือมี `-` คั่นต่อท้าย
 *  🚫 ห้ามใช้ `includes` (จับของคนอื่น) และห้ามใช้ `===` เฉย ๆ (พลาด `00073-11.8-NW`) */
export function ขึ้นต้นด้วยรหัส(ค่า, รหัส) {
  const s = typeof ค่า === "string" ? ค่า.trim() : "";
  if (!s || typeof รหัส !== "string" || !รหัส) return false;
  return s === รหัส || s.startsWith(`${รหัส}-`);
}

const อยู่ในรายชื่อขึ้นต้น = (ค่า, รายชื่อ) => รายชื่อ.some((ร) => ขึ้นต้นด้วยรหัส(ค่า, ร));

/** ตัวเลือกนี้ต้องขอ ลซ.2 ไหม — **สามสถานะ ห้ามยุบ**
 *  `"ต้องขอ"` · `"ยกเว้น"` (ยืนยันแล้วว่าไม่ต้อง) · `"ไม่เกี่ยว"` (ไม่ใช่ของกลุ่มควบคุมเลย เช่น โซ่ อะไหล่)
 *  🔑 แยก `ยกเว้น` ออกจาก `ไม่เกี่ยว` เพราะอย่างแรกคือคำตอบที่วัดมาแล้ว
 *     ส่วนอย่างหลังคือ "ไม่รู้จัก" ⇒ วันที่มีสินค้าควบคุมตัวใหม่เข้ามา มันจะตกมาที่ `ไม่เกี่ยว`
 *     แล้วเทสจะจับได้ ไม่ใช่เงียบหายไปกับของอีกสองพันรายการ
 *  ลำดับการตรวจมีความหมาย: ตัวเลือกบาร์ในทะเบียนมาก่อนรหัสยกเว้นของ "ตัวสินค้า"
 *  เพราะสินค้าใบเดียวกันมีทั้งสองแบบ (`01387` ยกเว้น แต่ `Bar NW 16` ของใบเดียวกันต้องขอ) */
export function สถานะป้ายของตัวเลือก({ sku, k, h } = {}) {
  if (ตัวเลือกบาร์ในทะเบียน.includes(typeof k === "string" ? k.trim() : "")) return "ต้องขอ";
  if (อยู่ในรายชื่อขึ้นต้น(sku, รหัสเลื่อยต้องขอ)) return "ต้องขอ";       /* เลื่อย: ทุกตัวเลือกของรุ่นนั้น */
  if (handleเลื่อยต้องขอ.includes(typeof h === "string" ? h.trim() : "")) return "ต้องขอ";
  if (อยู่ในรายชื่อขึ้นต้น(k, รหัสยกเว้น) || อยู่ในรายชื่อขึ้นต้น(sku, รหัสยกเว้น)) return "ยกเว้น";
  return "ไม่เกี่ยว";
}

/** ต้องขอ ลซ.2 ไหม (แบบสองทาง สำหรับที่ที่ต้องการแค่ติด/ไม่ติดป้าย) */
export const ตัวเลือกต้องขอลซ2 = (x) => สถานะป้ายของตัวเลือก(x) === "ต้องขอ";

/** สินค้าใบนี้ต้องติดป้ายไหม — `"ทุกตัวเลือก"` · `"บางตัวเลือก"` · `null`
 *  🔑 `"บางตัวเลือก"` มีไว้สำหรับบาร์ ⇒ หน้าจอต้องเขียนว่า **บางขนาด** ไม่ใช่เหมารวมทั้งใบ
 *  ⚠️ สินค้าที่ไม่มีตัวเลือก (`v` ว่าง) ให้ตัดสินจากตัวสินค้าเอง — สามรุ่นที่ไม่มี sku อยู่กลุ่มนี้ */
export function ป้ายของสินค้า(p) {
  if (!p || typeof p !== "object") return null;
  const ตัวเลือก = Array.isArray(p.v) && p.v.length
    ? p.v.map((v) => ({ sku: p.sku, k: v?.k, h: p.h }))
    : [{ sku: p.sku, k: p.sku, h: p.h }];
  const ต้องขอ = ตัวเลือก.filter((x) => ตัวเลือกต้องขอลซ2(x)).length;
  if (!ต้องขอ) return null;
  return ต้องขอ === ตัวเลือก.length ? "ทุกตัวเลือก" : "บางตัวเลือก";
}
