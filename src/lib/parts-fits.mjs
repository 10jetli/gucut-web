//    และของชิ้นนั้นอยู่ในคู่มือจริง (fmini กลุ่ม L เลข L7 = buffer จำนวน 2 · รหัส 23715483000)
//    **แต่ไม่มีในดัชนีจับคู่** ⇒ ลูกค้าที่เปิดหน้านั้นไม่มีทางไปผังได้
// ⇒ ทางนี้อ่านจาก `part-info.json` (`fits`/`pos` ที่แกะจากชื่อสินค้า) เป็น **ทางที่สอง**
//    สองทางรวมกันแบบ "เพิ่มอย่างเดียว" — ไม่แทนกัน เพราะตอบคนละคำถาม:
//      bysku = "ชิ้นนี้คือรหัสอะไหล่ตัวไหน" · fits = "ชื่อสินค้าบอกว่าใส่รุ่นอะไร"
//
// 🚫 **ห้ามเทียบรุ่นด้วย `includes()`** — "MINI" กับ "MINI-ONE" เป็นคนละรุ่น
//    และ MINI-ONE ท่านประธานสั่งว่าไม่ทำ (ดู PARTS_MODELS) ⇒ ต้องเท่ากันเป๊ะหลังล้างรูป
//    (คลาสเดียวกับบทเรียน `no-substring-classification` — ชื่อที่ยาวกว่าผ่านฟรี)

/** ล้างรูปคำรุ่นให้เทียบกันได้ — ตัดช่องว่าง/ขีด แล้วเป็นตัวพิมพ์ใหญ่ */
export function คำรุ่น(s) {
  return String(s ?? "").toUpperCase().replace(/[\s_-]+/g, "");
}

/** คำที่เรียกรุ่นหนึ่งได้ — **มาจากตาราง PARTS_MODELS เองทั้งสามช่อง** ไม่ได้แต่งขึ้นใหม่
 *  🔑 ตารางนั้นเป็นคนประกาศเองว่า slug `f250` = ชื่อ "F 250" = คำค้นร้าน "MS250"
 *     ⇒ รับทั้งสามรูปคือการ *อ่านตาราง* ไม่ใช่การเดาว่า F กับ MS เท่ากัน
 *     📏 ถ้าไม่รับ slug ด้วย ของจริงจะหลุด: `fits: ["F038"]` มี 15 ชิ้น
 *        แต่คำค้นร้านของรุ่นนั้นเขียนว่า "MS038" ⇒ จับไม่ติดสักชิ้น */
export function คำเรียกของรุ่น(m) {
  return new Set([m?.slug, m?.ชื่อ, m?.คำค้นร้าน].map(คำรุ่น).filter(Boolean));
}

/** แยกตำแหน่งในผัง: "L7" → กลุ่ม L เลข 7 · "NO.17" → ไม่มีตัวอักษรกลุ่ม
 *  คืน `null` เมื่อแยกไม่ได้ ⇒ ผู้เรียกต้องลิงก์หน้าผังเปล่า ๆ ไม่ใช่เดาตำแหน่ง */
export function แยกตำแหน่ง(pos) {
  const s = String(pos ?? "").trim().toUpperCase();
  const m = /^([A-Z])\s*0*(\d{1,3})$/.exec(s);
  if (!m) return null;
  return { ตัวอักษร: m[1], เลข: m[2], เต็ม: `${m[1]}${m[2]}` };
}

/** ตำแหน่งนั้น **มีอยู่จริงในคู่มือเล่มนั้น** ไหม
 *
 *  🔑 ข้อที่ทำให้ฟังก์ชันนี้จำเป็น: **คู่มือเขียนเลขแถวไม่เหมือนกัน** (วัดทั้ง 16 เล่ม 16 ต.ค. 2569)
 *     · `fmini` เขียนเลขแถวติดตัวอักษรกลุ่ม → `"L7"`  (121/121 แถว)
 *     · อีก 15 เล่มเขียนเลขเปล่า ๆ ต่อกลุ่ม → `"7"`   (0 แถวที่มีตัวอักษรนำ)
 *     ⇒ ยิง `n=L7` ใส่เล่มที่เขียน `"7"` จะไฮไลต์ไม่ติด **แบบเงียบ ๆ** (หน้ายังเปิดได้ ดูเหมือนปกติ)
 *  ⇒ จึงต้องเทียบกับ `เลข` ที่อยู่ในไฟล์จริง ไม่ใช่เดารูปแบบ
 *  🚫 ไม่เจอ = คืน `null` ⇒ **ลิงก์หน้าผังเปล่า ๆ ดีกว่าลิงก์ที่พาไปผิดที่**
 */
export function ตรวจตำแหน่งในคู่มือ(doc, pos) {
  const t = แยกตำแหน่ง(pos);
  if (!t || !doc || !Array.isArray(doc.กลุ่ม)) return null;
  const g = doc.กลุ่ม.find((x) => String(x?.ตัวอักษร ?? "").toUpperCase() === t.ตัวอักษร);
  if (!g || !Array.isArray(g.อะไหล่)) return null;
  // ลองทั้งสองรูปที่คู่มือใช้จริง — เอารูปที่ไฟล์นั้นมีจริงเท่านั้น
  for (const รูป of [t.เต็ม, t.เลข]) {
    if (g.อะไหล่.some((r) => String(r?.เลข ?? "").toUpperCase() === รูป)) {
      return { กลุ่ม: g.ตัวอักษร, เลข: รูป };
    }
  }
  return null;
}

/** รุ่นที่ควรโชว์ลิงก์สำหรับสินค้าชิ้นหนึ่ง
 *
 *  @param ข้อมูลชิ้น  `{ fits?: string[], pos?: string[] }` จาก part-info.json
 *  @param รุ่นทั้งหมด  PARTS_MODELS — **รายชื่อนี้คือรายชื่อรุ่นที่มีหน้าผังจริง**
 *                     (ด่าน `parts-models-ของครบ.test.mjs` ตรวจว่าไฟล์ครบทุกชื่อ)
 *                     ⇒ จับคู่กับตารางนี้ = ทำตามข้อ ③ "รุ่นที่ยังไม่มีหน้าผัง ห้ามโชว์ลิงก์"
 *  @param คู่มือของรุ่น  `(slug) => PartsDoc | null` — ใช้ยืนยันตำแหน่งก่อนใส่ลงลิงก์
 */
export function รุ่นที่ลิงก์ได้(ข้อมูลชิ้น, รุ่นทั้งหมด, คู่มือของรุ่น) {
  const fits = Array.isArray(ข้อมูลชิ้น?.fits) ? ข้อมูลชิ้น.fits : [];
  const pos = Array.isArray(ข้อมูลชิ้น?.pos) ? ข้อมูลชิ้น.pos : [];
  if (!fits.length || !Array.isArray(รุ่นทั้งหมด)) return [];
  const คำในชื่อ = new Set(fits.map(คำรุ่น).filter(Boolean));
  const out = [];
  for (const m of รุ่นทั้งหมด) {
    let ตรง = false;
    for (const คำ of คำเรียกของรุ่น(m)) if (คำในชื่อ.has(คำ)) { ตรง = true; break; }
    if (!ตรง) continue;
    const doc = typeof คู่มือของรุ่น === "function" ? คู่มือของรุ่น(m.slug) : null;
    let ที่ = null;
    for (const p of pos) { ที่ = ตรวจตำแหน่งในคู่มือ(doc, p); if (ที่) break; }
    out.push({ slug: m.slug, ชื่อ: m.ชื่อ, กลุ่ม: ที่?.กลุ่ม ?? null, เลข: ที่?.เลข ?? null });
  }
  return out;
}

/** ที่อยู่ของลิงก์ — มีตำแหน่งที่ยืนยันแล้วถึงจะติดพารามิเตอร์
 *  🔑 พารามิเตอร์ที่ยืนยันไม่ได้ **ห้ามติดไป** ไม่ใช่ติดไปแล้วหวังว่าจอจะเมินให้ */
export function ที่อยู่ลิงก์(x) {
  const ฐาน = `/parts/${x.slug}/`;
  if (!x.กลุ่ม || !x.เลข) return ฐาน;
  return `${ฐาน}?g=${encodeURIComponent(x.กลุ่ม)}&n=${encodeURIComponent(x.เลข)}`;
}
