/** บุลเล็ตที่ต้องตัดทิ้ง — ของที่เอาออกจากหน้าเว็บแล้วแต่ยังค้างอยู่ในคำอธิบายที่นำเข้ามา */
const ตัดทิ้ง = [
  /* 14 ต.ค. 2569 — ปุ่มดาวน์โหลดไฟล์อะไหล่ถูกเอาออกตามคำสั่งท่านประธาน
     ("ไม่จำเป็นละ เรามีแผนผัง") แทนด้วยหน้า /parts/ ที่กดดูทีละชิ้นได้ */
  /^\s*ดาวน์โหลดอะไหล่\s*$/,
];

export function ล้างคำอธิบาย(d) {
  return String(d || "")
    .split("\u2022")
    .filter((seg) => !ตัดทิ้ง.some((re) => re.test(seg)))
    .join("\u2022")
    .replace(/^\s*\u2022\s*/, "")
    .trim();
}
