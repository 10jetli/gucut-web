// ตัวเลือกที่อยู่รูป — ทุกรูปในเว็บวิ่งผ่านตัวนี้ (ตั้งไว้ที่ next.config.mjs)
//
// รูปสินค้าใน /img/ ถูกย่อไว้ล่วงหน้าแล้วเก็บที่ Cloudflare R2 (ดู scripts/img-to-r2.mjs)
// รูปอื่น ๆ ยังใช้ Netlify Image CDN ย่อสดให้เหมือนเดิม
//
// ---------------------------------------------------------------------------
// ทำไมถึงย้าย — วัดจากเครื่องในไทย รูปใบเดียวกันขนาดเดียวกัน 10 ครั้ง (25 ส.ค. 2569)
//   Netlify Image CDN   ค่ากลาง 0.151 วิ · 8,104 bytes
//   R2 (ย่อไว้แล้ว)      ค่ากลาง 0.070 วิ · 7,222 bytes
// เร็วขึ้น 2.2 เท่าและไฟล์เล็กลงด้วย เพราะไม่ต้องย่อสดระหว่างทาง
// และ Cloudflare มีเครื่องอยู่กรุงเทพ ส่วน Netlify ใกล้สุดคือสิงคโปร์
//
// ⚠️ Netlify Image CDN มีจังหวะพุ่งถึง 1.3 วินาที ตอนที่ต้องย่อรูปใหม่
//    ถ้าจังหวะนั้นไปโดนรูปแบนเนอร์หน้าแรก คะแนน PageSpeed จะตกทันที
//    ย่อไว้ก่อนจึงไม่ใช่แค่เร็วขึ้น แต่ "นิ่ง" ด้วย (วัดได้ 0.058–0.077 วิ)
// ---------------------------------------------------------------------------

// ⚠️ ต้องตรงกับ LADDER ใน scripts/img-to-r2.mjs เป๊ะ ๆ
//    ไม่ตรง = ขอไฟล์ที่ไม่เคยถูกสร้าง แล้วรูปหายทั้งเว็บ
const LADDER = [128, 256, 384, 640];

// ⚠️ ยังใช้ถังของคลิปอยู่ (คีย์ปัจจุบันสร้างถังใหม่ไม่ได้) แต่แยกโฟลเดอร์ /i/ ชัดเจน
//    ย้ายไป img.gucut.com ทีหลังได้ด้วยการแก้บรรทัดนี้บรรทัดเดียว
export const IMG_HOST = "https://video.gucut.com/i";

/** รูปที่ย่อไว้ล่วงหน้าแล้วเท่านั้น — ไฟล์ใน public/img/ ที่ scripts/img-to-r2.mjs กวาดครบ */
const isPrepared = (src) => typeof src === "string" && src.startsWith("/img/");

export default function imageLoader({ src, width, quality }) {
  if (isPrepared(src)) {
    // เลือกขั้นที่ "ใหญ่พอ" ขั้นแรก · ใหญ่กว่าทุกขั้น = ใช้ต้นฉบับ
    const step = LADDER.find((w) => w >= width) ?? "orig";
    // ⚠️ บนถังเก็บเป็น <ขั้น>/<ชื่อไฟล์> ไม่มีโฟลเดอร์ img ซ้อนอยู่
    //    ใส่ /img/ เข้าไปด้วย = 404 ทั้งเว็บ (เคยพลาดมาแล้ว 25 ส.ค. 2569)
    return `${IMG_HOST}/${step}/${src.slice("/img/".length)}`;
  }

  // รูปจากที่อื่น (รีวิว บทความ ปลายทางภายนอก) — ให้ Netlify ย่อสดเหมือนเดิม
  const params = new URLSearchParams({
    url: src,
    w: String(width),
    q: String(quality || 75),
  });
  return `/.netlify/images?${params}`;
}
