export const BOUNDS = { latMin: 5.6, latMax: 20.7, lonMin: 97.3, lonMax: 105.9 };

/** แปลง (ละติจูด, ลองจิจูด) → จุดใน viewBox ของ SVG (0..W, 0..H) */
export function project([lat, lon]: [number, number], W: number, H: number): [number, number] {
  const x = ((lon - BOUNDS.lonMin) / (BOUNDS.lonMax - BOUNDS.lonMin)) * W;
  const y = ((BOUNDS.latMax - lat) / (BOUNDS.latMax - BOUNDS.latMin)) * H;
  return [x, y];
}
