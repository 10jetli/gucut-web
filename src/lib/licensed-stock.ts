// สต็อกของที่อยู่ในทะเบียนใบอนุญาตเลื่อยโซ่ยนต์ — **ZORT ไม่ใช่แหล่งความจริงของกลุ่มนี้**
//
// 🔑 ทำไมต้องมีไฟล์นี้ (25 ก.ย. 2569 · เจ้าของร้านสั่ง "เปิดขายที่เว็บ ไม่ได้ใช้สต๊อค zort")
//    ของกลุ่มนี้นับเป็น **เลขซีเรียล** ในบัญชีรับ-จำหน่ายตามกฎหมาย ไม่ใช่จำนวนชิ้นธรรมดา
//    วัดจริงตอนนั้น: ZORT เชื่อไม่ได้ — ยิงครบ 9 รุ่นแล้วเจอสองอาการ: **ไม่มีในระบบเลย 4 รุ่น**
//    (F 660 · F 440 · F 288 · F 361) และ **มีแต่สต็อกเป็น 0 อีก 4 รุ่น** (NW 9800 · F 250 · F 070 · F 381)
//    เลขที่ลูกค้าเห็นจึงเป็นค่าแช่ตอน build จาก 15 ส.ค. 2569 ⇒ 7 รุ่นขึ้น "สินค้าหมด"
//    ทั้งที่ทะเบียนมีของอยู่ 24 เครื่อง (รวมที่โชว์ต่ำกว่าจริงด้วยเป็น 34 จาก 54 เครื่อง)
//
// ⚠️ ที่นี่เก็บ "จำนวน" อย่างเดียว **ไม่เก็บราคา** — ราคายังมาจาก ZORT/ไฟล์สินค้าเหมือนเดิม
//    (ZORT เคยให้ราคา NW 8800 = 18,000 ส่วนไฟล์สินค้าเขียน 20,000 — การแตะราคาเป็นเรื่องของเจ้าของร้าน)
import data from "@/data/licensed-stock.json";

type Map_ = Record<string, number>;

/** รหัสสินค้า → จำนวนที่เหลือในทะเบียน (รวมทั้งเลื่อยและบาร์) */
/**
 * กาง "ตัวเลือกในเว็บ → ขนาด+ยี่ห้อ" ออกเป็น "รหัส k → จำนวน"
 *
 * เจ้าของร้านสั่ง 25 ก.ย. 2569: *"อิงตาม Google Sheets ขนาดและยี่ห้อ พอ"*
 * ⚠️ ตัวเลือกที่ชี้ช่องเดียวกัน (เช่น `Bar NW 24-7800` กับ `Bar NW 24-9800`)
 *    **ใช้ของกองเดียวกัน** ⇒ ตัวเลขที่โชว์คือยอดของทั้งขนาดนั้น ไม่ใช่ของเฉพาะตัวเลือก
 *    เป็นไปตามที่เจ้าของร้านเลือก เพราะทะเบียนบันทึกแค่ "ความยาวนิ้ว" แยกละเอียดกว่านี้ไม่ได้
 */
function กางบาร์(): Map_ {
  // ⚠️ ต้องผ่าน `unknown` ก่อน — ในออบเจกต์มีทั้งตัวเลข (จำนวน) และสตริง (คีย์ `_` ที่เป็น
  //    คำอธิบาย) ⇒ ชนิดจริงไม่ใช่ Record<string, number> · แปลงตรง ๆ แล้ว tsc ตีตกทั้ง build
  const ก้อน = data as unknown as Record<string, Record<string, unknown> | undefined>;
  const ยอด = ก้อน["บาร์ตามขนาดและยี่ห้อ"] ?? {};
  const จับคู่ = ก้อน["บาร์ตัวเลือก→ขนาดยี่ห้อ"] ?? {};
  const out: Map_ = {};
  for (const [k, ช่อง] of Object.entries(จับคู่)) {
    if (k.startsWith("_") || typeof ช่อง !== "string") continue; // คีย์ `_` เป็นคำอธิบาย ไม่ใช่ข้อมูล
    const n = ยอด[ช่อง];
    if (typeof n === "number" && Number.isFinite(n)) out[k] = n;
  }
  return out;
}

export const LICENSED: Map_ = Object.freeze({
  ...((data as { เลื่อย?: Map_ }).เลื่อย ?? {}),
  ...((data as { บาร์?: Map_ }).บาร์ ?? {}),
  ...กางบาร์(),
});

/** วันที่นับของจากทะเบียนครั้งล่าสุด — โชว์ให้คนอ่านรู้ว่าเลขเก่าแค่ไหน */
export const LICENSED_ASOF: string = (data as { _วัดเมื่อ?: string })._วัดเมื่อ ?? "";

/**
 * จำนวนที่เหลือตามทะเบียน · คืน `null` ถ้าไม่ใช่ของในทะเบียน (ให้ไปใช้ ZORT ตามปกติ)
 *
 * ⚠️ ต้องแยก "ไม่ใช่ของในทะเบียน" (`null`) ออกจาก "อยู่ในทะเบียนแต่หมดแล้ว" (`0`) เสมอ
 *    ถ้ายุบเป็นค่าเดียว ของที่หมดจริงจะเด้งกลับไปใช้เลข ZORT ที่เชื่อไม่ได้
 */
export function licensedStock(sku: string | null | undefined): number | null {
  if (!sku) return null;
  const n = LICENSED[String(sku).trim()];
  return typeof n === "number" && Number.isFinite(n) ? n : null;
}

/** ชื่อรุ่นในช่องเลือกรุ่นของ `/permit/` → รหัสสินค้า (คีย์ที่ขึ้นต้นด้วย `_` เป็นคำอธิบาย ไม่ใช่ข้อมูล) */
const รุ่นเป็นรหัส: Record<string, string> = Object.fromEntries(
  Object.entries(
    (data as { "รุ่นเลื่อย→รหัสสินค้า"?: Record<string, string> })["รุ่นเลื่อย→รหัสสินค้า"] ?? {}
  ).filter(([k, v]) => !k.startsWith("_") && typeof v === "string")
);

/**
 * จำนวนคงเหลือตามทะเบียนของ "รุ่น" ที่เลือกในหน้า `/permit/`
 *
 * 🔑 เจ้าของร้านสั่ง 25 ก.ย. 2569: "ตัวไหนหมดตรงขออนุญาตก็เป็นเทาอ่อนเลือกไม่ได้"
 * ⚠️ รุ่นที่ **ไม่เคยนำเข้าเลย** (F038 · F090 · F880) ไม่มีในตารางจับคู่ ⇒ คืน `0` ไม่ใช่ `null`
 *    เพราะคำถามที่นี่คือ "ยังสั่งได้ไหม" ซึ่งตอบว่าไม่ได้เหมือนกันทั้งของหมดและของที่ไม่เคยมี
 *    (ต่างจาก `licensedStock()` ที่ `null` แปลว่า "ไปถาม ZORT ต่อ" — คนละคำถาม อย่าเอามาปนกัน)
 */
export function permitModelStock(model: string | null | undefined): number {
  if (!model) return 0;
  const sku = รุ่นเป็นรหัส[String(model).trim()];
  if (!sku) return 0;
  return licensedStock(sku) ?? 0;
}
