// 🔑 ทำไมต้องเป็นไฟล์เดียว: เกณฑ์ `<= 0` เคยถูกคัดลอกไว้ **สี่ที่**
//    (ProductCard · ProductDetail · SearchClient · VariantSheet) ⇒ แก้ที่เดียวไม่พอ
//    ไฟล์นี้จึงเป็นที่เดียวที่รู้กติกา · ที่อื่นเรียกใช้ ห้ามเขียน `<= 0` ซ้ำ
//    (มีด่าน `scripts/check-stock-state-single-source.mjs` กันการคัดลอกกลับมา)

export type StockState = "มีของ" | "หมดจริง" | "ไม่รู้";

/** แกนกลาง: `null`/`undefined`/ไม่ใช่ตัวเลข = **ไม่รู้** ห้ามกลายเป็น 0
 *  (กฎบ้าน: ไม่รู้ห้ามกลายเป็นศูนย์ที่ชั้นจอ — ศูนย์เป็นคำยืนยัน ไม่ใช่ความว่างเปล่า) */
export function สถานะจากค่า(st: number | null | undefined): StockState {
  if (st === null || st === undefined || !Number.isFinite(st)) return "ไม่รู้";
  return st > 0 ? "มีของ" : "หมดจริง";
}

/** ของที่ระดับสินค้า — `stKnown: false` แปลว่าเรายังไม่รู้ ไม่ใช่ว่าไม่มี */
export const สถานะของสินค้า = (p: { st: number; stKnown: boolean }): StockState =>
  สถานะจากค่า(p.stKnown ? p.st : null);

/** ของที่ระดับตัวเลือก (ขนาด/ฟัน) — ตัวเลือกที่ไม่รู้ ต้องกดเลือกได้ ห้ามขีดฆ่า */
export const สถานะของตัวเลือก = (v: { s: number; sKnown?: boolean }): StockState =>
  สถานะจากค่า(v.sKnown === false ? null : v.s);

/** ขึ้นป้าย "สินค้าหมด" ได้ไหม — **เฉพาะ `หมดจริง` เท่านั้น** */
export const ขึ้นป้ายหมดได้ = (s: StockState) => s === "หมดจริง";

/** ให้กดซื้อ/โชว์ในหน้ารวมได้ไหม — `ไม่รู้` ยังให้ขาย (ทักร้านถามได้ ดีกว่าปิดประตู) */
export const ยังขายได้ = (s: StockState) => s !== "หมดจริง";

/** ค่าที่ส่งให้ schema.org — `ไม่รู้` ต้องไม่ประกาศว่า OutOfStock
 *  ⚠️ ประกาศ OutOfStock ให้ของที่ยังไม่รู้ = บอก Google ว่าของหมด ⇒ หายจากผลค้นหา */
export const availabilityของ = (s: StockState) =>
  s === "มีของ" ? "https://schema.org/InStock"
    : s === "หมดจริง" ? "https://schema.org/OutOfStock"
      : "https://schema.org/LimitedAvailability";
