// ปัญหาที่แก้
//   `videos.ts` import `videos.json` เข้าไปตอน build
//   ⇒ คลิปใหม่ 1 ใบ = ต้องสร้างหน้าสินค้าใหม่ทั้ง 2,505 หน้า (~1 นาทีต่อครั้ง)
//   คลิป อ.ธง เข้าวันละ ~120 ใบ ⇒ อยากให้ขึ้นไวต้อง deploy ทั้งวัน
//   และค่า deploy คือตัวกินเครดิต Netlify อันดับสองของร้าน
//
// ท่าที่ใช้ — ท่าเดียวกับฟีดสินค้าที่ร้านทำสำเร็จแล้ว (สต็อกสดโดยไม่ต้อง deploy)
//   g1 ส่งรายชื่อคลิปขึ้น R2 ทุก 10 นาที (`clip-list-r2.timer`)
//   หน้าเว็บมาอ่านจาก `video.gucut.com` ตรง ๆ
//   ⇒ **ไม่แตะ Netlify สักครั้ง · 0 หน่วย** และคลิปใหม่ขึ้นภายใน 10 นาที
//
// 🔴 กติกาที่ห้ามถอด
//  1. **ของที่ฝังมากับ build คือตัวจริง** ตัวนี้ทำได้อย่างเดียวคือ "เติมของใหม่ต่อท้าย"
//     โหลดไม่ได้ / ไฟล์เพี้ยน ⇒ เงียบแล้วใช้ของเดิม **ห้ามทำให้ฟีดว่าง**
//  2. **ห้ามเอามาแทนที่ของเดิม** — ถ้าวันหนึ่งไฟล์บน R2 ถูกเขียนทับด้วยของสั้น ๆ
//     ฟีดต้องไม่หด เพราะของเดิมยังอยู่ครบ
//  3. **คลิปใหม่ไม่มีสินค้าผูก** — ตัวจับคู่สินค้าอยู่ฝั่ง server (catalog 4MB
//     ห้ามลากเข้า bundle) ⇒ ของใหม่เป็นคลิปเปล่าจนกว่าจะ deploy รอบถัดไป
//     ซึ่งยอมรับได้: คลิป อ.ธง ไม่ได้ผูกสินค้าอยู่แล้ว
import { VIDEO_HOST, type ShopVideo, type FeedItem } from "./videos";

const ที่อยู่ = `${VIDEO_HOST}/videos.json`;

/** คลิปที่ยังไม่มีในฟีด — คืนลิสต์ว่างเสมอเมื่อมีอะไรผิดพลาด (กติกาข้อ 1) */
export async function คลิปใหม่กว่าที่build(มีแล้ว: Set<string>): Promise<FeedItem[]> {
  if (!VIDEO_HOST) return [];
  try {
    const r = await fetch(ที่อยู่, { cache: "no-store" });
    if (!r.ok) return [];
    const ดิบ: unknown = await r.json();
    // ⚠️ ข้อมูลจากข้างนอกต้องกันรูปแบบไม่ครบเสมอ — ตอน deploy ใหม่
    //    หน้าเว็บเก่ากับไฟล์ใหม่จะอยู่ด้วยกันชั่วครู่เสมอ
    if (!Array.isArray(ดิบ)) return [];
    const ใหม่: FeedItem[] = [];
    for (const x of ดิบ) {
      const v = x as ShopVideo;
      if (!v || typeof v.v !== "string" || มีแล้ว.has(v.v)) continue;
      มีแล้ว.add(v.v);
      ใหม่.push({ v });          // กติกาข้อ 3 — ไม่มีสินค้าผูก
    }
    return ใหม่;
  } catch {
    return [];                   // กติกาข้อ 1
  }
}
