#!/usr/bin/env node
/* 🧪 **ไฟล์เทสที่ `import` ด่านซึ่งไม่มี guard ⇒ ข้อที่เหลือจะไม่ได้รัน**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ผมเขียนเทส 6 ข้อให้ `check-leaks` ⇒ รายงาน **`pass 1 · fail 0`**
 *    ⇒ ⇒ **5 ข้อไม่ได้รันเลย** เพราะด่านนั้น `process.exit(0)` ตอนถูก import
 *    🔑 **"fail 0" คือสิ่งที่เราอยากเห็น** ⇒ สิ่งที่ควรสะดุดคือ **`pass` น้อยกว่าที่เขียน**
 *       ⇒ แต่ไม่มีใครนับ ⇒ **การหยุดกลางทางหน้าตาเหมือนความสำเร็จ**
 *
 * 🔑 **ทำไมด่านนี้ตรวจ "เงื่อนไข" ไม่ใช่ "อาการ"**
 *    ฝั่งจอทำตัวที่ตรวจอาการ (เทียบ `# tests` ที่ `node:test` รายงานเอง) — ถูกและตรงกว่า
 *    ⚠️ แต่การตรวจอาการต้อง **รันเทสทุกไฟล์** ⇒ ฝั่งนี้มี 159 ไฟล์ ⇒ **ซ้ำกับ `npm test` ที่อยู่ในสายแล้ว**
 *    ⇒ ⇒ ตัวนี้จึงจับ **สาเหตุ**: *เทสที่ import ด่านที่ไม่มี guard* ⇒ **เบากว่า และจับได้ก่อนเกิด**
 * 🚫 **ขอบเขต: ไม่ได้ตรวจว่าข้อหายจริงไหม** — ตรวจว่า **มีเงื่อนไขที่ทำให้หายได้ไหม**
 *    ⇒ เขียวที่นี่ **ไม่ได้แทน** ตัวที่ตรวจอาการ · ถ้าวันหนึ่งมีสาเหตุอื่น ตัวนี้มองไม่เห็น
 *
 * ใช้: node scripts/check-test-imports-guard.mjs
 */
import { readFileSync, readdirSync, existsSync } from "node:fs";

const มีguard = (ไฟล์) => {
  try {
    const s = readFileSync(ไฟล์, "utf8");
    /* 🔴 **ต้องเห็น "การเทียบ" ไม่ใช่แค่ "ชื่อตัวแปร"** (แก้ 20 ก.ย. 2569 ตอนปลูกทดสอบ)
       รอบแรกผมเขียน `/import\.meta\.url|เป็นตัวหลัก|process\.argv\[1\]/`
       ⇒ ปลูกทดสอบด้วย `const เป็นตัวหลัก = true;` ⇒ **ตะแกรงยังเจอคำว่า "เป็นตัวหลัก" ⇒ ผ่าน**
       ⇒ ⇒ **ตะแกรงจับคำ ไม่ได้จับพฤติกรรม** — คลาสเดิมของวันนี้ (นับคำ ไม่ได้นับของ)
       ⇒ เกณฑ์ที่ถูก: ต้องมี **`import.meta.url` อยู่ในนิพจน์เปรียบเทียบ** จริง ๆ */
    return /import\.meta\.url\s*(===|==|!==|!=)|(===|==|!==|!=)\s*import\.meta\.url/.test(s);
  } catch { return null; }   /* อ่านไม่ได้ ⇒ **ยังไม่รู้** ไม่ใช่ "ไม่มี guard" */
};

const เทส = readdirSync("scripts/tests").filter((n) => n.endsWith(".test.mjs"));
const ปัญหา = [];
const ยังไม่รู้ = [];
for (const t of เทส) {
  const s = readFileSync(`scripts/tests/${t}`, "utf8");
  /* หา import ที่ชี้ไปไฟล์ด่าน (`../check-*.mjs` · `../probe-*` · `../verify-*` · `../audit-*`) */
  for (const m of s.matchAll(/from\s+["']\.\.\/((?:check|probe|verify|audit)-[\w.-]+\.mjs)["']/g)) {
    const ด่าน = `scripts/${m[1]}`;
    if (!existsSync(ด่าน)) { ยังไม่รู้.push(`${t} → ${m[1]} (ไม่มีไฟล์)`); continue; }
    const g = มีguard(ด่าน);
    if (g === null) { ยังไม่รู้.push(`${t} → ${m[1]} (อ่านไม่ได้)`); continue; }
    if (!g) ปัญหา.push({ เทส: t, ด่าน: m[1] });
  }
}

console.log(
  `🧪 ไฟล์เทส **${เทส.length}** · ที่ import ด่านโดยตรงแล้วด่านนั้นไม่มี guard: **${ปัญหา.length}**` +
  (ยังไม่รู้.length ? ` · ยังไม่รู้ ${ยังไม่รู้.length}` : "") +
  "\n   🚫 เขียวที่นี่ = **ไม่มีเงื่อนไขที่ทำให้ข้อหายแบบที่เรารู้จัก** ไม่ใช่ \"ทุกข้อรันครบ\"" +
  "\n   🔑 อาการจริงต้องดูจากเลขที่ `node:test` รายงานเอง (`# tests`) — ตัวนี้จับ **สาเหตุ** เท่านั้น"
);
if (ยังไม่รู้.length) console.log("   ❓ " + ยังไม่รู้.slice(0, 5).join(" · "));
if (ปัญหา.length) {
  console.error(
    `\n🔴 เทสเหล่านี้จะ **หยุดกลางทางแบบดูเหมือนผ่าน**:\n` +
    ปัญหา.map((x) => `   · ${x.เทส} → import ${x.ด่าน} (ไม่มี guard ⇒ ด่านลงมือ + process.exit ตอน import)`).join("\n") +
    "\n   ⇒ แก้ที่ **ไฟล์ด่าน**: ห่อส่วนลงมือด้วย `const เป็นตัวหลัก = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url;`" +
    "\n   🚫 อย่าแก้ที่ไฟล์เทส — ปัญหาอยู่ที่ด่านลงมือตอนถูก import"
  );
  process.exit(1);
}
