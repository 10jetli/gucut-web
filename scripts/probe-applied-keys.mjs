#!/usr/bin/env node
/* 🔑 อ่าน **ชุดคีย์ของ `applied`** ของทุกเส้น `list=` — คำประกาศที่เส้นนั้นพูดเอง
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ผมสร้างตัววัดสองรุ่นก่อนหน้านี้ และ **ผิดทั้งสองรุ่น**
 *    รุ่น ① สกัดชื่อจากซอร์ส ⇒ ผิดทั้งสองทิศ (ฝั่งจอพิสูจน์)
 *    รุ่น ② ยิงค่ามั่วแล้วเทียบจำนวนแถว ⇒ **ยังกำกวม** เพราะ "แถวเท่าเดิม" แยกสามกรณีนี้ไม่ออก:
 *      · ท่อเมินตัวกรองนี้  · ท่อเมินเฉพาะ **ค่านี้**  · ค่ามั่วดันไปตรงของจริง
 *      ⇒ ของจริง: ผมสรุปว่า `carrier` ของ logistics เป็นปุ่มหลอก **ผิด**
 *        ฝั่งจอยิงด้วยชื่อขนส่งจริง: total 35,781 → 32,499 ⇒ **กรองจริง**
 *
 * ✅ **รุ่นนี้ไม่เดาอะไรเลย** — ยิงเปล่า 1 ครั้งต่อเส้น แล้วอ่าน **ชุดคีย์** ของ `applied`
 *    วัดจริงแล้วว่าชุดคีย์ **คงที่ ไม่ขึ้นกับค่าที่ส่งไป** (ยิง 3 แบบได้ชุดเดียวกัน)
 *    ⇒ ชุดคีย์นั้นคือ **รายการพารามิเตอร์ที่เส้นนั้นพิจารณา** = คำประกาศที่เชื่อได้
 *    🔑 **ท่อรู้คำตอบและบอกอยู่แล้ว — สองรุ่นก่อนหน้าผมไปเดาจากอาการ**
 *       (คลาสเดียวกับบทเรียน "ถามอีกฝ่าย ก่อนจ่ายเงินไปวัดสถานะของเขา")
 *
 * ⚠️ สิ่งที่ชุดคีย์ **ไม่** บอก: ค่าที่ส่งไปใช้ได้ไหม ⇒ อันนั้นดูที่ `ignored` ต่อคำขอ
 *    ⇒ สองช่องตอบคนละคำถาม: `applied` = "พิจารณาอะไร" · `ignored` = "ค่าที่ส่งมารอบนี้ใช้ไม่ได้ตัวไหน"
 * ⚠️ เส้นที่ **ไม่มี `applied`** ⇒ `null` = **ยังไม่รู้** ไม่ใช่ "ไม่รับตัวกรองอะไร"
 *    ⇒ และนั่นคือช่องว่างฝั่งท่อที่ควรปิด: ให้ทุกเส้น `list=` ส่ง `applied` ⇒ เลิกต้องเดาตลอดกาล
 *
 * 📏วัดได้ยิงจริง(เส้น list= ที่ส่ง applied)=24 · 28 ก.ย. 2569 12:5x — **ครบทุกเส้นแล้ว**
 *    ประวัติของเลขนี้: 12 (19 ก.ย.) → 13 (27 ก.ย.) → 14 (28 ก.ย. เช้า · ที่ขยับเพราะแก้หมุดที่วัดผิด)
 *    → 20 (28 ก.ย. 11:5x) → **24 (28 ก.ย. 12:5x · deploy 05:46:46Z)**
 * 🔑 เลขนี้ **เต็มเพดานแล้ว** ⇒ หน้าที่ของหมุดเปลี่ยนจาก "ดูว่าโตขึ้นไหม" เป็น **"ดูว่าถอยหลังไหม"**
 *    ต่ำกว่า 24 เมื่อไหร่ = มีเส้นที่เคยส่ง `applied` แล้วเลิกส่ง ⇒ ฝั่งจอกลับไปเดาอีกครั้ง
 * ⚠️ และ **เพิ่มเส้น `list=` ใหม่ต้องดันเลขนี้ขึ้นด้วย** — ตัวหารคือจำนวนเส้นที่หมุดนี้ไล่ยิง
 *    ⇒ เลข 24 ไม่ใช่ "ครบตลอดกาล" แต่คือ "ครบเท่าที่มีวันนี้" (กติกา: เลขต้องมีขอบเขตกำกับ)
 * 🔴 **ที่ขยับจาก 13 เป็น 14 ไม่ใช่เพราะท่อเพิ่มเส้น — เพราะตัวหมุดนี้เองวัดผิด**
 *    `stockcard` ส่ง `applied` ครบมาตลอด แต่หมุดยิงโดยไม่ส่ง `sku` ⇒ ได้ `{error:"ต้องระบุ sku"}`
 *    ⇒ ไม่มีคีย์ `applied` ⇒ หมุดสรุปว่า **"เส้นนี้ไม่ส่ง"** ⇒ **ผมกับฝั่งจอพูดเลข 13/24 ต่อกันโดยไม่มีใครสงสัย**
 *    🔑 คลาส: **ตัวชี้ที่พังไปทางเดียวกับสิ่งที่มันตรวจ** (ยิงไม่ถูกวิธี = "ไม่เจอ" เหมือนกับไม่มีจริง)
 *    ⇒ แก้สองชั้น: ① เส้นที่ตอบ `error` ⇒ **"ยังไม่ได้วัด"** ไม่ใช่ "ไม่ส่ง"
 *                  ② ส่งพารามิเตอร์ที่เส้นบังคับให้ครบ ⇒ วัดได้จริงแทนที่จะข้าม
 *    (เดิม 12 · 19 ก.ย. 2569 ⇒ **โตขึ้น 1 เส้น** — ทิศที่ถูกต้องตามที่หมุดนี้บอกว่าควรเป็น
 *     ⇒ ยังเหลือ 11 เส้นที่ยังไม่ส่ง `applied` จาก 24 เส้น · ที่ยังไม่ส่งตอนวัดรอบนี้:
 *       returns-inbox · stockcard · warehouses · และอีก 8 เส้น)
 *    🔑 **หมุดค้างคือเหตุที่ด่านชั้นยิงจริงแดงเมื่อคืน 26 ก.ย.** — ของจริงโตแต่เลขไม่ขยับ
 *       ⇒ แดงแบบนี้คือ **ด่านทำงานถูก** ไม่ใช่ด่านพัง ⇒ แก้ที่หมุด ห้ามแก้ที่ด่าน
 *    🔑 หมุดนี้ **วัดซ้ำได้ด้วยการยิงของจริงเท่านั้น** (ต้องถามท่อว่าตอบ applied มาไหม)
 *       ⇒ จึงไม่อยู่ใน prebuild แต่อยู่ในชั้นที่ยิงจริงหลัง deploy: `scripts/verify-claims.mjs`
 *       (ฝั่งจอถามข้อนี้พอดี: หมุดที่ต้องยิงเน็ตจะกินเวลา prebuild ⇒ คำตอบคือ **แยกชั้น** ไม่ใช่เลิกติดหมุด)
 *    ⚠️ เลขนี้ควรขึ้นเรื่อย ๆ จนถึง 24 (ใบกระดาน t_mu83e8cd) ⇒ วันที่ขึ้น ด่านจะแดงให้มาแก้หมุด
 *
 * ใช้: node scripts/probe-applied-keys.mjs [--write]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { lists } from "../netlify/lib/endpoints.mjs";

let KEY = "";
try {
  KEY = readFileSync(join(homedir(), ".gucut-admin-key"), "utf8").trim();
} catch {
  console.error("❌ อ่าน ~/.gucut-admin-key ไม่ได้ — **วัดไม่ได้ทั้งชุด ไม่ใช่ 'ผ่าน'**");
  process.exit(2);
}
import { คิวรีที่บังคับ } from "../netlify/lib/list-required-params.mjs";

const SITE = process.env.SITE || "https://gucut.com";
const เขียนไฟล์ = process.argv.includes("--write");

const ผล = {};
let มีapplied = 0;
console.log(`🔑 อ่านชุดคีย์ของ applied — ${SITE}\n`);

for (const ชื่อ of lists) {
  let d = null;
  let err = null;
  try {
    /* 📌 **เส้นที่บังคับพารามิเตอร์ ต้องส่งให้ครบ ไม่งั้นวัดไม่ได้** (เพิ่ม 28 ก.ย. 2569)
       ⚠️ ค่าที่ใส่ต้องเป็น **ค่าที่มีอยู่จริงในคลัง** ไม่ใช่ค่าสมมติ
          (ใส่ sku ที่ไม่มีจริง ⇒ ได้ 0 แถว ซึ่งยังวัด `applied` ได้ แต่ถ้าเส้นไหนตอบ error
           กับรหัสที่ไม่มี เราจะกลับไปเจอปัญหาเดิม) · `01209` มีจริง — ใช้เป็นรหัสตรวจทั่วโปรเจกต์อยู่แล้ว
       🚫 ห้ามใส่ค่าที่ทำให้เส้นเขียนอะไร — เส้น `list=` เป็นเส้นอ่านทั้งหมด */
    /* 🔑 อ่านจาก **ตารางกลาง** `netlify/lib/list-required-params.mjs`
       เดิมพิมพ์ไว้ในไฟล์นี้ ⇒ `verify-claims.mjs` มีสำเนาที่สองซึ่งยังยิง `&limit=1` เปล่า ๆ
       ⇒ สองตัววัดได้เลขคนละตัว (24 vs 23) แล้วด่านชั้นยิงจริงแดงโดยท่อไม่ได้ผิดอะไรเลย */
    const บังคับ = คิวรีที่บังคับ(ชื่อ);
    const r = await fetch(`${SITE}/api/core?list=${encodeURIComponent(ชื่อ)}&limit=1${บังคับ}`, {
      headers: { "x-admin-key": KEY },
      signal: AbortSignal.timeout(60000),
    });
    d = await r.json().catch(() => null);
    if (!d) err = `ตอบ ${r.status} แต่อ่าน JSON ไม่ได้`;
  } catch (e) {
    err = String(e?.message || e).slice(0, 100);
  }
  if (err) {
    console.log(`⚠️  ${ชื่อ} — ยิงไม่สำเร็จ: ${err} ⇒ **ยังไม่ได้วัด ไม่ใช่ตก**`);
    ผล[ชื่อ] = { พิจารณา: null, เหตุ: `ยิงไม่สำเร็จ: ${err}` };
    continue;
  }
  /* 🔴 **แยก "ไม่ส่ง applied" ออกจาก "ยิงไม่ถูกวิธี"** (แก้ 28 ก.ย. 2569)
     ก่อนแก้: ตัวหมุดยิงทุกเส้นด้วย `&limit=1` เท่านั้น ⇒ เส้นที่ **ต้องมีพารามิเตอร์**
     (เช่น `stockcard` ต้องมี `sku`) ตอบ `{ error: "ต้องระบุ sku" }` ⇒ ไม่มีคีย์ `applied`
     ⇒ หมุดสรุปว่า **"เส้นนี้ไม่ส่ง applied"** ทั้งที่ของจริงส่งครบ
     📏 พิสูจน์ 28 ก.ย. 2569: ยิง `?list=stockcard&sku=01209&limit=2` ⇒ ได้
        `applied: {sku,kind,limit,offset,from,to}` **ครบถ้วน**
     🔑 คลาส: **ตัวชี้ที่พังไปทางเดียวกับสิ่งที่มันตรวจ** — ยิงไม่ถูกวิธีก็ "ไม่เจอ applied"
        เหมือนกับเส้นที่ไม่ส่งจริง ⇒ ทั้งผมและฝั่งจอพูดเลข 13/24 ต่อกันไปโดยไม่มีใครสงสัย
     ⇒ เส้นที่ตอบ `error` ⇒ **ยังไม่ได้วัด** ห้ามนับว่าไม่ส่ง · และบอกให้คนยิงซ้ำด้วยค่าที่ครบ */
  if (d.error && !d.applied) {
    console.log(`⚠️  ${ชื่อ} — ตอบ error: ${String(d.error).slice(0, 60)} ⇒ **ยังไม่ได้วัด** (ต้องส่งพารามิเตอร์ที่เส้นนี้บังคับ)`);
    ผล[ชื่อ] = { พิจารณา: null, เหตุ: `ตอบ error: ${String(d.error).slice(0, 80)} — ยิงด้วยพารามิเตอร์ที่ครบแล้ววัดใหม่` };
    continue;
  }
  const ap = d.applied;
  const ชื่อจริง = d.appliedParamNames ?? null;   // แผนที่ชื่อบนจอ → ชื่อพารามิเตอร์จริง
  if (!ap || typeof ap !== "object" || Array.isArray(ap)) {
    console.log(`⬜ ${ชื่อ} — **ไม่ส่ง applied** ⇒ ยังไม่รู้ว่าเส้นนี้พิจารณาอะไร`);
    ผล[ชื่อ] = { พิจารณา: null, เหตุ: "เส้นนี้ไม่ส่ง applied ⇒ ต้องเพิ่มที่ฝั่งท่อ" };
    continue;
  }
  มีapplied++;
  const คีย์ = Object.keys(ap).sort();
  ผล[ชื่อ] = { พิจารณา: คีย์, ชื่อบนจอ: ชื่อจริง, วัดเมื่อ: new Date().toISOString().slice(0, 10) };
  console.log(`✅ ${ชื่อ} — พิจารณา: ${คีย์.join(" ")}${ชื่อจริง ? ` · แผนที่ชื่อ: ${JSON.stringify(ชื่อจริง)}` : ""}`);
}

console.log(
  `\nมี applied: ${มีapplied} จาก ${lists.length} เส้น` +
  "\n⬜ ที่ยังไม่มี = ช่องว่างฝั่งท่อ ⇒ เพิ่ม applied แล้วปลายทางเลิกต้องเดาตลอดกาล" +
  "\n⚠️ ชุดคีย์บอกว่า **พิจารณาอะไร** ไม่ได้บอกว่า **ค่าที่ส่งไปใช้ได้ไหม** (อันนั้นดู `ignored` ต่อคำขอ)"
);

if (เขียนไฟล์) {
  writeFileSync("netlify/lib/list-applied-keys.mjs",
    "/* 🤖 สร้างโดย `scripts/probe-applied-keys.mjs --write` — **ห้ามแก้มือ**\n" +
    " * 🔑 ค่านี้คือ **ชุดคีย์ของ `applied`** ที่แต่ละเส้นส่งออกมาเอง = คำประกาศที่เส้นนั้นพูดเอง\n" +
    " *    ไม่ใช่การสกัดชื่อจากซอร์ส (ผิดทั้งสองทิศ) และไม่ใช่การเทียบจำนวนแถว (กำกวม)\n" +
    " * 🚫 `พิจารณา: null` = **ยังไม่รู้** (เส้นนั้นไม่ส่ง applied) ไม่ใช่ 'ไม่รับตัวกรอง'\n" +
    " * ⚠️ บอกว่า 'พิจารณาอะไร' ไม่ได้บอกว่า 'ค่าที่ส่งไปใช้ได้ไหม' ⇒ อันนั้นดู `ignored` ต่อคำขอ */\n" +
    "export const คีย์ที่เส้นพิจารณา = " + JSON.stringify(ผล, null, 2) + ";\n");
  console.log(`\n💾 เขียน netlify/lib/list-applied-keys.mjs แล้ว (${Object.keys(ผล).length} เส้น)`);
}
