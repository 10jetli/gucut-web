/* 🕰️ **จดว่าชั้นนี้รันครั้งล่าสุดเมื่อไหร่ และรันกับท่อรุ่นไหน** (เพิ่ม 19 ก.ย. 2569)
   🔴 ฝั่งจอตั้งคำถามที่ไม่มีใครถามมาก่อน: **ชั้นที่ยิงของจริงขึ้นกับการมี deploy**
      ⇒ วันที่หยุด deploy ยาว ๆ **ชั้นนี้หยุดทำงานไปด้วยโดยไม่มีอะไรบอก**
      ⇒ ตอนนี้เรารู้เพราะเราเป็นคนปิดเอง — **แต่ถ้าวันหน้ามันหยุดด้วยเหตุอื่น จะไม่มีใครสังเกต**
   🔑 และเกณฑ์ที่ถูก **ไม่ใช่ "กี่วันแล้วที่ไม่ได้รัน"** (ช่วงหยุด deploy จะหอนทุกวันจนคนปิดทิ้ง)
      แต่คือ **"มีท่อรุ่นใหม่ขึ้นแล้วแต่ชั้นนี้ยังไม่ได้รันกับรุ่นนั้น"**
      ⇒ ตัวเฝ้าเทียบ `x-core-build` ของจริง กับรุ่นที่จดไว้ที่นี่ ⇒ เงียบตอนหยุด deploy · ดังตอน deploy แล้วไม่ตรวจ
   ⚠️ เขียนไฟล์ล้มห้ามทำให้ผลการตรวจเปลี่ยน — บอกบนจอแล้วไปต่อ */
try {
  const { writeFileSync } = await import("node:fs");
  const { homedir } = await import("node:os");
  const { join } = await import("node:path");
  let รุ่นท่อ = null;
  try {
    const r = await fetch(`${API}?list=sales&limit=1`, { signal: AbortSignal.timeout(15000) });
    รุ่นท่อ = r.headers.get("x-core-build"); // null ได้ = ท่อรุ่นเก่ายังไม่ส่งหัวนี้บน 401
  } catch { /* ยิงไม่ถึง ⇒ null ⇒ ตัวเฝ้าอ่านว่า "ไม่รู้รุ่น" ไม่ใช่ "ตรงกัน" */ }
  writeFileSync(
    join(homedir(), ".gucut-verify-claims-last.json"),
    JSON.stringify({
      เมื่อ: new Date().toISOString(),
      รุ่นท่อที่ตรวจ: รุ่นท่อ,
      ผ่าน: tally["ผ่าน"] ?? 0,
      ไม่ผ่าน: tally["ไม่ผ่าน"] ?? 0,
      ตรวจไม่ได้: tally["ตรวจไม่ได้"] ?? 0,
      "🔑 อ่านยังไง": "ตัวเฝ้าเทียบ `รุ่นท่อที่ตรวจ` กับ x-core-build ของจริง — ต่างกัน = deploy แล้วยังไม่ตรวจ · null = ยังไม่รู้รุ่น (ห้ามอ่านว่าตรงกัน)",
    }, null, 1) + "\n"
  );
} catch (e) {
  console.log(`⚠️ จดเวลาการตรวจไม่สำเร็จ: ${String(e?.message ?? e).slice(0, 120)} (ผลการตรวจข้างบนยังใช้ได้)`);
}

