#!/usr/bin/env node
/* 🔬 วัดว่า **ตัวกรองไหนกรองจริง** ในแต่ละเส้น `list=` — ด้วยการยิงของจริง ไม่ใช่อ่านซอร์ส
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ผมสร้างช่อง `ตัวกรองที่รับ` จากการ **สกัดชื่อจากซอร์ส**
 *    แล้วบอกฝั่งจอว่า "ใช้ยืนยันทิศบวกได้" ⇒ เขาทำตาม แล้วด่านฟ้องจอที่ถูกอยู่แล้ว
 *    ⇒ เขายิงวัดก่อนแก้จอ แล้วพบว่า **ช่องของผมผิดทั้งสองทิศ**:
 *      `list=quotations` ⇒ ผมบอก `["limit","page","q","type"]`
 *      ของจริง (`supportedFilters`) คือ `["limit","page","store"]`
 *      · ใส่ `q`/`type` ที่ท่อ **เมินจริง** (โค้ดอ่านเข้ามาเพื่อจะรายงานว่าเมิน)
 *      · **ตกหล่น `store` ที่กรองจริง**
 *    🔑 สาเหตุ: ตัวสกัดตอบคำถาม **"มีชื่อไหนโผล่ในโค้ด"** ไม่ใช่ **"ชื่อไหนกรองจริง"**
 *       ⇒ ผมตั้งชื่อช่องตามคำถามที่สอง ทั้งที่มันตอบคำถามแรก
 *
 * 🔑 **วิธีเดียวที่เชื่อได้คือวัดพฤติกรรม**: ยิงค่าที่เป็นไปไม่ได้ แล้วดูว่าจำนวนแถวเปลี่ยนไหม
 *    · จำนวนแถวลด/ต่างจากค่าฐาน ⇒ **กรองจริง**
 *    · เท่าเดิมเป๊ะ ⇒ **เมิน** (ท่อรับชื่อไปแต่ไม่ได้ใช้)
 *    · ค่าฐาน 0 แถว หรือยิงไม่สำเร็จ ⇒ **ตัดสินไม่ได้** (สามสถานะ ห้ามยุบเป็นสอง)
 *
 * ⚠️ ค่าที่ใช้ทดสอบต้อง **ถูกรูปแต่ไม่มีทางตรงกับข้อมูลจริง** ไม่ใช่ค่าผิดรูป
 *    ค่าผิดรูปอาจถูกตีกลับด้วย error ⇒ วัดคนละเรื่อง (วัด "การตรวจรูปแบบ" ไม่ใช่ "การกรอง")
 * ⚠️ **เส้นที่แพง/ต้องมีพารามิเตอร์ก่อน ต้องข้ามอย่างมีเสียง** ไม่ใช่เงียบ
 *    (`sales` ยิง ZORT สด · `stockcard`/`bundleitems` ต้องมี sku ก่อนจึงมีแถว)
 *
 * ใช้:  node scripts/probe-list-filters.mjs [ชื่อเส้น ...] [--write]
 *       ไม่ใส่ชื่อ = ทุกเส้นที่ปลอดภัยพอจะยิงอัตโนมัติ
 *       `--write` = เขียนผลลง `netlify/lib/list-filters-measured.mjs` ให้ท่อประกาศต่อฝั่งจอ
 *
 * ⚠️ **สแนปช็อตที่วัดแล้วจะเก่าเงียบ ๆ** — โค้ดเปลี่ยนแล้วไฟล์ไม่เปลี่ยนเอง
 *    ⇒ จึงเก็บ `วัดเมื่อ` ไปกับทุกแถว และมีด่านฟ้องเมื่อเก่าเกินเกณฑ์
 *    ⇒ **ห้ามแก้ไฟล์นั้นด้วยมือ** — ค่าที่ไม่ได้มาจากการวัด คือค่าที่เราเพิ่งพิสูจน์ว่าเชื่อไม่ได้
 */
