/** ตัดคอมเมนต์ตามนามสกุลไฟล์ — ส่งชื่อไฟล์มาด้วยเพื่อรู้ว่าภาษานั้นซ่อนข้อความยังไง
 *  🔑 ทุกครั้งที่ขยายขอบเขตการกวาดไปภาษาใหม่ **ต้องมาเพิ่มที่นี่** ไม่งั้นเปิดรูเดิมในที่ใหม่
 *  @param {string} เนื้อ
 *  @param {string} [ไฟล์] ชื่อไฟล์ (ใช้ตัดสินว่าเป็น html/py/sh ด้วยไหม)
 *  @param {{คงเลขบรรทัด?: boolean}} [ตัวเลือก]
 *    `คงเลขบรรทัด: true` ⇒ แทนคอมเมนต์ด้วยช่องว่างความยาวเท่าเดิม **เลขบรรทัดไม่ขยับ**
 *    (ผู้ใช้ที่ต้องรายงาน "ไฟล์:บรรทัด" ต้องใช้โหมดนี้ · ค่าเริ่มต้นคือลบทิ้งเหมือนเดิม)
 */
/** `/` ตรงตำแหน่งนี้เป็น **regex เปิด** หรือ **ตัวหาร**?
 *  ตัดสินจากอักษรโค้ดตัวสุดท้ายก่อนหน้า (ท่ามาตรฐานของ tokenizer JS):
 *  ตามหลัง ค่า/วงเล็บปิด/ตัวแปร ⇒ ตัวหาร · ตามหลังอย่างอื่น ⇒ regex เปิด
 *  ⚠️ `}` ถือเป็น regex เปิด เพราะในโค้ดจริงมันคือปิดบล็อกเกือบทุกครั้ง
 *  🔑 เดาผิดไม่เสียหาย เพราะผู้เรียกมีด่านที่สอง: regex ต้องปิดใน **บรรทัดเดียวกัน**
 *     (ไวยากรณ์ JS บังคับไว้แล้ว) ไม่ปิด = เราเดาผิด ⇒ ย้อนกลับไปถือว่าเป็นตัวหาร */
const คำที่ตามด้วยregexได้ = new Set([
  "return", "typeof", "case", "in", "of", "new", "delete", "void", "throw",
  "do", "else", "instanceof", "yield", "await",
]);
function เป็นregexเปิด(ก่อนหน้า) {
  /* ⚡ เดินย้อนหลังทีละอักษร **ห้ามใช้ regex กับ `ก่อนหน้า` ทั้งก้อน** —
     ฟังก์ชันนี้ถูกเรียกทุกครั้งที่เจอ `/` ในไฟล์ (หลายพันครั้งต่อ build) */
  let k = ก่อนหน้า.length - 1;
  while (k >= 0 && (ก่อนหน้า[k] === " " || ก่อนหน้า[k] === "\n" || ก่อนหน้า[k] === "\t" || ก่อนหน้า[k] === "\r")) k--;
  if (k < 0) return true; // ต้นไฟล์
  const ตัวท้าย = ก่อนหน้า[k];
  if (/[A-Za-z0-9_$]/.test(ตัวท้าย)) {
    let a = k;
    while (a >= 0 && /[A-Za-z0-9_$]/.test(ก่อนหน้า[a])) a--;
    return คำที่ตามด้วยregexได้.has(ก่อนหน้า.slice(a + 1, k + 1));
  }
  if (ตัวท้าย === ")" || ตัวท้าย === "]") return false;
  return true;
}

export function ตัดคอมเมนต์(เนื้อ, ไฟล์ = "", { คงเลขบรรทัด = false } = {}) {
  const s = String(เนื้อ);
  let out = "";
  const ทิ้ง = (ช่วง) => { out += คงเลขบรรทัด ? ช่วง.replace(/[^\n]/g, " ") : ช่วง.replace(/[^\n]/g, ""); };
  let i = 0;
  while (i < s.length) {
    const c = s[i];
    const สอง = s.slice(i, i + 2);
    /* คอมเมนต์บล็อก — หาตัวปิดจริง ถ้าไม่มีให้กินถึงท้ายไฟล์ (เหมือน JS จริง) */
    if (สอง === "/*") {
      const จบ = s.indexOf("*/", i + 2);
      const ถึง = จบ === -1 ? s.length : จบ + 2;
      ทิ้ง(s.slice(i, ถึง));
      i = ถึง;
      continue;
    }
    /* คอมเมนต์บรรทัด — ตัดถึงท้ายบรรทัด (ไม่กินตัวขึ้นบรรทัด) */
    if (สอง === "//") {
      let จบ = s.indexOf("\n", i);
      if (จบ === -1) จบ = s.length;
      ทิ้ง(s.slice(i, จบ));
      i = จบ;
      continue;
    }
    /* regex literal — ต้องมาหลังเช็ค `//` และ `/*` (คอมเมนต์ชนะเสมอ)
       ข้างใน `[...]` เครื่องหมาย `/` ไม่ปิด regex ⇒ ต้องจำสถานะ character class */
    if (c === "/" && เป็นregexเปิด(out)) {
      let j = i + 1, ในวงเล็บเหลี่ยม = false, ปิดแล้ว = false;
      while (j < s.length) {
        const d = s[j];
        if (d === "\\") { j += 2; continue; }
        if (d === "\n") break; // regex ข้ามบรรทัดไม่ได้ ⇒ เราเดาผิด
        if (ในวงเล็บเหลี่ยม) { if (d === "]") ในวงเล็บเหลี่ยม = false; j++; continue; }
        if (d === "[") { ในวงเล็บเหลี่ยม = true; j++; continue; }
        if (d === "/") { j++; ปิดแล้ว = true; break; }
        j++;
      }
      if (ปิดแล้ว) {
        while (j < s.length && /[dgimsuvy]/.test(s[j])) j++; // แฟล็ก
        out += s.slice(i, j);
        i = j;
        continue;
      }
      /* ไม่ปิดในบรรทัดเดียว = เดาผิด ⇒ ปล่อยให้เดินต่อทีละอักษรเหมือนตัวหาร */
    }
    /* สตริง/เทมเพลต — คัดลอกทั้งก้อนโดยไม่ตีความอะไรข้างใน */
    if (c === '"' || c === "'" || c === "`") {
      let j = i + 1;
      while (j < s.length) {
        if (s[j] === "\\") { j += 2; continue; }
        if (s[j] === c) { j++; break; }
        /* สตริงเดี่ยว/คู่ จบที่ตัวขึ้นบรรทัดเสมอ — กันสตริงที่ไม่ปิดลากทั้งไฟล์ */
        if (c !== "`" && s[j] === "\n") break;
        j++;
      }
      out += s.slice(i, j);
      i = j;
      continue;
    }
    out += c;
    i++;
  }
  if (/\.(html?|xml|svg|md)$/i.test(ไฟล์)) {
    out = คงเลขบรรทัด
      ? out.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, " "))
      : out.replace(/<!--[\s\S]*?-->/g, "");
  }
  if (/\.(py|sh|bash|zsh|toml|ya?ml|env|conf)$/i.test(ไฟล์)) {
    out = out.replace(/(^|\s)#[^\n]*/g, (m, p1) => (คงเลขบรรทัด ? p1 + " ".repeat(m.length - p1.length) : p1));
  }
  return out;
}
