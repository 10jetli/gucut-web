/** ตัดคอมเมนต์ตามนามสกุลไฟล์ — ส่งชื่อไฟล์มาด้วยเพื่อรู้ว่าภาษานั้นซ่อนข้อความยังไง
 *  🔑 ทุกครั้งที่ขยายขอบเขตการกวาดไปภาษาใหม่ **ต้องมาเพิ่มที่นี่** ไม่งั้นเปิดรูเดิมในที่ใหม่
 *  @param {string} เนื้อ
 *  @param {string} [ไฟล์] ชื่อไฟล์ (ใช้ตัดสินว่าเป็น html/py/sh ด้วยไหม)
 *  @param {{คงเลขบรรทัด?: boolean}} [ตัวเลือก]
 *    `คงเลขบรรทัด: true` ⇒ แทนคอมเมนต์ด้วยช่องว่างความยาวเท่าเดิม **เลขบรรทัดไม่ขยับ**
 *    (ผู้ใช้ที่ต้องรายงาน "ไฟล์:บรรทัด" ต้องใช้โหมดนี้ · ค่าเริ่มต้นคือลบทิ้งเหมือนเดิม)
 */
export function ตัดคอมเมนต์(เนื้อ, ไฟล์ = "", { คงเลขบรรทัด = false } = {}) {
  const s = String(เนื้อ);
  let out = "";
  const ทิ้ง = (ช่วง) => { out += คงเลขบรรทัด ? ช่วง.replace(/[^\n]/g, " ") : ช่วง.replace(/[^\n]/g, ""); };
  let i = 0;
  while (i < s.length) {
    const c = s[i];
    const สอง = s.slice(i, i + 2);
    /* คอมเมนต์บล็อก — หาตัวปิดจริง ถ้าไม่มีให้กินถึงท้ายไฟล์ (เหมือน JS จริง) */
    if (สอง === "/*") {
      const จบ = s.indexOf("*/", i + 2);
      const ถึง = จบ === -1 ? s.length : จบ + 2;
      ทิ้ง(s.slice(i, ถึง));
      i = ถึง;
      continue;
    }
    /* คอมเมนต์บรรทัด — ตัดถึงท้ายบรรทัด (ไม่กินตัวขึ้นบรรทัด) */
    if (สอง === "//") {
      let จบ = s.indexOf("\n", i);
      if (จบ === -1) จบ = s.length;
      ทิ้ง(s.slice(i, จบ));
      i = จบ;
      continue;
    }
    /* สตริง/เทมเพลต — คัดลอกทั้งก้อนโดยไม่ตีความอะไรข้างใน */
    if (c === '"' || c === "'" || c === "`") {
      let j = i + 1;
      while (j < s.length) {
        if (s[j] === "\\") { j += 2; continue; }
        if (s[j] === c) { j++; break; }
        /* สตริงเดี่ยว/คู่ จบที่ตัวขึ้นบรรทัดเสมอ — กันสตริงที่ไม่ปิดลากทั้งไฟล์ */
        if (c !== "`" && s[j] === "\n") break;
        j++;
      }
      out += s.slice(i, j);
      i = j;
      continue;
    }
    out += c;
    i++;
  }
  if (/\.(html?|xml|svg|md)$/i.test(ไฟล์)) {
    out = คงเลขบรรทัด
      ? out.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, " "))
      : out.replace(/<!--[\s\S]*?-->/g, "");
  }
  if (/\.(py|sh|bash|zsh|toml|ya?ml|env|conf)$/i.test(ไฟล์)) {
    out = out.replace(/(^|\s)#[^\n]*/g, (m, p1) => (คงเลขบรรทัด ? p1 + " ".repeat(m.length - p1.length) : p1));
  }
  return out;
}
