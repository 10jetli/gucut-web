/** ตัดคอมเมนต์ตามนามสกุลไฟล์ — ส่งชื่อไฟล์มาด้วยเพื่อรู้ว่าภาษานั้นซ่อนข้อความยังไง
 *  🔑 ทุกครั้งที่ขยายขอบเขตการกวาดไปภาษาใหม่ **ต้องมาเพิ่มที่นี่** ไม่งั้นเปิดรูเดิมในที่ใหม่ */
export function ตัดคอมเมนต์(เนื้อ, ไฟล์ = "") {
  let out = String(เนื้อ)
    .replace(/^\s*\/\/.*$/gm, "")          // คอมเมนต์ที่กินทั้งบรรทัด
    .replace(/(^|\s)\/\/[^\n]*$/gm, "$1")  // คอมเมนต์ท้ายบรรทัด (ต้องมีช่องว่าง/ต้นบรรทัดนำ)
    .replace(/\/\*[\s\S]*?\*\//g, "");     // คอมเมนต์บล็อก
  if (/\.(html?|xml|svg|md)$/i.test(ไฟล์)) out = out.replace(/<!--[\s\S]*?-->/g, "");
  if (/\.(py|sh|bash|zsh|toml|ya?ml|env|conf)$/i.test(ไฟล์)) out = out.replace(/(^|\s)#[^\n]*/g, "$1");
  return out;
}
