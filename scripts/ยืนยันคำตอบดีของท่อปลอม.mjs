#!/usr/bin/env node
/* ยืนยันว่า **คำตอบ "ของดี" ของท่อปลอมยังดีอยู่** — ใช้เป็น `ยืนยันปลูกลง` ของทะเบียนด่าน
 *
 * 🔑 ทำไมต้องมีไฟล์นี้: เครื่องมือร่วม `ปลูกแล้ววัด` บังคับให้พิสูจน์ว่าปลูกลงจริง
 *    ด้วยคำสั่งที่ **ต้องล้มหลังปลูก** · แต่การปลูกที่นี่เป็นการ **ลบ/แก้คีย์ในคำตอบ**
 *    ⇒ `node --check` ยังผ่าน (ไฟล์ยังถูกไวยากรณ์) ⇒ ใช้เป็นหลักฐานไม่ได้
 *    ⇒ ไฟล์นี้ตรวจ *ความหมาย* แทน: คำตอบของดีต้องมีคีย์ตามสัญญาครบ และขาเขียนต้องถูกปฏิเสธ
 *
 * exit 0 = ของดียังดี (ยังไม่ปลูก) · exit 1 = มีอะไรถูกแก้ (ปลูกลงแล้ว)
 */
import { เครดิต, ใบคืนสินค้า, คำตอบlist, สถานะที่ควรตอบ } from "./ท่อปลอมสำหรับวัดด่าน.mjs";

const พลาด = [];
const ต้องมี = (o, คีย์, ชื่อ) => {
  for (const k of คีย์) if (!Object.prototype.hasOwnProperty.call(o, k)) พลาด.push(`${ชื่อ} ขาด ${k}`);
};

ต้องมี(เครดิต, ["used", "plan", "burnPerDay", "daysLeft", "burnWindowHours",
  "ตัวอย่างล่าสุดเมื่อ", "ตัวอย่างเก่าเกินชั่วโมง"], "เครดิต");
ต้องมี(ใบคืนสินค้า, ["list", "unreadable", "qtyUnreadableLines", "qtyZeroLines",
  "priceUnreadableLines"], "ใบคืนสินค้า");
ต้องมี(คำตอบlist, ["limitClamped", "สัญญาของเส้นนี้", "applied"], "คำตอบlist");

/* ขาเขียนต้องถูกปฏิเสธ — ถ้าตารางตัดสินถูกแก้ให้ปล่อยผ่าน ต้องจับได้ที่นี่ */
const คู่ที่ต้องเป็น = [
  ["GET", "list=orders&limit=1", 200], ["POST", "list=orders&limit=1", 405],
  ["DELETE", "list=orders&limit=1", 405], ["POST", "move=1", 400],
  ["GET", "addsale=1", 405], ["DELETE", "movedel=not-a-number", 400],
];
for (const [m, q, ควร] of คู่ที่ต้องเป็น) {
  const ได้ = สถานะที่ควรตอบ(m, q);
  if (ได้ !== ควร) พลาด.push(`${m} ?${q} ควร ${ควร} แต่ตารางบอก ${ได้}`);
}

if (พลาด.length) {
  console.error(`❌ คำตอบของดีถูกแก้ ${พลาด.length} จุด: ${พลาด.join(" · ")}`);
  process.exit(1);
}
console.log("✅ คำตอบ 'ของดี' ของท่อปลอมครบตามสัญญา");
