#!/usr/bin/env node
/* 🧪 **ตัวช่วยปลูกบั๊กพิสูจน์ด่าน** — บังคับสามข้อที่ทีมพลาดซ้ำ ๆ ให้เป็นกลไก ไม่ใช่ความระวัง
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — **ทีมปลูกบั๊กไม่ลง/ผิดรูป รวมกัน 10 ครั้งในวันเดียว**
 *    (ฝั่งจอ 8 · ฝั่งท่อ 2) และ **ทุกครั้งผลขึ้น "เขียว"**
 *    ⇒ "เขียว" ตอนปลูกบั๊กมีสองความหมายที่ตรงข้ามกัน:
 *      ① ด่านจับไม่ได้ (ด่านพัง — ต้องแก้ด่าน)
 *      ② **การปลูกไม่ได้ลงจริง** (ไม่ได้ทดสอบอะไรเลย — ต้องแก้วิธีปลูก)
 *    ⇒ ถ้าเชื่อผลรอบแรก จะไป "แก้" ด่านที่ทำงานถูกอยู่แล้ว = **ตัวแก้ที่ทำลายของถูก**
 *    ⇒ ของจริงวันนี้: เกือบรายงานว่าด่านคุมสวิตช์ส่งของจริงพัง · เกือบรายงานว่าด่าน 3 ตัวพัง
 *
 * 🔑 เครื่องมือนี้แยกสามสถานะให้ขาด และ **คืนไฟล์เดิมเสมอ** (แม้คำสั่งทดสอบจะพังกลางทาง)
 *
 * ใช้:
 *   node scripts/plant-bug.mjs <ไฟล์> <ข้อความที่จะแทน> <แทนด้วย> -- <คำสั่งทดสอบ...>
 * ตัวอย่าง:
 *   node scripts/plant-bug.mjs netlify/lib/zort-stock.mjs \
 *     'return Number.isFinite(n) ? n : null;' 'return Number.isFinite(n) ? n : 0;' \
 *     -- npm test
 *
 * 🚫 **ห้ามใช้กับไฟล์ที่ไม่อยู่ใน git** — ตัวนี้พึ่ง git ยืนยันว่าคืนไฟล์ครบ
 *
 * ⚠️ **ข้อจำกัดที่ต้องรู้ก่อนอ่านผล** (เพิ่ม 19 ก.ย. 2569 · ฝั่งจอเป็นคนชี้หลักการ)
 *    เครื่องมือนี้ **ยุบการทดลองให้เหลือคำตัดสิน** ⇒ มันพกสมมติฐานของการทดลองไปด้วยว่า
 *    **"การปลูก = ใส่ของเสีย"** ⇒ ป้าย ✅/🔴 อ่านถูกเฉพาะเมื่อใช้ตามสมมติฐานนั้น
 *    ⇒ ถ้าใช้ **กลับทิศ** (ปลูกของที่ทำให้สถานะกลายเป็นปกติ เพื่อพิสูจน์ว่าด่านเงียบได้จริง)
 *      ป้าย "🔴 ด่านจับไม่ได้" จะโผล่มาในขณะที่ **นั่นคือผลที่เราต้องการ**
 *    ⇒ ใช้กลับทิศได้ **แต่ต้องอ่านผลเอง อย่าอ่านป้าย** (ผมใช้แบบนี้พิสูจน์ตัวเฝ้าตัวสำรอง 19 ก.ย.)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";

/* 🔴 **คำสั่งทดสอบที่จบด้วยท่อ (`| tail` · `| grep` · `| head`) จะกลืน exit code** (เพิ่ม 19 ก.ย. 2569)
   ผมเหยียบกับดักนี้ **สามครั้งในวันเดียว**: ห่อฮุกด้วย `| tail -8` ⇒ exit code มาจาก `tail`
   ⇒ เครื่องมือนี้สรุปว่า "ด่านจับไม่ได้" ทั้งที่ด่านตกถูกต้อง ⇒ **แดงลวงที่พาไปรื้อของที่ทำงานดี**
   🔑 กฎที่พลาดซ้ำต้องเป็นด่าน ไม่ใช่ความจำ ⇒ เตือนตรงนี้ก่อนรัน (เตือน ไม่ขวาง —
      เพราะบางครั้งเจตนาคือ exit code ของตัวท้ายท่อจริง ๆ) */
function เตือนท่อกลืนรหัสจบ(คำสั่ง) {
  const s = คำสั่ง.join(" ");
  if (!/\|\s*(tail|head|grep|sed|awk|cut|wc)\b/.test(s)) return;
  if (/exit\s+\$\{?(rc|PIPESTATUS)/.test(s) || /set\s+-o\s+pipefail/.test(s)) return;
  console.log(
    "⚠️  คำสั่งทดสอบมีท่อไปหา tail/grep/head — **exit code จะเป็นของตัวท้ายท่อ ไม่ใช่ของด่าน**\n" +
    "    ⇒ ผลอาจออกมาเป็น 'ด่านจับไม่ได้' ทั้งที่ด่านตกถูกต้อง (เจอจริง 3 ครั้ง 19 ก.ย. 2569)\n" +
    "    ⇒ ท่าที่ถูก: `bash -c 'คำสั่ง > /tmp/log 2>&1; rc=$?; tail -20 /tmp/log; exit $rc'`\n"
  );
}

const argvดิบ = process.argv.slice(2);
/* 🔴 **ธง `--คาดว่าแดง <ข้อความในชื่อเทส>`** (เพิ่ม 19 ก.ย. 2569 · ฝั่งจอชี้ให้)
   คำของเขา: *"เครื่องมือที่ยุบการทดลองให้เหลือคำตัดสิน จะพกสมมติฐานของการทดลองนั้นไปด้วย"*
   ⇒ รุ่นแรกของเครื่องมือนี้สรุปว่า **"ตก = ด่านจับได้"** ซึ่งพกสมมติฐานที่ไม่ได้เขียนบอกไว้ว่า
     **ตกเพราะข้อที่เราสนใจ** ⇒ ถ้าปลูกบั๊กแล้วทำเทสข้ออื่นพังเป็นลูกโซ่ มันก็ยังขึ้น ✅
   ⇒ ใส่ชื่อเทสที่คาดว่าจะแดงมาด้วย แล้วเครื่องมือจะเทียบให้ ⇒ **แดงถูกข้อ** ต่างจาก **แดงข้ออื่น** */
let คาดว่าแดง = null;
const argv = [];
for (let i = 0; i < argvดิบ.length; i++) {
  if (argvดิบ[i] === "--คาดว่าแดง" || argvดิบ[i] === "--expect-red") { คาดว่าแดง = argvดิบ[++i]; continue; }
  argv.push(argvดิบ[i]);
}
const แบ่ง = argv.indexOf("--");
if (แบ่ง < 0 || แบ่ง < 3) {
  console.error(
    "ใช้: node scripts/plant-bug.mjs <ไฟล์> <ข้อความที่จะแทน> <แทนด้วย> -- <คำสั่งทดสอบ...>\n" +
    "  ⚠️ ต้องมี `--` คั่นก่อนคำสั่งทดสอบ"
  );
  process.exit(2);
}
const [ไฟล์, หา, แทน] = argv.slice(0, 3);
const คำสั่ง = argv.slice(แบ่ง + 1);
if (!คำสั่ง.length) { console.error("ไม่ได้ใส่คำสั่งทดสอบหลัง --"); process.exit(2); }

const md5 = (s) => createHash("md5").update(s).digest("hex").slice(0, 12);
const เดิม = readFileSync(ไฟล์, "utf8");
const md5เดิม = md5(เดิม);

/* ── ข้อ ① ยืนยันว่าข้อความที่จะแทน **มีอยู่จริง** และรู้ว่ามีกี่จุด ───────────────
   🔑 หาไม่เจอ = ปลูกไม่ลง ⇒ ต้องหยุดที่นี่ **ห้ามปล่อยให้ไปรันทดสอบแล้วอ่านผลเขียว** */
const จำนวนที่เจอ = เดิม.split(หา).length - 1;
if (จำนวนที่เจอ === 0) {
  console.error(
    `✗ ปลูกไม่ลง — หาข้อความนี้ใน ${ไฟล์} ไม่เจอเลย:\n    ${หา.slice(0, 120)}\n` +
    "  🔑 **นี่คือสาเหตุอันดับหนึ่งของ \"ปลูกบั๊กแล้วด่านยังเขียว\"**\n" +
    "     (ไฟล์ถูกแก้ไปแล้วก่อนหน้า · ช่องว่างไม่ตรง · คัดลอกมาจากรุ่นเก่า)\n" +
    "  ⇒ เปิดไฟล์ดูของจริงก่อน แล้วคัดลอกข้อความจากไฟล์ตรง ๆ"
  );
  process.exit(3);
}
if (จำนวนที่เจอ > 1) {
  console.log(`⚠️ เจอ ${จำนวนที่เจอ} จุด — จะแทน **ทุกจุด** (ถ้าต้องการจุดเดียว ให้ใส่ข้อความที่เจาะจงกว่านี้)`);
}

const ใหม่ = เดิม.split(หา).join(แทน);
/* ── ข้อ ② ยืนยันว่าเนื้อไฟล์ **เปลี่ยนจริง** (ไม่ใช่แทนด้วยของเดิม) ── */
if (md5(ใหม่) === md5เดิม) {
  console.error(`✗ ปลูกไม่ลง — แทนแล้วเนื้อไฟล์ไม่เปลี่ยน (md5 เดิม ${md5เดิม})\n` +
    "  ⇒ 'แทนด้วย' เหมือน 'ข้อความที่จะแทน' หรือเปล่า");
  process.exit(3);
}

let ผลรัน = null;
try {
  writeFileSync(ไฟล์, ใหม่);
  console.log(`🧪 ปลูกแล้ว: ${ไฟล์} · ${จำนวนที่เจอ} จุด · md5 ${md5เดิม} → ${md5(ใหม่)}`);
  console.log(`▶️  รัน: ${คำสั่ง.join(" ")}`);
  เตือนท่อกลืนรหัสจบ(คำสั่ง);   // ⚠️ ท่อกลืน exit code ⇒ ผลจะเป็น "จับไม่ได้" ทั้งที่ด่านตก
  /* ⚠️ ต้อง **เก็บ output ไว้เทียบ** ไม่ใช่ inherit เฉย ๆ ไม่งั้นตรวจไม่ได้ว่าแดงถูกข้อ
     แต่ยังพิมพ์ให้เห็นทั้งหมดเหมือนเดิม (ห้ามกลืน output — คนต้องเห็นว่าเกิดอะไรขึ้น) */
  ผลรัน = spawnSync(คำสั่ง[0], คำสั่ง.slice(1), { encoding: "utf8", shell: false });
  if (ผลรัน.stdout) process.stdout.write(ผลรัน.stdout);
  if (ผลรัน.stderr) process.stderr.write(ผลรัน.stderr);
} finally {
  /* ── ข้อ ③ **คืนไฟล์เดิมเสมอ และพิสูจน์ว่าคืนครบ** ─────────────────────────
     🔴 ถ้าคืนไม่ครบ เราจะทิ้งบั๊กที่ปลูกไว้ในรีโปโดยไม่มีใครรู้
        ⇒ ของที่สร้างมาพิสูจน์ความถูกต้อง กลายเป็นตัวใส่บั๊กเอง */
  writeFileSync(ไฟล์, เดิม);
  const md5คืน = md5(readFileSync(ไฟล์, "utf8"));
  if (md5คืน !== md5เดิม) {
    console.error(`🔴🔴 **คืนไฟล์ไม่ครบ** (${md5คืน} ≠ ${md5เดิม}) ⇒ รีบ \`git checkout ${ไฟล์}\` เดี๋ยวนี้`);
    process.exit(4);
  }
  console.log(`♻️  คืนไฟล์เดิมแล้ว · md5 ตรงกับก่อนปลูก (${md5เดิม})`);
}

const รหัสออก = ผลรัน?.status;
if (ผลรัน?.error) {
  console.error(`✗ รันคำสั่งทดสอบไม่ได้: ${ผลรัน.error.message}`);
  console.error("  ⇒ **นี่ไม่ใช่ผลของด่าน** — ยังไม่ได้ทดสอบอะไร");
  process.exit(5);
}

console.log("\n══════════ ผลการพิสูจน์ ══════════");

/* รายชื่อเทสที่แดง — อ่านจากรูป TAP ของ node:test (`not ok <n> - <ชื่อ>`) */
const ข้อที่แดง = [...String(ผลรัน.stdout || "").matchAll(/^not ok \d+ - (.+)$/gm)].map((m) => m[1].trim());
if (ข้อที่แดง.length) {
  console.log(`📋 ข้อที่แดง ${ข้อที่แดง.length} ข้อ:`);
  for (const t of ข้อที่แดง) console.log(`   · ${t.slice(0, 100)}`);
}

if (รหัสออก !== 0) {
  /* 🔑 **แดง ≠ แดงถูกข้อ** — ถ้าไม่ระบุ `--คาดว่าแดง` เครื่องมือต้องบอกตรง ๆ ว่ามันไม่รู้ */
  if (!คาดว่าแดง) {
    console.log(
      `✅ **ปลูกลงจริง และคำสั่งทดสอบตก** (exit ${รหัสออก})\n` +
      "   ⚠️ แต่เครื่องมือนี้ **ยังไม่รู้ว่าแดงเพราะข้อที่คุณสนใจหรือข้ออื่น**\n" +
      "      ⇒ ใส่ `--คาดว่าแดง \"<ข้อความในชื่อเทส>\"` แล้วมันจะเทียบให้\n" +
      "   ⚠️ และเหลืออีกครึ่งที่ตรวจให้ไม่ได้: **ด่านต้องไม่ร้องใส่ของปกติ**\n" +
      "      ⇒ ต้องมีเทสอีกข้อที่ใส่ \"ของถูกแต่ต่างจากเดิม\" แล้วต้องเขียว (พลังแยกแยะ)"
    );
    process.exit(0);
  }
  const ตรงข้อ = ข้อที่แดง.filter((t) => t.includes(คาดว่าแดง));
  const ข้ออื่น = ข้อที่แดง.filter((t) => !t.includes(คาดว่าแดง));
  if (!ตรงข้อ.length) {
    console.error(
      `⚠️ **แดง แต่ไม่ใช่ข้อที่คาด** — หา "${คาดว่าแดง}" ในชื่อข้อที่แดงไม่เจอ\n` +
      "   ⇒ ด่านที่คุณตั้งใจทดสอบ **อาจไม่ได้จับอะไรเลย** และที่แดงคือของอื่นพังเป็นลูกโซ่\n" +
      "   ⇒ **ห้ามอ่านผลนี้ว่าด่านพิสูจน์แล้ว**"
    );
    process.exit(1);
  }
  console.log(
    `✅ **ด่านพิสูจน์แล้ว** — ปลูกลงจริง และ **แดงถูกข้อ** (${ตรงข้อ.length} ข้อตรงกับที่คาด)` +
    (ข้ออื่น.length
      ? `\n   ⚠️ มีอีก ${ข้ออื่น.length} ข้อที่แดงด้วย — ดูว่าพังเป็นลูกโซ่หรือเป็นด่านอื่นที่จับได้จริง`
      : "") +
    "\n   ⚠️ เหลืออีกครึ่งที่ตรวจให้ไม่ได้: **ด่านต้องไม่ร้องใส่ของปกติ** (พลังแยกแยะ)"
  );
  process.exit(0);
}
console.error(
  "🔴 **ด่านจับไม่ได้** — ปลูกบั๊กลงจริง (ยืนยันด้วย md5 แล้ว) แต่คำสั่งทดสอบ **ผ่าน**\n" +
  "   ⇒ คราวนี้ตัดสินได้เลยว่าเป็นที่ด่าน **ไม่ใช่ที่วิธีปลูก** เพราะการปลูกถูกยืนยันแล้ว\n" +
  "   ⇒ ไปดูว่าด่านค้นด้วยรูปอะไร · ตรวจก้อนที่ใหญ่เกินไปหรือเปล่า · หรือถูกคอมเมนต์ทำให้พอใจ"
);
process.exit(1);
