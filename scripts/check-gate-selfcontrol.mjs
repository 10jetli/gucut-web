#!/usr/bin/env node
/* 🧪 ตัวนับหนี้: **ด่านที่ไม่มีตัวควบคุมฝังใน ต้องลดลง ห้ามเพิ่ม**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ฝั่งจอเสนอ และเป็น **หนี้ร่วมที่วัดได้ทั้งสองฝั่ง**
 *    ฝั่งท่อ **1 จาก 18** · ฝั่งจอ **3 จาก 47** ⇒ สัดส่วนพอ ๆ กัน (~6%) ⇒ ไม่ใช่ปัญหาบ้านเดียว
 *
 * 🔑 **ทำไมต้องเป็น "ฝังใน" ไม่ใช่ขั้นแยกในสาย**
 *    ฝั่งจอมี 8 ตัวที่ทำ `--self-test` เป็น **ขั้นแยกใน `package.json`** ⇒ รันทุก build เหมือนกัน
 *    ⚠️ แต่ **ถอดขั้นนั้นออกเมื่อไหร่ ด่านยังเขียวโดยไม่มีอะไรฟ้อง**
 *    ⇒ ⇒ ฝังในตัวด่าน = **ลืมเรียกไม่ได้ และถอดออกโดยไม่ตั้งใจไม่ได้**
 *
 * 📏 **สองแกนที่ต้องแยก (อย่ารวมเป็นเลขเดียว — ฝั่งจอชี้ และถูก)**
 *    ① **ตะแกรงแยกแยะได้** — มีเคส **ต้องจับ** และ **ต้องไม่จับ** อยู่ในโค้ดที่รันจริง
 *       ตอบคำถาม: *ตะแกรงยังมองเห็นของที่มันควรเห็นไหม*
 *       ⚠️ มีแต่เคส "ต้องจับ" ⇒ มองไม่เห็นตะแกรงที่ **กว้างเกิน** (ร้องใส่ของถูก)
 *    ② **พื้นประชากร** — กวาดได้ 0/น้อยผิดปกติ ⇒ ประกาศว่า **ตะแกรงพัง** ไม่ใช่ "รีโปสะอาด"
 *       ตอบคำถาม: *เรายังส่องของอยู่จริงไหม*
 *    ⇒ ด่านนี้นับ **แกน ① เท่านั้น** (แกน ② ฝั่งท่อมีอยู่แล้ว 10/18 ⇒ ไม่ใช่คอขวด)
 *
 * 🔴 **ต้องตัดคอมเมนต์ก่อนนับ** — "เล่าว่าเคยทำตัวควบคุมด้วยมือ" ไม่ใช่ "มีตัวควบคุม"
 *    ฝั่งจอเจอว่าตะแกรงเขา **นับเกิน 1 ตัว** เพราะข้อนี้ ⇒ เปิดอ่านทีละไฟล์แล้วจับได้
 *    ⇒ ⇒ **"การเอ่ยถึงตัวควบคุม" กับ "การมีตัวควบคุม" แยกจาก grep เปล่า ๆ ไม่ได้**
 *
 * 📌 **ลำดับที่ตกลงกับฝั่งจอว่าจะไล่ก่อน** (เกณฑ์เดียวกันทั้งสองฝั่ง เพื่อเทียบกันได้)
 *    ① ด่านที่ **เขียวมาตลอดและไม่เคยแดงเลย** ⇒ เสี่ยงเป็นเขียวลวงที่สุด
 *    ② ด่านที่ **ตะแกรงเป็น regex** ⇒ พังเงียบง่ายที่สุด (เราสองคนโดนคนละสองรอบวันนี้)
 *    ③ ด่านที่ **คุมเส้นเงิน/สต็อก** ⇒ ผิดแล้วแพงที่สุด
 *
 * ใช้: node scripts/check-gate-selfcontrol.mjs
 */
import { readFileSync } from "node:fs";
import { ตัดคอมเมนต์ } from "./_strip-comments.mjs";

/* 🔒 เพดาน = **ของจริงวันที่ตั้ง** (20 ก.ย. 2569: 18 ด่าน − 1 ที่มีแล้ว = 17)
   ลดได้ ห้ามขึ้น · ต่ำกว่าเพดานก็ตก (ต้องขันเลขในคอมมิตเดียวกัน) */
const เพดาน = 17;

/** มีตัวควบคุม **แกน ①** ในโค้ดที่รันจริงไหม (ไม่นับคอมเมนต์)
 *  🔴 **รอบแรกผมเขียนแค่ `/ต้องจับ/.test(โค้ด)` และมันนับเกิน** (จับได้ตอนปลูกทดสอบ 20 ก.ย. 2569)
 *     เหตุ: ด่านที่มีตัวควบคุมจริงจะ **พิมพ์คำว่า "ต้องไม่จับแต่จับ"** ในข้อความ error ด้วย
 *     ⇒ ⇒ ด่านที่ **แค่พิมพ์คำนั้น** แต่ไม่มีชุดเคสจริง **ก็จะถูกนับว่ามี**
 *     🔑 คลาสเดิมของเราเป๊ะ: **นับคำ ไม่ได้นับของ** ⇒ ต้องจับ **การประกาศตัวแปร** ไม่ใช่การเอ่ยถึง
 *  ⚠️ ผูกกับชื่อ `ต้องจับ` / `ต้องไม่จับ` โดยตั้งใจ — เป็นสำนวนของรีโปนี้ (ประกาศไว้ให้รู้ว่าเส้นแบ่งอยู่ไหน)
 *     วันไหนมีคนใช้ชื่ออื่น ด่านนี้จะนับว่า "ไม่มี" ⇒ ฝั่งปลอดภัย (หนี้ดูมากกว่าจริง ไม่ใช่น้อยกว่า) */
const ประกาศตัวแปร = (ชื่อ) => new RegExp(`(?:const|let|var)\\s+${ชื่อ}\\s*=`);
/* 🔴🔴 **เงื่อนไขที่สอง — ยกมาจากฝั่งจอ 20 ก.ย. 2569 หลังผมยิงทดสอบแล้วพบว่าเป็นรูจริง**
   ตะแกรงที่ดูแค่ **การประกาศตัวแปร** ยังนับของปลอมเป็นของจริง:
   ปลูก `const ต้องจับ = ["a"]; const ต้องไม่จับ = ["b"]; void ต้องจับ;` (ไม่เทียบผลเลย ไม่มี exit)
   ⇒ ⇒ **ตะแกรงรอบก่อนของผมนับว่า "มี"** ⇒ หนี้ลดจาก 17 เป็น 16 โดยที่ไม่มีการตรวจอะไรเกิดขึ้น
   ⚠️ **ร้ายกว่าการนับเกินของรอบก่อน** เพราะทำให้หนี้ดู **น้อยกว่าจริง** = ทิศที่ไม่มีใครมาตรวจ
   ⇒ จึงต้องเห็น **การเทียบผลจริงแล้วทำให้ตก** ด้วย ไม่ใช่แค่มีชุดเคสวางไว้
   🔑 ฝั่งจอมีเงื่อนไขนี้ตั้งแต่ตัวแรก และมัน **กันรูปของผมไว้ก่อนที่ผมจะรู้ว่ามีรูป** */
/* 🔴🔴 **รอบแรกผมเขียนเงื่อนไขนี้ผิดที่ และยิงทดสอบจับได้ทันที**
   เดิมถามว่า *"ไฟล์นี้มี `process.exit(1)` ไหม"* ⇒ **ด่านทุกตัวมี** (มันคือด่าน!) ⇒ **เงื่อนไขไร้ผล**
   ⇒ ปลูกของปลอม (`const ต้องจับ = [...]; void ต้องจับ;`) ⇒ หนี้ยังลดเป็น 16 ⇒ รูไม่ปิด
   🔑 **เกณฑ์ต้องผูกกับตัวของมันเอง ไม่ใช่กับอะไรก็ได้ที่อยู่ในไฟล์เดียวกัน**
      ⇒ ต้องเห็นว่า **ชุดเคสถูกนำไปใช้** (`ต้องจับ.filter(...)` / `.some(...)`)
      ไม่ใช่แค่ "ไฟล์นี้มีคำว่า filter อยู่ที่ไหนก็ได้" */
const ถูกนำไปใช้จริง = (ชื่อ, โค้ด) =>
  new RegExp(`${ชื่อ}\\s*\\.\\s*(?:filter|some|every|map|forEach|find)\\s*\\(`).test(โค้ด);
const เทียบผลแล้วทำให้ตก = (โค้ด) =>
  ถูกนำไปใช้จริง("ต้องจับ", โค้ด) && ถูกนำไปใช้จริง("ต้องไม่จับ", โค้ด);
export function มีตัวควบคุมสองทาง(เนื้อ, ชื่อไฟล์ = "x.mjs") {
  const โค้ด = ตัดคอมเมนต์(String(เนื้อ), ชื่อไฟล์);
  return ประกาศตัวแปร("ต้องจับ").test(โค้ด)
    && ประกาศตัวแปร("ต้องไม่จับ").test(โค้ด)
    && เทียบผลแล้วทำให้ตก(โค้ด);
}

/* 🧪 **ตัวควบคุมของด่านนี้เอง — รันทุกรอบ** (ไม่มีก็ตลก เพราะนี่คือด่านที่นับเรื่องนี้)
   ⚠️ เคสสำคัญที่สุดคือ **คอมเมนต์ต้องไม่นับ** — นั่นคือรูปที่ทำให้ฝั่งจอนับเกิน */
{
  /* 🔑 เคส "ต้องจับ" ต้องเป็น **ตัวควบคุมที่สมบูรณ์** — มีชุดเคสสองฝั่ง **และ** เทียบผลแล้วทำให้ตก
     (เดิมผมใส่แค่การประกาศตัวแปรสั้น ๆ ⇒ พอเพิ่มเงื่อนไขที่สอง เคสเก่าก็ตกทันที
      ⇒ ⇒ นั่น **ถูกต้อง**: เคสที่ไม่สมบูรณ์ไม่ควรถูกนับว่าเป็นตัวควบคุม) */
  const ต้องจับ = [
    'const ต้องจับ = ["a"]; const ต้องไม่จับ = ["b"];\nconst พลาด = [...ต้องจับ.filter(f), ...ต้องไม่จับ.filter(g)]; if (พลาด.length) process.exit(1);',
    'let ต้องจับ=[];\nlet ต้องไม่จับ=[];\nif (ต้องจับ.some(g) || ต้องไม่จับ.some(h)) throw new Error("x");',
  ];
  const ต้องไม่จับ = [
    "/* เคยทำตัวควบคุมด้วยมือ: ต้องจับ และ ต้องไม่จับ */ const x = 1;",
    "// วิธีทดสอบ: ปลูกของที่ ต้องจับ แล้วดูว่าแดง\nconst y = 2;",
    'const ต้องจับ = ["a"]; // ไม่มีฝั่งต้องไม่จับ ⇒ ทางเดียว ไม่นับ',
    /* 🔴 เคสที่จับผมได้เอง: ด่านที่ **พิมพ์** คำนั้นในข้อความ error แต่ไม่มีชุดเคสจริง */
    'console.error("ต้องไม่จับแต่จับ: " + x); console.error("ต้องจับแต่ไม่จับ");',
    /* 🔴 เคสที่ผมยิงทดสอบแล้วพบว่าตะแกรงรอบก่อน **นับของปลอมเป็นของจริง** (ทิศที่ทำให้หนี้ดูน้อยกว่าจริง) */
    'const ต้องจับ = ["a"];\nconst ต้องไม่จับ = ["b"];\nvoid ต้องจับ; void ต้องไม่จับ;',
    "const z = 3;",
  ];
  const พลาด = [
    ...ต้องจับ.filter((x) => !มีตัวควบคุมสองทาง(x)).map((x) => `ต้องจับแต่ไม่จับ: ${x.slice(0, 60)}`),
    ...ต้องไม่จับ.filter((x) => มีตัวควบคุมสองทาง(x)).map((x) => `ต้องไม่จับแต่จับ: ${x.slice(0, 60)}`),
  ];
  if (พลาด.length) {
    console.error(
      "🔴 **ตัวควบคุมของด่านนี้ไม่ผ่าน ⇒ ผลของด่านนี้อ่านไม่ได้** (ไม่ใช่ 'ไม่มีหนี้')\n" +
      พลาด.map((x) => `   · ${x}`).join("\n") +
      "\n   ⇒ น่าจะมาจากตัวถอดคอมเมนต์หรือรูปที่ใช้จับเปลี่ยน ⇒ แก้ตะแกรงก่อน แล้วรันซ้ำ"
    );
    process.exit(1);
  }
}

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const ด่าน = [...new Set([...(pkg.scripts.prebuild || "").matchAll(/scripts\/(check-[\w-]+)\.mjs/g)].map((m) => m[1]))];
if (ด่าน.length < 5) {
  console.error(`🔴 อ่านรายชื่อด่านจากสาย prebuild ได้แค่ ${ด่าน.length} ตัว ⇒ ตะแกรงพัง ไม่ใช่ว่าสายว่าง`);
  process.exit(1);
}

const ไม่มี = [];
for (const g of ด่าน) {
  let s = "";
  try { s = readFileSync(`scripts/${g}.mjs`, "utf8"); } catch (e) {
    console.error(`🔴 อ่าน scripts/${g}.mjs ไม่ได้: ${String(e?.message || e).slice(0, 80)} ⇒ นับไม่ครบ ⇒ ตก`);
    process.exit(1);
  }
  if (!มีตัวควบคุมสองทาง(s, `${g}.mjs`)) ไม่มี.push(g);
}

console.log(
  `🧪 ด่านที่ยังไม่มีตัวควบคุมฝังใน (แกน ① สองทาง): **${ไม่มี.length} จาก ${ด่าน.length}** (เพดาน ${เพดาน})\n` +
  "   📉 เลขนี้ต้องลดลง — **อ่านเป็นหนี้ ไม่ใช่บั๊ก** · เป็นหนี้ร่วมกับฝั่งจอ (เขา 44 จาก 47)\n" +
  "   🔑 ไล่ตามลำดับ: ① เขียวมาตลอดไม่เคยแดง ② ตะแกรงเป็น regex ③ คุมเส้นเงิน/สต็อก"
);
if (ไม่มี.length) console.log(`   · ${ไม่มี.join(" · ")}`);

if (ไม่มี.length > เพดาน) {
  console.error(
    `\n🔴 หนี้โตขึ้น (${ไม่มี.length} > ${เพดาน}) ⇒ มีด่านใหม่ที่ไม่มีตัวควบคุมฝังใน\n` +
    "   ⇒ ท่าที่ใช้: ใส่ชุด `ต้องจับ` / `ต้องไม่จับ` ไว้ในตัวด่าน แล้วให้ **ตกทันทีถ้าควบคุมไม่ผ่าน**\n" +
    "     พร้อมข้อความว่า **'ผลของด่านนี้อ่านไม่ได้'** ไม่ใช่ 'ไม่มีของ'\n" +
    "   📌 ตัวอย่างที่ทำแล้ว: `scripts/check-layer-direction.mjs`"
  );
  process.exit(1);
}
if (ไม่มี.length < เพดาน) {
  console.error(
    `\n❌ เหลือ ${ไม่มี.length} ต่ำกว่าเพดาน ${เพดาน} แล้ว ⇒ **ลดเพดานในไฟล์นี้ให้เท่ากับ ${ไม่มี.length} ในคอมมิตเดียวกัน**\n` +
    "   (เพดานที่ไม่ตามความจริง = ช่องว่างให้หนี้โตขึ้นเงียบ ๆ)"
  );
  process.exit(1);
}
