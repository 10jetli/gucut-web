#!/usr/bin/env node
/* 🕸️ ตัวไล่ดู: **ตาข่ายที่ถูกซ่อนอยู่ใต้เงื่อนไขที่ความหมายไม่เกี่ยวกัน**
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ฝั่งจอเจอคลาสนี้ในจอ `return-orders`:
 *    ตัวเทียบคำค้น (ตาข่ายบอกว่าท่อใช้ `q` จริงไหม) ถูกเขียนซ้อนอยู่ใน
 *    `{d?.applied?.source === "mirror" && (...)}`
 *    ⇒ **รอบที่ท่อตอบจาก ZORT สด ตาข่ายไม่ทำงานเลย และไม่มีอะไรบอกว่ามันหายไป**
 *    ⇒ อ่านโค้ดผ่าน ๆ เห็นว่า "จอนี้เทียบแล้ว" ซึ่งจริง **ครึ่งเดียว**
 *    🔑 mirror-vs-live ไม่เกี่ยวเลยกับคำถาม "q ถูกใช้ไหม" — เงื่อนไขนอกจึงเป็นตัวปิดตาข่ายฟรี ๆ
 *
 * ⇒ ไฟล์นี้ถามคำถามเดียวกันกับ **ฝั่งท่อ**: ด่าน/ตาข่ายของเราตัวไหนนั่งอยู่ใต้สวิตช์
 *    (โหมด · แหล่งข้อมูล · ธง env · เปิด/ปิด) ที่ไม่เกี่ยวกับสิ่งที่ตาข่ายนั้นตรวจ
 *
 * 🚫 **นี่คือ "รายการที่ต้องเอาตาดู" ไม่ใช่ "รายการที่ต้องแก้"** — ตาข่ายบางตัว
 *    *ควร* อยู่ใต้เงื่อนไขนั้นจริง ๆ (เช่นด่านของโหมด live ที่ไม่มีความหมายในโหมดซ้อม)
 *    ⇒ จึงไม่ทำให้ build ตก · ความรุนแรงต้องเท่ากับรัศมีความเสียหาย
 * 🚫 และไม่ใช่ parser — นับปีกกาแบบหยาบ · ข้ามสตริง/regex ที่มีปีกกาไม่ได้
 *    ⇒ อ่านว่า **"เจอเท่านี้ในตะแกรงนี้" ไม่ใช่ "มีเท่านี้"**
 *
 * ใช้: node scripts/check-nested-nets.mjs [--all]
 *   (ไม่ใส่ธง = โชว์เฉพาะที่เข้าข่ายน่าสงสัย · `--all` = โชว์ตาข่ายทุกตัวที่อยู่ใต้ if)
 */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { เตือนถ้ามีไฟล์ซ้อนชั้น } from "./lib/ไฟล์ซ้อนชั้นที่ด่านมองไม่เห็น.mjs";

const โฟลเดอร์ = ["netlify/lib", "netlify/functions"];

/** ตาข่าย/ด่าน = บรรทัดที่ **ตัดสินว่าอย่าเชื่อข้อมูลรอบนี้** */
const ตาข่าย = [
  [/\bthrow new Error\(/, "โยน error"],
  [/\bskip:\s/, "คืน skip"],
  [/\binconclusive:\s*true/, "ประกาศว่าแปลผลไม่ได้"],
  [/\bwarn(ing)?:\s*(true|`|")/, "ติดธงเตือน"],
];

/** สวิตช์ = เงื่อนไขที่พูดถึง "โหมด/แหล่ง/ธง" ⇒ ไม่ใช่เรื่องความถูกต้องของข้อมูล
 *  ⚠️ รายการนี้เป็น **ตะแกรงคำ** — คำใหม่ที่ทีมเริ่มใช้จะหลุดจนกว่าจะมีคนเติม
 *     ⇒ ของที่ตะแกรงนี้ไม่เจอ ห้ามอ่านว่า "ไม่มี" */
/* 🔴 **20 ก.ย. 2569 — `\b` ไม่ทำงานกับอักษรไทย** (ตัวควบคุมที่เพิ่มวันนี้จับได้ทันทีที่รันครั้งแรก)
   เดิมเขียน `/\b(...|เปิด|ปิด|โหมด|แหล่ง)\b/i` ⇒ `\b` ต้องการขอบคำแบบ ASCII
   ⇒ ⇒ **คำไทยทั้งสี่คำไม่เคยถูกจับเลยตั้งแต่เขียนด่านนี้** (`"ถ้าโหมดเป็นซ้อม"` ⇒ ไม่ match)
   ⇒ ตะแกรงจึงเห็นแต่โค้ดภาษาอังกฤษ ⇒ **บรรทัดที่อธิบายสวิตช์เป็นภาษาไทยหลุดทั้งหมด**
   🔑 คลาส: **ตัวกวาดที่ผสมคำสองภาษาในรูปเดียว กติกาขอบคำจะใช้ได้กับภาษาเดียว**
   ✅ แยกสองรูป: อังกฤษใช้ `\b` · ไทยไม่ใช้ (ไทยไม่มีขอบคำแบบนั้น) */
const คำสวิตช์อังกฤษ = /\b(mode|source|mirror|live|dry|cache|cached|stale|enabled?|disabled?|flag|switch|process\.env)\b/i;
const คำสวิตช์ไทย = /(เปิด|ปิด|โหมด|แหล่ง)/;
const คำสวิตช์ = { test: (s) => คำสวิตช์อังกฤษ.test(s) || คำสวิตช์ไทย.test(s) };

/* 🧪 **ตัวควบคุมฝังใน — รันทุกรอบก่อนตัดสิน** (ท่าของฝั่งจอ · 20 ก.ย. 2569 เย็น)
   ตัวตัดสินของด่านนี้คือ `คำสวิตช์` ⇒ ทดสอบมันตรง ๆ ด้วยบรรทัดจำลอง
   ⚠️ ตะแกรงคำแบบนี้ **กว้างเกินได้ง่ายที่สุด** (เราสองคนโดนคนละสองรอบวันนี้)
      ⇒ เคส **ต้องไม่จับ** จึงสำคัญกว่าเคสต้องจับในด่านนี้ */
{
  const ต้องจับ = [
    "if (mode === 'dry') return;",
    "const v = process.env.STOCK_PUSH_AUTO;",
    "ถ้าโหมดเป็นซ้อม ให้ข้าม",
  ];
  const ต้องไม่จับ = [
    "const n = rows.length;",
    "await coreQuery(sql, แถว);",
    "/* นับจำนวนบรรทัด */",
  ];
  const พลาด = [
    ...ต้องจับ.filter((x) => !คำสวิตช์.test(x)).map((x) => `ต้องจับแต่ไม่จับ: ${x}`),
    ...ต้องไม่จับ.filter((x) => คำสวิตช์.test(x)).map((x) => `ต้องไม่จับแต่จับ: ${x}`),
  ];
  if (พลาด.length) {
    console.error(
      "🔴 **ตัวควบคุมของด่านนี้ไม่ผ่าน ⇒ ผลของด่านนี้อ่านไม่ได้** (ไม่ใช่ 'ไม่มีตาข่ายซ้อน')\n" +
      พลาด.map((x) => `   · ${x}`).join("\n")
    );
    process.exit(1);
  }
}

/* 🔑 กวาด netlify/lib · netlify/functions ชั้นเดียว ⇒ ไฟล์ในโฟลเดอร์ย่อยจะหลุดเงียบ ๆ
   (วัดแล้ว 20 ก.ย. 2569: ทั้งสองรากแบนจริง 0 ไฟล์) */
if (เตือนถ้ามีไฟล์ซ้อนชั้น(โฟลเดอร์, (n) => n.endsWith(".mjs"), "check-nested-nets")) {
  process.exit(1);
}
const ผล = [];
let ไฟล์ที่สแกน = 0;
let ตาข่ายที่เจอ = 0;

for (const d of โฟลเดอร์) {
  for (const ชื่อ of readdirSync(d)) {
    if (!ชื่อ.endsWith(".mjs")) continue;
    const path = join(d, ชื่อ);
    const บรรทัด = readFileSync(path, "utf8").split("\n");
    ไฟล์ที่สแกน += 1;

    /* กองเงื่อนไขที่ครอบอยู่ — เก็บ (ข้อความเงื่อนไข, ความลึกตอนเปิด) */
    const กอง = [];
    let ลึก = 0;
    let ในคอมเมนต์ = false;

    for (let i = 0; i < บรรทัด.length; i += 1) {
      let ln = บรรทัด[i];
      // ตัดคอมเมนต์หยาบ ๆ ก่อน — ไม่งั้นคำในคอมเมนต์ทำให้เข้าข่ายเอง (ชั้นหลอกที่ถูกที่สุด)
      if (ในคอมเมนต์) {
        const จบ = ln.indexOf("*" + "/");
        if (จบ < 0) continue;
        ln = ln.slice(จบ + 2);
        ในคอมเมนต์ = false;
      }
      ln = ln.replace(/\/\/.*$/, "");
      const เปิด = ln.indexOf("/" + "*");
      if (เปิด >= 0) {
        const จบ = ln.indexOf("*" + "/", เปิด);
        if (จบ < 0) { ln = ln.slice(0, เปิด); ในคอมเมนต์ = true; } else ln = ln.slice(0, เปิด) + ln.slice(จบ + 2);
      }
      if (!ln.trim()) continue;

      const เงื่อนไข = /^\s*\}?\s*(?:else\s+)?if\s*\((.+)\)\s*\{\s*$/.exec(ln);
      const ชนิด = ตาข่าย.find(([re]) => re.test(ln));
      if (ชนิด) {
        ตาข่ายที่เจอ += 1;
        const ครอบ = กอง.map((g) => g.cond);
        const สวิตช์ที่ครอบ = ครอบ.filter((c) => คำสวิตช์.test(c));
        // 🔑 เข้าข่ายเมื่อ **เงื่อนไขนอกเป็นสวิตช์ แต่ตัวตาข่ายเองไม่ได้พูดถึงสวิตช์นั้น**
        const น่าสงสัย = สวิตช์ที่ครอบ.length > 0 && !คำสวิตช์.test(ln);
        ผล.push({ path, บรรทัด: i + 1, โค้ด: ln.trim().slice(0, 110), ชนิด: ชนิด[1], ครอบ, น่าสงสัย });
      }

      if (เงื่อนไข) {
        ลึก += 1;
        กอง.push({ cond: เงื่อนไข[1].trim().slice(0, 100), ลึก });
        continue;
      }
      // นับปีกกาแบบหยาบ (ยอมรับความคลาดเคลื่อน — ดูหัวไฟล์)
      for (const ch of ln) {
        if (ch === "{") ลึก += 1;
        else if (ch === "}") {
          ลึก -= 1;
          while (กอง.length && กอง[กอง.length - 1].ลึก > ลึก) กอง.pop();
        }
      }
    }
  }
}

const โชว์ทั้งหมด = process.argv.includes("--all");
const ที่จะโชว์ = ผล.filter((r) => โชว์ทั้งหมด || r.น่าสงสัย);

console.log("🕸️  ตาข่ายที่นั่งอยู่ใต้สวิตช์ที่ความหมายไม่เกี่ยวกัน — **รายการที่ต้องเอาตาดู ไม่ใช่รายการที่ต้องแก้**\n");
for (const r of ที่จะโชว์) {
  console.log(`${r.น่าสงสัย ? "👁" : "·"} ${r.path}:${r.บรรทัด} — ${r.ชนิด}`);
  console.log(`   ${r.โค้ด}`);
  for (const c of r.ครอบ) console.log(`   ↳ อยู่ใต้: if (${c})${คำสวิตช์.test(c) ? "   ⬅️ สวิตช์" : ""}`);
}

console.log(
  `\n📏 ตะแกรง: สแกน ${ไฟล์ที่สแกน} ไฟล์ใน ${โฟลเดอร์.join(" · ")}` +
  `\n   ตาข่ายที่นับได้ทั้งหมด ${ตาข่ายที่เจอ} จุด · อยู่ใต้ if ${ผล.filter((r) => r.ครอบ.length).length} จุด · **เข้าข่ายน่าสงสัย ${ผล.filter((r) => r.น่าสงสัย).length} จุด**` +
  "\n   ⚠️ ตะแกรงเป็นคำ + นับปีกกาหยาบ ⇒ อ่านว่า \"เจอเท่านี้ในตะแกรงนี้\" **ไม่ใช่ \"มีเท่านี้\"**" +
  "\n   ⚠️ ของที่ *ควร* อยู่ใต้สวิตช์นั้นจริงก็จะโผล่ที่นี่ — ต้องอ่านทีละจุด ห้ามเหมาแก้"
);
