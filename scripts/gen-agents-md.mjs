import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));

const products = read("src/data/products.json");
const collections = read("src/data/collections.json");

// ---------------------------------------------------------------------------
// อ่านชื่อร้าน/คำโปรยจาก src/lib/shop.ts ที่เดียว — ห้ามพิมพ์ชื่อร้านลงไฟล์นี้
// (กติกาของ "ร้านต้นแบบ" — clone ไปเปิดร้านใหม่ต้องแก้ที่ BRAND ที่เดียวจบ)
// อ่านด้วยการจับข้อความเอาเพราะไฟล์นั้นเป็น TypeScript สคริปต์ .mjs import ตรง ๆ ไม่ได้
// ---------------------------------------------------------------------------
const shopSrc = fs.readFileSync(path.join(root, "src/lib/shop.ts"), "utf8");
const pick = (key, fallback) =>
  shopSrc.match(new RegExp(`${key}:\\s*"([^"]+)"`))?.[1] ?? fallback;

const BRAND_NAME = pick("name", "");
const TAGLINE = pick("tagline", "");
const SITE = (process.env.NEXT_PUBLIC_SITE_URL || "https://gucut.com").replace(/\/$/, "");
if (!BRAND_NAME) throw new Error("gen-agents-md: อ่านชื่อร้านจาก src/lib/shop.ts ไม่ได้");

const sellable = products.filter((p) => p.img && p.st > 0);
const prices = sellable.map((p) => p.p).filter((n) => n > 0).sort((a, b) => a - b);
const low = prices[0] ?? 0;
const high = prices[prices.length - 1] ?? 0;

// หมวดที่มีของจริงพอสมควร เรียงตามจำนวนสินค้า
const tops = collections
  .filter((c) => c.n >= 3)
  .sort((a, b) => b.n - a.n)
  .slice(0, 24);

const baht = (n) => `฿${n.toLocaleString("en-US")}`;

