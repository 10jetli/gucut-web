# 🔴 ที่มา 19 ก.ย. 2569 (ฝั่งจอถามผมว่า "ชุดทดสอบครอบสคริปต์ตอน build ไหม") ⇒ **ไม่ครอบ**
#    ฮุกเดิมรันแค่ `scripts/tests/*.test.mjs` + check-floating
#    ⇒ ของจริงที่เกิดวันเดียวกัน: `gen-audit-json.mjs` โยน ReferenceError **ค้าง 3 commit**
#      เพราะเทสไม่เคยเรียกสคริปต์ตอน build ⇒ ถ้า push ไป Netlify ตกทั้งรอบ **เสียเครดิตฟรี**
#    ⇒ ที่รอดมาทั้งวันเพราะผมรัน `npm run build` เองก่อน commit = **ความตั้งใจ ไม่ใช่กลไก**
# ⚠️ แลกด้วยเวลา ~2-4 นาทีต่อการ push — ยอมรับได้เพราะด่านความถี่จำกัด push อยู่แล้ว
