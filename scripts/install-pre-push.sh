# 🔴 ที่มา 19 ก.ย. 2569 (ฝั่งจอจับได้): ด่านนี้พิมพ์ว่า "ทุกครั้งที่ push = สร้างเว็บใหม่ทั้งก้อน"
#    ซึ่ง **ไม่จริงระหว่าง build ถูกปิดที่ Netlify** ⇒ ด่านที่พูดสิ่งที่ไม่จริง สอนให้คนเลิกอ่านมัน
# 🔑 hook ไม่มี token ⇒ ถาม Netlify เองไม่ได้ ⇒ คนที่ไปกดปุ่มต้องเขียนไฟล์กลางไว้
#    (~/claude-shared/สถานะbuild-netlify.md — ที่เดียว ทุกบัญชีอ่านตัวเดียวกัน)
# 🚫 ไม่มีไฟล์ / เก่าเกิน 24 ชม. ⇒ บอกว่า **"ไม่รู้สถานะ"** ห้ามเดาไปทางใดทางหนึ่ง
#    (เดาว่า "ปิดอยู่" = ปล่อย push รัวเพราะคิดว่าฟรี · เดาว่า "เปิด" = คำเตือนกลับไปโกหกเหมือนเดิม)
ข้อความราคาของpush() {
  BS="$HOME/claude-shared/สถานะbuild-netlify.md"
  if [ ! -f "$BS" ]; then
    echo "⚠️ ไม่รู้สถานะ build ที่ Netlify (ไม่มี $BS) — ถือว่า push แล้วอาจเสียค่า build"
    return
  fi
  ST=$(grep -m1 "^สถานะ:" "$BS" | awk '{print $2}')
  WHEN=$(grep -m1 "^เมื่อ:" "$BS" | cut -d" " -f2-)
  # 🔴 **ความสดต้องอ่านจาก `เมื่อ:` ในไฟล์ ไม่ใช่ mtime** (แก้ 21 ก.ย. 2569)
  #    ของเดิมใช้ `date -r "$BS"` ⇒ **ใครแก้คอมเมนต์/เติมหมายเหตุ ก็ทำให้ของเก่าดูสดทันที**
  #    ⇒ ⇒ ด่านจะพูดว่า "build ปิดอยู่ push ฟรี" ด้วยข้อมูลอายุ 2 วัน เพราะมีคนเพิ่งแก้ไฟล์ด้วยเรื่องอื่น
  #    🔑 คลาส: **ใช้เมตาดาต้าของไฟล์แทนเนื้อหา ⇒ การแก้ที่ไม่เกี่ยวกันรีเซ็ตความสดให้ฟรี**
  #    (เจอ 21 ก.ย. ตอนจะเติมหมายเหตุลงไฟล์นี้เอง แล้วรู้ว่าทำแล้วจะทำให้ตัวเลขโกหก)
  #    ⚠️ อ่าน `เมื่อ:` ไม่ได้ ⇒ **บอกว่าไม่รู้** ห้ามถอยไปใช้ mtime เงียบ ๆ
  WHEN_TS=$(date -d "$WHEN" +%s 2>/dev/null || echo "")
  if [ -z "$WHEN_TS" ]; then
    echo "⚠️ อ่านบรรทัด 'เมื่อ:' ในไฟล์สถานะไม่ได้ (ได้ '$WHEN') ⇒ **ถือว่าไม่รู้สถานะ build**"
    return
  fi
  AGE_H=$(( ( $(date +%s) - WHEN_TS ) / 3600 ))
  if [ "$AGE_H" -gt 24 ]; then
    echo "⚠️ สถานะ build ในไฟล์กลางเก่า $AGE_H ชม. (ล่าสุดว่า '$ST' เมื่อ $WHEN) ⇒ **ถือว่าไม่รู้**"
  elif [ "$ST" = "stopped" ]; then
    echo "🧊 Netlify **ปิด build อยู่** (ตั้งแต่ $WHEN) ⇒ push นี้ไม่สร้างเว็บใหม่และไม่เสียค่า build"
    echo "      แต่ของที่วิ่งให้คนใช้ยังเป็นรุ่นเก่า ⇒ push ไปก็ยังไม่ถึงมือใคร"
  else
    echo "ทุกครั้งที่ push = สร้างเว็บใหม่ทั้งก้อน · deploy กินเครดิตเกือบทั้งหมด (สถานะ '$ST' เมื่อ $WHEN)"
  fi
}

# 🔴 **ด่านความถี่ต้องอ่าน "push ที่ถึง remote จริง" ไม่ใช่แสตมป์ในเครื่อง** (แก้ 21 ก.ย. 2569)
#    ของจริงฝั่งจอ: ด่านบอกว่า "push ครั้งก่อนเพิ่งผ่านไป 4 นาที" ทั้งที่ **ไม่มี push ไหนสำเร็จเลยใน 3 ชม.**
#    ต้นตอ: แสตมป์ถูกเขียน **ตอนด่านผ่าน** ซึ่งเกิด *ก่อน* git เริ่มส่งจริง
#    ⇒ push ที่ถูกฆ่า/ล้มกลางทาง **จุดนาฬิกา 45 นาที ทั้งที่ไม่มีอะไรถึง remote**
#    ⇒ ⇒ และฝั่งเราแพงเป็นพิเศษ: ลองใหม่แต่ละครั้งต้องรันเทสทั้งชุดซ้ำ
# 🔑 กติกา: **ตัวนับที่ต้องตอบว่า "เกิดขึ้นจริงไหม" ห้ามเขียนก่อนเหตุการณ์**
#    ⇒ reflog ของ refs/remotes/origin/<branch> รายการ `update by push` = ของที่ถึง remote จริงเท่านั้น
#       (`fetch` ไม่นับ · ไม่มีธงในเครื่องให้เพี้ยน) — ท่านี้ฝั่งจอคิดก่อน ผมเอามาใช้
BR=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo main)
NOW=$(date +%s)
MINGAP="${PUSH_MIN_GAP_MIN:-45}"
LAST=$(git reflog show --date=unix "refs/remotes/origin/$BR" 2>/dev/null \
        | grep -m1 'update by push' | sed -n 's/.*@{\([0-9][0-9]*\)}.*/\1/p')
if [ -n "$LAST" ]; then
  DIFF=$(( (NOW - LAST) / 60 ))
  if [ "$DIFF" -lt "$MINGAP" ]; then
    if [ "${ALLOW_FAST_PUSH:-}" = "1" ]; then
      echo "⏩ push ถี่ (ห่างจากครั้งก่อน $DIFF นาที) — ผ่านเพราะสั่ง ALLOW_FAST_PUSH=1"
    else
      AHEAD=$(git rev-list --count @{u}..HEAD 2>/dev/null || echo "?")
      echo "🛑 ไม่ push — ห่างจากครั้งก่อนเพียง $DIFF นาที (เกณฑ์ $MINGAP นาที)"
      echo "   $(ข้อความราคาของpush)"
      echo "   ตอนนี้ค้างอยู่ $AHEAD commit — รวบไปรอบเดียวจ่ายครั้งเดียว"
      echo ""
      echo "   ของพังจริง/ของด่วน:  ALLOW_FAST_PUSH=1 git push"
      echo "   (เจตนาของด่านนี้คือให้ 'ถี่' เป็นการตัดสินใจ ไม่ใช่ค่าเริ่มต้น)"
      exit 1
    fi
  fi
else
  # 🚫 ไม่เจอ push ที่ถึง remote ⇒ **"ยังไม่รู้" ไม่ใช่ "ห่างพอแล้ว"** ⇒ ปล่อยผ่านพร้อมบอกเหตุ
  echo "ℹ️ ไม่พบรายการ 'update by push' ใน reflog ของ origin/$BR ⇒ ด่านความถี่ไม่มีข้อมูลให้เทียบ (ข้ามรอบนี้)"
fi
