#!/usr/bin/env node
/* สร้าง `netlify/lib/list-filters.json` — **ตัวกรองที่แต่ละเส้น `list=` อ่านจริงจากคำขอ**
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · ฝั่งจอเสนอ และเหตุผลของเขาหนักกว่าที่ผมคิด:
 *    เขามีคำกล่าวอ้างเรื่องท่อบนจอ **186 จุด** แต่ตะแกรงของเขาตัดสินได้แค่ **4 จุด (2%)**
 *    เพราะคำพวกนั้นเขียนเป็นภาษาคน ("ท่อไม่รับตัวกรองสถานะ") **ไม่ได้อ้างคีย์ที่เครื่องเทียบได้**
 *    ⇒ คำของเขา: *"คำกล่าวอ้างเรื่องท่อ ควรอ้างคีย์ในสัญญาที่ท่อประกาศ ไม่ใช่เล่าเป็นประโยค"*
 *    ⇒ วันที่ท่อประกาศ `ตัวกรองที่รับ` ครบทุกเส้น ด่านฝั่งเขาจะเทียบได้เองทั้ง 186 จุด
 *      **โดยไม่ต้องยิงเลยสักครั้ง** (ประหยัดทั้งเครดิตและเวลา)
 *    ⚠️ และเขาจะ **ไม่ทำด่านนั้นจนกว่าจะครบ** เพราะทำตอนนี้จะฟ้อง 20 เส้นที่ถูกอยู่แล้ว
 *      = เสียงรบกวนที่ฆ่าตาข่าย ⇒ ของชิ้นนี้คือการปลดล็อกงานของเขา
 *
 * 🔑 **สกัดจากซอร์ส ไม่ใช่เขียนมือ** — ถ้าเขียนมือ วันหนึ่งโค้ดเปลี่ยนแล้วรายการค้าง
 *    แล้วด่านของฝั่งจอจะเทียบกับความจริงเก่า ⇒ ฟ้องผิดตัว หรือปล่อยผ่านของที่เปลี่ยนไปแล้ว
 *    ⇒ รันใน prebuild ทุกครั้ง ⇒ ค้างไม่ได้โดยโครงสร้าง
 *
 * ⚠️ **ขอบเขตของการสกัดนี้ — ต้องติดไปกับข้อมูลเสมอ**
 *    จับได้เฉพาะ `searchParams.get("x")` / `.has("x")` ที่เขียนอยู่ **ในบล็อกของเส้นนั้น**
 *    ตัวกรองที่ถูกอ่านลึกลงไปในไลบรารี (ส่งผ่าน options) **จับไม่ได้**
 *    ⇒ ไฟล์ผลลัพธ์จึงมี `การสกัด` กำกับทุกแถว · ปลายทางต้องอ่านว่า
 *      "อย่างน้อยเท่านี้" ไม่ใช่ "เท่านี้เท่านั้น" 🚫 **ห้ามใช้ตัดสินว่าเส้นไม่รับตัวกรองตัวหนึ่ง**
 */
import { readFileSync, writeFileSync } from "node:fs";
import { lists } from "../netlify/lib/endpoints.mjs";

const SRC = readFileSync("netlify/functions/core.mjs", "utf8");
const ออก = {};
const ไม่เจอบล็อก = [];

/* หาบล็อกของเส้น: `get("list") === "<ชื่อ>"` หรืออยู่ในรายการรวม (STORE_LISTS ฯลฯ) */
for (const ชื่อ of lists) {
  const รูป = [
    `get("list") === "${ชื่อ}"`,
    `"list") === "${ชื่อ}"`,
  ];
  let i = -1;
  for (const r of รูป) { i = SRC.indexOf(r); if (i > 0) break; }
  if (i < 0) { ไม่เจอบล็อก.push(ชื่อ); continue; }

  /* 🔴 **ขอบเขตบล็อกต้องนับวงเล็บปีกกา ไม่ใช่ "จนถึง dispatch ตัวถัดไป"**
     รอบแรกผมใช้ "จนถึง dispatch ตัวถัดไป" ⇒ กินเส้นอื่นที่อยู่ระหว่างกลางเข้ามา
     (`bundleitems` ได้ `syncbundles`/`zortmissing` ติดมา · `deadstock` ได้ `synctransfers`)
     ⇒ รายการ **กว้างเกินจริง** ⇒ ด่านฝั่งจอจะยืนยันคำกล่าวอ้างว่า "เส้นนี้รับตัวกรองนี้"
       ทั้งที่ไม่รับ ⇒ **เขียวลวง ซึ่งเป็นทิศที่อันตรายกว่าครอบไม่ครบ**
     🔑 กว้างเกิน ≠ ปลอดภัยกว่าแคบเกิน — ขึ้นกับว่าปลายทางเอาไปทำอะไร
        ที่นี่ปลายทางใช้ "ยืนยันว่ารับจริง" ⇒ **ของเกินคือคำยืนยันเท็จ** */
  const เปิด = SRC.indexOf("{", i);
  let ลึก = 0, จบ = -1;
  for (let k = เปิด; k < SRC.length && k < เปิด + 20000; k++) {
    const ch = SRC[k];
    if (ch === "{") ลึก++;
    else if (ch === "}") { ลึก--; if (ลึก === 0) { จบ = k; break; } }
  }
  const จบตามเพดาน = จบ < 0;
  const ก้อน = SRC.slice(i, จบตามเพดาน ? i + 20000 : จบ);

  const เจอ = new Set();
  for (const m of ก้อน.matchAll(/searchParams\.(?:get|has)\(\s*"([^"]+)"\s*\)/g)) {
    if (m[1] !== "list") เจอ.add(m[1]);
  }
  /* 🔴 **ว่างเปล่า ≠ "ไม่รับตัวกรองอะไรเลย"** — หลายเส้นถูกจัดการในบล็อกรวม (`STORE_LISTS`)
     แล้วตัวกรองถูกอ่านที่อื่น ⇒ การสกัดมองไม่เห็น ⇒ ถ้าเขียน `[]` ปลายทางจะอ่านว่า
     "ท่อยืนยันว่าไม่รับอะไรเลย" ซึ่งเป็น **คำยืนยันเท็จที่หน้าตาเหมือนข้อมูล**
     ⇒ ว่าง ⇒ ส่ง `null` พร้อมเหตุผล (สามสถานะ ห้ามยุบเป็นสอง)
     ของจริงที่เจอ: `orders` สกัดได้ 0 ตัว ทั้งที่สัญญาบอกว่ากรองด้วย `q` จริง */
  ออก[ชื่อ] = {
    ตัวกรองที่รับ: เจอ.size ? [...เจอ].sort() : null,
    การสกัด: จบตามเพดาน
      ? "หาวงเล็บปิดบล็อกไม่เจอใน 20,000 ตัวอักษร ⇒ **ผลอาจเพี้ยน อย่าเชื่อแถวนี้**"
      : เจอ.size
        ? "สกัดจากภายในบล็อกของเส้นนี้ (นับวงเล็บปีกกาปิด)"
        : "สกัดจากบล็อกแล้ว **ไม่เจอการอ่านพารามิเตอร์เลย** ⇒ น่าจะถูกจัดการในบล็อกรวม " +
          "หรืออ่านตัวกรองในไลบรารี ⇒ **null = ยังไม่รู้ ไม่ใช่ไม่รับ**",
  };
}

const ผล = {
  "🔑 อ่านไฟล์นี้ยังไง":
    "`ตัวกรองที่รับ` = ชื่อพารามิเตอร์ที่เส้นนั้น **อ่านจริงจากคำขอ** สกัดจากซอร์ส ณ เวลา build · " +
    "🚫 **อ่านว่า \"อย่างน้อยเท่านี้\" ไม่ใช่ \"เท่านี้เท่านั้น\"** — ตัวกรองที่ถูกอ่านลึกในไลบรารี " +
    "(ส่งผ่าน options) สกัดไม่ได้ ⇒ **ห้ามใช้ตัดสินว่าเส้นไม่รับตัวกรองตัวหนึ่ง** " +
    "ใช้ได้ทางเดียว: ยืนยันว่า \"เส้นนี้รับตัวนี้จริง\"",
  สร้างเมื่อ: new Date().toISOString(),
  จำนวนเส้น: Object.keys(ออก).length,
  สกัดได้จริง: Object.values(ออก).filter((x) => Array.isArray(x.ตัวกรองที่รับ)).length,
  ยังไม่รู้: Object.values(ออก).filter((x) => x.ตัวกรองที่รับ === null).length,
  เส้นที่หาบล็อกไม่เจอ: ไม่เจอบล็อก,
  เส้น: ออก,
};
writeFileSync("netlify/lib/list-filters.json", JSON.stringify(ผล, null, 2) + "\n");
console.log(
  `gen-list-filters: ${ผล.จำนวนเส้น} เส้นจาก ${lists.length} · สกัดได้จริง ${ผล.สกัดได้จริง} · ` +
  `ยังไม่รู้ (null) ${ผล.ยังไม่รู้} · หาบล็อกไม่เจอ ${ไม่เจอบล็อก.length}` +
  (ไม่เจอบล็อก.length ? ` (${ไม่เจอบล็อก.join(", ")})` : "") + " ✓\n" +
  "   🚫 อ่านผลว่า \"อย่างน้อยเท่านี้\" — ตัวกรองที่อ่านลึกในไลบรารีสกัดไม่ได้"
);
