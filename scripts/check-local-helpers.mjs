/* 🔴 **ลำดับการถอดสำคัญมาก — รุ่นแรกของด่านนี้กินโค้ดไป 79%**
   📏 วัดจริง: core-products.mjs 104,305 → 21,659 ตัวอักษร ⇒ `function headers()` หายไปด้วย
      ⇒ ด่านฟ้องสองไฟล์ที่ไม่ได้ผิดอะไรเลย = **แดงลวง ซึ่งแพงกว่าเขียวลวง**
        เพราะคนจะไปแก้ของที่ยังดี (เกือบทำแล้วคืนนี้)
   เหตุ: ถอดคอมเมนต์ **ก่อน** ถอดสตริง ⇒ `/*` ที่อยู่ **ข้างในสตริง SQL template**
      จับคู่กับลำดับปิดคอมเมนต์ของอีกสตริงที่ห่างไปไกล แล้วกลืนทุกอย่างระหว่างนั้น
   🔴 **และคอมเมนต์ก้อนนี้เองก็เคยฆ่าตัวเอง**: รุ่นแรกผมยกตัวอย่างลำดับปิดคอมเมนต์ไว้ข้างในนี้
      ⇒ มันปิดคอมเมนต์บล็อกตรงนั้นจริง ⇒ เนื้อที่เหลือกลายเป็นโค้ด ⇒ SyntaxError
      ⇒ ซึ่งคือข้อที่คอมเมนต์นี้อธิบายอยู่พอดี: **เขียนลำดับปิดคอมเมนต์ไว้ในคอมเมนต์ไม่ได้
        แม้จะใส่เครื่องหมายคำพูด** (เครื่องหมายคำพูดไม่มีความหมายกับตัวแยกคอมเมนต์)
   🔑 กับดักนี้โปรเจกต์มีบทเรียนอยู่แล้ว: **คอมเมนต์ที่อยู่ข้างในสตริง template ไม่ใช่คอมเมนต์**
   ⇒ ลำดับที่ถูก: **สตริงก่อน → คอมเมนต์บล็อก → คอมเมนต์บรรทัด** */
function เอาแต่โค้ด(เต็ม, f) {
  const โค้ด = เต็ม
    .replace(/`(?:[^`\\]|\\[\s\S])*`/g, "``")
    .replace(/"(?:[^"\\\n]|\\[\s\S])*"/g, '""')
    .replace(/'(?:[^'\\\n]|\\[\s\S])*'/g, "''")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/[^\n]*/g, "");
  /* 🛡️ ตาข่ายกันด่านกินโค้ดเอง — เหลือน้อยกว่า 15% = ตัวถอดพัง ไม่ใช่ไฟล์ผิด
     ⇒ **ด่านที่พังต้องประกาศตัว ไม่ใช่กล่าวหาคนอื่น** */
  if (โค้ด.length < เต็ม.length * 0.15) return null;   // แยกไม่ได้ ⇒ **ข้าม ไม่ตัดสิน**
  return โค้ด;
}

const ไฟล์ = [];
for (const ที่ of ["netlify/lib", "netlify/functions"]) {
  for (const f of readdirSync(ที่)) if (f.endsWith(".mjs")) ไฟล์.push(path.join(ที่, f));
}

const ปัญหา = [];
const ข้าม = [];
for (const f of ไฟล์) {
  const เต็ม = readFileSync(f, "utf8");
  const โค้ด = เอาแต่โค้ด(เต็ม, f);
  /* 🔴 **แยกโค้ดจากคอมเมนต์ด้วย regex ไม่ได้เสมอ และนี่คือปัญหาไก่กับไข่**
     คอมเมนต์ในรีโปนี้ใช้ backtick ครอบชื่อโค้ดเยอะมาก ⇒ backtick เดี่ยวในคอมเมนต์
     จับคู่กับ backtick ของสตริง template จริง แล้วกลืนโค้ดไป
     ⇒ ถอดสตริงก่อนก็พลาด (คอมเมนต์มี backtick) · ถอดคอมเมนต์ก่อนก็พลาด (สตริงมีเครื่องหมายคอมเมนต์)
     ⇒ ทางที่ซื่อสัตย์คือ **ข้ามไฟล์ที่แยกไม่ได้ แล้วประกาศว่าครอบไม่ครบ**
     🔑 กติกาเดิมของโปรเจกต์: **ครอบไม่ครบ แล้วรายงานเหมือนครอบครบ** คือกับดักที่เจอซ้ำที่สุด
        ⇒ ด่านนี้จึงพิมพ์จำนวนไฟล์ที่ข้ามทุกครั้ง ห้ามเงียบ */
  if (โค้ด === null) { ข้าม.push(f); continue; }
  for (const ชื่อ of ตัวช่วยท้องถิ่น) {
    if (!new RegExp(`\\b${ชื่อ}\\s*\\(`).test(โค้ด)) continue;
    /* 🔑 ตรวจ "ประกาศ" จาก **ข้อความเต็ม** ไม่ใช่ข้อความที่ถอดแล้ว
       ⇒ ทิศความผิดของด่านนี้จะเอนไป **ไม่กล่าวหา** (พลาดบั๊กได้ แต่ไม่ฟ้องคนที่ไม่ผิด)
       ⇒ แดงลวงแพงกว่าเขียวลวง เพราะคนจะไปแก้ของที่ยังดี */
    const ประกาศ = new RegExp(`(function\\s+${ชื่อ}\\b|(?:const|let|var)\\s+${ชื่อ}\\s*=)`).test(เต็ม);
    const นำเข้า = new RegExp(`import[^;]*\\b${ชื่อ}\\b[^;]*from`).test(เต็ม);
    if (!ประกาศ && !นำเข้า) ปัญหา.push({ f, ชื่อ });
  }
}

if (ปัญหา.length) {
  console.error("🔴 เรียกตัวช่วยที่ไฟล์นี้ **ไม่ได้ประกาศและไม่ได้นำเข้า** ⇒ ReferenceError ตอนเดินเส้น");
  for (const { f, ชื่อ } of ปัญหา) console.error(`   · ${f} — เรียก ${ชื่อ}() แต่ไม่มีในไฟล์`);
  console.error("   ⇒ ใช้ชื่อที่ไฟล์นั้นมีอยู่ หรือ import เข้ามาให้ชัด");
  process.exit(1);
}
console.log(`✅ ตัวช่วยท้องถิ่น: ตรวจ ${ไฟล์.length - ข้าม.length}/${ไฟล์.length} ไฟล์ × ${ตัวช่วยท้องถิ่น.length} ชื่อ — ไม่มีการเรียกข้ามไฟล์`);
if (ข้าม.length) console.log(`   ⚠️ **ข้าม ${ข้าม.length} ไฟล์ที่แยกโค้ดจากคอมเมนต์ไม่ได้** ⇒ ด่านนี้ครอบไม่ครบ: ${ข้าม.map((x) => x.split("/").pop()).join(" · ")}`);
