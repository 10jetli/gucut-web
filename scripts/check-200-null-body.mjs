#!/usr/bin/env node
/* หา "HTTP 200 แต่ body อ่านไม่ได้ แล้วถูกแทนด้วยกล่องว่าง" — คลาสของใบ B14
 *
 * 🔴 ที่มา 3 ต.ค. 2569: `facebookInsights` และ `googleInsights` ตรวจแค่ `!r.ok`
 *    ⇒ body เป็น null ผ่านด่านไป ⇒ `body?.data || []` ⇒ **rows ว่าง**
 *    ⇒ หน้า /admin/ads/ อ่านว่า "ไม่มีแคมเปญ · ใช้เงิน ฿0" ⇒ ROAS เป็นอนันต์
 *
 * 🔑 **ตัวนี้รายงาน ไม่ตีกลับ build** — รูปแบบนี้มีในรีโป 68 จุด และส่วนใหญ่ปลอดภัย
 *    (บางจุด null ถูกจัดการถูกแล้ว · บางจุดใช้กับเส้นที่ไม่ได้เอาเลขไปโชว์)
 *    ด่านที่แดงใส่ของปกติจะถูกปิดภายในวันเดียว ⇒ ตัวนี้จึงทำหน้าที่ **ชี้ให้ไปดู**
 *    ⚠️ เลขที่ออกมาคือ "ที่ต้องดู" ไม่ใช่ "ที่ต้องแก้" (กฎ same-shape-other-direction)
 *
 * เกณฑ์ที่นับว่าน่าสงสัย — ต้องครบทั้งสามข้อในหน้าต่าง 25 บรรทัดหลัง `json().catch`
 *   ① ถอยเป็น null/undefined เมื่ออ่าน JSON ไม่ได้
 *   ② มีด่านที่ดูแค่สถานะ HTTP (`!r.ok` / `res.ok` / `.status`)
 *   ③ แล้วเอา body ไปใช้แบบ `|| []` · `?? []` · `|| {}` · `?? {}` (กล่องว่างแทนความไม่รู้)
 * ⇒ ครบสามข้อ = ความไม่รู้ถูกแปลงเป็น "ว่าง" โดยไม่มีใครฟ้อง
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const ราก = ["netlify"];
const ไฟล์ = [];
const เดิน = (d) => {
  for (const ชื่อ of readdirSync(d)) {
    if (ชื่อ === "node_modules" || ชื่อ.startsWith(".")) continue;
    const p = join(d, ชื่อ);
    if (statSync(p).isDirectory()) เดิน(p);
    else if (p.endsWith(".mjs")) ไฟล์.push(p);
  }
};
ราก.forEach(เดิน);

const ถอยเป็นว่าง = /\|\|\s*\[\]|\?\?\s*\[\]|\|\|\s*\{\}|\?\?\s*\{\}/;
const ด่านสถานะ = /!\s*\w+\.ok\b|\w+\.ok\s*\)|\.status\b/;
const จุดถอยเป็นnull = /\.json\(\)\s*\.catch\(\s*\(\)\s*=>\s*(null|undefined)\s*\)/;

/** เกณฑ์ตัดสินอยู่ที่เดียว — ใช้ทั้งกับฟิกซ์เจอร์ของตัวควบคุม และกับไฟล์จริง
 *  🔑 ถ้าเขียนเกณฑ์ไว้สองที่ ตัวควบคุมจะทดสอบ "สำเนาของเกณฑ์" ไม่ใช่เกณฑ์ที่ใช้งาน */
const เข้าเกณฑ์ทั้งสามข้อ = (หน้าต่าง) =>
  จุดถอยเป็นnull.test(หน้าต่าง) && ด่านสถานะ.test(หน้าต่าง) && ถอยเป็นว่าง.test(หน้าต่าง);

/* ── 🧪 ตัวควบคุมฝังใน — **ต้องผ่านก่อนตัดสินไฟล์จริง** ──
   🔴 ที่มา 3 ต.ค. 2569: ด่านนี้ถูก `check-plant-formulas` ตีกลับตอน push
      ด้วยเหตุผลว่า "ยังไม่รู้ว่าร้องได้ไหม" ⇒ **เขียวของมันแปลว่า "ยังไม่เจอ" ไม่ใช่ "ไม่มี"**
   🔑 ตัวควบคุมนี้จึงป้อน **คู่ที่รู้คำตอบอยู่แล้ว** ให้ตัวจับคู่ตัวจริงตัดสินทุกครั้งที่รัน
      ① รูปอันตราย (ตรวจแค่สถานะ แล้วถอยเป็นกล่องว่าง) ⇒ **ต้องจับได้**
      ② รูปที่กันไว้ถูกแล้ว (เช็ค `data?.success` แล้วโยน) ⇒ **ต้องไม่จับ**
   ⚠️ ข้อ ② สำคัญกว่าข้อ ① — ด่านที่จับทุกอย่างคือด่านที่ถูกปิดภายในวันเดียว
   ⚠️ ใช้ชื่อ `ต้องจับ` / `ต้องไม่จับ` ตามสำนวนของรีโปนี้ (เส้นแบ่งถูกประกาศไว้ให้รู้ว่าอยู่ไหน)
      และ **ต้องเอาชุดไปใช้จริง** ไม่ใช่ประกาศทิ้งไว้ — ประกาศทิ้งไว้คือหนี้ที่ดูเหมือนปิดแล้ว */
const ต้องจับ = [
  // ① ตรวจแค่สถานะ แล้วถอยเป็นกล่องว่าง (รูปของใบ B14 ทั้งสองเจ้า)
  `const body = await r.json().catch(() => null);
   if (!r.ok) throw new Error("พัง");
   return body?.data || [];`,
  // ② รูปเดียวกันแต่ถอยเป็นออบเจกต์ว่าง
  `const j = await res.json().catch(() => null);
   if (!res.ok) return [];
   return j?.metrics ?? {};`,
];
const ต้องไม่จับ = [
  // ① กันไว้ถูกแล้ว — เช็คเนื้อคำตอบ ไม่ใช่แค่สถานะ แล้วโยน
  `const data = await res.json().catch(() => null);
   if (!res.ok || !data?.success) throw new Error("อ่านไม่ได้");
   return Array.isArray(data.result) ? data.result : [];`,
  // ② ถอยเป็นกล่องว่างแต่ไม่มีการถอยเป็น null ตั้งแต่ต้น ⇒ คนละเรื่อง
  `const body = await r.json();
   if (!r.ok) throw new Error("พัง");
   return body?.data || [];`,
];

const พลาดที่ต้องจับ = ต้องจับ.filter((x) => !เข้าเกณฑ์ทั้งสามข้อ(x));
const พลาดที่ต้องไม่จับ = ต้องไม่จับ.filter((x) => เข้าเกณฑ์ทั้งสามข้อ(x));
if (พลาดที่ต้องจับ.length || พลาดที่ต้องไม่จับ.length) {
  console.error("🔴 **ผลของด่านนี้อ่านไม่ได้** — ตัวควบคุมฝังในไม่ผ่าน (ไม่ใช่ 'ไม่มีของ')");
  if (พลาดที่ต้องจับ.length) {
    console.error(`   · ต้องจับแต่ไม่จับ ${พลาดที่ต้องจับ.length} เคส ⇒ ผลเขียวทั้งหมดเชื่อไม่ได้`);
  }
  if (พลาดที่ต้องไม่จับ.length) {
    console.error(`   · ต้องไม่จับแต่จับ ${พลาดที่ต้องไม่จับ.length} เคส ⇒ แดงลวงจนคนปิดด่าน`);
  }
  process.exit(1);
}
console.log(`🧪 ตัวควบคุมฝังในผ่าน — ต้องจับ ${ต้องจับ.length} เคส · ต้องไม่จับ ${ต้องไม่จับ.length} เคส`);

const น่าสงสัย = [];
let รูปทั้งหมด = 0;

for (const f of ไฟล์) {
  const บรรทัด = readFileSync(f, "utf8").split("\n");
  บรรทัด.forEach((l, i) => {
    if (!จุดถอยเป็นnull.test(l)) return;
    รูปทั้งหมด++;
    const หน้าต่าง = บรรทัด.slice(i, i + 25).join("\n");
    if (เข้าเกณฑ์ทั้งสามข้อ(หน้าต่าง)) น่าสงสัย.push(`${f}:${i + 1}`);
  });
}

/* 🔒 **ชุดที่ตรวจด้วยตาแล้วว่าปลอดภัย — ล็อกด้วยชื่อ ไม่ใช่ด้วยจำนวน**
   เหตุที่ต้องล็อก: ด่านที่พิมพ์ 6 บรรทัดเดิมทุกรอบ จะถูกเมินภายในวันเดียว
   แล้ววันที่มีของใหม่โผล่ บรรทัดที่ 7 จะจมอยู่ในของเดิม (กฎ rules-need-a-gate-not-a-reminder)
   ⚠️ **ล็อกด้วยจำนวนไม่ได้** — ของเดิมหายไปหนึ่งจุดแล้วมีของใหม่มาหนึ่งจุด จำนวนเท่าเดิม
   ⚠️ ปลดชื่อออกจากชุดนี้ได้เมื่อ **ไปอ่านโค้ดจุดนั้นแล้วเท่านั้น** ห้ามปลดเพื่อให้เขียว
   📏 ตรวจด้วยตา 3 ต.ค. 2569 — ทั้งสี่จุดโยนหรือคืนสถานะ "อ่านไม่ได้" อยู่แล้ว:
      read-id   → คืน `{parseFail:true}` (มีสถานะที่สามจริง)
      status    → `if (!j?.ok) throw`
      coredb    → `if (!res.ok || !data?.success) throw`
      d1move    → `if (!res.ok || !data?.success) throw` */
const ตรวจแล้วปลอดภัย = new Set([
  "netlify/functions/read-id.mjs:395",
  "netlify/functions/status.mjs:141",
  "netlify/lib/coredb.mjs:158",
  "netlify/lib/d1move.mjs:57",
  // สองจุดของใบ B14 — แก้แล้ว 3 ต.ค. 2569 (โยนเมื่ออ่าน body ไม่ได้)
  "netlify/lib/adstats.mjs:171",
  "netlify/lib/googleads.mjs:91",
]);
const ของใหม่ = น่าสงสัย.filter((x) => !ตรวจแล้วปลอดภัย.has(x));

console.log(`🔎 รูปแบบ \`json().catch(() => null)\` ทั้งรีโป: ${รูปทั้งหมด} จุด`);
console.log(`   เข้าเกณฑ์ครบสามข้อ: ${น่าสงสัย.length} จุด · ตรวจด้วยตาแล้ว ${น่าสงสัย.length - ของใหม่.length} จุด`);
if (!ของใหม่.length) {
  console.log("   ✅ ไม่มีจุดใหม่ที่ยังไม่เคยตรวจ");
} else {
  console.log(`   ⚠️ **จุดใหม่ที่ยังไม่เคยตรวจ ${ของใหม่.length} จุด** — ไปอ่านโค้ดแล้วตัดสิน:`);
  for (const x of ของใหม่) console.log(`     · ${x}`);
}
console.log("\n🔑 เกณฑ์ตัดสินว่าแก้หรือไม่ — ถามว่า **ใครอ่านเลขนี้ และเขาแยก 'ไม่รู้' จาก 0 ได้ไหม**");
console.log("   เลขที่ขึ้นจอหรือเอาไปคิดต่อ ⇒ ต้องโยน · เลขที่ใช้ภายในและมีทางถอยอื่น ⇒ ปล่อยได้");
console.log("   (ตัวนี้ไม่ตีกลับ build — รายงานเท่านั้น)");
