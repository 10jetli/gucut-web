/** คีย์ของคำตอบ รวมคีย์ชั้นลูกของ object (จอเขียน interface ซ้อน จึงต้องเห็นชั้นลูกด้วย)
 *  ⚠️ ไม่ลงลึกในสมาชิกของ array ทุกตัว — เอาแค่ตัวแรกเป็นตัวอย่างรูปแถว
 *     (ลงทุกตัว = สารบัญบวมและช้า โดยไม่ได้ข้อมูลใหม่ เพราะแถวรูปเดียวกัน)
 *  ⚠️ ลึกสุด 3 ชั้น — ลึกกว่านั้นฝั่งจอไม่เคยเขียน interface ถึง */
function เก็บคีย์(v, ทาง = "", ออก = new Set(), ลึก = 0) {
  if (ลึก > 3 || v === null || typeof v !== "object") return ออก;
  if (Array.isArray(v)) {
    if (v.length) เก็บคีย์(v[0], `${ทาง}[]`, ออก, ลึก + 1);
    return ออก;
  }
  for (const k of Object.keys(v)) {
    const p = ทาง ? `${ทาง}.${k}` : k;
    ออก.add(p);
    เก็บคีย์(v[k], p, ออก, ลึก + 1);
  }
  return ออก;
}

async function ยิง(qs) {
  const t0 = Date.now();
  try {
    const res = await fetch(`${BASE}/api/core?${qs}`, {
      headers: { "x-admin-key": KEY },
      signal: AbortSignal.timeout(45000),
    });
    const text = await res.text();
    let data = null;
    try {
      data = JSON.parse(text);
    } catch {
      /* ไม่ใช่ JSON = ของผิดรูป ต้องรู้ ไม่ใช่กลืน */
      return { http: res.status, ผิดรูป: text.slice(0, 120), ms: Date.now() - t0 };
    }
    return { http: res.status, data, coreBuild: res.headers.get("x-core-build"), ms: Date.now() - t0 };
  } catch (e) {
    return { ยิงไม่ถึง: String(e?.message || e).slice(0, 120), ms: Date.now() - t0 };
  }
}

