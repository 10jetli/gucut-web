import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const ไฟล์ = join(homedir(), ".gucut-probe-runs.json");

const อ่าน = () => {
  try { return JSON.parse(readFileSync(ไฟล์, "utf8")); } catch { return null; }
};

/** ตัวตรวจเรียกตอนจบ — จดว่ารันแล้วเมื่อไหร่ และผลเป็นอะไร
 *  🚫 ห้ามทำให้ตัวตรวจล้มเพราะจดไม่ได้ (เสียบันทึกดีกว่าเสียผลตรวจ) */
export function จดว่ารันแล้ว(ชื่อ, ผล = null) {
  try {
    const เดิม = อ่าน() ?? {};
    เดิม[ชื่อ] = { เมื่อ: new Date().toISOString(), ผล };
    writeFileSync(ไฟล์, JSON.stringify(เดิม, null, 1));
    return true;
  } catch { return false; }
}

/** @returns {{ยังไม่รู้:true}|{รายการ:object}} — **แยก "ยังไม่รู้" จาก "ไม่เคยรัน"** */
export function อ่านบันทึกการรัน() {
  const d = อ่าน();
  if (d === null) return { ยังไม่รู้: true, เหตุ: `ไม่มีไฟล์ ${ไฟล์} — เครื่องนี้อาจยังไม่เคยรันตัวตรวจนอกลูกโซ่เลย หรือเป็นเครื่องอื่น` };
  return { รายการ: d };
}
