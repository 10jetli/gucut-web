import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const ประกาศตัวแปร = (ชื่อ) => new RegExp(`(?:const|let|var)\\s+${ชื่อ}\\s*=`);

/* 🔑 **ต้องเห็น "ชุดเคสถูกนำไปใช้" ไม่ใช่แค่ "ประกาศไว้"**
   ของจริง 20 ก.ย. 2569: ปลูก `const ต้องจับ = ["a"]; const ต้องไม่จับ = ["b"]; void ต้องจับ;`
   (ไม่เทียบผลเลย) ⇒ ตะแกรงรุ่นที่ดูแค่การประกาศ **นับว่า "มี"** ⇒ หนี้ดูน้อยกว่าจริง
   ⚠️ และห้ามถามว่า "ไฟล์นี้มี `process.exit(1)` ไหม" — **ด่านทุกตัวมี** ⇒ เงื่อนไขไร้ผล */
const ถูกนำไปใช้จริง = (ชื่อ, โค้ด) =>
  new RegExp(`${ชื่อ}\\s*\\.\\s*(?:filter|some|every|map|forEach|find)\\s*\\(`).test(โค้ด);

/** ด่านนี้มีตัวควบคุมสองทาง (`ต้องจับ` + `ต้องไม่จับ`) **ในโค้ดที่รันจริง** ไหม */
export function มีตัวควบคุมสองทาง(เนื้อ, ชื่อไฟล์ = "x.mjs") {
  const โค้ด = ตัดคอมเมนต์(String(เนื้อ), ชื่อไฟล์);
  return ประกาศตัวแปร("ต้องจับ").test(โค้ด)
    && ประกาศตัวแปร("ต้องไม่จับ").test(โค้ด)
    && ถูกนำไปใช้จริง("ต้องจับ", โค้ด)
    && ถูกนำไปใช้จริง("ต้องไม่จับ", โค้ด);
}
