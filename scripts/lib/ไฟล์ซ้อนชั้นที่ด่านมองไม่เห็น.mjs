import { readdirSync, statSync } from "node:fs";
import { join } from "node:path";

/** นับไฟล์ที่ตรงเงื่อนไขซึ่งอยู่ **ลึกกว่าชั้นเดียว** ใต้รากที่ให้มา */
export function ไฟล์ซ้อนชั้น(ราก, ตรงเงื่อนไข) {
  const เจอ = [];
  const เดิน = (d, ลึก) => {
    let รายการ;
    try { รายการ = readdirSync(d); } catch { return; }
    for (const ชื่อ of รายการ) {
      if (ชื่อ === "node_modules" || ชื่อ === ".next" || ชื่อ === "out" || ชื่อ === ".netlify") continue;
      const p = join(d, ชื่อ);
      let st;
      try { st = statSync(p); } catch { continue; }
      if (st.isDirectory()) { เดิน(p, ลึก + 1); continue; }
      if (ลึก >= 1 && ตรงเงื่อนไข(ชื่อ)) เจอ.push(p);
    }
  };
  เดิน(ราก, 0);
  return เจอ;
}

/** ใช้ในด่านที่กวาดชั้นเดียว — คืน `true` ถ้าเจอของที่ด่านนั้นมองไม่เห็น (และพิมพ์บอกแล้ว)
 *  @param {string[]} ราก รายชื่อโฟลเดอร์ที่ด่านนั้นกวาดแบบชั้นเดียว
 *  @param {(ชื่อไฟล์:string)=>boolean} ตรงเงื่อนไข เงื่อนไขไฟล์ที่ด่านนั้นสนใจ
 *  @param {string} ชื่อด่าน สำหรับข้อความ */
export function เตือนถ้ามีไฟล์ซ้อนชั้น(ราก, ตรงเงื่อนไข, ชื่อด่าน) {
  const เจอ = ราก.flatMap((r) => ไฟล์ซ้อนชั้น(r, ตรงเงื่อนไข));
  if (!เจอ.length) return false;
  console.error(
    `🔴 ${ชื่อด่าน}: มีไฟล์ที่ด่านนี้ **มองไม่เห็น** ${เจอ.length} ไฟล์ (มันกวาดแค่ชั้นเดียว)\n` +
    เจอ.slice(0, 10).map((p) => `   · ${p}`).join("\n") +
    (เจอ.length > 10 ? `\n   · (อีก ${เจอ.length - 10} ไฟล์)` : "") +
    "\n   ⇒ เขียวของด่านนี้จะแปลว่า **\"ไม่ได้ดู\" ไม่ใช่ \"ไม่มี\"** สำหรับไฟล์ข้างบน\n" +
    "   ⇒ เลือกทางเดียว: ทำให้ด่านลงลึก (แล้วทบทวนเลข/เพดานที่มันพิมพ์) หรือย้ายไฟล์ขึ้นชั้นบนสุด"
  );
  return true;
}
