export function คำเตือนเล่นประวัติซ้ำ(อะไรที่อ่าน) {
  return `⚠️ HEAD ไม่ใช่ปลายกิ่งใด = **กำลังเล่นประวัติซ้ำ** และด่านนี้อ่าน ${อะไรที่อ่าน} **ของวันนี้**\n` +
    "   ⇒ ผลที่ได้เป็นการเทียบ *คอมมิตเก่า* กับ *โลกวันนี้* ⇒ **แปลไม่ได้ ไม่ใช่ผ่านและไม่ใช่ตก**\n" +
    "   🔑 \"ไม่มีของให้เทียบ\" กับ \"มีของแต่คนละยุค\" คนละเรื่อง — อันนี้คืออันหลัง";
}
