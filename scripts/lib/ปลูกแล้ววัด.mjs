/* ปลูกบั๊กแล้ววัดด่าน — **บังคับให้ยืนยันว่าปลูกลงก่อนตัดสินด่านเสมอ**
 * (19 ก.ย. 2569 · ฝั่งท่อเสนอให้เป็นกติการ่วม · ฝั่งผมเหยียบ 4 ครั้งในวันเดียว)
 *
 * 🔴 ปัญหาที่ไฟล์นี้เกิดมาแก้ — **"ด่านเงียบ" มีสองสาเหตุที่แยกจากผลลัพธ์ไม่ได้**
 *    ① ตะแกรงของด่านพัง ⇒ ด่านเชื่อไม่ได้ ต้องไปแก้ด่าน
 *    ② **เราปลูกไม่ลง หรือปลูกนอกขอบเขตที่ด่านจับ** ⇒ ด่านถูกอยู่แล้ว
 *    ⇒ สองอย่างนี้ให้ผลหน้าตาเหมือนกันเป๊ะ (เขียว) ⇒ **เดาผิดแล้วไปรื้อด่านที่ทำงานดี**
 *
 * 📏 ของจริงวันเดียว 19 ก.ย. 2569 ฝั่งผม:
 *    · ปลูก `doSomething()` ใส่ `check-floating` ⇒ เงียบ (ด่านตั้งใจไม่จับท่านั้น)
 *    · ปลูกข้อความที่ *คิดว่า* อยู่ใน `vendors.ts` ⇒ ไม่มีในไฟล์จริง
 *    · ปลูกในคอมเมนต์บล็อก ⇒ ถูกกลืน · ปลูกต่อท้าย `//` บรรทัดเดียว ⇒ ถูกกลืน
 *    ⇒ ทั้งสี่ครั้งได้ "เขียว" ซึ่งอ่านได้ว่าด่านพัง **ทั้งที่ด่านถูกทุกครั้ง**
 *
 * 🔑 กติกาสามข้อที่ไฟล์นี้บังคับ:
 *    ① **ต้องพิสูจน์ว่าปลูกลง** ด้วยคำสั่งที่ *ต้องล้ม* หลังปลูก — ไม่ใช่เชื่อว่า replace สำเร็จ
 *    ② **คืนไฟล์ใน `finally` + ดักสัญญาณตาย** — ตายกลางทาง = ไฟล์ค้างพังเงียบ ๆ
 *    ③ **ไฟล์เป้าหมายต้องสะอาดใน git ก่อน** ⇒ มี `git checkout --` เป็นตาข่ายรับเสมอ
 */
/** 🔑 **รายชื่อผลลัพธ์ทั้งหมด — ผู้เรียกต้องเทียบกับค่าในนี้ ห้ามพิมพ์สตริงเอง**
 *  (เพิ่ม 20 ก.ย. 2569 หลังเปลี่ยนชื่อผลหนึ่งตัว แล้วฝั่งท่อพบว่าโค้ดเขาเทียบชื่อเก่าอยู่
 *   ⇒ ถ้าเขาไม่แก้ตาม **ทะเบียนเขาจะเขียวตลอดกาล** เพราะเทียบกับชื่อที่ไม่มีอยู่แล้ว)
 *  ⇒ ผู้เรียกที่ `import` รายชื่อนี้ จะพังเสียงดังตอนชื่อหาย แทนที่จะเงียบแล้วผ่านฟรี */
/* 🔴 **ขอบเขตของคำว่า "ด่านจับได้" — เขียนไว้ตรงนี้เพราะมันถูกอ่านผิดได้ง่ายที่สุด**
 *    (ข้อของฝั่งจอ 20 ก.ย. 2569 หลังเขาพิสูจน์ด่านรวด 6 ตัวแล้วจับความจริงข้อนี้ได้เอง)
 *
 *    เราปลูก **ของที่ด่านประกาศเองว่าจับ** ⇒ ⇒ ที่พิสูจน์ได้จริงคือ **"ด่านนี้ไม่เขียวตลอดกาล"**
 *    🚫 **ไม่ได้พิสูจน์ว่ามันจับของจริงที่จะเกิดในอนาคต** — เพราะเราไม่ได้ปลูกสิ่งที่โลกจะส่งมา
 *       แต่ปลูกสิ่งที่ตัวมันบอกว่าทำได้ ⇒ **นี่คือเพดานของวิธีปลูกทั้งวิธี ไม่ใช่ข้อบกพร่องของด่านตัวไหน**
 *
 *    🔑 ⇒ ในทะเบียน คำว่า **"พิสูจน์แล้ว" แปลว่า "ไม่เขียวตลอดกาล" เท่านั้น**
 *       ⇒ ⇒ **ห้ามอ่านว่า "ด่านนี้เชื่อได้"** · อ่านผลรวมของทะเบียนเป็น
 *          *"กี่ด่านที่รู้ว่ายังมีชีวิต"* ไม่ใช่ *"กี่ด่านที่กันของจริงได้"*
 *    📌 ของที่จะยกเพดานนี้ได้มีทางเดียว: **ปลูกจากของจริงที่เคยเกิด** (บั๊กในประวัติ git)
 *       — ยังไม่ทำ ⇒ จดเป็นหนี้ ไม่ใช่เขียนว่าทำแล้ว */
