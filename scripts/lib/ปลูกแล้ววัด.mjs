/* ปลูกบั๊กแล้ววัดด่าน — **บังคับให้ยืนยันว่าปลูกลงก่อนตัดสินด่านเสมอ**
 * (19 ก.ย. 2569 · ฝั่งท่อเสนอให้เป็นกติการ่วม · ฝั่งผมเหยียบ 4 ครั้งในวันเดียว)
 *
 * 🔴 ปัญหาที่ไฟล์นี้เกิดมาแก้ — **"ด่านเงียบ" มีสองสาเหตุที่แยกจากผลลัพธ์ไม่ได้**
 *    ① ตะแกรงของด่านพัง ⇒ ด่านเชื่อไม่ได้ ต้องไปแก้ด่าน
 *    ② **เราปลูกไม่ลง หรือปลูกนอกขอบเขตที่ด่านจับ** ⇒ ด่านถูกอยู่แล้ว
 *    ⇒ สองอย่างนี้ให้ผลหน้าตาเหมือนกันเป๊ะ (เขียว) ⇒ **เดาผิดแล้วไปรื้อด่านที่ทำงานดี**
 *
 * 📏 ของจริงวันเดียว 19 ก.ย. 2569 ฝั่งผม:
 *    · ปลูก `doSomething()` ใส่ `check-floating` ⇒ เงียบ (ด่านตั้งใจไม่จับท่านั้น)
 *    · ปลูกข้อความที่ *คิดว่า* อยู่ใน `vendors.ts` ⇒ ไม่มีในไฟล์จริง
 *    · ปลูกในคอมเมนต์บล็อก ⇒ ถูกกลืน · ปลูกต่อท้าย `//` บรรทัดเดียว ⇒ ถูกกลืน
 *    ⇒ ทั้งสี่ครั้งได้ "เขียว" ซึ่งอ่านได้ว่าด่านพัง **ทั้งที่ด่านถูกทุกครั้ง**
 *
 * 🔑 กติกาสามข้อที่ไฟล์นี้บังคับ:
 *    ① **ต้องพิสูจน์ว่าปลูกลง** ด้วยคำสั่งที่ *ต้องล้ม* หลังปลูก — ไม่ใช่เชื่อว่า replace สำเร็จ
 *    ② **คืนไฟล์ใน `finally` + ดักสัญญาณตาย** — ตายกลางทาง = ไฟล์ค้างพังเงียบ ๆ
 *    ③ **ไฟล์เป้าหมายต้องสะอาดใน git ก่อน** ⇒ มี `git checkout --` เป็นตาข่ายรับเสมอ
 */
/** 🔑 **รายชื่อผลลัพธ์ทั้งหมด — ผู้เรียกต้องเทียบกับค่าในนี้ ห้ามพิมพ์สตริงเอง**
 *  (เพิ่ม 20 ก.ย. 2569 หลังเปลี่ยนชื่อผลหนึ่งตัว แล้วฝั่งท่อพบว่าโค้ดเขาเทียบชื่อเก่าอยู่
 *   ⇒ ถ้าเขาไม่แก้ตาม **ทะเบียนเขาจะเขียวตลอดกาล** เพราะเทียบกับชื่อที่ไม่มีอยู่แล้ว)
 *  ⇒ ผู้เรียกที่ `import` รายชื่อนี้ จะพังเสียงดังตอนชื่อหาย แทนที่จะเงียบแล้วผ่านฟรี */
export const ผลลัพธ์ทั้งหมด = Object.freeze([
  'ด่านจับได้',
  'ด่านเห็นแต่ไม่ทำให้ตก',
  'ด่านเขียวทั้งที่ปลูกลง',
  'ด่านแดงแต่ไม่เอ่ยถึงของที่ปลูก',
  'ปลูกไม่ลง',
  'ตัดสินไม่ได้ (ไม่มีหลักฐานว่าปลูกอยู่ในขอบเขตของด่าน)',
])

import { readFileSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'

/**
 * @param {object} o
 * @param {string} o.ไฟล์            พาธไฟล์ที่จะปลูก (relative กับ cwd)
 * @param {(เดิม:string)=>string} o.แก้  คืนเนื้อไฟล์ที่ปลูกแล้ว · **ต้องต่างจากเดิม**
 * @param {string[]} [o.ยืนยันปลูกลง]  คำสั่งที่ **ต้องล้ม** หลังปลูก (เช่น ['node','--check',ไฟล์])
 *                                     ไม่ใส่ = ใช้ "เนื้อไฟล์ต่างจากเดิม" ซึ่งอ่อนกว่า **และจะเตือน**
 * @param {string[]} o.ด่าน            คำสั่งของด่านที่จะวัด
 * @param {string} [o.ต้องเอ่ยถึง]     ผลของด่านต้องมีข้อความนี้ (เช่นชื่อไฟล์ที่ปลูก)
 *   🔑 **ต้องเป็นรูปที่ "ด่านพิมพ์" ไม่ใช่รูปที่ "เราปลูก"** — ถ้าด่านแปลงค่าก่อนพิมพ์
 *      (เช่นปลูก `99,999` แต่ด่าน normalize แล้วพิมพ์ `99999`) จะได้ผล "แดงแต่ไม่เอ่ยถึง" ผิด ๆ
 *      (ฝั่งท่อเจอกับตัว 19 ก.ย. 2569)
 * @returns {{ผล:'ด่านจับได้'|'ด่านเห็นแต่ไม่ทำให้ตก'|'ด่านเขียวทั้งที่ปลูกลง'|'ปลูกไม่ลง'|'ด่านแดงแต่ไม่เอ่ยถึงของที่ปลูก'|'ตัดสินไม่ได้ (ไม่มีหลักฐานว่าปลูกอยู่ในขอบเขตของด่าน)', รายละเอียด:string}}
 */
export function ปลูกแล้ววัด({ ไฟล์, แก้, ยืนยันปลูกลง, ต้องมีในไฟล์, ด่าน, ต้องเอ่ยถึง }) {
  /* ③ ตาข่ายที่ไม่พึ่งตัวเอง */
  const สกปรก = spawnSync('git', ['status', '--porcelain', '--', ไฟล์], { encoding: 'utf8' })
  if ((สกปรก.stdout || '').trim()) {
    return { ผล: 'ปลูกไม่ลง', รายละเอียด: `ไฟล์ ${ไฟล์} มีของแก้ค้างใน git ⇒ ไม่ปลูกทับ (ต้องมี git เป็นตาข่ายรับก่อน)` }
  }

  const เดิม = readFileSync(ไฟล์, 'utf8')
  const ใหม่ = แก้(เดิม)
  if (ใหม่ === เดิม) {
    return { ผล: 'ปลูกไม่ลง', รายละเอียด: `\`แก้()\` คืนเนื้อเดิม — ข้อความที่จะแทนไม่มีอยู่ในไฟล์จริง` }
  }

  const คืน = () => { try { writeFileSync(ไฟล์, เดิม) } catch { /* สุดทางแล้ว */ } }
  const สัญญาณ = ['SIGINT', 'SIGTERM', 'SIGHUP']
  const ตัวดัก = () => { คืน(); process.exit(130) }
  for (const s of สัญญาณ) process.on(s, ตัวดัก)

  try {
    writeFileSync(ไฟล์, ใหม่)

    /* หลักฐานอย่างอ่อน: ของที่ปลูกต้องมีรูปที่ด่านมองหาจริง ๆ อยู่ในไฟล์ */
    if (ต้องมีในไฟล์ && !ใหม่.includes(ต้องมีในไฟล์)) {
      return { ผล: 'ปลูกไม่ลง', รายละเอียด: `ปลูกแล้วแต่ไม่พบ "${ต้องมีในไฟล์}" ในไฟล์ ⇒ ของที่ปลูกไม่ได้อยู่ในรูปที่ตั้งใจ` }
    }

    /* ① ข้อสำคัญที่สุด — ไม่มีข้อนี้ ผลที่ได้ตีความไม่ได้ */
    if (ยืนยันปลูกลง) {
      const y = spawnSync(ยืนยันปลูกลง[0], ยืนยันปลูกลง.slice(1), { encoding: 'utf8' })
      if (y.status === 0) {
        return { ผล: 'ปลูกไม่ลง', รายละเอียด: `คำสั่งยืนยันไม่ล้ม (\`${ยืนยันปลูกลง.join(' ')}\` exit 0) ⇒ ของที่ปลูกไม่ได้ทำให้อะไรเปลี่ยนจริง` }
      }
    }

    const r = spawnSync(ด่าน[0], ด่าน.slice(1), { encoding: 'utf8' })
    const out = (r.stdout || '') + (r.stderr || '')
    if (r.status === 0) {
      /* 🔴 **ห้ามตัดสินว่าด่านพัง ถ้ายังไม่มีหลักฐานว่าของที่ปลูกอยู่ในขอบเขตที่ด่านจับ**
         (เพิ่ม 19 ก.ย. 2569 หลังเครื่องมือนี้ติดป้าย "ด่านจับไม่ได้" ให้ `check-dead-links`
          ทั้งที่ของจริงคือผมปลูก `export const X = "/…"` ซึ่งไม่มีคำว่า `href` —
          และด่านนั้นประกาศไว้ชัดว่าจับเฉพาะ `href=` / `href:`)
         🔑 "เนื้อไฟล์เปลี่ยน" พิสูจน์แค่ว่า **การแก้ไฟล์** ลงจริง
            ไม่ได้พิสูจน์ว่า **ของที่ปลูกเป็นชนิดที่ด่านมองหา** — คนละชั้นกัน */
      /* 🔑 **ผลลัพธ์ที่ห้า: ด่านเห็น แต่ไม่ทำให้ตก** (ฝั่งท่อเพิ่ม 19 ก.ย. 2569 · ผมยกมาให้เหมือนกัน)
         ด่านที่ **รายงานอย่างเดียวโดยเจตนา** (เช่นของที่คนเจอแก้เองไม่ได้ ⇒ ถ้าทำ build ตก
         จะถูกถอดทั้งด่าน) จะ `exit 0` เสมอ **แต่พิมพ์ของที่จับได้ตรงตัว**
         ⇒ เครื่องมือที่ดูแต่ exit code จะ **โทษด่านผิด** ทุกครั้งที่ความรุนแรงถูกตั้งต่ำโดยเจตนา
         🔑 **ความรุนแรงเป็นการตัดสินใจ แยกจากการตรวจจับ** ⇒ ต้องแยกสองเรื่องนี้ในผลลัพธ์ */
      if (ต้องเอ่ยถึง && out.includes(ต้องเอ่ยถึง)) {
        return { ผล: 'ด่านเห็นแต่ไม่ทำให้ตก', รายละเอียด: `exit 0 แต่ผลเอ่ยถึง "${ต้องเอ่ยถึง}" ⇒ ด่านจับได้ · ความรุนแรงถูกตั้งเป็น "รายงานอย่างเดียว"` }
      }
      if (!ยืนยันปลูกลง && !ต้องมีในไฟล์) {
        return {
          ผล: 'ตัดสินไม่ได้ (ไม่มีหลักฐานว่าปลูกอยู่ในขอบเขตของด่าน)',
          รายละเอียด: 'ด่านเขียว แต่ไม่ได้ใส่ `ยืนยันปลูกลง` หรือ `ต้องมีในไฟล์` ⇒ แยกไม่ออกว่า "ตะแกรงพัง" หรือ "ปลูกนอกขอบเขต"',
        }
      }
      /* 🔴 **เปลี่ยนชื่อผลและถ้อยคำ 20 ก.ย. 2569 — ของเดิมสรุปแทนคนอ่าน และมันผิด 5 ครั้งจาก 5**
         เดิมชื่อ `ด่านจับไม่ได้` + เขียนว่า "ตะแกรงของด่านมีปัญหาจริง"
         ⇒ ฝั่งจอเจอผลนี้ 5 ครั้งในคืนเดียว และ **ทั้ง 5 ครั้งของจริงคือปลูกนอกขอบเขต ด่านถูก**
           (ชื่อผสม ASCII+ไทย · เป้ามีป้ายยกเว้น · ประตูเป็นชื่อเปล่า · คีย์ไม่ได้เปิดอยู่ · ฯลฯ)
         🔑 **`ต้องมีในไฟล์` พิสูจน์แค่ว่าข้อความอยู่ในไฟล์ ไม่ได้พิสูจน์ว่ามันอยู่ในรูปที่ด่านมองหา**
            ⇒ ผลนี้จึงแปลได้สองทางเสมอ และทางที่พบบ่อยกว่าคือ "เราปลูกผิดที่" */
      return {
        ผล: 'ด่านเขียวทั้งที่ปลูกลง',
        รายละเอียด: 'ปลูกลงแล้ว (ยืนยันแล้ว) แต่ด่านยังเขียว ⇒ **แปลได้สองทาง เรียงตามที่พบบ่อย**: '
          + '① ของที่ปลูก **ไม่อยู่ในรูป/ขอบเขตที่ด่านมองหา** (อ่านเงื่อนไขของด่านก่อน: ราก · รายการยกเว้น · '
          + 'รูปที่มันบังคับ) · ② ตะแกรงของด่านมีปัญหาจริง '
          + '⇒ **ห้ามสรุปข้อ ② ก่อนไล่ข้อ ①** — ถ้าไล่แล้วพบว่าขอบเขตแคบเกินจริง นั่นเป็นคนละเรื่องกับตะแกรงพัง',
      }
    }
    if (ต้องเอ่ยถึง && !out.includes(ต้องเอ่ยถึง)) {
      return {
        ผล: 'ด่านแดงแต่ไม่เอ่ยถึงของที่ปลูก',
        รายละเอียด: `ด่านแดง แต่ผลไม่มีคำว่า "${ต้องเอ่ยถึง}" ⇒ **อาจแดงด้วยเหตุอื่น ห้ามอ่านว่าพิสูจน์แล้ว**`,
      }
    }
    return { ผล: 'ด่านจับได้', รายละเอียด: `exit ${r.status}${ต้องเอ่ยถึง ? ` · เอ่ยถึง "${ต้องเอ่ยถึง}"` : ''}` }
  } finally {
    คืน()
    for (const s of สัญญาณ) process.off(s, ตัวดัก)
  }
}
