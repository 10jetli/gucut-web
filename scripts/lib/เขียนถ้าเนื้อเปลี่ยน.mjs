/* 💾 **เขียนไฟล์เฉพาะเมื่อเนื้อเปลี่ยน — ไม่นับ timestamp เป็นเนื้อ**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ฝั่งจอถามว่าฝั่งท่อมีไฟล์ที่ถูกเขียนทับด้วย timestamp ไหม
 *    📏 วัดแล้ว: **มี 4 ไฟล์** (`cron-table` · `endpoints` · `list-filters` · `warn-keys`)
 *       ทุกครั้งที่ `npm run build` ⇒ diff = **1 บรรทัด คือ `generatedAt`/`สร้างเมื่อ`**
 *    ⇒ ⇒ **git สกปรกทุกครั้งที่ตรวจ โดยไม่มีอะไรเปลี่ยนจริง** และผลตามมาสามชั้น:
 *      ① ท่ากิ่งทิ้ง (worktree) ที่ต้องการ tree สะอาด ใช้ไม่ได้จนกว่าจะ revert มือทุกครั้ง
 *      ② **อีกบัญชีในเครื่องเดียวกัน pull ไม่ได้** — บทเรียนที่เราเจ็บมาแล้ว
 *      ③ ประวัติคอมมิตมีใบที่ "เปลี่ยนแต่เวลา" ⇒ คนอ่าน log แยกไม่ออกว่าใบไหนเปลี่ยนของจริง
 *
 * 🔑 กติกา: timestamp มีไว้ตอบว่า **"ของนี้สร้างเมื่อไหร่"** ⇒ มีค่าเฉพาะเมื่อ **เนื้อเปลี่ยน**
 *    ถ้าเนื้อเหมือนเดิม เวลาเดิมก็ยังจริง (มันบอกว่าเนื้อชุดนี้เกิดเมื่อไหร่ ไม่ใช่ "ตรวจล่าสุดเมื่อไหร่")
 * 🚫 **ห้ามใช้กับไฟล์ที่ timestamp คือเนื้อหา** เช่นสมุดบันทึกการรัน · log · ผลวัดรายรอบ
 *    (ที่นั่น "รันอีกครั้งแล้วได้ผลเดิม" เป็น **ข้อมูล** ไม่ใช่ noise)
 */
import { readFileSync, writeFileSync } from "node:fs";

/** รูปของบรรทัดเวลาที่ถือว่า "ไม่ใช่เนื้อ" — เพิ่มได้ แต่ต้องเป็นบรรทัดที่ **สร้างจากนาฬิกา** เท่านั้น */
/* 🔴 **ท้ายบรรทัดต้องรับทั้ง `;` และ `,`** — พลาดมาแล้วในวันเดียวกับที่เขียน (20 ก.ย. 2569)
   รอบแรกผมเขียน `,?` อย่างเดียว ⇒ บรรทัด `export const generatedAt = "…";` **ไม่เข้าเงื่อนไข**
   ⇒ ตัวช่วยเลยเขียนไฟล์ทุกครั้งเหมือนไม่มีอะไรเปลี่ยน ⇒ **และผมรายงานว่าแก้แล้วไปก่อนหน้านั้น**
   🔑 จับได้เพราะวัดด้วย **ลายนิ้วมือไฟล์ (md5) ก่อน-หลัง** ไม่ใช่ดู `git status`
      — `git status` เทียบกับ committed ⇒ "เขียนครั้งเดียว" กับ "เขียนทุกรอบ" **หน้าตาเหมือนกันเป๊ะ** */
/* 🔴 **รายชื่อนี้จะค้างเสมอ — ประกาศไว้ตรง ๆ**
   20 ก.ย. 2569: เพิ่ม `"at"` เพราะ `gen-zort-arch.mjs` มีช่องเวลาชื่อนั้นใน `selfCheck`
   ⇒ ไฟล์ผลลัพธ์ถูกเขียนทุก build ⇒ git ไม่สะอาด ⇒ อีกบัญชี pull ไม่ได้
   (คลาสเดิมที่แก้เมื่อเช้าวันเดียวกัน · **รูปใหม่ ไม่ใช่บั๊กใหม่**)
   🔑 วิธีตรวจว่ารายชื่อยังครบ **ไม่ใช่การอ่านรายชื่อนี้** แต่คือวัดพฤติกรรม:
      `git status --porcelain` ต้องว่างหลัง `npm run build` (และหลัง `npm test`)
   ⚠️ ค่าต้องเป็นรูป ISO เท่านั้น ห้ามรับค่าอะไรก็ได้ — ไม่งั้นจะกลืน **ข้อมูลจริง**
      ที่บังเอิญอยู่ในช่องชื่อเดียวกัน แล้วไฟล์ที่เนื้อเปลี่ยนจริงจะไม่ถูกเขียน */
const รูปวันเวลาISO = String.raw`\d{4}-\d{2}-\d{2}(?:[T ][\d:.]+Z?)?`;
const รูปเวลา = [
  /^\s*(?:export const )?generatedAt\s*[=:]\s*["'][^"']*["'][;,]?\s*$/m,
  /^\s*"(?:สร้างเมื่อ|วัดเมื่อ|generatedAt)"\s*:\s*"[^"]*"[;,]?\s*$/m,
  new RegExp(String.raw`^\s*"(?:at|ranAt|checkedAt|ตรวจเมื่อ)"\s*:\s*"${รูปวันเวลาISO}"[;,]?\s*$`, "m"),
];

const ถอดเวลา = (s) => {
  let out = String(s);
  for (const r of รูปเวลา) out = out.replace(new RegExp(r.source, "gm"), "⟪เวลา⟫");
  return out;
};

/** เขียน `path` ด้วย `เนื้อ` เฉพาะเมื่อเนื้อ (ไม่นับบรรทัดเวลา) ต่างจากไฟล์เดิม
 *  @returns {"เขียนใหม่"|"เนื้อเดิม—ไม่เขียน"|"ไฟล์ใหม่"} */
export function เขียนถ้าเนื้อเปลี่ยน(path, เนื้อ) {
  let เดิม = null;
  try { เดิม = readFileSync(path, "utf8"); } catch { /* ไม่มีไฟล์เดิม = ของใหม่ */ }
  if (เดิม === null) { writeFileSync(path, เนื้อ); return "ไฟล์ใหม่"; }
  if (ถอดเวลา(เดิม) === ถอดเวลา(เนื้อ)) return "เนื้อเดิม—ไม่เขียน";
  writeFileSync(path, เนื้อ);
  return "เขียนใหม่";
}
