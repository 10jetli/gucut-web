/** ใช้กับตะแกรงข้อความ: คืนรายการที่ **ตะแกรงตอบผิด** (ว่างเปล่า = ผ่านทุกรูปในคลัง)
 *  @param {(ข้อความ:string)=>boolean} ตะแกรง ฟังก์ชันที่คืน true เมื่อ "เข้าข่าย"
 *  @param {string[]} [เฉพาะที่มา] กรองเฉพาะรูปที่มาจากบางเหตุการณ์ (ค้นด้วย substring) */
export function ตรวจตะแกรงกับรูปที่เคยพลาด(ตะแกรง, เฉพาะที่มา) {
  const ชุด = เฉพาะที่มา
    ? รูปที่ตะแกรงข้อความเคยพลาด.filter(([, , ที่มา]) => เฉพาะที่มา.some((k) => ที่มา.includes(k)))
    : รูปที่ตะแกรงข้อความเคยพลาด;
  const ผิด = [];
  for (const [ข้อความ, ควรจับ, ที่มา] of ชุด) {
    let ได้ = null;
    try { ได้ = !!ตะแกรง(ข้อความ); } catch (e) { ผิด.push({ ข้อความ, ที่มา, เหตุ: `ตะแกรงโยน error: ${e?.message}` }); continue; }
    if (ได้ !== ควรจับ) {
      ผิด.push({ ข้อความ, ที่มา, เหตุ: ควรจับ ? "ควรจับแต่ไม่จับ (เขียวลวง)" : "ไม่ควรจับแต่จับ (แดงลวง)" });
    }
  }
  /* 🔑 คืน **จำนวนที่ทดสอบ** ด้วยเสมอ — ผ่าน 0/0 ไม่ใช่ข่าวดี มันคือ "ไม่ได้ทดสอบ" */
  return { ทดสอบ: ชุด.length, ผิด };
}
