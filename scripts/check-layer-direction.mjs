#!/usr/bin/env node
/* 🔽 ด่านเพดาน: **ชั้นล่าง (`lib/`) ห้าม import ชั้นบน (`functions/` · `components/` · `app/`)**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ฝั่งจอเจอในรีโปเขาก่อน: `lib/product-menu.ts` import ชนิดจาก
 *    `components/zort/index.tsx` ⇒ **ชั้นล่างพึ่งชั้นบน = ทิศกลับหัว**
 *    ⇒ วันที่ใครย้าย/ลบ component นั้น `lib/` พังตามโดยไม่มีเหตุผลทางตรรกะเลย
 *    ⇒ เขาแก้แล้ว (ย้ายชนิดไป `lib/types.ts` + re-export ไว้ที่เดิม ⇒ ผู้เรียกไม่ต้องแก้)
 *
 * 📏 **ผมวัดฝั่งนี้ตาม ⇒ เจอ 1 จุด และเป็นเส้นเงิน**
 *    `netlify/lib/beam-sweep.mjs` → `await import("../functions/orders.mjs")` (`markOrderPaid`)
 *    ⚠️ คอมเมนต์ที่นั่นเขียนไว้เองว่า *"import แบบเลื่อนเวลา กันวงกลม"*
 *       ⇒ ⇒ **dynamic import ที่ใส่เพื่อกันวงกลม คือหลักฐานว่าทิศพึ่งพาผิด ไม่ใช่การแก้**
 *          มันย้ายความพังจาก "โหลดไม่ได้" ไปเป็น "พังตอนรันถ้าเส้นทางนั้นถูกเรียก"
 *
 * 🚫 **ทำไมไม่แก้วันนี้ (ตัดสินไว้ 20 ก.ย. 2569 — เขียนไว้เพื่อไม่ให้คนรอบหน้าคิดว่าลืม)**
 *    `markOrderPaid` พึ่ง `zortAddOrder` ซึ่ง **นิยามอยู่ใน `functions/orders.mjs` เอง**
 *    ⇒ ย้ายแล้วลากตามทั้งเส้นเงิน (ยืนยันเงินเข้า) และเส้นส่งออเดอร์เข้า ZORT
 *    ⇒ และกติกาของโปรเจกต์นี้คือ **ไฟล์ `.mjs` ต้องยิงของจริงหลัง deploy** (`tsc` มองไม่เห็น)
 *      ตอนนี้ **ธงหยุด deploy ติดอาวุธ** ⇒ ทดสอบจริงไม่ได้ ⇒ diff ใหญ่บนเส้นเงินโดยไม่มีทางพิสูจน์
 *      = ความเสี่ยงที่ไม่คุ้ม ⇒ **จดเป็นหนี้ที่วัดแล้ว และกันของใหม่ไว้ก่อน**
 *
 * 🔑 ท่าเดียวกับ `check-num-helpers` / `check-thai-offset-copies`: **เพดานลดได้ ห้ามขึ้น**
 *    และ **ต่ำกว่าเพดานก็ตก** ไม่งั้นเพดานค้างสูงตลอดกาลแล้วด่านกลายเป็นด่านที่ผ่านเสมอ
 *    (ผมเจอกับตัวเองวันนี้: เพดาน 46 ทั้งที่ของจริง 45 ⇒ มีช่องให้แย่ลง 1 จุดโดยไม่มีใครรู้)
 *
 * ใช้: node scripts/check-layer-direction.mjs
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { ตัดคอมเมนต์ } from "./_strip-comments.mjs";

/* 🔒 เพดาน = **ของจริงวันที่ตั้ง** (20 ก.ย. 2569) ไม่ใช่เลขที่ใครคิดว่าเหมาะ
   นับใหม่ได้ด้วย: `node scripts/check-layer-direction.mjs` */
const เพดาน = 1;

const ไฟล์ = [];
(function เดิน(d) {
  for (const e of readdirSync(d)) {
    if (["node_modules", ".next", "out", ".netlify", ".git", "public"].includes(e)) continue;
    const p = join(d, e);
    try { statSync(p).isDirectory() ? เดิน(p) : /\.(mjs|ts|tsx)$/.test(e) && ไฟล์.push(p); }
    catch (err) {
      /* อ่านไม่ได้ ⇒ **บอกออกมา** ไม่ใช่นับได้น้อยลงแล้วผ่าน */
      console.error(`🔴 อ่าน ${p} ไม่ได้: ${String(err?.message || err).slice(0, 80)} ⇒ นับไม่ครบ ⇒ ถือว่าตก`);
      process.exit(1);
    }
  }
})(".");

const เป็นชั้นล่าง = (p) => /(^|\/)(netlify\/lib|src\/lib)\//.test(p.replace(/\\/g, "/"));
/* 🔑 ตรวจ **เป้าหมายของ import** ไม่ใช่ชื่อไฟล์ผู้เรียก — ครอบ **สามรูป**
   ⚠️ ต้องครอบ `await import(...)` ด้วย ไม่งั้นรูปที่ "กันวงกลม" (ซึ่งคือรูปที่เราตามหา) หลุดทั้งหมด
   🔴 **และต้องครอบ `require(...)` ด้วย — ผมลืมรูปนี้ในรอบแรก** (20 ก.ย. 2569)
      ตลกร้าย: ผมเป็นคนเตือนฝั่งจอเองว่า *"เช็คด้วยว่าตะแกรงครอบ await import/require หรือยัง"*
      แล้ว **ตะแกรงของผมเองไม่ครอบ `require`** ⇒ ตัวควบคุมที่ฝังไว้จับได้ตั้งแต่รันครั้งแรก
      🔑 ⇒ นี่คือเหตุผลทั้งหมดของการฝังตัวควบคุม: **การรู้ว่าต้องครอบอะไร ไม่ได้ทำให้เราครอบ** */
const ชี้ชั้นบน = /(?:^|[^\w])(?:import|from|require)\s*\(?\s*["']([^"']+)["']/g;
const เป้าเป็นชั้นบน = (t) =>
  /(?:^|\/)(?:\.\.\/)*functions\//.test(t) ||
  /(?:^|\/)(?:\.\.\/)*edge-functions\//.test(t) ||
  /@\/(?:components|app)\//.test(t) ||
  /(?:^|\/)(?:\.\.\/)*(?:components|app)\//.test(t);

/* 🧪 **ตัวควบคุมฝังในตัวด่าน — รันทุกรอบ ก่อนตัดสินอะไรทั้งนั้น** (ท่าที่ฝั่งจอใช้ 20 ก.ย. 2569)
   🔑 เหตุ: สูตรปลูกในทะเบียนรันด้วยมือ (`ด่านแยกแยะได้ไหม.mjs`) ⇒ **ระหว่างการรันมือแต่ละครั้ง
      ตะแกรงพังได้เงียบ ๆ** แล้วผลจะเป็น "0 จุด" ซึ่งอ่านเหมือนข่าวดีที่สุด
   ⇒ ⇒ ควบคุมไม่ผ่าน = **ด่านตกทันที พร้อมบอกว่า "ผลของมันอ่านไม่ได้" ไม่ใช่ "ไม่มีของ"**
   ⚠️ ต้องมีทั้งเคส **ต้องจับ** และเคส **ต้องไม่จับ** — มีแต่เคสต้องจับ จะไม่เห็นตะแกรงที่กว้างเกิน
   ✅ ไฟล์นี้อยู่ใน `scripts/` ซึ่ง **ไม่ใช่ชั้นล่าง** ⇒ ข้อความตัวอย่างข้างล่างไม่ถูกกวาดเอง
      (ต่างจากฝั่งจอที่ต้องยกเว้นไฟล์ตัวเอง — ที่นี่ได้มาฟรีเพราะเกณฑ์ชั้นเจาะจงกว่า)
      🚫 แต่ถ้าวันหนึ่งขยายเกณฑ์ชั้นล่างให้ครอบ `scripts/` **ต้องกลับมายกเว้นไฟล์นี้** */
{
  const ต้องจับ = [
    'import { x } from "../functions/orders.mjs";',
    'const { x } = await import("../functions/orders.mjs");',
    'import X from "@/components/zort";',
    'const m = require("../../app/api/x/route.ts");',
  ];
  const ต้องไม่จับ = [
    'import { x } from "./order-finalize.mjs";',
    'import { y } from "@/lib/types";',
    'import { z } from "../lib/session.mjs";',
  ];
  const จับไหม = (บรรทัด) => [...บรรทัด.matchAll(ชี้ชั้นบน)].some((m) => เป้าเป็นชั้นบน(m[1]));
  const พลาด = [
    ...ต้องจับ.filter((x) => !จับไหม(x)).map((x) => `ต้องจับแต่ไม่จับ: ${x}`),
    ...ต้องไม่จับ.filter((x) => จับไหม(x)).map((x) => `ต้องไม่จับแต่จับ: ${x}`),
  ];
  if (พลาด.length) {
    console.error(
      "🔴 **ตัวควบคุมของด่านนี้ไม่ผ่าน ⇒ ผลของด่านนี้อ่านไม่ได้** (ไม่ใช่ 'ไม่มีของ')\n" +
      พลาด.map((x) => `   · ${x}`).join("\n") +
      "\n   ⇒ ตะแกรงเสียหรือรูป import เปลี่ยน ⇒ แก้ตะแกรงก่อน แล้วรันซ้ำ"
    );
    process.exit(1);
  }
}

const พบ = [];
for (const p of ไฟล์) {
  if (!เป็นชั้นล่าง(p)) continue;
  const s = ตัดคอมเมนต์(readFileSync(p, "utf8"), p);
  for (const m of s.matchAll(ชี้ชั้นบน)) if (เป้าเป็นชั้นบน(m[1])) พบ.push([p, m[1]]);
}
if (!ไฟล์.length) {
  console.error("🔴 ไม่เจอไฟล์สักไฟล์ ⇒ ตะแกรงพัง ไม่ใช่ผ่าน");
  process.exit(1);
}

const ชั้นล่าง = ไฟล์.filter(เป็นชั้นล่าง).length;
console.log(
  `🔽 ชั้นล่างพึ่งชั้นบน: **${พบ.length} จุด** (เพดาน ${เพดาน}) — สแกน ${ไฟล์.length} ไฟล์ · ชั้นล่าง ${ชั้นล่าง} ไฟล์\n` +
  "   📉 เลขนี้ต้องลดลง — **อ่านเป็นหนี้ ไม่ใช่บั๊กที่ต้องแก้เดี๋ยวนี้**\n" +
  "   🔑 `await import()` ที่ใส่เพื่อ 'กันวงกลม' นับเป็นทิศกลับหัวด้วย — มันกลบอาการ ไม่ได้แก้ทิศ"
);
for (const [p, t] of พบ) console.log(`   · ${p} → ${t}`);

if (พบ.length > เพดาน) {
  console.error(
    `\n🔴 กองโตขึ้น (${พบ.length} > ${เพดาน}) ⇒ มีคนเพิ่ม import จากชั้นบนเข้าไปใน lib/\n` +
    "   ⇒ ท่าแก้: ย้ายของที่ต้องใช้ร่วมกันลงไปที่ `lib/` แล้ว **re-export ไว้ที่เดิม**\n" +
    "     ⇒ ผู้เรียกทุกตัวไม่ต้องแก้สักไฟล์ (ท่าที่ฝั่งจอใช้กับ `RowMenuItem` 20 ก.ย. 2569)"
  );
  process.exit(1);
}
if (พบ.length < เพดาน) {
  console.error(
    `\n❌ เหลือ ${พบ.length} จุด ต่ำกว่าเพดาน ${เพดาน} แล้ว ⇒ **ลดเพดานในไฟล์นี้ให้เท่ากับ ${พบ.length} ในคอมมิตเดียวกัน**\n` +
    "   (เพดานที่ไม่ตามความจริง = ช่องว่างให้กองโตขึ้นเงียบ ๆ · เลขต้องเดินลงทางเดียว)"
  );
  process.exit(1);
}
