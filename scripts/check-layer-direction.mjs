import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { ตัดคอมเมนต์ } from "./_strip-comments.mjs";

/* 🔒 เพดาน = **ของจริงวันที่ตั้ง** (20 ก.ย. 2569) ไม่ใช่เลขที่ใครคิดว่าเหมาะ
   นับใหม่ได้ด้วย: `node scripts/check-layer-direction.mjs` */
const เพดาน = 1;

const ไฟล์ = [];
(function เดิน(d) {
  for (const e of readdirSync(d)) {
    if (["node_modules", ".next", "out", ".netlify", ".git", "public"].includes(e)) continue;
    const p = join(d, e);
    try { statSync(p).isDirectory() ? เดิน(p) : /\.(mjs|ts|tsx)$/.test(e) && ไฟล์.push(p); }
    catch (err) {
      /* อ่านไม่ได้ ⇒ **บอกออกมา** ไม่ใช่นับได้น้อยลงแล้วผ่าน */
      console.error(`🔴 อ่าน ${p} ไม่ได้: ${String(err?.message || err).slice(0, 80)} ⇒ นับไม่ครบ ⇒ ถือว่าตก`);
      process.exit(1);
    }
  }
})(".");

const เป็นชั้นล่าง = (p) => /(^|\/)(netlify\/lib|src\/lib)\//.test(p.replace(/\\/g, "/"));
/* 🔑 ตรวจ **เป้าหมายของ import** ไม่ใช่ชื่อไฟล์ผู้เรียก — ทั้ง static และ dynamic
   ⚠️ ต้องครอบ `await import(...)` ด้วย ไม่งั้นรูปที่ "กันวงกลม" (ซึ่งคือรูปที่เราตามหา) หลุดทั้งหมด */
const ชี้ชั้นบน = /(?:^|[^\w])(?:import|from)\s*\(?\s*["']([^"']+)["']/g;
const เป้าเป็นชั้นบน = (t) =>
  /(?:^|\/)(?:\.\.\/)*functions\//.test(t) ||
  /(?:^|\/)(?:\.\.\/)*edge-functions\//.test(t) ||
  /@\/(?:components|app)\//.test(t) ||
  /(?:^|\/)(?:\.\.\/)*(?:components|app)\//.test(t);

const พบ = [];
for (const p of ไฟล์) {
  if (!เป็นชั้นล่าง(p)) continue;
  const s = ตัดคอมเมนต์(readFileSync(p, "utf8"), p);
  for (const m of s.matchAll(ชี้ชั้นบน)) if (เป้าเป็นชั้นบน(m[1])) พบ.push([p, m[1]]);
}
if (!ไฟล์.length) {
  console.error("🔴 ไม่เจอไฟล์สักไฟล์ ⇒ ตะแกรงพัง ไม่ใช่ผ่าน");
  process.exit(1);
}

const ชั้นล่าง = ไฟล์.filter(เป็นชั้นล่าง).length;
console.log(
  `🔽 ชั้นล่างพึ่งชั้นบน: **${พบ.length} จุด** (เพดาน ${เพดาน}) — สแกน ${ไฟล์.length} ไฟล์ · ชั้นล่าง ${ชั้นล่าง} ไฟล์\n` +
  "   📉 เลขนี้ต้องลดลง — **อ่านเป็นหนี้ ไม่ใช่บั๊กที่ต้องแก้เดี๋ยวนี้**\n" +
  "   🔑 `await import()` ที่ใส่เพื่อ 'กันวงกลม' นับเป็นทิศกลับหัวด้วย — มันกลบอาการ ไม่ได้แก้ทิศ"
);
for (const [p, t] of พบ) console.log(`   · ${p} → ${t}`);

if (พบ.length > เพดาน) {
  console.error(
    `\n🔴 กองโตขึ้น (${พบ.length} > ${เพดาน}) ⇒ มีคนเพิ่ม import จากชั้นบนเข้าไปใน lib/\n` +
    "   ⇒ ท่าแก้: ย้ายของที่ต้องใช้ร่วมกันลงไปที่ `lib/` แล้ว **re-export ไว้ที่เดิม**\n" +
    "     ⇒ ผู้เรียกทุกตัวไม่ต้องแก้สักไฟล์ (ท่าที่ฝั่งจอใช้กับ `RowMenuItem` 20 ก.ย. 2569)"
  );
  process.exit(1);
}
if (พบ.length < เพดาน) {
  console.error(
    `\n❌ เหลือ ${พบ.length} จุด ต่ำกว่าเพดาน ${เพดาน} แล้ว ⇒ **ลดเพดานในไฟล์นี้ให้เท่ากับ ${พบ.length} ในคอมมิตเดียวกัน**\n` +
    "   (เพดานที่ไม่ตามความจริง = ช่องว่างให้กองโตขึ้นเงียบ ๆ · เลขต้องเดินลงทางเดียว)"
  );
  process.exit(1);
}
