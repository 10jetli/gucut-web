#!/bin/bash
# ประกาศ "วันหยุด deploy" — ท่านประธานสั่ง 19 ก.ย. 2569: *"วันนี้ลองไม่ใช้เครดิตทำได้ไหม ทุกส่วน"*
#
# 🔴 ที่มา: เครดิต Netlify เผา 3,965/วัน ⇒ เหลืออีก ~4.8 วัน
#    วัดจริง: **deploy = 92.2% ของเครดิตทั้งหมด** (960 จาก 1,040.7)
#    18–19 ก.ย. มี commit ขึ้น main 117 ใบ (gucut-web) + 131 ใบ (gucut-next)
#    ทั้งสองโปรเจกต์อยู่ **ทีมเดียวกัน ใช้เครดิตกองเดียวกัน**
#
# 🔑 **หยุด deploy = หยุดค่าใช้จ่าย 92% ทันที โดยไม่กระทบลูกค้าเลย**
#    เว็บที่ deploy ไว้แล้วยังเสิร์ฟอยู่ตามปกติ ลูกค้าสั่งของได้เหมือนเดิม
#
# ⚠️ **อีก 8% หยุดไม่ได้ และไม่ควรหยุด**
#    · ฟังก์ชันทำงาน 4% — งานตามเวลา 16 ตัว (ดันสต็อก · กระจกออเดอร์ · สำรองข้อมูล ·
#      กวาดเงินเข้า Beam) ปิดแล้วสต็อกเพี้ยน เงินเข้าไม่รู้ ข้อมูลไม่ถูกสำรอง
#    · คำขอ + แบนด์วิดท์ 4% — **ลูกค้าจริงเปิดเว็บ** ปิดคือปิดร้าน
#    ⇒ วันที่ไม่ deploy เลย คาดว่าเหลือราว 80–160 เครดิต/วัน แทน 3,965
#
# ใช้:  bash scripts/freeze-deploy.sh on "เหตุผล"   ประกาศหยุด
#       bash scripts/freeze-deploy.sh off            เลิกหยุด
#       bash scripts/freeze-deploy.sh                ดูสถานะ
set -u
FLAG="$HOME/.gucut-deploy-freeze"

case "${1:-status}" in
  on)
    printf '%s\n%s\n' "$(date '+%Y-%m-%d %H:%M')" "${2:-ท่านประธานสั่งหยุด deploy}" > "$FLAG"
    echo "🧊 ประกาศหยุด deploy แล้ว"
    echo "   เหตุผล: ${2:-ท่านประธานสั่งหยุด deploy}"
    echo "   ด่านก่อน push จะบล็อกทุก repo ในเครื่องนี้"
    echo "   ⚠️ ของด่วนจริง ๆ ข้ามได้ด้วย SKIP_PREPUSH=1 git push — แต่ต้องรู้ว่ากำลังจ่ายอะไร"
    ;;
  off)
    rm -f "$FLAG"
    echo "✅ เลิกหยุด deploy แล้ว — push ได้ตามปกติ"
    ;;
  *)
    if [ -f "$FLAG" ]; then
      echo "🧊 กำลังหยุด deploy อยู่"
      sed 's/^/   /' "$FLAG"
    else
      echo "✅ ไม่ได้หยุด — push ได้ตามปกติ"
    fi
    ;;
esac
