/** ไฟล์ที่ `core.mjs` import — ไล่ **สองชั้น** (core ⇒ lib ⇒ lib) เพราะ `core-*` เรียกต่อกันเอง */
function ไฟล์ที่coreเรียก() {
  const เจอ = new Set(["netlify/functions/core.mjs"]);
  const คิว = ["netlify/functions/core.mjs"];
  for (let ชั้น = 0; ชั้น < 2 && คิว.length; ชั้น++) {
    for (const f of คิว.splice(0)) {
      let s = "";
      try { s = readFileSync(f, "utf8"); } catch { continue; }
      /* ⚠️ ต้องมี `/` ปิดท้ายทั้งสองรูป — รอบแรกผมเขียน `(?:\.\.\/lib|\.\/)` **ขาดขีดหลัง lib**
           ⇒ จับได้ 1 ไฟล์ ⇒ **ด่าน "ได้น้อยผิดปกติ ⇒ ตก" ที่เพิ่งใส่จับได้ทันที**
           ⇒ ⇒ ถ้าไม่มีด่านนั้น ไฟล์นี้จะเขียนรายชื่อสั้น ๆ แล้วจอจะขึ้น "ไม่รู้" ทั้งกระดาน */
      for (const m of s.matchAll(/["'`](?:\.\.\/lib\/|\.\/)([a-z0-9-]+)\.mjs["'`]/g)) {
        const p = `netlify/lib/${m[1]}.mjs`;
        if (!เจอ.has(p) && existsSync(p) && !ยกเว้นขาออก.test(p)) { เจอ.add(p); คิว.push(p); }
      }
    }
  }
  return [...เจอ].sort();
}
