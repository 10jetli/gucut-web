/* `...(cond ? { a: 1, b } : {})` และ `...(cond && { a: 1 })` */
const รูปคีย์มีเงื่อนไข = /\.\.\.\(\s*[^?&]{0,120}?(?:\?\s*\{|&&\s*\{)([^{}]{0,300})\}/g;

/** ชื่อคีย์จากเนื้อใน `{ … }` — รับทั้ง `k: v`, `k`, `"ไทย มีช่องว่าง": v` */
function ชื่อคีย์จากบล็อก(เนื้อ) {
  const ออก = [];
  for (const ส่วน of เนื้อ.split(",")) {
    const t = ส่วน.trim();
    if (!t) continue;
    const m = /^("([^"]{1,80})"|'([^']{1,80})'|([A-Za-z_$][\w$]*))\s*(?::|$)/.exec(t);
    if (m) ออก.push(m[2] ?? m[3] ?? m[4]);
  }
  return ออก;
}

