/* สร้าง netlify/lib/endpoints.mjs จาก "ซอร์สจริงของ core.mjs" ตอน build
 *
 * 🔴 ที่มา (18 ก.ย. 2569): ฝั่งจอเจอเส้น `list=channel-gaps` ที่ **ไม่มีจอไหนใช้เลย**
 *    และเป็นเรื่องเงิน (91 รหัสที่เคยขายได้บนช่องทางนั้นแล้วเงียบ ทั้งที่มีของในคลัง 96,944 ชิ้น)
 *    วิธีที่เขาค้นพบคือ **ยิงชื่อมั่วโดยบังเอิญ** แล้วเห็น `accepts` ในข้อความ 400
 *    ⇒ ท่อมีของที่ไม่มีใครรู้ว่ามี และวิธีค้นพบคือความบังเอิญ — นั่นคือปัญหาของฝั่งท่อ
 *
 * 🔴 และรายชื่อ `known` ที่เคยใช้เขียนข้อความ 400 **ล้าสมัยแล้วจริง** (พิสูจน์วันเดียวกัน):
 *    เทียบกับ `get("list") === "…"` ในซอร์ส พบ `returns-inbox` มีอยู่จริงแต่ไม่อยู่ในรายชื่อ
 *    ⇒ ถ้าฝั่งจอทำด่าน "จอใช้ทุกเส้นหรือยัง" โดยเชื่อรายชื่อนั้น **จะพลาดเส้นนี้เงียบ ๆ**
 *    🔑 รายชื่อที่คนเติมด้วยมือ จะล้าสมัยเสมอ — ให้อ่านจากซอร์สที่ทำงานจริงแทน
 *
 * ⚠️ **ห้ามเอารายชื่อนี้ไปใช้ตัดสินว่าเส้นไหนเปิด/ปิด** — คอมเมนต์เดิมใน core.mjs เตือนไว้แล้วว่า
 *    การตัดสินใจอยู่ที่ "มาถึงบรรทัดท้ายสุด = ไม่รู้จัก" ไม่ใช่ที่รายชื่อ
 *    ถ้าย้ายไปเช็คกับรายชื่อ วันที่ตัวสร้างนี้อ่านไม่เจอหนึ่งชื่อ = **ปิดเส้นที่ใช้งานอยู่ทันที**
 *    ⇒ ตัวนี้มีไว้ทำสองอย่างเท่านั้น: เขียนข้อความบอกทาง · ให้ด่านฝั่งจอเทียบ
 * ⚠️ อ่านไม่เจอสักชื่อ = การอ่านพัง ไม่ใช่ "ไม่มีเส้น" ⇒ โยน error ให้ build ตก ห้ามเขียนไฟล์ว่าง
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ราก = join(dirname(fileURLToPath(import.meta.url)), "..");
const ต้นทาง = join(ราก, "netlify", "functions", "core.mjs");
const ปลายทาง = join(ราก, "netlify", "lib", "endpoints.mjs");

const src = readFileSync(ต้นทาง, "utf8");
/* ตัดคอมเมนต์ก่อนค้นเสมอ — ชื่อเส้นถูกพูดถึงในคำอธิบายเยอะมาก
   (บทเรียนวันเดียวกัน: ตัวตรวจที่อ่านซอร์สดิบจะจับข้อความในคอมเมนต์) */
const code = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

const ชื่อ = new Set();
for (const m of code.matchAll(/get\("list"\)\s*===\s*"([a-z-]+)"/g)) ชื่อ.add(m[1]);
for (const m of code.matchAll(/listArg\s*===\s*"([a-z-]+)"/g)) ชื่อ.add(m[1]);

/* 🔴 **`list=` ไม่ใช่รูปเดียวของเส้นในท่อ** — จับได้ทันทีที่สร้างตัวนี้เสร็จ (18 ก.ย. 2569)
   อีกสายเพิ่ม `?skuaudit=1` ในชั่วโมงเดียวกัน ⇒ รายชื่อ `lists` ไม่ขยับเลย
   ⇒ ถ้าส่งแค่ `lists` ให้ด่านฝั่งจอ เขาจะเชื่อว่าครอบทุกเส้น แล้ว **พลาดเส้นทั้งกองนี้**
     = ครอบไม่ครบแล้วรายงานเหมือนครอบครบ ซึ่งเป็นกับดักที่ทีมเจอซ้ำที่สุด
   ⇒ เก็บกองที่สองด้วย: เส้นที่เปิดด้วยพารามิเตอร์ของตัวเอง (`get("xxx")` ใน if)
   ⚠️ กองนี้ **หยาบกว่า** กองแรกโดยธรรมชาติ เพราะ `get()` ถูกใช้อ่านค่าตัวกรองด้วย
      ⇒ ตัดชื่อที่รู้ว่าเป็นตัวกรองออก และเขียนกำกับว่าเป็น "รายชื่อคร่าว ๆ ต้องดูด้วยตา"
      **ห้ามเอาไปนับเป็นจำนวนเส้นที่แน่นอน** */
const ตัวกรองที่ไม่ใช่เส้น = new Set([
  "list", "store", "q", "limit", "offset", "page", "days", "from", "to", "status", "sku",
  "reason", "channel", "platform", "type", "keyword", "source", "only", "full", "detail",
  "amountmax", "amountmin", "carrier", "cat", "category", "day", "confirm", "force",
]);
/* 🔴 **19 ก.ย. 2569 — ตัวกวาดนี้เคยมองเห็นแค่ `.get()` แล้วพลาดเส้นทั้งกอง 19 เส้น**
   วัดจริงตอนเพิ่มเส้น `?envcheck=1`: เส้นใหม่ไม่โผล่ในสารบัญเลย ⇒ ไล่ดูจึงพบว่า
   เส้นที่เขียนด้วย `if (url.searchParams.has("x"))` **หลุดทั้งหมด 19 จาก 19**
   ในนั้นมี `deleteproduct` ซึ่งเป็นเส้นที่ **ลบของจริง**
   🔑 คลาส: **ครอบไม่ครบแล้วรายงานเหมือนครอบครบ** — ซึ่งเป็นสิ่งที่คอมเมนต์ข้างบนนี้
      เขียนไว้เองว่ากลัว แล้วตัวมันเองก็เป็นเสียเอง เพราะผูกกับ *รูปการเขียน* ไม่ใช่ *เจตนา*
   ⇒ แก้สองชั้น: (ก) กวาดทั้ง `.get()` และ `.has()`
      (ข) **ถ้าเจอรูปการอ่านแบบใหม่ที่ตัวกวาดไม่รู้จัก ให้ build ตก** ไม่ใช่ข้ามเงียบ ๆ
      (ถ้าไม่มีข้อ ข วันที่ใครเขียน `.getAll()` หรือ `.entries()` เราจะพลาดอีกแบบเดิม) */
const รูปที่ตัวกวาดรู้จัก = new Set(["get", "has"]);
const เส้นพารามิเตอร์ = new Set();
for (const m of code.matchAll(/if \(url\.searchParams\.(get|has)\("([a-zA-Z][a-zA-Z0-9_]*)"\)/g)) {
  if (!ตัวกรองที่ไม่ใช่เส้น.has(m[2])) เส้นพารามิเตอร์.add(m[2]);
}
const รูปที่ไม่รู้จัก = [
  ...new Set(
    [...code.matchAll(/if \(url\.searchParams\.([A-Za-z]+)\(/g)]
      .map((m) => m[1])
      .filter((ชื่อ) => !รูปที่ตัวกวาดรู้จัก.has(ชื่อ)),
  ),
].sort();
if (รูปที่ไม่รู้จัก.length) {
  throw new Error(
    "gen-endpoints: เจอรูปการอ่านพารามิเตอร์ที่ตัวกวาดไม่รู้จัก: " + รูปที่ไม่รู้จัก.join(", ") + "\n" +
    "  ⇒ เส้นที่เขียนด้วยรูปนี้จะ **หลุดจากสารบัญแบบเงียบ ๆ** แล้วด่านฝั่งจอจะเชื่อว่าครอบครบ\n" +
    "  ⇒ เพิ่มรูปนั้นลง `รูปที่ตัวกวาดรู้จัก` และแก้ regex ให้รับด้วย (เคยพลาดมาแล้ว 19 เส้น 19 ก.ย. 2569)",
  );
}

/* 🔖 **ช่องที่แต่ละตัวเขียน "รับเข้า"** — ฝั่งจอขอ 18 ก.ย. 2569 คืนเดียวกับที่เจอสามใบติด:
     ท่อรับ weight/size/tag ได้ แต่จอเขียนว่า "ท่อยังไม่มีช่องนี้" · ท่อรับ number/day/cod ได้ แต่ฟอร์มไม่มีช่อง
     ท่อส่ง countExcludingVoided มาแล้ว แต่จอไม่รู้จึงไปขอของใหม่
   🔑 ทั้งสามคือ **ของที่ซื้อมาแล้วไม่ได้แกะกล่อง** — ไม่มีอะไรพัง ไม่มีอะไรฟ้อง
      และ **หาไม่เจอด้วยการอ่านโค้ดฝั่งตัวเอง** ต้องเอาสองฝั่งมาวางเทียบกัน
   ⚠️ **กองนี้หยาบ** — regex เก็บ `o.xxx` ในตัวฟังก์ชัน ซึ่งปนกับตัวช่วยที่ถูกฉีดเข้ามาทดสอบ
      (เช่น o.coreQuery · o.archiveSlips) ⇒ ตัดชื่อที่รู้ว่าเป็นตัวช่วยออก แต่ไม่รับประกันว่าสะอาด
      ⇒ ใช้เป็น "รายการที่ต้องดูด้วยตา" ห้ามนับเป็นสัญญาของ API */
const ตัวช่วยที่ฉีดเข้ามา = new Set(["coreQuery", "archiveSlips", "now", "fetch", "store", "log", "signal"]);
const writeFields = {};
try {
  const w = readFileSync(join(ราก, "netlify", "lib", "zort-write.mjs"), "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
  const หัว = [...w.matchAll(/export async function (zort[A-Za-z]+)\s*\(/g)];
  for (let i = 0; i < หัว.length; i++) {
    const เริ่ม = หัว[i].index;
    const จบ = i + 1 < หัว.length ? หัว[i + 1].index : w.length;
    const body = w.slice(เริ่ม, จบ);
    const f = [...new Set([...body.matchAll(/\bo\.([A-Za-z_][\w]*)/g)].map((m) => m[1]))]
      .filter((x) => !ตัวช่วยที่ฉีดเข้ามา.has(x))
      .sort();
    if (f.length) writeFields[หัว[i][1]] = f;
  }
} catch {
  /* อ่านไม่ได้ ⇒ ปล่อยว่าง แล้วให้ปลายทางส่ง null — ไม่ทำให้ build ตก
     เพราะกองนี้เป็นของเสริม ต่างจาก `lists` ที่เป็นสารบัญหลัก */
}

if (!ชื่อ.size) {
  throw new Error(
    "gen-endpoints: อ่าน core.mjs ไม่เจอเส้น list สักเส้น — รูปโค้ดเปลี่ยนไปแล้วหรือ path ผิด\n" +
    "  (ห้ามเขียนไฟล์ว่าง: รายชื่อว่างอ่านได้ว่า 'ท่อไม่มีเส้นเลย' ซึ่งดูเหมือนคำตอบที่สมบูรณ์)"
  );
}

const เรียง = [...ชื่อ].sort();
writeFileSync(
  ปลายทาง,
  "// ⚠️ ไฟล์นี้ถูกสร้างอัตโนมัติโดย scripts/gen-endpoints.mjs — ห้ามแก้มือ\n" +
  "// ที่มาของรายชื่อ: `get(\"list\") === \"…\"` ในซอร์สของ netlify/functions/core.mjs (แหล่งเดียว)\n" +
  "// 🚫 ห้ามเอาไปใช้ตัดสินว่าเส้นไหนเปิด/ปิด — ใช้เขียนข้อความบอกทาง และให้ด่านฝั่งจอเทียบเท่านั้น\n" +
  `export const generatedAt = ${JSON.stringify(new Date().toISOString())};\n` +
  `export const source = ${JSON.stringify('netlify/functions/core.mjs (get("list") === "…")')};\n` +
  `export const lists = ${JSON.stringify(เรียง, null, 1)};\n` +
  "// ⚠️ กองนี้ **หยาบกว่า** lists — มาจาก `if (url.searchParams.get(\"xxx\"))` ซึ่งปนกับตัวกรองได้\n" +
  "//    ใช้เป็น 'รายการที่ต้องดูด้วยตา' ห้ามนับเป็นจำนวนเส้นที่แน่นอน\n" +
  `export const paramRoutes = ${JSON.stringify([...เส้นพารามิเตอร์].sort(), null, 1)};\n` +
  "// ⚠️ ช่องที่ตัวเขียนของ ZORT รับเข้า — **หยาบ** (regex เก็บ o.xxx) ใช้ดูด้วยตา ห้ามถือเป็นสัญญา API\n" +
  `export const writeFields = ${JSON.stringify(writeFields, null, 1)};\n`
);
console.log(`gen-endpoints: list ${เรียง.length} เส้น · เส้นพารามิเตอร์ (หยาบ) ${เส้นพารามิเตอร์.size} ชื่อ → netlify/lib/endpoints.mjs`);
