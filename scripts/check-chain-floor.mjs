// ด่าน: **จำนวนด่านในสาย build ต้องไม่ลดลงเงียบ ๆ**
//
// 🔴 ที่มา 14 ต.ค. 2569 — ฝั่งจอวัดฝั่งตัวเองก่อน แล้วเตือนว่าฝั่งนี้น่าจะมีรูเดียวกัน:
//    *"ตัวนับที่อยู่ในของที่มันนับ หายไปพร้อมกับของที่มันนับ"*
//    ตรวจแล้วมีจริง: `check-gate-selfcontrol` มีพื้นแค่ `< 5` ซึ่งเป็นด่านกัน **ตะแกรงพัง**
//    ไม่ใช่ด่านกัน **สายหด** ⇒ 25 ตัวหดเหลือ 5 ได้โดยเขียวสนิท · และตัวมันเองก็อยู่ในสาย
//
// 🔑 จึงต้องถูกเรียกจาก **ฮุค pre-push เท่านั้น** (อยู่นอกสาย) — รูปเดียวกับ `check-test-floor`
// ⚠️ ขอบเขตที่ปิดไม่ได้ และเขียนไว้โดยตั้งใจ: ถอดบรรทัดที่เรียกตัวนี้ออกจากฮุค ⇒ เงียบเหมือนกัน
//    `check-hook-installed` จับ "ฮุคไม่ตรงรีโป" ได้ แต่ไม่จับ "รีโปแก้ฮุคให้หลวม"
//    ⇒ **ชั้นสุดท้ายยังเป็นคน** — ประกาศดีกว่าให้คนคิดว่าปิดครบ
// ⬜ สามสถานะ: อ่านไฟล์พื้น/package.json ไม่ได้ ⇒ **"คุมไม่ได้รอบนี้" ไม่ใช่ "ผ่าน"**
import { readFileSync, writeFileSync } from "node:fs";

const FLOOR_FILE = process.argv[2] || "scripts/lib/พื้นจำนวนด่านในสาย.json";
const PKG = process.argv[3] || "package.json";

let f;
try { f = JSON.parse(readFileSync(FLOOR_FILE, "utf8")); }
catch { console.log(`   ⬜ คุมไม่ได้รอบนี้: อ่าน ${FLOOR_FILE} ไม่ได้ (ช่องว่าง ไม่ใช่ผลผ่าน)`); process.exit(0); }

const พื้น = Number(f["สูงสุดที่เคยเห็น"]);
const คำนำหน้า = f["_คำนำหน้าที่นับ"];
const สายที่นับ = f["_สายที่นับ"];
if (!Number.isFinite(พื้น) || !Array.isArray(คำนำหน้า) || !Array.isArray(สายที่นับ)) {
  console.log(`   ⬜ คุมไม่ได้รอบนี้: ไฟล์พื้นขาดค่าที่ต้องใช้ตัดสิน (พื้น/คำนำหน้า/สาย)`); process.exit(0);
}

let pkg;
try { pkg = JSON.parse(readFileSync(PKG, "utf8")); }
catch { console.log(`   ⬜ คุมไม่ได้รอบนี้: อ่าน ${PKG} ไม่ได้`); process.exit(0); }

// นับ **ชื่อไม่ซ้ำ** ไม่ใช่จำนวนครั้งที่ปรากฏ — ชื่อเดิมโผล่สองครั้งในสายได้ (เช่นมี --self-test)
// 🔑 ฝั่งจอเหยียบข้อนี้ 14 ต.ค.: ตัวทดสอบเขา **คาดเลขจากสูตร** (153−3) แต่ของจริง 151 เพราะชื่อซ้ำ
const สาย = สายที่นับ.map((k) => String(pkg?.scripts?.[k] ?? "")).join(" ");
const คำ = คำนำหน้า.map((p) => p.replace("-", "")).join("|");
/* 🔴 **ห้ามใช้ `\w` ในตะแกรงชื่อไฟล์** — `\w` ไม่ครอบอักขระไทย
 *    ⇒ ด่านชื่อ `check-ชื่อไทย.mjs` จะถูกมองไม่เห็น ⇒ **สายหดโดยด่านไม่รู้ตัว**
 *    (เคสร่วมจับผมได้ทันทีด้วยฟิกซ์เจอร์ชื่อไทย — ผมไม่ได้ตั้งใจทดสอบเรื่องนี้)
 *    ⇒ ใช้ "อะไรก็ได้ที่ไม่ใช่ตัวคั่นคำสั่ง/ช่องว่าง" แทน · คลาส `lesson-with-a-narrow-signature…` */
const ชื่อ = new Set([...สาย.matchAll(new RegExp(String.raw`scripts/((?:${คำ})-[^\s&|;"'<>]+)\.mjs`, "g"))].map((m) => m[1]));
const n = ชื่อ.size;

if (n < 5) {
  console.log(`❌ อ่านรายชื่อด่านจากสายได้แค่ ${n} ตัว ⇒ **ตะแกรงพัง ไม่ใช่สายว่าง** (เกณฑ์นี้คนละอันกับพื้น)`);
  process.exit(1);
}

const ป้าย = `ด่านในสาย ${สายที่นับ.join("/")} = ${n} · พื้นที่เคยเห็น ${พื้น} (${f["วันที่"] ?? "ไม่ทราบวันที่"})`;

if (n >= พื้น) {
  if (n > พื้น) {
    f["สูงสุดที่เคยเห็น"] = n;
    f["วันที่"] = new Date(Date.now() + 7 * 3600e3).toISOString().slice(0, 10);
    f["เหตุที่ลด"] = null;
    writeFileSync(FLOOR_FILE, JSON.stringify(f, null, 2) + "\n");
    console.log(`   📈 ${ป้าย} ⇒ ยกพื้นขึ้นเป็น ${n} แล้ว (แก้ไฟล์ ${FLOOR_FILE} — commit ตามไปด้วย)`);
  } else {
    console.log(`   ✅ ${ป้าย}`);
  }
  process.exit(0);
}

const ลด = f["เหตุที่ลด"];
if (ลด && Number(ลด["ถึงจำนวน"]) === n && String(ลด["เหตุ"] ?? "").trim().length >= 10) {
  console.log(`   🔸 ${ป้าย} ⇒ **ลดโดยตั้งใจ** ${ลด["วันที่"] ?? ""}: ${ลด["เหตุ"]}`);
  process.exit(0);  // 🚫 ห้ามเขียนพื้นลง — ตัวตรวจที่เขียนไฟล์ที่มันตรวจ ต้องเขียนทิศเดียว
}

console.log(`❌ ไม่ผ่านด่านจำนวนด่านในสาย — ไม่ push`);
console.log(`   ${ป้าย} ⇒ **หายไป ${พื้น - n} ตัว**`);
console.log(`   🔑 ด่าน "ตก" กับด่าน "หายจากสาย" คนละเรื่อง — exit code จับได้แค่ด่านที่ตก`);
console.log(`   ไล่ดู: มีใครถอดชื่อออกจาก scripts.${สายที่นับ.join("/")} ใน package.json ไหม ·`);
console.log(`          เปลี่ยนชื่อไฟล์ด่านแล้วไม่แก้สายไหม · ย้ายด่านไปอยู่นอกสายโดยตั้งใจไหม`);
if (ลด) console.log(`   ⚠️ ไฟล์พื้นมี เหตุที่ลด แต่ ถึงจำนวน=${ลด["ถึงจำนวน"]} ไม่ตรงของจริง ${n} (หรือเหตุสั้นกว่า 10 อักขระ)`);
else console.log(`   ลดจริงต้องตั้ง เหตุที่ลด ใน ${FLOOR_FILE} ⇒ { ถึงจำนวน: ${n}, เหตุ: "...", วันที่: "..." }`);
process.exit(1);
