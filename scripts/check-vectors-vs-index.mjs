#!/usr/bin/env node
/* 🖼️ **ลายนิ้วมือรูป (`img-vectors.bin`) ต้องเรียงตรงกับ `items` ใน `search-index.json`**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ฝั่งจอเจอ "ชนิดที่ห้า" ของพาธในคู่มือ: **พาธที่ต้องอยู่ด้วยกัน**
 *    ⇒ `existsSync` ตอบ ✅ ได้ทั้งที่ของพัง ⇒ ผมส่องฝั่งนี้แล้วเจอชนิดที่หนักกว่า:
 *    **"ต้องตรงกันเป๊ะ"** — ทั้งสองไฟล์มีอยู่ แต่ **เนื้อไม่สอดคล้องกัน** ⇒ พังเงียบ
 *
 * 📏 กวาด `CLAUDE.md` แล้วพบกติกาชนิดนี้ **3 คู่** · มีด่านคุมแล้ว **2 คู่** (`check-twin-tables`):
 *    `LADDER` (ขั้นบันไดขนาดรูป) · ตารางค่าส่ง 12 ขั้น
 *    🔴 **คู่ที่สามไม่มีใครคุม** — และคู่มือเขียนผลไว้ตรง ๆ ว่า **"ผลค้นหาจะสลับตัวกันมั่ว"**
 *    ⇒ ⇒ อาการ: ลูกค้าถ่ายรูปอะไหล่ **ได้สินค้าผิดตัวแบบดูน่าเชื่อ** — ไม่มี error ไม่มีจอแดง
 *
 * 🚫 **ขอบเขต: ด่านนี้จับได้ทิศเดียว**
 *    จำนวนไม่เท่ากัน ⇒ **ผิดแน่นอน** · จำนวนเท่ากัน ⇒ **ยังไม่รู้ว่าเรียงตรงกันไหม**
 *    (สลับลำดับโดยจำนวนเท่าเดิม ด่านนี้มองไม่เห็น) ⇒ ⇒ **เขียวที่นี่ = "ไม่พบความไม่ตรง"**
 *    ไม่ใช่ "เรียงตรงกัน" · เรื่องลำดับพิสูจน์ได้ทางเดียวคือสร้างใหม่แล้วเทียบไบต์
 *
 * ใช้: node scripts/check-vectors-vs-index.mjs
 */
import { readFileSync, statSync } from "node:fs";

const ไฟล์บิน = "public/img-vectors.bin";
const ไฟล์ดัชนี = "public/search-index.json";

let bin, ดัชนี;
try { bin = readFileSync(ไฟล์บิน); } catch (e) {
  console.error(`🔴 อ่าน ${ไฟล์บิน} ไม่ได้: ${String(e?.message || e).slice(0, 100)}`);
  console.error("   ⇒ **ยังไม่ได้ตรวจ ไม่ใช่ผ่าน** (ไฟล์นี้ต้องมีเพื่อให้ปุ่มกล้องทำงาน)");
  process.exit(1);
}
try { ดัชนี = JSON.parse(readFileSync(ไฟล์ดัชนี, "utf8")); } catch (e) {
  console.error(`🔴 อ่าน ${ไฟล์ดัชนี} ไม่ได้: ${String(e?.message || e).slice(0, 100)} ⇒ ยังไม่ได้ตรวจ`);
  process.exit(1);
}
const items = Array.isArray(ดัชนี) ? ดัชนี : (ดัชนี.items ?? null);
if (!Array.isArray(items)) {
  console.error(`🔴 ${ไฟล์ดัชนี} ไม่มีอาเรย์ \`items\` ⇒ **รูปแบบเปลี่ยน ⇒ ตรวจไม่ได้** (ไม่ใช่ผ่าน)`);
  process.exit(1);
}
if (bin.length < 6) {
  console.error(`🔴 ${ไฟล์บิน} สั้นกว่าหัวไฟล์ (${bin.length} ไบต์) ⇒ ไฟล์เสีย`);
  process.exit(1);
}

/* หัวไฟล์ตาม `gen-img-vectors.mjs`: [0..3] uint32 จำนวน · [4..5] uint16 มิติ · แล้ว Int8 ต่อค่า */
const จำนวนในหัว = bin.readUInt32LE(0);
const มิติ = bin.readUInt16LE(4);
const ขนาดที่ควรเป็น = 6 + จำนวนในหัว * มิติ;

const ปัญหา = [];
if (มิติ <= 0 || มิติ > 4096) ปัญหา.push(`มิติในหัวไฟล์ = ${มิติ} ⇒ ไม่สมเหตุสมผล ⇒ หัวไฟล์เสียหรือรูปแบบเปลี่ยน`);
if (bin.length !== ขนาดที่ควรเป็น) {
  ปัญหา.push(
    `ขนาดไฟล์ไม่ตรงกับหัวไฟล์: ของจริง ${bin.length} ไบต์ · ควรเป็น ${ขนาดที่ควรเป็น} ` +
    `(6 + ${จำนวนในหัว}×${มิติ}) ⇒ ไฟล์ถูกตัดกลางทาง หรือสร้างไม่จบ`
  );
}
if (จำนวนในหัว !== items.length) {
  ปัญหา.push(
    `จำนวนเวกเตอร์ (${จำนวนในหัว}) ≠ จำนวน items ในดัชนี (${items.length}) ` +
    `⇒ **ลายนิ้วมือกับรายชื่อสินค้าคนละชุด** ⇒ ผลค้นหาด้วยรูปจะชี้ผิดตัว ` +
    `⇒ แก้ด้วย: node scripts/gen-img-vectors.mjs (ใช้เวลา ~4 นาที) แล้ว commit ไฟล์ .bin ตามไปด้วย`
  );
}

console.log(
  `🖼️ ลายนิ้วมือรูป ↔ ดัชนีค้นหา: เวกเตอร์ **${จำนวนในหัว}** · items **${items.length}** · มิติ ${มิติ} · ` +
  `${(statSync(ไฟล์บิน).size / 1048576).toFixed(2)} MB\n` +
  "   🚫 เขียวที่นี่ = **ไม่พบความไม่ตรง** ไม่ใช่ \"เรียงตรงกัน\" — สลับลำดับโดยจำนวนเท่าเดิม ด่านนี้มองไม่เห็น\n" +
  "   ⇒ เรื่องลำดับพิสูจน์ได้ทางเดียวคือ **สร้างใหม่แล้วเทียบไบต์** (~4 นาที ⇒ ไม่เหมาะกับทุก build)"
);
if (ปัญหา.length) {
  console.error("\n🔴 " + ปัญหา.join("\n🔴 "));
  process.exit(1);
}
