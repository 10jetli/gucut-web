#!/usr/bin/env node
/* 🧩 **ตัวช่วยทุกตัวใน `scripts/lib/` ต้องโหลดขึ้นได้จริง** — ไม่ใช่แค่ไวยากรณ์ถูก
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ผมแก้ `gen-zort-arch.mjs` ให้ใช้ `fileURLToPath()` แล้ว **ลืมใส่ `import`**
 *    ⇒ **เทส 709 ผ่าน · `node --check` ผ่าน · ตัวสร้างพังสนิทด้วย `ReferenceError`**
 *    เพราะด่านที่มีอยู่ตรวจ **ข้อความในซอร์ส** ไม่ได้ **โหลดโมดูลจริง**
 *    ⇒ จับได้เพราะ build ตกที่ขั้นอื่นโดยบังเอิญ ⇒ ถ้าไฟล์นั้นไม่อยู่ในสาย **จะไม่มีอะไรฟ้องเลย**
 *
 * 🔑 ฝั่งจอวัดกองเดียวกันแล้วเจอของที่หนักกว่า: ตัวช่วย **3 ใน 7 ไม่เคยถูกรันเลย**
 *    และหนึ่งในนั้นคือ `ปลูกแล้ววัด.mjs` = **เครื่องมือที่สองรีโปใช้พิสูจน์ว่าด่านจับบั๊กได้**
 *    ⇒ ⇒ ถ้ามันพังเงียบ **เราจะพิสูจน์อะไรไม่ได้ทั้งสองฝั่ง และไม่มีอะไรบอก**
 *
 * 📏 ฝั่งนี้วัดแล้ว: `scripts/lib/` มี 10 ตัว · ตัวที่ถูกเรียกเฉพาะ **เป็น subprocess ตอนปลูก**
 *    (`ยืนยันคำตอบดีของท่อปลอม.mjs`) ไม่ถูกโหลดในสายรันปกติเลย
 *
 * 🚫 **ขอบเขต: ครอบแค่ระดับบนสุดของโมดูล** — `ReferenceError` ที่ซ่อนอยู่ในฟังก์ชัน
 *    ที่ไม่มีใครเรียก **ยังหลุดได้** ⇒ ทางแก้ของเรื่องนั้นคือ **เรียกมันจริงในเทส** ไม่ใช่ด่านนี้
 * 🚫 และด่านนี้ **ไม่รับประกันว่าตัวช่วยทำงานถูก** — แค่ว่ามัน "ขึ้นได้"
 *
 * ใช้: node scripts/check-lib-loads.mjs
 */
import { readdirSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

const ราก = "scripts/lib";
let ไฟล์;
try {
  ไฟล์ = readdirSync(ราก).filter((n) => n.endsWith(".mjs"));
} catch (e) {
  console.error(`🔴 อ่าน ${ราก} ไม่ได้: ${String(e?.message || e).slice(0, 120)} ⇒ **ยังไม่ได้ตรวจ ไม่ใช่ผ่าน**`);
  process.exit(1);
}
if (!ไฟล์.length) {
  console.error(`🔴 ไม่เจอไฟล์ใน ${ราก} สักไฟล์ ⇒ ตะแกรงพัง ไม่ใช่ผ่าน`);
  process.exit(1);
}

const พัง = [];
for (const ชื่อ of ไฟล์) {
  try {
    /* 🔑 ต้องเป็น `pathToFileURL` ไม่ใช่พาธเปล่า — ชื่อไฟล์ไทยจะพังบน import() ถ้าไม่แปลง
       (คลาสเดียวกับที่ `.pathname` ทำให้ `gen-zort-arch` พัง) */
    await import(pathToFileURL(resolve(ราก, ชื่อ)).href);
  } catch (e) {
    พัง.push({ ชื่อ, ชนิด: e?.constructor?.name ?? "Error", เหตุ: String(e?.message || e).slice(0, 160) });
  }
}

console.log(
  `🧩 โหลดตัวช่วยใน ${ราก}: **${ไฟล์.length - พัง.length}/${ไฟล์.length} ขึ้นได้**` +
  "\n   🚫 เขียวที่นี่ = **โมดูลขึ้นได้** ไม่ใช่ 'ตัวช่วยทำงานถูก' · และครอบแค่ระดับบนสุดของโมดูล" +
  "\n   🔑 มีไว้จับคลาส: ลืม `import` ⇒ `ReferenceError` ตอนโหลด ซึ่ง `node --check` **มองไม่เห็น**"
);
if (พัง.length) {
  console.error(
    `\n🔴 โหลดไม่ขึ้น ${พัง.length} ตัว:\n` +
    พัง.map((x) => `   · ${x.ชื่อ} — **${x.ชนิด}**: ${x.เหตุ}`).join("\n") +
    "\n   ⇒ `ReferenceError` = ลืม import (คนละทางแก้กับ `SyntaxError` ซึ่งเป็นไวยากรณ์)"
  );
  process.exit(1);
}
