#!/usr/bin/env node
/* 🔑 ยิงตรวจว่า **คีย์ที่ท่อสัญญากับจอไว้ มีอยู่จริงบน production** — รันหลัง deploy ทุกครั้ง
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — วันนี้เจอสองรอบว่า "เขียนเสร็จ" ไม่เท่ากับ "จอได้ของ"
 *    ① ผม push ช่องอัตราเผาขึ้นไป แล้ว **ทางแคชคืนก้อนเก่าที่ไม่มีคีย์นั้น**
 *      ⇒ ฝั่งจอยิงตรวจแล้วไม่เจอคีย์ ⇒ **แยกไม่ออกจาก "ท่อยังไม่ได้ deploy"**
 *    ② ผมบอกฝั่งจอว่า "ประกาศครบ 24 เส้นแล้ว" ทั้งที่ยัง push ไม่ขึ้น ⇒ เขายิงเจอ 4 จาก 24
 *    ⇒ 🔑 **สามขั้นที่ตกลงกันแล้ว: เขียนเสร็จ / push แล้ว / ยิงตรวจ production แล้ว**
 *      ตัวนี้คือขั้นที่สาม · ไม่มีขั้นนี้ เราจะรายงานว่า "เสร็จ" ด้วยความหมายที่ฝั่งจอใช้ไม่ได้
 *
 * 🚫 **ตัวนี้ไม่ตรวจว่าค่าถูกหรือไม่ถูก** — ตรวจแค่ว่า "คีย์มีอยู่"
 *    เพราะปัญหาที่กัดเราซ้ำ ๆ คือ **คีย์หายไปทั้งคีย์** แล้ว `?? null` ฝั่งจอกลืนความต่างไป
 *    ⇒ ค่าที่ถูกเป็นหน้าที่ของ `verify-claims.mjs` และเทสในเครื่อง
 *
 * ใช้: node scripts/verify-contract-keys.mjs
 */
import { readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

let KEY = "";
try {
  KEY = readFileSync(join(homedir(), ".gucut-admin-key"), "utf8").trim();
} catch {
  console.error("❌ อ่าน ~/.gucut-admin-key ไม่ได้ — **ตรวจไม่ได้ทั้งชุด ไม่ใช่ 'ผ่าน'**");
  process.exit(2);
}
const SITE = process.env.SITE || "https://gucut.com";

/** คีย์ที่สัญญาไว้กับฝั่งจอ — **เพิ่มทุกครั้งที่ตกลงคีย์ใหม่กัน**
 *  `ต้องมีคีย์` = ต้องมีอยู่จริง (ค่าเป็นอะไรก็ได้ รวมทั้ง null/0/{}/[] )
 *  ⚠️ เขียน `ที่มา` กำกับว่าใครขอและเมื่อไหร่ ⇒ วันไหนอยากถอด จะรู้ว่าต้องไปคุยกับใคร */
const สัญญา = [
  {
    ชื่อ: "อัตราเผาเครดิต (ป้ายบนทุกจอ)",
    path: "/api/core?x=ไม่มีจริง",   // ไม่ใช้ — ดูข้างล่าง
    ข้าม: true,
  },
  {
    ชื่อ: "เครดิต Netlify",
    path: "/api/netlify-credits",
    ต้องมีคีย์: ["used", "plan", "burnPerDay", "daysLeft", "burnWindowHours", "ตัวอย่างล่าสุดเมื่อ", "ตัวอย่างเก่าเกินชั่วโมง"],
    ที่มา: "ฝั่งจอขอ 19 ก.ย. 2569 — ป้ายเครดิตเปลี่ยนสีตาม daysLeft · เกณฑ์ต้องมาจากท่อ",
  },
  {
    ชื่อ: "ฟีดใบคืนสินค้า",
    path: "/api/returns-feed",
    ต้องมีคีย์: ["list", "unreadable", "qtyUnreadableLines", "qtyZeroLines", "priceUnreadableLines"],
    ที่มา: "ฝั่งจอเตรียมช่องรับไว้ 19 ก.ย. 2569 — แยก 'ท่อยังไม่ส่ง' จาก 'ส่งแล้วและเป็นศูนย์'",
  },
  {
    ชื่อ: "สัญญาของเส้น list= (ตัวอย่าง purchases)",
    path: "/api/core?list=purchases&limit=1",
    ต้องมีคีย์: ["limitClamped"],
    ต้องมีคีย์ซ้อน: { "สัญญาของเส้นนี้": ["ไล่หน้า", "ต้องมี", "ตัวกรองที่รับ", "ตัวกรองที่รับ—ที่มา"] },
    /* 🔴 **"คีย์มีอยู่" เป็นคำถามที่อ่อนเกินไปสำหรับคีย์นี้** (เพิ่ม 19 ก.ย. 2569)
       ผมตรวจแค่คีย์มีอยู่ ⇒ **ผ่าน** ⇒ รายงานฝั่งจอว่า "จอได้ของแล้ว"
       ⇒ ฝั่งจอยิงตรวจ **ค่า** แล้วเจอว่าทั้ง 24 เส้นเป็น `null` (ตารางไม่ถูกรวมเข้าฟังก์ชัน)
       ⇒ 🔑 **ผมตรวจผ่านในขณะที่ของยังใช้ไม่ได้** — คำถามผิด ไม่ใช่ตัวตรวจพัง
       ⇒ เส้นที่ "รู้คำตอบอยู่แล้วว่าต้องไม่ว่าง" ให้ประกาศไว้ด้วย
       ⚠️ ใช้ `purchases` เพราะรู้แน่ว่ามีตัวกรองจริง — **ห้ามใช้เส้นที่ `null` โดยชอบธรรม**
          (5 เส้นถูกจัดการในบล็อกรวม ⇒ `null` ถูกต้องสำหรับเส้นพวกนั้น) */
    ต้องไม่ใช่null: ["สัญญาของเส้นนี้.ตัวกรองที่รับ"],
    ที่มา: "ฝั่งจอขอ 19 ก.ย. 2569 — ปลดล็อกด่านตรวจคำกล่าวอ้าง 186 จุด",
  },
];

const มีคีย์ = (o, k) => o && typeof o === "object" && Object.prototype.hasOwnProperty.call(o, k);

let ตก = 0;
let ผ่าน = 0;
console.log(`ยิงตรวจคีย์ตามสัญญา — ${SITE}\n`);

for (const s of สัญญา) {
  if (s.ข้าม) continue;
  let d = null;
  let err = null;
  try {
    const r = await fetch(`${SITE}${s.path}`, {
      headers: { "x-admin-key": KEY },
      signal: AbortSignal.timeout(30000),
    });
    d = await r.json().catch(() => null);
    if (!d) err = `ตอบ ${r.status} แต่อ่าน JSON ไม่ได้`;
  } catch (e) {
    err = String(e?.message || e).slice(0, 120);
  }
  if (err) {
    /* 🔑 ยิงไม่ถึง = **ยังไม่ได้ตรวจ** ไม่ใช่ "คีย์หาย" ⇒ ต้องเขียนให้ต่างกัน */
    console.error(`⚠️ [${s.ชื่อ}] ยิงไม่สำเร็จ: ${err}\n   ⇒ **ยังไม่ได้ตรวจ ไม่ใช่ตก**`);
    ตก++;
    continue;
  }
  const ขาด = (s.ต้องมีคีย์ ?? []).filter((k) => !มีคีย์(d, k));
  /* ค่าที่ต้องไม่เป็น null — คีย์มีอยู่แต่ค่าเป็น null = **ของยังใช้ไม่ได้** */
  const เป็นnull = [];
  for (const เส้นทาง of s.ต้องไม่ใช่null ?? []) {
    let v = d;
    for (const ส่วน of เส้นทาง.split(".")) v = v?.[ส่วน];
    if (v === null || v === undefined) เป็นnull.push(เส้นทาง);
  }
  const ขาดซ้อน = [];
  for (const [แม่, ลูก] of Object.entries(s.ต้องมีคีย์ซ้อน ?? {})) {
    if (!มีคีย์(d, แม่)) { ขาดซ้อน.push(`${แม่} (ไม่มีทั้งก้อน)`); continue; }
    for (const k of ลูก) if (!มีคีย์(d[แม่], k)) ขาดซ้อน.push(`${แม่}.${k}`);
  }
  if (เป็นnull.length) {
    console.error(
      `❌ [${s.ชื่อ}] คีย์มีอยู่ **แต่ค่าเป็น null**: ${เป็นnull.join(", ")}\n` +
      `   ที่มาของสัญญา: ${s.ที่มา}\n` +
      "   🔑 **\"คีย์มีอยู่\" ไม่พอสำหรับคีย์พวกนี้** — null แปลว่าของยังใช้ไม่ได้\n" +
      "   ⇒ เช็คว่าไฟล์ที่สร้างตอน build ถูกรวมเข้าฟังก์ชันจริงไหม (ต้องเป็น `.mjs` + static import)"
    );
    ตก++;
    continue;
  }
  if (ขาด.length || ขาดซ้อน.length) {
    console.error(
      `❌ [${s.ชื่อ}] ขาดคีย์: ${[...ขาด, ...ขาดซ้อน].join(", ")}\n` +
      `   ที่มาของสัญญา: ${s.ที่มา}\n` +
      "   ⇒ **คีย์หายทั้งคีย์ = ปลายทางแยก \"ท่อรุ่นเก่า\" จาก \"ค่าว่างจริง\" ไม่ออก**\n" +
      "   ⇒ เช็คว่า deploy ขึ้นครบแล้วจริงไหม · หรือมีทางแคชที่คืนก้อนเก่าที่ไม่มีคีย์นี้"
    );
    ตก++;
  } else {
    const ตัวอย่าง = (s.ต้องมีคีย์ ?? []).slice(0, 3).map((k) => `${k}=${JSON.stringify(d[k])?.slice(0, 22)}`).join(" · ");
    console.log(`✅ [${s.ชื่อ}] คีย์ครบ${ตัวอย่าง ? ` · ${ตัวอย่าง}` : ""}`);
    ผ่าน++;
  }
}

console.log(`\nผ่าน ${ผ่าน} · ต้องดู ${ตก}`);
if (ตก) {
  console.error("🚫 **ห้ามรายงานว่า \"จอได้ของแล้ว\"** จนกว่าตัวนี้จะผ่านครบ");
  process.exit(1);
}
console.log("🔑 ครบตามสัญญา — รายงานฝั่งจอได้ว่า \"ยิงตรวจ production แล้ว\"");
