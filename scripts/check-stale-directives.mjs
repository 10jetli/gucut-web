#!/usr/bin/env node
/* 📜 ไล่ดู **"คำสั่งในคอมเมนต์ที่ความจริงหมดอายุได้"**
 *
 * 🔴 ที่มา 19 ก.ย. 2569 (ฝั่งจอเจอในไฟล์ของเขา) — หัวไฟล์จอขนส่งสั่งไว้ว่า
 *    *"จำนวนของเราน้อยกว่า ZORT และห้ามปิดบัง"* พร้อมสั่งวิธีเขียนข้อความบนจอ
 *    แต่วัดจริง 16 ก.ย.: **เรามากกว่า ZORT 21 เท่า** ⇒ กล่องบนจอถูกแก้ไปแล้ว
 *    ⇒ **หัวไฟล์ยังสั่งตรงกันข้ามกับสิ่งที่จอแก้ไปแล้ว**
 *    🔑 **คำสั่งที่ค้าง อันตรายกว่าคำบรรยายที่ค้าง เพราะมันสั่งให้ลงมือ**
 *       คนที่อ่านแล้วทำตาม จะเขียนข้อความเท็จกลับเข้าไปทับของที่เพิ่งแก้
 *    ⚠️ และไฟล์เดียวกันนั้นเตือนเรื่องนี้ไว้เองสองย่อหน้าถัดลงไป
 *       ⇒ **ที่ที่ตรวจน้อยที่สุด คือที่ที่อ่านบ่อยที่สุด** (หัวไฟล์)
 *
 * ตะแกรง: คอมเมนต์ที่มี **คำสั่ง** (ห้าม…/ต้อง…) **และ** มีสิ่งที่หมดอายุได้ในบรรทัดเดียวกัน
 *   · ตัวเลข ≥2 หลัก (จำนวนของจริงเปลี่ยนทุกวัน)
 *   · คำเปรียบเทียบ (น้อยกว่า · มากกว่า · ต่ำกว่า · สูงกว่า · ยังไม่ · เท่ากับ)
 * 🚫 **รายงาน ไม่ใช่ด่าน** — คำสั่งเชิงหลักการที่มีเลขประกอบก็โผล่ที่นี่ (เช่น "ห้ามบอกว่ามี PIN นี้")
 *    ⇒ ต้องอ่านทีละจุด **ห้ามเหมาแก้** · ความรุนแรงต้องเท่ากับรัศมีความเสียหาย
 * 🚫 และตะแกรงนี้ **มองไม่เห็น** คำสั่งที่อ้างสถานะโดยไม่มีเลขและไม่มีคำเปรียบเทียบ
 *    ⇒ อ่านผลว่า "เจอเท่านี้ในตะแกรงนี้" ไม่ใช่ "มีเท่านี้"
 *
 * ใช้: node scripts/check-stale-directives.mjs [--all]
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const ราก = ["netlify/lib", "netlify/functions", "src/lib", "src/components", "scripts"];
const นามสกุล = /\.(mjs|ts|tsx|js)$/;
const คำสั่ง = /(ห้าม|ต้อง|ให้)(เขียน|บอก|โชว์|แสดง|ใช้|ปิดบัง|รายงาน)/;
const หมดอายุได้ = /\d{2,}|น้อยกว่า|มากกว่า|ต่ำกว่า|สูงกว่า|ยังไม่|เท่ากับ|ครบแล้ว/;
/* เงื่อนไขในประโยคเดียวกันทำให้คำสั่งไม่หมดอายุ — มันสั่ง "เมื่อเกิด X" ไม่ใช่ "สถานะคือ X" */
const มีเงื่อนไข = /\bถ้า|เมื่อ|กรณี|ตอนที่|failed|error|ล้ม|ไม่สำเร็จ/;

/* 🧪 **ตัวควบคุมฝังใน — รันทุกรอบก่อนตัดสิน** (ท่าของฝั่งจอ · ยกมา 20 ก.ย. 2569 เย็น)
   🔑 ด่านนี้อยู่ในกอง **"ไม่มีอะไรพิสูจน์สักชั้น"** (ไม่มีสูตรในทะเบียน · ไม่มีตัวควบคุม)
      ⇒ ฝั่งจอชี้ว่าแรงลงที่กองนี้คุ้มที่สุด เพราะกองที่มีสูตรแล้วมีตาข่ายอยู่ชั้นหนึ่ง
   ⚠️ ต้องมีทั้ง **ต้องจับ** และ **ต้องไม่จับ** — มีแต่ฝั่งแรกจะมองไม่เห็นตะแกรงที่กว้างเกิน
   ⇒ ควบคุมไม่ผ่าน = **ผลของด่านนี้อ่านไม่ได้** ไม่ใช่ "ไม่มีคำสั่งที่หมดอายุ" */
{
  const ต้องจับ = [
    "ห้ามเขียนว่าเหลือ 45 จุด",          // คำสั่ง + เลขที่หมดอายุได้
    "ต้องบอกว่าต่ำกว่าเกณฑ์",             // คำสั่ง + คำเปรียบเทียบ
  ];
  const ต้องไม่จับ = [
    "ถ้าล้มให้เขียนเหตุไว้",              // มีเงื่อนไข ⇒ ไม่ใช่คำกล่าวอ้างสภาพ
    "อ่านไฟล์แล้วนับบรรทัด",              // ไม่มีคำสั่ง
    "",                                   // บรรทัดเปล่า
  ];
  const เข้าเกณฑ์ = (ln) => คำสั่ง.test(ln) && หมดอายุได้.test(ln) && !มีเงื่อนไข.test(ln);
  const พลาด = [
    ...ต้องจับ.filter((x) => !เข้าเกณฑ์(x)).map((x) => `ต้องจับแต่ไม่จับ: ${x}`),
    ...ต้องไม่จับ.filter((x) => เข้าเกณฑ์(x)).map((x) => `ต้องไม่จับแต่จับ: ${x}`),
  ];
  if (พลาด.length) {
    console.error(
      "🔴 **ตัวควบคุมของด่านนี้ไม่ผ่าน ⇒ ผลของด่านนี้อ่านไม่ได้** (ไม่ใช่ 'ไม่มีคำสั่งที่หมดอายุ')\n" +
      พลาด.map((x) => `   · ${x}`).join("\n")
    );
    process.exit(1);
  }
}

const ไฟล์ทั้งหมด = [];
const เดิน = (d) => {
  for (const ชื่อ of readdirSync(d)) {
    const p = join(d, ชื่อ);
    if (statSync(p).isDirectory()) { if (ชื่อ !== "node_modules") เดิน(p); continue; }
    if (นามสกุล.test(ชื่อ)) ไฟล์ทั้งหมด.push(p);
  }
};
for (const r of ราก) { try { เดิน(r); } catch { /* ไม่มีโฟลเดอร์ = ข้าม */ } }

if (ไฟล์ทั้งหมด.length === 0) {
  console.error("✗ check-stale-directives: สแกนได้ 0 ไฟล์ ⇒ **ตะแกรงพัง ไม่ใช่ไม่มีปัญหา**");
  process.exit(2);
}

const โชว์ทั้งหมด = process.argv.includes("--all");
let จุดคำสั่ง = 0;
const น่าสงสัย = [];
const หัวไฟล์ = [];

for (const p of ไฟล์ทั้งหมด) {
  const บรรทัด = readFileSync(p, "utf8").split("\n");
  for (let i = 0; i < บรรทัด.length; i += 1) {
    const ln = บรรทัด[i];
    if (!/^\s*(\/\/|\/?\*|\s\*)/.test(ln)) continue;   // เฉพาะบรรทัดคอมเมนต์
    if (!คำสั่ง.test(ln)) continue;
    จุดคำสั่ง += 1;
    if (!หมดอายุได้.test(ln)) continue;
    if (มีเงื่อนไข.test(ln)) continue;                 // สั่งแบบมีเงื่อนไข ⇒ ไม่หมดอายุเอง
    const รายการ = { p, บรรทัด: i + 1, ข้อความ: ln.trim().replace(/^[/*\s]+/, "").slice(0, 120) };
    น่าสงสัย.push(รายการ);
    if (i < 25) หัวไฟล์.push(รายการ);                  // 🔑 หัวไฟล์ = ที่คนอ่านบ่อยที่สุด
  }
}

console.log("📜 คำสั่งในคอมเมนต์ที่ **ความจริงหมดอายุได้** — รายการที่ต้องเอาตาดู ไม่ใช่รายการที่ต้องแก้\n");
console.log(`🔺 อยู่ใน 25 บรรทัดแรกของไฟล์ (${หัวไฟล์.length} จุด) — **อ่านบ่อยสุด ตรวจน้อยสุด ⇒ ดูก่อน**`);
for (const r of หัวไฟล์) console.log(`   ${r.p}:${r.บรรทัด} — ${r.ข้อความ}`);
if (โชว์ทั้งหมด) {
  console.log(`\n· ที่เหลือ (${น่าสงสัย.length - หัวไฟล์.length} จุด)`);
  for (const r of น่าสงสัย.filter((x) => !หัวไฟล์.includes(x))) console.log(`   ${r.p}:${r.บรรทัด} — ${r.ข้อความ}`);
}
console.log(
  `\n📏 ตะแกรง: ${ไฟล์ทั้งหมด.length} ไฟล์ใน ${ราก.join(" · ")}` +
  `\n   จุดที่เป็นคำสั่ง ${จุดคำสั่ง} · ในนั้น **หมดอายุได้และไม่มีเงื่อนไขกำกับ ${น่าสงสัย.length} จุด**` +
  "\n   ⚠️ มองไม่เห็นคำสั่งที่อ้างสถานะโดยไม่มีเลขและไม่มีคำเปรียบเทียบ ⇒ \"เจอเท่านี้ในตะแกรงนี้\"" +
  "\n   🔑 วิธีแก้ที่ถูกไม่ใช่ลบคำสั่ง แต่คือ **เขียนวันที่ + ที่มาของเลขกำกับ** ให้คนรอบหน้าไปวัดซ้ำได้"
);
