#!/usr/bin/env node
/* 🌱 ด่านราคาถูก: **สูตรปลูกบั๊กทุกสูตรต้องยัง "ปลูกลง" ได้**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 (ฝั่งจอเจอในรีโปเขา แล้วส่งมาให้ผมส่อง):
 *    เขาเขียน lib ตัวหนึ่งใหม่ ⇒ ข้อความที่สูตรของทะเบียนจะแทน **ไม่มีในไฟล์อีกแล้ว**
 *    ⇒ สูตรตอบ "ปลูกไม่ลง" · และถ้าเครื่องมือเชื่อว่า `replace` สำเร็จ
 *      ผลจะออกมาเป็น **"ด่านเขียว"** แล้วคนจะ **โทษด่านผิด**
 *    🔑 ประโยคของเขา: **การแก้โค้ดทำให้ "หลักฐานการพิสูจน์" หมดอายุเงียบ ๆ ได้**
 *
 * 🔑 **ทำไมต้องมีด่านนี้แยกจากตัวรันทะเบียน**
 *    ตัวรันทะเบียน (`ด่านแยกแยะได้ไหม.mjs`) **ปลูกของจริงและรันด่านจริง** ⇒ ใช้เวลาเป็นนาที
 *    ⇒ ใส่ใน prebuild ไม่ได้ (งบเวลาเป็นของใช้ร่วมกัน) ⇒ มันถูกรัน **ด้วยมือ** เท่านั้น
 *    ⇒ ระหว่างการรันมือแต่ละครั้ง สูตรหมดอายุได้โดยไม่มีอะไรฟ้อง
 *    ⇒ ด่านนี้จึงตรวจ **ข้อเดียว** ที่ถูกที่สุดและหมดอายุง่ายที่สุด: `แก้()` ยังเปลี่ยนเนื้อไฟล์ไหม
 *
 * 🚫 **ด่านนี้ไม่ได้บอกว่าด่านนั้นจับบั๊กได้** — บอกแค่ว่า "สูตรยังมีที่ให้ปลูก"
 *    ⇒ เขียวที่นี่ **ไม่ใช่** การทดแทนการรันทะเบียนจริง · มันแค่กัน "สูตรตายเงียบ"
 * 🚫 และ **ไม่แก้ไฟล์ใด ๆ** — ทำงานในหน่วยความจำล้วน (ตัวตรวจห้ามเปลี่ยนสิ่งที่มันตรวจ)
 *
 * ใช้: node scripts/check-plant-formulas.mjs
 */
import { existsSync, readFileSync } from "node:fs";
import { ทะเบียน } from "./lib/ทะเบียนด่าน.mjs";

let ตก = 0;
let ผ่าน = 0;
/* 🔑 **แยกตัวนับตามเหตุ** — เดิมนับ "ขาดเงื่อนไขเป้า" รวมกับ "ปลูกไม่ลง" ป้ายเดียว
   ⇒ คนอ่านจะไปไล่หาว่าข้อความที่สูตรมองหาหายไปไหน ทั้งที่ของจริงคือ **ยังไม่ได้เขียนเอกสาร**
   ⇒ กฎของทีมเราเอง: สองเหตุที่แก้คนละแบบ ห้ามยัดป้ายเดียวกัน */
let ขาดเงื่อนไข = 0;
const ข้าม = [];

for (const t of ทะเบียน) {
  if (!t.ไฟล์ || typeof t.แก้ !== "function") {
    ข้าม.push(`${t.ด่าน} — ไม่มีไฟล์/สูตร`);
    continue;
  }
  if (!existsSync(t.ไฟล์)) {
    console.error(`🔴 ${t.ด่าน}\n   ไฟล์เป้าหมายไม่มีอยู่แล้ว: ${t.ไฟล์} ⇒ **สูตรนี้ปลูกไม่ได้ตลอดกาล**`);
    ตก++;
    continue;
  }
  /* 🔑 **บังคับให้ทุกสูตรเขียน "เงื่อนไขของเป้า"** (ฝั่งจอเสนอเป็นธรรมเนียม 20 ก.ย. 2569
     ⇒ ผมทำเป็น **ฟิลด์ข้อมูล** เพื่อให้เครื่องตรวจได้ · ธรรมเนียมที่ไม่มีด่านจะหายไปกับคนที่ลืม)
     เหตุผล: ตัวสูตรอ่านออกจากโค้ดได้ แต่ "ทำไมต้องเป็นเป้านี้" อ่านไม่ออกถ้าไม่เขียน
     ⇒ คนรอบหน้าที่ปลูกนอกขอบเขตจะเสียเวลาไล่ว่า "ด่านพังหรือเราผิด" (ฝั่งจอเจอ 6 ครั้งในวันเดียว) */
  if (!t.เงื่อนไขเป้า || String(t.เงื่อนไขเป้า).trim().length < 20) {
    console.error(
      `🔴 ${t.ด่าน}\n   ไม่มีฟิลด์ \`เงื่อนไขเป้า\` (หรือสั้นเกินจะมีความหมาย)\n` +
      "   ⇒ เขียนว่า **เป้าต้องมีคุณสมบัติอะไรถึงจะอยู่ในขอบเขตที่ด่านนั้นจับ**\n" +
      "   ⇒ ไม่มีข้อนี้ = วันที่ปลูกแล้วเงียบ จะแยกไม่ออกว่า \"ด่านพัง\" หรือ \"ปลูกนอกขอบเขต\""
    );
    ขาดเงื่อนไข++;
    continue;
  }
  const เดิม = readFileSync(t.ไฟล์, "utf8");
  let ใหม่;
  try {
    ใหม่ = t.แก้(เดิม);
  } catch (e) {
    console.error(`🔴 ${t.ด่าน}\n   สูตรโยน error: ${String(e?.message || e).slice(0, 120)}`);
    ตก++;
    continue;
  }
  if (ใหม่ === เดิม) {
    console.error(
      `🔴 ${t.ด่าน}\n` +
      `   สูตรไม่เปลี่ยนเนื้อ ${t.ไฟล์} เลย ⇒ **ปลูกไม่ลง**\n` +
      "   ⇒ ข้อความที่สูตรมองหาถูกแก้/ลบไปแล้ว (มักเกิดตอนเขียนไฟล์นั้นใหม่)\n" +
      "   ⇒ 🔑 ถ้าไม่มีด่านนี้ ตัวรันทะเบียนจะรายงานผลของ **ไฟล์ที่ไม่ได้ถูกปลูก** ⇒ โทษด่านผิด"
    );
    ตก++;
    continue;
  }
  ผ่าน++;
}

console.log(
  `\n📏 ตรวจสูตรปลูก ${ทะเบียน.length} สูตร — ปลูกลง ${ผ่าน} · ปลูกไม่ลง ${ตก}` +
  (ขาดเงื่อนไข ? ` · **ขาดเงื่อนไขเป้า ${ขาดเงื่อนไข}** (คนละเรื่องกับปลูกไม่ลง — อันนี้คือยังไม่ได้เขียนเอกสาร)` : "") +
  (ข้าม.length ? `\n   ⏭️ ข้าม ${ข้าม.length} (ไม่มีไฟล์/สูตร): ${ข้าม.join(" · ")}` : "") +
  "\n   🚫 เขียวที่นี่ = **สูตรยังมีที่ให้ปลูก** ไม่ใช่ \"ด่านนั้นจับบั๊กได้\"" +
  "\n      ⇒ ข้อหลังต้องรัน `node scripts/ด่านแยกแยะได้ไหม.mjs` (ปลูกของจริง ใช้เวลาเป็นนาที)"
);
if (ทะเบียน.length === 0) {
  console.error("🔴 ทะเบียนว่าง ⇒ ด่านนี้ไม่ได้ตรวจอะไรเลย ⇒ ถือว่าตก");
  process.exit(1);
}
process.exitCode = (ตก + ขาดเงื่อนไข) ? 1 : 0;
