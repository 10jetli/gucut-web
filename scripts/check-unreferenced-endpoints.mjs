/* ✂️ ตัวตัดคอมเมนต์อยู่ที่ `scripts/_strip-comments.mjs` **แหล่งเดียว**
   🔴 เดิมไฟล์นี้มีสำเนาของตัวเอง แล้วมันพัง 3 รูปคนละรูปกับสำเนาในไฟล์ด่าน (19 ก.ย. 2569)
      ⇒ ก๊อปตรรกะไว้สองที่ = แก้ที่เดียวแล้วเชื่อว่าจบ ทั้งที่อีกที่ยังพังอยู่ */
const ไม่เอาคอมเมนต์ = (เนื้อ, ไฟล์ = "") => ตัดคอมเมนต์(เนื้อ, ไฟล์);

/* 🔴 **นามสกุลที่กวาด = ขอบเขตของคำตอบ** (แก้ 19 ก.ย. 2569 หลังฝั่งจอเจอกับตัวเอง)
   เขากวาดแต่ `.ts/.tsx/.mjs` ⇒ พลาด `public/catalog/` ที่เป็น HTML/JS ล้วนและเรียก API จริง
   ⇒ รายงานว่า 3 เส้นตาย **ทั้งที่แคตตาล็อกกับระบบโอนสินค้าเรียกอยู่ทุกวัน** (ลบตาม = พังทันที)
   🔑 และชั้นที่เจ็บที่สุดของเขาคือ: อุดจุดบอดหนึ่งชั้นแล้ว **เลขไม่ขยับ ⇒ เชื่อว่ายืนยันแล้ว**
      ทั้งที่ "เลขไม่เปลี่ยนหลังอุดจุดบอด" แปลแค่ว่า **จุดบอดที่เหลือไม่ได้อยู่ในที่ที่เพิ่งเปิดดู**
   ⇒ ฝั่งท่อจึงต้องกวาด `.py`/`.sh` ด้วย เพราะ **มีสคริปต์บน g1 (~/bin) ยิง `gucut.com/api/` จริง**
      📏วัดได้(ไฟล์ใน ~/bin ที่ยิง gucut.com/api/)=5 · 19 ก.ย. 2569
      ⇒ ไม่กวาด = ฟ้องเส้นที่งานตามเวลาในเครื่องเรียกอยู่ */
const ไฟล์ในโฟลเดอร์ = (d, นามสกุล = /\.(mjs|ts|tsx|js|json|html|py|sh|toml|yml|yaml)$/) => {
  const out = [];
  const เดิน = (p) => {
    for (const ชื่อ of readdirSync(p)) {
      if (ชื่อ === "node_modules" || ชื่อ === ".next" || ชื่อ === "out") continue;
      const full = join(p, ชื่อ);
      if (statSync(full).isDirectory()) เดิน(full);
      else if (นามสกุล.test(ชื่อ)) out.push(full);
    }
  };
  เดิน(d);
  return out;
};

