#!/usr/bin/env node
/* 👯 ด่าน: **ตารางที่ต้องตรงกันสองที่ ต้องตรงกันจริง**
 *
 * 🔴 ที่มา 19 ก.ย. 2569 ค่ำ · ฝั่งจอเปลี่ยนคำถามจาก "คำบรรยายยังตรงไหม" เป็น
 *    **"กติกายังถูกทำตามจริงไหม"** พร้อมประโยคที่ทำให้ผมมาไล่ฝั่งท่อทันที:
 *    **"กติกาที่ทุกคนละเมิด คือกติกาที่ตายไปแล้ว และมันตายเงียบกว่าคำบรรยายค้าง
 *      เพราะไม่มีใครต้องแก้อะไรเลยเพื่อให้มันตาย — แค่ไม่ทำตาม"**
 *
 * ⇒ ไล่ `CLAUDE.md` หาคำว่า "ต้องตรงกัน" ⇒ เจอ 2 ข้อ ⇒ **ทั้งสองข้อไม่มีกลไกบังคับเลย**
 *    มีแต่คอมเมนต์ในไฟล์ทั้งสองฝั่งที่ชี้หากันไปมา ("ต้องตรงกับ … เป๊ะ ๆ")
 *    🔑 คอมเมนต์ที่ชี้หากันคือ **คำเตือน** · ของที่บังคับได้คือ **ด่าน**
 *
 * ความเสียหายถ้าไม่ตรง — เหตุผลที่ข้อนี้ทำเป็นด่านไม่ใช่รายงาน:
 * · `LADDER` (`src/lib/image-loader.js` ↔ `scripts/img-to-r2.mjs`)
 *   ⇒ หน้าเว็บขอไฟล์ขนาดที่ **ไม่เคยถูกสร้างบน R2** ⇒ **รูปหายทั้งเว็บ** (404 ทุกใบ)
 * · ตารางค่าส่ง (`src/lib/shipping.ts` ↔ `netlify/lib/shipping.mjs`)
 *   ⇒ ยอดที่ลูกค้าเห็นตอนกรอก **ต่างจากยอดที่เซิร์ฟเวอร์คิดตอนกดสั่ง** ⇒ เงินจริงและความเชื่อถือ
 *   (เซิร์ฟเวอร์คิดค่าส่งใหม่เองเสมอโดยไม่เชื่อ `body.shipping` ⇒ ความต่างจะโผล่ **ตอนจ่ายเงิน**)
 *
 * ⚠️ ขอบเขต: เทียบ **ตัวเลขในตาราง** ที่สกัดด้วย regex เท่านั้น
 *    ไม่ได้เทียบตรรกะรอบตาราง (เงื่อนไข `>=` vs `>` · การปัดเศษ · ลำดับขั้น)
 *    ⇒ ผ่านด่านนี้ = "ตัวเลขชุดเดียวกัน" **ไม่ใช่ "คิดเงินเหมือนกัน"**
 * 🚫 สกัดไม่ได้ (regex ไม่เจอ) ⇒ **ถือว่าตก** ไม่ใช่ผ่าน — ไม่งั้นวันที่มีคนเปลี่ยนรูปการเขียน
 *    ด่านจะเขียวตลอดกาลโดยไม่เทียบอะไรเลย (คลาส "ตัวตรวจที่เขียวได้ทั้งที่ของจริงพัง")
 */
import { readFileSync } from "node:fs";

/** เลขทั้งหมดในข้อความ — ใช้เทียบเป็น "ชุดเดียวกันไหม" */
const เลขใน = (s) => (s.match(/\d+(?:\.\d+)?/g) ?? []).map(Number);

/** คู่ที่ต้องตรงกัน — เพิ่มคู่ใหม่ที่นี่ที่เดียว
 *  `สกัด` ต้องคืน **อาร์เรย์ตัวเลข** หรือ `null` ถ้าอ่านไม่ออก (null ⇒ ตก) */
const คู่ = [
  {
    ชื่อ: "LADDER (ขั้นบันไดขนาดรูป)",
    เสียหายถ้าไม่ตรง: "หน้าเว็บขอขนาดที่ไม่เคยถูกสร้างบน R2 ⇒ รูปหายทั้งเว็บ",
    ฝั่ง: [
      { path: "src/lib/image-loader.js", สกัด: (s) => {
        const m = /const LADDER\s*=\s*\[([^\]]+)\]/.exec(s);
        return m ? เลขใน(m[1]) : null;
      } },
      { path: "scripts/img-to-r2.mjs", สกัด: (s) => {
        const m = /const LADDER\s*=\s*\[([^\]]+)\]/.exec(s);
        return m ? เลขใน(m[1]) : null;
      } },
    ],
  },
  {
    ชื่อ: "ตารางค่าส่ง 12 ขั้น",
    เสียหายถ้าไม่ตรง: "ยอดที่ลูกค้าเห็นต่างจากยอดที่เซิร์ฟเวอร์คิดตอนกดสั่ง ⇒ เงินจริง",
    ฝั่ง: [
      { path: "src/lib/shipping.ts", สกัด: (s) => {
        const m = /SHIPPING_TIERS[^=]*=\s*\[([\s\S]*?)\n\]/.exec(s);
        return m ? เลขใน(m[1]) : null;
      } },
      { path: "netlify/lib/shipping.mjs", สกัด: (s) => {
        const m = /(?:SHIPPING_TIERS|TIERS)[^=]*=\s*\[([\s\S]*?)\n\]/.exec(s);
        return m ? เลขใน(m[1]) : null;
      } },
    ],
  },
];

let ตก = 0;
for (const c of คู่) {
  const ค่า = c.ฝั่ง.map((f) => {
    let src = null;
    try { src = readFileSync(f.path, "utf8"); } catch { return { ...f, ผล: null, เหตุ: "อ่านไฟล์ไม่ได้" }; }
    const ผล = f.สกัด(src);
    return { ...f, ผล, เหตุ: ผล ? null : "สกัดไม่ออก (รูปการเขียนคงเปลี่ยน)" };
  });

  const อ่านไม่ได้ = ค่า.filter((v) => !v.ผล);
  if (อ่านไม่ได้.length) {
    ตก += 1;
    console.log(`🔴 ${c.ชื่อ} — **สกัดไม่ได้ ⇒ ถือว่าตก ไม่ใช่ผ่าน**`);
    for (const v of อ่านไม่ได้) console.log(`   · ${v.path}: ${v.เหตุ}`);
    console.log(`   ⇒ ถ้าปล่อยผ่าน ด่านนี้จะเขียวตลอดกาลโดยไม่เทียบอะไรเลย`);
    continue;
  }

  const [a, b] = ค่า;
  const ตรง = a.ผล.length === b.ผล.length && a.ผล.every((n, i) => n === b.ผล[i]);
  if (ตรง) {
    console.log(`✅ ${c.ชื่อ} — ตรงกัน (${a.ผล.length} เลข) · ${a.path} ↔ ${b.path}`);
  } else {
    ตก += 1;
    console.log(
      `🔴 ${c.ชื่อ} — **ไม่ตรงกัน**\n` +
      `   ${a.path}: ${a.ผล.join(" ")}\n` +
      `   ${b.path}: ${b.ผล.join(" ")}\n` +
      `   ⇒ ผลถ้าปล่อย: ${c.เสียหายถ้าไม่ตรง}`
    );
  }
}

console.log(
  `\n📏 เทียบ ${คู่.length} คู่ · ตก ${ตก}` +
  "\n   ⚠️ เทียบ **ตัวเลขในตาราง** เท่านั้น — ไม่ได้เทียบตรรกะรอบตาราง (`>=` vs `>` · การปัดเศษ)" +
  "\n   ⇒ ผ่าน = \"ตัวเลขชุดเดียวกัน\" **ไม่ใช่ \"คิดเงินเหมือนกัน\"**"
);

if (ตก) process.exit(1);
