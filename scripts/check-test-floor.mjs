// ด่าน: **จำนวนเทสต้องไม่ลดลงเงียบ ๆ**
//
// 🔴 ที่มา 14 ต.ค. 2569 — ได้มาจากกฎที่คุณส้มตั้งชื่อ:
//    *"ด่านที่เขียนขึ้นเพื่อคุมคนหนึ่ง จะถูกทดสอบเฉพาะทิศที่คนนั้นจะโกง
//      และทิศที่ไม่มีใครได้ประโยชน์จากการโกง คือทิศที่ตัวด่านเองพัง"*
//    ด่าน push ถูกเขียนเพื่อคุม **"ผมจะ push ของพัง"** ⇒ ทิศที่ตรวจคือ "เทสตก"
//    ทิศที่ไม่มีใครได้ประโยชน์ = **จำนวนเทสลดลง** ⇒ `# fail 0` ⇒ ด่านพิมพ์ "ผ่าน" อย่างซื่อสัตย์
//    ⇒ ของจริงที่จะทำให้เกิด: glob จับไฟล์ได้น้อยลง · ย้ายไฟล์ออกจาก scripts/tests/ ·
//      เปลี่ยนแฟลก runner · ไฟล์เทสที่ไม่ประกาศ test() เลย
//    🔑 เทสตกจับได้ด้วย exit code · **เทสหายไม่มีอะไรจับ** — คนละทิศ คนละกลไก
//
// ⚠️ สามสถานะ ไม่ใช่สองสถานะ: อ่านไฟล์พื้นไม่ได้ ⇒ **"คุมไม่ได้รอบนี้"** ไม่ใช่ "ผ่าน"
import { readFileSync, writeFileSync } from "node:fs";

const logPath = process.argv[2];
const FLOOR_FILE = "scripts/lib/พื้นจำนวนเทส.json";

function อ่านจำนวนเทส(p) {
  const t = readFileSync(p, "utf8");
  const m = t.match(/^# tests (\d+)$/m);
  return m ? Number(m[1]) : null;
}

let n;
try { n = อ่านจำนวนเทส(logPath); }
catch { console.log("   ⬜ คุมไม่ได้รอบนี้: อ่าน log เทสไม่ได้ (ช่องว่าง ไม่ใช่ผลผ่าน)"); process.exit(0); }
if (n === null) { console.log("   ⬜ คุมไม่ได้รอบนี้: ใน log ไม่มีบรรทัด '# tests N' (ช่องว่าง ไม่ใช่ผลผ่าน)"); process.exit(0); }

let f;
try { f = JSON.parse(readFileSync(FLOOR_FILE, "utf8")); }
catch { console.log(`   ⬜ คุมไม่ได้รอบนี้: อ่าน ${FLOOR_FILE} ไม่ได้ (ช่องว่าง ไม่ใช่ผลผ่าน)`); process.exit(0); }

const พื้น = Number(f["สูงสุดที่เคยเห็น"]);
if (!Number.isFinite(พื้น)) { console.log(`   ⬜ คุมไม่ได้รอบนี้: ค่า สูงสุดที่เคยเห็น ใน ${FLOOR_FILE} ไม่ใช่ตัวเลข`); process.exit(0); }

// ป้ายขอบเขตมาก่อนตัวเลข
const ป้าย = `เทสที่รันรอบนี้ ${n} · พื้นที่เคยเห็น ${พื้น} (${f["วันที่"] ?? "ไม่ทราบวันที่"})`;

if (n >= พื้น) {
  if (n > พื้น) {
    f["สูงสุดที่เคยเห็น"] = n;
    f["วันที่"] = new Date(Date.now() + 7 * 3600e3).toISOString().slice(0, 10); // วันไทย
    f["เหตุที่ลด"] = null;
    writeFileSync(FLOOR_FILE, JSON.stringify(f, null, 2) + "\n");
    console.log(`   📈 ${ป้าย} ⇒ ยกพื้นขึ้นเป็น ${n} แล้ว (แก้ไฟล์ ${FLOOR_FILE} — commit ตามไปด้วย)`);
  } else {
    console.log(`   ✅ ${ป้าย}`);
  }
  process.exit(0);
}

const ลด = f["เหตุที่ลด"];
if (ลด && Number(ลด["ถึงจำนวน"]) === n && String(ลด["เหตุ"] ?? "").trim().length >= 10) {
  console.log(`   🔸 ${ป้าย} ⇒ **ลดโดยตั้งใจ** ${ลด["วันที่"] ?? ""}: ${ลด["เหตุ"]}`);
  process.exit(0);
}

console.log(`❌ ไม่ผ่านด่านจำนวนเทส — ไม่ push`);
console.log(`   ${ป้าย} ⇒ **หายไป ${พื้น - n} ตัว**`);
console.log(`   🔑 เทส "ตก" กับเทส "หาย" คนละเรื่อง — exit code จับได้แค่เทสที่ตก`);
console.log(`   ไล่ดูตามนี้: glob scripts/tests/*.test.mjs จับได้กี่ไฟล์ · มีไฟล์ถูกย้าย/เปลี่ยนนามสกุลไหม ·`);
console.log(`              มีไฟล์ที่ไม่ประกาศ test() เลยไหม · แฟลก runner เปลี่ยนไหม`);
if (ลด) console.log(`   ⚠️ ไฟล์พื้นมี เหตุที่ลด อยู่ แต่ ถึงจำนวน=${ลด["ถึงจำนวน"]} ไม่ตรงกับของจริง ${n} (หรือเหตุสั้นกว่า 10 ตัวอักษร)`);
else console.log(`   ลดจริงต้องตั้ง เหตุที่ลด ใน ${FLOOR_FILE} ⇒ { ถึงจำนวน: ${n}, เหตุ: "...", วันที่: "..." }`);
process.exit(1);
