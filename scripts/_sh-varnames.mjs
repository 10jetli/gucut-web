/* ตรรกะบริสุทธิ์ของด่าน `check-shell-varnames.mjs` — แยกออกมาเพื่อให้ **เทสเรียกได้**
 * 🔑 ถ้าเทส import ตัวด่านตรง ๆ โค้ดระดับบนสุดจะสแกนทั้งรีโปและอาจ `exit(1)` กลางเทส
 *    ⇒ เทสจะวัด "สภาพรีโปวันนี้" แทนที่จะวัด "ตะแกรงแยกแยะได้ไหม"
 */
/** ชื่อตัวแปรที่ bash ยอมรับ: [A-Za-z_][A-Za-z0-9_]* — อะไรที่นอกนี้ = ล้มเงียบ
 *  ⚠️ ต้องมี `^\s*` — **ของจริงที่ทำให้เกิดด่านนี้อยู่ในย่อหน้า** (`  ผลที่จะจด="failed"` ใต้ `if`)
 *     รอบแรกเขียน `^` เปล่า ⇒ ด่าน **จับต้นเหตุของตัวเองไม่ได้** และของที่ปลูกทดสอบ
 *     (ซึ่งผมพิมพ์ชิดซ้าย) ก็ผ่านหมด ⇒ เขียวลวงที่มาจาก "ของปลูกไม่เหมือนของจริง" */
export const การกำหนดค่า = /(?:^\s*|[;&|(]\s*|\b(?:then|else|do|export|local|readonly)\s+)([A-Za-z_]*[\u0080-\uFFFF][^\s=;|&()'"`$]*)=/u;

/** ลบ **เนื้อใน** เครื่องหมายคำพูดออก (เก็บคู่เครื่องหมายไว้เป็นที่ว่าง)
 *  🔴 ที่มา: รันแรกของด่านนี้ให้ **แดงลวง** ใส่ `~/bin/เฝ้าเว็บกลับมา.sh:10`
 *     ของจริงคือ `echo "... (ก่อนหน้า=$PREV)"` — เป็น **ข้อความ** ไม่ใช่การกำหนดค่า
 *     เหตุ: ตะแกรงนับ `(` เป็นจุดเริ่มคำสั่ง ⇒ `(ก่อนหน้า=` ในสตริงจึงเข้าข่าย
 *  🔑 แดงลวงแพงกว่าเขียวลวง — คนลงมือแก้ตาม แล้วไปพังของที่ยังดี */
export function ลบเนื้อในสตริง(บรรทัด) {
  let ออก = "";
  let ล้อม = null; // " หรือ ' ที่กำลังเปิดอยู่
  for (let i = 0; i < บรรทัด.length; i += 1) {
    const ch = บรรทัด[i];
    if (ล้อม) {
      if (ch === "\\" && ล้อม === '"') { i += 1; continue; }
      if (ch === ล้อม) { ล้อม = null; ออก += ch; }
      continue;
    }
    if (ch === '"' || ch === "'") { ล้อม = ch; ออก += ch; continue; }
    ออก += ch;
  }
  return ออก;
}
