#!/usr/bin/env node
/* ⚖️ สัดส่วน **"เครื่องตรวจได้เอง" เทียบ "อาศัยคำรับรอง"** ในด่านฝั่งท่อ
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ฝั่งจอวัดฝั่งตัวเองแล้วพบว่า 5 จาก 10 จอ
 *    ที่ "ผ่านด่าน applied" ผ่านด้วย **คำรับรองของคนเขียน** ไม่ใช่การตรวจ
 *    แกนของเรื่อง (ประโยคของเขา): *"คำรับรองถูกและมีเสมอ · การพิสูจน์แพงและบางทีทำไม่ได้
 *    ถ้าตัววัดนับสองอย่างนี้เท่ากัน ของถูกจะชนะทุกครั้งที่มีแรงกดดัน"*
 *    ⇒ ไม่มีใครตัดสินใจให้ด่านกลายเป็นพิธีกรรม มันแค่เป็นทางที่ต้านน้อยที่สุด ทีละข้อยกเว้นที่ฟังขึ้น
 *    ⇒ ฝั่งท่อจึงต้องวัดตัวเองด้วย **ก่อนที่จะเป็นแบบเดียวกันโดยไม่มีใครรู้**
 *
 * 🔑 และข้อที่สำคัญที่สุด: ตัวเลขต้องมาพร้อม **วิธีตอบสนองที่ถูก**
 *    ⇒ *"ต้องแก้ตัวจับ ไม่ใช่เพิ่มคำรับรอง"* — เพราะวิธีที่ง่ายที่สุดในการทำให้ด่านแดงเป็นเขียว
 *      คือเขียนคำรับรองเพิ่มอีกใบ ซึ่งลดเลขได้โดยไม่ได้เพิ่มความจริงเลยแม้แต่นิด
 *
 * 🚫 **รายงาน ไม่ใช่ด่าน** — ไม่ทำให้ build ตก · บางเรื่องพิสูจน์ด้วยเครื่องไม่ได้จริง ๆ
 *    (ยิงด้วยรหัสผิดแล้วต้องได้ 401 ⇒ ทำอัตโนมัติไม่ได้เพราะ adminGate ล็อก IP 15 นาที)
 * 🚫 **ไม่ใช่ parser** · ตะแกรงเป็นรูปของ assert ⇒ อ่านว่า "เจอเท่านี้ในตะแกรงนี้"
 *
 * ใช้: node scripts/check-attestation-ratio.mjs [--รายไฟล์]
 */
import { readdirSync, readFileSync } from "node:fs";

const ไดเรกทอรี = "scripts/tests";
/* คำรับรอง = assert ที่ตรวจ **เนื้อไฟล์/ข้อความที่คนเขียนไว้** ⇒ เขียนข้อความให้ตรงก็ผ่าน
   กลไก    = assert ที่ตรวจ **ค่าที่ได้จากการเรียกใช้จริง** ⇒ ต้องทำงานถูกจึงผ่าน */
const ดูเหมือนเนื้อไฟล์ = /\b(src|SRC|code|text|raw|เนื้อ|ซอร์ส|โค้ด|contents?)\b|readFileSync|ซอร์สไม่เอาคอมเมนต์/;

let ไฟล์ = 0;
let ไฟล์ที่อ่านซอร์ส = 0;
let กลไกแน่ = 0;      // assert ในไฟล์ที่ **ไม่เคยอ่านซอร์สเลย** ⇒ ตรวจค่าตอนรันแน่นอน
let คำรับรองแน่ = 0;  // assert ที่สิ่งถูกตรวจดูเหมือนเนื้อไฟล์ตรง ๆ
let แยกไม่ออก = 0;    // assert ในไฟล์ที่อ่านซอร์ส แต่ตัวที่ถูกตรวจชื่ออะไรก็ไม่รู้
const รายไฟล์ = [];

for (const f of readdirSync(ไดเรกทอรี).filter((x) => x.endsWith(".test.mjs"))) {
  ไฟล์ += 1;
  const s = readFileSync(`${ไดเรกทอรี}/${f}`, "utf8");
  const อ่านซอร์ส = /readFileSync|ซอร์สไม่เอาคอมเมนต์|เทียบคอมเมนต์/.test(s);
  if (อ่านซอร์ส) ไฟล์ที่อ่านซอร์ส += 1;
  let ก = 0;
  let ค = 0;
  let ม = 0;
  for (const m of s.matchAll(/\bassert(?:\.\w+)?\(\s*([^,)\n]{1,120})/g)) {
    const ตัวถูกตรวจ = m[1];
    if (ดูเหมือนเนื้อไฟล์.test(ตัวถูกตรวจ)) ค += 1;
    else if (อ่านซอร์ส) ม += 1;   // 🚫 ห้ามนับเป็นกลไก — ดูเหตุผลหัวไฟล์
    else ก += 1;
  }
  กลไกแน่ += ก;
  คำรับรองแน่ += ค;
  แยกไม่ออก += ม;
  if (ค + ม > 0) รายไฟล์.push({ f, ก, ค, ม });
}

/* 📏 0 ไฟล์ = ตก ไม่ใช่เขียว (ย้ายโฟลเดอร์/เปลี่ยนนามสกุลแล้วรายงานจะดูสวยที่สุด) */
if (ไฟล์ === 0) {
  console.error("✗ check-attestation-ratio: สแกนได้ 0 ไฟล์เทส ⇒ **ตะแกรงพัง ไม่ใช่ไม่มีปัญหา**");
  process.exit(2);
}

const รวม = กลไกแน่ + คำรับรองแน่ + แยกไม่ออก;

if (process.argv.includes("--รายไฟล์")) {
  for (const r of รายไฟล์.sort((a, b) => b.ค + b.ม - (a.ค + a.ม))) {
    console.log(`   คำรับรองแน่ ${r.ค} · แยกไม่ออก ${r.ม} · กลไก ${r.ก} — ${r.f}`);
  }
  console.log("");
}

console.log(
  "⚖️  ด่านฝั่งท่อ — **สามกอง ไม่ใช่สองกอง**\n" +
  `   ✅ กลไกแน่ ๆ ${กลไกแน่} (อยู่ในไฟล์ที่ไม่เคยอ่านซอร์สเลย ⇒ ตรวจค่าตอนรันแน่นอน)\n` +
  `   📝 คำรับรองแน่ ๆ ${คำรับรองแน่} (สิ่งที่ถูกตรวจคือเนื้อไฟล์ ⇒ เขียนข้อความให้ตรงก็ผ่าน)\n` +
  `   ❓ **แยกไม่ออกด้วยตะแกรงนี้ ${แยกไม่ออก}** (อยู่ในไฟล์ที่อ่านซอร์ส แต่ตัวแปรชื่ออื่น)\n` +
  `   📏 ตะแกรง: assert ทุกตัวใน ${ไดเรกทอรี}/*.test.mjs (${ไฟล์} ไฟล์ · อ่านซอร์ส ${ไฟล์ที่อ่านซอร์ส} ไฟล์) · รวม ${รวม} จุด\n` +
  "      🔴 **รุ่นแรกของรายงานนี้ยัดกอง ❓ ไปรวมกับ ✅ แล้วได้ 'คำรับรองแค่ 2.1%'**\n" +
  "         เอาตาดูตัวอย่างจริงแล้วพบว่าผิด: `admin-routes-use-gate` เทียบตัวแปรชื่อ `ค้าง`/`ตายแล้ว`\n" +
  "         ซึ่งเป็นรายการที่ได้จาก **การกวาดซอร์ส** ⇒ เป็นคำรับรอง แต่ถูกนับเป็นกลไก\n" +
  "         🔑 ตัวเลขที่เข้าข้างตัวเองต้องถูกสงสัยก่อนถูกรายงาน [[three-states-not-two]]\n" +
  "      ⚠️ อ่านว่า \"เจอเท่านี้ในตะแกรงนี้\" ไม่ใช่ \"มีเท่านี้\"\n" +
  (แยกไม่ออก > กลไกแน่ * 0.3
    ? "   🔴 กอง ❓ ใหญ่เกินกว่าจะสรุปอะไรได้ ⇒ **ต้องแก้ตะแกรงก่อน ห้ามรายงานสัดส่วน**\n"
    : "   ✅ กอง ❓ เล็กพอที่สัดส่วนเริ่มมีความหมาย — แต่ยังต้องดูแนวโน้ม ไม่ใช่ครั้งเดียว\n") +
  "   🔑 วิธีที่ง่ายที่สุดในการทำให้ด่านแดงกลายเป็นเขียว **คือเขียนคำรับรองเพิ่มอีกใบ**\n" +
  "      ⇒ *ต้องแก้ตัวจับ ไม่ใช่เพิ่มคำรับรอง* (ประโยคของฝั่งจอ 19 ก.ย. 2569)"
);
