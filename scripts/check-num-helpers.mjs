#!/usr/bin/env node
/* ด่านนับถอยหลัง: ตัวช่วยอ่านตัวเลขที่ **กลืน "อ่านไม่ได้" เป็น 0** ต้องลดลงเท่านั้น
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · ใบงาน `t_mu7u2c7j` (ท่านประธานติ๊กสั่ง)
 *    ทั้ง repo มีตัวช่วยชื่อ `num`/`money`/`toNum` **เขียนซ้ำกันไฟล์ละตัว** ส่วนใหญ่รูปเดียวกันเป๊ะ:
 *      `const num = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0)`
 *    ⇒ `Number(undefined)` = NaN ⇒ **0** · `Number(null)` = 0 ⇒ **0** · `Number("1,234")` = NaN ⇒ **0**
 *    ⇒ "ไม่มีข้อมูล" กับ "ศูนย์" กลายเป็นค่าเดียวกัน แล้ว **ศูนย์ทำให้คนสบายใจ**
 *
 * 🔑 ทำไมเป็น "ด่านนับถอยหลัง" ไม่ใช่ "ด่านห้ามมี":
 *    ห้ามมีทันที = ต้องแก้ 26 ไฟล์ในรอบเดียวระหว่างวันหยุด deploy โดยไม่มีทางยิงของจริงตรวจ
 *    ⇒ เสี่ยงกว่าปัญหาเดิม · และวันนี้เจอมาแล้ว 4 ครั้งว่า **ด่านที่ผูกกับรูปโค้ดขวางการแก้ที่ถูกต้อง**
 *    ⇒ ด่านนี้จึงยอมให้ของเดิมอยู่ แต่ **ห้ามเพิ่มใหม่** และบังคับให้เลขลดลงตามเวลา
 *    (ท่าเดียวกับที่ฝั่งจอทำกับ `check-unknown-vs-zero` — ตกลงกันไว้ 19 ก.ย. 2569)
 *
 * ⚠️ **ด่านนี้ไม่ได้บอกว่า 0 ผิดทุกที่** — ตัวนับ (`COUNT`) ที่ไม่มีแถว 0 คือคำตอบที่ถูก
 *    ที่ผิดคือ **เงินกับจำนวนของที่มาจากนอกบ้าน** ⇒ เลขนี้คือ "จำนวนจุดที่ต้องไปดู"
 *    ไม่ใช่ "จำนวนบั๊ก" (กฎ: grep เจอ = ที่ต้องดู ไม่ใช่ที่ต้องแก้)
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

/* 🔒 เพดานปัจจุบัน — **ลดได้ ห้ามเพิ่ม** · แก้เลขนี้ลงทุกครั้งที่ปลดไฟล์ได้จริง
      วัดเมื่อ 19 ก.ย. 2569 ด้วย **ตัวนี้เอง** หลังปลด `zort-stock.mjs` เป็นไฟล์แรก
   ⚠️ **เลขในใบงานคือ 28 · ตัวนี้นับได้ 24 — ต่างกันเพราะคนละตะแกรง ไม่ใช่เพราะของหาย**
      ใบงานใช้รูปที่กว้างกว่า (รวม `baht()` ที่เอาไปพิมพ์บนจอ · รวมตัวที่ไม่ได้คืน 0)
      🔑 บทเรียน: **เลขที่ได้จาก grep ต้องติดตะแกรงไปด้วยทุกครั้ง** ไม่งั้นสองคนวัดเรื่องเดียวกัน
         ได้เลขต่างกันแล้วเถียงกันว่าใครผิด · เลขที่ด่านนี้ใช้ = เลขที่ด่านนี้วัดเอง เท่านั้น */
const เพดาน = 24;

const ไฟล์ = [];
(function เดิน(d) {
  for (const e of readdirSync(d)) {
    if (e === "node_modules" || e === ".git" || e === "out" || e === ".next" || e === "public") continue;
    const p = join(d, e);
    if (statSync(p).isDirectory()) เดิน(p);
    else if (/\.(mjs|ts|tsx|js)$/.test(e)) ไฟล์.push(p);
  }
})(".");

/* รูปที่นับ: ประกาศตัวแปลงเลขที่ **มีทางออกเป็น 0 เมื่ออ่านไม่ได้**
   ⚠️ นับที่ "ประกาศ" ไม่ใช่ที่ "เรียกใช้" — ที่เรียกใช้มีหลายพันจุด และไม่ใช่ตัวปัญหา
      (ตัวปัญหาคือกติกาที่ตัวช่วยตัวนั้นตั้งไว้ ⇒ แก้ที่ประกาศ = แก้ทุกจุดที่เรียก) */
const ชื่อ = /(?:const|let|function)\s+(num|money|toNum|toNumber|asNum|numOf|amt|toFloat|parseNum|toAmount)\b/;
const พบ = [];
for (const f of ไฟล์) {
  const บรรทัด = readFileSync(f, "utf8").split("\n");
  for (let i = 0; i < บรรทัด.length; i++) {
    if (!ชื่อ.test(บรรทัด[i])) continue;
    const ก้อน = บรรทัด.slice(i, i + 5).join("\n");
    if (!/Number\(|parseFloat\(|parseInt\(/.test(ก้อน)) continue;
    /* คืน 0 เมื่ออ่านไม่ได้ = ตัวที่นับ · คืน null/undefined = ตัวที่ถูกแล้ว ไม่นับ */
    if (!/(\?\s*Number\([^)]*\)\s*:\s*0|\|\|\s*0\s*[;,)\n]|:\s*0\s*[;,)\n])/.test(ก้อน)) continue;
    พบ.push(`${f.replace(/^\.\//, "")}:${i + 1}`);
  }
}

const n = พบ.length;
if (n > เพดาน) {
  console.error(
    `❌ check-num-helpers: ตัวช่วยที่กลืน "อ่านไม่ได้ → 0" มี ${n} จุด แต่เพดานคือ ${เพดาน}\n` +
    `   ⇒ มีคนเพิ่มตัวใหม่ **ห้ามเพิ่ม** — ให้คืน null เมื่ออ่านไม่ได้ แล้วให้ผู้เรียกตัดสินใจ\n` +
    `   (ตัวอย่างที่ทำถูกแล้ว: netlify/lib/mkp-finance.mjs \`money()\` · netlify/lib/zort-stock.mjs)\n` +
    พบ.map((x) => `   · ${x}`).join("\n")
  );
  process.exit(1);
}
/* ⚠️ เลขจริงต่ำกว่าเพดาน = มีคนแก้แล้วแต่ไม่ได้ลดเพดาน ⇒ **ต้องฟ้อง**
   ไม่งั้นเพดานจะค้างสูงตลอดกาล แล้วด่านนี้จะกลายเป็นด่านที่ผ่านเสมอ (เขียวลวง) */
if (n < เพดาน) {
  console.error(
    `❌ check-num-helpers: เหลือ ${n} จุด ต่ำกว่าเพดาน ${เพดาน} แล้ว ⇒ **ลดเพดานในไฟล์นี้ให้เท่ากับ ${n}**\n` +
    "   (เพดานที่ไม่ตามความจริง = ด่านที่ผ่านเสมอ · เลขต้องเดินลงทางเดียว)"
  );
  process.exit(1);
}
console.log(
  `check-num-helpers: ตัวช่วยที่ยังกลืน "อ่านไม่ได้ → 0" เหลือ ${n} จุด (เพดาน ${เพดาน}) ✓\n` +
  "   📉 เลขนี้ต้องลดลงตามเวลา — เงินกับจำนวนของที่มาจากนอกบ้านต้องแยก \"ไม่รู้\" ออกจาก \"ศูนย์\""
);
