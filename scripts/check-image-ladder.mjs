/* 🔑 จับ "การประกาศอาร์เรย์ชื่อ LADDER/STEPS/ขั้นบันได" ที่มีเลขอยู่ในวงเล็บทันที
 *    ⚠️ ต้อง **ตัดคอมเมนต์ก่อน** ไม่งั้นคอมเมนต์ที่อธิบายกติกา (เช่นในใบไม้เอง หรือ
 *      ในหัวด่านนี้) จะถูกนับเป็นการประกาศ ⇒ ด่านลงโทษคนที่เขียนเอกสารกำกับ
 *      (คลาสที่ทีมเหยียบ 4 รอบ: "ตะแกรงที่ไม่ตัดคอมเมนต์") */
const รูปประกาศ = /(?:const|let|var|export\s+const)\s+(LADDER|STEPS|ขั้นบันได)\s*(?::[^=]*)?=\s*\[([^\]]*)\]/;

/* 🔑 **ชื่อตัวแปรอย่างเดียวตัดสินไม่ได้** — ต้องดูรูปของค่าด้วย
 *    เจอของจริงตอนเขียนด่านนี้: `src/lib/social.ts` มี `const STEPS = [0, 0.5, 0.9]`
 *    (ระดับความลึกการดูคลิป) และ `scripts/video-to-r2.mjs` มี `LADDER` เป็น**ออบเจกต์**
 *    (ความสูงคลิป) ⇒ ชื่อซ้ำ แต่คนละเรื่องสิ้นเชิง · ถ้าจับด้วยชื่อ ด่านนี้จะสั่งคนไป
 *    แก้ของที่ยังดีอยู่ (คลาส: **แดงลวงแพงกว่าเขียวลวง เพราะคนลงมือแก้ตาม**)
 * ⇒ เกณฑ์: ทุกสมาชิกเป็น **จำนวนเต็ม** · มี ≥2 ตัว · ตัวโตสุด ≥128 (หน่วยพิกเซล)
 * 📌 ขอบเขตที่เกณฑ์นี้ปล่อย (เขียนไว้ ไม่ใช่ซ่อน):
 *    · ประกาศขั้นเดียว (`[128]`) ⇒ ไม่จับ — แต่สำเนาขั้นเดียวไม่มีความหมายในระบบนี้
 *    · ประกาศด้วยตัวแปร (`[A, B]`) ⇒ ไม่จับ — เลขไม่อยู่ในซอร์สให้เทียบตั้งแต่ต้น */
function ดูเหมือนขั้นบันไดรูป(ในวงเล็บ) {
  const ชิ้น = ในวงเล็บ.split(",").map((x) => x.trim()).filter(Boolean);
  if (ชิ้น.length < 2) return false;
  if (!ชิ้น.every((x) => /^\d+$/.test(x))) return false;
  return Math.max(...ชิ้น.map(Number)) >= 128;
}

/* 🔑 **ตัดเนื้อในเครื่องหมายคำพูดออกก่อนกวาดไฟล์** — การประกาศไม่เคยอยู่ในสตริง
 *    เจอของจริงตอนเขียนด่านนี้: `scripts/lib/ทะเบียนด่าน.mjs` เก็บ**สูตรปลูก**
 *    และ `scripts/tests/image-ladder.test.mjs` เก็บ**ฟิกซ์เจอร์** เป็นสตริงที่หน้าตา
 *    เหมือนการประกาศเป๊ะ ⇒ ด่านจับของตัวเองแล้วสั่งให้ไปแก้ของที่ถูกอยู่
 *    ⇒ เดิมแก้ด้วยการ "ลงทะเบียนยกเว้นรายไฟล์" ซึ่งโตขึ้นเรื่อย ๆ และปิดตาด่าน
 *      กับโค้ดจริงในไฟล์นั้นไปด้วย · ตัดสตริงแก้ที่ต้นเหตุและครอบกรณีในอนาคตเอง
 * 📌 ขอบเขต: เป็นตัวตัดแบบหยาบ (ไม่เข้าใจ escape ซ้อนชั้นทุกแบบ)
 *    ⇒ ความผิดพลาดจะไปทาง **ไม่จับ** (false negative) ไม่ใช่จับผิดคน
 *      ซึ่งเป็นทิศที่เลือกไว้โดยตั้งใจ: แดงลวงทำให้คนไปพังของที่ยังดี */
function ตัดสตริง(s) {
  return s
    .replace(/'(?:\\.|[^'\\\n])*'/g, "''")
    .replace(/"(?:\\.|[^"\\\n])*"/g, '""')
    .replace(/`(?:\\.|[^`\\])*`/g, "``");
}

/** จับว่า "ไฟล์นี้ประกาศขั้นบันไดขนาดรูปเองไหม" — ชื่อ **และ** รูปของค่าต้องเข้าทั้งคู่ */
function ประกาศขั้นบันไดรูป(เนื้อ) {
  const m = รูปประกาศ.exec(เนื้อ);
  return m && ดูเหมือนขั้นบันไดรูป(m[2]) ? m : null;
}

/* ─────────────────────────────────────────────────────────────────────────────
 * 🧪 ตัวควบคุมสองทาง (รันด้วย `--selftest`) — **ด่านที่ไม่เคยถูกพิสูจน์ว่าแยกแยะได้
 *    ให้ผลเขียวที่แปลว่า "ยังไม่เจอ" ไม่ใช่ "ไม่มี"**
 * ต้องจับ: สำเนาจริง · ต้องไม่จับ: ของที่ชื่อซ้ำแต่คนละเรื่อง
 * ───────────────────────────────────────────────────────────────────────────── */
if (process.argv.includes("--selftest")) {
  const ต้องจับ = [
    ['const LADDER = [128, 256, 384, 640];', "สำเนาตรง ๆ"],
    ['export const LADDER = [128,256,384,512];', "สำเนาที่ค่าเพี้ยน (อันตรายที่สุด)"],
    ['const STEPS = [128, 256, 384, 640] as const', "ชื่อ STEPS แบบฝั่งจอ"],
    ['const ขั้นบันได = [256, 640];', "ชื่อไทย"],
  ];
  const ต้องไม่จับ = [
    ['const STEPS = [0, 0.5, 0.9];', "ความลึกการดูคลิป (social.ts ของจริง)"],
    ['const LADDER = [\n  { h: 480 },\n];', "ความสูงคลิปเป็นออบเจกต์ (video-to-r2 ของจริง)"],
    ['const STEPS = [1, 2, 3];', "เลขเล็ก ไม่ใช่พิกเซล"],
    ['const LADDER = [W];', "ประกาศด้วยตัวแปร — เลขไม่อยู่ในซอร์ส"],
  ];
  let ตก = 0;
  for (const [โค้ด, ชื่อ] of ต้องจับ) {
    const ได้ = !!ประกาศขั้นบันไดรูป(โค้ด);
    if (!ได้) { console.error(`🔴 ต้องจับแต่ไม่จับ: ${ชื่อ}`); ตก++; } else console.log(`   ✅ จับได้: ${ชื่อ}`);
  }
  for (const [โค้ด, ชื่อ] of ต้องไม่จับ) {
    const ได้ = !!ประกาศขั้นบันไดรูป(โค้ด);
    if (ได้) { console.error(`🔴 ไม่ควรจับแต่จับ (แดงลวง): ${ชื่อ}`); ตก++; } else console.log(`   ✅ เว้นถูก: ${ชื่อ}`);
  }
  console.log(ตก ? `🔴 ตัวควบคุมตก ${ตก} ข้อ` : "✅ ตัวควบคุมสองทางผ่านครบ — ด่านนี้แยกแยะได้จริง");
  process.exit(ตก ? 2 : 0);
}

function ไล่ไฟล์(d, เก็บ = []) {
  for (const ชื่อ of readdirSync(d)) {
    if (ชื่อ === "node_modules" || ชื่อ.startsWith(".")) continue;
    const p = join(d, ชื่อ);
    if (statSync(p).isDirectory()) ไล่ไฟล์(p, เก็บ);
    else if (นามสกุล.test(ชื่อ)) เก็บ.push(p);
  }
  return เก็บ;
}

const ไฟล์ทั้งหมด = โฟลเดอร์.flatMap((d) => ไล่ไฟล์(d));
if (ไฟล์ทั้งหมด.length < 50) {
  console.error(`🔴 ไล่ไฟล์ได้แค่ ${ไฟล์ทั้งหมด.length} ไฟล์ ⇒ **ตะแกรงพัง ไม่ใช่ไม่มีของ**`);
  process.exit(2);
}

/* 🔒 ด่านแรก: ตัวแหล่งเดียวต้องมีจริง และต้อง **ไม่ import อะไรเลย**
 *    (ใบไม้ที่เริ่ม import = ลากของเข้าบันเดิลเบราว์เซอร์ลูกค้าได้ทันที) */
let ใบไม้;
try { ใบไม้ = readFileSync(แหล่งเดียว, "utf8"); }
catch { console.error(`🔴 ไม่มี ${แหล่งเดียว} ⇒ ไม่มีแหล่งเดียวให้ชี้ — วัดต่อไม่ได้`); process.exit(2); }
const ใบไม้ไร้คอมเมนต์ = ตัดคอมเมนต์(ใบไม้, แหล่งเดียว, { คงเลขบรรทัด: true });
const ปัญหา = [];
if (/^\s*(import|require)\b/m.test(ใบไม้ไร้คอมเมนต์)) {
  ปัญหา.push(`${แหล่งเดียว} เริ่ม import ของอื่น — ใบไม้ต้องไม่มี dependency (ดูเหตุผลในไฟล์นั้น)`);
}
if (!ประกาศขั้นบันไดรูป(ใบไม้ไร้คอมเมนต์)) {
  console.error(`🔴 สกัดค่าใน ${แหล่งเดียว} ไม่ได้ ⇒ **ถือว่าตก** (รูปการเขียนคงเปลี่ยน)`);
  process.exit(2);
}

/* ด่านที่สอง: ห้ามไฟล์อื่นประกาศเอง */
for (const f of ไฟล์ทั้งหมด) {
  const rel = f.replace(/^\.\//, "");
  if (rel === แหล่งเดียว) continue;
  const เนื้อ = ตัดสตริง(ตัดคอมเมนต์(readFileSync(f, "utf8"), f, { คงเลขบรรทัด: true }));
  if (!ประกาศขั้นบันไดรูป(เนื้อ)) continue;
  const เหตุยกเว้น = ยกเว้น.get(rel);
  if (เหตุยกเว้น) continue;
  const บรรทัด = เนื้อ.split("\n").findIndex((l) => ประกาศขั้นบันไดรูป(l)) + 1;
  ปัญหา.push(`${rel}:${บรรทัด} ประกาศขั้นบันไดเอง — ต้อง \`import { LADDER } from "…/image-ladder.mjs"\``);
}

if (ปัญหา.length) {
  console.error("🔴 ขั้นบันไดขนาดรูปมีสำเนาเกินหนึ่ง (หรือใบไม้ไม่สะอาด)");
  for (const p of ปัญหา) console.error("   · " + p);
  console.error("   ⇒ ไม่ตรงกันเมื่อไหร่ = 404 รูปหายทั้งเว็บ · ฝั่งจอกลายเป็นกล่องเทาแบบไม่มี error");
  process.exit(1);
}

/* ⚠️ นับเฉพาะไฟล์ที่ **`import` จริง** — ไม่นับไฟล์ที่เพียง*เอ่ยถึง*ในคอมเมนต์
 *    (เช่น `check-twin-tables.mjs` ที่อธิบายประวัติการย้าย) ไม่งั้นเลข "ผู้ใช้ N"
 *    จะถูกอ่านเป็นหลักฐานว่ามีคนใช้จริง N ราย ซึ่งไม่จริง
 *    🔑 คลาสที่ทีมจดไว้: **ตัววัดที่นับ "การเอ่ยถึง" จะให้เลขดีขึ้นเองทุกครั้งที่เราขยันเขียนเอกสาร** */
const ใช้แหล่งเดียว = ไฟล์ทั้งหมด.filter((f) => {
  if (f.endsWith("image-ladder.mjs")) return false;
  const เนื้อ = ตัดคอมเมนต์(readFileSync(f, "utf8"), f, { คงเลขบรรทัด: true });
  return /^\s*import[^;]*image-ladder\.mjs/m.test(เนื้อ);
});
console.log(`✅ ขั้นบันไดขนาดรูปมีแหล่งเดียว (${แหล่งเดียว}) · ผู้ใช้ ${ใช้แหล่งเดียว.length} ไฟล์`);
for (const f of ใช้แหล่งเดียว) console.log(`   · ${f.replace(/^\.\//, "")}`);
for (const [f, เหตุ] of ยกเว้น) console.log(`   ⏭️ เว้น ${f} — ${เหตุ}`);
console.log("   ⚠️ ขอบเขต: ฝั่งจอคนละรีโป **ด่านนี้มองไม่เห็น** — เทียบที่ฝั่งเขาผ่านสารบัญ `imageLadder`");
