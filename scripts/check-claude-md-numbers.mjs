/* 🔑 **ทุกแถวต้องมี `คำสั่งนับ`** (ฝั่งจอทำเป็นด่านก่อน แล้วบอกมา 20 ก.ย. 2569 · เหตุผลมาจากฝั่งผม)
   เลขที่ไม่มีคำสั่งกำกับ **จะถูกนับด้วยวิธีอื่นในรอบหน้าเสมอ** แล้วคนรอบหน้าจะสรุปว่า
   **คู่มือผิด ทั้งที่คู่มือถูก** — ของจริงในไฟล์นี้: `ls` ไม่นับไฟล์ซ่อน แต่ `readdirSync` นับ
   ⇒ ต่างกัน 1 (5824 vs 5823) ⇒ ด่านเกือบร้องใส่คู่มือที่ถูกต้อง
   🚫 ไม่มีช่องนี้ ⇒ **ถือว่าตะแกรงพัง (exit 1)** ไม่ใช่ "คู่มือผิด" */

/** ทะเบียน: `หา` ต้องผูกกับ **ถ้อยคำที่มีความหมาย** ห้ามผูกกับช่องว่างจัดคอลัมน์
 *  🔴 ฝั่งจอผูกกับช่องว่างที่เดาเอา ⇒ หาไม่เจอตั้งแต่รันครั้งแรก (โชคดีที่ทางแดงนั้นถูกเดินจริง) */
