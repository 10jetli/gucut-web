#!/usr/bin/env node
/* 📖 เทียบ **ตัวเลขที่ CLAUDE.md อ้าง** กับที่วัดได้จริงในเครื่อง
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ฝั่งจอไล่คู่มือฝั่งเขาด้วยมือแล้วเจอค้าง 2 จุด
 *    (เส้นนอกกำแพงล็อกอิน: คู่มือบอก 3 ของจริง 12 · ชิ้นส่วน UI: บอก 4 ของจริง 8)
 *    ⇒ แล้วเขาทำเป็นด่าน ด้วยเหตุผลที่ผมเสนอ: **คู่มือบอกจำนวน · ด่านเป็นคนเฝ้าจำนวนนั้น**
 *    ⇒ ฝั่งท่อทำตัวเดียวกัน เพราะคู่มือท่อก็มีเลขพิมพ์มืออยู่ 4 ตัว
 *    ⚠️ วันนี้เลขทั้งสี่ยัง **ตรง** — แต่เหตุที่ตรงคือ **ของไม่ขยับตั้งแต่ปิด Shopify**
 *       🔑 ตัวเลขที่ยังตรงเพราะของไม่ขยับ **ไม่ได้พิสูจน์ว่ามีกลไกเฝ้ามันอยู่**
 *
 * 🚫 **ตัวเลขไม่ตรง ⇒ ดังแต่ไม่ทำให้ build ตก** (เกณฑ์ของฝั่งจอ 19 ก.ย. เย็น)
 *    เกณฑ์แบ่งความรุนแรง **ไม่ใช่ "เรื่องนี้สำคัญแค่ไหน" แต่คือ "คนที่เจอแก้ได้เองไหม"**
 *    ⇒ `CLAUDE.md` เป็นเอกสารของท่านประธาน **เราแก้เองไม่ได้** ⇒ ปล่อยให้ตก = ด่านที่คนเจอแก้ไม่ได้
 *      ⇒ จะถูกถอดทั้งด่านภายในวันเดียว แล้วเราเสีย **ทั้งข้อสำคัญและตัวเฝ้า** ไปพร้อมกัน
 * 🔒 **แต่สองอย่างนี้ทำให้ตก เพราะแก้ได้โดยไม่ต้องแตะ CLAUDE.md**
 *    · หาประโยคที่ลงทะเบียนไม่เจอ (คู่มือถูกเรียบเรียงใหม่) ⇒ ตัวนับเงียบ = **เขียวตลอดกาล**
 *    · ทะเบียนว่าง ⇒ ไม่มีอะไรให้ตรวจ
 */
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ราก = fileURLToPath(new URL("..", import.meta.url));
const คู่มือ = readFileSync(`${ราก}CLAUDE.md`, "utf8");

/* 🔴 **ต้องนับด้วย "วิธีเดียวกับที่คู่มือประกาศ"** (แก้ทันทีรอบแรก 19 ก.ย. เย็น)
   คู่มือเขียนวิธีนับไว้ตรง ๆ ว่า `ls public/img | wc -l` — และ `ls` **ไม่นับไฟล์ที่ขึ้นต้นด้วยจุด**
   ⇒ รอบแรกผมใช้ `readdirSync().length` (นับ dotfile ด้วย) ⇒ ได้ 5824/3118 vs คู่มือ 5823/3117
   ⇒ **ด่านเกือบรายงานว่าคู่มือค้างไป 1 ทั้งที่คู่มือถูก และตัวนับของผมต่างวิธี**
   🔑 คลาสเดิมของวันนี้: **สองวิธีนับของเดียวกัน ให้เลขต่างกัน** ⇒ ด่านต้องใช้วิธีที่ **เอกสารประกาศ**
      ไม่ใช่วิธีที่สะดวกกับภาษาที่เราเขียนด่าน (ไม่งั้นได้ด่านที่ร้องใส่ของถูก) */
const ไม่ใช่ไฟล์ซ่อน = (ชื่อ) => !ชื่อ.startsWith(".");
const นับไฟล์ = (d, กรอง = ไม่ใช่ไฟล์ซ่อน) => readdirSync(`${ราก}${d}`).filter(กรอง).length;
const นับใน = (ไฟล์) => {
  const j = JSON.parse(readFileSync(`${ราก}${ไฟล์}`, "utf8"));
  return Array.isArray(j) ? j.length : Object.keys(j).length;
};

/** ทะเบียน: `หา` ต้องผูกกับ **ถ้อยคำที่มีความหมาย** ห้ามผูกกับช่องว่างจัดคอลัมน์
 *  🔴 ฝั่งจอผูกกับช่องว่างที่เดาเอา ⇒ หาไม่เจอตั้งแต่รันครั้งแรก (โชคดีที่ทางแดงนั้นถูกเดินจริง) */
const ทะเบียน = [
  { ชื่อ: "สินค้าใน products.json", หา: /products\.json[^\n]*?วัดจริง[^\n]*?:\s*([\d,]+)\s*รายการ/, วัด: () => นับใน("src/data/products.json") },
  { ชื่อ: "รูปสินค้าใน public/img", หา: /ls public\/img \| wc -l[^\n]*?:\s*([\d,]+)\s*ไฟล์/, วัด: () => นับไฟล์("public/img") },
  { ชื่อ: "รูปรีวิวใน public/rv-img", หา: /ls public\/rv-img \| wc -l[^\n]*?:\s*([\d,]+)\s*ไฟล์/, วัด: () => นับไฟล์("public/rv-img") },
  { ชื่อ: "บทความใน articles.json", หา: /articles\.json[^\n]*?วัดจริง[^\n]*?:\s*([\d,]+)\s*บทความ/, วัด: () => นับใน("src/data/articles.json") },
];

if (!ทะเบียน.length) {
  console.error("✗ check-claude-md-numbers: ทะเบียนว่าง ⇒ ไม่มีอะไรให้ตรวจ (ตะแกรงพัง ไม่ใช่ผ่าน)");
  process.exit(2);
}

const หาไม่เจอ = [];
const ไม่ตรง = [];
const ตรง = [];
for (const t of ทะเบียน) {
  const m = คู่มือ.match(t.หา);
  if (!m) { หาไม่เจอ.push(t.ชื่อ); continue; }
  const ในคู่มือ = Number(m[1].replace(/,/g, ""));
  let จริง = null;
  try { จริง = t.วัด(); } catch (e) { หาไม่เจอ.push(`${t.ชื่อ} (วัดไม่ได้: ${String(e?.message ?? e).slice(0, 60)})`); continue; }
  if (ในคู่มือ === จริง) ตรง.push(`${t.ชื่อ}=${จริง}`);
  else ไม่ตรง.push(`${t.ชื่อ}: คู่มือบอก ${ในคู่มือ} · วัดได้ ${จริง}`);
}

console.log(`📖 เทียบตัวเลขใน CLAUDE.md กับของจริง — ตรง ${ตรง.length} · ไม่ตรง ${ไม่ตรง.length} · หาประโยคไม่เจอ ${หาไม่เจอ.length}`);
if (ตรง.length) console.log(`   ✅ ${ตรง.join(" · ")}`);
for (const x of ไม่ตรง) console.log(`   🔴 ${x}`);
if (ไม่ตรง.length) {
  console.log(
    "   ⚠️ **นี่คือหนี้ ไม่ใช่ผ่าน** — แต่ไม่ทำให้ build ตกโดยตั้งใจ เพราะ `CLAUDE.md` แก้เองไม่ได้\n" +
    "      ⇒ ต้องขออนุมัติท่านประธานก่อนแก้ถ้อยคำ · ด่านที่คนเจอแก้ไม่ได้ จะถูกถอดทั้งด่าน"
  );
}
/* ── 🔴 ชั้นที่สอง: **เลขเดียวกันที่เขียนหลายที่ ต้องตรงกันเอง** (เพิ่ม 20 ก.ย. 2569) ──
   ที่มา: ฝั่งจอเจอว่ากรณี "ปลูกนอกขอบเขต" กับ "ขอบเขตแคบเกินไป" **เป็นพร้อมกันได้**
   และถ้าหยุดที่ข้อแรก (แก้สูตรปลูกให้ผ่าน) **รูจริงจะยังอยู่และไม่มีใครรู้**
   ⇒ ผมมีเคสนั้นเป๊ะ: `2,483 รายการ` อยู่ใน CLAUDE.md **สองที่** (บรรทัด 171 และ 198)
     แต่ `หา` ของชั้นแรกผูกกับคำว่า `products.json` ⇒ **อ่านที่เดียว**
     ⇒ ถ้าอีกที่ค้างเลขเก่า ⇒ **ด่านเงียบ** ⇒ คู่มือขัดกับตัวเองโดยไม่มีอะไรฟ้อง
   🔑 ชั้นนี้ตรวจได้ **โดยไม่ต้องรู้ว่าจุดไหนคือจุดที่ถูก** — แค่ต้องตรงกัน
   🔴🔴 **และเคสที่จุดประกายชั้นนี้ ชั้นนี้เองก็จับไม่ได้ — ต้องเขียนไว้ ไม่ใช่อ้างว่าอุดแล้ว**
   ปลูกจริงแล้ว (แก้เลขที่บรรทัดซึ่งชั้นแรกไม่อ่าน) ⇒ **ชั้นสองยังเงียบ**
   เหตุ: กุญแจคือ (แหล่งที่นับ + หน่วย) · บรรทัด 198 ได้กุญแจ `products.json|รายการ`
   แต่บรรทัด 171 เขียนว่า *"อยู่ในโค้ด ไม่เรียก API ใคร · วัดจริง …: 2,483 รายการ"*
   ⇒ ได้กุญแจ `API|รายการ` ⇒ **คนละกุญแจ ⇒ ไม่ถูกเทียบกัน**
   🔑 ⇒ **สองบรรทัดนั้นพูดถึงของเดียวกันโดยไม่มีคำร่วมที่เครื่องจับได้** ⇒ ตะแกรงข้อความทำไม่ได้
   ⇒ ⇒ และรอบแรกผมใช้ "หน่วย" อย่างเดียวเป็นกุญแจ ซึ่ง **จับเคสนี้ได้** แต่ให้แดงลวงสองหน่วย
     (`ไฟล์` ใช้กับสามอย่าง · `ตัว` ใช้กับสองอย่าง)
     ⇒ **ผมแลกทิศหนึ่งกับอีกทิศ** = คลาส `noise-filters-eat-real-cases` ที่คลังเรามีอยู่แล้ว
   📌 **สิ่งที่ชั้นนี้ทำได้จริง**: จับ "เลขเดียวกันของแหล่งเดียวกันเขียนต่างกัน" (8 หน่วย · ตอนนี้ตรงหมด)
   📌 **สิ่งที่ยังทำไม่ได้ (หนี้)**: สองประโยคที่พูดถึงของเดียวกันด้วยคำต่างกันสิ้นเชิง
      ⇒ ทางที่จะใช้: ให้คู่มือมี **ป้ายกำกับร่วม** ที่จุดเดียวกัน (เช่น `⟨นับ:products.json⟩`)
        ⇒ ต้องขออนุมัติท่านประธานก่อน เพราะเป็นการแก้ถ้อยคำในเอกสารของท่าน */
{
  /* 🔴 **รอบแรกผมใช้ "หน่วย" อย่างเดียวเป็นกุญแจ ⇒ แดงลวงทันที**
     หน่วย `ไฟล์` ใช้กับสามอย่างคนละเรื่อง (รูปสินค้า 5,823 · รูปรีวิว 3,117 · รูปบทความ 17)
     และ `ตัว` ใช้กับบอต AI 19 กับบอตทั้งหมด 28 ⇒ **ต่างกันโดยชอบธรรม**
     🔑 กุญแจต้องเป็น **(สิ่งที่ถูกนับ + หน่วย)** ไม่ใช่หน่วยเดียว —
        กับดักเดียวกับที่ทีมไล่กันทั้งคืน: กุญแจแคบ/กว้างเกินไปทำให้ผลไม่มีความหมาย */
  const กลุ่ม = new Map(); // "แหล่ง|หน่วย" → Map ของเลข
  for (const m of คู่มือ.matchAll(/([\w.\/-]+)[^\n]{0,40}วัดจริง[^\n]*?:\s*([\d,]+)\s*([ก-๙A-Za-z.\/-]+)/g)) {
    const เลข = m[2].replace(/,/g, "");
    const หน่วย = `${m[1]}|${m[3].trim()}`;
    if (!กลุ่ม.has(หน่วย)) กลุ่ม.set(หน่วย, new Map());
    const ใน = กลุ่ม.get(หน่วย);
    ใน.set(เลข, (ใน.get(เลข) ?? 0) + 1);
  }
  const ขัดกันเอง = [...กลุ่ม.entries()].filter(([, ใน]) => ใน.size > 1);
  console.log(
    `📖 ชั้นสอง — เลขที่เขียนหลายที่ต้องตรงกันเอง: ตรวจ ${กลุ่ม.size} หน่วย · ` +
    `**ขัดกันเอง ${ขัดกันเอง.length} หน่วย**`
  );
  for (const [หน่วย, ใน] of ขัดกันเอง) {
    console.log(`   🔴 หน่วย "${หน่วย}" เขียนไว้หลายเลข: ${[...ใน.keys()].join(" vs ")}`);
  }
  if (ขัดกันเอง.length) {
    console.log(
      "   ⚠️ **หนี้เหมือนชั้นแรก ไม่ทำให้ build ตก** (CLAUDE.md แก้เองไม่ได้ ต้องขออนุมัติ)\n" +
      "      🔑 แต่ข้อนี้ต่างจากชั้นแรก: มัน **ไม่ต้องรู้ว่าจุดไหนถูก** ⇒ จับ 'ที่หนึ่งค้าง' ได้เสมอ"
    );
  }
}

if (หาไม่เจอ.length) {
  console.error(
    `✗ หาประโยคที่ลงทะเบียนไม่เจอ: ${หาไม่เจอ.join(" · ")}\n` +
    "   🔑 **ทางนี้ทำให้ตก** เพราะแก้ได้โดยไม่ต้องแตะ CLAUDE.md (แก้ `หา` ในไฟล์นี้)\n" +
    "   ⇒ ถ้าปล่อยผ่าน ตัวนับจะเงียบไปเฉย ๆ = **เขียวตลอดกาล** ซึ่งคือโรคที่ด่านนี้มีไว้กัน"
  );
  process.exit(1);
}
