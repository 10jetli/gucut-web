#!/usr/bin/env node
/* 🏷️ ยิงของจริง: **เส้น API ไหนแยก "เราถามผิด" จาก "ร้านไม่มีของ" ได้**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — คุณส้มวัดฝั่งจอ: 83 ไฟล์ยิงท่อนี้ · อ่านช่อง `fallthrough` แค่ 9
 *    และเขาชี้ว่าฝั่งเขา **รอดเพราะโครงสร้าง ไม่ใช่เพราะเลือกไว้**
 *    ⇒ ผมส่องกลับฝั่งท่อ แล้วพบว่ารูปนี้หนักกว่า: **ป้ายมีอยู่เส้นเดียว (`core.mjs`)**
 *
 * 🔴 **และผมพลาดสองรอบก่อนจะมาถึงตัวนี้ — จดไว้เพราะมันคือเหตุผลที่ตัวนี้ต้องยิง ไม่ใช่อ่านซอร์ส**
 *    รอบ ① เกณฑ์ "อ่านชื่อพารามิเตอร์ ≥2 ชื่อ" ⇒ ได้ **11 เส้น** — กว้างเกิน
 *          เพราะนับ **ตัวเลือก** (`size` `days` `baht` `cursor`) เป็น **ตัวแจกงาน**
 *    รอบ ② เกณฑ์ "ชื่อที่โผล่ในเงื่อนไข `if`" ⇒ ได้ **5 เส้น** — แคบเกิน
 *          เพราะ **พลาด `social` กับ `channels` ที่ยิงแล้วตกไปคำตอบตั้งต้นจริง**
 *    🔑 ⇒ **ตัวเดียวที่ตัดสินได้คือการยิง** ⇒ จึงเป็น `probe-` ไม่ใช่ `check-`
 *       และเพราะมันต้องมีเว็บ **จึงรันมือ ไม่เข้า prebuild** (กฎห้ามเช็คอัตโนมัติ)
 *
 * 🚫 **ยิงเฉพาะเส้นในรายชื่อข้างล่าง — ห้ามกวาดทั้งโฟลเดอร์**
 *    เส้นอย่าง `beam-test` (สร้างใบชำระเงิน) และ `lazada|tiktok|shopee` (ดึง/เขียนของจริง)
 *    **GET ก็เปลี่ยนข้อมูลได้** ⇒ "อ่านอย่างเดียว" ไม่ใช่คุณสมบัติของคำกริยา HTTP
 *
 * ใช้: node scripts/probe-fallthrough-markers.mjs   (ต้องมี ~/.gucut-admin-key)
 */
import { readFileSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { homedir } from "node:os";

const ฐาน = process.env.PROBE_BASE || "https://gucut.com";
const ชื่อปลอม = "ไม่มีเส้นนี้จริง";
/* เส้นที่ **ยิงแล้วไม่เปลี่ยนข้อมูล** — พิสูจน์แล้วด้วยการอ่านซอร์สก่อนยิงทุกตัว 20 ก.ย. 2569 */
const เส้น = ["core", "orders", "permit-doc", "time", "social", "chat", "channels"];

let คีย์ = "";
try { คีย์ = readFileSync(`${homedir()}/.gucut-admin-key`, "utf8").trim(); } catch (e) {
  console.error(`🔴 อ่านรหัสหลังร้านไม่ได้: ${String(e?.message || e).slice(0, 120)}`);
  console.error("   ⇒ **ตัดสินไม่ได้** ไม่ใช่ผ่าน (ถ้าไม่มีรหัส ทุกเส้นจะตอบ 401 ซึ่งดูเหมือนผลวัดที่ดี)");
  process.exit(1);
}

/* 🔑 **ตัวส่วนต้องพิมพ์คู่กับตัวเศษเสมอ** — ข้อของคุณส้ม 20 ก.ย. 2569 (ใบ S2 รอบสาม):
   **ตัวเศษที่ไม่มีตัวส่วน ไม่ได้อ่านว่า "ไม่รู้" — มันอ่านว่า "น้อย"**
   ⇒ ความเงียบของตัวส่วนทำงานเป็น **คำยืนยัน** ⇒ "วัด 7 เส้น" อ่านเหมือนครอบเกือบหมด
   🔴 ผมเขียนไฟล์นี้เสร็จโดยไม่มีบรรทัดนี้ **ในวันเดียวกับที่รับกติกานั้นมา** */
const เส้นทั้งร้าน = readdirSync("netlify/functions")
  .filter((n) => n.endsWith(".mjs"))
  .filter((n) => /export const config\s*=\s*\{[^}]*path/.test(readFileSync(`netlify/functions/${n}`, "utf8")));

const ผล = [];
for (const s of เส้น) {
  const u = `${ฐาน}/api/${s}?${encodeURIComponent(ชื่อปลอม)}=1`;
  let r, เนื้อ = "", d = null;
  try {
    r = await fetch(u, { headers: { "x-admin-key": คีย์ } });
    เนื้อ = await r.text();
    try { d = JSON.parse(เนื้อ); } catch {}
  } catch (e) { ผล.push({ s, ตัดสินไม่ได้: String(e?.message || e).slice(0, 80) }); continue; }
  const มีป้าย = d && typeof d === "object" && d.fallthrough === true;
  const ปฏิเสธ = r.status >= 400;
  ผล.push({
    s, status: r.status, ไบต์: เนื้อ.length,
    แยกได้: มีป้าย || ปฏิเสธ,
    ทาง: มีป้าย ? "ป้าย fallthrough" : ปฏิเสธ ? `ปฏิเสธ ${r.status}` : "— ตกไปคำตอบตั้งต้นเงียบ ๆ",
    คีย์แรก: d && typeof d === "object" && !Array.isArray(d) ? Object.keys(d).slice(0, 4) : null,
  });
}

const แยกได้ = ผล.filter((x) => x.แยกได้).length;
const เงียบ = ผล.filter((x) => x.แยกได้ === false);
const ตัดสินไม่ได้ = ผล.filter((x) => x.ตัดสินไม่ได้);
/* 🔴 **ตัวเลขนี้ประกอบจากสองยุค — เพิ่มป้าย 20 ก.ย. 2569 (ข้อของฝั่งจอ)**
   `เส้นทั้งร้าน` นับจาก **ซอร์สในเครื่อง** · ผลการยิงมาจาก **ท่อที่ deploy อยู่**
   ⇒ วันที่มีคอมมิตค้าง (วันนี้ 110 ใบ) **สองข้างของเศษส่วนนี้มาจากโค้ดคนละชุด**
   ⇒ ⇒ ถ้าผมเพิ่มเส้นใหม่ในเครื่อง ตัวส่วนโตขึ้นทันที **แต่ท่อยังไม่มีเส้นนั้น**
      ⇒ สัดส่วนจะตกลงโดยที่ **ไม่มีอะไรแย่ลงเลยในโลกจริง**
   🔑 ฝั่งจอสรุปรูปร่วมของทั้งวันไว้: **ตัวเลขที่ประกอบจากสองแหล่ง ต้องพกยุคของทั้งสองแหล่งมาด้วย**
      (เจอรูปนี้ 3 ครั้งในวันเดียว: `x-core-build` · `check-pipe-keys` · `ครอบคลุม` ของสมุดจดเวลา) */
/* 🔴 `await` ใน IIFE ธรรมดาไม่ได้ (ต้องเป็น async) — ใช้ import แบบ static แทน
   ⇒ node --check จับได้ทันที **เพราะเป็น SyntaxError** (ต่างจาก ReferenceError ที่มันมองไม่เห็น) */
const คอมมิตค้าง = (() => {
  try {
    return Number(execFileSync("git", ["rev-list", "--count", "origin/main..HEAD"], { encoding: "utf8" }).trim());
  } catch { return null; }
})();
const สัดส่วน = ((เส้น.length / เส้นทั้งร้าน.length) * 100).toFixed(0);
console.log(
  `🏷️ ยิงชื่อพารามิเตอร์ที่ไม่มีจริงใส่ **${เส้น.length} เส้น จากเส้น API ทั้งหมด ${เส้นทั้งร้าน.length} เส้น (${สัดส่วน}%)** ที่ ${ฐาน}\n` +
  `   ⇒ **${เส้นทั้งร้าน.length - เส้น.length} เส้นไม่ได้วัด** — ไม่ใช่ "ผ่าน" คือ **ยังไม่รู้**` +
  (คอมมิตค้าง
    ? `\n   ⚠️ **ตัวส่วนมาจากซอร์สในเครื่อง · ผลการยิงมาจากท่อที่ deploy** และตอนนี้มีคอมมิตค้าง **${คอมมิตค้าง} ใบ**\n` +
      "      ⇒ สองข้างของเศษส่วนนี้ **มาจากโค้ดคนละชุด** ⇒ อ่านสัดส่วนเป็นค่าประมาณ ไม่ใช่ข้อเท็จจริง"
    : "")
);
for (const x of ผล) {
  if (x.ตัดสินไม่ได้) { console.log(`   ❓ ${x.s} — ตัดสินไม่ได้: ${x.ตัดสินไม่ได้}`); continue; }
  console.log(`   ${x.แยกได้ ? "✅" : "🔴"} ${x.s.padEnd(11)} ${String(x.status)} · ${String(x.ไบต์).padStart(6)} ไบต์ · ${x.ทาง}` +
    (x.คีย์แรก ? `  ${JSON.stringify(x.คีย์แรก)}` : ""));
}
console.log(
  `\n📊 แยก "ถามผิด" ออกจาก "ไม่มีของ" ได้ **${แยกได้}/${เส้น.length}** เส้นที่วัด ` +
  `(= ${แยกได้}/${เส้นทั้งร้าน.length} ของเส้นทั้งร้าน — ตัวส่วนที่ใหญ่กว่าคือตัวที่ตอบคำถามจริง)` +
  (ตัดสินไม่ได้.length ? ` · ตัดสินไม่ได้ ${ตัดสินไม่ได้.length} เส้น` : "") +
  `\n⚠️ ขอบเขต: **${เส้น.length} เส้นนี้เท่านั้น** — เส้นที่ยิงแล้วอาจเปลี่ยนข้อมูล (\`beam-test\` · ` +
  `\`lazada\` · \`tiktok\` · \`shopee\`) **ไม่ได้วัด** ⇒ เขียวข้างบนไม่ครอบพวกนั้น` +
  "\n📌 การติดป้ายเพิ่มติดกติกาใน CLAUDE.md (`grep -c fallthrough` ต้องเจอที่เดียว) ⇒ **รอท่านประธานตัดสิน**"
);
if (เงียบ.length) {
  console.log("\n🔴 เส้นที่ตกไปคำตอบตั้งต้นเงียบ ๆ ⇒ จอที่ถามผิดจะเขียนว่า \"ไม่มีรายการ\":\n" +
    เงียบ.map((x) => `   · /api/${x.s}`).join("\n"));
}
