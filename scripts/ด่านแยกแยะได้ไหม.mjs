/** ทะเบียน — เพิ่มด่านใหม่ที่นี่ พร้อม **วิธีปลูกที่เหมือนของจริง**
 *  🔑 `ยืนยันปลูกลง` คือคำสั่งที่ **ต้องล้ม** หลังปลูก ⇒ กัน "ปลูกไม่ลงแล้วอ่านเขียวว่าด่านพัง" */
import { ทะเบียน, ตัวตรวจนอกลูกโซ่ } from "./lib/ทะเบียนด่าน.mjs";

const กรอง = process.argv[2];
const รายการ = กรอง ? ทะเบียน.filter((t) => t.ด่าน.includes(กรอง)) : ทะเบียน;

/* ── 🟡 โหมด "สูตรคู่": เคสที่ปลูกแล้ว **ด่านต้องเงียบ** ──────────────────────
   🔴 ที่มา 12 ต.ค. 2569 · ใบ t_mv4w4m68 (ท่านประธานติ๊ก) — ฝั่งจอชี้คลาส
      **"ตะแกรงที่ไม่ตัดคอมเมนต์ลงโทษการเขียนเอกสารกำกับ"**
      (ยิ่งเขียนคำเตือนคลาสนั้นไว้ดี ยิ่งโดนฟ้อง ⇒ คนจะเลิกเขียนคำเตือน)
      📏 ของจริงที่ฝั่งท่อเจอวันเดียวกัน: `check-num-helpers` นับรูปในคอมเมนต์
         และตัวนับติดเพดานพอดี ⇒ **คอมเมนต์เตือนหนึ่งบรรทัดทำ build ตก**

   🔑 ทะเบียนเดิมตอบได้แค่ **"ด่านจับของเสียได้ไหม"** · เคสคอมเมนต์ถามกลับทิศ:
      **"ด่านปล่อยของที่ไม่ใช่ของเสียไหม"** ⇒ ถ้ารวมสองคำถามเป็นช่องเดียว
      ผลจะอ่านกลับหัวทันที (ด่านที่ "จับได้" ในเคสคอมเมนต์ = **ด่านที่พัง**)
   ⇒ จึงกลับคำตัดสินที่นี่ และ **เปลี่ยนชื่อผลให้ต่างกัน** ไม่ใช้คำว่า "ด่านจับได้" ปนกัน

   ⚠️ **ห้ามเติมเคส `ต้องเงียบ` ให้ด่านที่ "คอมเมนต์คือสิ่งที่มันตรวจ"**
      (`check-code-twins` อ่านป้ายฝาแฝดซึ่งเป็นคอมเมนต์ · `check-stale-directives`
       ตรวจคำกำกับที่ค้าง) ⇒ ด่านพวกนั้น **ต้องจับคอมเมนต์** การเติมเคสนี้จะกลายเป็น
       การสั่งให้มันเลิกทำงาน · ใบงานเขียนข้อนี้ไว้ชัดแล้ว */
const ชื่อผลเงียบ = { เงียบ: "ด่านเงียบตามที่ควร", ร้อง: "🔴 ด่านร้องใส่คอมเมนต์" };

const ผล = [];
for (const t of รายการ) {
  const r = ปลูกแล้ววัด({
    ไฟล์: t.ไฟล์,
    แก้: t.แก้,
    ยืนยันปลูกลง: t.ยืนยันปลูกลง,
    /* ส่งต่อช่องใหม่ของเครื่องมือร่วม (ฝั่งจอเพิ่ม 20 ก.ย.) — ไม่ส่งต่อ = ใบที่ใส่ช่องนี้
       จะถูกเมินเงียบ ๆ แล้วได้ผล "ตัดสินไม่ได้" ทั้งที่กรอกหลักฐานมาแล้ว */
    ต้องมีในไฟล์: t.ต้องมีในไฟล์,
    ด่าน: t.คำสั่ง,
    /* 🔴🔴 **เคส `ต้องเงียบ` ต้องตัดสินด้วย "รหัสจบ" เท่านั้น ห้ามใช้ `ต้องเอ่ยถึง`**
       📏 เจอตอนเดินเครื่องรอบแรก (12 ต.ค. 2569): `check-twin-tables` ถูกแก้ให้ตัดคอมเมนต์แล้ว
          และ **ตรงกันจริง (ตก 0)** แต่เคสยังขึ้นแดง
          เพราะ **ข้อความ "สำเร็จ" ของด่านนั้นเอ่ยชื่อไฟล์**:
          `✅ ตารางค่าส่ง 12 ขั้น — ตรงกัน (23 เลข) · … ↔ netlify/lib/shipping.mjs`
          ⇒ เกณฑ์ "ผลเอ่ยถึงชื่อไฟล์ ⇒ ด่านจับได้" เป็นจริงแม้ตอนด่านพอใจ
       🔑 คลาส: **เกณฑ์วัดที่ยืมมาข้ามทิศของคำถาม**
          `ต้องเอ่ยถึง` ถูกสร้างมาเพื่อกัน "ตัวเศษเกินจริง" ในทิศ *ด่านต้องจับ*
          พอกลับทิศเป็น *ด่านต้องเงียบ* มันกลายเป็น **ตัวผลิตแดงลวง** ทันที
          ⇒ ⇒ และแดงลวงที่นี่แพงกว่าปกติ เพราะมันจะสั่งให้คนไป "แก้" ด่านที่ถูกอยู่แล้ว

       📏 **และวัดต่อว่าเกณฑ์รหัสจบมีพลังพอไหม** (ไม่ได้เปลี่ยนเกณฑ์แล้วเชื่อเอง):
          ปลูกให้เลขสองฝั่งไม่ตรงกันจริง ⇒ `check-twin-tables` ออก **exit 1**
          ⇒ รหัสจบแยกแยะได้เต็มที่สำหรับด่านชุดนี้
       ✅ **ของที่เคยเขียนว่า "ยังไม่เติม" — เติมแล้วในรอบสาม** เพราะเงื่อนไขที่ตั้งไว้เองเข้า:
          พอเติมเคสให้ `check-200-null-body` (ด่านที่ **ร้องแต่ไม่ตีกลับ**) เกณฑ์รหัสจบ
          มองการร้องไม่เห็นทันที ⇒ ใส่ช่อง `ข้อความตอนร้อง` ที่ **วัดจากการปลูกของเสียจริง**
          🔑 และข้อบังคับของช่องนี้: ข้อความที่ใส่ต้อง **ไม่มีอยู่ในเอาต์พุตตอนสะอาด**
             ไม่งั้นมันกลายเป็นตัวผลิตแดงลวงแบบเดียวกับ `ต้องเอ่ยถึง` รอบแรก */
    /* ✅ **เติมช่อง `ข้อความตอนร้อง` แล้ว (12 ต.ค. 2569 รอบสาม)** — เพราะ **วัดเจอของจริง**
       `check-200-null-body` เป็นด่าน **"ร้องแต่ไม่ตีกลับ"** (exit 0 + พิมพ์รายการ)
       ⇒ เกณฑ์ "รหัสจบเท่านั้น" **มองการร้องของมันไม่เห็น** ⇒ เคสคอมเมนต์จะเขียวลวง
       📏 วัดสองสภาพก่อนตั้งค่า (ไม่ได้เดารูปข้อความ):
          สะอาด ⇒ **ไม่เอ่ยถึง `core-contacts.mjs` เลย**
          ปลูกโค้ดจริง ⇒ พิมพ์ `· netlify/lib/core-contacts.mjs:518 (กุญแจ: …)`
          ⇒ `"core-contacts.mjs:"` **มีตอนร้อง · ไม่มีตอนสะอาด** ⇒ แยกแยะได้
       🔑 ต่างจาก `check-twin-tables` ที่ **ข้อความสำเร็จเอ่ยชื่อไฟล์** ⇒ ตัวนั้นใช้รหัสจบ
       ⇒ ⇒ บทเรียน: เกณฑ์ไม่ได้ขึ้นกับ "ทิศของคำถาม" อย่างเดียว แต่ขึ้นกับ
          **ข้อความของด่านตัวนั้น** ⇒ ต้อง **วัดสองสภาพของด่านนั้นเอง** ก่อนเลือกเกณฑ์ */
    ต้องเอ่ยถึง: t.ต้องเงียบ ? t.ข้อความตอนร้อง : t.ต้องเอ่ยถึง,
  });
  if (t.ต้องเงียบ) {
    /* กลับคำตัดสิน: "ด่านจับได้"/"เห็นแต่ไม่ทำให้ตก" = **ไม่ผ่าน** สำหรับเคสชนิดนี้
       และ "ไม่จับ" = ผ่าน · `ปลูกไม่ลง` ยังเป็น `ปลูกไม่ลง` เหมือนเดิม (วัดไม่ได้ ≠ ผ่าน) */
    const จับ = r.ผล === "ด่านจับได้" || r.ผล === "ด่านเห็นแต่ไม่ทำให้ตก";
    const ผลกลับ = r.ผล === "ปลูกไม่ลง" ? "ปลูกไม่ลง" : จับ ? ชื่อผลเงียบ.ร้อง : ชื่อผลเงียบ.เงียบ;
    ผล.push({ ...t, ...r, ผล: ผลกลับ, ผลดิบ: r.ผล });
    console.log(`${ผลกลับ === ชื่อผลเงียบ.เงียบ ? "✅" : ผลกลับ === "ปลูกไม่ลง" ? "🟠" : "🔴"} ${t.ด่าน} — ${ผลกลับ}`);
    if (ผลกลับ !== ชื่อผลเงียบ.เงียบ) {
      console.log(`   ${r.รายละเอียด}`);
      console.log("   ⚠️ เคสนี้ปลูก **คอมเมนต์** ⇒ ด่านร้อง = ลงโทษคนเขียนเอกสารกำกับ");
    }
    continue;
  }
  ผล.push({ ...t, ...r });
  const ไอคอน = r.ผล === "ด่านจับได้" ? "✅" : r.ผล === "ด่านเห็นแต่ไม่ทำให้ตก" ? "🔵"
    : r.ผล === "ปลูกไม่ลง" ? "🟠" : "🔴";
  console.log(`${ไอคอน} ${t.ด่าน} — ${r.ผล}`);
  if (r.ผล !== "ด่านจับได้") console.log(`   ${r.รายละเอียด}`);
}

