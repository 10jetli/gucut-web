#!/usr/bin/env node
/* 📖 **ทะเบียน: ด่านตัวไหน "พิสูจน์แล้วว่าแยกแยะได้"** — และตัวไหนยังไม่เคยถูกพิสูจน์
 *
 * 🔴 ที่มา 19 ก.ย. 2569 ค่ำ · ฝั่งจอทำทะเบียนแบบนี้ก่อน แล้ววัดได้ว่า **6 จาก 39 ด่าน**
 *    ของเขาถูกพิสูจน์แล้ว ⇒ ที่เหลือ **เขียวของมันแปลว่า "ยังไม่เจอ" ไม่ใช่ "ไม่มี"**
 *    ⇒ ฝั่งท่อ **ไม่มีทะเบียนแบบนี้เลย** ⇒ ผมตอบไม่ได้ว่าด่าน 16 ตัวของผมกี่ตัวเคยถูกพิสูจน์
 *    ⇒ ไฟล์นี้ทำให้ตอบได้ **ด้วยการรันของจริง ไม่ใช่ความจำ**
 *
 * 🔑 ทำไมต้องเป็นทะเบียนที่ **คนเขียนเอง** ไม่ใช่ตะแกรงที่สกัดจากซอร์ส:
 *    ฝั่งจอลองสกัด "ด่านที่พิมพ์รายการตอนแดง" จากรูปการเขียน ⇒ ได้ 17 จุด และ
 *    **รู้เองว่าอย่างน้อย 4 ตัวในนั้นพิมพ์รายการจริง** ⇒ ตะแกรงผูกกับ *รูปการเขียน* ไม่ใช่ *พฤติกรรม*
 *    ⇒ พฤติกรรมพิสูจน์ได้ทางเดียว: **ปลูกของเสียเข้าไป แล้วดูว่ามันแดงและเอ่ยถึงของที่ปลูกไหม**
 *
 * 🔑 และข้อที่ฝั่งจอเติมให้ใบบทเรียนวันนี้ ใช้กับไฟล์นี้ตรง ๆ:
 *    **"ถ้าไม่มีเคสที่เรารู้คำตอบเลย เราจะไม่มีวันรู้ว่าตัววัดผิด"**
 *    ⇒ ทะเบียนนี้ **คือคลังเคสที่เรารู้คำตอบ** ⇒ มันไม่ใช่แค่ขั้นตอนตรวจ แต่เป็นเงื่อนไขที่ทำให้วัดได้
 *
 * ⚠️ ด่านที่ยังไม่อยู่ในทะเบียน **ไม่ได้แปลว่าพัง** — แปลว่า "เขียวของมันยังไม่มีน้ำหนัก"
 *    🚫 ไฟล์นี้จึง **ไม่ทำให้ build ตก** (ไม่อยู่ใน prebuild) — เป็นตัววัดความครอบคลุม ไม่ใช่ด่าน
 *
 * ใช้: node scripts/ด่านแยกแยะได้ไหม.mjs [ชื่อบางส่วน]
 */
import { readdirSync } from "node:fs";
import { ปลูกแล้ววัด, ผลลัพธ์ทั้งหมด } from "./lib/ปลูกแล้ววัด.mjs";

/* 🔑 ชื่อผลที่แปลว่า "มาดู" — ประกาศไว้**หัวไฟล์**พร้อมด่านตรวจชื่อ
   🔴 **เคยวางด่านนี้ไว้ท้ายไฟล์ แล้วผิด** (20 ก.ย. 2569): กว่าจะถึงมันคือปลูกครบ 10 เคส
      ใช้เวลาหลายนาทีไปแล้ว ⇒ ด่านที่วางหลังจ่ายค่า ไม่ได้กันค่าใช้จ่าย [[guard-after-the-cost]] */
const ต้องมาดู = ["ด่านเขียวทั้งที่ปลูกลง", "ตัดสินไม่ได้ (ไม่มีหลักฐานว่าปลูกอยู่ในขอบเขตของด่าน)"];
/* 🔑 **ด่านเชิงโครงสร้างแทนการระวัง** (ฝั่งจอ export `ผลลัพธ์ทั้งหมด` ให้ 20 ก.ย. 2569)
   ชื่อที่เราเทียบต้องมีอยู่จริงในรายชื่อของเครื่องมือ — ถ้าเขาเปลี่ยนชื่ออีกแล้วเราไม่รู้
   **ต้องพังเสียงดังที่นี่** ไม่ใช่เงียบแล้วทะเบียนผ่านฟรีตลอดกาล
   ⚠️ ห้ามแก้เป็นคำเตือน: `console.warn` แล้วเดินต่อ = กลับไปเป็นของเดิมที่เงียบ */
for (const ชื่อ of ต้องมาดู) {
  if (!ผลลัพธ์ทั้งหมด.includes(ชื่อ)) {
    console.error(
      `🚫 ชื่อผล "${ชื่อ}" ไม่มีอยู่ในรายชื่อของเครื่องมือร่วมแล้ว\n` +
      "   ⇒ เทียบแบบนี้จะไม่มีวันเป็นจริง = **ทะเบียนนี้จะไม่แดงอีกเลย**\n" +
      `   ⇒ รายชื่อปัจจุบัน: ${ผลลัพธ์ทั้งหมด.join(" · ")}\n` +
      "   ⇒ แก้ `ต้องมาดู` ให้ตรง แล้วคุยกับฝั่งจอว่าใครอ่านค่านี้อยู่อีก"
    );
    process.exit(1);
  }
}

/** ทะเบียน — เพิ่มด่านใหม่ที่นี่ พร้อม **วิธีปลูกที่เหมือนของจริง**
 *  🔑 `ยืนยันปลูกลง` คือคำสั่งที่ **ต้องล้ม** หลังปลูก ⇒ กัน "ปลูกไม่ลงแล้วอ่านเขียวว่าด่านพัง" */
import { ทะเบียน } from "./lib/ทะเบียนด่าน.mjs";

const กรอง = process.argv[2];
const รายการ = กรอง ? ทะเบียน.filter((t) => t.ด่าน.includes(กรอง)) : ทะเบียน;

const ผล = [];
for (const t of รายการ) {
  const r = ปลูกแล้ววัด({
    ไฟล์: t.ไฟล์,
    แก้: t.แก้,
    ยืนยันปลูกลง: t.ยืนยันปลูกลง,
    /* ส่งต่อช่องใหม่ของเครื่องมือร่วม (ฝั่งจอเพิ่ม 20 ก.ย.) — ไม่ส่งต่อ = ใบที่ใส่ช่องนี้
       จะถูกเมินเงียบ ๆ แล้วได้ผล "ตัดสินไม่ได้" ทั้งที่กรอกหลักฐานมาแล้ว */
    ต้องมีในไฟล์: t.ต้องมีในไฟล์,
    ด่าน: t.คำสั่ง,
    ต้องเอ่ยถึง: t.ต้องเอ่ยถึง,
  });
  ผล.push({ ...t, ...r });
  const ไอคอน = r.ผล === "ด่านจับได้" ? "✅" : r.ผล === "ด่านเห็นแต่ไม่ทำให้ตก" ? "🔵"
    : r.ผล === "ปลูกไม่ลง" ? "🟠" : "🔴";
  console.log(`${ไอคอน} ${t.ด่าน} — ${r.ผล}`);
  if (r.ผล !== "ด่านจับได้") console.log(`   ${r.รายละเอียด}`);
}

/* ความครอบคลุม — เทียบกับจำนวนด่านที่มีจริงในโฟลเดอร์ ไม่ใช่จำนวนในทะเบียน
   🔑 ถ้าเทียบกับทะเบียนเอง จะได้ 100% ตลอดกาล (สองข้างของเครื่องหมายเท่ากับมาจากที่เดียวกัน)

   🔴🔴 **แต่ตัวหารนี้ยังเลือกเอง — ฝั่งจอจับได้ในตัวเองก่อน แล้วผมพบว่าท่อมีเหมือนกัน (20 ก.ย.)**
   `check-*.mjs` = **16 ตัว** ⇒ นั่นคือตัวหารที่ผมรายงานมาทั้งคืน
   ของจริง: `scripts/` มี **62 ไฟล์ .mjs** · **นอก prebuild 30** · ในนั้นคัดด้วยตาแล้วเป็น
   **ตัวตรวจของจริงอีก 9 ตัว** ที่ **ไม่เคยถูกพิสูจน์เลยสักตัว**:
     `audit-core-contract` · `check-filters-work` · `check-ordercheck-shipping` ·
     `check-paging-complete` · `check-permit-models` · `probe-applied-keys` ·
     `probe-list-filters` · `verify-claims` · `verify-contract-keys`
   ⇒ **ตัวหารที่ซื่อสัตย์ = 16 + 9 = 25** ⇒ อยู่ในทะเบียน **5** ⇒ **5/25 ไม่ใช่ 5/16**
   ⚠️ ในเก้าตัวนั้น **5 ตัวต้องมีเว็บจริงถึงจะป้อนของเสียได้** ⇒ พิสูจน์ได้หลัง deploy เท่านั้น
      **4 ตัวพิสูจน์ได้ตั้งแต่ตอนนี้** ⇒ จดเป็นหนี้ตรง ๆ (ยังไม่ทำ)
   🚫 **ห้ามรายงานว่า "ตัวตรวจของท่อแข็งแรง" จนกว่าจะรวมกองนี้เข้าตัวหาร** (ข้อห้ามเดียวกับฝั่งจอ)
   🔑 คลาส: **ตัวส่วนที่เลือกเอง ทำให้อัตราดูดีโดยไม่มีอะไรดีขึ้น** — และไม่มีใครทัก
      เพราะเลขดูสมเหตุสมผล */

const ด่านทั้งหมด = readdirSync("scripts").filter((f) => f.startsWith("check-") && f.endsWith(".mjs"));
/** ตัวตรวจ **นอกลูกโซ่ prebuild** — คัดด้วยตาจาก 19 ตัวที่ตะแกรงจับได้ (20 ก.ย. 2569)
 *  🚫 ตัดตัวสร้าง/ตัวย้ายไฟล์ออก (`img-to-r2` ฯลฯ มี `exit(1)` เพราะจัดการ error ไม่ใช่ตัดสินถูกผิด)
 *  🔑 **ต้องเป็นรายชื่อ ไม่ใช่ตัวเลข** — เลขที่เขียนฝังจะค้างทันทีที่พิสูจน์เพิ่มได้หนึ่งตัว
 *     (เพิ่งเกิดกับบรรทัดนี้เอง: เขียน "9 ตัวที่ยังไม่เคยพิสูจน์" แล้วพิสูจน์ `check-permit-models`
 *      ในนาทีเดียวกัน ⇒ ข้อความค้างทันที) */
const ตัวตรวจนอกลูกโซ่ = [
  "audit-core-contract.mjs", "check-filters-work.mjs", "check-ordercheck-shipping.mjs",
  "check-paging-complete.mjs", "check-permit-models.mjs", "probe-applied-keys.mjs",
  "probe-list-filters.mjs", "verify-claims.mjs", "verify-contract-keys.mjs",
];
const ชื่อในทะเบียน = new Set(ทะเบียน.map((t) => t.ด่าน.split(" ")[0] + ".mjs"));
const ยังไม่พิสูจน์ = ด่านทั้งหมด.filter((f) => !ชื่อในทะเบียน.has(f));
/* 🔵 "ด่านเห็นแต่ไม่ทำให้ตก" **นับเป็นตรวจจับได้** — ความรุนแรงเป็นการตัดสินใจแยกเรื่อง */
const จับได้ = ผล.filter((r) => r.ผล === "ด่านจับได้" || r.ผล === "ด่านเห็นแต่ไม่ทำให้ตก").length;

console.log(
  `\n📏 ทะเบียนนี้พิสูจน์ ${ผล.length} เคส · **ด่านจับได้ ${จับได้}** · ไม่ผ่าน ${ผล.length - จับได้}` +
  `\n   ด่าน \`check-*.mjs\` ${ด่านทั้งหมด.length} ตัว · อยู่ในทะเบียน ${ชื่อในทะเบียน.size} ตัว` +
  `\n   🔴 **ตัวหารที่ซื่อสัตย์: ${ด่านทั้งหมด.length + ตัวตรวจนอกลูกโซ่.length}** ` +
  `(${ด่านทั้งหมด.length} ใน prebuild + ตัวตรวจนอกลูกโซ่ ${ตัวตรวจนอกลูกโซ่.length} ตัว)` +
  `\n      ⇒ **${ชื่อในทะเบียน.size}/${ด่านทั้งหมด.length + ตัวตรวจนอกลูกโซ่.length}** · ` +
  `ห้ามรายงานเป็น ${ชื่อในทะเบียน.size}/${ด่านทั้งหมด.length} (ตัวส่วนที่เลือกเอง)` +
  `\n      · ตัวตรวจนอกลูกโซ่ที่ **ยังไม่เคยพิสูจน์: ${ตัวตรวจนอกลูกโซ่.filter((f) => !ชื่อในทะเบียน.has(f)).length} ตัว** ⇒ ` +
  ตัวตรวจนอกลูกโซ่.filter((f) => !ชื่อในทะเบียน.has(f)).join(" · ") +
  `\n   🔴 **ยังไม่เคยถูกพิสูจน์ ${ยังไม่พิสูจน์.length} ตัว** ⇒ เขียวของมันแปลว่า "ยังไม่เจอ" ไม่ใช่ "ไม่มี":` +
  `\n      ${ยังไม่พิสูจน์.join(" · ")}` +
  "\n   ⚠️ ไม่อยู่ในทะเบียน ≠ พัง · ไฟล์นี้ไม่ทำให้ build ตก (เป็นตัววัดความครอบคลุม ไม่ใช่ด่าน)"
);

/* 🔴 ชื่อผลเปลี่ยน 20 ก.ย. 2569 — ฝั่งจอเปลี่ยน `ด่านจับไม่ได้` ⇒ `ด่านเขียวทั้งที่ปลูกลง`
   ⚠️ **ถ้าไม่แก้บรรทัดนี้ตาม ทะเบียนจะไม่แดงอีกเลยตลอดกาล** (เทียบกับชื่อที่ไม่มีอยู่แล้ว)
      = คลาส "ตัวตรวจที่เขียวตลอดกาล" ที่เราเขียนกฎห้ามไว้เอง ⇒ นี่คือเหตุผลที่การเปลี่ยนชื่อ
      ฟิลด์ในสัญญาร่วม ต้องประกาศเส้นทางเต็มว่าใครอ่านค่านี้อยู่
   🔑 ทั้งสองผลข้างล่างแปลว่า **"มาดู"** ไม่ใช่ "ด่านพัง" — ทางที่พบบ่อยกว่าคือเราปลูกนอกขอบเขต */
if (ผล.some((r) => ต้องมาดู.includes(r.ผล))) process.exitCode = 1;
