/* 🔴 ชื่อผลเปลี่ยน 20 ก.ย. 2569 — ฝั่งจอเปลี่ยน `ด่านจับไม่ได้` ⇒ `ด่านเขียวทั้งที่ปลูกลง`
   ⚠️ **ถ้าไม่แก้บรรทัดนี้ตาม ทะเบียนจะไม่แดงอีกเลยตลอดกาล** (เทียบกับชื่อที่ไม่มีอยู่แล้ว)
      = คลาส "ตัวตรวจที่เขียวตลอดกาล" ที่เราเขียนกฎห้ามไว้เอง ⇒ นี่คือเหตุผลที่การเปลี่ยนชื่อ
      ฟิลด์ในสัญญาร่วม ต้องประกาศเส้นทางเต็มว่าใครอ่านค่านี้อยู่
   🔑 ทั้งสองผลข้างล่างแปลว่า **"มาดู"** ไม่ใช่ "ด่านพัง" — ทางที่พบบ่อยกว่าคือเราปลูกนอกขอบเขต */
if (ผล.some((r) => ต้องมาดู.includes(r.ผล) || r.ผล === ชื่อผลเงียบ.ร้อง)) process.exitCode = 1;
/* 🟠 **รหัสจบ 2 = "วัดไม่ได้" ไม่ใช่ "ตก"** (13 ต.ค. 2569 · เหตุเดียวกับบรรทัดสรุป)
   ⚠️ `ตัดสินไม่ได้ (…)` อยู่ใน `ต้องมาดู` ด้วย ⇒ มันได้ 1 ไปแล้วข้างบนโดยตั้งใจ
      (เคสนั้นอาจแปลว่าสูตรปลูกเราผิดขอบเขต ซึ่งต้องมีคนมาดูจริง)
   ⇒ ที่เหลือให้ 2: **ปลูกไม่ลงล้วน ๆ** ⇒ ยังไม่ได้วัด ⇒ ห้ามอ่านเป็น "ด่านพัง"
      และห้ามอ่านเป็น "ผ่าน" ด้วย ⇒ จึงไม่ใช่ 0 [[three-states-not-two]] */
if (!process.exitCode && ผล.some((r) => r.ผล === "ปลูกไม่ลง")) process.exitCode = 2;
