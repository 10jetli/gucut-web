#!/usr/bin/env node
/* ⏰ ด่านเพดาน: **จำนวนจุดที่บวก 7 ชั่วโมงด้วยมือ ต้องลดลง ห้ามเพิ่ม**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — บั๊ก `orderdate` ที่ส่งเข้า ZORT
 *    ไฟล์นั้น **มีตัวบวก 7 ของตัวเองอยู่แล้ว** (เขียนไว้เพื่อ `paymentdate` พร้อมคอมเมนต์อธิบาย)
 *    แต่ช่องข้าง ๆ ยังตัดวันจาก UTC ⇒ **เอกสารบัญชีใบเดียวมีสองมาตรฐานเวลา**
 *    ⇒ พิสูจน์ว่ากองนี้ไม่ใช่เรื่องความสวยงามของโค้ด แต่เป็น **กองที่รอคนถัดไปลืมบวก**
 *
 * 🔑 ฝั่งจอเจอรูปกลับด้านในรีโปเขาวันเดียวกัน: **ของถูกอยู่ในเพจ ของผิดอยู่ใน lib**
 *    ⇒ คนที่ทำตามกติกา "อย่าเขียนซ้ำ ใช้ของใน lib" จะ **ดึงของผิดไปใช้**
 *    ⇒ **กติการวมศูนย์ช่วยได้เฉพาะเมื่อของที่ศูนย์กลางถูก** ⇒ จึงเพิ่ม `วันนี้ไทย()` ที่ `thaiday.mjs` ก่อน
 *
 * 🚫 **ไม่ย้ายทั้งกองในรอบเดียว** — diff ใหญ่และพาดผ่านเส้นเงิน (ออเดอร์ · ค่าธรรมเนียม · เครดิต)
 *    ⇒ ใช้ท่าที่รีโปนี้ใช้อยู่แล้วกับ `check-num-helpers`: **เพดานที่ลดได้ ห้ามขึ้น**
 *    ⇒ ของเดิมไม่ถูกบังคับให้แก้วันนี้ แต่ **ของใหม่เพิ่มไม่ได้**
 *
 * 🚫 และด่านนี้ **ไม่ได้บอกว่า 46 จุดนั้นผิด** — วัดแล้วทุกจุด **ถูกวันนี้**
 *    มันบอกว่า "กองนี้ต้องเล็กลง" เท่านั้น ⇒ อ่านเลขนี้เป็น **หนี้** ไม่ใช่ **บั๊ก**
 *
 * ใช้: node scripts/check-thai-offset-copies.mjs
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { ตัดคอมเมนต์ } from "./_strip-comments.mjs";

/* 📏 วัดจริง 20 ก.ย. 2569: **46 จุด ใน 22 ไฟล์** (ไม่นับแหล่งกลางกับไฟล์นี้เอง · ถอดคอมเมนต์ก่อนนับ)
   🔴 เลขแรกที่ผมได้คือ **48** ซึ่งสูงเกินจริง เพราะตะแกรงรอบแรก **นับคำอธิบายในคอมเมนต์ด้วย**
      ⇒ ถ้าตั้งเพดานไว้ 48 จะเหลือ **ช่องว่างให้เพิ่มของใหม่ได้อีกสองจุดโดยด่านไม่ร้อง**
      🔑 **เพดานที่สูงกว่าของจริง = ด่านที่ยอมให้แย่ลงได้เงียบ ๆ** ⇒ ต้องตั้งเท่าที่วัดได้เท่านั้น
   ⚠️ **ห้ามขึ้นเพดานเพื่อให้ผ่าน** — ขึ้นเพดานคือการยอมรับว่ากองโตขึ้น
      ถ้าจำเป็นจริง ให้เขียนเหตุไว้ในคอมมิตว่าทำไมจุดใหม่ใช้แหล่งกลางไม่ได้ */
const เพดาน = 46;
/* 🔴 **ต้องยกเว้นตัวเอง และต้องถอดคอมเมนต์ก่อนนับ** (เจอทันทีที่รันครั้งแรก 20 ก.ย. 2569)
   ไฟล์นี้มีรูปนั้นอยู่ใน **regex ของตัวเอง** และในคอมเมนต์อธิบาย ⇒ นับตัวเองเข้าไปด้วย
   ⇒ ฐานที่วัดได้กลายเป็น 49 ทั้งที่ของจริง 48 ⇒ **ด่านแดงตั้งแต่ยังไม่มีใครทำอะไรผิด**
   🔑 คลาสที่ทั้งสองฝั่งเจอซ้ำ ๆ วันนี้: **ตัวกวาดด้วยข้อความจะเจอข้อความของตัวมันเอง**
      (ฝั่งจอเจอกับ `pgrep -f` และกับคำว่า "โฟลเดอร์ย่อย" ในคำอธิบายด่านเขา) */
const ยกเว้น = new Set(["netlify/lib/thaiday.mjs", "scripts/check-thai-offset-copies.mjs"]);
const รูป = /\+\s*7\s*\*\s*(?:3600e3|3600\s*\*\s*1000|60\s*\*\s*60\s*\*\s*1000)/g;

const ไฟล์ = [];
const เดิน = (d) => {
  for (const ชื่อ of readdirSync(d)) {
    if (["node_modules", ".next", "out", ".netlify"].includes(ชื่อ)) continue;
    const p = join(d, ชื่อ);
    if (statSync(p).isDirectory()) เดิน(p);
    else if (/\.(mjs|ts|tsx|js)$/.test(ชื่อ)) ไฟล์.push(p);
  }
};
for (const r of ["netlify", "src", "scripts"]) {
  try { เดิน(r); } catch (e) {
    /* อ่านรากไม่ได้ ⇒ **บอกออกมา** ไม่ใช่นับได้น้อยลงแล้วผ่าน (กติกา: catch ต้องแนบเหตุ) */
    console.error(`🔴 อ่านราก ${r} ไม่ได้: ${String(e?.message || e).slice(0, 80)} ⇒ **นับไม่ครบ ⇒ ถือว่าตก**`);
    process.exit(1);
  }
}
if (!ไฟล์.length) {
  console.error("🔴 ไม่เจอไฟล์สักไฟล์ ⇒ ตะแกรงพัง ไม่ใช่ผ่าน");
  process.exit(1);
}

const ราย = [];
let รวม = 0;
for (const p of ไฟล์) {
  if (ยกเว้น.has(p)) continue;
  /* ถอดคอมเมนต์ก่อนนับ — คำอธิบายที่ยกรูปนี้มาพูดถึง ไม่ใช่โค้ดที่บวกเวลา */
  const n = (ตัดคอมเมนต์(readFileSync(p, "utf8"), p).match(รูป) ?? []).length;
  if (n) { ราย.push([p, n]); รวม += n; }
}
ราย.sort((a, b) => b[1] - a[1]);

console.log(
  `⏰ บวก 7 ชม. ด้วยมือ: **${รวม} จุด ใน ${ราย.length} ไฟล์** (เพดาน ${เพดาน}) — สแกน ${ไฟล์.length} ไฟล์` +
  `\n   ⇒ ใช้ \`วันนี้ไทย()\` / \`วันไทยจากMs()\` / \`thaiDayFromUtc()\` จาก \`netlify/lib/thaiday.mjs\` แทน` +
  "\n   📉 เลขนี้ต้องลดลงตามเวลา — **อ่านเป็นหนี้ ไม่ใช่บั๊ก** (วัดแล้ว: ทุกจุดถูกวันนี้)" +
  `\n   🔑 เหตุที่กองนี้สำคัญ: บั๊ก \`orderdate\` เกิดในไฟล์ที่ **มีตัวบวก 7 ของตัวเองอยู่แล้ว**`
);
if (รวม > เพดาน) {
  console.error(
    `\n🔴 กองโตขึ้น (${รวม} > ${เพดาน}) ⇒ มีคนเขียน \`+ 7 * 3600e3\` ใหม่\n` +
    ราย.slice(0, 6).map(([p, n]) => `   · ${p} — ${n}`).join("\n") +
    "\n   ⇒ ใช้แหล่งกลางแทน · ถ้าใช้ไม่ได้จริง ให้เขียนเหตุในคอมมิตแล้วขึ้นเพดานพร้อมเหตุผล"
  );
  process.exit(1);
}
