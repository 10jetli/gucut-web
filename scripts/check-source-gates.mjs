#!/usr/bin/env node
/* ด่านนับถอยหลัง: **ด่านอ่านซอร์สที่ตรวจ "ข้อความ" ไม่ใช่ "กลไก"** ต้องลดลงเท่านั้น
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · **เกณฑ์เป็นของฝั่งจอ** ผมเอามาใช้กับฝั่งท่อให้นับแบบเดียวกัน
 *    เกณฑ์ของเขา: ด่านอ่านซอร์สสมเหตุสมผลเมื่อข้อความที่มันหา **คือกลไกเอง**
 *      (`await` · `?? null` · ชื่อคีย์ที่แอปอิมพอร์ตไปใช้จริง · `process.env.X` ที่มีการอ่านค่า)
 *    ไม่สมเหตุสมผลเมื่อข้อความนั้นเป็นเพียง **คำบรรยาย** ของกลไก
 *      (คอมเมนต์ · บรรทัดเอกสาร · สตริงที่ไม่มีใครเรนเดอร์ · ชื่อตัวแปรที่ไม่มีใครอ่านค่า)
 *    วิธีทดสอบหนึ่งนาที: **ปลูกข้อความที่ด่านต้องการ ในรูปคอมเมนต์**
 *      เขียว = ด่านนั้นไม่เคยตรวจพฤติกรรมเลย ⇒ **นับเป็นศูนย์ ไม่ใช่ครึ่งคะแนน**
 *
 * 🔑 และข้อที่เขาเติมซึ่งสำคัญมาก — **ต้องแยกสามกอง ไม่ใช่สองกอง**
 *    ① จับกลไกจริง             ⇒ เชื่อได้
 *    ② **บังคับ**ข้อความ (`assert.match`)        ⇒ คอมเมนต์หลอกได้ ⇒ **เงียบทั้งที่พัง**
 *    ③ **ห้าม**ข้อความ (`assert.doesNotMatch`)  ⇒ คอมเมนต์ทำให้ **ร้องใส่ของถูก**
 *       ⇒ ส่งคนไปพังของที่ยังดี (ของเขาเคยฟ้อง 14 จอ เพราะรีโปตั้งชื่อตัวแปรเป็นภาษาไทย)
 *    ⇒ ② กับ ③ อันตรายคนละทิศ **แต่ทั้งคู่ไม่ใช่การตรวจพฤติกรรม**
 *
 * ⚠️ **ตัวที่ผ่านด่านนี้ ห้ามนับว่า "ปลอดภัย"** — ให้ถือว่า **"ยังไม่ตกที่ชั้นนี้"**
 *    (คำกำชับของฝั่งจอ · ด่านนี้ตอบได้แค่ "ไม่ได้ตรวจข้อความล้วน" ไม่ได้ตอบว่า "ตรวจแน่นพอ")
 */
import { readdirSync, readFileSync } from "node:fs";
import { เตือนถ้ามีไฟล์ซ้อนชั้น } from "./lib/ไฟล์ซ้อนชั้นที่ด่านมองไม่เห็น.mjs";

const ไทย = /[฀-๿]/;
/* รูปที่ถือว่าเป็น "กลไก" — ถ้าแพตเทิร์นมีอันใดอันหนึ่ง ถือว่าจับกลไก ไม่ใช่คำบรรยาย */
/* ⚠️ รอบแรกผมลืมนับ **รูปที่เป็น regex เชิงโครงสร้าง** (`\\s` `\\w` `=` `;`) เป็นกลไก
   ⇒ `/const\\s+ประวัติKEY\\s*=/` (ห้ามประกาศคีย์เอง) ถูกจัดเป็น "ห้ามข้อความ" ซึ่งผิด —
     มันจับ **การประกาศตัวแปร** ซึ่งเป็นกลไกเต็มตัว ⇒ ตะแกรงแคบเกินทำให้ของดีถูกนับว่าเสีย
   🔑 เจอเพราะไล่ดูรายการที่มันฟ้อง **ไม่ใช่เชื่อเลขรวม** */
const กลไก = /await|\?\?|process\.env|=>|\bfunction\b|\breturn\b|\bimport\b|\bexport\b|[{}()[\]]|:\s|=|;|\\s|\\w|\\d|\\+/;

const ผล = { จับกลไก: [], บังคับข้อความ: [], ห้ามข้อความ: [] };
const ใช้ตัวถอดคอมเมนต์ = [];
/* 📏 **นับไฟล์ที่สแกนได้จริง และ 0 ไฟล์ = ตก** — ข้อนี้ผมเป็นคนกำชับฝั่งจอเองตอนยก
   `check-floating` ข้ามรีโป แล้วพบว่าด่านของผมเองไม่มี ⇒ เติมให้ครบก่อนส่งของให้ใคร
   🔑 ด่านที่สแกน 0 ไฟล์แล้วขึ้นเขียว **อันตรายกว่าไม่มีด่าน** (ย้ายโฟลเดอร์ · เปลี่ยนนามสกุล) */
let ไฟล์เทสทั้งหมด = 0;
let ไฟล์ที่อ่านซอร์ส = 0;

/* 🔑 กวาด `scripts/tests` ชั้นเดียว ⇒ เทสในโฟลเดอร์ย่อยจะหลุดเงียบ ๆ (20 ก.ย. 2569) */
if (เตือนถ้ามีไฟล์ซ้อนชั้น(["scripts/tests"], (n) => n.endsWith(".test.mjs"), "check-source-gates")) {
  process.exit(1);
}
for (const f of readdirSync("scripts/tests").filter((x) => x.endsWith(".test.mjs"))) {
  ไฟล์เทสทั้งหมด++;
  const s = readFileSync(`scripts/tests/${f}`, "utf8");
  if (!/readFileSync|ซอร์สไม่เอาคอมเมนต์|เทียบคอมเมนต์/.test(s)) continue;
  ไฟล์ที่อ่านซอร์ส++;
  /* ใช้ตัวถอดคอมเมนต์กลาง ⇒ คอมเมนต์หลอกไม่ได้แล้ว ⇒ ไม่นับเข้ากอง ② */
  if (/_src\.mjs/.test(s)) { ใช้ตัวถอดคอมเมนต์.push(f); continue; }

  /* 🔴 **ต้องดูว่า "อะไรถูกตรวจ" ไม่ใช่แค่ "ไฟล์นี้เคยอ่านซอร์ส"** (แก้รอบสอง 19 ก.ย. 2569)
     รอบแรกผมนับ `assert` ทุกตัวในไฟล์ที่ **เคย** ใช้ `readFileSync` ⇒ นับตัวที่ตรวจ
     **ค่าตอนรัน** เข้ามาด้วย (เช่น `assert.doesNotMatch(String(r.storeScope), /เฉพาะร้าน/)`
     ซึ่งตรวจค่าที่ฟังก์ชันคืนจริง = กลไกเต็มตัว คอมเมนต์หลอกไม่ได้เลย)
     ⇒ **ตะแกรงระดับไฟล์ หยาบเกินกว่าคำถามที่ถาม** ⇒ ได้เลขที่พาไปแก้ของที่ถูกอยู่
     🔑 เป็นครั้งที่สามของวันที่หน่วยของตะแกรงใหญ่กว่าหน่วยที่ผิดได้เอง
     ⇒ นับเฉพาะเมื่อ **ตัวที่ถูกตรวจดูเหมือนเนื้อไฟล์** (src/code/text/raw/SRC/readFileSync) */
  const ดูเหมือนซอร์ส = /\b(src|SRC|code|text|raw|เนื้อ|ซอร์ส|โค้ด)\b|readFileSync/;
  for (const m of s.matchAll(/assert\.(match|doesNotMatch)\(([^,]+),\s*\/([^/\n]{2,90})\//g)) {
    const [, ชนิด, ตัวถูกตรวจ, รูป] = m;
    if (!ดูเหมือนซอร์ส.test(ตัวถูกตรวจ)) continue;   // ตรวจค่าตอนรัน ⇒ กลไก ไม่เข้าชั้นนี้
    if (!ไทย.test(รูป)) continue;          // ASCII = มักเป็นชื่อสัญลักษณ์/โค้ด ⇒ ข้ามชั้นนี้
    /* ⚠️ **ชื่อคีย์/ชื่อตัวแปรที่ปนไทยกับอังกฤษ ก็เป็นกลไก** (แก้รอบสาม)
       เช่น `/missingSampleครบ/` `/missingSampleเพดาน/` = **ชื่อคีย์ที่จอไปอ่านค่าจริง**
       ⇒ ไม่ใช่คำบรรยาย · รอบแรกถูกนับเป็น "บังคับข้อความ" เพราะไม่มีอักขระโครงสร้างเลย
       🔑 เกณฑ์: ไม่มีช่องว่าง + มีตัวอักษรอังกฤษปน ⇒ เป็นสัญลักษณ์ ไม่ใช่ประโยค */
    const เป็นชื่อสัญลักษณ์ = !/\s/.test(รูป) && /[A-Za-z]/.test(รูป);
    if (กลไก.test(รูป) || เป็นชื่อสัญลักษณ์) { ผล.จับกลไก.push(`${f}  /${รูป.slice(0, 60)}/`); continue; }
    (ชนิด === "doesNotMatch" ? ผล.ห้ามข้อความ : ผล.บังคับข้อความ).push(`${f}  /${รูป.slice(0, 60)}/`);
  }
}

/* 🔒 เพดานปัจจุบัน — **ลดได้ ห้ามเพิ่ม** · วัดด้วยตัวนี้เอง 19 ก.ย. 2569
   ⚠️ เลขนี้เทียบกับฝั่งจอได้เพราะใช้เกณฑ์เดียวกัน **แต่ต้องบอกตะแกรงคู่ไปด้วยทุกครั้ง** */
const เพดาน = { บังคับข้อความ: 0, ห้ามข้อความ: 0 };
/* 🔴 **ประวัติของเลขนี้เองคือบทเรียนที่ดีที่สุดในไฟล์นี้: 46 → 36 → 16 → 44 → 3**
   ทุกครั้งที่แคบตะแกรงลง เลขลดลงเพราะ **ของที่ถูกอยู่แล้วถูกนับเข้ามา** ไม่ใช่เพราะมีคนแก้อะไร
     · 46 = ไฟล์เทสที่อ่านซอร์ส · 36 = ที่ยังไม่ถอดคอมเมนต์ · 16 = ที่ค้นด้วยข้อความไทย
     · 44 = นับรายจุด (ไม่ใช่รายไฟล์) แต่ยังนับ assert ที่ตรวจ **ค่าตอนรัน** เข้ามา
     · 3 = นับเฉพาะ assert ที่ตรวจเนื้อไฟล์จริง
     · **0 = หลังหักชื่อคีย์ที่ปนไทย-อังกฤษ (กลไก) และไฟล์ที่ย้ายไปใช้ตัวถอดคอมเมนต์กลาง**
   ⇒ คำตอบจริงคือ **ฝั่งท่อไม่มีด่านอ่านซอร์สที่คอมเมนต์หลอกได้เหลืออยู่** (หลังแก้ 2 ไฟล์)
   🔑 ถ้ารายงานเลข 44 หรือ 16 ออกไป **จะพาคนไปแก้ของที่ถูกอยู่แล้วหลายสิบจุด**
   🔑 และผมเดาเพดานผิดสองรอบ (24 แล้ว 44) ⇒ **ห้ามเดาเพดาน ให้ด่านวัดเองแล้วเอาเลขนั้น**
   🔑 เป็นครั้งที่สองของวันที่ผมเดาเพดานแล้วผิด (เช้านี้ 26 vs 24 ที่ check-num-helpers)
      ⇒ **ห้ามเดาเพดาน ให้ด่านวัดเองแล้วเอาเลขนั้น** · ด่านที่ฟ้องสองทิศจับได้ทันที
   ⚠️ **กอง "บังคับข้อความ" 44 จุดนี้ไม่ใช่ "ด่านขยะ 44 จุด"** — หลายตัวคุมข้อความที่
      โค้ดส่งออกจริง (ข้อความ error ที่ปลายทางอ่าน) ซึ่งเป็นสัญญาที่ควรมีด่านคุม
      ⇒ **ทางแก้คือให้มันอ่านซอร์สที่ถอดคอมเมนต์แล้ว ไม่ใช่ลบด่านทิ้ง**
      ⇒ ลบด่านเพื่อให้เลขลด = ซ่อนหนี้ ไม่ใช่ใช้หนี้ (กติกาเดียวกับที่ฝั่งจอเขียนไว้) */

if (ไฟล์เทสทั้งหมด === 0 || ไฟล์ที่อ่านซอร์ส === 0) {
  console.error(
    `✗ check-source-gates: สแกนได้ ${ไฟล์เทสทั้งหมด} ไฟล์เทส · ที่อ่านซอร์ส ${ไฟล์ที่อ่านซอร์ส}\n` +
    "   ⇒ **นี่ไม่ใช่ข่าวดี** — แปลว่าตะแกรงชี้ผิดที่ (ย้ายโฟลเดอร์? เปลี่ยนนามสกุล?)\n" +
    "   ⇒ ด่านที่เขียวเพราะไม่ได้ตรวจอะไร อันตรายกว่าไม่มีด่าน"
  );
  process.exit(1);
}

const น = { บังคับข้อความ: ผล.บังคับข้อความ.length, ห้ามข้อความ: ผล.ห้ามข้อความ.length };
let ตก = false;
for (const k of Object.keys(เพดาน)) {
  if (น[k] > เพดาน[k]) {
    console.error(
      `❌ check-source-gates: กอง "${k}" มี ${น[k]} จุด แต่เพดานคือ ${เพดาน[k]} ⇒ **มีคนเพิ่มใหม่**\n` +
      (k === "บังคับข้อความ"
        ? "   ⇒ ด่านที่บังคับข้อความล้วน **คอมเมนต์หลอกได้** ⇒ เงียบทั้งที่พัง\n"
        : "   ⇒ ด่านที่ห้ามข้อความล้วน **คอมเมนต์ทำให้ร้องใส่ของถูก** ⇒ ส่งคนไปพังของที่ยังดี\n") +
      "   ⇒ ใช้ `scripts/tests/_src.mjs` (`เทียบคอมเมนต์`) เพื่อตรวจกับซอร์สที่ถอดคอมเมนต์แล้ว\n" +
      ผล[k].map((x) => `   · ${x}`).join("\n")
    );
    ตก = true;
  } else if (น[k] < เพดาน[k]) {
    console.error(
      `❌ check-source-gates: กอง "${k}" เหลือ ${น[k]} ต่ำกว่าเพดาน ${เพดาน[k]} ` +
      `⇒ **ลดเพดานในไฟล์นี้ให้เท่ากับ ${น[k]}**\n   (เพดานที่ไม่ตามความจริง = ด่านที่ผ่านเสมอ)`
    );
    ตก = true;
  }
}
if (ตก) process.exit(1);

console.log(
  `check-source-gates: บังคับข้อความ ${น.บังคับข้อความ} · ห้ามข้อความ ${น.ห้ามข้อความ} ` +
  `· จับกลไก ${ผล.จับกลไก.length} · ใช้ตัวถอดคอมเมนต์แล้ว ${ใช้ตัวถอดคอมเมนต์.length} ไฟล์ ✓\n` +
  `   📏 สแกน ${ไฟล์เทสทั้งหมด} ไฟล์เทส · ที่อ่านซอร์ส ${ไฟล์ที่อ่านซอร์ส} ไฟล์ (0 ไฟล์ = ตก ไม่ใช่เขียว)\n` +
  "   📉 สองกองแรกต้องลดลงตามเวลา — ทั้งคู่ไม่ใช่การตรวจพฤติกรรม (คนละทิศแต่ไม่ใช่การตรวจทั้งคู่)\n" +
  "   ⚠️ **ตัวที่ผ่านด่านนี้ห้ามนับว่า \"ปลอดภัย\"** ให้ถือว่า \"ยังไม่ตกที่ชั้นนี้\"\n" +
  "   🪜 **และ 0 นี้คือ 0 ที่ \"ชั้นคอมเมนต์\" เท่านั้น ไม่ใช่ 0 ทุกชั้น** (ฝั่งจอชี้ 19 ก.ย. 2569)\n" +
  "      บันไดของสิ่งที่ทำให้ด่านพอใจ เรียงจากปลอมง่ายไปปลอมยาก:\n" +
  "      คอมเมนต์ → บรรทัดเอกสาร → สตริงที่ไม่มีใครเรนเดอร์ → โค้ดตาย → **ค่าจริงที่ไม่เกี่ยวข้องแต่รูปร่างตรง**\n" +
  "      ⇒ ชั้นสุดท้ายปลอมยากที่สุดจึง **น่าเชื่อที่สุดและอันตรายที่สุด**\n" +
  "      ⇒ ของจริงฝั่งจอ: `process.env.ANTHROPIC_API_KEY` (กุญแจ **ขาออก**) ทำให้ตัวจับที่หา `_KEY` พอใจ\n" +
  "        ทั้งที่ไม่ได้ยืนยันตัวคนเรียกเลย ⇒ ถอดการตรวจของจริงออก **ด่านยังเขียว**\n" +
  "      ⇒ ด่านนี้ตัดได้แค่ชั้นแรก ⇒ 🔑 **หยุดได้เมื่อสิ่งที่ทำให้ด่านพอใจ คือพฤติกรรมที่เราต้องการ**\n" +
  "        ไม่ใช่ร่องรอยของมัน (เช่น ยิงจริงด้วยรหัสผิดแล้วต้องได้ 401)\n" +
  "   🔍 ตะแกรง: นับเฉพาะ `assert.match`/`doesNotMatch` ที่แพตเทิร์นมีอักษรไทยและไม่มีรูปของกลไก"
);
