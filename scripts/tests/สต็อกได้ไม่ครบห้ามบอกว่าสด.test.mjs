/* 🔴 ด่าน: **กวาดสต็อกได้ไม่ครบ ห้ามตอบว่า `stale: false`** (ใบบั๊ก B09 · 28 ก.ย. 2569)
 *
 * ของเดิมคืน `stale:false` ทุกครั้งที่กวาดสำเร็จ **แม้บางหน้าจะพลาดถาวร**
 * ธง `partial` มีอยู่ **แต่ผู้เรียกที่สำคัญไม่ได้อ่าน**:
 *   `products-feed.mjs:33` อ่าน `{map, at, stale}` · `catalog-feed.mjs:34` อ่าน `{map}`
 *   (มีแต่ `feed-health.mjs` ที่อ่าน `partial`) ⇒ **จอสุขภาพเห็น แต่ฟีดที่ AI ใช้ไม่เห็น**
 * ⇒ รหัสที่ตกหล่น **หายเงียบ ๆ โดยฟีดบอกว่าข้อมูลสดและครบ**
 * 🔑 กติกา: **ค่าที่ปลอดภัยต้องเป็นค่าที่ผู้เรียกได้จากการอ่านแบบง่ายที่สุด**
 *    ไม่ใช่ค่าที่ต้องรู้จักถามถึงก่อน
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const src = await readFile(new URL("../../netlify/lib/zort-stock.mjs", import.meta.url), "utf8");
/* 🔴 **ตัดท่อนต้องนับจากจุดเริ่ม ไม่ใช่หา `} catch {` จากต้นไฟล์**
 *    ครั้งแรกผมเขียน `src.indexOf("} catch {")` ⇒ ไปเจอ `} catch` ของการอ่านแคช (บรรทัด 177)
 *    ซึ่งอยู่ **ก่อน** ท่อนที่จะตรวจ ⇒ ได้ท่อนว่าง ⇒ **ด่านแดงทั้งที่โค้ดถูกแล้ว (แดงลวง)**
 *    🔑 คลาสเดียวกับที่เจอเช้านี้: ตัวชี้ที่หา "ครั้งแรกที่เจอ" ในของที่มีหลายตัว */
const เริ่ม = src.indexOf("const fresh = await scrape()");
const ท่อน = src.slice(เริ่ม, src.indexOf("} catch {", เริ่ม));

test("🔴 ได้ไม่ครบ ⇒ ต้องติด `stale: true` (ห้ามมีทาง return stale:false ในกิ่ง partial)", () => {
  assert.match(ท่อน, /if \(fresh\.partial\)/, "ต้องมีกิ่งแยกสำหรับกรณีได้ไม่ครบ");
  const กิ่ง = ท่อน.slice(ท่อน.indexOf("if (fresh.partial)"));
  const ก่อนจบกิ่ง = กิ่ง.slice(0, กิ่ง.indexOf("return { ...fresh, stale: false }"));
  assert.ok(!/stale:\s*false/.test(ก่อนจบกิ่ง.replace(/partial:\s*false/g, "")),
    "ในกิ่ง partial ห้ามคืน stale:false");
  assert.match(ก่อนจบกิ่ง, /stale:\s*true/, "กิ่ง partial ต้องคืน stale:true");
});

test("🔑 มีแคชเก่าที่ครบ ⇒ ต้องใช้ของเก่า (หลักของไฟล์นี้: ของเก่าที่จริง ดีกว่าของใหม่ที่ไม่ครบ)", () => {
  const กิ่ง = ท่อน.slice(ท่อน.indexOf("if (fresh.partial)"));
  assert.match(กิ่ง, /if \(cached\?\.map\)/, "ต้องเช็คว่ามีแคชเก่าก่อน");
  assert.match(กิ่ง, /\.\.\.cached/, "ต้องคืนข้อมูลจากแคชเก่า ไม่ใช่ของใหม่ที่ไม่ครบ");
});

test("✅ ครบ ⇒ ยังต้องคืน `stale: false` (ไม่ใช่แก้แล้วบอกว่าเก่าทุกครั้ง)", () => {
  assert.match(ท่อน, /return \{ \.\.\.fresh, stale: false \}/, "กรณีครบต้องยังบอกว่าสด");
});

test("📏 ต้องบอก **จำนวนหน้าที่พลาด** ไม่ใช่แค่ true/false", () => {
  assert.match(src, /หน้าที่พลาด: stillFailed\.length/,
    "ขาด 1 หน้าจาก 14 กับขาด 9 หน้า ต้องตัดสินใจคนละอย่าง ⇒ ต้องส่งจำนวนออกมา");
});

test("🚫 แคชต้องไม่ถูกเขียนทับด้วยของที่ไม่ครบ (ของเดิมถูกอยู่แล้ว — กันแก้พลาดภายหลัง)", () => {
  assert.match(ท่อน, /if \(!fresh\.partial\) await s\.setJSON/, "เขียนแคชเฉพาะเมื่อได้ครบ");
});

/* ══════════ 🔴 รูที่สามของคลาสเดียวกัน — ฝั่งจอทะลุเข้ามาได้ (28 ก.ย. 2569) ══════════
   เขาปลูก **ทางออกใหม่** ในตัวกวาด: ขาดหน้าเดียว ⇒ คืน `partial: false` และ `หน้าที่พลาด: 0`
   ⇒ `node --check` ผ่าน · ด่านเดิมยังเขียว เพราะมันตรวจแต่ **กิ่ง `if (fresh.partial)` ที่รู้จัก**
   📏 เขาพิสูจน์ผลต่างตามกติกา ⑤: อินพุตเดียวกัน (`stillFailed.length === 1`)
      ทางเดิมให้ `partial:true · หน้าที่พลาด:1` · ทางที่ปลูกให้ `partial:false · หน้าที่พลาด:0`
   ⚠️ เดินถึงได้แน่ — **ใบ B09 เกิดจากกรณีนี้เป๊ะ** (กวาดได้ไม่ครบหน้า)
   ⇒ ความเสียหาย: หน้าสถานะบอกว่า **"สด"** ทั้งที่ขาดข้อมูลไปหนึ่งหน้า = ชื่อของด่านตัวนี้เอง

   ✅ ปิดด้วยแม่แบบที่ฝั่งจอชี้ว่าดีที่สุดในชุดนี้ (`คำอธิบายความถี่ต้องตรงกับcron`):
      **ถามระบบว่ามีอะไรอยู่ แล้วตรวจทุกตัวที่เจอ** ไม่ใช่เขียนชื่อ/บรรทัดที่รู้จักไว้ในเทส
   ⇒ ที่นี่แปลว่า: ทุกที่ที่ประกาศ `partial` ต้องคิดจาก **ความยาวของรายการที่พลาดจริง**
      ห้ามมีที่ไหนฝังค่าคงที่ (`partial: false` / `หน้าที่พลาด: 0`) ในตัวกวาด */

import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";
import { เลขบรรทัด, ปลูกในโค้ด, โหลดผ่านไหม } from "./_src.mjs";

const โค้ดเต็ม = ตัดคอมเมนต์(src, "zort-stock.mjs", { คงเลขบรรทัด: true });

/** ก้อนของตัวกวาด (ตั้งแต่ประกาศ `stillFailed` ถึงจบ `return` ของมัน) */
function ก้อนตัวกวาด(s) {
  const i = s.indexOf("const stillFailed = []");
  if (i < 0) return null;
  const j = s.indexOf("export ", i);
  return { เนื้อ: s.slice(i, j < 0 ? s.length : j), เริ่ม: i };
}

test("🔴 ทุกที่ที่ประกาศ `partial` ในตัวกวาด ต้องคิดจากรายการที่พลาดจริง — ห้ามฝังค่าคงที่", () => {
  const ก = ก้อนตัวกวาด(โค้ดเต็ม);
  assert.ok(ก, "ไม่เจอตัวกวาด (`stillFailed`) — ไฟล์เปลี่ยนโครง ให้แก้ด่าน ไม่ใช่ลบด่าน");
  const ที่ประกาศ = [...ก.เนื้อ.matchAll(/partial:\s*([^,\n}]+)/g)];
  console.log(
    `   📏 จุดที่ประกาศ partial ในตัวกวาด ${ที่ประกาศ.length} จุด: ` +
      ที่ประกาศ.map((m) => `บรรทัด ${เลขบรรทัด(โค้ดเต็ม, ก.เริ่ม + m.index)} = ${m[1].trim()}`).join(" · ")
  );
  assert.ok(ที่ประกาศ.length >= 1, "ไม่เจอการประกาศ partial เลย ⇒ ตะแกรงพัง ไม่ใช่ไฟล์สะอาด");
  for (const m of ที่ประกาศ) {
    const ค่า = m[1].trim();
    assert.match(
      ค่า, /stillFailed/,
      `partial ที่บรรทัด ${เลขบรรทัด(โค้ดเต็ม, ก.เริ่ม + m.index)} ประกาศเป็น \`${ค่า}\` ` +
        "⇒ ไม่ได้คิดจากรายการหน้าที่พลาดจริง · ค่าคงที่ตรงนี้ = หน้าสถานะจะบอกว่า **สด** ทั้งที่ขาดข้อมูล"
    );
  }
  /* และตัวนับหน้าที่พลาดต้องมาจากที่เดียวกัน ไม่ใช่เลขที่พิมพ์เอง */
  const นับ = [...ก.เนื้อ.matchAll(/หน้าที่พลาด:\s*([^,\n}]+)/g)];
  for (const m of นับ)
    assert.match(m[1].trim(), /stillFailed/,
      `หน้าที่พลาด ประกาศเป็น \`${m[1].trim()}\` ⇒ ต้องคิดจาก stillFailed ไม่ใช่ค่าคงที่`);
});

test("🧪 ตัวควบคุม: ปลูกทางออกที่ฝัง `partial: false` ⇒ เกณฑ์ต้องจับได้ (เคสที่ฝั่งจอปลูกจริง)", () => {
  const { ปลูก, บรรทัด } = ปลูกในโค้ด(
    src,
    "    partial: stillFailed.length > 0,",
    "    partial: stillFailed.length > 1,   // ขาดหน้าเดียวไม่นับว่าไม่ครบ",
    { ไฟล์: "netlify/lib/zort-stock.mjs" }
  );
  console.log(`   🌱 ปลูกในโค้ดบรรทัด ${บรรทัด}`);
  โหลดผ่านไหม(ปลูก, "ปลูก-partial-หลวม");
  /* 🔑 กติกา ⑤: พิสูจน์ว่า **ผลต่างจริง** ด้วยการรันสูตรทั้งสองรุ่นกับอินพุตเดียวกัน (ชั้น ① แข็งสุด) */
  const เดิม = (n) => n > 0;
  const ปลูกแล้ว = (n) => n > 1;
  assert.equal(เดิม(1), true, "ของเดิม: ขาดหน้าเดียว = ไม่ครบ");
  assert.equal(ปลูกแล้ว(1), false, "ที่ปลูก: ขาดหน้าเดียวกลับบอกว่าครบ ⇒ ผลต่างจริง");
  /* เกณฑ์ของด่านต้องยังจับได้ เพราะยังอ้าง stillFailed — ⇒ ต้องเพิ่มเกณฑ์ที่เข้มกว่านี้ */
  const ก = ก้อนตัวกวาด(ตัดคอมเมนต์(ปลูก, "zort-stock.mjs", { คงเลขบรรทัด: true }));
  const ค่า = ก.เนื้อ.match(/partial:\s*([^,\n}]+)/)[1].trim();
  assert.match(ค่า, /stillFailed\.length > 1/, "ปลูกต้องติดจริง");
  assert.ok(!/stillFailed\.length > 0/.test(ค่า),
    "⚠️ เกณฑ์ 'อ้าง stillFailed' อย่างเดียวยังไม่พอ — จับการเปลี่ยนเกณฑ์เปรียบเทียบไม่ได้ " +
      "⇒ จึงมีเทสข้อถัดไปตรึงสูตรไว้ตรง ๆ");
});

test("🔒 สูตรของ `partial` ต้องเป็น `stillFailed.length > 0` เป๊ะ — ขาดหน้าเดียวก็คือไม่ครบ", () => {
  /* 🔑 ตรึงสูตรไว้เพราะ **เกณฑ์เปรียบเทียบคือที่ที่ความผิดพลาดซ่อนได้เนียนที่สุด**
     `> 1` อ่านผ่านตาเหมือน `> 0` และไม่มีเทสไหนในชุดเดิมจับได้
     ⚠️ วันที่อยากเปลี่ยนเกณฑ์จริง ๆ ให้แก้เทสนี้พร้อมเหตุผลที่วัดมา ห้ามแก้เงียบ ๆ */
  const ก = ก้อนตัวกวาด(โค้ดเต็ม);
  const ค่า = ก.เนื้อ.match(/partial:\s*([^,\n}]+)/)[1].trim();
  assert.equal(ค่า, "stillFailed.length > 0",
    `สูตร partial เปลี่ยนไปเป็น \`${ค่า}\` ⇒ ถ้าตั้งใจ ให้แก้เทสนี้พร้อมเหตุผล ไม่ใช่แก้โค้ดเงียบ ๆ`);
  const นับ = ก.เนื้อ.match(/หน้าที่พลาด:\s*([^,\n}]+)/)[1].trim();
  assert.equal(นับ, "stillFailed.length", `ตัวนับหน้าที่พลาดเปลี่ยนไปเป็น \`${นับ}\``);
});
