/* ตัวเตือน "คิดแผนได้แต่ยิงไม่ออก" — รัน: node scripts/tests/ตัวเตือนรอบกวาดไม่คืบ.test.mjs
 *
 * 🔴 ของจริงที่ตัวเตือนนี้เกิดมาเฝ้า (6 ต.ค. 2569):
 *    ตัวกวาด Lazada คิดแผนได้ 37 แถว แล้ว **ยิง 0 ทุกรอบ** เพราะด่านเวลาตัดสินก่อนก้อนแรก
 *    `not_fired` ถูกจดลงสมุดครบทุกรอบ **แต่ไม่มีใครอ่าน** ⇒ เงียบ 18 วัน
 *    ⇒ 51 แผ่นค้างโฆษณาเกินโดยไม่มีอะไรขึ้นเหลือง · เจอเพราะคนไล่กันเอง ไม่ใช่เพราะระบบบอก
 *
 * 🔑 เรียกฟังก์ชันจริงจาก status.mjs — **ไม่ลอกตรรกะมาเขียนใหม่** (test-must-hit-the-path)
 */
import { นับรอบที่ไม่คืบ, ติดกันที่ถือว่าไม่ปกติ } from "../../netlify/functions/status.mjs";

let fail = 0;
const ok = (name, cond, extra = "") => {
  if (cond) console.log(`  ✅ ${name}`);
  else { fail++; console.log(`  ❌ ${name} ${extra}`); }
};
/** แถวสมุด — เรียงใหม่ไปเก่าเสมอ (เหมือน ORDER BY at DESC) */
const แถว = (channel, planned, fired, not_fired = null, at = "2026-10-05T19:00:00Z") =>
  ({ channel, at, planned, fired, not_fired });

console.log("① อาการของจริง: คิดแผนได้ ยิง 0 ติดกัน ⇒ ต้องนับครบและเก็บจำนวนแถวค้าง");
{
  const g = นับรอบที่ไม่คืบ([
    แถว("lazada", 37, 0, 37), แถว("lazada", 37, 0, 37), แถว("lazada", 35, 0, 35),
  ]).get("lazada");
  ok("นับได้ 3 รอบติด", g.ไม่คืบติดกัน === 3, JSON.stringify(g));
  ok("เก็บจำนวนแถวค้างจากรอบล่าสุด", g.แถวค้าง === 37, JSON.stringify(g));
  ok("ถึงเกณฑ์เตือน", g.ไม่คืบติดกัน >= ติดกันที่ถือว่าไม่ปกติ);
}

console.log("② ตัวควบคุมลบ: ยิงออกแล้ว ⇒ ต้องจบสาย ไม่นับต่อ");
{
  const g = นับรอบที่ไม่คืบ([
    แถว("lazada", 37, 0, 37),   // รอบล่าสุดไม่คืบ
    แถว("lazada", 20, 20, 0),   // ก่อนหน้านั้นคืบ ⇒ ต้องตัดสาย
    แถว("lazada", 37, 0, 37), แถว("lazada", 37, 0, 37),
  ]).get("lazada");
  ok("นับแค่ 1 ไม่ลามข้ามรอบที่คืบ", g.ไม่คืบติดกัน === 1, JSON.stringify(g));
  ok("ไม่ถึงเกณฑ์ ⇒ ไม่เตือน", g.ไม่คืบติดกัน < ติดกันที่ถือว่าไม่ปกติ);
}

console.log("③ รอบที่ไม่มีงาน (planned 0) — ห้ามนับ และห้ามตัดสาย");
{
  const g = นับรอบที่ไม่คืบ([
    แถว("lazada", 37, 0, 37),
    แถว("lazada", 0, 0, 0),     // ไม่มีงาน ⇒ ข้าม ไม่ตัดสาย
    แถว("lazada", 37, 0, 37),
    แถว("lazada", 0, 0, 0),
    แถว("lazada", 37, 0, 37),
  ]).get("lazada");
  ok("ไม่คืบ 3 รอบ (ข้ามรอบว่าง ไม่ตัดสาย)", g.ไม่คืบติดกัน === 3, JSON.stringify(g));
  /* 🔑 ถ้านับรอบว่างเป็น "ไม่คืบ" จะได้ 5 ⇒ เตือนทั้งที่ระบบว่างงานจริง (บวกลวง)
     ถ้าให้รอบว่าง "ตัดสาย" จะได้ 1 ⇒ ไม่เคยเตือนทั้งที่ค้างจริง (ลบลวง)
     ⇒ ทั้งสองทางผิด และผิดคนละทิศ — นี่คือเหตุที่ต้องมีสถานะที่สาม */
  ok("ไม่ใช่ 5 (ไม่ได้นับรอบว่างเป็นไม่คืบ)", g.ไม่คืบติดกัน !== 5);
  ok("ไม่ใช่ 1 (รอบว่างไม่ได้ตัดสาย)", g.ไม่คืบติดกัน !== 1);
}

console.log("④ แยกตามเจ้า — เจ้าหนึ่งค้างต้องไม่ลามไปอีกเจ้า");
{
  const m = นับรอบที่ไม่คืบ([
    แถว("lazada", 37, 0, 37), แถว("shopee", 46, 46, 0),
    แถว("lazada", 37, 0, 37), แถว("shopee", 46, 46, 0),
    แถว("lazada", 37, 0, 37), แถว("tiktok", 35, 35, 0),
  ]);
  ok("lazada ค้าง 3", m.get("lazada").ไม่คืบติดกัน === 3);
  ok("shopee ไม่ค้าง", m.get("shopee").ไม่คืบติดกัน === 0);
  ok("tiktok ไม่ค้าง", m.get("tiktok").ไม่คืบติดกัน === 0);
}

console.log("⑤ สมุดรุ่นเก่าไม่ได้จด not_fired ⇒ ต้องเป็น null ไม่ใช่ 0");
{
  const g = นับรอบที่ไม่คืบ([
    แถว("lazada", 37, 0, null), แถว("lazada", 37, 0, null), แถว("lazada", 37, 0, null),
  ]).get("lazada");
  ok("ยังเตือนได้แม้ไม่รู้จำนวนแถว", g.ไม่คืบติดกัน === 3);
  ok("แถวค้างเป็น null ไม่ใช่ 0", g.แถวค้าง === null, JSON.stringify(g));
  /* 🔑 ถ้าแปลงเป็น 0 ปลายทางจะเขียนว่า "ค้าง 0 แถว" ซึ่งอ่านว่าไม่มีปัญหา
     ทั้งที่ความจริงคือ "ไม่รู้ว่าค้างกี่แถว" — ไม่รู้ ≠ ศูนย์ */
}

console.log("⑥ ข้อมูลพิการ — ต้องไม่ล้ม (หน้าสถานะล้มทั้งหน้าแย่กว่าตัวเตือนตัวเดียวเงียบ)");
{
  for (const เสีย of [null, undefined, "ไม่ใช่อาร์เรย์", [null], [{}], [{ channel: null }]]) {
    try { นับรอบที่ไม่คืบ(เสีย); ok(`รับ ${JSON.stringify(เสีย)} ได้`, true); }
    catch (e) { ok(`รับ ${JSON.stringify(เสีย)} ได้`, false, String(e.message)); }
  }
}

console.log("⑦ เกณฑ์ต้องมาจากแหล่งเดียว ไม่ใช่เลขที่เทสพิมพ์เอง");
{
  ok("ติดกันที่ถือว่าไม่ปกติ เป็นจำนวนเต็ม > 0", Number.isInteger(ติดกันที่ถือว่าไม่ปกติ) && ติดกันที่ถือว่าไม่ปกติ > 0, String(ติดกันที่ถือว่าไม่ปกติ));
  /* ป้อนสายยาวเท่าเกณฑ์พอดี และสั้นกว่าหนึ่งรอบ — พิสูจน์ว่าเส้นแบ่งอยู่ตรงที่ประกาศไว้จริง */
  const สาย = (n) => นับรอบที่ไม่คืบ(Array.from({ length: n }, () => แถว("lazada", 9, 0, 9))).get("lazada").ไม่คืบติดกัน;
  ok("เท่าเกณฑ์พอดี ⇒ ถึงเกณฑ์", สาย(ติดกันที่ถือว่าไม่ปกติ) >= ติดกันที่ถือว่าไม่ปกติ);
  ok("น้อยกว่าเกณฑ์หนึ่งรอบ ⇒ ยังไม่ถึง", สาย(ติดกันที่ถือว่าไม่ปกติ - 1) < ติดกันที่ถือว่าไม่ปกติ);
}

console.log(fail ? `\n❌ ตก ${fail} ข้อ` : "\n✅ ผ่านทุกข้อ");
process.exit(fail ? 1 : 0);
