/* ── ตัวตรวจตัวจริง: รับ "ข้อความซอร์ส" เข้ามา แล้วคืนรายการที่ผิด ──
   แยกเป็นฟังก์ชันเพื่อให้ **ตัวควบคุมลบ** เอาซอร์สที่ปลูกบั๊กแล้วมายิงตัวเดียวกันได้ */
function ตรวจ(ดิบ, { พิมพ์ = false } = {}) {
  const ผิด = [];
  /* ✂️ ทำงานบนโค้ดล้วน (คงเลขบรรทัด) — ห้ามกวาดบนซอร์สดิบ ดูเหตุด้านบน */
  const s = ตัดคอมเมนต์(ดิบ, "stock.mjs", { คงเลขบรรทัด: true });

  /* ② คำตอบของชุดสินค้า — **ทุกที่ที่เจอ ไม่ใช่ที่แรก** */
  const ที่ชุด = [...s.matchAll(/kind:\s*"bundle"/g)].map((m) => m.index);
  if (!ที่ชุด.length)
    ผิด.push(
      'ไม่เจอทางออกของชุดสินค้า (kind:"bundle") **ในโค้ด** — ' +
      "ถ้าซอร์สดิบยังมีอยู่ แปลว่ามันอยู่ในคอมเมนต์ ⇒ ด่านนี้ไม่มีของให้ตรวจ (เขียว = ไม่ได้ดู)"
    );
  for (const i of ที่ชุด) {
    const ก้อน = s.slice(s.lastIndexOf("{", i), s.indexOf("}", i) + 1);
    const ที่ = `บรรทัด ${เลขบรรทัด(s, i)}`;
    if (พิมพ์) console.log(`   🔎 ตรวจทางออกชุดสินค้าที่ ${ที่}: ${ก้อน.replace(/\s+/g, " ").slice(0, 90)}`);
    if (!/priceFrom:\s*"web"/.test(ก้อน))
      ผิด.push(`[${ที่}] คำตอบของชุดต้องบอก priceFrom:"web" — ไม่งั้นปลายทางไม่รู้ว่าราคาต้องไปเอาจากไฟล์สินค้า`);
    if (/(^|[^\w.])p\s*:/.test(ก้อน))
      ผิด.push(`[${ที่}] คำตอบของชุด **มีช่อง p** ⇒ ลูกค้าอาจถูกเก็บเงินตามราคา ZORT ที่ต่างจากที่เห็น · ได้: ${ก้อน.replace(/\s+/g, " ").slice(0, 120)}`);
    if (/\bst:\s*0\b/.test(ก้อน))
      ผิด.push(`[${ที่}] คำตอบของชุดฝังค่า st: 0 ไว้ — สต็อกต้องมาจากค่าจริงของ ZORT`);
  }

  /* ① คำตอบ "ไม่พบ" ต้องไม่แนบจำนวนใด ๆ */
  const ไม่พบ = [...s.matchAll(/\{[^{}]*found:\s*false[^{}]*\}/g)].map((m) => m[0]);
  if (!ไม่พบ.length) ผิด.push("ไม่เจอคำตอบ found:false — รหัสที่ไม่มีต้องต่างจากสต็อก 0");
  for (const ก of ไม่พบ)
    if (/\bst\s*:/.test(ก))
      ผิด.push(`คำตอบ "ไม่พบ" แนบ st มาด้วย ⇒ จอแยก "ไม่มีรหัสนี้" จาก "ของหมด" ไม่ออก · ได้: ${ก}`);

  /* ③ ทางออกที่ "ไม่ใช่ชุด" ต้องยังส่ง p — **ทั้งสองทาง** (ปกติ + ทะเบียนชนะ)
     ⚠️ เคยเขียนเป็นเงื่อนไขเดียว แล้วตัวควบคุมลบไม่แดง เพราะอีกทางหนึ่งมี p อยู่
        ⇒ ครอบไม่ครบ แต่รายงานเหมือนครอบครบ (คลาสที่ทีมเจอซ้ำที่สุด) */
  const ทางที่ต้องมีราคา = [
    /* ⚠️ อย่าตรึงทั้งก้อนแบบตัวอักษร — วันที่ **เพิ่ม** ช่อง (เช่น `src`) ด่านจะแดงทั้งที่ของถูกขึ้น
       ⇒ ตรึงเฉพาะสิ่งที่ต้องมีจริง: ทางนี้ต้องส่ง `st` และ `p` · เพิ่มช่องอื่นได้ */
    ["สินค้าเดี่ยวปกติ", /return json\(\{ found: true, st, p[,}]/],
    /* 5 ต.ค. 2569 · รูปของทางนี้เปลี่ยนเป็น `st: lic.st` ตอนต่อตัวหักกลับ (อ่านทะเบียนสด)
       `lic` เปลี่ยนจาก "ตัวเลข|null" เป็น "{st, meta}|null" ⇒ **เจตนาของด่านไม่เปลี่ยน**:
       ทางนี้ต้องยังส่ง `p` ของ ZORT ไปพร้อมจำนวนจากทะเบียน · ตรึงแค่สิ่งที่ต้องมีจริง */
    ["ทะเบียนชนะ ZORT", /return json\(\{ found: true, st: lic\.st, p[,\s]/],
  ];
  for (const [ชื่อ, รูป] of ทางที่ต้องมีราคา)
    if (!รูป.test(s))
      ผิด.push(`ทางออก "${ชื่อ}" ไม่ส่ง p แล้ว — แก้ข้อ ② แล้วห้ามตัดราคาของทางอื่นไปด้วย`);

  return ผิด;
}

