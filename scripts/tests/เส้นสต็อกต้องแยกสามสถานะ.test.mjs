/* 🔴 ด่าน: **เส้น `/api/stock` ต้องแยกสามสถานะให้ขาด** (สเปกจากฝั่งจอ · ใบ t_mu8i1pu1 · 28 ก.ย. 2569)
 *
 * ① ไม่มีรหัสนี้   ⇒ `{ found:false }`  — **ต้องต่างจาก "มีของแต่เหลือ 0"**
 * ② สินค้าเป็นชุด  ⇒ `kind:"bundle"` + `priceFrom:"web"` และ **ห้ามมีช่อง `p`**
 *    🔴 เหตุ: ราคาเว็บต่างจาก ZORT **100 จาก 146 รหัส** และ `orders.mjs` มีท่อน
 *       `if (zp > 0 && zp !== i.price) i.price = zp` ⇒ ส่ง `p` ของชุดออกไป =
 *       **ลูกค้าเห็น 380 แล้วถูกเก็บ 450 โดยไม่มีอะไรบอกเขา** ⇒ เรื่องที่เจ้าของร้านต้องตัดสิน ไม่ใช่เรา
 * ③ สินค้าเดี่ยว   ⇒ ส่ง `p` ได้ (ราคามาจาก ZORT) ⇒ แก้ข้อ ② แล้วห้ามตัดราคาของทุกตัวไปด้วย
 *
 * 🔑 ทั้งสามข้อคือคลาสเดียวกัน: **"ไม่มี/ไม่รู้" ห้ามถูกแทนด้วยตัวเลขที่อ่านได้เหมือนข้อเท็จจริง**
 *
 * ⚠️ ด่านนี้อ่าน **ซอร์ส** (เทสต้องรันได้ตอนไม่มีคีย์ ZORT) — ค่าที่อ้างมาจากการยิงของจริง
 *    วัดจริง 28 ก.ย. 2569 บน gucut.com:
 *      ไม่มีรหัส        ⇒ {"found":false}
 *      ชุด 01209-22T   ⇒ {"found":true,"st":-7,"kind":"bundle","priceFrom":"web"}  ← **ไม่มี p**
 *      เดี่ยว 03800     ⇒ {"found":true,"st":-1,"p":4200}
 * ⚠️ กติกาที่ตกลงกับฝั่งจอ: ทุกด่านต้องมี **ตัวควบคุมลบ** — ปลูกบั๊กแล้วด่านต้องแดง
 *    ไม่งั้น "เขียว" แปลได้แค่ว่ายังไม่เจอ ไม่ได้แปลว่าไม่มี
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const ไฟล์ = new URL("../../netlify/functions/stock.mjs", import.meta.url);
const src = await readFile(ไฟล์, "utf8");

/* ── ตัวตรวจตัวจริง: รับ "ข้อความซอร์ส" เข้ามา แล้วคืนรายการที่ผิด ──
   แยกเป็นฟังก์ชันเพื่อให้ **ตัวควบคุมลบ** เอาซอร์สที่ปลูกบั๊กแล้วมายิงตัวเดียวกันได้ */
function ตรวจ(s) {
  const ผิด = [];

  /* ② คำตอบของชุดสินค้า */
  const i = s.indexOf('kind: "bundle"');
  if (i < 0) ผิด.push("ไม่เจอทางออกของชุดสินค้า (kind:\"bundle\") — เส้นนี้เคยมี ห้ามหาย");
  else {
    const ก้อน = s.slice(s.lastIndexOf("{", i), s.indexOf("}", i) + 1);
    if (!/priceFrom:\s*"web"/.test(ก้อน))
      ผิด.push("คำตอบของชุดต้องบอก priceFrom:\"web\" — ไม่งั้นปลายทางไม่รู้ว่าราคาต้องไปเอาจากไฟล์สินค้า");
    if (/(^|[^\w.])p\s*:/.test(ก้อน))
      ผิด.push(`คำตอบของชุด **มีช่อง p** ⇒ ลูกค้าอาจถูกเก็บเงินตามราคา ZORT ที่ต่างจากที่เห็น · ได้: ${ก้อน.replace(/\s+/g, " ").slice(0, 120)}`);
    if (/\bst:\s*0\b/.test(ก้อน))
      ผิด.push("คำตอบของชุดฝังค่า st: 0 ไว้ — สต็อกต้องมาจากค่าจริงของ ZORT");
  }

  /* ① คำตอบ "ไม่พบ" ต้องไม่แนบจำนวนใด ๆ */
  const ไม่พบ = [...s.matchAll(/\{[^{}]*found:\s*false[^{}]*\}/g)].map((m) => m[0]);
  if (!ไม่พบ.length) ผิด.push("ไม่เจอคำตอบ found:false — รหัสที่ไม่มีต้องต่างจากสต็อก 0");
  for (const ก of ไม่พบ)
    if (/\bst\s*:/.test(ก))
      ผิด.push(`คำตอบ "ไม่พบ" แนบ st มาด้วย ⇒ จอแยก "ไม่มีรหัสนี้" จาก "ของหมด" ไม่ออก · ได้: ${ก}`);

  /* ③ ทางออกที่ "ไม่ใช่ชุด" ต้องยังส่ง p — **ทั้งสองทาง** (ปกติ + ทะเบียนชนะ)
     ⚠️ เคยเขียนเป็นเงื่อนไขเดียว แล้วตัวควบคุมลบไม่แดง เพราะอีกทางหนึ่งมี p อยู่
        ⇒ ครอบไม่ครบ แต่รายงานเหมือนครอบครบ (คลาสที่ทีมเจอซ้ำที่สุด) */
  const ทางที่ต้องมีราคา = [
    ["สินค้าเดี่ยวปกติ", /return json\(\{ found: true, st, p \}/],
    ["ทะเบียนชนะ ZORT", /return json\(\{ found: true, st: lic, p[,\s]/],
  ];
  for (const [ชื่อ, รูป] of ทางที่ต้องมีราคา)
    if (!รูป.test(s))
      ผิด.push(`ทางออก "${ชื่อ}" ไม่ส่ง p แล้ว — แก้ข้อ ② แล้วห้ามตัดราคาของทางอื่นไปด้วย`);

  return ผิด;
}

test("✅ อ่านไฟล์จริงได้ (อ่านไม่ได้ = เขียวลวง)", () => {
  assert.ok(src.length > 1000, `ไฟล์ต้องมีเนื้อ · ยาว ${src.length}`);
  assert.match(src, /export const config/, "ต้องเป็นฟังก์ชัน Netlify ที่ประกาศ path เอง");
});

test("ของจริงวันนี้ต้องผ่านครบสามข้อ", () => {
  const ผิด = ตรวจ(src);
  assert.deepEqual(ผิด, [], `stock.mjs ผิดกติกา:\n- ${ผิด.join("\n- ")}`);
});

/* ── ตัวควบคุมลบ: ปลูกบั๊กจริงแล้วด่านต้องแดง ──
   ⚠️ กติกาข้อ ② ของฝั่งจอ: **สูตรปลูกต้องโหลดผ่าน** — จึงปลูกด้วยการแก้ข้อความให้ยังเป็น JS ที่ถูก
   แล้ว `node --check` ซอร์สที่ปลูกแล้วเพื่อพิสูจน์ว่าแดงมาจากด่าน ไม่ใช่จากไฟล์พัง */
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

function โหลดผ่านไหม(s, ชื่อ) {
  const f = join(mkdtempSync(join(tmpdir(), "ปลูก-")), `${ชื่อ}.mjs`);
  writeFileSync(f, s);
  execFileSync(process.execPath, ["--check", f]); // โยนถ้าไฟล์พัง
  return true;
}

test("🧪 ตัวควบคุม ② ปลูก `p` ให้ชุดสินค้า ⇒ ด่านต้องจับได้", () => {
  const ปลูก = src.replace('kind: "bundle", priceFrom: "web"', 'kind: "bundle", p: 1, priceFrom: "web"');
  assert.notEqual(ปลูก, src, "ปลูกไม่ติด — สูตรปลูกล้าสมัย ให้แก้สูตร ไม่ใช่ลบเทส");
  โหลดผ่านไหม(ปลูก, "ปลูก-p-ในชุด");
  const ผิด = ตรวจ(ปลูก);
  assert.ok(ผิด.some((x) => x.includes("มีช่อง p")), `ด่านต้องจับ p ในชุดได้ แต่ได้: ${JSON.stringify(ผิด)}`);
});

test("🧪 ตัวควบคุม ① ปลูก `st: 0` ลงคำตอบ 'ไม่พบ' ⇒ ด่านต้องจับได้", () => {
  const ปลูก = src.replace("{ found: false }", "{ found: false, st: 0 }");
  assert.notEqual(ปลูก, src, "ปลูกไม่ติด — สูตรปลูกล้าสมัย");
  โหลดผ่านไหม(ปลูก, "ปลูก-st-ในไม่พบ");
  const ผิด = ตรวจ(ปลูก);
  assert.ok(ผิด.some((x) => x.includes('"ไม่พบ" แนบ st')), `ด่านต้องจับ st ในคำตอบไม่พบได้ แต่ได้: ${JSON.stringify(ผิด)}`);
});

test("🧪 ตัวควบคุม ③ ถอน p ของสินค้าเดี่ยว ⇒ ด่านต้องจับได้ (กันแก้ข้อ ② แล้วลามไปทั้งเส้น)", () => {
  const ปลูก = src.replace(/found: true, st, p \}/g, "found: true, st }");
  assert.notEqual(ปลูก, src, "ปลูกไม่ติด — สูตรปลูกล้าสมัย");
  โหลดผ่านไหม(ปลูก, "ปลูก-ถอนราคา");
  const ผิด = ตรวจ(ปลูก);
  assert.ok(ผิด.some((x) => x.includes("สินค้าเดี่ยวปกติ")), `ด่านต้องจับการถอนราคาได้ แต่ได้: ${JSON.stringify(ผิด)}`);
});

test("🧪 ตัวควบคุม ③ข ถอน p ของทาง 'ทะเบียนชนะ' ⇒ ด่านต้องจับได้ (พิสูจน์ว่าครอบทั้งสองทาง)", () => {
  const ปลูก = src.replace("found: true, st: lic, p, src:", "found: true, st: lic, src:");
  assert.notEqual(ปลูก, src, "ปลูกไม่ติด — สูตรปลูกล้าสมัย");
  โหลดผ่านไหม(ปลูก, "ปลูก-ถอนราคาทะเบียน");
  const ผิด = ตรวจ(ปลูก);
  assert.ok(ผิด.some((x) => x.includes("ทะเบียนชนะ ZORT")), `ด่านต้องจับได้ แต่ได้: ${JSON.stringify(ผิด)}`);
});

test("ทะเบียนชนะ ZORT เรื่องจำนวน แต่ราคายังเป็นของ ZORT (ท่านประธานยืนยัน 28 ก.ย. 2569)", () => {
  assert.match(src, /src:\s*"licensed"/, "ต้องประกาศที่มาว่า licensed ⇒ จอรู้ว่าเลขนี้ไม่ได้มาจาก ZORT");
  const i = src.indexOf("lic !== null) return json({ found: true, st: lic, p");
  assert.ok(i > 0, "ทางที่ ZORT รู้จักด้วย ต้องยังส่ง p ของ ZORT ไปพร้อมจำนวนจากทะเบียน");
});
