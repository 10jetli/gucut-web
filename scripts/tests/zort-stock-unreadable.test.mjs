/* ด่าน: ZORT ส่งแถวมาแต่ "อ่านช่องสต็อกไม่ได้" ต้องหยุด **ไม่ใช่เขียนศูนย์ทับของเก่า**
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · จากใบงาน `t_mu7u2c7j` (ท่านประธานติ๊กสั่ง)
 *    ใบงานตั้งหัวเรื่องว่า "ตัวช่วยอ่านตัวเลข 28 ชุดไม่ถอดจุลภาค ⇒ เสี่ยงกลายเป็น 0"
 *    ⇒ วัดแล้วพบว่า **จุลภาคไม่ใช่ความเสี่ยงหลัก** ของจริงคือ `Number(undefined)` → NaN → 0
 *      คือ "ช่องข้อมูลหาย" ไม่ใช่ "ตัวเลขมีจุลภาค" (ยังถอดจุลภาคให้ด้วย เพราะไม่มีผลข้างเคียง)
 *    ⇒ และที่สำคัญกว่าคือ **ที่ไหน** ไม่ใช่ **กี่ที่**: ไฟล์นี้เป็นตัวที่ผลไหลถึงลูกค้าตรงที่สุด
 *      (สต็อก+ราคาทั้งเว็บ · `/products.json` ที่ AI อ่าน) และ **ไม่มีด่านตรวจรูปร่างเลย**
 *      ต่างจาก `lazada.mjs` ที่มีด่านตรวจชนิดข้อมูลระดับ sku และโยน error อยู่แล้ว
 *
 * 🔑 สิ่งที่ทำให้ด่านนี้ "แยกแยะได้" ไม่ใช่แค่ "ร้องได้":
 *    ผูกกับ **ช่องไม่มีอยู่** ไม่ใช่ **ค่าเป็น 0** ⇒ วันที่ของหมดจริงทั้งคลัง ด่านต้องเงียบ
 *    (ถ้าผูกกับค่า 0 ด่านนี้จะร้องในวันที่ของหมดจริง แล้วเว็บจะใช้สต็อกเก่าทั้งที่ ZORT ถูก)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { collectZortStock } from "../../netlify/lib/zort-stock.mjs";

/** หน้าปลอมหนึ่งหน้าแล้วจบ (แถวน้อยกว่า PAGE=200 ⇒ ตัวกวาดถือว่าหน้าสุดท้าย) */
const หน้าเดียว = (rows) => (page) => (page === 1 ? rows : []);

test("ปกติ: อ่านได้ทุกแถว ⇒ ไม่ร้อง และตัวนับเป็น 0", async () => {
  const r = await collectZortStock(หน้าเดียว([
    { sku: "A1", availablestock: 5, sellprice: 100 },
    { sku: "A2", stock: 0, price: 250 },          // ใช้ชื่อช่องสำรอง — ต้องอ่านได้
  ]));
  assert.equal(r.rowsSeen, 2);
  assert.equal(r.unreadableStock, 0);
  assert.equal(r.unreadablePrice, 0);
  assert.deepEqual(r.map.A1, [5, 100]);
  assert.deepEqual(r.map.A2, [0, 250]);
});

test("🧪 ปลูกบั๊ก: ZORT เปลี่ยนชื่อช่องสต็อกทุกแถว ⇒ ต้องโยน error ไม่ใช่คืนศูนย์", async () => {
  await assert.rejects(
    () => collectZortStock(หน้าเดียว([
      { sku: "A1", available_stock: 5, sellprice: 100 },   // ชื่อใหม่ที่โค้ดไม่รู้จัก
      { sku: "A2", available_stock: 9, sellprice: 250 },
    ])),
    /อ่านช่องสต็อกไม่ได้เลยสักแถว/,
    "ช่องหายทุกแถวแล้วยังคืนผลสำเร็จ = เขียนสต็อกศูนย์ทับแคช ⇒ หน้าร้านขึ้นสินค้าหมดทั้งเว็บ",
  );
});

test("🔑 พลังแยกแยะ: ของหมดจริงทั้งคลัง (0 ทุกแถว) ⇒ **ต้องไม่ร้อง**", async () => {
  /* นี่คือข้อที่ทำให้ด่านนี้ต่างจาก "ด่านที่ร้องเวลาเห็นศูนย์"
     ถ้าข้อนี้แดง แปลว่าเราสร้างแดงลวงที่จะทำให้เว็บใช้สต็อกเก่าในวันที่ ZORT ถูกต้อง */
  const r = await collectZortStock(หน้าเดียว([
    { sku: "A1", availablestock: 0, sellprice: 100 },
    { sku: "A2", availablestock: 0, sellprice: 250 },
  ]));
  assert.equal(r.unreadableStock, 0, "ค่า 0 ต้องนับว่า 'อ่านได้' ไม่ใช่ 'อ่านไม่ได้'");
  assert.deepEqual(r.map.A1, [0, 100]);
});

test("บางแถวอ่านไม่ได้ ⇒ รายงานตัวเลข แต่ยังเดินต่อ (ไม่ผูกกับ partial โดยตั้งใจ)", async () => {
  /* ⚠️ ถ้าวันหนึ่งมีคนเปลี่ยนให้กรณีนี้ตั้ง partial = true **แคชจะไม่ถูกเขียนเลย**
     ⇒ กวาดทั้งคลังใหม่ทุกคำขอ (บั๊กจริง 28 ส.ค. 2569 · แพงมาก) ⇒ ด่านนี้ล็อกเจตนานั้นไว้ */
  const r = await collectZortStock(หน้าเดียว([
    { sku: "A1", availablestock: 5, sellprice: 100 },
    { sku: "A2", sellprice: 250 },                       // ไม่มีช่องสต็อกเลย
  ]));
  assert.equal(r.unreadableStock, 1);
  assert.equal(r.partial, false, "บางแถวอ่านไม่ได้ ห้ามทำให้ partial เป็นจริง (แคชจะไม่ถูกเขียน)");
  assert.deepEqual(r.map.A2, [0, 250], "ค่าที่ส่งออกยังเป็น 0 เหมือนเดิม — รอบนี้เปลี่ยนแค่ 'เรารู้ตัว'");
});

test("ช่องราคาหายก็ต้องนับ — ราคา 0 บาทคือการขายฟรี", async () => {
  const r = await collectZortStock(หน้าเดียว([{ sku: "A1", availablestock: 5 }]));
  assert.equal(r.unreadablePrice, 1);
  /* 🚫 ยังไม่โยน error เมื่อราคาหายทุกแถว **โดยตั้งใจ**: ยังไม่ได้วัดว่าของจริง
     มีสินค้าที่ไม่มีราคาขายกี่ตัว (ของแถม/ของเลิกขายอาจไม่มีราคา) ⇒ โยนทันทีอาจเป็นแดงลวง
     ⇒ เก็บตัวเลขไว้ก่อน แล้วรัดเมื่อเห็นค่าจริง — เขียนไว้ที่นี่เพื่อไม่ให้ใครนึกว่าตกหล่น */
  assert.equal(r.rowsSeen, 1);
});

test("จุลภาคในตัวเลข (ถ้าวันหนึ่งมา) ต้องอ่านได้ ไม่ใช่กลายเป็น 0", async () => {
  const r = await collectZortStock(หน้าเดียว([{ sku: "A1", availablestock: "1,234", sellprice: "16,305.50" }]));
  assert.deepEqual(r.map.A1, [1234, 16305.5]);
  assert.equal(r.unreadableStock, 0);
});

test("หน้าโหลดไม่สำเร็จ (null) ยังต้องแยกจาก 'จบชุด' เหมือนเดิม", async () => {
  /* กันการแก้ที่เผลอทำให้ null กลายเป็น "จบแล้ว" — บั๊กที่ไฟล์นี้เคยโดนและเขียนเตือนไว้ */
  let เรียก = 0;
  const ดึง = (page) => {
    เรียก++;
    if (page === 1) return null;                       // พลาด
    if (page === 2) return [{ sku: "B1", availablestock: 1, sellprice: 2 }];
    return [];
  };
  const r = await collectZortStock(ดึง);
  assert.ok(เรียก > 2, "ต้องลองหน้าที่พลาดอีกครั้ง ไม่ใช่หยุดทันที");
  assert.equal(r.partial, true, "ยังพลาดอยู่ ⇒ partial ต้องเป็นจริง (ห้ามเขียนทับแคชที่ครบกว่า)");
});
