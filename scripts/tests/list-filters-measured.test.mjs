/* ด่าน: สแนปช็อต "ตัวกรองที่วัดแล้ว" ต้องครบทุกเส้น · ไม่เก่าเกินเกณฑ์ · และแยกสามสถานะให้ขาด
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ฝั่งจอยิงวัดแล้วพบว่าช่องที่สกัดจากซอร์สของผม **ผิดทั้งสองทิศ**
 *    ⇒ ทางเดียวที่เชื่อได้คือ **วัดพฤติกรรม** (`scripts/probe-list-filters.mjs`)
 *    ⇒ แต่ของที่วัดแล้วเก็บไว้เป็นไฟล์ **จะเก่าเงียบ ๆ** เมื่อโค้ดเปลี่ยน
 *      ⇒ ด่านนี้บังคับว่า **ต้องมีทุกเส้น · มีวันที่ · ไม่เก่าเกินเกณฑ์**
 * 🔑 และบังคับ **สามสถานะ**: อาเรย์ (วัดได้) · `null` + เหตุผล (วัดไม่ได้) · ห้ามมีแถวที่ไม่มีทั้งสอง
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ตัวกรองที่วัดแล้ว } from "../../netlify/lib/list-filters-measured.mjs";
import { สัญญาของเส้น } from "../../netlify/lib/list-contracts.mjs";
import { lists } from "../../netlify/lib/endpoints.mjs";

/* เกณฑ์อายุ — สแนปช็อตที่เก่ากว่านี้ถือว่าเชื่อไม่ได้แล้ว
   🔑 ตั้ง 30 วันเพราะตัวกรองไม่ได้เปลี่ยนบ่อย แต่ **ไม่ตั้ง = เก่าได้ตลอดกาล** */
const เก่าได้ไม่เกินวัน = 30;

test("ทุกเส้นใน lists ต้องมีแถวในสแนปช็อต", () => {
  const ขาด = lists.filter((l) => !(l in ตัวกรองที่วัดแล้ว)).sort();
  assert.deepEqual(ขาด, [],
    "เส้นเหล่านี้ยังไม่ถูกวัด: " + ขาด.join(", ") +
      "\n  ⇒ รัน `node scripts/probe-list-filters.mjs --write` แล้ว commit ไฟล์ตามไปด้วย");
});

test("แต่ละแถวต้องเป็นสามสถานะที่ชัดเจน — ห้ามมีแถวที่ตอบไม่ได้ว่าอยู่สถานะไหน", () => {
  for (const [ชื่อ, v] of Object.entries(ตัวกรองที่วัดแล้ว)) {
    assert.match(String(v.วัดเมื่อ ?? ""), /^\d{4}-\d{2}-\d{2}$/, `${ชื่อ}: ต้องมีวันที่วัด`);
    if (Array.isArray(v.กรองจริง)) continue;                       // ① วัดได้
    assert.equal(v.กรองจริง, null, `${ชื่อ}: กรองจริง ต้องเป็นอาเรย์ หรือ null เท่านั้น`);
    /* ② วัดไม่ได้ ⇒ **ต้องมีเหตุผล** ไม่งั้นคนอ่านจะแปลว่า "ไม่มีตัวกรอง" */
    assert.ok(String(v.เหตุที่ยังไม่รู้ ?? "").length > 3,
      `${ชื่อ}: กรองจริง เป็น null ⇒ ต้องเขียนเหตุผล (null ไม่ใช่ "ไม่มีตัวกรอง")`);
  }
});

test("สแนปช็อตต้องไม่เก่าเกินเกณฑ์ — ของที่วัดแล้วจะเก่าเงียบ ๆ", () => {
  const วันที่ = Object.values(ตัวกรองที่วัดแล้ว).map((v) => v.วัดเมื่อ).filter(Boolean).sort();
  assert.ok(วันที่.length, "ไม่มีวันที่วัดเลยสักแถว");
  const อายุวัน = (Date.now() - new Date(วันที่[0] + "T00:00:00Z").getTime()) / 864e5;
  assert.ok(อายุวัน <= เก่าได้ไม่เกินวัน,
    `สแนปช็อตเก่า ${Math.round(อายุวัน)} วัน (เกณฑ์ ${เก่าได้ไม่เกินวัน}) ` +
      "⇒ รัน `node scripts/probe-list-filters.mjs --write` ใหม่\n" +
      "  🔑 ค่าที่วัดแล้วไม่อัปเดตเอง — โค้ดเปลี่ยนแล้วไฟล์ยังบอกความจริงเก่า");
});

test("🔑 อาเรย์ว่างต้องอ่านคู่กับ 'วัดไม่ได้เพราะถูกตีกลับ' เสมอ", () => {
  /* 🔴 ของจริง: `quotations` ได้ `[]` ซึ่งอ่านได้ว่า "ไม่มีตัวกรองเลย"
     แต่ `store` กรองจริง — ตัววัดถูกตีกลับ 400 ก่อนจะได้วัด
     ⇒ สัญญาจึงต้องส่งกองที่ถูกตีกลับมาด้วย ไม่งั้นอาเรย์ว่างกลายเป็นคำยืนยันเท็จ */
  const r = สัญญาของเส้น("quotations");
  assert.deepEqual(r["กรองจริง(วัดแล้ว)"], []);
  assert.ok(r["วัดไม่ได้เพราะถูกตีกลับ"].includes("store"),
    "ต้องบอกว่า store วัดไม่ได้เพราะถูกตีกลับ — ไม่งั้น [] จะถูกอ่านว่า 'ไม่มีตัวกรอง'");
  const ช่วย = String(r["🔑 อ่านตัวกรองยังไง"] ?? "");
  assert.match(ช่วย, /อาเรย์ว่างก็ยังไม่พอ/, "คำอธิบายต้องเตือนเรื่องอาเรย์ว่าง");
  assert.match(ช่วย, /ห้ามใช้ตัดสิน/, "ต้องห้ามใช้ `ชื่อที่โผล่ในบล็อก` ตัดสิน");
});
