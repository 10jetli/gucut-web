/* ด่าน: ช่องเลือกรุ่นที่ /permit/ — รุ่นที่หมดต้องเป็นสีเทาเลือกไม่ได้
 *
 * 🔴 ที่มา 25 ก.ย. 2569 · ท่านประธานสั่ง "ตัวไหนหมดตรงขออนุญาตก็เป็นเทาอ่อนเลือกไม่ได้"
 *    ก่อนหน้านี้เลือกรุ่นที่ไม่มีของได้ แล้วกรอกแบบ ลซ.๑ จนจบ พิมพ์เอาไปยื่นที่ ทสจ.
 *    ⇒ ลูกค้าเสียเวลาเดินทางไปสำนักงาน แล้วมารู้ทีหลังว่าร้านไม่มีเครื่องจะส่งให้
 *
 * 🔑 สิ่งที่ทำให้ด่านนี้ "แยกแยะได้":
 *    ① ผูกกับ **ตารางจับคู่รุ่น→รหัส** — วันที่ใครเปลี่ยนชื่อรุ่นใน permit.ts แต่ลืมแก้ตาราง
 *       ฟังก์ชันจะคืน 0 ⇒ รุ่นที่มีของกลายเป็นสีเทาเงียบ ๆ **ขายไม่ได้ทั้งรุ่น**
 *       ด่านนี้จับได้เพราะเทียบรายชื่อสองฝั่งตรง ๆ
 *    ② มี **ทิศลบ** — รุ่นที่มีของต้องเลือกได้ ถ้าด่านเขียวทั้งที่ทุกอย่างคืน 0 แปลว่าไม่ได้ทดสอบอะไร
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ราก = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const ดิบ = JSON.parse(readFileSync(join(ราก, "src", "data", "licensed-stock.json"), "utf8"));
const จับคู่ = Object.fromEntries(
  Object.entries(ดิบ["รุ่นเลื่อย→รหัสสินค้า"] || {}).filter(([k, v]) => !k.startsWith("_") && typeof v === "string")
);
const เลื่อย = ดิบ["เลื่อย"] || {};

/** สำเนาตรรกะของ permitModelStock() ฝั่ง .ts — .mjs import .ts ตรง ๆ ไม่ได้ */
const เหลือของรุ่น = (m) => {
  if (!m) return 0;
  const sku = จับคู่[String(m).trim()];
  if (!sku) return 0;
  const n = เลื่อย[sku];
  return typeof n === "number" && Number.isFinite(n) ? n : 0;
};

/** ดึงรายชื่อรุ่นที่ต้องขอใบอนุญาตจาก permit.ts ด้วยการอ่านซอร์ส (.mjs import .ts ไม่ได้) */
function รุ่นที่ต้องขอ() {
  const s = readFileSync(join(ราก, "src", "lib", "permit.ts"), "utf8");
  const i = s.indexOf("PERMIT_MODELS");
  assert.notEqual(i, -1, "หา PERMIT_MODELS ใน permit.ts ไม่เจอ — ชื่อถูกเปลี่ยนหรือไฟล์ย้าย");
  const เริ่ม = s.indexOf("[", i);
  const จบ = s.indexOf("];", เริ่ม);
  assert.ok(จบ > เริ่ม, "อ่านขอบเขตของ PERMIT_MODELS ไม่ได้");
  const out = [...s.slice(เริ่ม, จบ).matchAll(/model:\s*"([^"]+)"/g)].map((m) => m[1]);
  assert.ok(out.length >= 10, `อ่านรุ่นได้แค่ ${out.length} — น่าจะอ่านผิดช่วง`);
  return out;
}

test("ทุกรุ่นในช่องเลือก ต้องตอบได้ว่าเหลือเท่าไหร่ (ไม่มีรุ่นไหนหลุดตาราง)", () => {
  const รุ่น = รุ่นที่ต้องขอ();
  const ไม่มีในตาราง = รุ่น.filter((m) => !จับคู่[m]);
  // F038 · F090 · F880 ไม่เคยนำเข้า ⇒ ไม่มีในตารางโดยตั้งใจ
  assert.deepEqual(ไม่มีในตาราง.sort(), ["F038", "F090", "F880"].sort(),
    "มีรุ่นหลุดตารางจับคู่นอกเหนือจาก 3 รุ่นที่ไม่เคยนำเข้า ⇒ รุ่นนั้นจะกลายเป็นสีเทาทั้งที่มีของ");
});

test("รุ่นที่ไม่เคยนำเข้า ต้องเป็นสีเทา (เหลือ 0)", () => {
  for (const m of ["F038", "F090", "F880"]) {
    assert.equal(เหลือของรุ่น(m), 0, `${m} ไม่เคยนำเข้า ต้องเลือกไม่ได้`);
  }
});

test("✅ ทิศลบ: รุ่นที่มีของต้องเลือกได้ — ถ้าข้อนี้ตกคือเทาหมดทั้งกระดาน", () => {
  const มีของ = [["F660", 20], ["NW8800?", null], ["F440", 6], ["F250", 5], ["F070", 3], ["9800 SUPER PRO", 1]];
  assert.equal(เหลือของรุ่น("F660"), 20);
  assert.equal(เหลือของรุ่น("F440"), 6);
  assert.equal(เหลือของรุ่น("8800 SUPER-S"), 10, "ชื่อรุ่นมีช่องว่างและขีด — จุดที่จับคู่พลาดง่ายที่สุด");
  assert.equal(เหลือของรุ่น("9800 SUPER PRO"), 1);
  assert.ok(มีของ.length > 0);
  // นับรวม: ต้องมีรุ่นที่เลือกได้มากกว่ารุ่นที่เทา ไม่งั้นแปลว่าอะไรบางอย่างพังเป็นวงกว้าง
  const รุ่น = รุ่นที่ต้องขอ();
  const เลือกได้ = รุ่น.filter((m) => เหลือของรุ่น(m) > 0).length;
  assert.ok(เลือกได้ >= 9, `เลือกได้แค่ ${เลือกได้} รุ่นจาก ${รุ่น.length} — น้อยผิดปกติ`);
});

test("ค่าที่ป้อนมาเพี้ยน ต้องได้ 0 ไม่ใช่พัง", () => {
  for (const v of [null, undefined, "", "   ", "ไม่มีรุ่นนี้", 0, {}]) {
    assert.equal(เหลือของรุ่น(v), 0);
  }
});

test("รหัสในตารางจับคู่ ต้องมีอยู่จริงในทะเบียน", () => {
  // 🔑 กันพิมพ์รหัสผิด เช่น "F250" แทน "F 250" ⇒ รุ่นนั้นเทาเงียบ ๆ ทั้งที่มีของ
  for (const [รุ่น, sku] of Object.entries(จับคู่)) {
    assert.ok(sku in เลื่อย, `รุ่น ${รุ่น} ชี้ไปที่รหัส "${sku}" ซึ่งไม่มีในทะเบียน`);
  }
});
