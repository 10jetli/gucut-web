/* ด่าน: **ห้ามแปลง URL↔พาธไฟล์ ด้วยมือ** — ทั้งสองทิศ
 *
 * 🔴 ที่มา 19 ก.ย. 2569 (ฝั่งจอเจอฝั่งเขา 28 ไฟล์ · ฝั่งท่อเจอ 4 จุด)
 *    · URL→พาธ: `new URL(..., import.meta.url).pathname` ⇒ อักษรไทย/ช่องว่างเป็น `%xx` ⇒ อ่านไฟล์ไม่เจอ
 *    · พาธ→URL: `"file://" + พาธ` ⇒ **ไม่เข้ารหัส** ⇒ URL ผิดรูป (ช่องว่างดิบ)
 *    ⇒ วันนี้รอดทั้งสองทิศเพราะพาธของเราเป็น ASCII ล้วน **ยังไม่เคยพัง**
 *    ⇒ 🔑 และ "ช่องว่างในพาธ" ไม่ใช่เรื่องแปลกเลย ไม่ต้องรอถึงชื่อไทย
 *
 * 🔑 ด่านนี้คือของที่ฝั่งจอสรุปไว้: **บั๊กตัวเดียวที่เจอ มักเป็นตัวอย่างของคลาส ไม่ใช่เหตุการณ์เดี่ยว**
 *    ⇒ แก้จุดที่กัดเราแล้วเดินต่อ = อีก N จุดรออยู่เงียบ ๆ ⇒ ด่านนี้กันไม่ให้สำนวนนั้นกลับมา
 * ⚠️ ขอบเขต: กวาดเฉพาะ `scripts/ netlify/ src/` และเฉพาะสองสำนวนนี้
 *    ⇒ อ่านว่า "สำนวนนี้ไม่มีในตะแกรงนี้" ไม่ใช่ "ไม่มีทางพังเรื่องพาธ"
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ราก = fileURLToPath(new URL("../..", import.meta.url));
const ไฟล์ = [];
const เดิน = (d) => {
  for (const ชื่อ of readdirSync(d)) {
    if (ชื่อ === "node_modules" || ชื่อ === ".next" || ชื่อ === "out") continue;
    const p = join(d, ชื่อ);
    if (statSync(p).isDirectory()) เดิน(p);
    else if (/\.(mjs|ts|tsx|js)$/.test(ชื่อ)) ไฟล์.push(p);
  }
};
for (const d of ["scripts", "netlify", "src"]) เดิน(join(ราก, d));

/* 🔴 **ต้องตัดคอมเมนต์ก่อนตรวจ — ไม่งั้นด่านจับคำอธิบายของตัวเอง** (เจอทันทีรอบแรก)
   ผมเขียนคอมเมนต์อธิบายสำนวนที่ห้ามใช้ไว้ในไฟล์ที่เพิ่งแก้ **และในไฟล์ด่านนี้เอง**
   ⇒ ด่านแดงทั้งสองข้อทั้งที่โค้ดถูกหมดแล้ว = **แดงลวงที่จะพาคนไปลบคำอธิบาย**
   🔑 คลาสเดียวกับที่ไล่กันทั้งวัน (การเอ่ยถึง ≠ การใช้) โผล่ในด่านที่เพิ่งเขียนเสร็จ 30 วินาที */
const ไม่เอาคอมเมนต์ = (t) =>
  t.replace(/^\s*\/\/.*$/gm, "").replace(/(?<![:/])\/\/[^\n]*$/gm, "")  /* 🔴 กัน `:` **และ `/`** ข้างหน้า — `file:///x` มี **สามสแลช**
       ⇒ ตัวกันแบบ `(?<!:)` เดิมยังตัดที่สแลชคู่ที่ 2-3 ⇒ กิน URL ทิ้งเหมือนเดิม (เจอ 19 ก.ย. 2569
       ตอนปลูก `new URL("file:///tmp/x").pathname` แล้วด่านไม่ฟ้อง) */.replace(/\/\*[\s\S]*?\*\//g, "");
const เนื้อของ = (f) => ไม่เอาคอมเมนต์(readFileSync(f, "utf8"));

test("ตะแกรงต้องเห็นไฟล์จริง (0 ไฟล์ = ตะแกรงพัง ไม่ใช่ผ่าน)", () => {
  assert.ok(ไฟล์.length > 100, `สแกนได้ ${ไฟล์.length} ไฟล์ — น้อยเกินจริง`);
});

/* 🔑 **ตั้งตะแกรงที่เงื่อนไขที่ทำให้มันผิด ไม่ใช่ที่หน้าตาที่มันเขียน** (ข้อของฝั่งจอ 19 ก.ย. 2569)
   `.pathname` **ไม่ผิดในตัวเอง** — มันถูกต้องเสมอกับ HTTP URL (ฝั่งท่อมี 5 จุดที่ใช้ถูก)
   สิ่งที่ทำให้ผิดคือ **ที่มาของค่าเป็น file URL** ⇒ ตะแกรงจึงต้องผูกกับที่มา ไม่ใช่ชื่อคุณสมบัติ
   ⇒ รายชื่อที่มาที่นับเป็น file URL: `import.meta.url` · `pathToFileURL(...)` · สตริงที่ขึ้นต้น `file:`
   ⚠️ ที่ตะแกรงนี้ยังจับไม่ได้: file URL ที่ถูกเก็บในตัวแปรแล้วส่งข้ามฟังก์ชัน
      ⇒ อ่านว่า "สำนวนตรง ๆ ไม่มีแล้ว" ไม่ใช่ "ไม่มีทางพังเรื่องนี้อีก" */
const ที่มาเป็นfileURL = [
  /import\.meta\.url\s*\)\s*\.pathname/,
  /pathToFileURL\([^)]*\)\s*\.pathname/,
  /new URL\(\s*["'`]file:[^)]*\)\s*\.pathname/,
];
test("ห้ามใช้ .pathname กับค่าที่มาจาก file URL (HTTP URL ใช้ได้ตามปกติ)", () => {
  const เจอ = ไฟล์
    .filter((f) => ที่มาเป็นfileURL.some((re) => re.test(เนื้อของ(f))))
    .map((f) => f.replace(ราก, ""));
  assert.deepEqual(เจอ, [], "ให้ใช้ fileURLToPath() — .pathname เข้ารหัสอักษรไทย/ช่องว่างเป็น %xx");
});

// ⚠️ ชื่อเทสต้อง **บรรยาย** ไม่ใช่ยกสำนวนที่ห้ามมาเป็น literal — ไม่งั้นด่านจับชื่อเทสของตัวเอง
test("ห้ามต่อสตริงคำนำหน้าไฟล์ URL เข้ากับพาธเอง (ต้องใช้ pathToFileURL)", () => {
  const เจอ = ไฟล์.filter((f) => /["'`]file:\/\/["'`]\s*\+/.test(เนื้อของ(f)))
    .map((f) => f.replace(ราก, ""));
  assert.deepEqual(เจอ, [], "ให้ใช้ pathToFileURL() — การต่อสตริงไม่เข้ารหัสช่องว่าง");
});

test("พิสูจน์ว่าสองสำนวนนั้นพังจริงกับรูปที่เรายังไม่มี (ไม่ใช่ห้ามลอย ๆ)", () => {
  /* 🔑 "ป้อนรูปที่เรายังไม่มี" — พาธมีช่องว่างและอักษรไทย ทั้งที่ของจริงยังเป็น ASCII */
  const ฐาน = "file:///home/jetli/มี ช่องว่าง/scripts/a.mjs";
  assert.match(new URL("../x.json", ฐาน).pathname, /%[0-9A-F]{2}/i, "ทิศ URL→พาธ ต้องเห็น %xx");
  assert.doesNotMatch(fileURLToPath(new URL("../x.json", ฐาน)), /%[0-9A-F]{2}/i, "fileURLToPath ต้องถอดรหัสให้");
  const พาธ = "/home/jetli/มี ช่องว่าง/x.json";
  /* 🔑 ประกอบคำนำหน้าเป็นสองชิ้น **โดยตั้งใจ** — ไม่งั้นไฟล์ด่านนี้เองจะเข้าข่ายสำนวนที่มันห้าม
     ⇒ ทางเลือกอีกทางคือยกเว้นไฟล์ตัวเอง แต่นั่นทำให้ด่าน **ตรวจตัวเองไม่ได้ตลอดกาล**
     ⇒ เลือกทางนี้เพราะยังพิสูจน์พฤติกรรมเดิมได้ครบ และด่านยังครอบทุกไฟล์รวมทั้งตัวมันเอง */
  const คำนำหน้าที่ห้าม = "file:" + "//";
  assert.match(คำนำหน้าที่ห้าม + พาธ, / /, "ทิศ พาธ→URL แบบต่อสตริง ต้องเหลือช่องว่างดิบ = URL ผิดรูป");
  assert.doesNotMatch(pathToFileURL(พาธ).href, / /, "pathToFileURL ต้องเข้ารหัสให้");
});
