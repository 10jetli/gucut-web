/* 🎬 ตัวอ่านคลิป อ.ธง — ทางหลักเปลี่ยนจากฟีด RSS มาเป็น "หน้าช่อง" (12 พ.ย. 2569)
 *
 * 🔴 ที่มา: YouTube ปิดฟีด `feeds/videos.xml` ของช่องนี้ — วัดจริงวันนั้นได้ 404 ทุก user-agent
 *    ผลคือหน้า /ajthong/ ค้างอยู่ที่คลิปของวันที่ 20 ต.ค. **สามสัปดาห์**
 *    โดยคำตอบติดธง `สด:false` ถูกต้องตามที่ออกแบบไว้ — แต่ไม่มีใครไปดูธงนั้น
 *    🔑 ทางถอยที่ประกาศตัวแล้วแต่ไม่มีคนอ่าน ก็ยังเป็น "ทางหลักเงียบ ๆ" อยู่ดี
 *
 * เทสนี้คุมสิ่งที่พังได้จริงของตัวอ่าน HTML: รูปแบบที่ YouTube ใช้จริง · การกันซ้ำ ·
 * และกฎ "ว่างเปล่าต้องไม่ถูกตีเป็นสำเร็จ"
 */
import { strict as assert } from "node:assert";
import test from "node:test";

import { อ่านหน้าช่องอธง, อ่านฟีดอธง } from "../../netlify/lib/ajthong-clips.mjs";

/** ชิ้นส่วน HTML รูปแบบเดียวกับที่หน้าช่องส่งมาจริง (คัดโครงมา ไม่ได้แต่งเอง) */
const ชิ้น = (id, ชื่อ) =>
  `{"videoId":"${id}","listType":"PLAYLIST_EDIT_LIST_TYPE_QUEUE"},` +
  `"metadata":{"lockupMetadataViewModel":{"title":{"content":"${ชื่อ}"}}},`;

test("หน้าช่อง: อ่านรหัส+ชื่อได้ และเรียงตามลำดับในหน้า (ใหม่สุดก่อน)", () => {
  const html = ชิ้น("aaaaaaaaaaa", "อ.ธง · 30 ต.ค. 2569") + ชิ้น("bbbbbbbbbbb", "อ.ธง · 6 ต.ค. 2569");
  const ผล = อ่านหน้าช่องอธง(html);
  assert.equal(ผล.คลิป.length, 2);
  assert.deepEqual(ผล.คลิป.map((c) => c.id), ["aaaaaaaaaaa", "bbbbbbbbbbb"]);
  assert.equal(ผล.คลิป[0].ชื่อ, "อ.ธง · 30 ต.ค. 2569");
  assert.equal(ผล.คลิป[0].ฝังที่, "https://www.youtube-nocookie.com/embed/aaaaaaaaaaa");
});

test("หน้าช่อง: รหัสเดียวกันโผล่หลายครั้งในหน้า ⇒ นับใบเดียว", () => {
  // ของจริงโผล่ซ้ำเยอะมาก (วัดจากหน้าจริง: 23 ใบจาก 161 ครั้งที่พบรหัส)
  const html = ชิ้น("ccccccccccc", "ก") + ชิ้น("ccccccccccc", "ก") + ชิ้น("dddddddddddd".slice(0, 11), "ข");
  const ผล = อ่านหน้าช่องอธง(html);
  assert.equal(ผล.คลิป.length, 2);
  assert.ok(ผล.ตัดเพราะซ้ำในฟีด >= 1);
});

test("หน้าช่อง: อ่านชื่อไม่ได้ ต้องยังคืนคลิป — ชื่อเป็นของประกอบ ไม่ใช่เงื่อนไข", () => {
  const ผล = อ่านหน้าช่องอธง('"videoId":"eeeeeeeeeee","อย่างอื่น":1');
  assert.equal(ผล.คลิป.length, 1);
  assert.equal(ผล.คลิป[0].ชื่อ, "");
  assert.equal(ผล.คลิป[0].id, "eeeeeeeeeee");
});

test("🔴 หน้าช่อง: ไม่มีคลิปเลย ต้องคืนรายการว่าง (คนเรียกเป็นคนตัดสินว่าผิดปกติ)", () => {
  // กฎของฟังก์ชันเรียก: ว่าง = ถือว่าอ่านไม่ได้ ⇒ ไปใช้ทางสำรอง/ของเก่า
  // ห้ามให้ตัวอ่าน "เดา" ว่าช่องไม่มีคลิป
  for (const ของเสีย of ["", "<html></html>", '{"videoId":"สั้นไป"}']) {
    assert.equal(อ่านหน้าช่องอธง(ของเสีย).คลิป.length, 0);
  }
});

test("หน้าช่อง: ไม่แต่งวันที่ขึ้นมาเอง (หน้าช่องไม่ได้ให้วันที่แน่นอน)", () => {
  const ผล = อ่านหน้าช่องอธง(ชิ้น("fffffffffff", "อ.ธง · 1 ม.ค. 2569"));
  assert.equal(ผล.คลิป[0].เมื่อ, null);
});

test("ฟีด RSS เดิมยังอ่านได้เหมือนเดิม (ทางสำรองต้องไม่พังตามไปด้วย)", () => {
  const xml =
    '<feed><entry><yt:videoId>ggggggggggg</yt:videoId><title>ชื่อคลิป</title>' +
    "<published>2026-10-20T08:04:34+00:00</published></entry></feed>";
  const ผล = อ่านฟีดอธง(xml);
  assert.equal(ผล.คลิป.length, 1);
  assert.equal(ผล.คลิป[0].id, "ggggggggggg");
  assert.equal(ผล.คลิป[0].เมื่อ, "2026-10-20T08:04:34+00:00");
});
