/* ทดสอบ: เส้น `?reserved=1` — ของที่ถูกจองในใบค้าง รายรหัส (ใบ t_mva2nls5)
 *
 * 🔴 ที่มา (16 ต.ค. 2569): จอ ZORT โชว์ "พร้อมขาย" ที่ API ของ ZORT ไม่ได้ส่งมา
 *    📏 รหัส 00894: API ZORT -337.5 · กระจกเรา -337.5 (ตรงเป๊ะ) · **จอ ZORT -468.5**
 *    ⇒ ซิงก์ถี่แค่ไหนก็ไม่ได้เลขของจอ ⇒ ต้องคิดของเราเองให้ได้แล้วเทียบ
 *
 * 🔑 สิ่งที่เทสนี้ตรึง (ไม่ใช่ตรึงตัวเลข — ตัวเลขเปลี่ยนทุกวัน):
 *    ① คำสั่งเดียว GROUP BY — ห้ามกลับไปไล่ทีละใบ (วัดแล้ว 298 ใบ = 298 คำขอ · และ
 *       `product=` + ช่วงหลายปี ⇒ 500 ที่ 15.4 วิ)
 *    ② **ไม่มีช่วงวัน** โดยตั้งใจ — ของที่ถูกจองคือใบที่ยังไม่จบ ไม่ว่าเก่าแค่ไหน
 *    ③ คำตอบต้องมีคำเตือนว่า **ยังไม่ใช่สูตรของ ZORT** (ยังไม่ตรงทั้ง 437.5 และ 568.5)
 *    ④ ต้องมีดัชนีของ `status` — บทเรียนวันเดียวกัน: กรองด้วยคอลัมน์ไม่มีดัชนี = ตายที่ 15 วิ
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const lib = readFileSync("netlify/lib/core-stock.mjs", "utf8");
const route = readFileSync("netlify/functions/core.mjs", "utf8");
const db = readFileSync("netlify/lib/coredb.mjs", "utf8");

const ตัวฟังก์ชัน = (() => {
  const i = lib.indexOf("export async function reservedBySku");
  assert.ok(i > 0, "หาฟังก์ชัน reservedBySku ไม่เจอ");
  const j = lib.indexOf("\n}", i);
  return lib.slice(i, j > 0 ? j : i + 4000);
})();

test("① คำสั่งเดียว GROUP BY — ห้ามไล่ทีละใบ", () => {
  const กี่คำสั่ง = (ตัวฟังก์ชัน.match(/coreQuery\(/g) || []).length;
  assert.equal(กี่คำสั่ง, 1, `ต้องยิงฐานครั้งเดียว ได้ ${กี่คำสั่ง} ⇒ ไล่ทีละใบคือรูปที่วัดแล้วว่าตาย`);
  assert.match(ตัวฟังก์ชัน, /GROUP BY oi\.sku/, "ต้องรวมที่ฐาน ไม่ใช่ดึงแถวมาบวกในโค้ด");
  /* 🚫 ห้ามวนลูปยิงต่อ (for/while ที่มี await fetch หรือ coreQuery ข้างใน) */
  assert.ok(!/for \([^)]*\)\s*{[\s\S]{0,400}coreQuery\(/.test(ตัวฟังก์ชัน), "ห้ามยิงฐานในลูป");
});

test("② ห้ามมีช่วงวันในเงื่อนไข — ของที่ถูกจองไม่ขึ้นกับความเก่าของใบ", () => {
  assert.ok(!/order_date >=|order_date <=|o\.order_date >/.test(ตัวฟังก์ชัน),
    "มีช่วงวันในเงื่อนไข = ใบค้างเก่าจะหลุดจากการนับ (ใบผี Shopify ก็ยังจองของในสายตา ZORT)");
  /* MIN/MAX order_date ใช้ **รายงาน** ได้ (บอกว่าของเก่าสุดใบไหน) แต่ต้องไม่ใช่ตัวกรอง */
  assert.match(ตัวฟังก์ชัน, /MIN\(o\.order_date\)/, "ควรรายงานวันเก่าสุดไว้ให้คนอ่านตัดสินใจ");
});

test("③ คำตอบต้องกันคนเอาไปใช้แทน available", () => {
  assert.match(ตัวฟังก์ชัน, /ห้ามใช้ทำอะไร/, "ต้องมีช่องเตือนในคำตอบ ไม่ใช่เขียนไว้แต่ในคอมเมนต์");
  assert.match(ตัวฟังก์ชัน, /437\.5/, "คำเตือนต้องอ้างเลขที่วัดได้จริง (API ZORT)");
  assert.match(ตัวฟังก์ชัน, /568\.5/, "คำเตือนต้องอ้างเลขของจอ ZORT ด้วย ⇒ คนเห็นว่ายังไม่ตรงทั้งคู่");
  assert.match(ตัวฟังก์ชัน, /สถานะที่ถือว่ายังไม่จบ/, "ต้องประกาศว่านับสถานะอะไร ไม่ให้คนเดา");
});

test("④ ดัชนีของ status ต้องมีในสคีมา", () => {
  assert.match(db, /idx_orders_status_source ON orders\(status, source\)/,
    "กรองด้วย status โดยไม่มีดัชนี = คลาสที่วัดแล้วว่าตายที่ 15 วินาที");
});

test("⑤ เส้นต้องเป็น GET อย่างเดียว และผ่านตัวแปลงร้านกลาง", () => {
  const i = route.indexOf('if (url.searchParams.get("reserved"))');
  assert.ok(i > 0, "ยังไม่ต่อสายเส้นนี้ ⇒ เขียนฟังก์ชันแล้วไม่มีใครเรียก = เท่ากับไม่มี");
  /* ⚠️ **ตัดบรรทัดคอมเมนต์ออกก่อนตรวจ** — ในบล็อกนี้มีคอมเมนต์ที่ **อ้างรูปที่ห้ามใช้**
     ไว้เป็นหลักฐานว่าเคยเขียนผิดแบบไหน ⇒ ถ้าตรวจรวมคอมเมนต์ เทสจะแดงเพราะข้อความอธิบาย
     (เจอเองรอบนี้ · และเช้านี้ด่าน sql-contains ก็จับคอมเมนต์ผมด้วยเหตุเดียวกัน)
     🔑 ที่นี่เลือก "ตรวจให้แม่นขึ้น" ได้ เพราะเป็นเทสของเส้นนี้เอง
        ต่างจากด่านกลางที่ใช้ร่วมกันทั้งรีโป ซึ่ง **ไม่ควรผ่อนเพื่อให้โค้ดตัวเองผ่าน** */
  /* ⚠️ ตัด **ทั้งก้อนคอมเมนต์** ไม่ใช่ตัดตามคำขึ้นต้นบรรทัด — สไตล์คอมเมนต์ของรีโปนี้
     ขึ้นบรรทัดต่อด้วยข้อความไทย ไม่ได้นำด้วย `*` ⇒ การกรองตามคำขึ้นต้นจับไม่ติด (ลองแล้ว) */
  /* ⚠️ **ตัดให้จบที่เส้นของตัวเองเท่านั้น** — การปลูกบั๊กจับได้ว่าเวอร์ชันก่อนหน้า
     ใช้หน้าต่างคงที่ 1,800 ตัวอักษร ⇒ เลยไปถึง `if (url.searchParams.get("stockcompare"))`
     ซึ่งมีด่าน GET ของมันเอง ⇒ ถอดด่าน GET ของ **เส้นนี้** ออกแล้วเทสยังเขียว
     = เทสที่ตรวจโค้ดของเพื่อนบ้านแทนโค้ดที่ตั้งใจตรวจ (กฎ test-must-hit-the-path) */
  const หลังเส้นนี้ = route.indexOf('if (url.searchParams.get("stockcompare"))', i);
  assert.ok(หลังเส้นนี้ > i, "หาเส้นถัดไปไม่เจอ — ขอบของบล็อกเชื่อถือไม่ได้");
  const บล็อก = route.slice(i, หลังเส้นนี้).replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*/g, "");
  assert.match(บล็อก, /req\.method !== "GET"/, "ต้องกัน method อื่น (เคยพลาด: ปุ่มลบเขียนเป็น POST แล้วเงียบ)");
  assert.match(บล็อก, /parseSingleStore\(url\.searchParams\.get\("store"\)\)/, "ต้องเรียกตัวแปลงกลางเสมอ");
  assert.ok(!/\{ source: "" \}/.test(บล็อก), "ห้ามตั้งความหมาย 'ว่าง = รวมสองร้าน' เอาเอง");
  assert.match(บล็อก, /storeDefaulted/, "ต้องแยก 'ผู้ใช้เลือก z1' ออกจาก 'ท่อเลือกให้'");
});
