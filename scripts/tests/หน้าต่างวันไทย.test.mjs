/* 📅 **หน้าต่างวันที่ใช้ตัดสินการสั่งซื้อ ต้องเป็นวันไทย ไม่ใช่วัน UTC**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ฝั่งจอย้อน diff บั๊กจริงของเขา (`lib/reorder.ts` · `lib/returns.ts`
 *    ส่งหน้าต่างวันเป็น UTC) ⇒ **สายตรวจ 75 ขั้นของเขาเงียบสนิท · `tsc` เขียว**
 *    ⇒ เขาถามว่าฝั่งท่อมีตาข่ายไหม ⇒ 📏 ผมปลูกบั๊กเดียวกัน (เอา `+ 7 * 3600e3` ออก)
 *    ⇒ ⇒ **เทส 716 ข้อผ่านหมด · เงียบสนิทเหมือนกัน** ⇒ **ทั้งสองฝั่งไม่มีตาข่าย**
 *
 * 🔑 ทำไมเรื่องนี้ไม่ใช่เรื่องเล็ก: `reorderPlan` **ตัดสินว่าจะสั่งซื้อของเท่าไหร่**
 *    ⇒ หน้าต่างเพี้ยนหนึ่งวัน = **ยอดขายหนึ่งวันหายจากการคำนวณ** ⇒ สั่งของน้อยไป/มากไป
 *    ⇒ ⇒ **ของจริงในคลัง ไม่ใช่แค่เลขบนจอ**
 *
 * 🔑 เทสนี้เขียน **ตอนบั๊กยังปลูกอยู่** แล้วเห็นแดงจริงก่อนคืน diff
 *    (ท่าที่ทั้งสองฝั่งพิสูจน์วันนี้ว่า *เทสที่ไม่เคยเห็นแดงของบั๊กจริง คือเทสที่ยังไม่รู้ว่าเฝ้าอะไร*)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { วันไทยย้อน } from "../../netlify/lib/thaiday.mjs";

/* เวลา UTC ที่ตกในช่วงเสี่ยง: 18:30Z = 01:30 ไทยของ "วันถัดไป" */
const เสี่ยง = Date.parse("2026-09-19T18:30:00Z");

test("ช่วง 00:00–07:00 ไทย ⇒ ต้องได้วันไทย ไม่ใช่วัน UTC", () => {
  assert.equal(วันไทยย้อน(0, เสี่ยง), "2026-09-20", "ตี 1.30 ไทย ⇒ ต้องเป็นวันที่ 20");
  /* รุ่นบั๊ก (ไม่บวก 7) จะได้ 19 ⇒ ยอดขายของวันที่ 20 หายจากหน้าต่าง */
  assert.notEqual(new Date(เสี่ยง).toISOString().slice(0, 10), "2026-09-20",
    "ตัวควบคุม: วัน UTC ต้องต่างจากวันไทยที่เวลานี้ ไม่งั้นเคสนี้ไม่ได้ทดสอบอะไร");
});

test("ย้อนหลัง N วัน ⇒ ต้องนับจากวันไทย", () => {
  assert.equal(วันไทยย้อน(1, เสี่ยง), "2026-09-19");
  assert.equal(วันไทยย้อน(90, เสี่ยง), "2026-06-22");
  /* หน้าต่าง 90 วันของ reorderPlan: from=วันไทยย้อน(90) · to=วันไทยย้อน(0) */
  assert.ok(วันไทยย้อน(90, เสี่ยง) < วันไทยย้อน(0, เสี่ยง), "from ต้องน้อยกว่า to เสมอ");
});

test("ค่าผิด ⇒ `null` ไม่ใช่วันนี้ (วันนี้จะถูกอ่านว่าถูกต้อง)", () => {
  for (const v of [undefined, null, "abc", NaN, {}]) {
    const r = วันไทยย้อน(v, เสี่ยง);
    if (v === undefined) { assert.equal(r, "2026-09-20", "ไม่ส่งค่า = วันนี้ (ค่าตั้งต้น 0)"); continue; }
    assert.equal(r, null, `ค่าผิด (${JSON.stringify(v)}) ต้องได้ null`);
  }
});

test("🕳️ ปลูกรุ่นบั๊กไว้ในเทสเอง ⇒ ยืนยันว่าเทสชุดนี้แยกแยะได้", () => {
  const รุ่นบั๊ก = (n, ณเวลา) => new Date(ณเวลา - n * 86400e3).toISOString().slice(0, 10);
  assert.notEqual(รุ่นบั๊ก(0, เสี่ยง), วันไทยย้อน(0, เสี่ยง),
    "ถ้าสองรุ่นให้ผลเดียวกันที่เวลานี้ เทสชุดนี้ไม่ได้วัดอะไรเลย");
  assert.equal(รุ่นบั๊ก(0, เสี่ยง), "2026-09-19", "รุ่นบั๊กต้องได้วันก่อนหน้า (นั่นคืออาการจริง)");
});
