/* 🔴 ด่าน: **สูตรยอดโอน Shopee — ตรึงด้วยใบจริง และช่องที่ขาดห้ามแทน 0**
 *    (สเปกฝั่งจอ ข้อ 4 · ใบ t_mu8i1pu1 · 28 ก.ย. 2569)
 *
 * ทำไมเป็นเรื่องเงินตรง ๆ: `shopeeNet()` คือเลขที่เราบอกว่า **จะได้เงินเข้าเท่าไรต่อใบ**
 * · ช่องที่จำเป็นขาด ⇒ คืน `null` ห้ามแทน 0 แล้วคิดต่อ
 *   (แทน 0 = ได้ `formula_diff` สวยงามที่ไม่ได้พิสูจน์อะไร — กฎ blank-input-invents-output)
 * · ช่องที่ "ไม่มีก็แปลว่าไม่มีรายการนั้น" (ส่วนลด/ค่าส่งที่ Shopee ช่วย) ⇒ นับเป็น 0 ได้
 *   🔑 **สองความหมายของ "ไม่มี" อยู่ในสูตรเดียวกัน** ⇒ ด่านนี้ต้องแยกให้ขาด ไม่งั้นใครมาแก้จะยุบรวม
 *
 * ⚠️ ตัวเลขที่ใช้ตรึงมาจาก **ใบจริง** (วัด 18 ก.ย. 2569 · 8 ใบ · ต่าง 1 บาทใน 6 ใบ)
 *    🚫 ห้ามแก้ตัวเลขในด่านนี้ให้ diff เป็น 0 — วันที่ Shopee เปลี่ยนสูตร ต้อง **วัดกับใบจริงใหม่**
 *       (ถ้าปรับเลขให้ตรง ด่านจะเขียวตลอดกาลโดยไม่มีใครรู้ว่าสัญญากับ Shopee เปลี่ยนไปแล้ว)
 * ⚠️ ด่านที่อ่านซอร์สต้องพิมพ์ `ไฟล์:บรรทัด` ที่มันตัดสิน (กติกาที่ตกลงกับฝั่งจอ 28 ก.ย. 2569)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { shopeeNet, ปิดบัญชี } from "../../netlify/lib/mkp-finance-mirror.mjs";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด } from "./_src.mjs";

const ไฟล์ = "netlify/lib/mkp-finance-mirror.mjs";
const โค้ด = ซอร์สไม่เอาคอมเมนต์(ไฟล์);

/* ── ใบจำลองที่ "ครบทุกช่องจำเป็น" — ค่าทรงเดียวกับใบจริง ── */
const ใบครบ = {
  itemsTotal: 1000, commission: 50, serviceFee: 20, paymentFee: 30, shippingActual: 40,
  sellerTransactionFee: 5, shippingSubsidyByShopee: 35, shippingPaidByBuyer: 10,
};

test("✅ ใบที่ครบทุกช่อง ⇒ ได้ตัวเลข และตัวเลขต้องตรงกับการคิดมือ", () => {
  const ได้ = shopeeNet(ใบครบ);
  const มือ = 1000 - 50 - 20 - 5 - 30 - 40 + 35 + 10;
  assert.equal(ได้, มือ, `สูตรต้องได้ ${มือ} · ได้ ${ได้}`);
  assert.equal(ได้, 900, "ตรึงค่าไว้ด้วย — เปลี่ยนสูตรแล้วต้องมาแก้ด่านพร้อมเหตุผลที่วัดมา");
});

test("🔴 ช่อง **จำเป็น** ขาด ⇒ ต้องคืน `null` ห้ามแทน 0 แล้วคิดต่อ", () => {
  const จำเป็น = ["itemsTotal", "commission", "serviceFee", "paymentFee", "shippingActual"];
  for (const k of จำเป็น)
    for (const ขาด of [null, undefined]) {
      const ใบ = { ...ใบครบ, [k]: ขาด };
      assert.equal(
        shopeeNet(ใบ), null,
        `ขาด ${k} (${String(ขาด)}) ต้องได้ null · ได้ ${shopeeNet(ใบ)} ` +
          "⇒ ถ้าคิดต่อด้วย 0 เราจะรายงานยอดโอนที่ไม่มีใครวัด"
      );
    }
});

test("🔑 ช่องที่ 'ไม่มี = ไม่มีรายการนั้น' ⇒ นับเป็น 0 ได้ (ต้องไม่ถูกยุบรวมกับกองบน)", () => {
  const ยอมว่าง = ["sellerTransactionFee", "shippingSubsidyByShopee", "shippingPaidByBuyer"];
  for (const k of ยอมว่าง) {
    const ใบ = { ...ใบครบ, [k]: null };
    assert.notEqual(shopeeNet(ใบ), null, `${k} ว่างต้องยังคิดได้ — มันแปลว่าไม่มีรายการนั้น`);
  }
  /* และค่าที่ได้ต้องต่างจากใบครบตามจำนวนที่หายไปจริง ไม่ใช่เท่าเดิม */
  assert.equal(shopeeNet({ ...ใบครบ, sellerTransactionFee: null }), 905,
    "ค่าธรรมเนียมธุรกรรมที่ไม่มี ⇒ ไม่ต้องหัก ⇒ ยอดโอนสูงขึ้น 5");
  assert.equal(shopeeNet({ ...ใบครบ, shippingSubsidyByShopee: null }), 865,
    "ค่าส่งที่ Shopee ไม่ช่วย ⇒ ไม่ต้องบวกคืน ⇒ ยอดโอนต่ำลง 35");
});

test("🧪 ตัวควบคุมลบ: ถ้าสูตรแทนช่องขาดด้วย 0 ผลจะเปลี่ยนไปเป็นตัวเลข ⇒ ด่านข้างบนจับได้จริง", () => {
  /* 🔑 ปลูก "สูตรรุ่นเลว" ขึ้นมาเทียบ — พิสูจน์ว่าเกณฑ์ `=== null` แยกแยะได้ ไม่ใช่เขียวเพราะอะไรก็ผ่าน */
  const สูตรเลว = (f) => {
    const n = (v) => (v === null || v === undefined ? 0 : v);
    return n(f.itemsTotal) - n(f.commission) - n(f.serviceFee) - n(f.sellerTransactionFee)
      - n(f.paymentFee) - n(f.shippingActual) + n(f.shippingSubsidyByShopee) + n(f.shippingPaidByBuyer);
  };
  const ใบขาด = { ...ใบครบ, commission: null };
  assert.equal(shopeeNet(ใบขาด), null, "สูตรจริงต้องคืน null");
  assert.equal(typeof สูตรเลว(ใบขาด), "number", "สูตรเลวคืนตัวเลข ⇒ เกณฑ์ของด่านแยกสองรุ่นนี้ออก");
});

test("🔴 `ปิดบัญชี()` — ผลต่างสูตรห้ามนับว่า 'อธิบายได้'", () => {
  /* 🔴 ผมเคยเขียนให้ `formula_diff` ถูกนับเป็นค่าที่อธิบายได้ ⇒ จอขึ้นว่า "เหลืออธิบายไม่ได้ 0"
     ทั้งที่ 3,900฿ เป็นของที่ **ไม่รู้ว่าเป็นค่าอะไร** โดยนิยาม · และเทสรอบนั้นไม่จับ
     เพราะทุกใบจำลองตั้ง formula_diff ไว้ที่ 0 (ตั้งศูนย์ = ลบเส้นทางนั้นออกจากการทดสอบ) */
  /* ⚠️ ชื่อช่องต้องตรงกับที่ `shopeeFeesSummary` ส่งมาจริง — รุ่นแรกผมพิมพ์ชื่อคอลัมน์ในฐาน
     (items/fees/net) ซึ่งฟังก์ชันนี้ไม่รู้จัก ⇒ ได้ "ปิดบัญชีไม่ได้" แล้วด่านแดงเพราะ **ผมป้อนผิด**
     🔑 นี่คือเหตุที่ทางออก "ปิดบัญชีไม่ได้" ต้องบอกชื่อช่องที่ขาด — มันชี้ความผิดให้ผมเองได้ทันที */
  const แถว = {
    ราคาสินค้ารวม: 10000, ยอดโอนสุทธิ: 6700, คอมมิชชั่น: 800, ค่าบริการ: 200,
    ค่าธรรมเนียมชำระเงิน: 200, ค่าส่งตามจริง: 400, ค่าธุรกรรมผู้ขาย: 100,
    ค่าส่งที่Shopeeออกให้: 300, ค่าส่งที่ผู้ซื้อจ่าย: 200, ผลต่างสูตรรวม: 2100,
  };
  const r = ปิดบัญชี(แถว);
  const คีย์ = Object.keys(r).join(" · ");
  console.log(`   🔎 ปิดบัญชี() คืนช่อง: ${คีย์}`);
  assert.ok(!("🧾 ปิดบัญชีไม่ได้" in r), `ป้อนครบแล้วต้องไม่ตีกลับ · ได้: ${JSON.stringify(r)}`);
  assert.ok("🧾 ผลต่างสูตร (ยังไม่รู้ว่าเป็นค่าอะไร)" in r,
    `ผลต่างสูตรต้องอยู่ถังของตัวเอง ห้ามยุบเข้า 'ค่าธรรมเนียมที่มีชื่อ' · ได้ช่อง: ${คีย์}`);
  assert.equal(r["🧾 ผลต่างสูตร (ยังไม่รู้ว่าเป็นค่าอะไร)"], 2100,
    "ใบทดสอบใบนี้ตั้งผลต่างสูตร = 2,100 โดยตั้งใจ — **ตั้ง 0 เท่ากับลบเส้นทางนี้ออกจากการทดสอบ**");
  /* 🔑 ข้อสำคัญที่สุด: ผลต่างสูตร **ห้าม** ถูกนับรวมใน "ค่าธรรมเนียมที่มีชื่อ" */
  assert.equal(r["🧾 ค่าธรรมเนียมที่มีชื่อ"], 800 + 200 + 200 + 400 + 100 - 300 - 200,
    "ช่อง 'มีชื่อ' ต้องเป็นผลรวมของช่องที่ Shopee บอกชื่อเท่านั้น");
  assert.ok("🧾 เหลืออธิบายไม่ได้แม้รวมผลต่างสูตร" in r, "ต้องมีช่องเหลืออธิบายไม่ได้");
  assert.match(String(r["⚠️ ผลต่างสูตรไม่เป็นศูนย์"] ?? ""), /ห้ามเฉลี่ยทิ้ง/,
    "ผลต่างสูตรที่ไม่เป็นศูนย์ต้องมีคำเตือนติดมาด้วย ⇒ คนอ่านไม่เอาไปเฉลี่ยทิ้ง");
});

test("🔴 ไม่มีใบใหม่ ⇒ ต้องไม่กลืนเป็น 'ครบแล้ว' ถ้ายังมีใบค้าง (ขัดกันในตัว)", () => {
  const i = โค้ด.indexOf("ขัดกันในตัว");
  assert.ok(i > 0, "ทางออก 'ขัดกันในตัว' หายไป — เส้นนี้กันการรายงานว่าครบทั้งที่ตัวหยิบใบพัง");
  console.log(`   🔎 ทางออก 'ขัดกันในตัว' อยู่ ${ไฟล์}:${เลขบรรทัด(โค้ด, i)}`);
  const ก้อน = โค้ด.slice(Math.max(0, i - 400), i + 200);
  assert.match(ก้อน, /ค้างก่อนรอบนี้["\]]*\s*>\s*0/,
    "เกณฑ์ต้องเทียบกับจำนวนใบที่ค้าง — ไม่งั้น 'หยิบได้ 0 ใบ' จะอ่านว่าครบทุกครั้ง");
  assert.match(ก้อน, /out\.ok = false/, "ต้องพลิก ok เป็น false ⇒ จอไม่เขียนว่าสำเร็จ");
});

test("🔴 หมดเวลาแล้วต้องประกาศ `truncatedByTime` — ห้ามคืนผลบางส่วนที่หน้าตาเหมือนครบ", () => {
  const i = โค้ด.indexOf("truncatedByTime = true");
  assert.ok(i > 0, "ไม่เจอจุดที่ติดธงหมดเวลา");
  console.log(`   🔎 ธงหมดเวลาติดที่ ${ไฟล์}:${เลขบรรทัด(โค้ด, i)}`);
  assert.match(โค้ด.slice(i - 120, i + 60), /TIME_BUDGET_MS/,
    "ต้องผูกกับงบเวลาจริง ไม่ใช่ติดธงตามเงื่อนไขอื่น");
  assert.match(โค้ด, /truncatedByTime:\s*false/,
    "ต้องประกาศคีย์นี้ตั้งแต่ต้น — คีย์ที่โผล่เป็นบางครั้งทำให้จอแยก 'ไม่ครบ' จาก 'ท่อรุ่นเก่า' ไม่ออก");
});

test("🔔 เกณฑ์เตือนสูตรเพี้ยนต้องอยู่ที่ตัวงาน และผูกกับใบที่ต่างเกิน 2 บาท", () => {
  const งานไฟล์ = "netlify/functions/mkp-fees-sync.mjs";
  const งาน = ซอร์สไม่เอาคอมเมนต์(งานไฟล์);
  const i = งาน.indexOf("ใบที่สูตรต่างเกิน2บาท");
  assert.ok(i > 0, "ตัวงานต้องอ่านรายการใบที่สูตรต่างเกิน 2 บาท");
  console.log(`   🔎 เกณฑ์เตือนอยู่ ${งานไฟล์}:${เลขบรรทัด(งาน, i)}`);
  assert.match(งาน, /await fetch\(`https:\/\/api\.telegram\.org/,
    "ตัวแจ้งเตือนต้องถูก await — ไม่งั้น Netlify แช่แข็งฟังก์ชันแล้วเสียงหาย");
  assert.match(งาน, /ห้ามปรับเลขให้ต่างเป็น 0/,
    "ข้อความเตือนต้องบอกวิธีที่ **ห้าม** ทำด้วย ไม่งั้นคนรอบหน้าจะแก้ให้ diff เป็น 0 แล้วปิดเสียง");
  /* ชีพจรต้องเขียนทุกรอบ — ไม่งั้นแยก "ไม่มีใบใหม่" จาก "งานตาย" ไม่ออก */
  assert.match(งาน, /INSERT INTO core_meta \(k, v, at\) VALUES \('mkp_fees_sync'/,
    "ต้องเขียนชีพจร core_meta ทุกรอบ");
  assert.ok(!/MAX\(at\).*shopee_fees/.test(งาน),
    "ห้ามใช้ MAX(at) ของตารางแทนชีพจร — คืนที่ไม่มีใบใหม่จะดูเหมือนงานตาย");
});
