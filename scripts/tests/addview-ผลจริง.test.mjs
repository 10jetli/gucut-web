import assert from "node:assert/strict";
import { mock, test } from "node:test";

let พัง = new Set();     // ชั้นที่จะให้เขียนล้ม: "w" · "q" · "f"
let เขียน = [];
mock.module("@netlify/blobs", { namedExports: {
  getStore: () => ({
    setJSON: async (k) => {
      const ชั้น = String(k).split("/")[0];
      if (พัง.has(ชั้น)) throw new Error(`Blobs 500: ${ชั้น} ล่มจำลอง`);
      เขียน.push(k);
    },
    list: async () => ({ blobs: [] }),
    get: async () => null,
  }),
} });

const { addView } = await import("../../netlify/lib/views.mjs");
const ตั้ง = () => { พัง = new Set(); เขียน = []; };

test("เขียนครบทุกชั้น ⇒ บันทึกแล้วครบ · ล้มว่าง", async () => {
  ตั้ง();
  const r = await addView("clip1", "ผู้ชม1", 0.95);
  assert.deepEqual(r.บันทึกแล้ว, ["w", "q", "f"]);
  assert.deepEqual(r.ล้ม, []);
  assert.equal(เขียน.length, 3, "ต้องเขียนลงถังจริงสามคีย์ (ไม่ใช่ประกอบผลด้วยมือ)");
});

test("ดูไม่ถึงครึ่ง ⇒ เขียนแค่ w (ไม่ใช่ความล้มเหลว)", async () => {
  ตั้ง();
  const r = await addView("clip1", "ผู้ชม1", 0.1);
  assert.deepEqual(r.บันทึกแล้ว, ["w"]);
  assert.deepEqual(r.ล้ม, [], "ไม่ได้เขียน q/f เพราะยังไม่ถึงเกณฑ์ ⇒ ต้องไม่นับเป็นล้ม");
});

test("🔑 ชั้น w ล้ม ⇒ ต้องรายงาน (วิวหายทั้งใบ)", async () => {
  ตั้ง(); พัง.add("w");
  const r = await addView("clip1", "ผู้ชม1", 0.95);
  assert.ok(r.ล้ม.includes("w"), "ของเดิมกลืนด้วย .catch(() => {}) ⇒ ผู้เรียกไม่มีทางรู้");
  assert.ok(!r.บันทึกแล้ว.includes("w"));
});

test("🔑 ทิศกลับ: ชั้น q ล้ม แต่ w สำเร็จ ⇒ **วิวต้องยังนับได้**", async () => {
  ตั้ง(); พัง.add("q");
  const r = await addView("clip1", "ผู้ชม1", 0.95);
  assert.ok(r.บันทึกแล้ว.includes("w"), "w สำเร็จ ⇒ วิวนับได้ — ห้ามโยนทั้งก้อนเพราะ q ล้ม");
  assert.deepEqual(r.ล้ม, ["q"], "ต้องบอกว่าเสียความละเอียด ไม่ใช่เงียบ และไม่ใช่ถือว่าวิวหาย");
});

test("ทุกชั้นล้ม ⇒ บันทึกแล้วว่าง · ล้มครบ", async () => {
  ตั้ง(); พัง = new Set(["w", "q", "f"]);
  const r = await addView("clip1", "ผู้ชม1", 0.95);
  assert.deepEqual(r.บันทึกแล้ว, []);
  assert.deepEqual(r.ล้ม.sort(), ["f", "q", "w"]);
});

test("🔑 ค่าไม่ถูกต้อง ⇒ แยกจาก 'ถังล่ม' (คนละความผิด คนละรหัส HTTP)", async () => {
  ตั้ง();
  for (const [ชื่อ, id, vid] of [["ไม่มี id", "", "v"], ["ไม่มี vid", "c", ""], ["ทั้งคู่ว่าง", "", ""]]) {
    const r = await addView(id, vid, 0.9);
    assert.equal(r.ค่าไม่ถูกต้อง, true, ชื่อ);
    assert.deepEqual(r.บันทึกแล้ว, [], `${ชื่อ}: ต้องไม่อ้างว่าเขียนอะไร`);
  }
  assert.equal(เขียน.length, 0, "ค่าเสีย ⇒ ต้องไม่แตะถังเลย");
});

test("`ล้ม` ต้องมีในคำตอบเสมอ **แม้เป็นอาร์เรย์ว่าง**", async () => {
  ตั้ง();
  const r = await addView("clip1", "ผู้ชม1", 0);
  assert.ok("ล้ม" in r && "บันทึกแล้ว" in r && "ค่าไม่ถูกต้อง" in r,
    "ไม่มีช่อง ≠ ไม่มีปัญหา — จอต้องแยก 'ท่อรุ่นเก่าไม่ส่งมา' จาก 'ไม่มีอะไรล้ม' ได้");
});

test("🔑 ผู้เรียก: `social.mjs` ต้องไม่ตอบ ok เมื่อชั้น w ล้ม (อ่านจากซอร์ส)", async () => {
  /* ⚠️ เส้น `/api/social` ต้องมีคำขอจริง+ถังจริงถึงจะยิงได้ ⇒ ตรวจรูปของผู้เรียกจากซอร์ส
     **ขอบเขต**: ข้อนี้พิสูจน์ว่า "ผู้เรียกดูค่าที่คืนมา" ไม่ได้พิสูจน์ว่า 503 ยิงตอนเงื่อนไขจริง
     (ของที่พิสูจน์พฤติกรรมคือเจ็ดข้อข้างบน ซึ่งขับ `addView` ตัวจริงกับถังปลอม) */
  const { readFileSync } = await import("node:fs");
  const { ตัดคอมเมนต์ } = await import("../_strip-comments.mjs");
  const โค้ด = ตัดคอมเมนต์(readFileSync("netlify/functions/social.mjs", "utf8"), "social.mjs");
  assert.match(โค้ด, /ผลวิว\s*=\s*await addView\(/, "ต้องเก็บค่าที่ addView คืนมา ไม่ใช่ await ทิ้ง");
  assert.match(โค้ด, /ผลวิว\.ล้ม\.includes\("w"\)[\s\S]{0,200}503/,
    "ชั้น w ล้ม ⇒ ต้องตอบ 503 — ของเดิมตอบ {ok:true} เสมอ");
  assert.match(โค้ด, /ค่าไม่ถูกต้อง[\s\S]{0,120}400/,
    "ค่าที่หน้าเว็บส่งมาเสีย ⇒ 400 ไม่ใช่ 503 (คนละความผิด)");
});
