import { test, mock } from "node:test";
import assert from "node:assert/strict";

let แถวค้าง = [];
let sqlที่ใช้ = "";
let argsที่ใช้ = [];
mock.module("../../netlify/lib/coredb.mjs", { namedExports: {
  coreReady: () => true,
  coreQuery: async (sql, args = []) => {
    if (/GROUP BY channel, skip_reason/.test(sql)) { sqlที่ใช้ = sql; argsที่ใช้ = args; return แถวค้าง; }
    return [];
  },
}});
const { สถานะดันสต็อก: สรุปให้จอ } = await import("../../netlify/lib/stock-push-sweep.mjs");

test("① เกณฑ์ต้องคิดเป็นชั่วโมง และส่งเกณฑ์ไปกับค่า", async () => {
  แถวค้าง = [];
  const r = await สรุปให้จอ();
  assert.equal(typeof r.ค้างนานเกณฑ์ชั่วโมง, "number", "ต้องส่งเกณฑ์ไปด้วย ไม่ให้จอฝังเลขเอง");
  assert.ok(r.ค้างนานเกณฑ์ชั่วโมง > 0);
  /* ⚠️ ผูกกับ **เจตนา**: คำสั่งต้องกรองด้วยเวลา ไม่ใช่ด้วยจำนวนรอบ
     (ถ้าวันหนึ่งมีคนเปลี่ยนไปกรองด้วย skip_streak ด่านนี้ต้องตก) */
  assert.match(sqlที่ใช้, /skip_first_at\s*<\s*datetime/, "ต้องกรองด้วยเวลา ไม่ใช่จำนวนรอบ");
  assert.ok(String(argsที่ใช้[0]).includes("hours"), "หน่วยต้องเป็นชั่วโมง");
});

test("② ไม่มีรหัสค้างนาน ⇒ ต้องเป็น [] ไม่ใช่ null (ตรวจแล้วไม่มี ≠ อ่านไม่ได้)", async () => {
  แถวค้าง = [];
  const r = await สรุปให้จอ();
  assert.deepEqual(r.ค้างนานผิดปกติ, [], "ตรวจแล้วไม่มี ต้องเป็นอาเรย์ว่าง");
});

test("③ มีรหัสค้างนาน ⇒ แยกตามเหตุและช่องทาง ห้ามยุบเป็นเลขเดียว", async () => {
  แถวค้าง = [
    { channel: "lazada", skip_reason: "negative", รหัส: 15, เก่าสุด: "2026-09-17 06:00:50", รอบติดกันมากสุด: 110 },
    { channel: "shopee", skip_reason: "unknown", รหัส: 43, เก่าสุด: "2026-09-17 15:35:09", รอบติดกันมากสุด: 90 },
  ];
  const r = await สรุปให้จอ();
  assert.equal(r.ค้างนานผิดปกติ.length, 2, "ต้องแยกแถวตาม (ช่องทาง × เหตุ)");
  const เหตุ = r.ค้างนานผิดปกติ.map((x) => x.skip_reason);
  assert.ok(เหตุ.includes("negative") && เหตุ.includes("unknown"), "เหตุต่างกันต้องไม่ถูกยุบรวม");
  /* คำอธิบายต้องบอกว่าใครแก้อะไร ไม่ใช่แค่บอกว่ามีปัญหา */
  const อธิบาย = Object.entries(r).filter(([k]) => k.includes("อ่านยังไง")).map(([, v]) => String(v)).join(" ");
  assert.match(อธิบาย, /negative/, "ต้องอธิบายว่าเหตุ negative หมายถึงอะไร");
  assert.match(อธิบาย, /ห้าม/, "ต้องเตือนห้ามเอากองที่ถูกข้ามทั้งกองมาขึ้นเตือน");
});

test("④ คำอธิบายต้องบอกว่าของกลุ่มนี้ **ไม่นับเป็น error** จึงไม่มีอะไรร้อง", async () => {
  แถวค้าง = [];
  const r = await สรุปให้จอ();
  const อธิบาย = Object.entries(r).filter(([k]) => k.includes("อ่านยังไง")).map(([, v]) => String(v)).join(" ");
  /* นี่คือเหตุที่ของค้าง 110 รอบโดยไม่มีใครรู้ — ถ้าไม่เขียนไว้ คนรอบหน้าจะงงว่าทำไมต้องมีช่องนี้
     ทั้งที่มีช่อง `มีข้อผิดพลาด` อยู่แล้ว */
  assert.match(อธิบาย, /ไม่นับเป็น error|ไม่มีอะไรร้อง/, "ต้องอธิบายว่าทำไมช่อง มีข้อผิดพลาด จับไม่ได้");
});

