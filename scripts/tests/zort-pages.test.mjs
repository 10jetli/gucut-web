import { test } from "node:test";
import assert from "node:assert/strict";
import { อ่านหน้าZort, ตรวจชนเพดาน } from "../../netlify/lib/zort-pages.mjs";

const เดิม = globalThis.fetch;
/** แทนขอบเครือข่าย · `how` บอกว่าปลายทางเสียแบบไหน */
const ปลายทาง = (how) => {
  globalThis.fetch = async () => {
    if (how === "ต่อไม่ติด") throw new Error("ECONNRESET");
    if (how === "500") return { ok: false, status: 500, json: async () => ({}) };
    if (how === "429") return { ok: false, status: 429, json: async () => ({}) };
    if (how === "jsonเสีย") return { ok: true, status: 200, json: async () => { throw new SyntaxError("Unexpected token <"); } };
    if (how === "ไม่มีlist") return { ok: true, status: 200, json: async () => ({ count: 7 }) };
    if (how === "listไม่ใช่อาเรย์") return { ok: true, status: 200, json: async () => ({ list: { 0: {} } }) };
    if (how === "listnull") return { ok: true, status: 200, json: async () => ({ list: null }) };
    if (how === "ว่าง") return { ok: true, status: 200, json: async () => ({ list: [] }) };
    return { ok: true, status: 200, json: async () => ({ list: [{ id: 1 }, { id: 2 }] }) };
  };
};
const คืน = () => { globalThis.fetch = เดิม; };

const ยิง = (หน้า = 1) => อ่านหน้าZort("https://x/y?page=1", {}, { หน้า, ชื่อ: "ทดสอบ", timeout: 50 });

test("ของดี: คืนรายการตามที่ปลายทางให้", async () => {
  ปลายทาง("ดี");
  try { assert.deepEqual(await ยิง(1), [{ id: 1 }, { id: 2 }]); } finally { คืน(); }
});

test("🔑 หน้าว่างจริง ⇒ [] ไม่โยน — นี่คือทางออก 'หมดจริง' ห้ามทำให้แดง", async () => {
  ปลายทาง("ว่าง");
  try {
    assert.deepEqual(await ยิง(1), []);
    assert.deepEqual(await ยิง(3), [], "หน้ากลางที่ว่างแต่มีช่อง list = หมดจริง ไม่ใช่อ่านไม่ได้");
  } finally { คืน(); }
});

test("🔑 ปลายทางเสียทุกแบบ ⇒ **โยน** ห้ามคืน [] (คืน [] = ลูปปิดเหมือนหมดหน้า)", async () => {
  for (const how of ["ต่อไม่ติด", "500", "429", "jsonเสีย"]) {
    ปลายทาง(how);
    try {
      await assert.rejects(
        () => ยิง(1), /ห้ามนับว่าหมดหน้า/,
        `${how}: ต้องโยนพร้อมคำว่า "ห้ามนับว่าหมดหน้า" — คืน [] คือรายงานว่าซิงก์ครบ`
      );
    } finally { คืน(); }
  }
});

test("ข้อความผิดพลาดต้องบอกเลขหน้าและชื่องาน (ไม่งั้นไล่ไม่ได้ว่าพังที่ไหน)", async () => {
  ปลายทาง("500");
  try {
    await assert.rejects(() => ยิง(4), (e) => {
      assert.match(e.message, /\[ทดสอบ\]/, "ต้องมีชื่องาน");
      assert.match(e.message, /หน้า 4/, "ต้องมีเลขหน้าจริง ไม่ใช่เลขที่เดา");
      assert.match(e.message, /500/, "ต้องมีรหัสที่ปลายทางตอบ");
      return true;
    });
  } finally { คืน(); }
});

test("🔑 ไม่มีช่อง list: **หน้าแรกไม่โยน · หน้า 2 ขึ้นไปโยน** (เหตุอยู่ในหัวไฟล์นั้น)", async () => {
  for (const how of ["ไม่มีlist", "listไม่ใช่อาเรย์", "listnull"]) {
    ปลายทาง(how);
    try {
      assert.deepEqual(
        await ยิง(1), [],
        `${how} หน้าแรก: ยังวัดรูปจริงตอนไม่มีข้อมูลไม่ได้ ⇒ ไม่ตั้งด่านบนรูปที่เดาเอา`
      );
      await assert.rejects(
        () => ยิง(2), /ไม่มีช่อง list กลางการไล่หน้า/,
        `${how} หน้า 2: มาถึงได้เพราะหน้าก่อนเต็มพอดี ⇒ ต้องมีช่อง list เสมอ`
      );
    } finally { คืน(); }
  }
});

// ───────────────────────── ตรวจชนเพดาน ─────────────────────────
test("🔑 ถึงหน้าสุดท้ายจริง ⇒ null (ห้ามร้องใส่รอบที่ครบจริง)", () => {
  assert.equal(
    ตรวจชนเพดาน({ ถึงหน้าสุดท้ายจริง: true, เพดานหน้า: 10, ต่อหน้า: 200, ชื่อ: "ก" }), null,
    "พลังแยกแยะ: ถ้าร้องใส่รอบที่ครบ คนจะปิดด่านทิ้งภายในวันเดียว"
  );
});

test("🔑 ไม่เจอหน้าสั้นเลย ⇒ Error — เพดานของเราห้ามกลายเป็นคำตอบเรื่องจำนวนของคนอื่น", () => {
  const e = ตรวจชนเพดาน({ ถึงหน้าสุดท้ายจริง: false, เพดานหน้า: 10, ต่อหน้า: 200, ชื่อ: "syncBundles" });
  assert.ok(e instanceof Error, "ต้องเป็น Error ไม่ใช่สตริง — ผู้เรียกใช้ .message");
  assert.match(e.message, /syncBundles/);
  assert.match(e.message, /10 หน้า/);
  assert.match(e.message, /2000 รายการ/, "ต้องคิดเลขให้ (เพดาน×ต่อหน้า) ไม่ใช่ให้คนคูณเอง");
  assert.match(e.message, /ห้ามใช้/, "ต้องบอกว่าห้ามใช้ของที่ได้ ไม่ใช่แค่บอกว่าชนเพดาน");
});

test("ช่วงเวลา (ถ้าส่งมา) ต้องโผล่ในข้อความ — ใบที่ชนเพดานต้องรู้ว่าช่วงไหน", () => {
  const e = ตรวจชนเพดาน({ ถึงหน้าสุดท้ายจริง: false, เพดานหน้า: 6, ต่อหน้า: 200, ชื่อ: "ข", ช่วง: "2026-10-01..10-07" });
  assert.match(e.message, /2026-10-01\.\.10-07/);
});
