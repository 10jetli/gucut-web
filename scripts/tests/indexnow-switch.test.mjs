/* ด่าน: สวิตช์ IndexNow ต้องอยู่ใน netlify.toml — **ของที่ไม่มีอะไรจุดชนวนจะตายเงียบ**
 *
 * 🔴 ที่มา 19 ก.ย. 2569 (สองชั้น)
 *    ① `npm run build` ในเครื่องเพื่อ **ตรวจ** ว่า build ผ่าน ⇒ postbuild ยิงบอก Bing/Yandex
 *      ว่า 10 หน้าเปลี่ยน **ทั้งที่ไม่มีอะไร deploy** ⇒ ข้อมูลเท็จ + ไฟล์นั้นเตือนตัวเองไว้แล้วว่าเสี่ยงถูกเมินทั้งโดเมน
 *    ② ทางแก้แรกของผมคือให้สคริปต์เดาว่า "อยู่บน Netlify ไหม" จากชื่อตัวแปร
 *      ⇒ **ถ้าเดาผิด IndexNow ตายเงียบตลอดกาล** = เอาของที่ทำงานอยู่ไปพัง ซึ่งแย่กว่าปัญหาเดิม
 *      ⇒ repo นี้ไม่มีที่ไหนใช้ `process.env.NETLIFY` มาก่อน ⇒ ไม่มีหลักฐานในบ้านว่าตัวแปรนั้นมีจริง
 * 🔑 จึงเปลี่ยนเป็นสวิตช์ตรง ๆ ใน `netlify.toml` ⇒ **ตรวจได้ด้วยตา ไม่ต้องอ่าน build log ของใคร**
 *    และ build ในเครื่องจะไม่มีตัวแปรนี้โดยธรรมชาติ
 * ⚠️ ด่านนี้มีไว้กันบรรทัดนั้น**หายไปเงียบ ๆ** ตอนมีคนจัดระเบียบ netlify.toml
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

test("netlify.toml ต้องตั้ง INDEXNOW_FORCE ไว้ใน build.environment", () => {
  const toml = readFileSync("netlify.toml", "utf8");
  const i = toml.indexOf("[build.environment]");
  assert.ok(i > 0, "ไม่มีบล็อก [build.environment] — เปลี่ยนโครงไฟล์แล้วต้องมาแก้ด่านนี้");
  const ถัดไป = toml.indexOf("\n[", i + 5);
  const ก้อน = toml.slice(i, ถัดไป > 0 ? ถัดไป : undefined);
  assert.match(
    ก้อน, /INDEXNOW_FORCE\s*=\s*"1"/,
    "ลบบรรทัดนี้ = IndexNow หยุดยิงถาวร (เว็บยังขึ้นปกติ แต่เครื่องค้นหารู้ช้าลงเป็นวัน) " +
      "⇒ ถ้าตั้งใจปิดจริง ให้แก้ด่านนี้พร้อมเขียนเหตุผล ไม่ใช่ลบบรรทัดเงียบ ๆ",
  );
});

test("สคริปต์ต้องยังมีทางเงียบเมื่อไม่มีสวิตช์ — build ในเครื่องห้ามยิงออกนอกบ้าน", () => {
  const src = readFileSync("scripts/ping-indexnow.mjs", "utf8");
  assert.match(src, /INDEXNOW_FORCE/, "สคริปต์ต้องอ่านสวิตช์ตัวนี้");
  assert.match(src, /process\.exit\(0\)/, "ไม่มีสวิตช์ ⇒ ต้องออกเงียบ ไม่ใช่ทำ build ล้ม");
  /* 🔑 ผูกกับ **เจตนา**: ต้องมีข้อความบอกว่าข้ามเพราะอะไร ไม่ใช่ข้ามเงียบสนิท
     (ทางถอยต้องประกาศตัวเมื่อถูกใช้ ไม่งั้นกลายเป็นทางหลักโดยไม่มีใครตัดสินใจ) */
  assert.match(src, /ข้าม/, "ต้องพิมพ์บอกว่าข้ามเพราะอะไร");
});
