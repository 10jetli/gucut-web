import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด, ปลูกในโค้ด } from "./_src.mjs";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const ไฟล์ = "netlify/functions/feed-health.mjs";
const โค้ด = ซอร์สไม่เอาคอมเมนต์(ไฟล์);
const ดิบ = readFileSync(ไฟล์, "utf8");

/** ยกก้อน object literal ของทางออก `!map` มาอ่านค่าจริง (ไม่ต้องยิงเน็ต) */
function ก้อนอ่านไม่ได้() {
  const i = โค้ด.indexOf("if (!map) {");
  assert.ok(i > 0, "ไม่เจอทางออก 'อ่าน ZORT ไม่ได้' — เส้นนี้เคยมี ห้ามหาย");
  const j = โค้ด.indexOf("return json({", i);
  let d = 0, k = โค้ด.indexOf("{", j + 12);
  for (let x = k; x < โค้ด.length; x += 1) {
    if (โค้ด[x] === "{") d += 1;
    else if (โค้ด[x] === "}" && --d === 0) {
      k = x;
      break;
    }
  }
  const เนื้อ = โค้ด.slice(โค้ด.indexOf("{", j + 12), k + 1);
  return { เนื้อ, บรรทัด: เลขบรรทัด(โค้ด, i) };
}

test("✅ อ่านไฟล์และหาทางออก 'อ่านไม่ได้' เจอ", () => {
  const { เนื้อ, บรรทัด } = ก้อนอ่านไม่ได้();
  console.log(`   🔎 ${ไฟล์}:${บรรทัด} ทางออกตอน ZORT อ่านไม่ได้ (${เนื้อ.length} ตัวอักษร)`);
  assert.ok(เนื้อ.length > 100, `ก้อนสั้นผิดปกติ (${เนื้อ.length}) — น่าจะจับผิดที่`);
  assert.match(โค้ด, /path:\s*"\/api\/feed-health"/, "ต้องประกาศ path เอง");
});

test("🔴 ทั้งสามคำถาม: อ่าน ZORT ไม่ได้ ⇒ ต้องเป็น `null` **ห้ามเป็น 0 หรือ []**", () => {
  const { เนื้อ } = ก้อนอ่านไม่ได้();
  /* ① ความสดของสต็อก */
  assert.match(เนื้อ, /stockLive:\s*null/,
    "`stockLive: false` แปลว่า 'ใช้ของเก่าอยู่' ซึ่งคนละเรื่องกับ 'ไม่รู้' ⇒ ต้องเป็น null");
  assert.match(เนื้อ, /stockSource:\s*"unreadable"/, "ต้องบอกที่มาว่าอ่านไม่ได้");
  /* ② ของใน ZORT ที่เว็บไม่มีหน้า */
  for (const k of ["inZort", "matched", "missingCount", "missing"])
    assert.match(
      เนื้อ, new RegExp(`${k}:\\s*null`),
      `\`${k}\` ต้องเป็น null · ถ้าเป็น 0/[] จอจะอ่านว่า "ตรวจแล้วไม่มีอะไรตกหล่น"`
    );
  /* ③ ของบนเว็บที่หาไม่เจอใน ZORT */
  for (const k of ["notInZortCount", "notInZort"])
    assert.match(เนื้อ, new RegExp(`${k}:\\s*null`), `\`${k}\` ต้องเป็น null`);
  /* 🔑 และต้องไม่มีเลข 0 หรืออาร์เรย์ว่างหลุดอยู่ในก้อนนี้เลย (ยกเว้น onSite ที่รู้จริง) */
  const ขาด = [...เนื้อ.matchAll(/(\w+):\s*(0|\[\])\s*[,}]/g)].map((m) => m[1]);
  assert.deepEqual(ขาด, [], `ยังมีช่องที่ตอบ 0/[] ตอนไม่รู้: ${ขาด.join(", ")}`);
});

test("🔑 `onSite` ต้องยังเป็นตัวเลข — ข้อนี้เรารู้จริง (มาจากไฟล์ของเว็บเอง ไม่ได้ถาม ZORT)", () => {
  const { เนื้อ } = ก้อนอ่านไม่ได้();
  assert.match(เนื้อ, /onSite:\s*list\.length/,
    "ทำ null ทั้งก้อนก็ผิดอีกทาง — ช่องที่วัดได้จริงต้องตอบตัวเลข ไม่งั้นจอจะบอดทั้งหน้า");
});

