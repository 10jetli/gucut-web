  const i = โค้ด.lastIndexOf("stockSource:");
  console.log(`   🔎 ${ไฟล์}:${เลขบรรทัด(โค้ด, i)} ที่มาของสต็อกในทางปกติ`);
  const บรรทัด = โค้ด.slice(i, โค้ด.indexOf("\n", i));
