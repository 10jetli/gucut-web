/* ด่านของอัตราเผาเครดิต — ฝั่งจอขอสามช่องนี้พร้อมเงื่อนไขสองข้อ (19 ก.ย. 2569)
 *
 * 🔴 ที่มาของทั้งเรื่อง: ป้ายเครดิตอยู่บนทุกจออยู่แล้ว **แต่โชว์ `used/plan`**
 *    ตอน 09:27 ป้ายขึ้น "ใช้ไป 5.2%" (อ่านว่าสบายมาก) ขณะที่ตัวเฝ้าร้องว่า **เหลือ 4.8 วัน**
 *    ⇒ ทั้งคู่ถูก แต่ตอบคนละคำถาม: ยอดสะสมตอบ "เหลือเท่าไหร่" · อัตราตอบ "จะถึงเมื่อไหร่"
 *    🔑 **เกณฑ์ที่ดูแต่ยอดสะสม จะเงียบในวันที่ควรดังที่สุด** (วันที่เผาหนักผิดปกติแต่ยอดยังต่ำ)
 *
 * เงื่อนไขที่ฝั่งจอขอ และด่านนี้บังคับ
 *  ① `burnWindowHours` **ต้องมาคู่กับอัตราเสมอ** — เลข "4.8 วัน" ที่ไม่มีหน้าต่างกำกับ
 *     ทำให้ตัดสินใจผิดแรงกว่าไม่มีเลข
 *  ② คิดไม่ได้ ⇒ **`null` ห้าม 0 และห้ามค่าตั้งต้น** — `0 วัน` จะกลายเป็นแดงทันที
 *     `999 วัน` จะเขียวตลอดกาล ⇒ `null` คือคำตอบที่ถูกเมื่อยังไม่รู้
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { คิดอัตราเผา } from "../../netlify/functions/netlify-credits.mjs";

const ชม = (n) => n * 3600_000;
const now = 1_700_000_000_000;

test("① คิดได้ ⇒ ต้องมี burnWindowHours มาด้วยเสมอ", () => {
  const r = คิดอัตราเผา([{ at: now - ชม(10), used: 100 }], { at: now, used: 200, left: 1000 });
  assert.equal(r.burnWindowHours, 10, "ต้องบอกหน้าต่างที่ใช้คิด");
  assert.equal(r.burnPerDay, 240, "เผา 100 ใน 10 ชม. ⇒ 240/วัน");
  assert.equal(r.daysLeft, 4.2, "เหลือ 1000 ÷ 240 ≈ 4.2 วัน");
});

test("② ประวัติไม่พอ (หน้าต่างสั้นกว่าเกณฑ์) ⇒ อัตราเป็น null ห้ามเป็น 0", () => {
  const r = คิดอัตราเผา([{ at: now - ชม(0.5), used: 100 }], { at: now, used: 200, left: 1000 });
  assert.equal(r.burnPerDay, null, "หน้าต่างสั้น ⇒ ยังไม่รู้ ไม่ใช่เผา 0");
  assert.equal(r.daysLeft, null);
  /* 🔑 แต่ยังบอกหน้าต่างที่มี ⇒ คนอ่านรู้ว่าทำไมยังคิดไม่ได้ */
  assert.equal(r.burnWindowHours, 0.5);
});

test("② ไม่มีประวัติเลย ⇒ null ทั้งสามช่อง", () => {
  const r = คิดอัตราเผา([], { at: now, used: 200, left: 1000 });
  assert.deepEqual(r, { burnPerDay: null, daysLeft: null, burnWindowHours: null });
});

test("ยอดใช้ไม่ขยับ ⇒ burnPerDay 0 ได้ แต่ daysLeft ต้องเป็น null", () => {
  /* 🔑 "เผา 0" เป็นข้อเท็จจริงที่วัดได้ · แต่ "เหลือกี่วัน" หารด้วยศูนย์ไม่ได้
     ⇒ ห้ามเดาเป็นค่ามาก ๆ (จะเขียวตลอดกาล) */
  const r = คิดอัตราเผา([{ at: now - ชม(5), used: 200 }], { at: now, used: 200, left: 1000 });
  assert.equal(r.burnPerDay, 0);
  assert.equal(r.daysLeft, null, "หารด้วยศูนย์ไม่ได้ ⇒ ยังไม่รู้ ห้ามเดาเป็นเขียว");
  assert.equal(r.burnWindowHours, 5);
});

test("ขึ้นรอบบิลใหม่ (ยอดใช้ลดลง) ⇒ ต้องไม่ได้อัตราติดลบ", () => {
  /* ⚠️ จุดเก่าที่ยอดใช้ **มากกว่า** ตอนนี้ = คร่อมการรีเซ็ตรอบบิล ⇒ ต้องถูกตัดออก
     ถ้าไม่ตัด จะได้เผาติดลบ แล้ววันเหลือกลายเป็นค่าเพี้ยน */
  const r = คิดอัตราเผา(
    [{ at: now - ชม(20), used: 9000 }, { at: now - ชม(4), used: 50 }],
    { at: now, used: 150, left: 1000 },
  );
  assert.equal(r.burnWindowHours, 4, "ต้องใช้จุดหลังรีเซ็ตเท่านั้น");
  assert.equal(r.burnPerDay, 600, "เผา 100 ใน 4 ชม. ⇒ 600/วัน");
  assert.ok(r.burnPerDay > 0, "ห้ามได้อัตราติดลบ");
});

test("เลือกหน้าต่างยาวที่สุดที่มี ไม่ใช่สองจุดติดกัน", () => {
  /* 🔑 นี่คือบทเรียนของวันนั้นเอง — สองจุดติดกัน (1 ชม.) ให้เลขที่หลอกตา
     ประวัติมี 10 ชม. ⇒ ต้องใช้ 10 ชม. ไม่ใช่ 1 ชม.ล่าสุด */
  const r = คิดอัตราเผา(
    [{ at: now - ชม(10), used: 100 }, { at: now - ชม(1), used: 900 }],
    { at: now, used: 1000, left: 1000 },
  );
  assert.equal(r.burnWindowHours, 10, "ต้องใช้จุดที่เก่าสุดในประวัติ");
  assert.equal(r.burnPerDay, 2160, "เผา 900 ใน 10 ชม. — ถ้าใช้ 1 ชม.ล่าสุดจะได้ 2,400 ซึ่งผันผวนกว่า");
});

test("ค่าที่อ่านไม่ได้ในประวัติ ต้องถูกข้าม ไม่ใช่ทำให้ทั้งก้อนพัง", () => {
  const r = คิดอัตราเผา(
    [{ at: "ไม่ใช่เวลา", used: 1 }, { at: now - ชม(6), used: 100 }, { used: 5 }],
    { at: now, used: 220, left: 600 },
  );
  assert.equal(r.burnWindowHours, 6);
  assert.equal(r.burnPerDay, 480);
});
