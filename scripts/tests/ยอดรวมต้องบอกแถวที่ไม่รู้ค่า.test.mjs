test("🔌 บรรทัดที่รู้จำนวนแต่ไม่รู้ราคา ต้องนับเป็น 'ไม่รู้' — ไม่ใช่คิดเป็น 0 บาท", () => {
  /* ยกสูตรเดียวกับที่ใช้จริงมาทดสอบพฤติกรรม (ของจริงอยู่ใน core-purchases)
     🔴 **รุ่นแรกผมเขียนเงื่อนไขเองที่นี่และในโค้ดจริง แล้วพลาดทันที**:
        `Number(null)` เป็น 0 และ finite · `String(null).trim()` เป็น "null" ไม่ใช่ค่าว่าง
        ⇒ บรรทัดที่ราคาเป็น null ผ่านเป็น 0 บาท = บั๊กเดิมที่งานนี้เกิดมาแก้ · เทสข้อนี้จับได้
     🔑 บทเรียน: ตัวกลางมีไว้ให้ **เรียก** ไม่ใช่ให้ **ลอกแนวคิดไปเขียนใหม่** */
  const เอาค่า = (l) => {
    const q = เลขหรือไม่รู้(l.qty);
    const pr = เลขหรือไม่รู้(l.price);
    return q === null || pr === null ? null : q * pr;
  };
  assert.equal(Number(null), 0, "ยืนยันพฤติกรรมของภาษาที่ทำให้พลาด: Number(null) = 0");
  assert.equal(Number.isFinite(Number(null)), true, "และมันเป็น finite ด้วย");
  const r = รวมแถว([{ qty: 2, price: 100 }, { qty: 3, price: null }, { qty: "", price: 50 }], เอาค่า);
  assert.equal(r.ผลรวม, 200, "รวมเฉพาะบรรทัดที่รู้ทั้งสองช่อง");
  assert.equal(r.ไม่รู้ค่า, 2, "บรรทัดที่ขาดช่องใดช่องหนึ่งต้องนับว่าไม่รู้");
  assert.equal(เอาค่า({ qty: 0, price: 100 }), 0, "จำนวน 0 ที่รู้จริง ⇒ ยอด 0 บาท ถูกต้อง (ไม่ใช่ไม่รู้)");
});

