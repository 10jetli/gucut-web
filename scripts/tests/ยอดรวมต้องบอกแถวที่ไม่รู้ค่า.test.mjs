test("🧪 ตัวควบคุม: สูตรแบบเก่า (`Number(x) || 0`) ให้ยอดเท่ากันแต่ **ไม่มีทางรู้ว่าไม่ครบ**", () => {
  const แถว = [{ a: 10 }, { a: null }, { a: " " }, { a: 5 }];
  const เก่า = แถว.reduce((s, r) => s + (Number(r.a) || 0), 0);
  const ใหม่ = รวมแถว(แถว, (r) => r.a);
  /* 🔑 หัวใจของงานนี้: **ตัวเลขเท่ากัน** ⇒ ดูจากยอดอย่างเดียวแยกไม่ออกเลย */
  assert.equal(เก่า, ใหม่.ผลรวม, "ยอดต้องเท่ากัน — ความต่างอยู่ที่ความครบ ไม่ใช่ที่ตัวเลข");
  assert.equal(typeof เก่า, "number", "สูตรเก่าคืนตัวเลขเปล่า");
  assert.equal(ใหม่.ครบ, false, "สูตรใหม่ต้องบอกว่าไม่ครบ");
  assert.equal(ใหม่.ไม่รู้ค่า, 2, "และบอกว่ากี่แถว");
  /* ⚠️ กับดักที่ `Number(" ") = 0` ทำให้สูตรเก่าดูเหมือนถูก: มันบวก 0 **โดยไม่ผ่านเงื่อนไข `|| 0`** เลย */
  assert.equal(Number(" "), 0, "ยืนยันพฤติกรรมของภาษา — ช่องว่างล้วนเป็น 0 และ finite");
});

