/** เจาะเอาเฉพาะก้อนของฟังก์ชันที่ต้องการ
 *  🔴 **จำเป็น** เพราะไฟล์นี้มี `amountความครบ` **สองที่** (ยอดซื้อ บรรทัด ~319 · ใบเสนอราคา ~850)
 *     `indexOf` เจอที่แรกเสมอ ⇒ เทสข้อ ② เคยไปตรวจก้อนของยอดซื้อ แล้วแดงด้วยเหตุผลที่ผิด
 *     🔑 คลาสที่วันนี้ผมเหยียบซ้ำหลายรอบ: อ่านที่แรกแล้วสรุปแทนทั้งไฟล์ */
