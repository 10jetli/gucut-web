/* ด่าน: **ห้ามมีร่องรอยของ "ของปลูกทดสอบ" ค้างในรีโป**
 *
 * 🔴 ที่มา 19 ก.ย. เย็น — ฝั่งจอเพิ่มข้อนี้ให้ตัวเองหลังเครื่องมือของเขาเรียกตัวเองไม่รู้จบ
 *    แล้ว **เขียนทับไฟล์ด่านจริงทับกันมั่ว** · กู้แล้วตัวที่ยังวิ่งอยู่เขียนกลับมาอีก
 *    🔑 ข้อที่เขาสรุปและผมไม่มี: **"รีโปสะอาด" จาก `git status` ไม่พอ**
 *       ถ้าเครื่องมือเราเขียนทับไฟล์ที่ **ถูก commit ไปแล้ว** — git บอกว่าสะอาด แต่เนื้อในเป็นของปลูก
 * ⇒ ด่านนี้กวาดหาคำที่ **เครื่องมือปลูกของเราใช้จริง** (ไม่ใช่คำที่นึกเอา)
 * ⚠️ `/(?!)/` เป็น sentinel ที่ **ถูกต้องและต้องมีได้** (รูปที่ไม่แมตช์อะไรเลยโดยไม่มีคำ) ⇒ ไม่นับ
 * ⚠️ ไฟล์ด่านนี้เองต้องเอ่ยถึงคำพวกนั้นได้ ⇒ ประกอบสตริงเป็นชิ้น ๆ **ไม่ยกเว้นไฟล์ตัวเอง**
 *    (ยกเว้นตัวเอง = ด่านตรวจไฟล์นั้นไม่ได้ตลอดกาล — กติกาที่เราตั้งกันไว้)
 */
import { test } from "node:test";
import { คำหมุดของปลูก } from "../lib/คำหมุดของปลูก.mjs";
import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const ราก = fileURLToPath(new URL("../..", import.meta.url));
const ไฟล์ = [];
const เดิน = (d) => {
  for (const ชื่อ of readdirSync(d)) {
    if (["node_modules", ".next", "out", ".git"].includes(ชื่อ)) continue;
    const p = join(d, ชื่อ);
    if (statSync(p).isDirectory()) เดิน(p);
    else if (/\.(mjs|ts|tsx|js|json|sh|py)$/.test(ชื่อ)) ไฟล์.push(p);
  }
};
for (const d of ["scripts", "netlify", "src"]) เดิน(join(ราก, d));

/* คำที่ **เครื่องมือปลูกของผมใช้จริงวันนี้** — ประกอบเป็นชิ้นเพื่อไม่ให้ไฟล์นี้เข้าข่ายตัวเอง */
/* 📌 **อ้างจากแหล่งเดียว ไม่พิมพ์เอง** (แก้ 20 ก.ย. 2569 · กฎร่วมกับฝั่งจอ)
   🔴 เดิมรายการนี้พิมพ์เองที่นี่ ⇒ และหมุด `ZZNOPEZZ` ที่ใช้อยู่ 6 จุด **ไม่เคยถูกเพิ่มเข้ามา**
   ⇒ ⇒ **ด่านมองไม่เห็นหมุดที่เราใช้จริง** ⇒ ถ้ามันค้างในไฟล์จริง ไม่มีใครจับได้
   🔑 ⇒ **รายการหมุดต้องเป็นแหล่งเดียว** ⇒ ที่นั่นคือ `scripts/lib/คำหมุดของปลูก.mjs` */
const ร่องรอยของปลูก = คำหมุดของปลูก;
/* 🔴 **ด่านนี้จับผิดตัวในรันครั้งแรก** — และเหตุมีค่ามากกว่าตัวบั๊ก
   ผมใส่ `"ตัวแปรที่ไม่มีอยู่จริง"` (คำที่ผมใช้ปลูกจริงวันนี้) ลงในรายการ
   ⇒ ไปเจอใน **คอมเมนต์** ของ `core-stock.mjs` ที่เขียนอธิบายไว้ตั้งแต่ก่อนหน้านี้
   ⇒ ด่านฟ้องของที่ไม่ใช่ของปลูก = **ร้องใส่ของปกติ** ซึ่งจะถูกปิดภายในวันเดียว
   🔑 กฎที่ได้: **คำที่ใช้เป็น sentinel ต้องเป็นคำที่ "เกิดขึ้นเองตามธรรมชาติไม่ได้"**
      `ZZNEVERMATCHZZ` ผ่านเกณฑ์ · `ตัวแปรที่ไม่มีอยู่จริง` **ไม่ผ่าน** (เป็นภาษาคนปกติ)
   ⇒ ถอดคำนั้นออก + ตัดคอมเมนต์ก่อนกวาดเป็นชั้นที่สอง
   📌 และต่อจากนี้ **เวลาปลูกให้ใช้ sentinel ที่เกิดเองไม่ได้เท่านั้น** ไม่งั้นของปลูกที่ค้าง
      จะตรวจไม่เจอ (ด่านนี้จะมองไม่เห็นมัน) */

test("ตะแกรงต้องเห็นไฟล์จริง (0 ไฟล์ = ตะแกรงพัง ไม่ใช่สะอาด)", () => {
  assert.ok(ไฟล์.length > 100, `สแกนได้ ${ไฟล์.length} ไฟล์ — น้อยเกินจริง`);
});

test("ไม่มีร่องรอยของปลูกค้างในรีโป (git status สะอาดไม่พอ)", () => {
  const เจอ = [];
  for (const f of ไฟล์) {
    const t = ตัดคอมเมนต์(readFileSync(f, "utf8"), f);   // คอมเมนต์อธิบายเรื่องนี้ได้ ห้ามนับเป็นของปลูก
    for (const คำ of ร่องรอยของปลูก) {
      if (t.includes(คำ)) เจอ.push(`${f.replace(ราก, "")}: ${คำ}`);
    }
  }
  assert.deepEqual(เจอ, [], "เจอร่องรอยของปลูก ⇒ เครื่องมือปลูกอาจคืนไฟล์ไม่ครบ (หรือมีคน commit ทับ)");
});
