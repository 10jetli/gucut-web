/* เทส `scripts/lib/ปลูกแล้ววัด.mjs` — **ยกมาจากรีโปจอ ⇒ ต้องพิสูจน์ในรีโปนี้ก่อนเชื่อ**
 *
 * 🔑 หัวใจ: เครื่องมือต้องแยก **"ปลูกไม่ลง"** ออกจาก **"ด่านเขียวทั้งที่ปลูกลง"** ให้ได้
 * 🔴 ชื่อผลเปลี่ยน 20 ก.ย. 2569 (ฝั่งจอเปลี่ยนในเครื่องมือร่วม · ท่อยกมาให้เหมือนทุกไบต์):
 *    เดิม `ด่านจับไม่ได้` ⇒ **สรุปแทนคนอ่านว่าตะแกรงพัง** และฝั่งจอเจอว่าผิด 5 ครั้งจาก 5
 *    (ของจริงคือปลูกนอกขอบเขต ด่านถูก) · และเพิ่มผลที่หก `ตัดสินไม่ได้…` สำหรับกรณีเขียว
 *    ที่ไม่มีหลักฐานว่าปลูกอยู่ในขอบเขต
 *    สองอย่างนี้เดิมให้ผลหน้าตาเหมือนกัน (เขียว) ⇒ คนแปลว่าด่านพัง ⇒ **ไปรื้อด่านที่ทำงานดี**
 *    ทีมเหยียบคลาสนี้รวมกัน 7–8 ครั้งใน 19 ก.ย. 2569 วันเดียว (จอ 4 · ท่อ 3–4)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { ปลูกแล้ววัด } from "../lib/ปลูกแล้ววัด.mjs";

/* 🔑 **ลายนิ้วมือของไฟล์เป้าหมาย ณ ตอนเริ่มเทส** — จดไว้ก่อนกรณีแรกทำงาน
   🔴 ทำไมไม่ใช้ `git status` อย่างเดียว (บทเรียนของผมเอง 20 ก.ย. 2569):
      `git status` เทียบกับ **committed** ⇒ ถ้าไฟล์มีของค้างอยู่ก่อนเทส มันจะแดงทั้งที่เครื่องมือไม่ผิด
      และมันวัด **สภาพสุดท้าย** ⇒ ถ้ากรณีที่ 2 ไม่คืนไฟล์ แต่กรณีที่ 3 เขียนทับด้วยเนื้อเดิม
      ⇒ **ผ่านทั้งที่มีกรณีที่ไม่คืน** ⇒ ⇒ เป็นการวัดปลายทาง ไม่ใช่วัดทุกขั้น
   ⇒ จึงเทียบ **ลายนิ้วมือ ก่อน-หลังทุกกรณี** ซึ่งเป็นท่าที่พิสูจน์แล้วว่าแยกได้จริง */
const นิ้วมือ = (f) => createHash("md5").update(readFileSync(f)).digest("hex");
const ไฟล์จริง = "scripts/gen-warn-keys.mjs"; // ไฟล์ในรีโปนี้ · สะอาดใน git ตอนรันเทส

test("ปลูกไม่ลง: ข้อความที่จะแทนไม่มีในไฟล์จริง", () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: ไฟล์จริง,
    แก้: (s) => s.replace("ข้อความที่ไม่มีอยู่จริง" + "ZZ" + "NOPEZZ", "x"),
    ด่าน: ["node", "scripts/check-syntax.mjs"],
  });
  assert.equal(r.ผล, "ปลูกไม่ลง");
  assert.match(r.รายละเอียด, /คืนเนื้อเดิม/);
});

test("ปลูกไม่ลง: ปลูกลงแต่คำสั่งยืนยันไม่ล้ม ⇒ ของที่ปลูกไม่ได้เปลี่ยนอะไรจริง", () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: ไฟล์จริง,
    // เติมบรรทัดว่าง = ไฟล์ต่างจากเดิมจริง แต่ `node --check` ยังผ่าน ⇒ ไม่ได้ปลูกบั๊ก
    แก้: (s) => s + "\n",
    ยืนยันปลูกลง: ["node", "--check", ไฟล์จริง],
    ด่าน: ["node", "scripts/check-syntax.mjs"],
  });
  assert.equal(r.ผล, "ปลูกไม่ลง");
  assert.match(r.รายละเอียด, /ไม่ล้ม/);
});

test("ด่านจับได้: ปลูกบั๊กจริง + ยืนยันลง + ด่านแดงและเอ่ยถึงไฟล์", () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: ไฟล์จริง,
    แก้: (s) => s + "\nconst " + "ZZ" + "NOPEZZ" + " = ;\n", // ไวยากรณ์พังแน่
    ยืนยันปลูกลง: ["node", "--check", ไฟล์จริง],
    ด่าน: ["node", "scripts/check-syntax.mjs"],
    ต้องเอ่ยถึง: ไฟล์จริง,
  });
  assert.equal(r.ผล, "ด่านจับได้");
});

test("ด่านแดงแต่ไม่เอ่ยถึงของที่ปลูก ⇒ ห้ามอ่านว่าพิสูจน์แล้ว", () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: ไฟล์จริง,
    แก้: (s) => s + "\nconst " + "ZZ" + "NOPEZZ" + " = ;\n",
    ยืนยันปลูกลง: ["node", "--check", ไฟล์จริง],
    ด่าน: ["node", "scripts/check-syntax.mjs"],
    ต้องเอ่ยถึง: "ข้อความที่ด่านจะไม่พูดถึงแน่ ๆ " + "ZZ" + "NOPEZZ",
  });
  assert.equal(r.ผล, "ด่านแดงแต่ไม่เอ่ยถึงของที่ปลูก");
});

test("ด่านเขียวทั้งที่ปลูกลง: ปลูกลงจริงแต่ด่านนั้นไม่ได้ตรวจเรื่องนี้", () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: ไฟล์จริง,
    แก้: (s) => s + "\nconst " + "ZZ" + "NOPEZZ" + " = ;\n",
    ยืนยันปลูกลง: ["node", "--check", ไฟล์จริง],
    // ด่านตารางคู่ไม่เกี่ยวกับไวยากรณ์ของไฟล์นี้เลย ⇒ ต้องเขียว
    // ⇒ ตอบว่า "ด่านเขียวทั้งที่ปลูกลง" (ซึ่งกรณีนี้ **ของจริงคือปลูกนอกขอบเขต ด่านถูก**)
    ด่าน: ["node", "scripts/check-twin-tables.mjs"],
  });
  assert.equal(r.ผล, "ด่านเขียวทั้งที่ปลูกลง");
  // 🔑 ถ้อยคำต้อง **เรียงข้อ ① ปลูกนอกขอบเขต ก่อน** ② ตะแกรงพัง — ห้ามสรุปข้อ ② ให้คนอ่าน
  assert.match(r.รายละเอียด, /ไม่อยู่ในรูป\/ขอบเขตที่ด่านมองหา/);
  assert.match(r.รายละเอียด, /ห้ามสรุปข้อ ② ก่อนไล่ข้อ ①/);
});

test("🔑 ทุกกรณีต้องคืนไฟล์ให้สะอาดใน git", () => {
  const out = execFileSync("git", ["status", "--porcelain", "--", ไฟล์จริง], { encoding: "utf8" });
  assert.equal(out.trim(), "", "ไฟล์เป้าหมายต้องไม่มีของค้างหลังรันเทสทุกข้อ");
});

test("🔑 คืนไฟล์ **เนื้อเดียวกันเป๊ะ** ทุกกรณี — เทียบกับเนื้อใน git ไม่ใช่กับไฟล์บนดิสก์", async () => {
  /* 🔴 **รอบแรกผมเขียนข้อนี้ผิด และมันไม่ตกตอนปลูกของเสีย** (20 ก.ย. 2569)
     เดิมจดลายนิ้วมือจาก **ไฟล์บนดิสก์ตอนเริ่มข้อนี้** ⇒ แต่ข้อนี้รันเป็นข้อสุดท้าย
     ⇒ ถ้าข้อก่อน ๆ ทำไฟล์เพี้ยนไว้ **ค่าอ้างอิงก็เพี้ยนตามไปด้วย** ⇒ เทียบกับตัวเองที่เพี้ยน ⇒ **ผ่าน**
     ⇒ ⇒ พิสูจน์ด้วยการปลูก: ทำให้เครื่องมือ "ไม่คืนไฟล์" ⇒ เทสอื่นตก 4 ข้อ **แต่ข้อนี้ไม่ตก**
     🔑 บทเรียนซ้อนบทเรียน: ผมใช้ md5 เพื่อแก้จุดบอดของ `git status`
        แล้วเจอว่า **md5 ที่อ่านจากของที่อาจถูกแตะ ก็มีจุดบอดของตัวเอง**
        ⇒ **ค่าอ้างอิงต้องมาจากแหล่งที่การทดสอบแตะไม่ได้** ⇒ ใช้เนื้อที่ commit ไว้ (`git show`) */
  const เนื้อในgit = execFileSync("git", ["show", `HEAD:${ไฟล์จริง}`], { encoding: "buffer" });
  const ก่อน = createHash("md5").update(เนื้อในgit).digest("hex");
  assert.equal(นิ้วมือ(ไฟล์จริง), ก่อน, "ไฟล์เป้าหมายต้องสะอาดก่อนเริ่มข้อนี้ (ถ้าไม่สะอาด ข้อนี้วัดอะไรไม่ได้)");
  /* เดินทุกผลลัพธ์ที่เครื่องมือคืนได้ ทีละกรณี แล้วเทียบลายนิ้วมือทันทีหลังแต่ละรอบ
     ⇒ จับกรณีที่ "ไม่คืน" ได้แม้กรณีถัดไปจะเขียนทับด้วยเนื้อเดิม */
  const กรณี = [
    { ชื่อ: "ปลูกไม่ลง", แก้: (x) => x, ด่าน: ["node", "-e", "process.exit(0)"] },
    { ชื่อ: "ด่านจับได้", แก้: (x) => x + "\nconst __ปลูก = 1;\n", ด่าน: ["node", "-e", "console.log('__ปลูก'); process.exit(1)"], ต้องเอ่ยถึง: "__ปลูก" },
    { ชื่อ: "ด่านเขียวทั้งที่ปลูกลง", แก้: (x) => x + "\nconst __ปลูก2 = 2;\n", ด่าน: ["node", "-e", "process.exit(0)"] },
  ];
  for (const g of กรณี) {
    await ปลูกแล้ววัด({ ไฟล์: ไฟล์จริง, แก้: g.แก้, ด่าน: g.ด่าน, ต้องเอ่ยถึง: g.ต้องเอ่ยถึง });
    assert.equal(นิ้วมือ(ไฟล์จริง), ก่อน, `กรณี "${g.ชื่อ}" ไม่ได้คืนไฟล์เนื้อเดิม ⇒ เครื่องมือนี้ทำลายรีโป`);
  }
});
