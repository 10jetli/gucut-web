import { test } from "node:test";
import assert from "node:assert/strict";
import { ตรวจเนื้อ, RULES } from "../check-leaks.mjs";

test("มีกฎอยู่จริง และทุกกฎมีเหตุผลกำกับ", () => {
  assert.ok(RULES.length >= 2, `กฎต้องมีอย่างน้อย 2 ข้อ (มี ${RULES.length})`);
  for (const r of RULES) {
    assert.ok(r.id, "ทุกกฎต้องมี id");
    assert.ok(r.why && r.why.length >= 10, `กฎ ${r.id} ต้องเขียนว่าทำไมห้าม (≥10 ตัวอักษร)`);
    assert.ok(r.needle || r.regex, `กฎ ${r.id} ต้องมี needle หรือ regex`);
  }
});

test("🔴 ที่อยู่ร้านหลุด ⇒ ต้องจับได้", () => {
  const กฎที่อยู่ = RULES.find((r) => r.id === "ที่อยู่ร้าน");
  assert.ok(กฎที่อยู่, "ต้องมีกฎที่อยู่ร้าน");
  const พบ = ตรวจเนื้อ(`<div>ร้าน GUCUT ${กฎที่อยู่.needle} ต.ค่ายบกหวาน</div>`);
  assert.equal(พบ.length, 1, "ที่อยู่ร้านโล่ง ๆ ต้องถูกจับ");
  assert.equal(พบ[0].rule.id, "ที่อยู่ร้าน");
});

test("✅ ที่อยู่ส่งเอกสาร ลซ.๒ ⇒ ต้องไม่จับ (ยกเว้นที่ตั้งใจ)", () => {
  const กฎที่อยู่ = RULES.find((r) => r.id === "ที่อยู่ร้าน");
  /* ต้องมีคำในรายการ allowNear อยู่ใกล้ ๆ ⇒ ถือว่าเป็นที่อยู่ส่งเอกสาร */
  const พบ = ตรวจเนื้อ(`ส่งเอกสาร ลซ.๒ มาที่ ${กฎที่อยู่.needle}`);
  assert.equal(พบ.length, 0, "ที่อยู่ส่งเอกสารต้องไม่ถูกจับ — ไม่งั้นด่านร้องใส่ของที่ตั้งใจให้มี");
});

test("✅ เนื้อที่ไม่มีอะไรต้องห้าม ⇒ ว่าง", () => {
  assert.deepEqual(ตรวจเนื้อ("<html><body>เลื่อยยนต์ NEWWAVE ราคาดี</body></html>"), []);
});

test("ค่าที่ไม่ใช่ข้อความ ⇒ ไม่พัง และไม่จับอะไร", () => {
  for (const v of [null, undefined, 0, {}, []]) assert.deepEqual(ตรวจเนื้อ(v), []);
});

test("🕳️ ตัวควบคุม: ถ้า `allowNear` ถูกถอด ที่อยู่ส่งเอกสารจะถูกจับ ⇒ พิสูจน์ว่าข้อ 3 วัดจริง", () => {
  const กฎที่อยู่ = RULES.find((r) => r.id === "ที่อยู่ร้าน");
  const กฎไม่มียกเว้น = [{ ...กฎที่อยู่, allowNear: undefined }];
  const พบ = ตรวจเนื้อ(`ส่งเอกสาร ลซ.๒ มาที่ ${กฎที่อยู่.needle}`, กฎไม่มียกเว้น);
  assert.equal(พบ.length, 1, "ถอนยกเว้นแล้วต้องจับ — ไม่งั้นข้อ 3 ผ่านเพราะเหตุอื่น");
});
