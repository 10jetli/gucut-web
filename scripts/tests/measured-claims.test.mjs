import { test } from "node:test";
import assert from "node:assert/strict";
import { execSync } from "node:child_process";
import { เล่นประวัติซ้ำไหม } from "../lib/เล่นประวัติซ้ำไหม.mjs";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ราก = fileURLToPath(new URL("../..", import.meta.url));

/** ทะเบียนวิธีวัดซ้ำ — คีย์ต้องตรงกับข้อความในวงเล็บของหมุด
 *  แต่ละตัวคืน `{ ค่า }` หรือ `{ วัดไม่ได้: "เหตุ" }` */
/* 🔴 **เพิ่ม 20 ก.ย. 2569 — หมุดที่วัดของนอกรีโปทำให้ประวัติ build ซ้ำไม่ได้ตลอดกาล**
   ของจริง: ตรวจย้อนหลังคำกล่าวอ้าง "build ผ่าน" ในคอมมิตเก่า 3 ใบ ⇒ **ตกทั้งสามใบ**
   ด้วยเหตุเดียวกัน: หมุด `ไฟล์ใน ~/bin` เขียนว่า 4 แต่วันนี้ `~/bin` มี 5 ไฟล์
   (เทสอื่นผ่าน 637–642 ⇒ ตกข้อเดียวข้อนี้)
   🔑 **ตกแบบนี้ไม่ได้แปลว่า build เคยแดง** — มันแปลว่าเรากำลังเทียบคอมมิตเก่ากับโลกวันนี้
      ⇒ อ่านผลผิดเมื่อไหร่ จะสรุปว่า "คอมมิตเก่าพัง" แล้วไปไล่แก้ของที่ไม่เคยเสีย
   🔑 ผลที่ตามมาที่แพงกว่า: **bisect · rebuild รุ่นเก่า · ตรวจย้อนหลัง ใช้ไม่ได้ทั้งหมด**
      ทันทีที่โลกข้างนอกขยับ — โดยไม่มีอะไรฟ้อง
   ⇒ วิธีวัดจึงต้องประกาศว่า `นอกรีโป` และตอน **เล่นประวัติซ้ำ** ให้เป็น "ต้องมาดู" ไม่ใช่ "ตก"
   🚫 แต่ที่ปลายกิ่ง (ปัจจุบัน) ต้อง **ตกเหมือนเดิม** ไม่งั้นหมุดจะไม่มีใครมาอัปเดต */

const วิธีวัด = {
  "ไฟล์ใน ~/bin ที่ยิง gucut.com/api/": Object.assign(() => {
    const d = join(homedir(), "bin");
    if (!existsSync(d)) return { วัดไม่ได้: `ไม่มีโฟลเดอร์ ${d} ⇒ วัดซ้ำไม่ได้ในเครื่องนี้` };
    const out = execSync(`grep -rl "gucut.com/api/" ${JSON.stringify(d)} 2>/dev/null | wc -l`, { encoding: "utf8" });
    return { ค่า: Number(out.trim()) };
  }, { นอกรีโป: true }),
};

const ไฟล์ = [];
const เดิน = (d) => {
  for (const ชื่อ of readdirSync(d)) {
    if (ชื่อ === "node_modules" || ชื่อ === ".next" || ชื่อ === "out") continue;
    const p = join(d, ชื่อ);
    if (statSync(p).isDirectory()) เดิน(p);
    else if (/\.(mjs|ts|tsx|js)$/.test(ชื่อ)) ไฟล์.push(p);
  }
};
for (const d of ["scripts", "netlify", "src"]) เดิน(join(ราก, d));

const หมุด = [];
for (const f of ไฟล์) {
  for (const m of readFileSync(f, "utf8").matchAll(/📏วัดได้\(([^)]+)\)=(\d+)/g)) {
    หมุด.push({ ไฟล์: f.replace(ราก, ""), อะไร: m[1].trim(), เลข: Number(m[2]) });
  }
}

test("ตะแกรงต้องเห็นไฟล์จริง (0 ไฟล์ = ตะแกรงพัง ไม่ใช่ผ่าน)", () => {
  assert.ok(ไฟล์.length > 100, `สแกนได้ ${ไฟล์.length} ไฟล์ — น้อยเกินจริง`);
});

test("ทุกหมุด 📏วัดได้ ต้องมีวิธีวัดในทะเบียน", () => {
  const ไม่มีวิธีวัด = หมุด.filter((h) => !วิธีวัด[h.อะไร]).map((h) => `${h.ไฟล์}: ${h.อะไร}`);
  assert.deepEqual(ไม่มีวิธีวัด, [], "หมุดที่ไม่มีใครวัดซ้ำ = คำรับรองเปล่า ⇒ ลงทะเบียนวิธีวัดด้วย");
});

test("ต้องรายงานว่า **วิธีวัดถูกใช้กี่รายการ** — ทะเบียนที่ไม่มีหมุดใช้ ห้ามนับเป็นความครอบคลุม", (t) => {
  /* 🔴 ฝั่งจอเจอในเครื่องมือที่เขาเขียน **เพื่อกันโรคนี้พอดี**: บรรทัดสรุปพิมพ์ว่า
     "ทะเบียนวิธีวัด 3 รายการ" ⇒ อ่านเหมือนตรวจ 3 อย่าง ทั้งที่มีหมุดใช้จริง 2
     🔑 โรค "ตัวเลขที่ไม่มีขอบเขตกำกับ" — เขาทำผิดข้อนี้สามรอบในวันเดียว รอบที่สามอยู่ในไฟล์ที่กันมันเอง
     📌 วิธีวัดที่ยังไม่มีหมุดใช้ **ไม่ใช่ความผิด** (เตรียมล่วงหน้าได้) แต่ **ห้ามนับเป็นความครอบคลุม** */
  const ใช้จริง = new Set(หมุด.map((h) => h.อะไร));
  const ไม่ถูกใช้ = Object.keys(วิธีวัด).filter((k) => !ใช้จริง.has(k));
  t.diagnostic(`📏 วิธีวัดที่ถูกใช้ ${ใช้จริง.size} จาก ${Object.keys(วิธีวัด).length} รายการในทะเบียน` +
    (ไม่ถูกใช้.length ? ` · ยังไม่มีหมุดใช้: ${ไม่ถูกใช้.join(" · ")}` : ""));
  assert.ok(ใช้จริง.size > 0, "ไม่มีวิธีวัดไหนถูกใช้เลย = ทะเบียนเป็นของประดับ");
});

test("เลขในหมุดต้องตรงกับที่วัดได้จริง (วัดไม่ได้ ⇒ บอกเหตุ ไม่ใช่ผ่านเงียบ)", (t) => {
  assert.ok(หมุด.length > 0, "ไม่มีหมุดเลย = กติกานี้ยังไม่ถูกใช้ ⇒ ถือว่าตะแกรงพัง");
  const ข้าม = [];
  const ต้องมาดู = [];
  const สภาพ = เล่นประวัติซ้ำไหม();
  /* ตอบไม่ได้ ⇒ เข้มไว้ (ถือว่าอยู่ปัจจุบัน) **แต่ต้องพูดออกมา** ไม่ใช่เงียบ */
  if (สภาพ.ตอบไม่ได้) t.diagnostic(`⚠️ แยกไม่ออกว่าอยู่ปลายกิ่งหรือเล่นประวัติซ้ำ (${สภาพ.ตอบไม่ได้}) ⇒ ตัดสินแบบเข้ม`);
  const เล่นซ้ำ = สภาพ.ใช่ === true;
  for (const h of หมุด) {
    const r = วิธีวัด[h.อะไร]();
    if (r.วัดไม่ได้) { ข้าม.push(`${h.อะไร}: ${r.วัดไม่ได้}`); continue; }
    /* หมุดที่วัดของนอกรีโป + กำลังเล่นประวัติซ้ำ ⇒ **ผลแปลไม่ได้** ห้ามทำให้ตก
       (สัญญาเดิมของทีม: `inconclusive` ต้องไม่ปนกับ "ไม่ผ่าน") */
    if (เล่นซ้ำ && วิธีวัด[h.อะไร].นอกรีโป && r.ค่า !== h.เลข) {
      ต้องมาดู.push(`${h.อะไร}: หมุดเขียน ${h.เลข} · วันนี้วัดได้ ${r.ค่า}`);
      continue;
    }
    assert.equal(r.ค่า, h.เลข, `${h.ไฟล์} เขียนว่า ${h.เลข} แต่วัดได้ ${r.ค่า} (${h.อะไร})`);
  }
  if (ข้าม.length) t.diagnostic(`⚠️ วัดไม่ได้ ${ข้าม.length} หมุด: ${ข้าม.join(" · ")}`);
  if (ต้องมาดู.length) {
    t.diagnostic(
      `⚠️ กำลังเล่นประวัติซ้ำ (HEAD ไม่ใช่ปลายกิ่งใด) ⇒ ไม่ตัดสินหมุดที่วัดของนอกรีโป ${ต้องมาดู.length} ตัว: ` +
      ต้องมาดู.join(" · ") +
      " ⇒ **ผลแปลไม่ได้ ไม่ใช่ผ่านและไม่ใช่ตก** (โลกข้างนอกขยับหลังคอมมิตนั้น)"
    );
  }
});
