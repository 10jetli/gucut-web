// `?productlabels=` — รหัสตอบ HTTP ต้องตัดสินจากช่องที่ฟังก์ชัน **คืนจริง**
//
// 🔴 ของจริง 16 ต.ค. 2569 (ฝั่งจอแจ้ง 21:3x): เส้นนี้ตอบ **502 มาตลอด แม้ตอนสำเร็จครบ**
//    เหตุ: ตรรกะรหัสตอบถูก **คัดลอกมาจากเส้น PEAK** ทั้งก้อนพร้อมคอมเมนต์:
//      r.สรุป === "สำเร็จครบทุกใบ" ? 200 : r.สรุป === "อ่านคำตอบของ PEAK ไม่ได้" ? 502 : 502
//    แต่ zortProductLabels ไม่เคยคืนช่อง `สรุป` ⇒ undefined ⇒ ตกท้ายเป็น 502 ทุกครั้ง
//    ⇒ จอบาร์โค้ด **ไม่เคยรู้เลยว่าสินค้าตัวไหนมีบาร์โค้ด** ตั้งแต่วันที่คัดลอกมา
//
// 🔑 คลาส: **ตัดสินผลจากช่องที่ฟังก์ชันอื่นคืน** — ช่องที่ไม่มีอยู่จริงอ่านเป็น undefined
//    แล้วตกไปทางที่เขียนท้ายสุด **โดยไม่มีอะไรฟ้อง** · เทส/build มองไม่เห็นเพราะไม่ได้ยิงเส้นจริง
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";

const src = fs.readFileSync("netlify/functions/core.mjs", "utf8");
const i = src.indexOf('if (url.searchParams.has("productlabels"))');
const จบ = src.indexOf("if (url.searchParams", i + 50);
const ก้อนเต็ม = src.slice(i, จบ > i ? จบ : i + 3000);
/* 🔑 **ถอดคอมเมนต์ออกก่อนตรวจ** — ด่านนี้เฝ้า "โค้ดที่ทำงาน" ไม่ใช่เอกสาร
   ⚠️ รอบแรกผมตรวจทั้งก้อน ⇒ แดงเพราะ **คอมเมนต์ที่ผมเขียนอธิบายบั๊กเก่าอ้างชื่อ r.สรุป อยู่**
      = แดงลวง · และถ้าใครแก้ด้วยการลบคอมเมนต์ จะเสียคำอธิบายที่กันคนเขียนผิดซ้ำไปด้วย
   ⇒ ด่านที่ห้ามพูดถึงของเก่า จะบีบให้คนลบประวัติทิ้ง ซึ่งแย่กว่าปล่อยให้พูดถึง */
const ก้อน = ก้อนเต็ม.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");

test("ห้ามตัดสินรหัสตอบจากช่อง `สรุป` ซึ่งเส้นนี้ไม่เคยได้รับ", () => {
  assert.ok(i > 0, "ไม่เจอเส้น productlabels");
  assert.ok(!/r\.สรุป/.test(ก้อน),
    "กลับไปอ่าน r.สรุป อีกแล้ว — zortProductLabels ไม่คืนช่องนี้ ⇒ undefined ⇒ 502 ตลอดกาล");
  assert.ok(!/PEAK/.test(ก้อน.replace(/\/\*[\s\S]*?\*\//g, "")),
    "ตรรกะของเส้น PEAK ไม่ควรอยู่ในโค้ดที่ทำงานของเส้นนี้");
});

test("ตัดสินจากช่องที่ zortProductLabels คืนจริง (failed · rows)", () => {
  assert.match(ก้อน, /r\.failed/);
  assert.match(ก้อน, /r\.rows/);
  /* สามทางที่ต้องแยก: ไม่ล้ม ⇒ 200 · ล้มหมด ⇒ 502 · ล้มบางส่วน ⇒ 200 + ประกาศ */
  assert.match(ก้อน, /ล้ม === 0 \? 200 : ได้แถว === 0 \? 502 : 200/);
});

test("ล้มบางส่วนต้องประกาศ ไม่กลืน และไม่ทิ้งแถวที่ใช้ได้", () => {
  assert.match(ก้อน, /partial: true/);
  assert.match(ก้อน, /failedParts/);
  // ⚠️ ห้ามตอบ 502 ตอนได้แถวมาบ้าง — จอจะทิ้งแถวที่ใช้ได้ทั้งหมด
  assert.ok(!/ได้แถว > 0 \? 502/.test(ก้อน));
});

test("`missing` ไม่ใช่ความล้มเหลว — ต้องไม่ถูกนับเป็นเหตุให้ตอบ 502", () => {
  /* ZORT ไม่มีรหัสนี้ = **คำตอบ** · ถาม ZORT ไม่สำเร็จ = **ไม่รู้** ⇒ คนละเรื่อง
     ถ้าเอา missing ไปตัดสินรหัสตอบ จอจะอ่านว่า "ท่อพัง" ทั้งที่ท่อตอบถูก */
  const ตัวตัดสิน = ก้อน.match(/const (?:ล้ม|ได้แถว) = [^\n]+/g) ?? [];
  assert.ok(ตัวตัดสิน.length >= 2, "ต้องมีตัวตัดสินสองตัว (ล้ม · ได้แถว)");
  for (const บรรทัด of ตัวตัดสิน) assert.ok(!/missing/.test(บรรทัด), `missing หลุดเข้าตัวตัดสิน: ${บรรทัด}`);
});
