/* 🔴 ด่าน: **หน้าสถานะระบบ — "ประเมินไม่ได้" ห้ามขึ้นเขียว** (สเปกฝั่งจอ ข้อ 10 · ใบ t_mu8i1pu1)
 *
 * คลาส: ธงสุขภาพที่เป็นค่าคงที่ · ตัวตรวจที่ไม่เคยแตะของที่มันอ้างว่าตรวจ
 * ⚠️ `check()` เดิมมี 4 ทาง: off (สีเทา) · warn (ควรมาดู) · slow/ok · down (โยน error)
 *    แต่ **ทางที่ห้า** ที่ไม่มีใครตั้งใจคือ "ตัวตรวจคืน undefined" ⇒ ตกลงมาที่ `ok` + note ว่าง
 *    ⇒ ใครเขียนตัวตรวจใหม่แล้วลืม `return` จะได้เขียวตลอดกาล **โดยไม่เคยยิงอะไรเลย**
 *
 * 🔑 ทำไมเป็น `warn` ไม่ใช่ `down`: ระบบอาจปกติดี **เราแค่ไม่รู้** ⇒ แดงลวงทำให้คนเลิกเชื่อหน้านี้
 *    (บทเรียนของโครงการเอง 31 ส.ค. 2569: ตัวตรวจฟีดที่ฟ้องผิดทำคนเลิกเชื่อทั้งหน้า)
 *    และ `warn` **ทั้งท่อและจอรองรับอยู่แล้ว** ⇒ ไม่ต้องนัด deploy สองฝั่ง
 *
 * ⚠️ ด่านนี้ตรวจซอร์ส (status.mjs ต้องมีรหัสหลังร้านถึงยิงได้) · มีตัวควบคุมลบที่ปลูกจริง
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const src = await readFile(new URL("../../netlify/functions/status.mjs", import.meta.url), "utf8");

/** ดึงเนื้อฟังก์ชัน check() ออกมาทั้งก้อน (นับวงเล็บปีกกา) */
function ก้อนcheck(s) {
  const i = s.indexOf("async function check(");
  assert.ok(i > 0, "ไม่เจอฟังก์ชัน check() — ไฟล์เปลี่ยนโครง ให้แก้ด่าน ไม่ใช่ลบด่าน");
  let d = 0, j = s.indexOf("{", i);
  for (let k = j; k < s.length; k++) {
    if (s[k] === "{") d++;
    else if (s[k] === "}" && --d === 0) return s.slice(i, k + 1);
  }
  throw new Error("วงเล็บไม่ปิด");
}

test("✅ อ่านไฟล์และหาก้อน check() ได้", () => {
  const ก = ก้อนcheck(src);
  assert.ok(ก.length > 300, `ก้อน check() สั้นผิดปกติ (${ก.length}) — น่าจะจับผิดที่`);
});

test("undefined/null ต้องถูกดักก่อนถึงทางออก ok", () => {
  const ก = ก้อนcheck(src);
  const iดัก = ก.search(/r === undefined \|\| r === null/);
  const iเขียว = ก.search(/state: ms > SLOW_MS \? "slow" : "ok"/);
  assert.ok(iดัก > 0, "ไม่มีตัวดัก 'ตัวตรวจไม่คืนค่า' ⇒ ลืม return = เขียวตลอดกาล");
  assert.ok(iเขียว > 0, "ไม่เจอทางออกเขียว — ไฟล์เปลี่ยนโครง");
  assert.ok(iดัก < iเขียว,
    `ตัวดักต้องอยู่ **ก่อน** ทางออกเขียว · ตอนนี้ดักที่ ${iดัก} เขียวที่ ${iเขียว} ⇒ ดักทีหลังคือไม่ได้ดัก`);
});

test("สถานะที่ใช้ต้องเป็น warn (ท่อ+จอรองรับแล้ว) ไม่ใช่สถานะใหม่ที่จอไม่รู้จัก", () => {
  const ก = ก้อนcheck(src);
  const i = ก.indexOf("r === undefined");
  const ก้อนดัก = ก.slice(i, i + 500);
  assert.match(ก้อนดัก, /state: "warn"/,
    "ต้องใช้ warn — สถานะใหม่ที่จอไม่รู้จักจะถูกกลืนเป็นเขียว ซึ่งคือบั๊กที่กำลังแก้");
  assert.match(ก้อนดัก, /ไม่ใช่ว่าระบบพัง/,
    "note ต้องบอกให้ชัดว่า 'ไม่รู้' ≠ 'พัง' ไม่งั้นคนจะไปแก้ระบบที่ยังดี");
});

test("สี่ทางเดิมต้องยังอยู่ครบ (ตัวควบคุม: แก้เรื่องหนึ่งแล้วห้ามทำอีกสี่เรื่องหาย)", () => {
  const ก = ก้อนcheck(src);
  for (const [ชื่อ, รูป] of [
    ["off", /state: "off"/], ["warn", /state: "warn"/],
    ["ok/slow", /"slow" : "ok"/], ["down", /state: "down"/],
  ])
    assert.match(ก, รูป, `ทาง ${ชื่อ} หายไปจาก check()`);
});

/* 🧪 ตัวควบคุมลบ — ถอนตัวดักออกแล้วด่านต้องแดง (พิสูจน์ว่าด่านนี้ไม่ใช่ข้อความประดับ) */
test("🧪 ตัวควบคุมลบ: ถอนตัวดักออก ⇒ ด่านต้องจับได้", () => {
  const ปลูก = src.replace(/if \(r === undefined \|\| r === null\)[\s\S]*?\n      \};\n/, "");
  assert.notEqual(ปลูก, src, "ปลูกไม่ติด — สูตรปลูกล้าสมัย ให้แก้สูตร ไม่ใช่ลบเทส");
  const ก = ก้อนcheck(ปลูก);
  assert.ok(!/r === undefined/.test(ก), "ปลูกแล้วตัวดักต้องหายจริง");
  assert.match(ก, /"slow" : "ok"/, "และทางออกเขียวต้องยังอยู่ ⇒ พิสูจน์ว่าไฟล์ไม่ได้พังทั้งก้อน");
});

/* 🔴 ข้อที่ยังไม่ได้แก้ และจดไว้ให้คนรอบหน้าเห็น (ไม่ใช่ด่าน — เป็นคำเตือนที่คิดจากของจริง)
   ตัวตรวจ 3 ตัวของการเข้าสู่ระบบ (LINE/Facebook/Google) คืน `{}` เมื่อ env ครบ = เขียว
   ซึ่งพิสูจน์แค่ว่า **ตั้งค่าไว้** ไม่ได้พิสูจน์ว่า **ล็อกอินได้** (คลาส does-it-exist ≠ usable)
   ⇒ ยังไม่แก้เพราะต้องยิงไปหาผู้ให้บริการจริง ต้องให้ท่านประธานสั่งก่อน */
test("บันทึกช่องว่างที่รู้ตัว: ตัวตรวจ OAuth ยังดูแค่ env", () => {
  const ต้องมี = ["LINE_CHANNEL_ID", "FACEBOOK_APP_ID", "GOOGLE_CLIENT_ID"];
  for (const ก of ต้องมี) assert.ok(src.includes(ก), `ตัวตรวจ ${ก} หายไป`);
  /* ถ้าวันหน้ามีคนเปลี่ยนไปยิงจริง ให้เทสนี้ตกแล้วมาลบบรรทัดนี้ทิ้ง — ตาข่ายกันคำเตือนค้าง */
  const i = src.indexOf('check("เข้าสู่ระบบด้วย LINE"');
  assert.match(src.slice(i, i + 200), /\{\}\s*:\s*\{ off: true \}/,
    "ตัวตรวจ LINE เปลี่ยนไปแล้ว ⇒ คำเตือนในไฟล์นี้ล้าสมัย ให้ไปแก้คอมเมนต์ด้วย");
});
