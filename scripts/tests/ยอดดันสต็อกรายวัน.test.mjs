/* 📅 ด่าน: **ยอดรวมการยิงสต็อกรายวันต้องเก็บถาวรและบวกถูก**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — ฝั่งจอวัดว่าสมุด `stockpush/log` ถูกตัดที่ **50 รอบ**
 *    ที่ความถี่วันนั้น (3 เจ้า × ~12 รอบ/ชม.) ⇒ หน้าต่างที่อ่านได้เหลือไม่กี่ชั่วโมง
 *    ⇒ คำถาม *"วันนี้มีอะไรออกไปแตะสต็อกบ้าง"* **ตอบย้อนหลังไม่ได้หลังพ้นกะ**
 *    🔑 และวันนั้น **ของออกไปจริงแล้ว** (shopee 58 รหัส · tiktok 60 รหัส) ⇒ ไม่ใช่ความเสี่ยงสมมติ
 *
 * 🔑 ตัวบวกถูก **แยกออกมาเป็นฟังก์ชันล้วน** (`บวกยอดรายวัน`) เพื่อให้เทสพฤติกรรมได้จริง
 *    ก่อนหน้านี้มันฝังอยู่ในเส้นที่ยิงแพลตฟอร์ม ⇒ เทสได้แค่ "รูปแบบของซอร์ส"
 *    ⇒ ⇒ ด่านรูปแบบบอกได้ว่า *เราเขียนอะไรไว้* · ด่านพฤติกรรมบอกว่า *มันทำอะไรจริง*
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { บวกยอดรายวัน, คีย์ยอดรายวัน } from "../../netlify/lib/stock-push-live.mjs";

const รอบ = (o) => ({ platform: "shopee", at: "2026-09-20T05:50:00.000Z", fired: 0, pushed: 0, rejected: 0, notSent: 0, ...o });

test("คีย์ต้องแยกทั้งวันและเจ้า — ไม่ใช่ก้อนเดียวทั้งวัน", () => {
  assert.equal(คีย์ยอดรายวัน("2569-09-20", "shopee"), "stockpush/daily/2569-09-20/shopee");
  assert.notEqual(คีย์ยอดรายวัน("2569-09-20", "shopee"), คีย์ยอดรายวัน("2569-09-20", "tiktok"));
  assert.notEqual(คีย์ยอดรายวัน("2569-09-20", "shopee"), คีย์ยอดรายวัน("2569-09-21", "shopee"));
});

test("รอบแรกของวัน: ไม่มีค่าเดิม ⇒ เริ่มนับจากศูนย์", () => {
  const r = บวกยอดรายวัน(null, รอบ({ fired: 19, pushed: 19, notSent: 3 }), "2569-09-20");
  assert.equal(r.รอบ, 1);
  assert.equal(r.ยิงออก, 19);
  assert.equal(r.สำเร็จ, 19);
  assert.equal(r.ไม่ได้ส่ง, 3);
  assert.equal(r.รอบแรกเมื่อ, "2026-09-20T05:50:00.000Z");
});

test("🔑 รอบถัดไปต้อง **บวก** ไม่ใช่ทับ — และ `รอบแรกเมื่อ` ต้องไม่ขยับ", () => {
  let r = บวกยอดรายวัน(null, รอบ({ fired: 19, pushed: 19 }), "2569-09-20");
  r = บวกยอดรายวัน(r, รอบ({ at: "2026-09-20T06:05:00.000Z", fired: 19, pushed: 18, rejected: 1 }), "2569-09-20");
  r = บวกยอดรายวัน(r, รอบ({ at: "2026-09-20T06:50:00.000Z", fired: 19, pushed: 19 }), "2569-09-20");
  r = บวกยอดรายวัน(r, รอบ({ at: "2026-09-20T10:20:00.000Z", fired: 1, pushed: 1 }), "2569-09-20");
  /* 📏 ตัวเลขชุดนี้คือของจริงที่ฝั่งจอวัดได้จากสมุดวันที่ 20 ก.ย. (shopee 19+19+19+1 = 58) */
  assert.equal(r.รอบ, 4);
  assert.equal(r.ยิงออก, 58, "ต้องได้ 58 = ยอดจริงของ shopee วันนั้น");
  assert.equal(r.สำเร็จ, 57);
  assert.equal(r.ถูกปฏิเสธ, 1);
  assert.equal(r.รอบแรกเมื่อ, "2026-09-20T05:50:00.000Z", "รอบแรกต้องไม่ถูกเขียนทับ");
  assert.equal(r.รอบล่าสุดเมื่อ, "2026-09-20T10:20:00.000Z");
});

test("🔬 พลังแยกแยะ: ถ้าตัวบวกเปลี่ยนเป็น 'ทับ' เทสข้างบนต้องแดง", () => {
  /* ปลูกในหน่วยความจำ: ตัวบวกแบบที่ทับของเดิม (บั๊กที่เราต้องกัน) */
  const ทับ = (เดิม, out) => ({ รอบ: 1, ยิงออก: Number(out.fired ?? 0) });
  let r = ทับ(null, รอบ({ fired: 19 }));
  r = ทับ(r, รอบ({ fired: 19 }));
  assert.notEqual(r.ยิงออก, 38, "ตัวปลูกต้องให้ผลผิดจริง ⇒ ยืนยันว่าข้อข้างบนแยกแยะได้");
  assert.equal(r.ยิงออก, 19);
});

test("🔑 รอบที่ยิงออก 0 ต้องยังนับเป็นหนึ่งรอบ — `??` ไม่ใช่ `||`", () => {
  /* ⚠️ `0 || x` กลืนศูนย์จริง ⇒ ถ้าใช้ `||` รอบที่ด่านกันไว้หมด (fired 0) จะหายจากตัวนับ
     ⇒ แล้วยอด "รอบ" จะบอกน้อยกว่าความจริง ⇒ คนอ่านคิดว่าตัวกวาดไม่ได้วิ่ง */
  let r = บวกยอดรายวัน(null, รอบ({ fired: 0, notSent: 57 }), "2569-09-20");
  r = บวกยอดรายวัน(r, รอบ({ fired: 0, notSent: 57 }), "2569-09-20");
  assert.equal(r.รอบ, 2, "สองรอบที่ไม่ยิงอะไรเลย ต้องยังนับได้ 2 รอบ");
  assert.equal(r.ยิงออก, 0);
  assert.equal(r.ไม่ได้ส่ง, 114);
});

test("🔑 จดไม่ได้ต้องไม่ทำให้การยิงล้ม — ของออกไปแล้ว ผลต้องคืนครบ", () => {
  const src = readFileSync("netlify/lib/stock-push-live.mjs", "utf8");
  assert.match(src, /dailySkipped/, "ต้องมีช่องบอกว่าจดรายวันไม่สำเร็จ");
  assert.match(src, /return \{ \.\.\.out, dailySkipped/, "ต้องคืน out เดิมครบ ไม่โยน error");
});

test("🔑 เส้นอ่านต้องประกาศเพดานจริง ไม่ใช่ null", () => {
  /* 🔴 ของเดิมส่ง `limitApplied: null` ⇒ ผู้เรียก **แยกไม่ออกว่า "มีแค่ 50 รอบ" หรือ "ถูกตัดเหลือ 50"**
     ⇒ ช่องที่ออกแบบมาเตือนเรื่องการตัด **เงียบเสียเอง** ซึ่งร้ายกว่าไม่มีช่องเลย (ฝั่งจอชี้ 20 ก.ย.) */
  const core = readFileSync("netlify/functions/core.mjs", "utf8");
  const เริ่ม = core.indexOf('url.searchParams.get("stockpushlog")');
  assert.ok(เริ่ม > 0, "หาเส้น stockpushlog ไม่เจอ ⇒ ตะแกรงพัง ไม่ใช่ผ่าน");
  const เส้น = core.slice(เริ่ม, เริ่ม + 3000);
  assert.match(เส้น, /limitApplied: 50/, "ต้องบอกเพดานเป็นตัวเลขจริง");
  assert.match(เส้น, /limitAppliedBy/, "ต้องบอกว่าเพดานมาจากตัวเขียน ไม่ใช่จากคำขอ");
  assert.match(เส้น, /ยอดรวมรายวัน/, "ต้องส่งยอดรวมรายวันมาคู่กัน");
  assert.match(เส้น, /ไม่ใช่ศูนย์/, "ต้องเขียนว่าก่อนวันเริ่มจดคือ 'ไม่มีข้อมูล' ไม่ใช่ 0");
});
