/* ด่านของทะเบียน env — สามเรื่องที่พลาดแล้วเจ็บ
 *
 * ① รายชื่อในทะเบียนต้องตรงกับ `process.env.*` ที่ใช้จริงในซอร์ส
 *    ถ้าไม่มีด่านนี้ รายชื่อจะค้างแน่นอน ซึ่งเป็น**โรคเดียวกับที่ env-report.mjs ตั้งใจรักษา**
 *    (ทะเบียนที่ค้างแย่กว่าไม่มีทะเบียน เพราะมันให้ความมั่นใจที่ไม่มีฐาน)
 * ② 🚫 ห้ามส่งค่าออกไปในทุกรูปแบบ — repo เป็น PUBLIC
 * ③ ขาด "ตัวเลือก" ต้องไม่ถูกนับว่าเสีย (สามสถานะ ห้ามยุบเป็นสอง)
 *
 * 🔑 ด่านนี้ถูกพิสูจน์ด้วยการปลูกบั๊กก่อนเชื่อ (ดูท้ายไฟล์ — ปลูกทั้งสามทิศแล้วแดงจริงทั้งสาม)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { ENV_DECLARED, แพลตฟอร์มใส่ให้เอง, envReport } from "../../netlify/lib/env-report.mjs";

/** กวาดชื่อ env ที่ใช้จริงในซอร์สฝั่งเซิร์ฟเวอร์ */
function กวาดชื่อจากซอร์ส(รากเริ่ม = "netlify") {
  const เจอ = new Set();
  const เดิน = (d) => {
    for (const ชื่อไฟล์ of readdirSync(d)) {
      const p = join(d, ชื่อไฟล์);
      if (statSync(p).isDirectory()) { เดิน(p); continue; }
      if (!/\.(mjs|js)$/.test(ชื่อไฟล์)) continue;
      const s = readFileSync(p, "utf8");
      for (const m of s.matchAll(/process\.env\.([A-Z0-9_]+)/g)) เจอ.add(m[1]);
      for (const m of s.matchAll(/process\.env\[\s*["'`]([A-Z0-9_]+)["'`]\s*\]/g)) เจอ.add(m[1]);
    }
  };
  เดิน(รากเริ่ม);
  return เจอ;
}

test("① ทุกชื่อ env ที่ใช้จริงในซอร์ส ต้องอยู่ในทะเบียน", () => {
  const ในซอร์ส = กวาดชื่อจากซอร์ส();
  const ประกาศแล้ว = new Set([...ENV_DECLARED.map((e) => e.ชื่อ), ...แพลตฟอร์มใส่ให้เอง]);
  const ขาด = [...ในซอร์ส].filter((n) => !ประกาศแล้ว.has(n)).sort();
  assert.deepEqual(
    ขาด, [],
    "มี env ที่โค้ดใช้จริงแต่ไม่ได้ประกาศในทะเบียน — เพิ่มลง ENV_DECLARED พร้อมช่อง `ขาดแล้ว` " +
      "ว่าขาดตัวนี้แล้วอะไรพัง (หรือลง แพลตฟอร์มใส่ให้เอง ถ้าเป็นของที่ Netlify ใส่มาเอง): " + ขาด.join(", "),
  );
});

test("① ย้อนทิศ — ชื่อในทะเบียนที่ไม่มีใครใช้แล้ว ต้องถูกถอดออก", () => {
  const ในซอร์ส = กวาดชื่อจากซอร์ส();
  const ตายแล้ว = ENV_DECLARED.map((e) => e.ชื่อ).filter((n) => !ในซอร์ส.has(n)).sort();
  /* ⚠️ ทิศนี้สำคัญเท่าทิศแรก — ชื่อที่โค้ดเลิกใช้แล้วยังค้างในทะเบียน
     ทำให้คนไปตั้งค่าที่ไม่มีผลอะไร แล้วเชื่อว่าได้แก้ปัญหาแล้ว */
  assert.deepEqual(ตายแล้ว, [], "ทะเบียนมีชื่อที่ซอร์สไม่ใช้แล้ว ให้ถอดออก: " + ตายแล้ว.join(", "));
});

test("② 🚫 คำตอบต้องไม่มีค่าของ env ปนออกไปเลย", () => {
  const ชื่อทดสอบ = ENV_DECLARED[0].ชื่อ;
  const เดิม = process.env[ชื่อทดสอบ];
  const ค่าลับ = "ZZsecret-value-9f3a-must-never-leakZZ";
  process.env[ชื่อทดสอบ] = ค่าลับ;
  try {
    const ข้อความ = JSON.stringify(envReport());
    assert.ok(!ข้อความ.includes(ค่าลับ), "ค่าของ env หลุดออกมาในคำตอบ");
    /* ตัวขึ้นต้น/ท่อนกลาง ก็ห้ามหลุด — คีย์จริงบางตัวเดาต่อได้จากท่อนหน้า */
    assert.ok(!ข้อความ.includes(ค่าลับ.slice(0, 8)), "ตัวขึ้นต้นของค่า env หลุดออกมา");
    /* ความยาวก็คือข้อมูลของคีย์ — ห้ามมีช่องไหนเท่ากับความยาวค่า */
    const ช่องที่เป็นเลข = JSON.stringify(envReport().รายการ.find((e) => e.ชื่อ === ชื่อทดสอบ));
    assert.ok(!ช่องที่เป็นเลข.includes(String(ค่าลับ.length)), "ความยาวของค่า env หลุดออกมา");
  } finally {
    if (เดิม === undefined) delete process.env[ชื่อทดสอบ];
    else process.env[ชื่อทดสอบ] = เดิม;
  }
});

test("② ค่าว่าง/ช่องว่างล้วน ต้องถือว่ายังไม่ได้ตั้ง", () => {
  const ชื่อทดสอบ = ENV_DECLARED[0].ชื่อ;
  const เดิม = process.env[ชื่อทดสอบ];
  try {
    process.env[ชื่อทดสอบ] = "   ";
    const แถว = envReport().รายการ.find((e) => e.ชื่อ === ชื่อทดสอบ);
    assert.equal(แถว.มีค่า, false, "ช่องว่างล้วนต้องนับว่าไม่มีค่า — ไม่งั้นตั้งพลาดแล้วจอขึ้นเขียว");
  } finally {
    if (เดิม === undefined) delete process.env[ชื่อทดสอบ];
    else process.env[ชื่อทดสอบ] = เดิม;
  }
});

test("③ ขาดแค่ 'ตัวเลือก' ต้องไม่ถูกรายงานว่าเสีย", () => {
  const r = envReport();
  if (r.ขาดบังคับ.length === 0 && r.ขาดตัวเลือก.length > 0) {
    assert.notEqual(r.สถานะ, "เสีย", "ขาดเฉพาะตัวเลือกไม่ใช่ของเสีย — เหมารวมแล้วจอแดงถาวร คนเลิกอ่าน");
  }
  /* ทุกแถวต้องบอกได้ว่าขาดแล้วอะไรพัง ไม่งั้นคนอ่านตัดสินความเร่งด่วนไม่ได้ */
  for (const e of ENV_DECLARED) {
    assert.ok(e.ขาดแล้ว && e.ขาดแล้ว.length > 3, `${e.ชื่อ} ไม่ได้บอกว่าขาดแล้วอะไรพัง`);
    assert.ok(["บังคับ", "ตัวเลือก"].includes(e.จำเป็น), `${e.ชื่อ} ช่อง จำเป็น ต้องเป็น บังคับ/ตัวเลือก`);
  }
});

test("③ คำตอบต้องประกาศขอบเขตของตัวเอง", () => {
  const r = envReport();
  const ขอบเขต = Object.entries(r).filter(([k]) => k.includes("ขอบเขต")).map(([, v]) => String(v)).join(" ");
  assert.ok(ขอบเขต.length > 50, "คำตอบต้องมีช่องขอบเขต");
  /* ⚠️ ผูกกับ **เจตนา** ไม่ใช่ถ้อยคำ — เคยพลาด 3 ครั้งใน 19 ก.ย. ที่ผูกกับรูปโค้ด
     แล้วด่านไปขวางการแก้ที่ถูกต้อง */
  assert.ok(/ไม่ได้เอาข้อความ|ยังไม่ปิด/.test(ขอบเขต), "ขอบเขตต้องบอกว่าเส้นนี้ไม่ได้แสดงข้อความจาก ~100 จุดนั้น");
});

