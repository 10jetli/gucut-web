// รัน: node --experimental-test-module-mocks --test scripts/tests/เกณฑ์ข้ามนาน-แหล่งเดียว.test.mjs
//
// 🔴 **ที่มา 5 ต.ค. 2569 — เจอก่อนปล่อยลง ไม่ใช่หลังพัง**
//    `ค้างเกินกี่ชั่วโมง` เคยเป็น const **ข้างในฟังก์ชัน** ของ stock-push-sweep.mjs
//    ผมเขียนตัวตรวจหน้าสถานะที่ import ค่านั้น ⇒ ถ้าไม่ยกขึ้นมา export จะได้ undefined
//    แล้ว **ถอยไปใช้ 24 ที่พิมพ์ไว้ในไฟล์นั้นเงียบ ๆ** ⇒ เกณฑ์สองแหล่งที่หน้าตาเหมือนแหล่งเดียว
//    ⇒ วันที่ใครแก้เกณฑ์ หน้าสถานะจะไม่ตาม **และไม่มีอะไรฟ้อง เพราะ 24 = 24 อยู่แล้ววันนี้**
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';
import { ค้างเกินกี่ชั่วโมงถือว่านาน } from '../../netlify/lib/stock-push-sweep.mjs';

const sweep = readFileSync('netlify/lib/stock-push-sweep.mjs', 'utf8');
const status = readFileSync('netlify/functions/status.mjs', 'utf8');
const ลบคอมเมนต์ = (t) => t.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');

test('① เกณฑ์ต้อง export ได้จริง และเป็นชั่วโมงที่สมเหตุสมผล', () => {
  assert.equal(typeof ค้างเกินกี่ชั่วโมงถือว่านาน, 'number');
  assert.ok(ค้างเกินกี่ชั่วโมงถือว่านาน > 0 && ค้างเกินกี่ชั่วโมงถือว่านาน <= 24 * 14,
    'ต้องอยู่ในช่วงที่มีความหมาย (มากกว่า 0 และไม่เกินสองสัปดาห์)');
});

test('② ตัวกวาดต้องใช้ค่าที่ export ไม่ใช่เลขของตัวเอง', () => {
  const โค้ด = ลบคอมเมนต์(sweep);
  assert.ok(/const ค้างเกินกี่ชั่วโมง = ค้างเกินกี่ชั่วโมงถือว่านาน;/.test(โค้ด),
    'ตัวกวาดต้องอ่านจากค่าที่ประกาศระดับโมดูล');
  const ประกาศ = (โค้ด.match(/ค้างเกินกี่ชั่วโมงถือว่านาน\s*=\s*\d+/g) || []).length;
  assert.equal(ประกาศ, 1, 'ต้องประกาศตัวเลขที่เดียวในไฟล์นี้');
});

test('③ 🔴 หน้าสถานะห้ามพิมพ์เลขชั่วโมงเอง — ต้อง import จากแหล่งเดียว', () => {
  const โค้ด = ลบคอมเมนต์(status);
  const ก้อน = /check\("รหัสที่ถูกข้ามจากการดันสต็อก"[\s\S]*?\n    \}\),/.exec(โค้ด)?.[0] ?? '';
  assert.ok(ก้อน.length > 300, `หาก้อนตัวตรวจไม่เจอหรือสั้นผิดปกติ (${ก้อน.length}) ⇒ ตัวตัดพัง`);
  assert.ok(/ค้างเกินกี่ชั่วโมงถือว่านาน/.test(ก้อน), 'ต้อง import เกณฑ์มาใช้');
  /* 🔑 ยอมให้มี `|| 24` เป็นทางถอยได้ **แต่ต้องมีการ import จริงอยู่ด้วย**
     ถ้าไม่มี import เลยแล้วมีแต่เลข ⇒ นั่นคือเกณฑ์แหล่งที่สองที่ปลอมตัว */
  assert.ok(/import\(.*stock-push-sweep\.mjs.*\)/.test(ก้อน),
    'ต้อง import จาก stock-push-sweep.mjs ตรง ๆ ไม่ใช่พิมพ์เลขไว้เอง');
});

test('④ 🔬 พลังแยกแยะ: ถ้าถอด export ออก การ import ต้องพังจริง ไม่ใช่เงียบ', async () => {
  /* ข้อนี้พิสูจน์ว่า "ปัญหาที่ใบนี้แก้" เป็นปัญหาจริง ไม่ใช่ความกังวล
     โหลดโมดูลด้วยชื่อ export ที่ไม่มีจริง ⇒ ต้องได้ undefined (ไม่ throw)
     ⇒ นี่คือเหตุผลว่าทำไมมันเงียบ: JS ไม่ร้องเมื่อ import ชื่อที่ไม่มีจาก ES module ที่โหลดสำเร็จ */
  const m = await import('../../netlify/lib/stock-push-sweep.mjs');
  assert.equal(m['ชื่อที่ไม่มีจริงแน่ ๆ'], undefined,
    'ยืนยันกลไก: ชื่อที่ไม่มีให้ undefined เงียบ ๆ ⇒ `|| 24` จะกลืนความผิดนี้ทั้งก้อน');
  assert.notEqual(m['ค้างเกินกี่ชั่วโมงถือว่านาน'], undefined,
    'และของจริงต้องไม่ undefined ⇒ ด่านนี้แยกสองสภาพออกจากกันได้');
});
