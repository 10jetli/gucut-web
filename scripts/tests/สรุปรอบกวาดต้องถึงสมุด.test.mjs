import { test } from "node:test";
import assert from "node:assert/strict";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด } from "./_src.mjs";
import { สรุปรอบกวาด } from "../../netlify/functions/beam-sweep.mjs";

const Jไฟล์ = "netlify/lib/job-timing.mjs";
const Bไฟล์ = "netlify/functions/beam-sweep.mjs";
const J = ซอร์สไม่เอาคอมเมนต์(Jไฟล์);
const B = ซอร์สไม่เอาคอมเมนต์(Bไฟล์);

/* ══════════ ① `นับ` ต้องแยกสามสถานะ (เรียกของจริง) ══════════ */

test("✅ ท่อนับให้แล้ว ⇒ `{สำเร็จ, ล้ม}`", () => {
  const r = สรุปรอบกวาด({ checked: 7, askFailed: 2, stoppedBecause: null, elapsedMs: 1234 });
  assert.deepEqual(r.นับ, { สำเร็จ: 7, ล้ม: 2 });
});

test("🔴 กิ่งในพัง (`ship` เป็น `{}`) ⇒ `นับ` ต้องเป็น **null** ห้ามเป็น 0", () => {
  /* 🚫 `{สำเร็จ:0, ล้ม:0}` อ่านว่า "ตรวจแล้วไม่มีใบ" ซึ่งเป็นคำกล่าวอ้างที่เรายังพูดไม่ได้
     ⇒ จอต้องขึ้นขีด (—) = "ท่อไม่ได้นับชิ้นให้รอบนี้" */
  assert.equal(สรุปรอบกวาด({}).นับ, null);
  assert.equal(สรุปรอบกวาด(undefined).นับ, null);
  assert.equal(สรุปรอบกวาด(null).นับ, null);
});

test("🔑 นับครึ่งเดียวก็ยังต้องเป็น null (ครอบไม่ครบ ห้ามรายงานเหมือนครอบครบ)", () => {
  assert.equal(สรุปรอบกวาด({ checked: 5 }).นับ, null, "ขาด askFailed ⇒ ยังตอบไม่ได้ว่ารอบนั้นครบไหม");
  assert.equal(สรุปรอบกวาด({ askFailed: 1 }).นับ, null, "ขาด checked");
});

test("🔑 `checked: 0` เป็นคำตอบที่ถูกต้อง — ห้ามถูกกลืนเป็น 'ไม่รู้'", () => {
  /* ตรงกันข้ามกับข้อบน: 0 ที่ **ท่อนับมาแล้ว** คือข้อมูลจริง ⇒ ต้องผ่าน
     (ถ้าเขียน `ship.checked &&` แทน `Number.isFinite` ข้อนี้จะกลายเป็น null เงียบ ๆ) */
  assert.deepEqual(สรุปรอบกวาด({ checked: 0, askFailed: 3 }).นับ, { สำเร็จ: 0, ล้ม: 3 });
});

/* ══════════ ② `note` ต้องแยก "ครบ" จาก "ท่อรุ่นเก่า" ══════════ */

test("🔴 `stoppedBecause: null` = ไล่ครบคิว ⇒ **ต้องพูดออกมา** ไม่ใช่เงียบ", () => {
  const r = สรุปรอบกวาด({ checked: 3, askFailed: 0, stoppedBecause: null, elapsedMs: 900 });
  assert.match(String(r.note), /ไล่ครบคิว/,
    `เงียบ = จอแยก "ครบ" จาก "ท่อรุ่นเก่าที่ยังไม่มีคีย์นี้" ไม่ออก · ได้: ${r.note}`);
  assert.match(String(r.note), /900 ms/, "ต้องพาเวลาที่ใช้มาด้วย");
});

test("🔑 ท่อรุ่นเก่า (ไม่มีคีย์ `stoppedBecause` เลย) ⇒ **ต้องไม่พูดว่าครบ**", () => {
  /* นี่คือเหตุที่ต้องเช็คด้วย `in` ไม่ใช่ค่าความจริง — `undefined === null` เป็นเท็จก็จริง
     แต่ถ้าเขียน `!ship.stoppedBecause` จะกลายเป็นจริงทั้งสองกรณี (กฎ optional-chain-doesnt-guard-right-side) */
  const r = สรุปรอบกวาด({ checked: 3, askFailed: 0 });
  assert.ok(!/ไล่ครบคิว/.test(String(r.note ?? "")),
    `ท่อที่ไม่ส่งคีย์นี้มา ห้ามถูกอ่านว่า "ครบ" · ได้: ${r.note}`);
});

test("✅ ถูกตัดกลางทาง ⇒ note บอกเหตุตรง ๆ และแยกสองเหตุออกจากกัน", () => {
  const เวลา = สรุปรอบกวาด({ checked: 2, askFailed: 0, stoppedBecause: "หมดงบเวลาของรอบ (18 วินาที)", elapsedMs: 18100 });
  const เพดาน = สรุปรอบกวาด({ checked: 10, askFailed: 0, stoppedBecause: "ครบเพดาน 10 ใบต่อรอบ", elapsedMs: 4000 });
  assert.match(String(เวลา.note), /งบเวลา/, "หมดงบเวลา = ZORT ช้า");
  assert.match(String(เพดาน.note), /เพดาน/, "ครบเพดาน = คิวยาวกว่าที่รอบเดียวไหว");
  /* 🔑 ฝั่งจอขอเองว่าสองอันนี้ต้องแยกให้ชัด **เพราะพาไปคนละทางแก้** */
  assert.notEqual(เวลา.note, เพดาน.note);
});

test("✅ ถาม ZORT ไม่สำเร็จ ⇒ note พาเหตุจริงมาด้วย (ไม่ใช่แค่จำนวน)", () => {
  const r = สรุปรอบกวาด({
    checked: 0, askFailed: 3, askFailReason: "ZORT ตอบ HTTP 502",
    stoppedBecause: "ถาม ZORT ล้มติดกัน 3 ใบ ⇒ ถือว่า ZORT ใช้ไม่ได้อยู่", elapsedMs: 2400,
  });
  assert.match(String(r.note), /502/, `ต้องเห็นเหตุจริง · ได้: ${r.note}`);
  assert.deepEqual(r.นับ, { สำเร็จ: 0, ล้ม: 3 });
});

test("🔑 ไม่มีอะไรจะเล่า ⇒ `note` เป็น null (ไม่ใช่สตริงว่าง)", () => {
  assert.equal(สรุปรอบกวาด({}).note, null, "สตริงว่างกับ null ถูกวาดคนละแบบที่จอ");
});

/* ══════════ ③ ต่อสายจริงไหม — ตรงนี้วัดพฤติกรรมไม่ได้ จึงอ่านรูปร่างและเขียนกำกับว่าทำไม ══════════
   `ครอบงานตามเวลา` เขียนลงสมุดผ่าน D1 ⇒ เรียกในเทสแล้วอ่านผลกลับไม่ได้
   ⇒ สองข้อนี้จึงตรวจว่า **ตัวห่อรับพารามิเตอร์และส่งต่อจริง** (ไม่ใช่แค่มีข้อความอยู่ในไฟล์) */

test("🔴 `ครอบงานตามเวลา` ต้องส่ง `นับชิ้น` ต่อให้ `วัดเวลางาน`", () => {
  const i = J.indexOf("export function ครอบงานตามเวลา");
  assert.ok(i > 0, "ไม่เจอตัวห่อ");
  const ก้อน = J.slice(i, J.indexOf("\n}\n", i));
  assert.match(ก้อน, /\{\s*ตัดสินผล[^}]*นับชิ้น/s, "ต้องรับ `นับชิ้น` เป็นพารามิเตอร์");
  assert.match(ก้อน, /^\s*นับชิ้น,\s*$/m,
    "ต้อง **ส่งต่อ** `นับชิ้น` เข้า วัดเวลางาน ด้วย — รับมาแล้วไม่ส่งต่อคือช่องหลอก");
  console.log(`   🔎 ${Jไฟล์}:${เลขบรรทัด(J, i)} ตัวห่อรับและส่งต่อ นับชิ้น`);
});

test("🔴 คำอธิบายของงานต้อง **ต่อท้าย** `HTTP <status>` ไม่ใช่ทับ", () => {
  /* `HTTP <status>` เป็นสิ่งเดียวที่สมุดมีอยู่เดิม และคอมเมนต์ในไฟล์สั่งให้เก็บไว้ให้คนตีความเอง
     ⇒ ถ้างานส่ง `อธิบาย` มาแล้วทับ status ทิ้ง เราจะเสียข้อมูลเก่าไปเพื่อได้ข้อมูลใหม่ */
  const i = J.indexOf("export function ครอบงานตามเวลา");
  const ก้อน = J.slice(i, J.indexOf("\n}\n", i));
  assert.match(ก้อน, /\[ฐาน, เพิ่ม\]\.filter\(Boolean\)\.join/,
    "ต้องรวมสองส่วนเข้าด้วยกัน · ได้: " + ก้อน.replace(/\s+/g, " ").slice(0, 160));
  assert.match(ก้อน, /HTTP \$\{r\.status\}/, "ต้องยังมี HTTP status อยู่");
});

test("🔴 `beam-sweep` ต้องส่งทั้ง `อธิบาย` และ `นับชิ้น` เข้าตัวห่อ", () => {
  const i = B.indexOf('ครอบงานตามเวลา("beam-sweep"');
  assert.ok(i > 0, "ไม่เจอการห่อ");
  const ก้อน = B.slice(i, B.indexOf(");", i));
  for (const k of ["อธิบาย:", "นับชิ้น:"])
    assert.ok(ก้อน.includes(k), `ขาด ${k} ⇒ ค่าที่ท่อเติมจะไม่ถึงสมุด · ได้: ${ก้อน.replace(/\s+/g, " ")}`);
  assert.match(ก้อน, /สรุปของรอบ\.get\(r\)/,
    "ต้องอ่านจากสรุปที่ผูกกับ Response — ห้ามแกะ body (แกะแล้ว body ถูกใช้ไปแล้ว)");
  console.log(`   🔎 ${Bไฟล์}:${เลขบรรทัด(B, i)} beam-sweep ต่อสายครบ`);
});

test("🚫 ห้ามใช้ตัวแปรระดับโมดูลเก็บสรุปของรอบ (สองรอบทับกันแล้วพังเงียบ)", () => {
  assert.match(B, /new WeakMap\(\)/, "ต้องผูกกับตัว Response ผ่าน WeakMap");
  /* ถ้าวันหนึ่งมีคนเปลี่ยนไปใช้ `let สรุป = null` ระดับโมดูล ข้อนี้จะแดง */
  assert.ok(!/^let สรุป/m.test(B), "เจอตัวแปรระดับโมดูล ⇒ รอบที่ทับกันจะอ่านสรุปของอีกรอบ");
});
