/* 🔑 ด่านของ **เครื่องมือชั้น ②** เอง (`คีย์ของก้อน`) — ตัวมันเองต้องถูกทดสอบ
 *    (28 ก.ย. 2569 · เครื่องมือนี้เกิดจากกติกา ⑤ ที่ตกลงกับฝั่งจอ)
 *
 * 🔴 วันแรกที่ใช้ มันมีจุดบอด: **ไม่รู้จักคีย์แบบย่อ** (`{ list, unreadable }` ไม่มีทวิภาค)
 *    ⇒ อ่านทางออกหลักของ `returns-feed.mjs` ได้แค่ `วัดเมื่อ` (ตัวเดียวที่มีทวิภาค)
 *    ⇒ ด่านที่ใช้มัน **แดงลวง** โดยบอกว่าไฟล์ที่ถูกอยู่แล้วขาดตัวนับ 4 ตัว
 *    🔑 เครื่องมือที่เราสร้างเพื่อกันเขียวลวง **สร้างแดงลวงได้เอง** ถ้าไม่มีใครทดสอบตัวมัน
 *       ⇒ ของที่ถูกเอาไปตัดสินของอื่น ต้องมีด่านของตัวเองเสมอ
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { คีย์ของก้อน } from "./_src.mjs";

test("คีย์แบบมีทวิภาค", () => {
  assert.deepEqual(คีย์ของก้อน('{ found: true, st: 1, kind: "bundle" }'), ["found", "st", "kind"]);
});

test("🔴 คีย์แบบย่อ (ไม่มีทวิภาค) — จุดบอดของรุ่นแรก", () => {
  assert.deepEqual(คีย์ของก้อน("{ list, unreadable, วัดเมื่อ: 1 }"), ["list", "unreadable", "วัดเมื่อ"]);
  assert.deepEqual(คีย์ของก้อน("{ a, b, c }"), ["a", "b", "c"], "ย่อล้วนทั้งก้อนก็ต้องอ่านได้");
  assert.deepEqual(คีย์ของก้อน("{ x }"), ["x"], "ตัวเดียวไม่มีจุลภาคตามหลัง");
});

test("ชื่อไทยใช้ได้ทั้งแบบย่อและแบบมีทวิภาค", () => {
  assert.deepEqual(คีย์ของก้อน("{ ยอดรวม, ครบ: true }"), ["ยอดรวม", "ครบ"]);
});

test("ต้องไม่หลงค่าที่ซ้อนอยู่ข้างใน", () => {
  assert.deepEqual(คีย์ของก้อน("{ a: { b: 1, c: 2 }, d: [1, 2], e: f(g, h) }"), ["a", "d", "e"]);
  assert.deepEqual(คีย์ของก้อน('{ a: "x: y", b: `t, u` }'), ["a", "b"], "ทวิภาค/จุลภาคในสตริงต้องไม่นับ");
});

test("🔑 spread ต้องไม่ถูกนับเป็นคีย์ — และนี่คือเหตุที่เครื่องมือนี้เกิด", () => {
  /* เคสของฝั่งจอ: แทรก spread ไว้ก่อนคีย์เดิม ⇒ คีย์หลังเขียนทับ ⇒ **ชุดคีย์ไม่เปลี่ยน**
     ⇒ เครื่องมือนี้จึงตอบว่า "ผลไม่ต่าง" ได้ถูกต้อง */
  assert.deepEqual(คีย์ของก้อน("{ ...(a ? { x: 1 } : {}), found: false, st }"), ["found", "st"]);
});

test("ก้อนว่าง ⇒ ไม่มีคีย์ (ไม่ใช่ error)", () => {
  assert.deepEqual(คีย์ของก้อน("{}"), []);
  assert.deepEqual(คีย์ของก้อน("{ }"), []);
});
