/* 🕰️ ด่าน: **`x-core-build` ต้องขยับทุกครั้งที่ build — ห้ามมีอะไรทำให้มันค้าง**
 *
 * 🔑 ทำไมสำคัญ: หัว `x-core-build` เป็น **ตัวชี้ยุคของท่อ** ที่ทั้งสองบัญชีใช้ตัดสินทั้งวันว่า
 *    *"ของที่เราแก้ถึงระบบจริงหรือยัง"* ⇒ ถ้ามันค้าง เราจะอ่านว่า "ยังไม่ deploy" ตลอดกาล
 *    ⇒ ⇒ และจะไปไล่หาเหตุที่ไม่มี (วันนี้เราสองคนเสียเวลากับเรื่อง "ยุคท่อ" หลายรอบอยู่แล้ว)
 *
 * 📏 ค่านั้นมาจาก `ARCH.generatedAt` ใน `netlify/lib/arch-data.mjs`
 *    ซึ่งถูกเขียนใหม่ทุก build โดย `scripts/gen-arch.mjs`
 *
 * 🔴 **ความเสี่ยงจริงที่ด่านนี้กัน** (เจอตอนตรวจตัวเอง 20 ก.ย. 2569):
 *    วันนี้ผมแก้ `gen-zort-arch.mjs` ให้ใช้ `เขียนถ้าเนื้อเปลี่ยน` **เพราะมันทำให้ git สะอาด**
 *    (เหตุผลที่ดีจริง — ไฟล์ที่ถูกเขียนทุก build ทำให้อีกบัญชี `pull` ไม่ได้)
 *    ⇒ ⇒ วันไหนมีคนเอาท่าเดียวกันไปใส่ `gen-arch.mjs` **ด้วยเหตุผลเดียวกันเป๊ะ**
 *       `generatedAt` จะไม่ขยับ ⇒ **`x-core-build` ค้างถาวร** ⇒ ตัวชี้ยุคโกหกโดยไม่มีอะไรฟ้อง
 *    🔑 คลาส: **การแก้ที่ถูกสำหรับไฟล์หนึ่ง เป็นการแก้ที่ผิดสำหรับไฟล์ที่ทำหน้าที่เป็นตัวชี้เวลา**
 *
 * 🚫 ถ้าวันหนึ่งจำเป็นต้องหยุดเขียน `arch-data.mjs` ทุก build จริง ๆ
 *    **ต้องหาที่อื่นให้ `x-core-build` ก่อน** (เช่น env ที่ Netlify ใส่ให้ตอน build)
 *    แล้วแก้เทสนี้พร้อมกัน — ห้ามปิดเทสนี้เฉย ๆ
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

/* 🔴 **ต้องตัดคอมเมนต์ก่อนตรวจ — ผมเหยียบเองทันทีในรอบเดียวกัน** (20 ก.ย. 2569)
   ผมเขียน **คำเตือน** ใน `gen-arch.mjs` ว่า *"ห้ามใช้ `เขียนถ้าเนื้อเปลี่ยน` กับไฟล์นี้"*
   ⇒ ⇒ เทสข้อแรกที่ห้ามคำนั้น **แดงทันที เพราะคำเตือนของผมเอง**
   🔑 คลาส *เอ่ยถึง ≠ มี* — วันนี้กัดทีมรวม 8 รอบ · รอบนี้ **ผมสร้างของที่กัดตัวเอง**
   ⇒ เกณฑ์ที่ถูก: ตรวจ **โค้ดที่รัน** ไม่ใช่ทั้งไฟล์ (ฝั่งจอสรุปเป็นคำถามบังคับไว้แล้ว:
     *"เลขนี้นับของที่ทำงาน หรือของที่เล่าเรื่อง"*) */
const โค้ดของ = (p) => ตัดคอมเมนต์(readFileSync(p, "utf8"), p);

test("`gen-arch.mjs` ต้องเขียน arch-data.mjs **ทุก build** (ห้ามใช้ `เขียนถ้าเนื้อเปลี่ยน`)", () => {
  const s = โค้ดของ("scripts/gen-arch.mjs");
  assert.match(s, /writeFileSync/, "ต้องยังเขียนไฟล์ตรง ๆ");
  assert.doesNotMatch(
    s, /เขียนถ้าเนื้อเปลี่ยน/,
    "🔴 ถ้าใช้ตัวช่วยนี้ ไฟล์จะไม่ถูกเขียนเมื่อเนื้อเหมือนเดิม ⇒ `generatedAt` ค้าง ⇒ `x-core-build` โกหก\n" +
    "   ⇒ ถ้าจำเป็นต้องทำจริง **ต้องย้ายที่มาของ x-core-build ก่อน** แล้วแก้เทสนี้พร้อมกัน",
  );
});

test("ไฟล์ที่ท่ออ่านเพื่อทำ `x-core-build` ต้องมี `generatedAt` ที่เป็นเวลาจริง", () => {
  const s = readFileSync("netlify/lib/arch-data.mjs", "utf8");
  const m = /generatedAt"?\s*:\s*"([^"]+)"/.exec(s);
  assert.ok(m, "ต้องมีช่อง generatedAt ในไฟล์ที่ generate");
  const t = Date.parse(m[1]);
  assert.ok(Number.isFinite(t), `generatedAt ต้องเป็นเวลาที่ parse ได้ (ได้ "${m[1]}")`);
  /* ⚠️ ไม่เช็คว่า "ใหม่กว่า X" — เครื่องที่ checkout สด ๆ ยังไม่ได้ build ⇒ จะแดงลวงทันที
     🔑 ด่านที่ร้องใส่ของปกติจะถูกปิดใน 1 วัน [[noise-filters-eat-real-cases]] */
});

test("🔑 `core.mjs` ต้องอ่าน build stamp จากไฟล์ที่ generate — ไม่ใช่ค่าที่พิมพ์มือ", () => {
  const s = readFileSync("netlify/functions/core.mjs", "utf8");
  assert.match(s, /CORE_BUILD = String\(m\?\.ARCH\?\.generatedAt/, "ต้องอ่านจาก ARCH.generatedAt");
  /* 🚫 ห้ามมีค่าเวลาที่พิมพ์ไว้ตรง ๆ เป็นค่าตั้งต้นของ stamp — นั่นคือ "เลขที่เน่าเงียบ ๆ"
     (ฝั่งจอสรุปวันนี้: เลขที่พิมพ์ค้างไว้เน่า · เลขที่คำนวณตอนรันไม่มีวันเน่า) */
  assert.doesNotMatch(
    s, /CORE_BUILD = "20\d\d-/,
    "ห้ามพิมพ์เวลา build ลงไปตรง ๆ — stamp ต้องมาจากไฟล์ที่ถูกสร้างตอน build",
  );
  assert.match(s, /CORE_BUILD = ""/, "อ่านไม่ได้ ⇒ ปล่อยว่าง (ส่งค่าว่างแย่กว่าไม่ส่ง ⇒ หัวจะไม่ถูกใส่)");
});

test("🔬 พลังแยกแยะ: ถ้าใครใส่ `เขียนถ้าเนื้อเปลี่ยน` ลง gen-arch ⇒ ข้อแรกต้องแดง", () => {
  const s = โค้ดของ("scripts/gen-arch.mjs");
  const ปลอม = s.replace("writeFileSync(", "เขียนถ้าเนื้อเปลี่ยน(");
  assert.notEqual(ปลอม, s, "ของปลูกต้องเปลี่ยนเนื้อจริง");
  assert.match(ปลอม, /เขียนถ้าเนื้อเปลี่ยน/, "ตะแกรงของข้อแรกต้องเห็นของปลูกนี้");
});
