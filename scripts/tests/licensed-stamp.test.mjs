test("รอบปั๊มครบวงจร — ค่าเริ่มต้นซ้อม · คำตอบต้องบอกขอบเขตที่ใช้ตัดสิน", async () => {
  /* 🔑 เลขเปล่า ๆ ตีความไม่ได้ว่า "ไม่มีอะไรต้องปั๊ม" หรือ "ไม่ได้ไปดู"
     ⇒ คำตอบต้องมีวันเริ่ม + จำนวนบรรทัดที่ดู ไม่งั้นศูนย์อ่านได้สองแบบ */
  const { รอบปั๊ม } = m;
  const เขียน = [];
  const q = async (sql, args = []) => {
    if (/^CREATE TABLE/i.test(sql)) return [];
    if (/^SELECT line_key/i.test(sql)) return [];
    if (/FROM order_items/i.test(sql)) {
      assert.equal(args[0], เริ่มปั๊มตั้งแต่, "ต้องกรองวันที่ฝั่ง SQL ด้วยวันเริ่ม");
      assert.ok(args.length > 5, "ต้องส่งรายชื่อรหัสทะเบียนไปกรองที่ SQL ไม่ใช่กรองจากชื่อสินค้า");
      return [{ number: "SO-9", date: "2026-10-07", status: "Pending", payStatus: "Paid",
                customer: "ก", sku: "Bar NW 22", qty: 1, line: 1 }];
    }
    if (/FROM registry WHERE sold_at IS NULL/i.test(sql))
      return [{ lot: 1, kind: "bar", spec: "NEWWAVE", model: "22", serial: "B-01", seq: 9, received: "1/1/2568" }];
    if (/^UPDATE|^INSERT/i.test(sql)) { เขียน.push(sql.slice(0, 6)); return []; }
    if (/^SELECT sold_at/i.test(sql)) return [{ sold_at: "" }];
    throw new Error("ท่อปลอมไม่รู้จัก: " + sql.slice(0, 40));
  };
  const r = await รอบปั๊ม({ query: q });
  assert.equal(r.ผล.ซ้อม, true, "ไม่ส่งคำยืนยัน ⇒ ต้องเป็นรอบซ้อม");
  assert.equal(เขียน.length, 0, "รอบซ้อมห้ามเขียน");
  assert.equal(r.แผน.ปั๊ม, 1);
  assert.equal(r.ขอบเขต.ปั๊มเฉพาะใบลงวันตั้งแต่, เริ่มปั๊มตั้งแต่);
  assert.equal(r.ขอบเขต.บรรทัดขายที่ดู, 1, "ต้องบอกว่าดูกี่บรรทัด ไม่งั้นศูนย์อ่านได้สองแบบ");
  assert.equal(r.ขอบเขต.ซีเรียลว่างทั้งหมด, 1);
});
