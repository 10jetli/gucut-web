test("ไม่ได้ตั้งโทเคน D1 ⇒ ต้องบอกเหตุนั้นตรง ๆ ไม่ใช่ 'อ่านไม่ได้' ลอย ๆ", async () => {
  /* 🔑 สามเหตุจบที่ "ใช้ค่าแช่แข็ง" เหมือนกัน แต่ทางแก้คนละเรื่อง:
       ลืมตั้ง env · ฐานล่ม · ทะเบียนว่าง ⇒ เหมารวมแล้วคนจะไปไล่ฐานทั้งที่แค่ลืมตั้งค่า
     ⚠️ เทสนี้เดินทางที่ **ไม่ฉีด query** ซึ่งเป็นทางที่ของจริงใช้ — ทางที่ไม่เคยถูกเดิน
        คือทางที่ยังไม่รู้ว่าใช้ได้ไหม [[ทางที่ไม่เคยถูกเดินคือทางที่ยังไม่รู้ว่าใช้ได้ไหม]]
     (ในเครื่องเทสไม่มี CLOUDFLARE_D1_TOKEN ⇒ ทางนี้คือทางที่จะวิ่ง) */
  if (process.env.CLOUDFLARE_D1_TOKEN) return; // เครื่องที่ตั้งค่าไว้ ข้ามข้อนี้โดยตั้งใจ
  /* 🔴 **รุ่นแรกของเทสข้อนี้เป็นเขียวลวง — จับได้ด้วยการปลูก (5 ต.ค. 2569)**
     รุ่นแรกตรวจแค่ `/CLOUDFLARE_D1_TOKEN/` ⇒ **ผ่านทั้งตอนมีด่านและตอนถอดด่าน**
     เพราะ `coreQuery` เองก็พูดถึงชื่อค่านั้น · ของจริงที่ต่างกันคือ **คำห่อ**:
       มีด่าน   ⇒ "ยังไม่ได้ตั้ง CLOUDFLARE_D1_TOKEN ในฟังก์ชันนี้ ⇒ อ่านทะเบียนสดไม่ได้"
       ถอดด่าน ⇒ "อ่านทะเบียนไม่สำเร็จ: ยังไม่ได้ตั้ง CLOUDFLARE_D1_TOKEN"   ← ไปแตะฐานแล้วค่อยพัง
     ⇒ คำว่า "อ่านทะเบียนไม่สำเร็จ" เป็นหลักฐานว่า **เดินไปถึงฐาน** ซึ่งคือสิ่งที่ด่านนี้กัน
        (ใช้ถ้อยคำเป็นตัวแทนของ "ไม่ได้ไปแตะฐานเลย" เพราะวัดการไม่เรียกตรง ๆ จากนอกโมดูลไม่ได้) */
  await assert.rejects(() => ทะเบียนเหลือทุกกลุ่ม(), (e) => {
    assert.ok(e instanceof ทะเบียนอ่านไม่ได้, "ต้องเป็นชนิด ทะเบียนอ่านไม่ได้");
    assert.match(e.message, /ยังไม่ได้ตั้ง CLOUDFLARE_D1_TOKEN ในฟังก์ชันนี้/,
      `เหตุต้องชี้ว่าไม่ได้ตั้งค่า ไม่ใช่ว่าฐานล่ม · ได้: ${e.message}`);
    assert.doesNotMatch(e.message, /อ่านทะเบียนไม่สำเร็จ/,
      `ต้องตีกลับ **ก่อน** ไปแตะฐาน — คำว่า "อ่านทะเบียนไม่สำเร็จ" แปลว่าเดินไปถึงฐานแล้ว · ได้: ${e.message}`);
    return true;
  });
  // และรหัสที่ไม่ใช่ของทะเบียนต้องยังได้ null **ก่อน** ไปแตะฐาน (ตัวควบคุมลบ)
  assert.equal(await ทะเบียนเหลือของรหัส("01387"), null, "รหัสนอกทะเบียนต้องไม่ต้องแตะฐานเลย");
});
