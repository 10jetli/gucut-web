/* ด่านสองทิศของรายชื่อ "เส้นที่เขียนของจริงแม้ไม่มีด่าน method"
 * ทิศ ① ชื่อหายจากสารบัญ (เปลี่ยนชื่อ/ถอดเส้น) ⇒ ตก — ไม่งั้นป้ายเตือนชี้ไปที่ไม่มีอะไร
 * ทิศ ② เส้นนั้นได้ป้าย write จากตัวอัตโนมัติแล้ว ⇒ ตก — ต้องถอดออก ให้รายชื่อ **หดเอง**
 *       (ถ้าไม่มีทิศนี้ ไฟล์จะโตทางเดียวจนกลายเป็นรายชื่อที่ไม่มีใครเชื่อ)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { เขียนแม้ไม่มีด่านMethod, ความปลอดภัยของเส้น } from "../../netlify/lib/route-safety.mjs";
import { paramRoutes, routeMethod } from "../../netlify/lib/endpoints.mjs";

test("① ทุกชื่อในรายชื่อต้องยังมีอยู่ในสารบัญเส้นจริง", () => {
  const หาย = เขียนแม้ไม่มีด่านMethod.map((x) => x.ชื่อ).filter((n) => !paramRoutes.includes(n));
  assert.deepEqual(หาย, [], "ชื่อในรายชื่อไม่มีในสารบัญแล้ว (เปลี่ยนชื่อหรือถอดเส้นไป?): " + หาย.join(", "));
});

test("② เส้นที่มีด่าน method แล้ว ต้องถูกถอดออกจากรายชื่อ", () => {
  const ควรถอด = เขียนแม้ไม่มีด่านMethod
    .map((x) => x.ชื่อ)
    .filter((n) => routeMethod[n] === "write" || routeMethod[n] === "readonly");
  assert.deepEqual(
    ควรถอด, [],
    "เส้นเหล่านี้มีด่าน method แล้ว ⇒ ตัวอัตโนมัติติดป้ายได้เอง ให้ถอดออกจาก route-safety.mjs: " + ควรถอด.join(", "),
  );
});

test("ทุกแถวต้องบอกว่าทำอะไร · ตรวจเมื่อไหร่ · ค้างอะไรอยู่", () => {
  for (const x of เขียนแม้ไม่มีด่านMethod) {
    assert.ok(x.ทำอะไร && x.ทำอะไร.length > 10, `${x.ชื่อ}: ต้องบอกว่าเขียนอะไร`);
    /* 📅 วันที่ตรวจสำคัญ — "ตรวจด้วยตาแล้ว" ไม่มีวันที่กำกับ = ไม่รู้ว่าเก่าแค่ไหน */
    assert.match(x.ตรวจเมื่อ || "", /^\d{4}-\d{2}-\d{2}$/, `${x.ชื่อ}: ต้องมีวันที่ตรวจ`);
    assert.ok(x.ค้างอยู่ && x.ค้างอยู่.length > 5, `${x.ชื่อ}: ต้องบอกว่าทำไมยังไม่ใส่ด่าน`);
  }
});

test("คำอธิบายต้องยืนยันว่า unknown ไม่ใช่ readonly และรายชื่อนี้ไม่ครบทั้งกอง", () => {
  const ข้อความ = JSON.stringify(ความปลอดภัยของเส้น());
  /* ผูกกับเจตนา ไม่ใช่ถ้อยคำ */
  assert.match(ข้อความ, /unknown/, "ต้องพูดถึงป้าย unknown");
  assert.match(ข้อความ, /ยังไม่ตรวจ|ไม่ครบ/, "ต้องบอกว่าที่ไม่อยู่ในรายชื่อ = ยังไม่ตรวจ ไม่ใช่ปลอดภัย");
});
