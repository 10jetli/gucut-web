// รัน: node --experimental-test-module-mocks --test scripts/tests/ภาพถ่ายสต็อก-เก็บราคาซื้อรายวัน.test.mjs
// ใบ t_mutopb3l ขั้นที่ 1 — ท่านประธานตัดสินนิยามต้นทุนเป็น "ถัวเฉลี่ยเคลื่อนที่" (4 ต.ค. 2569)
//
// 🔴 **เหตุที่ต้องมีเทสนี้**: products.purchase_price มีค่าเดียว "ณ ปัจจุบัน" และตัวซิงก์เขียนทับทุกรอบ
//    ⇒ ไม่มีที่ไหนเก็บว่าเมื่อวานราคาซื้อเท่าไร ⇒ **ทุกวันที่ผ่านไปคือประวัติที่เอาคืนไม่ได้**
//    ของที่เน่าเสียได้ ต้องมีด่านกันคนถอดออกโดยไม่รู้ว่ามันกันอะไรอยู่
//
// 🔑 เทสนี้ยิง `snapshotStock()` **ตัวจริง** แล้วอ่าน **คำสั่ง SQL ที่มันพ่นออกมา**
//    (ไม่ใช่การอ่านซอร์สเป็นข้อความ — คำสั่งที่พ่นคือพฤติกรรมของฟังก์ชัน)
import assert from 'node:assert/strict';
import { mock, test } from 'node:test';

const คำสั่งที่ยิง = [];
let ราคาซื้อในทะเบียน = [{ sku: 'A1', purchase_price: 6.2 }, { sku: 'A2', purchase_price: 0 }];
let ทะเบียนพัง = false;

mock.module('../../netlify/lib/coredb.mjs', {
  namedExports: {
    coreReady: () => true,
    แถวจากผล: (r) => (Array.isArray(r) ? r : (r?.results ?? [])),
    coreQuery: async (sql, params) => {
      คำสั่งที่ยิง.push(sql);
      if (/FROM products/i.test(sql)) {
        if (ทะเบียนพัง) throw new Error('D1 ปลอม (ปลูก): no such column: purchase_price');
        return ราคาซื้อในทะเบียน;
      }
      return [];
    },
  },
});
mock.module('@netlify/blobs', {
  namedExports: {
    getStore: () => ({
      // สามรหัส: A1 มีราคาซื้อ · A2 ราคาซื้อเป็น 0 จริง · A3 ไม่อยู่ในทะเบียนเลย
      get: async () => ({ map: { A1: [5, 16], A2: [1, 10], A3: [2, 20] } }),
    }),
  },
});

const { snapshotStock } = await import('../../netlify/lib/core-sync.mjs');
const หาคำสั่งเขียน = () => คำสั่งที่ยิง.find((s) => /INSERT INTO stock_snapshots/i.test(s));

test('① ต้องเขียนช่อง purchase_price ลงภาพถ่าย (ไม่ใช่แค่ qty/price)', async () => {
  คำสั่งที่ยิง.length = 0;
  const r = await snapshotStock();
  const sql = หาคำสั่งเขียน();
  assert.ok(sql, 'ไม่เจอคำสั่งเขียนภาพถ่ายเลย');
  assert.match(sql, /\(day,sku,qty,price,purchase_price\)/,
    '🔴 ภาพถ่ายไม่มีช่องราคาซื้อ = วันนี้ผ่านไปโดยไม่เก็บประวัติ');
  /* 🔑 สองเลขต้องแยกกัน: ทะเบียนมี 2 รหัส (A1·A2) แต่ภาพถ่ายมี 3 รหัส (A1·A2·A3)
     ⇒ เขียนราคาซื้อลงได้ 2 แถว · ทะเบียน 2 รหัส · **ห้ามรายงานเลขเดียวแทนทั้งสอง**
     (วัดของจริงบน production 4 ต.ค. 2569: ทะเบียน 2,675 · แคชสต็อก 2,674 ⇒ สองเลขไม่เท่ากันจริง) */
  assert.equal(r.ราคาซื้อที่เขียนลงภาพถ่าย, 2, 'ต้องบอกว่าเขียนราคาซื้อลงภาพถ่ายได้กี่แถว');
  assert.equal(r.ราคาซื้อในทะเบียนสินค้า, 2, 'และบอกขนาดทะเบียนแยกกัน');
});

test('② รหัสที่มีราคาซื้อ ต้องได้ค่าจริง — ไม่ใช่ 0', async () => {
  คำสั่งที่ยิง.length = 0;
  await snapshotStock();
  assert.match(หาคำสั่งเขียน(), /'A1',5,16,6\.2/, "A1 ต้องได้ 6.2 ตามทะเบียน");
});

test('③ 🔑 รหัสที่ยังไม่มีราคาซื้อ ต้องเป็น NULL ห้ามเป็น 0', async () => {
  คำสั่งที่ยิง.length = 0;
  await snapshotStock();
  const sql = หาคำสั่งเขียน();
  assert.match(sql, /'A3',2,20,NULL/,
    '🔴 "ยังไม่เคยเก็บ" ถูกเขียนเป็น 0 ⇒ ตัวคิดเฉลี่ยจะอ่านว่าต้นทุนศูนย์ แล้วรายงานกำไร 100%');
  /* คู่ตรงข้ามในคำสั่งเดียวกัน: A2 มีค่า 0 ในทะเบียนจริง ⇒ ต้องเป็น 0 ไม่ใช่ NULL
     ⇒ ด่านนี้แยก "ศูนย์จริง" ออกจาก "ยังไม่รู้" ได้ ไม่ใช่แค่ห้ามเลขใดเลขหนึ่ง */
  assert.match(sql, /'A2',1,10,0/, 'ศูนย์ที่ต้นทางบอกว่าศูนย์จริง ต้องยังเป็น 0');
});

test('④ ถ่ายซ้ำวันเดิมตอนทะเบียนว่าง ต้องไม่เขียนความว่างทับค่าที่เก็บได้แล้ว', async () => {
  คำสั่งที่ยิง.length = 0;
  await snapshotStock();
  assert.match(หาคำสั่งเขียน(), /purchase_price=COALESCE\(excluded\.purchase_price, stock_snapshots\.purchase_price\)/,
    '🔴 ไม่มี COALESCE = รอบบ่ายที่ทะเบียนยังว่าง จะลบราคาซื้อที่เก็บได้ตอนเช้า (ตัวแก้ที่ทำลายของถูก)');
});

test('⑤ ทะเบียนอ่านไม่ได้ ต้องยังถ่ายภาพต่อ และ **บอกว่าอ่านไม่ได้** ไม่ใช่เงียบ', async () => {
  ทะเบียนพัง = true;
  คำสั่งที่ยิง.length = 0;
  const r = await snapshotStock();
  ทะเบียนพัง = false;
  assert.ok(หาคำสั่งเขียน(), 'ภาพถ่ายของวันนั้นต้องยังถูกเขียน — ภาพที่ขาดราคาซื้อดีกว่าไม่มีภาพ');
  assert.match(หาคำสั่งเขียน(), /'A1',5,16,NULL/, 'อ่านทะเบียนไม่ได้ ⇒ ทุกรหัสต้องเป็น NULL');
  assert.ok(r.ราคาซื้ออ่านไม่ได้, '🔴 กลืน error เงียบ = วันข้างหน้าจะมีแต่ NULL โดยไม่มีใครรู้ว่าทำไม');
  assert.equal(r.ราคาซื้อที่เขียนลงภาพถ่าย, 0);
  assert.equal(r.ราคาซื้อในทะเบียนสินค้า, 0);
});

test('⑥ 🔬 พลังแยกแยะ: ถ้าใครเขียน 0 แทน NULL ด่านข้อ ③ ต้องแดง', () => {
  const ปลูก = `VALUES ('2026-10-04','A3',2,20,0)`;
  assert.doesNotMatch(ปลูก, /'A3',2,20,NULL/,
    'ตัวจับคู่ของข้อ ③ ต้องไม่ตรงกับคำสั่งที่เขียน 0 ⇒ ข้อ ③ จะแดงจริงเมื่อของจริงเพี้ยน');
});
