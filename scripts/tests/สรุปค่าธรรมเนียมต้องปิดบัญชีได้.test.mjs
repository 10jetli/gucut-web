/* 🔴 ด่าน: **สรุปค่าธรรมเนียมต้องบอกได้ว่าอธิบายส่วนต่างได้ครบไหม**
 *
 * ที่มา 27 ก.ย. 2569: สรุปให้ยอด "ส่วนต่าง 84,075 = 32.49%" แต่ช่องที่โชว์
 * (คอม + ค่าบริการ + ค่าส่งตามจริง) รวมได้ 81,769 ⇒ **เหลือ 2,306 บาทไม่มีชื่อ**
 * ของจริงอยู่ในตารางครบทุกใบ (ค่าธุรกรรมผู้ขาย · ค่าส่งที่ Shopee ออก · ค่าส่งที่ผู้ซื้อจ่าย ·
 * ผลต่างสูตร) แต่ SELECT ไม่ได้ส่งออกมา ⇒ คนอ่านไม่มีทางรู้ว่ายอดปิดบัญชีได้หรือไม่
 *
 * 🔑 เกณฑ์: คำตอบต้อง **ตรวจตัวเองได้** — ไม่ใช่ให้คนเอาเครื่องคิดเลขมาบวกทีหลัง
 * ⚠️ เคสควบคุมที่สำคัญที่สุด: ช่องขาด (null) ⇒ **ต้องไม่คิดให้** แล้วบอกว่าขาดช่องอะไร
 *    (แทน null ด้วย 0 แล้วคิดต่อ = ได้ส่วนต่างสวยงามที่ไม่ได้พิสูจน์อะไร)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ปิดบัญชี } from "../../netlify/lib/mkp-finance-mirror.mjs";

/** ตัวเลขจริงจากกระจก 313 ใบ (27 ก.ย. 2569) — ยังไม่รู้ค่าสี่ช่องใหม่ ⇒ ใส่ให้ปิดพอดีเพื่อทดสอบตรรกะ */
const ครบ = {
  ราคาสินค้ารวม: 258740, ยอดโอนสุทธิ: 174665,
  คอมมิชชั่น: 48925, ค่าบริการ: 22156, ค่าธรรมเนียมชำระเงิน: 0, ค่าส่งตามจริง: 10688,
  ค่าธุรกรรมผู้ขาย: 2306, ค่าส่งที่Shopeeออกให้: 0, ค่าส่งที่ผู้ซื้อจ่าย: 0, ผลต่างสูตรรวม: 0,
};

test("✅ ปิดบัญชีลงตัว ⇒ ไม่มีป้ายเตือน และเปอร์เซ็นต์ตรง", () => {
  const r = ปิดบัญชี(ครบ);
  assert.equal(r["🧾 เหลืออธิบายไม่ได้"], 0);
  assert.equal(r["⚠️ ยังมีรายการที่สูตรไม่รู้จัก"], undefined, "ปิดลงตัวต้องไม่มีป้ายเตือน");
  assert.equal(r["🧾 เปอร์เซ็นต์ค่าธรรมเนียมเทียบราคาสินค้า"], "32.49%");
});

test("🔴 ปิดไม่ลง ⇒ **ต้องขึ้นป้ายพร้อมจำนวนบาท** ห้ามเงียบ", () => {
  const r = ปิดบัญชี({ ...ครบ, ค่าธุรกรรมผู้ขาย: 0 });
  assert.equal(r["🧾 เหลืออธิบายไม่ได้"], 2306);
  assert.match(String(r["⚠️ ยังมีรายการที่สูตรไม่รู้จัก"]), /2306/);
});

test("🔑 ค่าส่งที่ Shopee ออก / ผู้ซื้อจ่าย ต้อง **ลบ** ไม่ใช่บวก (ทิศของสมการ)", () => {
  const r = ปิดบัญชี({ ...ครบ, ค่าส่งที่Shopeeออกให้: 100, ค่าธุรกรรมผู้ขาย: 2406 });
  assert.equal(r["🧾 เหลืออธิบายไม่ได้"], 0, "เพิ่มค่าส่งที่ Shopee ออก 100 ต้องชดเชยด้วยค่าธรรมเนียม +100");
});

test("⚠️ ช่องขาด (null) ⇒ ไม่คิดให้ และบอกชื่อช่องที่ขาด", () => {
  const r = ปิดบัญชี({ ...ครบ, ผลต่างสูตรรวม: null });
  assert.match(String(r["🧾 ปิดบัญชีไม่ได้"]), /ผลต่างสูตรรวม/);
  assert.equal(r["🧾 เหลืออธิบายไม่ได้"], undefined, "ขาดช่องแล้วห้ามคืนตัวเลขที่ดูเหมือนคำนวณได้");
});

test("🚫 SQL ของสรุปต้อง SELECT สี่ช่องนั้นออกมาจริง (ไม่งั้นตรรกะข้างบนไม่มีข้อมูลให้คิด)", async () => {
  const { readFile } = await import("node:fs/promises");
  const src = await readFile(new URL("../../netlify/lib/mkp-finance-mirror.mjs", import.meta.url), "utf8");
  for (const c of ["seller_txn_fee", "ship_subsidy", "ship_buyer", "formula_diff"]) {
    assert.match(src, new RegExp(`SUM\\(${c}\\)`), `สรุปต้องมี SUM(${c})`);
  }
});
