/* 🔴 ด่าน: **สรุปค่าธรรมเนียมต้องบอกได้ว่าอธิบายส่วนต่างได้ครบไหม**
 *
 * ที่มา 27 ก.ย. 2569: สรุปให้ยอด "ส่วนต่าง 84,075 = 32.49%" แต่ช่องที่โชว์
 * (คอม + ค่าบริการ + ค่าส่งตามจริง) รวมได้ 81,769 ⇒ เหลือ 2,306 บาทไม่มีชื่อ
 * ของจริงอยู่ในตารางครบทุกใบ แต่ SELECT ไม่ได้ส่งออกมา
 *
 * 🔴🔴 **และรอบแรกผมแก้ผิด — เทสชุดนี้เองเป็นตัวปล่อยให้ผ่าน**
 *    ผมเอา `ผลต่างสูตรรวม` ไปนับเป็น "อธิบายได้" ⇒ ของจริงขึ้น "เหลืออธิบายไม่ได้ 0"
 *    ทั้งที่ `ผลต่างสูตรรวม = 3,900` คือ **นิยามของส่วนที่สูตรอธิบายไม่ได้**
 *    เทสไม่จับเพราะผมตั้งทุกเคสด้วย `ผลต่างสูตรรวม: 0`
 *    🔑 **เคสทดสอบที่ตั้งค่าเป็นศูนย์ = ตัดทางนั้นออกจากการทดสอบ**
 *       ⇒ ค่าเริ่มต้นของชุดทดสอบนี้จึงเป็นค่าจริงที่ **ไม่เป็นศูนย์** ทุกช่อง
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ปิดบัญชี } from "../../netlify/lib/mkp-finance-mirror.mjs";

/** ตัวเลขจริงจากกระจก 313 ใบ (27 ก.ย. 2569) — **ทุกช่องเป็นค่าจริง ไม่มีศูนย์ปลอม** */
const จริง = {
  ราคาสินค้ารวม: 258740, ยอดโอนสุทธิ: 174665,
  คอมมิชชั่น: 48925, ค่าบริการ: 22156, ค่าธรรมเนียมชำระเงิน: 0, ค่าส่งตามจริง: 10688,
  ค่าธุรกรรมผู้ขาย: 9266, ค่าส่งที่Shopeeออกให้: 9651, ค่าส่งที่ผู้ซื้อจ่าย: 1209,
  ผลต่างสูตรรวม: 3900,
};

test("✅ ค่าจริงทั้งชุด ⇒ ปิดบัญชีลงตัว (เหลือ 0) และเปอร์เซ็นต์ตรงกับที่วัดได้", () => {
  const r = ปิดบัญชี(จริง);
  assert.equal(r["🧾 เหลืออธิบายไม่ได้แม้รวมผลต่างสูตร"], 0);
  assert.equal(r["🧾 เปอร์เซ็นต์ค่าธรรมเนียมเทียบราคาสินค้า"], "32.49%");
});

test("🔴 **ผลต่างสูตรไม่เป็นศูนย์ ⇒ ต้องขึ้นป้าย ห้ามนับเป็นอธิบายได้**", () => {
  const r = ปิดบัญชี(จริง);
  assert.ok(r["⚠️ ผลต่างสูตรไม่เป็นศูนย์"], "3,900 บาทต้องถูกประกาศ ไม่ใช่ถูกกลบ");
  assert.match(String(r["⚠️ ผลต่างสูตรไม่เป็นศูนย์"]), /3900/);
  assert.equal(r["🧾 ผลต่างสูตร (ยังไม่รู้ว่าเป็นค่าอะไร)"], 3900);
  /* 🔑 ช่อง "มีชื่อ" ต้องไม่รวมผลต่างสูตร ⇒ ต้องน้อยกว่าส่วนต่างทั้งก้อน */
  assert.ok(r["🧾 ค่าธรรมเนียมที่มีชื่อ"] < r["🧾 ส่วนต่างราคาสินค้า−เงินเข้า"],
    "ค่าธรรมเนียมที่มีชื่อต้องไม่กลืนผลต่างสูตรเข้ามา");
});

test("✅ ผลต่างสูตรเป็นศูนย์จริง ⇒ ไม่มีป้าย (คุมอีกทิศ)", () => {
  const r = ปิดบัญชี({ ...จริง, ผลต่างสูตรรวม: 0, ค่าธุรกรรมผู้ขาย: 9266 + 3900 });
  assert.equal(r["⚠️ ผลต่างสูตรไม่เป็นศูนย์"], undefined);
  assert.equal(r["🧾 เหลืออธิบายไม่ได้แม้รวมผลต่างสูตร"], 0);
});

test("🔴 ปิดไม่ลงจริง ⇒ ขึ้นป้าย 'ปิดบัญชีไม่ลงจริง' พร้อมจำนวนบาท", () => {
  const r = ปิดบัญชี({ ...จริง, ค่าธุรกรรมผู้ขาย: 0 });
  assert.equal(r["🧾 เหลืออธิบายไม่ได้แม้รวมผลต่างสูตร"], 9266);
  assert.match(String(r["🔴 ปิดบัญชีไม่ลงจริง"]), /9266/);
});

test("🔑 ค่าส่งที่ Shopee ออก / ผู้ซื้อจ่าย ต้อง **ลบ** ไม่ใช่บวก (ทิศของสมการ)", () => {
  const r = ปิดบัญชี({ ...จริง, ค่าส่งที่Shopeeออกให้: 9751, ค่าธุรกรรมผู้ขาย: 9366 });
  assert.equal(r["🧾 เหลืออธิบายไม่ได้แม้รวมผลต่างสูตร"], 0,
    "เพิ่มค่าส่งที่ Shopee ออก 100 ต้องชดเชยด้วยค่าธรรมเนียม +100");
});

test("⚠️ ช่องขาด (null) ⇒ ไม่คิดให้ และบอกชื่อช่องที่ขาด", () => {
  const r = ปิดบัญชี({ ...จริง, ผลต่างสูตรรวม: null });
  assert.match(String(r["🧾 ปิดบัญชีไม่ได้"]), /ผลต่างสูตรรวม/);
  assert.equal(r["🧾 เหลืออธิบายไม่ได้แม้รวมผลต่างสูตร"], undefined,
    "ขาดช่องแล้วห้ามคืนตัวเลขที่ดูเหมือนคำนวณได้");
});

test("🚫 SQL ของสรุปต้อง SELECT สี่ช่องนั้นออกมาจริง (ไม่งั้นตรรกะข้างบนไม่มีข้อมูลให้คิด)", async () => {
  const { readFile } = await import("node:fs/promises");
  const src = await readFile(new URL("../../netlify/lib/mkp-finance-mirror.mjs", import.meta.url), "utf8");
  for (const c of ["seller_txn_fee", "ship_subsidy", "ship_buyer", "formula_diff"]) {
    assert.match(src, new RegExp(`SUM\\(${c}\\)`), `สรุปต้องมี SUM(${c})`);
  }
});
