/* ด่าน: ของในทะเบียนใบอนุญาต — จำนวนต้องมาจากทะเบียน **ไม่ใช่ ZORT**
 *
 * 🔴 ที่มา 25 ก.ย. 2569 · ท่านประธานสั่ง "เลื่อยที่เหลือต้องไปเปิดขายที่เว็บ (ไม่ได้ใช้สต๊อค zort)"
 *    แล้วเสริม "บาร์ด้วย (ไม่ได้ใช้สต๊อค zort)"
 *    วัดจริงก่อนแก้: เลื่อย 7 รุ่นขึ้น "สินค้าหมด" บนเว็บ ทั้งที่ทะเบียนมีของ 24 เครื่อง
 *    ต้นเหตุ: ZORT เชื่อไม่ได้ **สองอาการคนละแบบ** (ยิงครบ 9 รุ่นถึงเห็น)
 *      • ไม่มีในระบบ ZORT เลย 4 รุ่น → `found:false` : F 660 · F 440 · F 288 · F 361
 *      • มีใน ZORT แต่สต็อกเป็น 0 อีก 4 รุ่น        : NW 9800 · F 250 · F 070 · F 381
 *      • ตรงพอดีรุ่นเดียว                            : NW 8800 (ZORT 9 · ทะเบียน 10)
 *      ⚠️ รอบแรกเขียนไว้ว่า "ZORT ไม่รู้จักเลยสักตัว" — **ผิด** เพราะยิงแค่ 2 รุ่นแล้วเหมารวม
 *    ⇒ เลขที่ลูกค้าเห็นเป็นค่าแช่ตอน build จาก 15 ส.ค. 2569 · รวม 34 จาก 54 เครื่องขายไม่ได้
 *
 * 🔑 สิ่งที่ทำให้ด่านนี้ "แยกแยะได้" ไม่ใช่แค่ "ร้องได้":
 *    ① ผูกกับ **การแยกสามสถานะ** — `null` (ไม่ใช่ของในทะเบียน) · `0` (อยู่ในทะเบียนแต่หมด) · `>0`
 *       วันที่ใครยุบ `0` กับ `null` เป็นค่าเดียว ของที่หมดจริงจะเด้งกลับไปใช้เลข ZORT
 *       ที่เชื่อไม่ได้ **โดยเว็บไม่ล้ม ไม่มี error** ⇒ ต้องมีเทสถึงจะจับได้
 *    ② ผูกกับ **ความตรงกันสองฝั่ง** (.ts ฝั่งหน้าเว็บ กับ .mjs ฝั่งเซิร์ฟเวอร์)
 *       สองฝั่งอ่าน JSON ก้อนเดียวกัน — ถ้าวันหนึ่งใครแยกเป็นสองไฟล์
 *       การ์ดสินค้ากับ /api/stock จะตอบคนละเลขเงียบ ๆ
 *    ③ **ตัวควบคุมย้อนกลับ**: รหัสที่ไม่ได้อยู่ในทะเบียนต้องได้ `null` เสมอ
 *       ถ้าด่านนี้ผ่านหมดทั้งที่ทุกอย่างคืนค่าเดียวกัน แปลว่าเทสไม่ได้ทดสอบอะไร
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ราก = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const { licensedStock, LICENSED, LICENSED_ASOF } = await import(
  join(ราก, "netlify", "lib", "licensed-stock.mjs")
);
const ดิบ = JSON.parse(readFileSync(join(ราก, "src", "data", "licensed-stock.json"), "utf8"));

test("รหัสเลื่อยในทะเบียนคืนจำนวนที่ถูก — ไม่ใช่ของ ZORT", () => {
  assert.equal(licensedStock("F 660"), 20, "F660 ทะเบียนมี 20 (ZORT ตอบ found:false)");
  assert.equal(licensedStock("NW 8800"), 10, "8800 ทะเบียนมี 10 (ZORT เคยบอก 9)");
  assert.equal(licensedStock("F 440"), 6, "F440 ทะเบียนมี 6 (เว็บเคยขึ้นสินค้าหมด)");
  assert.equal(licensedStock("F 250"), 5);
  assert.equal(licensedStock("NW 9800"), 1);
});

test("บาร์ต้องยังไม่ถูกเปิดใช้ — เจ้าของร้านสั่ง 'เอาเลื่อยก่อน บาร์รอก่อน'", () => {
  /* 🛑 คำสั่ง 25 ก.ย. 2569 · บาร์ต้องยังใช้ ZORT เหมือนเดิมจนกว่าจะยืนยัน
     ข้อที่ค้างอยู่: `02984` ชื่อสินค้าไม่ได้เขียนว่า "มีทะเบียน" ⇒ ถ้าร้านมีบาร์ KINGKONG
     นอกทะเบียนขายด้วย การใส่ 68 จะไปทับของที่ขายได้จริงให้ต่ำลง
     ⚠️ ด่านนี้ต้องตกทันทีที่ใครเผลอเปิดบาร์กลับมาโดยไม่ได้รับคำสั่ง */
  assert.equal(licensedStock("01387"), null, "บาร์ NEWWAVE ต้องยังใช้ ZORT");
  assert.equal(licensedStock("02984"), null, "บาร์ KINGKONG ต้องยังใช้ ZORT");
  assert.deepEqual(ดิบ["บาร์"], {}, "ช่อง 'บาร์' ต้องว่างจนกว่าเจ้าของร้านจะยืนยัน");
  // เลขที่นับได้ต้องไม่หายไปไหน — เก็บไว้ให้เปิดใช้ทีหลังได้ทันทีโดยไม่ต้องนับใหม่
  const รอ = ดิบ["_บาร์รอเจ้าของร้านยืนยัน"]?.["ค่าที่นับได้"];
  assert.deepEqual(รอ, { "01387": 65, "02984": 68 }, "ค่าที่นับได้ต้องยังอยู่ในไฟล์");
});

test("รหัสที่ไม่ได้อยู่ในทะเบียน ต้องได้ null เพื่อให้ไปใช้ ZORT ต่อ", () => {
  // 🔑 ตัวควบคุมย้อนกลับ — ถ้าข้อนี้ตก แปลว่าเราไปทับสต็อกของสินค้าทั้งร้าน ไม่ใช่แค่ของในทะเบียน
  for (const sku of ["00369-25T", "05540", "ไม่มีรหัสนี้", "F 6600", "660"]) {
    assert.equal(licensedStock(sku), null, `${sku} ต้องไม่ถูกทับ`);
  }
});

test("ค่าที่ป้อนมาเพี้ยน ต้องได้ null ไม่ใช่ 0", () => {
  // 0 แปลว่า "อยู่ในทะเบียนแต่หมด" ⇒ คืน 0 ตรงนี้จะทำให้สินค้าปกติขึ้นสินค้าหมดทั้งร้าน
  for (const v of [null, undefined, "", "   ", 0, false, NaN, {}, []]) {
    assert.equal(licensedStock(v), null, `ค่า ${JSON.stringify(v)} ต้องได้ null`);
  }
});

test("ช่องว่างหัวท้ายต้องไม่ทำให้จับคู่ไม่ติด", () => {
  assert.equal(licensedStock("  F 660  "), 20);
});

test("0 ต้องแยกจาก null ได้ — 'หมดแล้ว' ไม่ใช่ 'ไม่ใช่ของในทะเบียน'", () => {
  // จำลองวันที่ขายหมดพอดี: ต้องได้ 0 (ห้ามเด้งไปใช้ ZORT)
  const สำเนา = { ...LICENSED, "TEST ZERO": 0 };
  const หา = (s) => {
    const n = สำเนา[String(s).trim()];
    return typeof n === "number" && Number.isFinite(n) ? n : null;
  };
  assert.equal(หา("TEST ZERO"), 0, "หมดแล้วต้องเป็น 0");
  assert.notEqual(หา("TEST ZERO"), null, "0 ห้ามกลายเป็น null");
  assert.equal(หา("TEST MISSING"), null, "ไม่มีในทะเบียนต้องเป็น null");
});

test("เลขสองฝั่งต้องตรงกันเป๊ะ — .mjs (เซิร์ฟเวอร์) กับ .json (หน้าเว็บ)", () => {
  /* 🔴 ด่านนี้คือสิ่งเดียวที่กันเลขสองฝั่งเพี้ยนกัน
     `.mjs` พิมพ์เลขซ้ำโดยตั้งใจ เพราะตัวรวมไฟล์ของ Netlify **ไม่เอา .json ติดไปกับฟังก์ชัน**
     (ของจริง 19 ก.ย. 2569 · ดูคำเตือนหัว `netlify/lib/list-filters.mjs` — พังเงียบทั้ง 24 เส้น)
     ⇒ แลกความเสี่ยงนั้นด้วยการมีเลขสองที่ แล้วบังคับให้ตรงกันตรงนี้
     ⚠️ แก้ฝั่งเดียวเมื่อไหร่ต้องตกทันที ไม่งั้นการ์ดสินค้ากับ /api/stock จะตอบคนละเลขเงียบ ๆ */
  assert.deepEqual(
    { ...LICENSED },
    { ...ดิบ["เลื่อย"], ...(ดิบ["บาร์"] || {}) },
    "เลขใน netlify/lib/licensed-stock.mjs ไม่ตรงกับ src/data/licensed-stock.json"
  );
  assert.equal(LICENSED_ASOF, ดิบ["_วัดเมื่อ"], "วันที่นับของสองฝั่งต้องตรงกัน");
});

test("ตัวเลขในไฟล์ต้องสมเหตุสมผล", () => {
  assert.ok(ดิบ["เลื่อย"] && Object.keys(ดิบ["เลื่อย"]).length >= 9, "ต้องมีเลื่อยอย่างน้อย 9 รุ่น");
  for (const [กลุ่ม, ชุด] of Object.entries({ เลื่อย: ดิบ["เลื่อย"], บาร์: ดิบ["บาร์"] || {} })) {
    for (const [sku, n] of Object.entries(ชุด)) {
      assert.ok(Number.isInteger(n), `${กลุ่ม}/${sku} ต้องเป็นจำนวนเต็ม`);
      // ⚠️ ติดลบคือสิ่งที่ ZORT ทำพลาดกับ 02984 (-3) — ทะเบียนห้ามติดลบเด็ดขาด
      assert.ok(n >= 0, `${กลุ่ม}/${sku} ห้ามติดลบ (ได้ ${n})`);
      assert.ok(n <= 500, `${กลุ่ม}/${sku} = ${n} สูงผิดปกติ — ล็อตใหญ่สุดที่เคยนำเข้าคือ 100`);
    }
  }
  assert.match(LICENSED_ASOF, /^\d{4}-\d{2}-\d{2}$/, "ต้องมีวันที่นับของกำกับ");
});

test("เลื่อยรวมต้องตรงกับที่นับจากทะเบียน (54 เครื่อง ณ 25 ก.ย. 2569)", () => {
  // ⚠️ เลขนี้จะเปลี่ยนทุกครั้งที่ขายได้ — ตกเมื่อไหร่ให้ดูว่า "ขายไปจริง" หรือ "ใครพิมพ์ผิด"
  //    ห้ามแก้เลขคาดหวังให้ตรงกับของใหม่โดยไม่เทียบทะเบียนก่อน (นั่นคือการลบตาข่ายทิ้ง)
  const รวม = Object.values(ดิบ["เลื่อย"]).reduce((a, b) => a + b, 0);
  assert.equal(รวม, 54, `เลื่อยในทะเบียนรวม ${รวม} เครื่อง — ถ้าไม่ใช่ 54 ให้เทียบกับทะเบียนก่อนแก้เลขนี้`);
});

test("รุ่นที่ไม่เคยนำเข้าต้องไม่อยู่ในทะเบียน", () => {
  // F038 · F090 · F880 มีสินค้าในเว็บแต่ไม่เคยนำเข้าล็อตไหน — ต้องปล่อยให้เป็น 0 ตามเดิม
  for (const sku of ["F 038", "F 090", "F 880"]) {
    assert.equal(licensedStock(sku), null, `${sku} ไม่เคยนำเข้า ห้ามอยู่ในทะเบียน`);
  }
});
