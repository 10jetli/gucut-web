const ไฟล์ = readdirSync("netlify/functions").filter((f) => f.endsWith(".mjs"));

const เป็นงานตามเวลา = (code) => /export\s+const\s+config\s*=\s*\{[^}]*schedule/.test(code);
/* 🔴 **ต้องตรวจว่า "เรียกใช้จริง" ไม่ใช่ "มีชื่ออยู่"** (แก้ 19 ก.ย. 2569)
   รอบแรกผมใช้ `/adminGate/.test(code)` ⇒ ปลูกบั๊กเปลี่ยนเป็น `adminGateX` **ด่านยังเขียว**
   เพราะ `adminGateX` มีคำ `adminGate` อยู่ข้างใน ⇒ **ตะแกรงจับสตริงย่อย** (โรคที่ทีมห้ามตัวเองไว้แล้ว)
   ⇒ เปลี่ยนเป็นจับ **รูปของการเรียกฟังก์ชัน** พร้อมขอบคำ ⇒ ใกล้ "พฤติกรรม" ขึ้นอีกชั้น
   ⚠️ ยังไม่ใช่พฤติกรรมจริง (ยังเป็นการอ่านซอร์ส) ⇒ ชั้นพฤติกรรมคือยิงด้วยรหัสผิดแล้วต้องได้ 401 */
const เรียกใช้จริง = (code) => /\badminGate\s*\(/.test(code);

test("ไฟล์ฟังก์ชันที่คนเรียกได้ ต้องเรียก adminGate — ห้ามเทียบรหัสเอง", () => {
  const ค้าง = [];
  for (const f of ไฟล์) {
    const code = ซอร์สไม่เอาคอมเมนต์(`netlify/functions/${f}`);
    /* ① เทียบรหัสเอง = ผิดแน่นอน ไม่ว่าเป็นเส้นแบบไหน (จะไม่มีตัวกันเดารหัสรัว ๆ) */
    if (/CHAT_ADMIN_KEY/.test(code) && !เรียกใช้จริง(code)) {
      ค้าง.push(`${f} — อ่าน CHAT_ADMIN_KEY เองโดยไม่ผ่าน adminGate`);
      continue;
    }
    /* ② ไม่เรียก adminGate เลย ⇒ ต้องเป็นงานตามเวลา หรืออยู่ในรายการเส้นสาธารณะพร้อมเหตุผล */
    if (!เรียกใช้จริง(code) && !เป็นงานตามเวลา(code) && !(f in เส้นสาธารณะของลูกค้า)) {
      ค้าง.push(`${f} — ไม่เรียก adminGate · ไม่ใช่งานตามเวลา · ไม่อยู่ในรายการเส้นสาธารณะ`);
    }
  }
  assert.deepEqual(ค้าง, [],
    "ไฟล์เหล่านี้เทียบรหัสหลังร้านเอง ⇒ **ไม่มีตัวกันเดารหัสรัว ๆ**:\n  " + ค้าง.join("\n  ") +
      "\n  ⇒ ต้องเรียกผ่าน `netlify/lib/admin-gate.mjs` เท่านั้น");
});

test("รายการยกเว้นต้องเป็นรายไฟล์พร้อมเหตุผล และต้องไม่มีไฟล์ที่ตายแล้วค้างอยู่", () => {
  /* 🔑 ยกเว้นเป็นกลุ่ม = เปิดประตูให้ไฟล์ใหม่ที่ยังไม่มีใครดู (บทเรียนของฝั่งจอ)
     และรายการที่ชี้ไปไฟล์ที่ไม่มีอยู่ ทำให้คนเชื่อว่ามีไฟล์นั้น */
  const ตายแล้ว = Object.keys(เส้นสาธารณะของลูกค้า).filter((f) => !ไฟล์.includes(f));
  assert.deepEqual(ตายแล้ว, [], "รายการยกเว้นชี้ไปไฟล์ที่ไม่มีอยู่แล้ว: " + ตายแล้ว.join(", "));
  for (const [f, เหตุ] of Object.entries(เส้นสาธารณะของลูกค้า)) {
    assert.ok(String(เหตุ).length > 10, `${f}: เหตุผลยกเว้นสั้นเกินไป`);
  }
});

