// 📏 วัดก่อนลงมือ: ZORT ส่ง `shippingprovince` · `customerprovince` มาจริง
//   (ยิง ?zortfields=1&days=30 · 616 ใบ · เส้นนั้นคืนชื่อช่อง ไม่คืนค่า)
//
// 🔴 สิ่งที่เฝ้า — สามอย่างที่ถ้าพลาดแล้วตารางยังดูปกติทุกประการ:
//   ① ทางถอย (ที่อยู่ส่งของ → ที่อยู่ลูกค้า) ต้องประกาศตัวว่าถูกใช้กี่ใบ
//   ② ใบที่ไม่ระบุชื่อ ห้ามถูกนับเป็น "ลูกค้า" หนึ่งคน
//   ③ ลำดับต้องมีตัวตัดสินเสมอกัน ไม่งั้นสองจังหวัดยอดเท่ากันสลับที่ไปมาระหว่างคำขอ
import { test } from "node:test";
import assert from "node:assert/strict";
import { รวมรายจังหวัด } from "../../netlify/lib/core-orders.mjs";

const แถว = (sp, cp, nm, mkp, orders, sales) => ({ sp, cp, nm, mkp, orders, sales });

test("ใช้จังหวัดที่อยู่ส่งของก่อน · ว่างแล้วถอยไปใช้จังหวัดลูกค้า", () => {
  const r = รวมรายจังหวัด([
    แถว("หนองคาย", "อุดรธานี", "ก", "", 2, 100),   // มีทั้งสอง ⇒ ต้องเข้าหนองคาย
    แถว("", "อุดรธานี", "ข", "", 1, 50),            // มีแต่ของลูกค้า ⇒ ถอยไปอุดรธานี
  ]);
  const ชื่อ = r.ตาราง.map((x) => x.province);
  assert.ok(ชื่อ.includes("หนองคาย") && ชื่อ.includes("อุดรธานี"));
  // แถวที่มีทั้งสองช่องต้องไม่ไปโผล่ที่จังหวัดลูกค้า
  const อุดร = r.ตาราง.find((x) => x.province === "อุดรธานี");
  assert.equal(อุดร.orders, 1, "ใบที่มีจังหวัดส่งของแล้ว ต้องไม่ถูกนับที่จังหวัดลูกค้าด้วย");
});

test("ทางถอยต้องประกาศตัว — นับแยกสามทาง ไม่ใช่สอง", () => {
  const r = รวมรายจังหวัด([
    แถว("หนองคาย", "", "ก", "", 3, 10),
    แถว("", "อุดรธานี", "ข", "", 2, 10),
    แถว("", "", "ค", "", 5, 10),
  ]);
  assert.deepEqual(r.มาจาก, { ที่อยู่ส่งของ: 3, ที่อยู่ลูกค้า: 2, ไม่มีทั้งสองช่อง: 5 });
  assert.equal(r.มีจังหวัด, 5);
  assert.equal(r.ใบทั้งหมด, 10);
});

test("ใบไม่ระบุชื่อ ห้ามนับเป็นลูกค้า — ต้องอยู่ใน unnamedOrders", () => {
  const r = รวมรายจังหวัด([
    แถว("หนองคาย", "", "ก", "", 1, 100),
    แถว("หนองคาย", "", "", "", 7, 700),   // POS ไม่ระบุชื่อ 7 ใบ
  ]);
  const nk = r.ตาราง.find((x) => x.province === "หนองคาย");
  assert.equal(nk.customers, 1, "นับได้แค่ชื่อที่ไม่ว่าง");
  assert.equal(nk.unnamedOrders, 7);
  assert.equal(nk.orders, 8, "จำนวนใบต้องรวมใบที่ไม่ระบุชื่อด้วย");
});

test("ชื่อเดียวกันหลายแถว นับเป็นลูกค้าคนเดียว", () => {
  const r = รวมรายจังหวัด([
    แถว("หนองคาย", "", "ก", "shopee_a", 1, 10),
    แถว("หนองคาย", "", "ก", "lazada_a", 1, 10),
  ]);
  assert.equal(r.ตาราง[0].customers, 1);
  assert.equal(r.ตาราง[0].orders, 2);
});

test("ไม่มีจังหวัดเลย ⇒ มีจังหวัด = 0 (เส้นจะไม่ส่งตารางออกไป)", () => {
  const r = รวมรายจังหวัด([แถว("", "", "ก", "", 4, 10)]);
  assert.equal(r.มีจังหวัด, 0);
  assert.equal(r.ตาราง[0].province, "(ไม่ระบุ)");
});

test("ชื่อบนมาร์เก็ตเพลส — เฉพาะชื่อที่จะส่งกลับ และเป็นชุดไม่ซ้ำ", () => {
  const r = รวมรายจังหวัด([
    แถว("หนองคาย", "", "ก", "shopee_a", 1, 10),
    แถว("หนองคาย", "", "ก", "shopee_a", 1, 10),
    แถว("หนองคาย", "", "ก", "lazada_a", 1, 10),
    แถว("หนองคาย", "", "ข", "tiktok_b", 1, 10),   // ไม่อยู่ใน wantNames ⇒ ไม่เก็บ
  ], { wantNames: new Set(["ก"]) });
  assert.deepEqual([...r.มาร์เก็ตของชื่อ.get("ก")].sort(), ["lazada_a", "shopee_a"]);
  assert.equal(r.มาร์เก็ตของชื่อ.has("ข"), false);
});

test("ยอดเท่ากันต้องได้ลำดับเดิมทุกครั้ง (มีตัวตัดสินเสมอกัน)", () => {
  const ชุด = [แถว("ข", "", "x", "", 1, 100), แถว("ก", "", "y", "", 1, 100)];
  const a = รวมรายจังหวัด(ชุด).ตาราง.map((x) => x.province);
  const b = รวมรายจังหวัด([...ชุด].reverse()).ตาราง.map((x) => x.province);
  assert.deepEqual(a, b, "สองจังหวัดยอดเท่ากันต้องไม่สลับที่ตามลำดับที่ฐานส่งมา");
});

test("ป้ายขอบเขตในเส้น: ยังไม่มีจังหวัดเลย ⇒ ส่ง null + บอกวิธีกวาดย้อนหลัง", async () => {
  const fs = await import("node:fs");
  const src = fs.readFileSync("netlify/functions/core.mjs", "utf8");
  // 🔑 ตารางที่ทุกแถวเป็น "(ไม่ระบุ)" หน้าตาเหมือนผลวัดที่สมบูรณ์ ⇒ ห้ามส่งออกไป
  assert.match(src, /provinces: จังหวัด\.มีจังหวัด > 0 \? จังหวัด\.ตาราง : null/);
  assert.match(src, /provinceSkipped/);
  assert.match(src, /\?sync=1&from=&to=/);
});
