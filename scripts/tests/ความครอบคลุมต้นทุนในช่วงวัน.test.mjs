// 🔴 **ที่มาของไฟล์นี้คือความผิดของผมเอง** — ผมเขียนเกณฑ์ปิดใบไว้ว่า "รอ `ครอบกี่เปอร์เซ็นต์` ถึงเกณฑ์"
//    แต่เลขนั้นคิดจากบรรทัดขายย้อนหลัง **ทั้งกระจก** (วัดจริง 98,916 บรรทัด) ซึ่งเติมต้นทุนย้อนหลัง
//    ไม่ได้ตลอดกาล ⇒ **เกณฑ์นั้นไม่มีวันถึง** และใบจะค้างถาวรโดยดูเหมือนรอข้อมูลสะสม
//    ⇒ คำถามจริงของจอคือ "ช่วงที่ฉันโชว์อยู่ มีต้นทุนครบไหม" (กฎ: เลือกประชากรตามงาน ไม่ใช่ตามเครื่องมือ)
import assert from 'node:assert/strict';
import { mock, test } from 'node:test';
import { readFileSync } from 'node:fs';

let แถวตรึง = [{ 'วันแรก': '2026-10-04', 'บรรทัดที่มีต้นทุน': 336 }];
let แถวทั้งหมด = [{ n: 98916 }];
let แถวในช่วง = [];
const ยิงไป = [];
mock.module('../../netlify/lib/coredb.mjs', {
  namedExports: {
    coreReady: () => true,
    แถวจากผล: (r) => (Array.isArray(r) ? r : (r?.results ?? [])),
    coreQuery: async (sql, params) => {
      ยิงไป.push({ sql, params });
      if (/JOIN orders o ON o\.id = i\.order_id/.test(sql)) return แถวในช่วง;
      if (/FROM order_item_cost WHERE unit_cost IS NOT NULL/.test(sql)) return แถวตรึง;
      if (/COUNT\(\*\) AS n FROM order_items/.test(sql)) return แถวทั้งหมด;
      return [];
    },
  },
});
const { วันแรกที่มีต้นทุนตรึง, เกณฑ์ครอบยอดรวม } = await import('../../netlify/lib/ต้นทุนรายรหัส.mjs');

test('① ไม่ส่งช่วงวัน ⇒ ไม่มีก้อน "ในช่วง" และต้องบอกว่าเปอร์เซ็นต์ทั้งกระจกตัดสินใจไม่ได้', async () => {
  const r = await วันแรกที่มีต้นทุนตรึง();
  assert.equal(r.ok, true);
  assert.equal(r['ในช่วง'], undefined, 'ไม่ส่งช่วงมาแล้วแต่งก้อนในช่วงให้ = เดาแทนคนเรียก');
  assert.ok(String(r['ℹ️ ไม่ได้ส่งช่วงวันมา']).includes('ใช้ตัดสินใจไม่ได้'),
    'ต้องเขียนบอกตรง ๆ ว่าเลขทั้งกระจกใช้ตัดสินใจไม่ได้ ไม่ใช่ปล่อยให้คนหยิบไปใช้');
  assert.equal(r['เกณฑ์ครอบยอดรวม'], เกณฑ์ครอบยอดรวม, 'ต้องส่งเกณฑ์ไปกับคำตอบ ให้จอไม่ต้องเขียนเลขเอง');
});

test('② 🔴 ช่วงที่ไม่มีบรรทัดขายเลย ⇒ ต้องเป็น null ทั้งคู่ — ห้ามตอบ 100 และห้ามตอบ 0', async () => {
  /* "ไม่มีของให้ครอบ" ≠ "ครอบครบ" และ ≠ "ครอบไม่ได้เลย"
     ตัวหารศูนย์แล้วตอบ 100 จะทำให้จอเปิดยอดรวมในช่วงที่ไม่มีข้อมูล (กฎ ratios-need-a-floor) */
  แถวในช่วง = [{ 'ทั้งหมด': 0, 'มีต้นทุน': 0 }];
  const r = await วันแรกที่มีต้นทุนตรึง({ from: '2026-01-01', to: '2026-01-31' });
  assert.equal(r['ในช่วง']['ครอบกี่เปอร์เซ็นต์ในช่วง'], null);
  assert.equal(r['ในช่วง']['ถึงเกณฑ์ยอดรวมไหม'], null, 'ไม่มีของให้วัด ⇒ ตอบว่าแปลไม่ได้ ไม่ใช่ตอบว่าผ่าน/ไม่ผ่าน');
});

test('③ ช่วงที่ครอบครบ ⇒ ถึงเกณฑ์ · ช่วงที่ครอบน้อย ⇒ ไม่ถึงเกณฑ์', async () => {
  แถวในช่วง = [{ 'ทั้งหมด': 200, 'มีต้นทุน': 200 }];
  let r = await วันแรกที่มีต้นทุนตรึง({ from: '2026-10-04', to: '2026-10-04' });
  assert.equal(r['ในช่วง']['ครอบกี่เปอร์เซ็นต์ในช่วง'], 100);
  assert.equal(r['ในช่วง']['ถึงเกณฑ์ยอดรวมไหม'], true);

  แถวในช่วง = [{ 'ทั้งหมด': 200, 'มีต้นทุน': 20 }];
  r = await วันแรกที่มีต้นทุนตรึง({ from: '2026-09-01', to: '2026-10-04' });
  assert.equal(r['ในช่วง']['ครอบกี่เปอร์เซ็นต์ในช่วง'], 10);
  assert.equal(r['ในช่วง']['ถึงเกณฑ์ยอดรวมไหม'], false);
});

test('④ 🔬 พลังแยกแยะ: ค่าที่อยู่ "ขอบเกณฑ์พอดี" ต้องผ่าน และต่ำกว่าหนึ่งขั้นต้องไม่ผ่าน', async () => {
  /* ด่านที่ทดสอบแต่ 100% กับ 10% จะเขียวต่อให้โค้ดเทียบด้วยเกณฑ์อะไรก็ได้ ⇒ ไม่พิสูจน์ว่าเกณฑ์ถูกใช้ */
  แถวในช่วง = [{ 'ทั้งหมด': 1000, 'มีต้นทุน': เกณฑ์ครอบยอดรวม * 10 }];          // = เกณฑ์เป๊ะ
  let r = await วันแรกที่มีต้นทุนตรึง({ from: '2026-10-01', to: '2026-10-04' });
  assert.equal(r['ในช่วง']['ครอบกี่เปอร์เซ็นต์ในช่วง'], เกณฑ์ครอบยอดรวม);
  assert.equal(r['ในช่วง']['ถึงเกณฑ์ยอดรวมไหม'], true, 'ที่เกณฑ์พอดีต้องผ่าน (>=)');

  แถวในช่วง = [{ 'ทั้งหมด': 1000, 'มีต้นทุน': เกณฑ์ครอบยอดรวม * 10 - 1 }];      // ต่ำกว่า 0.1%
  r = await วันแรกที่มีต้นทุนตรึง({ from: '2026-10-01', to: '2026-10-04' });
  assert.equal(r['ในช่วง']['ถึงเกณฑ์ยอดรวมไหม'], false, 'ต่ำกว่าเกณฑ์หนึ่งขั้นต้องไม่ผ่าน ⇒ เกณฑ์ถูกใช้จริง');
});

test('⑤ 🔑 สองธงตอบคนละคำถาม — รายบรรทัดเปิดได้แม้ยอดรวมยังไม่ถึงเกณฑ์', async () => {
  /* ยุบเป็นธงเดียวแล้วปิดทั้งคู่ = ทิ้งความจริงรายบรรทัดที่มีอยู่แล้ว
     ยุบแล้วเปิดทั้งคู่ = ยอดรวมโกหกตั้งแต่วันแรก */
  แถวตรึง = [{ 'วันแรก': '2026-10-04', 'บรรทัดที่มีต้นทุน': 336 }];
  แถวในช่วง = [{ 'ทั้งหมด': 98916, 'มีต้นทุน': 336 }];
  const r = await วันแรกที่มีต้นทุนตรึง({ from: '2026-01-01', to: '2026-10-04' });
  assert.equal(r['โชว์กำไรรายบรรทัดได้'], true, 'มีบรรทัดที่ตรึงแล้ว ⇒ โชว์กำไรบรรทัดนั้นได้');
  assert.equal(r['ในช่วง']['ถึงเกณฑ์ยอดรวมไหม'], false, 'แต่ยอดรวมของช่วงนี้ยังเชื่อไม่ได้');
});

test('⑥ คู่ตรงข้ามของ ⑤: ยังไม่เคยตรึงเลย ⇒ รายบรรทัดก็ปิด และวันแรกต้องเป็น null ไม่ใช่วันนี้', async () => {
  แถวตรึง = [{ 'วันแรก': null, 'บรรทัดที่มีต้นทุน': 0 }];
  const r = await วันแรกที่มีต้นทุนตรึง();
  assert.equal(r['โชว์กำไรรายบรรทัดได้'], false);
  assert.equal(r['วันแรก'], null, 'null = ยังไม่เริ่มตรึง ห้ามเติมเป็นวันนี้');
  แถวตรึง = [{ 'วันแรก': '2026-10-04', 'บรรทัดที่มีต้นทุน': 336 }];
});

test('⑦ 🔒 วันที่รูปแบบผิดต้องถูกทิ้ง ไม่ใช่ส่งต่อเข้า SQL', async () => {
  ยิงไป.length = 0;
  const r = await วันแรกที่มีต้นทุนตรึง({ from: "2026-10-04' OR 1=1 --", to: '2026-10-04' });
  assert.equal(r['ในช่วง'], undefined, 'วันที่ผิดรูปแบบ ⇒ ถือว่าไม่ได้ส่งช่วงมา');
  const แตะช่วง = ยิงไป.filter((x) => /JOIN orders o/.test(x.sql));
  assert.equal(แตะช่วง.length, 0, 'ต้องไม่ยิงคำสั่งช่วงวันเลยเมื่อค่าไม่ผ่านรูปแบบ');
});

test('⑧ 🔑 เกณฑ์ต้องมีแหล่งเดียว — ห้ามมีเลขนั้นเขียนตายตัวซ้ำในท่อ', async () => {
  /* กฎ one-threshold-one-source: สองที่บอกคนละเลขเรื่องเดียวกัน แย่กว่าไม่มีเกณฑ์
     ด่านนี้อ่านซอร์สจริง เพราะความผิดแบบนี้ไม่โผล่ในผลลัพธ์ของฟังก์ชันเลย */
  const lib = readFileSync('netlify/lib/ต้นทุนรายรหัส.mjs', 'utf8');
  const core = readFileSync('netlify/functions/core.mjs', 'utf8');
  const ประกาศ = (lib.match(/export const เกณฑ์ครอบยอดรวม = \d+/g) || []).length;
  assert.equal(ประกาศ, 1, 'ต้องประกาศเกณฑ์ที่เดียว');
  assert.ok(!new RegExp(`>=\\s*${เกณฑ์ครอบยอดรวม}\\b`).test(core),
    `core.mjs ห้ามเทียบ ${เกณฑ์ครอบยอดรวม} เอง ⇒ ต้องอ่านธงที่ lib คิดให้`);
  assert.ok(/เกณฑ์ครอบยอดรวม/.test(core), 'core.mjs ต้องเขียนกำกับให้จอรู้ว่าเกณฑ์อยู่ที่ไหน');
});
