/* 🔴 ด่าน: **หน้าต่างตามเก็บของกระจกค่าธรรมเนียม ต้องกว้างกว่าหน้าต่างรอบปกติมาก**
 *    (29 ก.ย. 2569 — ของจริง: ออเดอร์ 85 ใบหายจากกระจกอย่างถาวร)
 *
 * กลไกที่ทำให้หายถาวร: ใบที่พลาดรอบ (งานล้ม / คิวยาวเกิน limit / หมดเวลา)
 * จะ **อายุเกินหน้าต่างตามเก็บ** แล้วไม่มีรอบไหนไปหยิบอีกเลย
 * ⇒ และ **ไม่มีอะไรฟ้อง** เพราะทุกรอบตอบว่า "ครบแล้ว" — ครบ **ในขอบเขตของตัวเอง**
 *   (ตัวสรุปวัดความครบเทียบ 400 วัน · ตัวซิงก์เดิมดู 14 วัน ⇒ สองเลขขอบเขตคนละอัน)
 *
 * 📏 ผลจริงตอนเติมกระจกให้ครบ: 327 → 412 ใบ
 *    ⇒ ผลต่างสูตร 3,914 → **5,046 บาท** · ใบที่ต่างเกิน 2 บาท 78 → **91**
 *    ⇒ เลขบนหน้าสถานะที่เคยอ่านว่า "78 ใบ" คิดจากกระจกที่ไม่ครบ
 *
 * 🔑 และคำกล่าวอ้างที่เคยตรึงเพดานไว้ **ไม่จริง** — คอมเมนต์เดิมเขียนว่า
 *    "Shopee ปฏิเสธช่วง ≥15 วัน ⇒ 14 คือเพดานจริง ไม่ใช่เลขที่เลือกเอง"
 *    ยิงวัดแล้ว `days=120` สำเร็จ เขียน 85 ใบ ล้ม 0 ⇒ เพดานนั้นเป็นของเส้น wallet ไม่ใช่เส้นนี้
 *    ⇒ ด่านนี้จึงกันไม่ให้ใครเอาเลข 14 กลับมาโดยอ้างคำกล่าวอ้างเดิม
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด } from "./_src.mjs";

const Jไฟล์ = "netlify/functions/mkp-fees-sync.mjs";
const Mไฟล์ = "netlify/lib/mkp-finance-mirror.mjs";
const J = ซอร์สไม่เอาคอมเมนต์(Jไฟล์);
const M = ซอร์สไม่เอาคอมเมนต์(Mไฟล์);

test("🔴 รอบกวาดกว้างต้องย้อนอย่างน้อย 60 วัน (ไม่ใช่ 14)", () => {
  const m = J.match(/const WIDE_DAYS = (\d+)/);
  assert.ok(m, "ไม่เจอ WIDE_DAYS — ถ้ากลับไปฝังเลขในบรรทัดเรียก ให้เอากลับมาเป็นค่าคงที่ที่มีชื่อ");
  const วัน = Number(m[1]);
  console.log(`   🔎 ${Jไฟล์}:${เลขบรรทัด(J, J.indexOf("const WIDE_DAYS"))} WIDE_DAYS = ${วัน}`);
  assert.ok(วัน >= 60,
    `หน้าต่างตามเก็บ ${วัน} วัน แคบเกิน — ใบที่พลาดรอบจะอายุเกินหน้าต่างแล้วหายถาวร ` +
      "(ของจริง 29 ก.ย. 2569: หน้าต่าง 14 วัน ทำให้หาย 85 ใบ)");
});

test("🔴 รอบกวาดกว้างต้องใช้ `WIDE_DAYS` จริง ไม่ใช่เลขฝังในบรรทัด", () => {
  const i = J.indexOf("mirrorShopeeFees({");
  assert.ok(i > 0, "ไม่เจอการเรียก mirrorShopeeFees");
  const บรรทัด = J.slice(i, J.indexOf("\n", i));
  console.log(`   🔎 ${Jไฟล์}:${เลขบรรทัด(J, i)} ${บรรทัด.trim()}`);
  assert.match(บรรทัด, /WIDE_DAYS/,
    `บรรทัดเรียกไม่ได้ใช้ WIDE_DAYS ⇒ ค่าคงที่กับค่าที่ใช้จริงจะเพี้ยนกันได้ · ได้: ${บรรทัด.trim()}`);
  /* 🚫 เลข 14 ในบรรทัดนี้คือรูปเดิมที่ทำให้ของหาย */
  assert.ok(!/days:\s*wide\s*\?\s*14/.test(บรรทัด), "เจอ `days: wide ? 14` ⇒ กลับไปเป็นรูปเดิมที่ทำให้หาย 85 ใบ");
});

test("🔑 `WIDE_DAYS` ต้องไม่เกินเพดานของ `mirrorShopeeFees` (ไม่งั้นค่าถูกบีบเงียบ ๆ)", () => {
  /* ตัวรับบีบด้วย Math.min(120, …) ⇒ ถ้าตั้ง WIDE_DAYS = 400 มันจะถูกบีบเหลือ 120
     แล้วคนอ่านโค้ดจะเชื่อว่ากวาด 400 วัน ซึ่งไม่จริง — ค่าที่ถูกบีบเงียบคือคำกล่าวอ้างเท็จ */
  const m = M.match(/parseInt\(o\.days[^)]*\)[^;]*/);
  assert.ok(m, "อ่านสูตรบีบ days ใน mkp-finance-mirror ไม่ได้");
  const เพดาน = Number((M.match(/Math\.min\((\d+),\s*parseInt\(o\.days/) || [])[1]);
  assert.ok(Number.isFinite(เพดาน), `อ่านเพดาน days ไม่ออก · ได้: ${m[0].slice(0, 90)}`);
  const วัน = Number(J.match(/const WIDE_DAYS = (\d+)/)[1]);
  console.log(`   📏 เพดานของตัวรับ ${เพดาน} วัน · WIDE_DAYS ${วัน} วัน`);
  assert.ok(วัน <= เพดาน,
    `WIDE_DAYS ${วัน} เกินเพดาน ${เพดาน} ของตัวรับ ⇒ จะถูกบีบเงียบ ๆ แล้วคอมเมนต์จะโกหก`);
});

/** ทุกที่ที่เอ่ยถึงคำกล่าวอ้างนั้น ต้องมีคำหักล้างอยู่ใกล้ ๆ
 *  🔴 รอบแรกผมเขียนว่า "ห้ามมีประโยคนี้เลย" ⇒ **ด่านแดงกับคอมเมนต์ของผมเอง**
 *     ที่ยกคำกล่าวอ้างเดิมมา **เพื่อหักล้าง** ⇒ การยกมาหักล้าง กับ การยืนยัน หน้าตาเหมือนกัน
 *  ⇒ เกณฑ์ที่ถูกคือ "เอ่ยได้ แต่ต้องมีหลักฐานหักล้างกำกับ" ไม่ใช่ "ห้ามเอ่ย" */
function เอ่ยแล้วไม่หักล้าง(เนื้อ, วลี = "14 คือเพดานจริง", ระยะ = 500) {
  const พลาด = [];
  let i = เนื้อ.indexOf(วลี);
  while (i >= 0) {
    const ช่วง = เนื้อ.slice(Math.max(0, i - ระยะ), i + ระยะ);
    if (!/ไม่จริง|ยิงวัดแล้ว|วัดแล้ว/.test(ช่วง)) พลาด.push(i);
    i = เนื้อ.indexOf(วลี, i + 1);
  }
  return พลาด;
}

test("🚫 เอ่ยคำกล่าวอ้าง \"14 คือเพดานจริง\" ได้ **เฉพาะเมื่อมีคำหักล้างกำกับ**", () => {
  const เนื้อ = readFileSync(Jไฟล์, "utf8");
  const ครั้งที่เอ่ย = (เนื้อ.match(/14 คือเพดานจริง/g) || []).length;
  const พลาด = เอ่ยแล้วไม่หักล้าง(เนื้อ);
  console.log(`   📏 เอ่ยถึง ${ครั้งที่เอ่ย} ครั้ง · ไม่มีคำหักล้างกำกับ ${พลาด.length} ครั้ง`);
  assert.equal(พลาด.length, 0,
    "มีที่เอ่ยคำกล่าวอ้างนั้นโดยไม่มีคำหักล้างกำกับ ⇒ อ่านเหมือนยังยืนยันอยู่ " +
      "(ยิงวัดแล้ว days=120 สำเร็จ ล้ม 0 ⇒ คำกล่าวอ้างนั้นไม่จริง)");
});

test("🧪 ตัวควบคุมสองทิศ — พิสูจน์ว่าเกณฑ์ข้อบนแยกแยะได้จริง ไม่ใช่เขียวเปล่า ๆ", () => {
  const จริง = readFileSync(Jไฟล์, "utf8");
  /* ทิศบวก: ไฟล์จริงเอ่ยถึงคำกล่าวอ้างนั้นอยู่ (เพื่อหักล้าง) ⇒ เกณฑ์ต้องยังเขียว */
  assert.ok((จริง.match(/14 คือเพดานจริง/g) || []).length >= 1,
    "ไฟล์จริงควรยกคำกล่าวอ้างเดิมมาหักล้างไว้ — ไม่งั้นคนรอบหน้าจะเขียนกลับเพราะไม่รู้ว่าเคยถูกหักล้าง");
  assert.equal(เอ่ยแล้วไม่หักล้าง(จริง).length, 0, "ของจริงต้องผ่าน");
  /* ทิศลบ: ปลูกการเอ่ยแบบไม่มีคำหักล้าง ⇒ เกณฑ์ต้องจับได้ */
  const ปลูก = "// 14 คือเพดานจริง ห้ามขยาย\nconst WIDE_DAYS = 14;\n";
  assert.equal(เอ่ยแล้วไม่หักล้าง(ปลูก).length, 1,
    "ปลูกการเอ่ยแบบไม่มีคำหักล้างแล้วต้องจับได้ ⇒ พิสูจน์ว่าเกณฑ์ไม่ใช่ทอโทโลจี");
});
