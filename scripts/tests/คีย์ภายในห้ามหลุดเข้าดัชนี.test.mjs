/* คีย์ภายในของตารางจับคู่ ห้ามหลุดเข้าดัชนีที่ลูกค้าเห็น (18 ต.ค. 2569)
 *
 * ของจริงที่เกิดแล้ว: `src/data/parts-bysku.json` มี SKU ปลอม A1 · A2 · H · 0010 · 0030
 *   มาจากคีย์ `+A1T` (ค่าคือข้อความป้าย) และ `+A1#R` (ค่าคือเลขลำดับ)
 *   วันนั้นยังไม่ชนกับสินค้าจริง ⇒ **ลูกค้ายังไม่เห็นผิด แต่ไม่มีอะไรกันไว้เลย**
 *
 * 🔑 เทสนี้ตรวจ **สองชั้น**
 *   ① ตัวกรองแยกแยะได้จริง (ยิงของเสียเข้าไปดูว่ามันตีกลับ)
 *   ② ไฟล์ดัชนีที่ commit อยู่ตอนนี้ ไม่มีของปลอมค้าง
 *      ⇒ ชั้นนี้สำคัญกว่า เพราะตัวกรองถูกแต่ไฟล์เก่าค้าง = ลูกค้ายังเห็นของผิด
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { เป็นคีย์ภายใน } from "../gen-parts-bysku.mjs";

test("ตัวกรองแยกคีย์ภายในออกจากรหัสคู่มือได้", () => {
  for (const k of ["+A1T", "+H1T", "+AB12T", "+A1#R", "0010#R", "x#R"]) {
    assert.equal(เป็นคีย์ภายใน(k), true, `ควรทิ้ง: ${k}`);
  }
  /* ควบคุมลบ — ของพวกนี้ทิ้งไม่ได้ ทิ้งแล้วลูกค้าหาอะไหล่ไม่เจอ
     🔑 ไม่มีควบคุมลบ = ตัวกรองที่ทิ้งทุกอย่างก็ผ่านเทสนี้ */
  for (const k of ["00004007000", "23716324000", "108.2", "+A1", "+H1", "L7"]) {
    assert.equal(เป็นคีย์ภายใน(k), false, `ห้ามทิ้ง: ${k}`);
  }
});

test("ดัชนีที่ commit อยู่ ไม่มี SKU ปลอมจากคีย์ภายใน", () => {
  const d = JSON.parse(readFileSync("src/data/parts-bysku.json", "utf8"));
  const เสีย = [];
  for (const [sku, รายการ] of Object.entries(d)) {
    for (const x of รายการ ?? []) {
      const r = String(x?.รหัส ?? "");
      /* `+A1T` / `#R` ไม่ควรโผล่เป็น "รหัส" ได้เลย — โผล่ = ตัวกรองไม่ทำงาน */
      if (เป็นคีย์ภายใน(r)) เสีย.push(`${sku} ← ${r}`);
      /* และรหัสที่ขึ้นต้นด้วย + คือคีย์ภายใน ไม่ใช่เลขอะไหล่ในคู่มือเล่มไหน */
      if (/^\+/.test(r)) เสีย.push(`${sku} ← ${r} (คีย์ภายใน ไม่ใช่รหัสคู่มือ)`);
    }
  }
  assert.deepEqual(เสีย, [], `พบของปลอมในดัชนี:\n  ${เสีย.join("\n  ")}`);
});
