/* ด่าน: สมุดเวลางานตามเวลา (`netlify/lib/job-timing.mjs`)
 *
 * 🔴 ที่มา 19 ก.ย. 2569 (ใบ S1) — แทนวิธี "ยิงงานจริง 3 รอบเพื่อจับเวลา" ด้วยการให้งานจดเวลาตัวเอง
 *    ⇒ ของที่ต้องพิสูจน์ ไม่ใช่ว่ามันจดได้ แต่คือ **สามข้อที่ถ้าผิดจะเจ็บ**:
 *    ① จดเวลาล้ม **ห้ามลากงานจริงล้มตาม** (สมุดหายดีกว่างานสำรอง/ซิงก์ไม่ได้ทำ) แต่ต้อง **ไม่เงียบ**
 *    ② ไม่ส่งตัวตัดสินผลมา ⇒ `ไม่ได้ตัดสิน` **ห้ามกลายเป็น ok** (เขียวลวงที่ไม่มีใครจับได้)
 *    ③ งานโยน error ⇒ จด `failed` แล้ว **โยนต่อ** (ไม่งั้นการเตือน Telegram เดิมหายไปเงียบ ๆ)
 *
 * 🔑 วิธีทำให้ "จดไม่ได้" เกิดจริงในเทสโดยไม่ต้องมีตัวปลอม: **ถอน `CLOUDFLARE_D1_TOKEN`**
 *    ⇒ `coreQuery` โยนทันทีก่อนออกเน็ต ⇒ ไม่มีคำขอจริงวิ่งออกไปสักคำขอ
 *    ⚠️ ด่านนี้จึงตรวจ **ทางล้มของการจด** เท่านั้น · ทางสำเร็จของการเขียน D1 พิสูจน์ได้ที่ของจริงหลัง deploy
 *       (`/api/core?jobtiming=1` ต้องมีแถวขึ้นมาเองภายในหนึ่งชั่วโมง) — เขียนกำกับไว้เพราะ
 *       ด่านที่ไม่บอกขอบเขตของตัวเองจะถูกอ่านว่า "ครอบทั้งเรื่อง" [[partial-coverage-reported-as-full]]
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { วัดเวลางาน, จดเวลางาน, แถวที่จะจด, รอบต่อวันจากcron, ผลที่ยอมรับ } from "../../netlify/lib/job-timing.mjs";

const ไม่มีD1 = (fn) => async () => {
  const เก่า = process.env.CLOUDFLARE_D1_TOKEN;
  delete process.env.CLOUDFLARE_D1_TOKEN;
  try {
    await fn();
  } finally {
    if (เก่า !== undefined) process.env.CLOUDFLARE_D1_TOKEN = เก่า;
  }
};

test("จดเวลาไม่ได้ ⇒ คืนเหตุเป็นข้อความ ห้ามโยน (งานจริงต้องไม่ล้มตาม)", ไม่มีD1(async () => {
  const ผล = await จดเวลางาน({ งาน: "เทส", ms: 5, ผล: "ok" });
  assert.notEqual(ผล, "ok", "ไม่มี D1 แล้วยังบอกว่า ok = ตัวจดโกหก");
  assert.match(ผล, /จดไม่ได้/, "ต้องบอกเหตุออกมา ห้ามคืนค่าว่างเงียบ ๆ");
}));

test("งานยังทำจบและคืนผลลัพธ์เดิม แม้จดเวลาไม่ได้", ไม่มีD1(async () => {
  const t = await วัดเวลางาน("เทส", async () => ({ ok: true, saved: 3 }), { ตัดสินผล: () => "ok" });
  assert.deepEqual(t.ผลลัพธ์, { ok: true, saved: 3 });
  assert.ok(Number.isFinite(t.ms));
  assert.match(t.จดเวลา, /จดไม่ได้/, "ต้องรายงานกลับมาว่าจดไม่ได้ — ผู้เรียกเอาไป log ต่อ");
}));

test("ไม่ส่งตัวตัดสินผล ⇒ ค่าที่ **เขียนลงแถวจริง** ต้องเป็น 'ไม่ได้ตัดสิน' ห้าม default เป็น ok", () => {
  /* 🔑 อ่าน **ค่าที่จะถูกเขียน** ไม่ใช่รายการสถานะที่ไฟล์เดียวกันประกาศไว้
     (รุ่นแรกของด่านนี้เทียบ `ผลที่ยอมรับ` ⇒ ปลูกบั๊ก "จด ok ทุกกรณี" แล้วยังเขียว) */
  const ช่องผล = (o) => แถวที่จะจด({ งาน: "เทส", ms: 1, ...o })[3];
  assert.equal(ช่องผล({ ผล: undefined }), "ไม่ได้ตัดสิน", "ไม่รู้ผล ⇒ ห้ามกลายเป็น ok");
  assert.equal(ช่องผล({ ผล: null }), "ไม่ได้ตัดสิน");
  assert.equal(ช่องผล({ ผล: "สำเร็จมั้ง" }), "ไม่ได้ตัดสิน", "สถานะนอกรายการ ⇒ ห้ามจดดิบ ๆ");
  assert.equal(ช่องผล({ ผล: "ok" }), "ok");
  assert.equal(ช่องผล({ ผล: "failed" }), "failed");
  assert.deepEqual(ผลที่ยอมรับ, ["ok", "failed", "ไม่ได้ตัดสิน"], "ชุดสถานะเปลี่ยน = สัญญากับจอเปลี่ยน");
  // ลำดับช่องต้องตรงกับ VALUES — สลับช่องแล้วจอจะอ่าน ms เป็นสถานะ
  const แถว = แถวที่จะจด({ งาน: "ก", ms: 1234.6, ผล: "ok", note: "x" });
  assert.equal(แถว[0], "ก");
  assert.equal(แถว[2], 1235, "ms ต้องปัดเป็นจำนวนเต็ม");
  assert.equal(แถว[4], "x");
});

test("งานโยน error ⇒ ต้องโยนต่อ (การเตือน Telegram เดิมต้องยังทำงาน)", ไม่มีD1(async () => {
  await assert.rejects(
    () => วัดเวลางาน("เทส", async () => { throw new Error("ZORT ตอบ 500"); }),
    /ZORT ตอบ 500/,
    "กลืน error = คนไม่รู้ว่างานล้ม ทั้งที่เราสร้างสมุดขึ้นมาเพื่อให้รู้"
  );
}));

test("รอบต่อวันจาก cron — รูปแบบที่ไม่รองรับต้องได้ null ไม่ใช่เลขเดา", () => {
  assert.equal(รอบต่อวันจากcron("*/15 * * * *"), 96);
  assert.equal(รอบต่อวันจากcron("40 */6 * * *"), 4);
  assert.equal(รอบต่อวันจากcron("19 * * * *"), 24);
  assert.equal(รอบต่อวันจากcron("7 */3 * * *"), 8);
  assert.equal(รอบต่อวันจากcron("0 3 * * *"), 1);
  assert.equal(รอบต่อวันจากcron("5,20,35,50 * * * *"), 96);
  // 🚫 วัน/เดือน/สัปดาห์ที่ไม่ใช่ * ⇒ null — ตัวหารของ "นาที/วัน" ผิดทั้งตารางถ้าเดา
  assert.equal(รอบต่อวันจากcron("0 0 * * 1"), null);
  assert.equal(รอบต่อวันจากcron("0 0 1 * *"), null);
  assert.equal(รอบต่อวันจากcron("มั่ว"), null);
  assert.equal(รอบต่อวันจากcron(""), null);
});

test("ตัวหารของ `ครอบคลุม` ต้องเป็นช่วงที่สมุดเปิดรับจริง ไม่ใช่ช่วงที่คนถาม", () => {
  /* 🔴 เจอตอนยิงของจริง 19 ก.ย. 2569: สมุดเพิ่งเริ่มจด 25 นาที ถาม 24 ชม. ⇒ ครอบคลุม 0.04
     ⇒ ดูเหมือนรอบหาย 96% ทั้งที่ครบทุกรอบที่ควรมี ⇒ **แดงลวงที่จะถูกปิดภายในวันเดียว**
     🔑 ตรวจสูตรตรง ๆ ที่ตัวเลข ไม่ใช่ตรวจว่าโค้ดมีคำว่า "ชมที่สมุดเปิด" (นั่นคือถามซ้ำ) */
  const ควรมี = (ต่อวัน, ชมที่สมุดเปิด) => Math.max(1, Math.round((ต่อวัน * ชมที่สมุดเปิด) / 24));
  // สมุดเปิดมา 0.42 ชม. · งานทุกชั่วโมง ⇒ ควรมี 1 รอบ ไม่ใช่ 24
  assert.equal(ควรมี(24, 0.42), 1);
  assert.equal(ควรมี(96, 0.42), 2);   // งานทุก 15 นาที ⇒ 1.68 ปัดเป็น 2
  assert.equal(ควรมี(24, 24), 24);    // สมุดเปิดครบช่วง ⇒ เท่าเดิม
  assert.equal(ควรมี(4, 1), 1, "งานทุก 6 ชม. ในช่วง 1 ชม. ⇒ อย่างน้อย 1 ห้ามเป็น 0 (หารศูนย์)");
});
