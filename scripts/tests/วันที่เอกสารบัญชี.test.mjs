/* 📅 **วันที่บนเอกสารที่ส่งเข้า ZORT ต้องเป็นวันไทย ไม่ใช่วัน UTC**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 — บั๊กจริงที่ผมแก้เมื่อเช้า: `orderdate` ใช้
 *    `new Date(order.at).toISOString().slice(0,10)` = **วัน UTC**
 *    ขณะที่ `paymentdate` ในออบเจกต์เดียวกัน **คิดแบบไทยอยู่แล้ว**
 *    ⇒ ⇒ **เอกสารบัญชีใบเดียวมีสองมาตรฐานเวลา** ⇒ ออเดอร์ช่วง 00:00–07:00 ไทย
 *       จะถูกบันทึกเป็น **วันก่อนหน้า** ⇒ ยอดขายรายวันเหลื่อม
 *
 * 🔑 **ทำไมเทสนี้มีอยู่**: ผมเอา diff ของคอมมิตที่แก้บั๊กนั้นมา **ย้อนกลับ** (ท่าที่ฝั่งจอลองก่อน)
 *    ⇒ **เทสทั้ง 714 ข้อผ่านหมด** ⇒ ⇒ **ไม่มีอะไรจับบั๊กนี้เลยแม้แต่ตัวเดียว**
 *    ⇒ นั่นคือค่าของการปลูกจากประวัติ: มันหาช่องที่ **ของจริงเคยลอดผ่านมาแล้ว**
 *
 * ⚠️ **ทำไมเป็นเทสระดับซอร์ส ไม่ใช่ระดับพฤติกรรม**
 *    `zortAddOrder()` ยิง ZORT จริงและต้องมีรหัสร้าน ⇒ เรียกในเทสไม่ได้
 *    ⇒ ที่ทำได้คือตรวจว่า **ช่องวันที่ในเอกสารนั้นไม่ได้คิดจาก UTC**
 *    🚫 ข้อจำกัดที่ยอมรับ: **เทสนี้จับ "รูปที่เคยผิด" ไม่ได้จับ "ความถูกต้องของค่า"**
 *       ⇒ ถ้าใครเขียนตัวคิดวันไทยผิดเอง เทสนี้มองไม่เห็น (ตัวนั้นมีเทสของมันแยก)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const ไฟล์ = "netlify/functions/orders.mjs";
/* ช่องวันที่ที่ไปโผล่บนเอกสารบัญชีของ ZORT — เพิ่มชื่อได้เมื่อมีช่องใหม่ */
const ช่องวันที่ = ["orderdate", "paymentdate", "shippingdate", "duedate"];

test("ช่องวันที่ในเอกสาร ZORT ต้องไม่คิดจาก UTC (toISOString().slice(0,10))", () => {
  const โค้ด = ตัดคอมเมนต์(readFileSync(ไฟล์, "utf8"), ไฟล์);
  const ผิด = [];
  for (const ช่อง of ช่องวันที่) {
    /* จับรูป `<ช่อง>: <อะไรก็ได้>toISOString()...slice(0, 10)` ในบรรทัดเดียวกัน */
    const r = new RegExp(`\\b${ช่อง}\\s*:\\s*[^,\\n]*toISOString\\(\\)[^,\\n]*slice\\(\\s*0\\s*,\\s*10\\s*\\)`);
    if (r.test(โค้ด)) ผิด.push(ช่อง);
  }
  assert.deepEqual(
    ผิด, [],
    `ช่องเหล่านี้คิดวันจาก UTC: ${ผิด.join(", ")} ⇒ ใช้ \`thaiDayFromUtc()\` จาก netlify/lib/thaiday.mjs\n` +
    "   เหตุ: เซิร์ฟเวอร์รัน UTC ร้านอยู่ไทย (UTC+7) ⇒ ออเดอร์ 00:00–07:00 ไทย จะถูกบันทึกเป็นวันก่อนหน้า"
  );
});

test("🕳️ ตัวควบคุม: รูปที่เทสมองหา ต้องตรงกับรูปของบั๊กจริง", () => {
  /* ป้อนโค้ดปลอมที่เป็น **รูปของบั๊กจริงเป๊ะ** ⇒ เงื่อนไขต้องจับได้
     🔑 ถ้าข้อนี้ไม่แดงเมื่อป้อนบั๊ก แปลว่าเทสข้างบน **มองหารูปที่ไม่มีอยู่จริง** */
  const บั๊กจริง = `      orderdate: new Date(order.at).toISOString().slice(0, 10),`;
  const r = /\borderdate\s*:\s*[^,\n]*toISOString\(\)[^,\n]*slice\(\s*0\s*,\s*10\s*\)/;
  assert.ok(r.test(บั๊กจริง), "เงื่อนไขต้องจับรูปของบั๊กจริงได้ ไม่งั้นเทสข้างบนไร้ความหมาย");
  /* และต้อง **ไม่** จับท่าที่ถูก */
  assert.ok(!r.test("      orderdate: thaiDayFromUtc(order.at),"), "ท่าที่ถูกต้องต้องไม่ถูกจับ");
});
