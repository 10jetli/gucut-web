/* ด่าน: สะพานส่งบัญชีเข้า PEAK ต้องแยก "อ่านคำตอบไม่ได้" ออกจาก "ส่งไม่สำเร็จ"
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · เจอตอนกวาดคลาส `?? []` บนข้อมูลนอกบ้าน (49 จุดในท่อ)
 *    ของเดิม: `const rows = box.invoices ?? []`
 *    ⇒ PEAK ตอบ 200 แต่รูปคำตอบเปลี่ยน ⇒ `rows = []`
 *    ⇒ ได้ `ok: 0, failed: []` = **"ไม่มีอะไรสำเร็จ และไม่มีอะไรล้ม"** (สถานะที่เป็นไปไม่ได้)
 *      · ใครเช็ค `failed.length === 0` อ่านว่า **เรียบร้อย**
 *      · ใครเช็ค `ok` อ่านว่า **ล้มหมด**
 *    ⇒ **นี่คือสะพานส่งยอดขายเข้าบัญชี/ภาษี** ⇒ ผิดทางนี้แพงกว่าจอเพี้ยน
 *
 * 🔴 และปลายทางเดิมเขียน `r.ok ? 200 : r.failed?.length ? 502 : 400`
 *    ⇒ ส่ง 5 ใบ สำเร็จ 3 ล้ม 2 ⇒ `ok` = 3 = truthy ⇒ **ตอบ 200 แล้วกลืน 2 ใบที่ล้ม**
 *    ⇒ อ่านคำตอบไม่ได้ ⇒ ตอบ **400** = "คำขอคุณผิด" ⇒ **ชี้ไปผิดทาง**
 *      (คนจะไปไล่หาว่ากรอกอะไรผิด ทั้งที่คำขอถูก เราอ่านคำตอบเขาไม่ได้เอง)
 * 🔑 กติกา: **จำนวน ห้ามใช้เป็นจริง/เท็จ** — ต้องมีฟิลด์ที่มีความหมายเดียวให้ปลายทางตัดสิน
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { สรุปผลส่งPEAK } from "../../netlify/lib/peak.mjs";

test("🧪 รูปคำตอบเปลี่ยน ⇒ ต้องบอกว่าอ่านไม่ได้ และ ok ต้องเป็น null ไม่ใช่ 0", () => {
  for (const box of [{}, null, undefined, { invoices: null }, { invoices: "ไม่ใช่อาเรย์" }]) {
    const r = สรุปผลส่งPEAK(5, box);
    assert.equal(r.สรุป, "อ่านคำตอบของ PEAK ไม่ได้");
    assert.equal(r.ok, null, "ok ต้องเป็น null — 0 อ่านว่า 'ส่งไม่สำเร็จเลย' ซึ่งเราไม่รู้");
    assert.equal(r.failed, null, "failed ต้องเป็น null — [] อ่านว่า 'ไม่มีใบไหนล้ม' ซึ่งเราไม่รู้");
    assert.equal(r.อ่านคำตอบได้, false);
    assert.equal(r.sent, 5, "ต้องยังบอกว่าเราส่งไปกี่ใบ");
  }
});

test("🔑 พลังแยกแยะ: สำเร็จครบ ⇒ ต้องเป็น 'สำเร็จครบทุกใบ' เท่านั้น", () => {
  const r = สรุปผลส่งPEAK(2, { invoices: [{ resCode: "200" }, { resCode: "200" }] });
  assert.equal(r.สรุป, "สำเร็จครบทุกใบ");
  assert.equal(r.ok, 2);
  assert.deepEqual(r.failed, []);
});

test("🔴 สำเร็จบางส่วน ต้องไม่ถูกอ่านว่าสำเร็จ — นี่คือเคสที่เคยตอบ 200 แล้วกลืนใบที่ล้ม", () => {
  const r = สรุปผลส่งPEAK(3, {
    invoices: [{ resCode: "200" }, { resCode: "400", resDesc: "ซ้ำ" }, { resCode: "200" }],
  });
  assert.equal(r.สรุป, "สำเร็จบางส่วน");
  assert.equal(r.ok, 2);
  assert.equal(r.failed.length, 1);
  assert.equal(r.failed[0].desc, "ซ้ำ", "ต้องบอกเหตุผลของใบที่ล้ม ไม่ใช่บอกแค่จำนวน");
  /* 🔑 ข้อสำคัญ: `ok` เป็น truthy ในเคสนี้ ⇒ ปลายทางที่ใช้ `ok ? สำเร็จ : ล้ม` จะผิด
     ⇒ ด่านนี้ล็อกไว้ว่า `สรุป` ต้องไม่ใช่ "สำเร็จครบทุกใบ" */
  assert.notEqual(r.สรุป, "สำเร็จครบทุกใบ");
});

test("ล้มทั้งหมด ⇒ แยกจาก 'สำเร็จบางส่วน' และจาก 'อ่านไม่ได้'", () => {
  const r = สรุปผลส่งPEAK(2, { invoices: [{ resCode: "400" }, { resCode: "500" }] });
  assert.equal(r.สรุป, "ล้มทั้งหมด");
  assert.equal(r.ok, 0, "ที่นี่ 0 ถูกต้อง เพราะเราอ่านคำตอบได้และรู้ว่าไม่มีใบไหนผ่าน");
});

test("PEAK ตอบมาไม่ครบจำนวนใบ ⇒ ต้องมีสถานะของตัวเอง", () => {
  /* ส่ง 3 ตอบ 1 — ถ้าไม่มีสถานะนี้ จะถูกอ่านว่า "สำเร็จครบทุกใบ" เพราะใบที่ตอบมาผ่านหมด
     ⇒ อีกสองใบหายไปเงียบ ๆ จากบัญชี */
  const r = สรุปผลส่งPEAK(3, { invoices: [{ resCode: "200" }] });
  assert.equal(r.สรุป, "PEAK ตอบมาไม่ครบจำนวนใบที่ส่ง");
  assert.equal(r.ตอบกลับมากี่ใบ, 1);
});

test("คำอธิบายต้องห้ามปลายทางเอา `ok` ไปตีเป็นจริง/เท็จ", () => {
  const r = สรุปผลส่งPEAK(1, { invoices: [{ resCode: "200" }] });
  const ช่วย = String(r["🔑 ปลายทางอ่านยังไง"] || "");
  assert.match(ช่วย, /ห้ามเอา `ok` ไปตี/, "ต้องเตือนเรื่องนี้ไว้ในคำตอบเอง");
  assert.match(ช่วย, /null/, "ต้องบอกความหมายของ null");
});
