/* ด่าน: สัญญาของประวัติเครดิตต้องมีแหล่งเดียว และ **เกณฑ์ต้องตามรอบเก็บจริง**
 *
 * 🔴 ที่มา 19 ก.ย. 2569 (สองข้อ)
 *    ① เช้านี้ผมเขียน `ประวัติKEY` กับ `เก็บกี่จุด` ไว้ **สองไฟล์** (ตัวเก็บ + ตัวอ่าน)
 *       ⇒ วันหนึ่งมีคนแก้ที่เดียว ⇒ ตัวเก็บเขียนคีย์หนึ่ง ตัวอ่านอ่านอีกคีย์
 *       ⇒ ตัวอ่านเห็นประวัติว่าง ⇒ อัตราเป็น `null` ⇒ **อ่านว่า "ยังไม่พอ" ซึ่งเป็นคำตอบที่ปกติมาก**
 *       ⇒ ไม่มีอะไรฟ้องเลย · นี่คือเหตุที่ต้องเป็นด่าน ไม่ใช่ความระวัง
 *    ② ฝั่งจอขอเอง: *"ขอให้ท่อส่งเกณฑ์มาด้วย ถ้าผมฝัง 3 ไว้ในจอ เราจะได้เลขเกณฑ์สองที่อีกรอบ
 *       ⇒ วันไหนคุณเปลี่ยนรอบเก็บ เกณฑ์จะตามเอง"* ⇒ เกณฑ์ต้อง **คิดจากรอบเก็บ** ไม่ใช่เลขที่พิมพ์ทิ้ง
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import {
  ประวัติKEY, เก็บกี่จุด, ชั่วโมงต่อรอบเก็บ, พลาดกี่รอบถึงเรียกว่าตาย, เกณฑ์เก่าเกินชั่วโมง, เวลาISO,
} from "../../netlify/lib/credit-history.mjs";

test("cron ของตัวเก็บต้องตรงกับ `ชั่วโมงต่อรอบเก็บ` ที่ประกาศไว้", () => {
  const src = readFileSync("netlify/functions/credit-sample.mjs", "utf8");
  const m = src.match(/schedule:\s*"([^"]+)"/);
  assert.ok(m, "หา cron ในตัวเก็บไม่เจอ");
  const [นาที, ชม] = m[1].split(/\s+/);
  /* รูป "53 * * * *" = ทุกชั่วโมง ⇒ ชั่วโมงต่อรอบเก็บ ต้องเป็น 1 */
  assert.match(นาที, /^\d+$/, "นาทีต้องเป็นเลขเดียว ไม่ใช่ทุกนาที");
  if (ชม === "*") {
    assert.equal(ชั่วโมงต่อรอบเก็บ, 1,
      `cron เก็บทุกชั่วโมง แต่ประกาศว่า ${ชั่วโมงต่อรอบเก็บ} ชม./รอบ ⇒ เกณฑ์ที่ส่งให้จอจะผิด`);
  } else {
    const ทุกกี่ชม = Number((ชม.match(/\*\/(\d+)/) || [])[1]);
    assert.equal(ชั่วโมงต่อรอบเก็บ, ทุกกี่ชม,
      "เปลี่ยน cron แล้วต้องเปลี่ยน `ชั่วโมงต่อรอบเก็บ` ให้ตรง — ไม่งั้นเกณฑ์ที่จอใช้จะผิด");
  }
});

test("เกณฑ์ต้องคิดจากรอบเก็บ ไม่ใช่เลขที่พิมพ์ทิ้งไว้", () => {
  assert.equal(เกณฑ์เก่าเกินชั่วโมง, ชั่วโมงต่อรอบเก็บ * พลาดกี่รอบถึงเรียกว่าตาย);
  assert.ok(พลาดกี่รอบถึงเรียกว่าตาย >= 2,
    "ต้องยอมให้พลาดได้อย่างน้อย 2 รอบ — Netlify เลื่อน/ข้ามงานตามเวลาได้เอง " +
    "เกณฑ์ที่ร้องตั้งแต่พลาดรอบแรก = ร้องใส่ของปกติ แล้วคนจะเลิกอ่านคำเตือน");
});

test("ทั้งตัวเก็บและตัวอ่านต้องนำเข้าสัญญาจากไฟล์กลาง ห้ามประกาศคีย์เอง", () => {
  for (const f of ["netlify/functions/credit-sample.mjs", "netlify/functions/netlify-credits.mjs"]) {
    const src = readFileSync(f, "utf8");
    assert.match(src, /from "\.\.\/lib\/credit-history\.mjs"/, `${f} ต้อง import สัญญาจากไฟล์กลาง`);
    assert.doesNotMatch(src, /const\s+ประวัติKEY\s*=/,
      `${f} ประกาศคีย์เอง ⇒ วันหนึ่งจะไม่ตรงกับอีกไฟล์ แล้วประวัติจะว่างแบบเงียบ`);
    assert.doesNotMatch(src, /"netlify-credits-history"/,
      `${f} เขียนชื่อคีย์เป็นข้อความตรง ๆ ⇒ ต้องใช้ตัวแปรจากไฟล์กลางเท่านั้น`);
  }
});

test("เวลาISO: ไม่มีค่า ⇒ null ห้ามคืนเวลาปัจจุบัน", () => {
  /* 🚫 ฝั่งจอกำชับข้อนี้: ถ้าไม่มีตัวอย่างแล้วส่งเวลาปัจจุบัน จอจะเห็นว่า "สด" ตลอดกาล */
  for (const v of [0, null, undefined, "", NaN, -5, "ไม่ใช่เลข"]) assert.equal(เวลาISO(v), null);
  assert.match(เวลาISO(1789792604819), /^\d{4}-\d{2}-\d{2}T.*Z$/);
});

test("ค่าที่ประกาศต้องสมเหตุสมผล", () => {
  assert.equal(ประวัติKEY, "netlify-credits-history");
  assert.ok(เก็บกี่จุด >= 24, "ต้องเก็บพอให้หน้าต่างกว้างกว่าหนึ่งวัน — อัตราจากชั่วโมงเดียวหลอกตา");
});
