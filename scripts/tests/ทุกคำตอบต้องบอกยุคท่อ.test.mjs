/* 🕰️ ด่าน: **ทุกคำตอบของ `/api/core` ต้องติดหัว `x-core-build` — ไม่ใช่ "เกือบทุกคำตอบ"**
 *
 * 🔴 ที่มา 21 ก.ย. 2569 — ฝั่งจอเสนอให้คู่มือเขียนว่า "วิธีรู้ว่า deploy แล้วหรือยัง มีสามทาง"
 *    ผมไปตรวจทางที่ถูกที่สุด (หัว `x-core-build`) ด้วยการยิงของจริง 6 เส้น แล้วพบว่า
 *    **`?ping=1` เป็นเส้นเดียวที่ไม่มีหัวนี้** — และมันคือเส้นที่คนจะใช้เช็คยุคมากที่สุด
 *    เพราะเบาที่สุดและ **ไม่ต้องมีรหัส**
 * 🔑 ทิศของความเสียหาย: **หัวหาย อ่านได้ว่า "ท่อรุ่นเก่า"** ⇒ แดงลวงที่ชี้ไปทางเดียวกับปัญหาที่เรากลัว
 *    ⇒ คนจะไป deploy ซ้ำ/ไล่หาเหตุที่ไม่มี [[probe-fails-toward-alarm]]
 * 🔴 และคอมเมนต์ที่อยู่ติดกับโค้ดนั้นเอง **เขียนว่า** *"`build` ติดอยู่ในหัว `x-core-build`
 *    ของทุกคำตอบอยู่แล้ว"* ⇒ **คำกล่าวอ้างที่เท็จสำหรับเส้นที่มันอยู่** [[stale-state-comments]]
 *
 * 📏 ตะแกรง: `new Response(` **ดิบ** ในไฟล์นั้น (ตัวที่ผ่านตัวช่วย `json()`/`okJson()`
 *    ได้หัวจากส่วนกลางอยู่แล้ว) ⇒ ทุกตัวต้องมี `x-core-build` ในก้อนของตัวเอง
 * 🚫 เพดาน **0 และห้ามขึ้น** — ตัวใหม่ที่ลืมใส่ ต้องทำให้ตก ไม่ใช่รอให้คนไปยิงเจอ
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const ไฟล์ = fileURLToPath(new URL("../../netlify/functions/core.mjs", import.meta.url));
const โค้ด = ตัดคอมเมนต์(readFileSync(ไฟล์, "utf8"), ไฟล์);

/** คืนตำแหน่งของ `new Response(` ที่ไม่มี `x-core-build` ในก้อน 500 ตัวอักษรถัดไป */
function ที่ไม่บอกยุค(s) {
  const out = [];
  const re = /new Response\(/g;
  let m;
  while ((m = re.exec(s))) {
    if (!/x-core-build/.test(s.slice(m.index, m.index + 500))) {
      out.push(s.slice(0, m.index).split("\n").length);
    }
  }
  return out;
}

test("ตะแกรงต้องเห็น `new Response(` ดิบมากพอ — เจอน้อย = ตะแกรงพัง ไม่ใช่โค้ดดีขึ้น", () => {
  const ทั้งหมด = (โค้ด.match(/new Response\(/g) || []).length;
  assert.ok(ทั้งหมด >= 5, `ต้องเจออย่างน้อย 5 จุด (เจอ ${ทั้งหมด})`);
});

test("🔒 ทุก `new Response(` ดิบ ต้องติดหัว `x-core-build` (เพดาน 0)", () => {
  const ขาด = ที่ไม่บอกยุค(โค้ด);
  assert.deepEqual(
    ขาด, [],
    `🔴 คำตอบที่ไม่บอกยุคของท่อ ${ขาด.length} จุด (บรรทัด ${ขาด.join(" · ")})\n` +
    "   ⇒ หัวหาย = จออ่านว่า 'ท่อรุ่นเก่า' ⇒ แดงลวงทิศเดียวกับปัญหาที่เรากลัว",
  );
});

test("🔑 `?ping=1` ต้องมีหัวนี้ด้วย — เส้นที่ไม่ต้องใช้รหัส คือเส้นที่คนใช้เช็คยุคจริง", () => {
  const i = โค้ด.indexOf('searchParams.get("ping")');
  assert.ok(i > 0, "หากิ่ง ping ไม่เจอ ⇒ ตะแกรงพัง");
  const กิ่ง = โค้ด.slice(i, i + 800);
  assert.match(กิ่ง, /x-core-build/, "กิ่ง ping ต้องส่งหัวยุคกลับมา");
  /* 🚫 และห้ามเติมฟิลด์อื่นลงเส้นนี้ — มันเปิดให้คนนอกอ่านได้ (ข้อห้ามเดิมในไฟล์นั้น) */
  assert.doesNotMatch(กิ่ง, /orders|stock|revenue|ยอดขาย/, "ห้ามเอาข้อมูลร้านมาเกาะเส้น ping");
});

test("🔬 พลังแยกแยะ: ถอดหัวออกจากกิ่งใดกิ่งหนึ่ง ⇒ ด่านต้องแดง", () => {
  const ปลอม = โค้ด.replace(/"x-core-build": CORE_BUILD,?/, "");
  assert.notEqual(ปลอม, โค้ด, "ของปลูกต้องเปลี่ยนเนื้อจริง");
  const ขาด = ที่ไม่บอกยุค(ปลอม);
  assert.ok(ขาด.length >= 1, "ตะแกรงต้องเห็นกิ่งที่ถูกถอดหัวออก");
});
