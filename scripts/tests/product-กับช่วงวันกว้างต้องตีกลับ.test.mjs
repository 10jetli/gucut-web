/* ทดสอบ: **กลไกเพดานช่วงวัน** ของ `list=orders` — ไม่ใช่ตัวเลขเพดาน
 *
 * 🔴 ที่มาของการเขียนใหม่ (16 ต.ค. 2569) — ไฟล์นี้ **กลับด้านสี่ครั้งในวันเดียว**:
 *    รอบ 1 เช้า : "ช่วงกว้างเพียว ๆ ต้องผ่าน"  (วัดได้ 200 ที่ 11.3 วิ)
 *    รอบ 2 สาย : "ต้องถูกตีกลับ"              (วัดได้ 500 ที่ 16.5 วิ สองนัด)
 *    รอบ 3 บ่าย: "ต้องผ่าน" อีกครั้ง           (ฝั่งจอแย้ง ⇒ เจอว่าเป็นดัชนีของ `source` ที่ขาด)
 *    รอบ 4 เย็น: ยกเพดานของ `product=` ออกด้วย (เติมดัชนีแล้ว ของหนักสุดเหลือ +1.2 วิ)
 * 🔑 **บทเรียน**: เทสที่ตรึง "ตัวเลขเพดาน" จะต้องถูกแก้ทุกครั้งที่เรารู้มากขึ้น
 *    และทุกครั้งที่แก้เทสเพื่อให้ตามโค้ด **พลังจับบั๊กจะหายไปเงียบ ๆ**
 *    ⇒ ตรึง **กลไก** แทน: "ถ้าประกาศเพดานไว้ ต้องบังคับและต้องอธิบาย · ถ้าไม่ประกาศ ต้องไม่บังคับ"
 *    ⇒ เปลี่ยนเลขเพดานได้โดยไม่ต้องแตะเทสนี้ แต่ **ถอดกลไกไม่ได้**
 *
 * 📏 ประวัติผลวัดที่ทำให้ตัดสินใจแต่ละรอบ อยู่ในคอมเมนต์ของ `param-guard.mjs` และ `coredb.mjs`
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { badParamError, เพดานช่วงวันของรายการขาย as เพดาน } from "../../netlify/lib/param-guard.mjs";

const คำขอ = (o) => new URLSearchParams({ list: "orders", ...o });
/** สร้างช่วงวันยาว N วันพอดี (นับปลายทั้งสองข้าง) */
const ช่วงยาว = (วัน) => {
  const เริ่ม = new Date("2026-01-01T00:00:00Z");
  const จบ = new Date(เริ่ม.getTime() + (วัน - 1) * 864e5);
  return { from: "2026-01-01", to: จบ.toISOString().slice(0, 10) };
};

test("ช่วงยาว N วันพอดี คิดถูก (ตัวช่วยของเทสเองต้องเชื่อถือได้ก่อน)", () => {
  assert.deepEqual(ช่วงยาว(1), { from: "2026-01-01", to: "2026-01-01" });
  assert.deepEqual(ช่วงยาว(366), { from: "2026-01-01", to: "2027-01-01" });
});

for (const [ชื่อ, คีย์, พารามเสริม] of [
  ["ช่วงวันเพียว ๆ", "เพดานวัน", {}],
  ["ช่วงวัน + product=", "เพดานวันเมื่อมีproduct", { product: "00894" }],
]) {
  test(`${ชื่อ}: ประกาศเพดานไว้ ⇒ ต้องบังคับ · ไม่ประกาศ (null) ⇒ ต้องไม่บังคับ`, () => {
    const ค่า = เพดาน[คีย์];
    assert.ok(ค่า === null || Number.isInteger(ค่า), `${คีย์} ต้องเป็นจำนวนเต็มหรือ null (ได้ ${ค่า})`);

    if (ค่า === null) {
      /* null = **ไม่มีเพดาน** ⇒ ช่วงยาวมากต้องผ่าน
         ⚠️ ข้อนี้กันบั๊กที่เจ็บที่สุดของการใช้ null: `วัน > null` เป็นจริงเมื่อ วัน > 0
            ⇒ ถ้าเทียบตรง ๆ จะตีกลับ **ทุกคำขอ** = ตรงข้ามกับเจตนาเป๊ะ */
      assert.equal(badParamError(คำขอ({ ...พารามเสริม, ...ช่วงยาว(9000) })), null,
        "ไม่ประกาศเพดาน แต่ยังตีกลับ ⇒ น่าจะเทียบกับ null ตรง ๆ");
      assert.equal(badParamError(คำขอ({ ...พารามเสริม, ...ช่วงยาว(1) })), null);
      return;
    }

    // ขอบล่าง: เท่าเพดานพอดีต้องผ่าน · เกินหนึ่งวันต้องไม่ผ่าน (กัน > เป็น >= และกันกลับด้าน)
    assert.equal(badParamError(คำขอ({ ...พารามเสริม, ...ช่วงยาว(ค่า) })), null, `${ค่า} วันพอดีต้องผ่าน`);
    const err = badParamError(คำขอ({ ...พารามเสริม, ...ช่วงยาว(ค่า + 1) }));
    assert.ok(err, `${ค่า + 1} วันต้องถูกตีกลับ`);
    /* เหตุต้องมีสามอย่าง ไม่ใช่แค่คำว่า "เกิน": เลขที่ขอมา · เพดาน · ทางแก้
       (เคยพลาด: ข้อความไม่บอกเลขที่ผู้เรียกขอ แล้วเทสยังเขียวเพราะไปแมตช์เลขในประโยคอ้างผลวัด) */
    assert.match(err, new RegExp(`\\b${ค่า + 1}\\b`), "เหตุต้องบอกจำนวนวันของคำขอนี้");
    assert.match(err, new RegExp(`${ค่า}\\s*วัน`), "เหตุต้องบอกเพดาน");
    assert.match(err, /แบ่งเป็นช่วง/, "เหตุต้องบอกทางแก้ ไม่ใช่บอกแค่ว่าผิด");
  });
}

test("เพดานต้องมีแหล่งเดียว และถูกส่งออกไปให้จออ่าน", () => {
  /* 🔴 ที่มา: ฝั่งจอเอาเลขที่ผม **วัดได้** (654 วัน) ไปฝังในจอ 2 จุดภายในชั่วโมงเดียวกัน
     เพราะท่อไม่มีอะไรให้อ่าน ⇒ เลขแยกร่างทันทีที่ท่อขยับ และไม่มีอะไรฟ้อง */
  const orders = readFileSync("netlify/lib/core-orders.mjs", "utf8");
  assert.match(orders, /ขอบเขตช่วงวัน: เพดานช่วงวันของรายการขาย/, "คำตอบต้องส่งเพดานออกไป");
  const guard = readFileSync("netlify/lib/param-guard.mjs", "utf8");
  assert.ok(!/เพดานวัน = \d/.test(guard), "ด่านต้องอ่านจากค่าที่ประกาศ ไม่ใช่เลขดิบ");
  assert.ok(เพดาน.ช่วงวันที่แนะนำ > 0, "ต้องมีค่าที่แนะนำ — เพดานไม่ใช่เส้นที่ควรวิ่งไปจ่อ");
  assert.match(เพดาน.ที่มา, /วัด/, "ต้องมีที่มาของเลขกำกับ");
  /* ดัชนีที่เป็นต้นเหตุจริงของ 500 ต้องอยู่ในสคีมา — ไม่ใช่แก้ด้วยเพดานแล้วลืมต้นเหตุ */
  const db = readFileSync("netlify/lib/coredb.mjs", "utf8");
  for (const ดัชนี of ["idx_orders_source_date", "idx_orders_number_source"]) {
    assert.ok(db.includes(ดัชนี), `ขาดดัชนี ${ดัชนี} ⇒ ต้นเหตุของ 500 กลับมาได้`);
  }
});

test("ด่านวันที่ตัวอื่นต้องไม่ถูกกระทบ", () => {
  assert.match(badParamError(คำขอ({ from: "2026-10-16", to: "2026-01-01" })), /ต้องไม่มากกว่า/);
  assert.match(badParamError(คำขอ({ from: "2026-13-45" })), /วันที่จริง/);
  assert.equal(badParamError(คำขอ({ product: "00894", from: "2020-01-01" })), null, "มีขาเดียวไม่ตัดสิน");
});
