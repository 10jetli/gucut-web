/* ทดสอบ: `product=` + ช่วงวันกว้างเกินเพดาน ⇒ ต้องตีกลับพร้อมเหตุ (ไม่ใช่ปล่อยให้ 500 ที่ 15 วินาที)
 *
 * 🔴 ที่มา (16 ต.ค. 2569 · ใบ t_mva0li5s) — วัดเองกับฐานจริง ยิงคนเดียวไม่มีคำขออื่นพร้อมกัน:
 *    289 วัน + product ⇒ 200 ที่ 3.3 วิ · 2,192 วัน + product ⇒ **500 ที่ 15.4 วิ** · 26 ปี ⇒ timeout
 *    และช่วง 4 ปี **ไม่มี** product ⇒ 200 ที่ 11.3 วิ ⇒ ตัวที่พาไปชนคือ **คู่** ของสองอย่าง
 *
 * ⚠️ เพดาน 400 **ไม่ใช่หน้าผาที่วัดได้** — รู้แค่ 289 รอด / 2,192 ไม่รอด
 *    เลือก 400 เพราะครอบตัวเลือกยาวสุดของจอ (ย้อนหลัง 1 ปี = 366 วัน) โดยยังห่างค่าที่ไม่รอด 5 เท่า
 * 🔑 เทสนี้ต้องจับ **ทั้งสองทิศ** ไม่ใช่ทิศเดียว:
 *    ① product + ช่วงเกินเพดาน ⇒ ต้องมีข้อความตีกลับ
 *    ② ช่วงกว้างเท่ากัน **แต่ไม่มี product** ⇒ **ต้องผ่าน** (ของจริงรอด — ห้ามไปปิดของที่ใช้ได้)
 *    ③ product + ช่วงในเพดาน ⇒ ต้องผ่าน (ไม่งั้นจอขายกรองสินค้าไม่ได้เลย)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { badParamError } from "../../netlify/lib/param-guard.mjs";

const คำขอ = (o) => new URLSearchParams({ list: "orders", ...o });

test("① product + ช่วงหลายปี ⇒ ตีกลับ และเหตุต้องบอกทั้งเลขวันและทางแก้", () => {
  const err = badParamError(คำขอ({ product: "00894", from: "2020-01-01", to: "2025-12-31" }));
  assert.ok(err, "ช่วง 2,192 วันพร้อม product ต้องถูกตีกลับ");
  assert.match(err, /product/, "เหตุต้องบอกว่าเกี่ยวกับตัวกรอง product");
  /* ⚠️ **ข้อนี้เคยไม่แยกแยะ และการปลูกบั๊กจับได้** (16 ต.ค. 2569)
     เดิมเขียน `/\d{3,}\s*วัน/` ⇒ ผ่านแม้ตัดเลขวันของผู้เรียกออกจากข้อความ
     เพราะไปแมตช์เลขในประโยคอ้างผลวัด ("2,192 วัน") และเพดาน ("ไม่เกิน 400 วัน")
     ⇒ เทสบอกว่า "ตรวจแล้วว่าบอกจำนวนวันที่ขอมา" ทั้งที่ไม่เคยตรวจ
     🔑 ต้องยึด **ค่าของคำขอนี้จริง ๆ**: 2020-01-01→2025-12-31 = 2192 วัน (ไม่มีจุลภาค)
        ซึ่งต่างจาก "2,192" ในประโยคอ้างผลวัด ⇒ ตัดเลขผู้เรียกออกแล้วเทสต้องแดง */
  assert.match(err, /\b2192\b/, "เหตุต้องบอกจำนวนวันของคำขอนี้ (2192) ไม่ใช่แค่คำว่าเกิน");
  assert.match(err, /เพดาน 400 วัน/, "มี product ⇒ เพดานต้องเป็น 400 ไม่ใช่ 731");
  assert.match(err, /ตัวกรองสินค้า/, "เหตุต้องบอกว่าเพดานนี้เป็นของตัวกรองสินค้า");
});

test("② ช่วงกว้างเพียว ๆ ⇒ **ต้องผ่าน** เพราะวัดได้ว่าทำงานได้ (และห้ามใส่เพดานทับ)", () => {
  /* 🔴 **ข้อนี้กลับด้านสองครั้งในวันเดียว — จดไว้ทั้งสองครั้งโดยตั้งใจ**
     รอบ 1 (เช้า): ตรึงว่า "ต้องผ่าน" เพราะวัดได้ 200 ที่ 11.3 วิ
     รอบ 2 (สาย): เปลี่ยนเป็น "ต้องถูกตีกลับ" เพราะวัดได้ 500 ที่ 16.5 วิ สองนัดติด
     รอบ 3 (บ่าย · อันนี้): กลับมาเป็น "ต้องผ่าน" เพราะฝั่งจอส่งข้อมูลมาแย้ง แล้วผมยิงตรวจเจอว่า
        📏 ไม่พิน store ⇒ **200 ที่ 8.0–8.3 วิ** (57,235 ใบ) · พิน store=z1 ⇒ **500 ที่ 15.3 วิ**
        ⇒ กรองให้แถวน้อยลงแล้วตาย = **ไม่มีดัชนีของ `source`** ไม่ใช่ความกว้างของช่วง
     🔑 บทเรียนที่ต้องไม่หายไปกับการแก้เทส: **ผลวัดที่ติดขอบ ใช้ตั้งกฎไม่ได้**
        สองรอบแรกผมตั้งกฎจากตัวอย่างนัดเดียวทั้งคู่ · รอบนี้ถึงมีตัวควบคุมที่แยกสองสาเหตุออกจากกัน
     ⚠️ ใครจะใส่เพดานช่วงวันเพียว ๆ กลับมา ต้องวัด **ทั้งพินร้านและไม่พินร้าน** ก่อน
        ไม่งั้นจะไปปิดคำขอที่ทำงานได้ที่ 8 วินาที */
  assert.equal(badParamError(คำขอ({ from: "2020-01-01", to: "2025-12-31" })), null,
    "ช่วงกว้างเพียว ๆ วัดได้ว่าทำงานได้ (8 วิ) ⇒ ห้ามตีกลับ");
  assert.equal(badParamError(คำขอ({ from: "2022-01-01", to: "2026-10-16" })), null);
});

test("③ product + ช่วงในเพดาน ⇒ ต้องผ่าน", () => {
  assert.equal(badParamError(คำขอ({ product: "00894", from: "2026-01-01", to: "2026-10-16" })), null);
  // ขอบเพดานพอดี 400 วัน ต้องผ่าน · 401 วันต้องไม่ผ่าน (กันเขียน > เป็น >= หรือกลับด้าน)
  assert.equal(badParamError(คำขอ({ product: "x", from: "2026-01-01", to: "2027-02-04" })), null, "มี product: 400 วันพอดีต้องผ่าน");
  assert.ok(badParamError(คำขอ({ product: "x", from: "2026-01-01", to: "2027-02-05" })), "มี product: 401 วันต้องไม่ผ่าน");
  /* ไม่มีเพดานของช่วงเพียว ๆ แล้ว ⇒ ช่วงยาวมากก็ต้องผ่านถ้าไม่มี product */
  assert.equal(badParamError(คำขอ({ from: "2000-01-01", to: "2026-10-16" })), null, "ช่วง 26 ปี ไม่มี product ⇒ ต้องผ่าน");
});

test("④ ไม่มีช่วงวันครบสองข้าง ⇒ ด่านนี้ไม่ตัดสิน (ปล่อยให้ด่านอื่นว่าไป)", () => {
  /* ⚠️ ถ้าด่านนี้ไปตัดสินตอนมีแค่ from หรือแค่ to มันจะคำนวณวันจาก undefined
     แล้วได้ NaN ⇒ `NaN > 400` เป็น false ⇒ ผ่านโดยบังเอิญ · ตรึงไว้ว่าเจตนาคือ "ไม่ตัดสิน" */
  assert.equal(badParamError(คำขอ({ product: "00894", from: "2020-01-01" })), null);
  assert.equal(badParamError(คำขอ({ product: "00894", to: "2026-10-16" })), null);
});

test("⑤ เพดานต้องมีแหล่งเดียว และต้องถูกส่งออกไปให้จออ่าน", async () => {
  /* 🔴 ที่มา (16 ต.ค. 2569): ฝั่งจอเอาเลขที่ผม **วัดได้** (654 วัน) ไปฝังในจอ 2 จุด
     ภายในชั่วโมงเดียวกัน เพราะท่อไม่มีอะไรให้อ่าน ⇒ วันที่ท่อขยับเพดาน จอจะยังใช้เลขเก่าเงียบ ๆ
     🔑 เทสนี้ตรึงสองอย่าง: ① ด่านกับคำตอบอ่านค่าชุดเดียวกัน ② คำตอบส่งค่านั้นออกไปจริง */
  const { เพดานช่วงวันของรายการขาย: เพดาน } = await import("../../netlify/lib/param-guard.mjs");
  const { readFileSync } = await import("node:fs");

  /* null = ไม่มีเพดาน (ต่างจาก 0 และต่างจาก "ยังไม่รู้") — ถอนออกเพราะวัดได้ว่าช่วงกว้างทำงานได้ */
  assert.equal(เพดาน.เพดานวัน, null, "ช่วงวันเพียว ๆ ต้องไม่มีเพดาน");
  assert.equal(เพดาน.เพดานวันเมื่อมีproduct, 400);
  /* ⚠️ เพดานต้องมากกว่าค่าที่แนะนำเสมอ — ถ้าเท่ากัน จอจะวิ่งไปจ่อเส้นที่ตีกลับพอดี
     และ 654 ที่วัดว่ารอด รอดที่ 7.7 วิ จากขอบ ~15 วิ ⇒ ค่าแนะนำต้องต่ำกว่านั้น */
  assert.ok(เพดาน.ช่วงวันที่แนะนำ < 654, "ค่าที่แนะนำต้องต่ำกว่า 654 (ค่าที่วัดว่ารอดแบบเฉียดฉิว)");
  assert.ok(เพดาน.ช่วงวันที่แนะนำ < เพดาน.เพดานวันเมื่อมีproduct, "ค่าที่แนะนำต้องต่ำกว่าเพดานของ product");
  assert.match(เพดาน.ที่มา, /16 ต\.ค\. 2569/, "ต้องมีที่มาของเลขกำกับ");

  const orders = readFileSync("netlify/lib/core-orders.mjs", "utf8");
  assert.match(orders, /ขอบเขตช่วงวัน: เพดานช่วงวันของรายการขาย/, "คำตอบต้องส่งเพดานออกไปให้จออ่าน");
  const guard = readFileSync("netlify/lib/param-guard.mjs", "utf8");
  /* 🚫 ห้ามมีเลขดิบในเงื่อนไขของด่าน — มีแล้วคือสองแหล่งทันที */
  assert.ok(!/เพดานวัน = \d/.test(guard), "ด่านต้องอ่านจากค่าที่ประกาศ ไม่ใช่เลขดิบ");
  /* ดัชนีที่เป็นต้นเหตุจริงต้องอยู่ในสคีมา — ไม่ใช่แก้ด้วยเพดานแล้วลืมต้นเหตุ */
  const db = readFileSync("netlify/lib/coredb.mjs", "utf8");
  assert.match(db, /idx_orders_source_date ON orders\(source, order_date\)/,
    "ต้องมีดัชนี (source, order_date) — ต้นเหตุจริงของ 500 ตอนพินร้าน");
});
