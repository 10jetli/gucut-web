/* ทดสอบ: `product=` + ช่วงวันกว้างเกินเพดาน ⇒ ต้องตีกลับพร้อมเหตุ (ไม่ใช่ปล่อยให้ 500 ที่ 15 วินาที)
 *
 * 🔴 ที่มา (16 ต.ค. 2569 · ใบ t_mva0li5s) — วัดเองกับฐานจริง ยิงคนเดียวไม่มีคำขออื่นพร้อมกัน:
 *    289 วัน + product ⇒ 200 ที่ 3.3 วิ · 2,192 วัน + product ⇒ **500 ที่ 15.4 วิ** · 26 ปี ⇒ timeout
 *    และช่วง 4 ปี **ไม่มี** product ⇒ 200 ที่ 11.3 วิ ⇒ ตัวที่พาไปชนคือ **คู่** ของสองอย่าง
 *
 * ⚠️ เพดาน 400 **ไม่ใช่หน้าผาที่วัดได้** — รู้แค่ 289 รอด / 2,192 ไม่รอด
 *    เลือก 400 เพราะครอบตัวเลือกยาวสุดของจอ (ย้อนหลัง 1 ปี = 366 วัน) โดยยังห่างค่าที่ไม่รอด 5 เท่า
 * 🔑 เทสนี้ต้องจับ **ทั้งสองทิศ** ไม่ใช่ทิศเดียว:
 *    ① product + ช่วงเกินเพดาน ⇒ ต้องมีข้อความตีกลับ
 *    ② ช่วงกว้างเท่ากัน **แต่ไม่มี product** ⇒ **ต้องผ่าน** (ของจริงรอด — ห้ามไปปิดของที่ใช้ได้)
 *    ③ product + ช่วงในเพดาน ⇒ ต้องผ่าน (ไม่งั้นจอขายกรองสินค้าไม่ได้เลย)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { badParamError } from "../../netlify/lib/param-guard.mjs";

const คำขอ = (o) => new URLSearchParams({ list: "orders", ...o });

test("① product + ช่วงหลายปี ⇒ ตีกลับ และเหตุต้องบอกทั้งเลขวันและทางแก้", () => {
  const err = badParamError(คำขอ({ product: "00894", from: "2020-01-01", to: "2025-12-31" }));
  assert.ok(err, "ช่วง 2,192 วันพร้อม product ต้องถูกตีกลับ");
  assert.match(err, /product/, "เหตุต้องบอกว่าเกี่ยวกับตัวกรอง product");
  /* ⚠️ **ข้อนี้เคยไม่แยกแยะ และการปลูกบั๊กจับได้** (16 ต.ค. 2569)
     เดิมเขียน `/\d{3,}\s*วัน/` ⇒ ผ่านแม้ตัดเลขวันของผู้เรียกออกจากข้อความ
     เพราะไปแมตช์เลขในประโยคอ้างผลวัด ("2,192 วัน") และเพดาน ("ไม่เกิน 400 วัน")
     ⇒ เทสบอกว่า "ตรวจแล้วว่าบอกจำนวนวันที่ขอมา" ทั้งที่ไม่เคยตรวจ
     🔑 ต้องยึด **ค่าของคำขอนี้จริง ๆ**: 2020-01-01→2025-12-31 = 2192 วัน (ไม่มีจุลภาค)
        ซึ่งต่างจาก "2,192" ในประโยคอ้างผลวัด ⇒ ตัดเลขผู้เรียกออกแล้วเทสต้องแดง */
  assert.match(err, /\b2192\b/, "เหตุต้องบอกจำนวนวันของคำขอนี้ (2192) ไม่ใช่แค่คำว่าเกิน");
  assert.match(err, /เพดาน 400 วัน/, "มี product ⇒ เพดานต้องเป็น 400 ไม่ใช่ 731");
  assert.match(err, /ตัวกรองสินค้า/, "เหตุต้องบอกว่าเพดานนี้เป็นของตัวกรองสินค้า");
});

test("② ช่วงกว้างเพียว ๆ ก็ต้องถูกตีกลับ — แต่ด้วยเพดานคนละค่า (731 วัน)", () => {
  /* 🔴 **ข้อนี้กลับด้านจากรอบแรกของวันเดียวกัน** (16 ต.ค. 2569)
     รอบเช้าเขียนว่า "ไม่มี product ⇒ ต้องผ่าน" เพราะวัดได้ 200 ที่ 11.3 วิ
     📏 วัดใหม่เว้นจังหวะ ยิงคนเดียว: 1,750 วัน ⇒ **500 ที่ 16.5 วิ สองนัดติด**
        และ **ตัวกรองไม่ช่วย** — ชื่อลูกค้าที่ไม่มีจริงก็ 500 ที่ 15.4 วิ เท่ากัน
     ⇒ ของเดิมที่ผมเรียกว่า "ใช้งานได้อยู่ทุกวัน" **พังอยู่แล้วตอนนี้**
     ⇒ 400 จึงไม่ได้ทำให้ใครเสียของที่ใช้ได้ (ฝั่งจอยืนยันและยินยอม)
     🔑 บทเรียน: เทสที่ตรึง "ต้องผ่าน" ไว้บนผลวัดนัดเดียวที่ติดขอบ จะกลายเป็นตัวขัดขวางการแก้ */
  const err = badParamError(คำขอ({ from: "2020-01-01", to: "2025-12-31" }));
  assert.ok(err, "ช่วง 2,192 วันแม้ไม่มี product ก็ต้องถูกตีกลับ");
  assert.match(err, /เพดาน 731 วัน/, "ต้องใช้เพดาน 731 เมื่อไม่มีตัวกรองสินค้า");
  assert.match(err, /17 คำสั่ง/, "เหตุต้องบอกตัวคูณจริง (x-d1-count = 17) ไม่ใช่บอกลอย ๆ ว่าหนัก");
  // และช่วงที่วัดว่ารอด (654 วัน) ต้องยังผ่าน — ไม่งั้นเราปิดของที่ใช้ได้จริง
  assert.equal(badParamError(คำขอ({ from: "2025-01-01", to: "2026-10-16" })), null, "654 วันวัดแล้วรอด ต้องไม่ถูกตีกลับ");
});

test("③ product + ช่วงในเพดาน ⇒ ต้องผ่าน", () => {
  assert.equal(badParamError(คำขอ({ product: "00894", from: "2026-01-01", to: "2026-10-16" })), null);
  // ขอบเพดานพอดี 400 วัน ต้องผ่าน · 401 วันต้องไม่ผ่าน (กันเขียน > เป็น >= หรือกลับด้าน)
  assert.equal(badParamError(คำขอ({ product: "x", from: "2026-01-01", to: "2027-02-04" })), null, "มี product: 400 วันพอดีต้องผ่าน");
  assert.ok(badParamError(คำขอ({ product: "x", from: "2026-01-01", to: "2027-02-05" })), "มี product: 401 วันต้องไม่ผ่าน");
  /* ขอบของเพดานไม่มีสินค้า — กันเขียน > เป็น >= หรือสลับค่าเพดานสองตัว */
  assert.equal(badParamError(คำขอ({ from: "2026-01-01", to: "2028-01-01" })), null, "ไม่มี product: 731 วันพอดีต้องผ่าน");
  assert.ok(badParamError(คำขอ({ from: "2026-01-01", to: "2028-01-02" })), "ไม่มี product: 732 วันต้องไม่ผ่าน");
});

test("④ ไม่มีช่วงวันครบสองข้าง ⇒ ด่านนี้ไม่ตัดสิน (ปล่อยให้ด่านอื่นว่าไป)", () => {
  /* ⚠️ ถ้าด่านนี้ไปตัดสินตอนมีแค่ from หรือแค่ to มันจะคำนวณวันจาก undefined
     แล้วได้ NaN ⇒ `NaN > 400` เป็น false ⇒ ผ่านโดยบังเอิญ · ตรึงไว้ว่าเจตนาคือ "ไม่ตัดสิน" */
  assert.equal(badParamError(คำขอ({ product: "00894", from: "2020-01-01" })), null);
  assert.equal(badParamError(คำขอ({ product: "00894", to: "2026-10-16" })), null);
});
