import assert from 'node:assert/strict';
import test from 'node:test';
import { สรุปที่เลือก } from '../../src/lib/parts-core.mjs';

const ทั้งหมด = { A: { sku: '04382', title: 'โซ่', price: 1250, image: null, handle: 'x', st: 5 } };

test('🔑 Infinity ⇒ ข้ามแถว (เคสที่แยกของเก่า/ของใหม่ออกจากกันได้)', () => {
  assert.deepEqual(สรุปที่เลือก({ A: Infinity }, ทั้งหมด), { รายการ: 0, ชิ้น: 0, เงิน: 0 });
  assert.deepEqual(สรุปที่เลือก({ A: -Infinity }, ทั้งหมด), { รายการ: 0, ชิ้น: 0, เงิน: 0 });
});

test('ค่าปกติยังทำงานเหมือนเดิม (ตัวควบคุมลบ — ไม่ใช่ว่าแก้แล้วอะไรก็เป็น 0)', () => {
  assert.deepEqual(สรุปที่เลือก({ A: 2 }, ทั้งหมด), { รายการ: 1, ชิ้น: 2, เงิน: 2500 });
  for (const v of [NaN, '1,234', -5, undefined, null, '', {}])
    assert.deepEqual(สรุปที่เลือก({ A: v }, ทั้งหมด), { รายการ: 0, ชิ้น: 0, เงิน: 0 }, `ค่า ${String(v)}`);
});

test('ทุกเลขที่คืนต้องเป็นจำนวนจำกัด — ห้ามมีค่าที่ JSON แปลงเป็น null', () => {
  for (const v of [Infinity, -Infinity, 1e400, 3])
    for (const [ช่อง, เลข] of Object.entries(สรุปที่เลือก({ A: v }, ทั้งหมด))) {
      assert.ok(Number.isFinite(เลข), `ช่อง ${ช่อง} จากค่า ${String(v)} ต้องเป็นจำนวนจำกัด (ได้ ${เลข})`);
      /* ล็อกอาการบนจอด้วย ไม่ใช่ล็อกแค่ชนิดข้อมูล — สองช่องนี้เรนเดอร์คนละทาง
         (JSX ดิบ ⇒ String() · Price ⇒ toLocaleString) ⇒ ต้องไม่มีทางไหนพิมพ์ Infinity/∞/NaN ออกจอ */
      assert.doesNotMatch(String(เลข), /Infinity|∞|NaN/, `ช่อง ${ช่อง} จะพิมพ์ออกจอเป็น ${String(เลข)}`);
      assert.doesNotMatch(เลข.toLocaleString('th-TH'), /Infinity|∞|NaN/, `ช่อง ${ช่อง} ผ่าน Price จะได้ ${เลข.toLocaleString('th-TH')}`);
    }
});
