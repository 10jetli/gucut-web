/* ด่านของทะเบียนขอบเขตค่า — กันทะเบียนค้างเงียบ
 *
 * 🔑 ทำไมต้องกวาดซอร์ส: ตระกูลชื่อนี้ **งอกใหม่เรื่อย ๆ** (truncated · truncatedByTime ·
 *    diffTruncated · hiddenTruncated · listedNoStockTruncated · unknownOnChannelTruncated)
 *    ⇒ ทะเบียนที่พิมพ์มือจะค้างภายในไม่กี่วันแน่นอน แล้วให้ความมั่นใจที่ไม่มีฐาน
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { ขอบเขตค่า, ชื่อที่ประกาศแล้ว, ขอบเขตของค่าที่ส่งไป } from "../../netlify/lib/value-scope.mjs";

/* ⚠️ ผูกกับ **รูปของชื่อ** โดยตั้งใจ (ไม่ใช่รายชื่อตายตัว) — ชื่อใหม่ในตระกูลนี้จะถูกจับเอง
   ถ้าเขียนเป็นรายชื่อตายตัว ด่านจะเขียวตลอดกาลเมื่อมีคนตั้งชื่อใหม่ */
const รูปชื่อในตระกูล = /\b([a-zA-Z]*[Tt]runcated[a-zA-Z]*|sliced[a-zA-Z]*|paging[A-Z][a-zA-Z]*|next(?:Offset|Page)|limitClamped|declaredTotal|byStatus[a-zA-Z]*|returnedCount|rowsFetched)\b/g;

function กวาดชื่อจากซอร์ส(ราก = "netlify") {
  const เจอ = new Set();
  const เดิน = (d) => {
    for (const f of readdirSync(d)) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) { เดิน(p); continue; }
      if (!/\.(mjs|js)$/.test(f)) continue;
      /* ตัดคอมเมนต์ออกก่อน — ชื่อที่ถูกพูดถึงในคำอธิบายไม่ใช่ชื่อที่ถูกส่งออกจริง
         (ไม่ตัด = ด่านจะฟ้องชื่อที่มีแต่ในคอมเมนต์ ซึ่งเป็นแดงลวง และแดงลวงแพงกว่าเขียวลวง) */
      const s = readFileSync(p, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
      /* เอาเฉพาะรูปที่ "ถูกส่งออกจริง": `ชื่อ:` ในออบเจกต์ หรือ `.ชื่อ =` */
      for (const m of s.matchAll(/(?:^|[\s{,(])([a-zA-Z][\w]*)\s*:/gm)) {
        if (String(m[1]).match(รูปชื่อในตระกูล)) เจอ.add(m[1]);
      }
      for (const m of s.matchAll(/\.([a-zA-Z][\w]*)\s*=[^=]/g)) {
        if (String(m[1]).match(รูปชื่อในตระกูล)) เจอ.add(m[1]);
      }
    }
  };
  เดิน(ราก);
  return เจอ;
}

test("ชื่อในตระกูลที่ท่อส่งออกจริง ต้องประกาศขอบเขตไว้ทุกตัว", () => {
  const ในซอร์ส = กวาดชื่อจากซอร์ส();
  const ขาด = [...ในซอร์ส].filter((n) => !ชื่อที่ประกาศแล้ว.includes(n)).sort();
  assert.deepEqual(
    ขาด, [],
    "มีชื่อที่ท่อส่งออกแต่ไม่ได้ประกาศว่าเป็น 'คำขอนี้' หรือ 'ทั้งชุด' — เพิ่มลง ขอบเขตค่า: " + ขาด.join(", ") +
      "\n  (ปลายทางที่เดาผิดจะขึ้นคำเตือนถาวรทั้งที่ไม่มีปัญหา แล้วคนเลิกเชื่อคำเตือนอื่นในจอเดียวกัน)",
  );
});

test("ทุกแถวต้องเป็น 'คำขอนี้' หรือ 'ทั้งชุด' และต้องอธิบายว่าคืออะไร", () => {
  for (const [k, v] of Object.entries(ขอบเขตค่า)) {
    assert.ok(["คำขอนี้", "ทั้งชุด"].includes(v.ขอบเขต), `${k}: ขอบเขตต้องเป็น คำขอนี้/ทั้งชุด`);
    assert.ok(v.คือ && v.คือ.length > 10, `${k}: ต้องบอกว่าค่านี้ตอบคำถามอะไร`);
  }
});

test("แนบเฉพาะคีย์ที่มีอยู่จริงในคำตอบ — ไม่ยัดคีย์ที่ไม่เกี่ยว", () => {
  const r = ขอบเขตของค่าที่ส่งไป({ rows: [], truncated: true, byStatus: {} });
  assert.equal(r.truncated, "คำขอนี้");
  assert.equal(r.byStatus, "ทั้งชุด");
  assert.ok(!("sliced" in r), "คีย์ที่คำตอบไม่มี ต้องไม่ถูกยัดเข้ามา");
  /* ไม่มีคีย์ในตระกูลเลย ⇒ ต้องคืน null ไม่ใช่ออบเจกต์ว่าง
     (ออบเจกต์ว่างอ่านได้ว่า "ตรวจแล้วไม่มีปัญหา" ซึ่งคนละอย่างกับ "ไม่เกี่ยวกับเส้นนี้") */
  assert.equal(ขอบเขตของค่าที่ส่งไป({ rows: [] }), null);
});

test("คำอธิบายต้องเตือนกับดักจริงที่เจอมา (limit=1 ⇒ truncated จริงเสมอ)", () => {
  const r = ขอบเขตของค่าที่ส่งไป({ truncated: false });
  const ข้อความ = Object.entries(r).filter(([k]) => k.includes("อ่านยังไง")).map(([, v]) => v).join(" ");
  /* ผูกกับ **เจตนา** ไม่ใช่ถ้อยคำ — ต้องมีทั้ง "คำเตือนถาวร" และ "ห้ามใช้เป็นคุณสมบัติของข้อมูล" */
  assert.ok(/ตลอดกาล|ถาวร/.test(ข้อความ), "ต้องเตือนว่าอ่านผิดแล้วได้คำเตือนที่ไม่มีวันหาย");
  assert.ok(/ห้าม/.test(ข้อความ), "ต้องบอกตรง ๆ ว่าห้ามเอาค่า 'คำขอนี้' ไปแสดงเป็นคุณสมบัติของข้อมูล");
});

