/* 🗜️ ด่าน: **ค่าที่ถูกบีบต้องบอกเหตุกลับไป** (ฝั่งจอขอ 28 ก.ย. 2569 · รูป `{asked, used, why}`)
 *
 * 🔴 ที่มาของงานนี้คือบั๊กบนจอ `/import` ของฝั่งจอเอง:
 *    พิมพ์ค่านอกช่วงแล้วกดบันทึก ⇒ ระบบใช้ค่าเดิมเงียบ ๆ ตอบ `ok:true`
 *    และ **ช่องกรอกยังโชว์เลขที่พิมพ์ไป** ⇒ คนตั้งราคาขายจากเกณฑ์ที่ไม่มีอยู่จริง
 *    🔑 แรงกว่าคลาส "ตัวกรองถูกเมิน" เพราะ **จอเป็นพยานยืนยันความเชื่อผิด** ⇒ ไม่มีอะไรให้สงสัย
 *
 * ⚠️ `applied` (ที่ท่อมีอยู่แล้ว) บอกได้แค่ "ใช้ค่าอะไร" — ไม่ได้บอก "ทำไมไม่ใช่ค่าที่ส่งมา"
 *    ⇒ ถ้าจอเขียนเหตุเอง จะเกิดคำอธิบายชุดที่สอง (คลาสเดียวกับ `srcNote`)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { บีบเลข, ก้อนการบีบ } from "../../netlify/lib/บีบค่า.mjs";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด } from "./_src.mjs";

const ขอบlimit = { ต่ำสุด: 1, สูงสุด: 200, ปริยาย: 50, หน่วย: "แถว" };

test("เกินเพดาน ⇒ บีบ + บอกเหตุครบสามอย่าง (asked · used · why)", () => {
  const r = บีบเลข("limit", 99999, ขอบlimit);
  assert.equal(r.ใช้, 200);
  assert.deepEqual(Object.keys(r.บันทึก).sort(), ["asked", "used", "why"]);
  assert.equal(r.บันทึก.asked, 99999, "ต้องเก็บค่าที่ผู้เรียกส่งมาจริง ⇒ จอบอกคนใช้ได้ว่าพิมพ์อะไรไป");
  assert.match(r.บันทึก.why, /เพดาน.*200/, "เหตุต้องบอกขอบที่แท้จริง ไม่ใช่แค่ว่า 'ค่าผิด'");
});

test("ต่ำกว่าขั้นต่ำ ⇒ บีบขึ้น + บอกเหตุ", () => {
  const r = บีบเลข("limit", 0, ขอบlimit);
  assert.equal(r.ใช้, 1);
  assert.match(r.บันทึก.why, /ต่ำสุด/);
});

test("อ่านเป็นเลขไม่ได้ ⇒ ใช้ค่าปริยาย **และต้องบอก** (ห้ามเงียบ)", () => {
  const r = บีบเลข("limit", "abc", ขอบlimit);
  assert.equal(r.ใช้, 50);
  assert.ok(r.บันทึก, "ค่าขยะที่ตกไปใช้ปริยายต้องถูกรายงาน — ไม่งั้นคือบั๊กเดิมของจอ /import เป๊ะ");
  assert.equal(r.บันทึก.asked, "abc");
});

test("เศษทศนิยมก็ถือว่าบีบ — ส่ง 1.9 แล้วได้ 1 ต้องรู้", () => {
  const r = บีบเลข("limit", 1.9, ขอบlimit);
  assert.equal(r.ใช้, 1);
  assert.match(r.บันทึก.why, /จำนวนเต็ม/);
});

test("🔑 **ไม่ได้ส่งมา ≠ ถูกบีบ** — ต้องไม่รายงาน ไม่งั้นทุกคำขอจะมีบันทึกเต็มไปหมด", () => {
  for (const ว่าง of [null, undefined, "", "   "]) {
    const r = บีบเลข("limit", ว่าง, ขอบlimit);
    assert.equal(r.ใช้, 50, `${JSON.stringify(ว่าง)} ⇒ ใช้ค่าปริยาย`);
    assert.equal(r.บันทึก, null,
      "ไม่ส่งมาแล้วรายงานว่าถูกบีบ = ตัวเตือนที่ร้องใส่ของปกติ ⇒ คนจะเลิกอ่าน");
  }
  assert.equal(บีบเลข("limit", 50, ขอบlimit).บันทึก, null, "ค่าที่อยู่ในขอบอยู่แล้วต้องไม่ถูกรายงาน");
});

test("🔑 ไม่มีการบีบ ⇒ **ไม่มีคีย์เลย** (ไม่ใช่คีย์ว่าง) ⇒ ปลายทางเช็คง่าย", () => {
  assert.equal(ก้อนการบีบ({ a: null, b: null }), undefined);
  const ก้อน = ก้อนการบีบ({ limit: { asked: 99999, used: 200, why: "x" }, offset: null });
  assert.deepEqual(Object.keys(ก้อน.clamped), ["limit"], "ช่องที่ไม่ถูกบีบต้องไม่โผล่ในก้อน");
  assert.match(ก้อน["⚠️ อ่านยังไง"], /บีบ ≠ ปฏิเสธ/,
    "ต้องเขียนกำกับให้ชัด — ค่าที่ท่อไม่ยอมรับเลยต้องตอบ 400 ไม่ใช่มาอยู่ในก้อนนี้");
});

/* ── ต่อสายของจริง: เขียนแล้วไม่มีใครเรียก = เท่ากับไม่มี ── */
const ไฟล์ = "netlify/lib/core-stock.mjs";
const โค้ด = ซอร์สไม่เอาคอมเมนต์(ไฟล์);

test("🔌 `list=stock` ต้องใช้ตัวบีบกลาง และส่งก้อนการบีบออกไป", () => {
  const i = โค้ด.indexOf("บีบเลข(");
  assert.ok(i > 0, "ยังไม่มีใครเรียกตัวบีบกลาง ⇒ เขียนเสร็จแล้วไม่ต่อสาย = เท่ากับไม่มี");
  console.log(`   🔎 ${ไฟล์}:${เลขบรรทัด(โค้ด, i)} เรียกตัวบีบกลาง`);
  assert.match(โค้ด, /\.\.\.\(การบีบ \?\? \{\}\)/, "ต้องใส่ก้อนการบีบลงคำตอบ — คิดแล้วไม่ส่งออก จอมองไม่เห็น");
  /* 🔑 **ต้องครบทุกเส้นที่จอใช้ชิ้นส่วนกลางอ่าน** — เส้นเดียวรายงาน อีกสองเส้นเงียบ
     ⇒ จอจะอ่านความเงียบว่า "ไม่มีการบีบ" = คลาสเดิมที่งานนี้เกิดมาแก้ */
  const เงียบ = [...โค้ด.matchAll(/const (limit|offset|days|soldDays) = Math\.(max|min)\(/g)]
    .map((m) => `${ไฟล์}:${เลขบรรทัด(โค้ด, m.index)} ${m[0]}`);
  assert.deepEqual(เงียบ, [], `ยังมีการบีบแบบเงียบ ๆ ค้างอยู่:\n- ${เงียบ.join("\n- ")}`);
  const กี่เส้น = (โค้ด.match(/\.\.\.\(การบีบ \?\? \{\}\)|\.\.\.\(ก้อนการบีบ\(/g) || []).length;
  console.log(`   📏 เส้นที่รายงานการบีบแล้ว: ${กี่เส้น}`);
  assert.ok(กี่เส้น >= 3, `ควรครบทั้ง list=stock · deadstock · stockcard · ได้ ${กี่เส้น}`);
});

test("🏷️ ต้องส่งแผนที่ป้ายของ `src` มาที่เดียว — ไม่ใช่ติดไปทุกแถว และไม่ใช่ให้จอแปลเอง", () => {
  const i = โค้ด.indexOf("srcLabels:");
  assert.ok(i > 0, "ขาดแผนที่ป้าย ⇒ จอจะโชว์คำว่า mirror ดิบ ๆ ให้คนแพ็กของอ่าน");
  console.log(`   🔎 ${ไฟล์}:${เลขบรรทัด(โค้ด, i)} แผนที่ป้ายของ src`);
  const ก้อน = โค้ด.slice(i, i + 800);
  for (const k of ["mirror", "licensed"]) assert.ok(ก้อน.includes(`${k}:`), `ขาดป้ายของ ${k}`);
  assert.match(ก้อน, /ไม่ตรงกับ ZORT เป็นเรื่องปกติ/, "ป้าย licensed ต้องบอกเรื่องนี้");
  assert.ok(!/ถูกต้อง|ผิด|แม่นกว่า/.test(ก้อน),
    "ป้ายบอก **แหล่งของตัวเลข** ห้ามตัดสินว่าเลขไหนถูก");
});
