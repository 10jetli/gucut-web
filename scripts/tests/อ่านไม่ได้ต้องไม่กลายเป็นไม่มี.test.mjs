import assert from 'node:assert/strict';
import { mock, test } from 'node:test';

/* ถังปลอมที่ **สั่งให้พังได้** — นี่คือหัวใจ เพราะทางที่ต้องตรวจคือทางที่ของพัง
   (ถังที่พังไม่ได้ ทำให้เทสเดินได้แค่ทางที่ถูกอยู่แล้ว) */
let พฤติกรรม = { throwOnGet: false, ค่า: null, throwOnSet: false };
const เรียก = { setJSON: 0 };
mock.module('@netlify/blobs', {
  namedExports: {
    getStore: () => ({
      async get() {
        if (พฤติกรรม.throwOnGet) throw new Error('Blobs สะดุด (จำลอง)');
        return พฤติกรรม.ค่า;
      },
      async setJSON(k, v) {
        เรียก.setJSON++;
        if (พฤติกรรม.throwOnSet) throw new Error('เขียนไม่ได้ (จำลอง)');
        พฤติกรรม.ค่า = v;
      },
      async delete() {},
    }),
  },
});

const points = await import('../../netlify/lib/points.mjs');
const coupons = await import('../../netlify/lib/coupons.mjs');

const ตั้ง = (x) => { พฤติกรรม = { throwOnGet: false, ค่า: null, throwOnSet: false, ...x }; };

test('กติกาแต้ม: อ่านไม่ได้ ⇒ ทางเงินต้อง **โยน** · ทางแสดงผลต้องบอกว่าไม่รู้', async () => {
  ตั้ง({ throwOnGet: true });
  /* ทางเงิน — ถ้าไม่โยน แปลว่ามีใครเอา readLoyalty กลับไปใช้ หรือใส่ catch ทับ */
  await assert.rejects(() => points.อ่านกติกาแบบเข้ม(), /.*/,
    'อ่านกติกาแบบเข้ม ต้องโยนเมื่ออ่านไม่ได้ — คืนค่าเริ่มต้นคือการเดาเรื่องเงิน');
  /* ทางแสดงผล — คืนค่าได้ แต่ต้องติดป้ายว่าไม่รู้ */
  const cfg = await points.readLoyalty();
  assert.equal(cfg.unknown, true, 'readLoyalty ต้องแนบ unknown: true');
});

test('🔴 ร้านที่ปิดระบบแต้ม (on:false) ต้องไม่กลายเป็นเปิดเอง — ทั้งตอนอ่านได้และอ่านไม่ได้', async () => {
  ตั้ง({ ค่า: { on: false } });
  const ปกติ = await points.readLoyalty();
  assert.equal(ปกติ.on, false, 'อ่านได้แล้วต้องได้ on:false ตามที่ร้านตั้ง');
  assert.equal(ปกติ.unknown, false);
  const เข้ม = await points.อ่านกติกาแบบเข้ม();
  assert.equal(เข้ม.on, false, 'ทางเงินต้องเห็น on:false ด้วย');

  /* 🔑 ตัวควบคุมของความผิดตัวจริง: `DEFAULTS.on` เป็น true
     ⇒ ถ้าใครเผลอกลับไป `{ ...DEFAULTS }` ตอนอ่านไม่ได้ ข้อนี้จะจับได้ */
  assert.equal(points.DEFAULTS.on, true,
    'สมมติฐานของเทสนี้: ค่าเริ่มต้นเป็น true ⇒ การคืนค่าเริ่มต้นตอนไม่รู้ = เปิดระบบให้เอง');
  ตั้ง({ throwOnGet: true });
  const ไม่รู้ = await points.readLoyalty();
  assert.equal(ไม่รู้.unknown, true,
    'อ่านไม่ได้แล้วต้องไม่มีใครเอา on ไปใช้ได้โดยไม่เห็นธง unknown');
});

test('โค้ดส่วนลด: ทางเขียนต้องโยน ไม่ใช่กลืนเป็น [] แล้วเขียนทับ', async () => {
  ตั้ง({ throwOnGet: true });
  const s = coupons.couponStore();
  await assert.rejects(() => coupons.readCouponsForWrite(s), /.*/,
    'readCouponsForWrite ห้ามมี catch — ไม่งั้นเขียน [] ทับโค้ดทุกใบ');
  await assert.rejects(() => coupons.นับโควตาโค้ด('SAVE'), /.*/,
    'นับโควตาโค้ด ต้องโยน ⇒ ผู้เรียกจะไม่ติดธงว่าทำแล้ว');
  /* ทางอ่านของหน้าเช็คเอาต์ยังต้องไม่ล้ม (ทิศนี้ตั้งใจให้กลืน) */
  assert.deepEqual(await coupons.readCoupons(s), [], 'ทางอ่านยังต้องกลืนเป็น [] ไม่ล้มหน้าเช็คเอาต์');
});

test('🔴 อ่านรายชื่อโค้ดไม่ได้ ⇒ ต้องแยก "ไม่เจอ" ออกจาก "ตรวจไม่ได้"', async () => {
  ตั้ง({ throwOnGet: true });
  const s = coupons.couponStore();
  const r = await coupons.อ่านโค้ดพร้อมสถานะ(s);
  assert.equal(r.อ่านไม่ได้, true, 'store โยน ⇒ ต้องรายงานว่าอ่านไม่ได้');

  /* ไม่มีคีย์ = ร้านยังไม่เคยสร้างโค้ด ⇒ **ไม่ใช่** อ่านไม่ได้
     🔑 สองกรณีนี้ `s.get()` คืนค่าแยกกันไม่ได้ (null ทั้งคู่) ถ้าไม่ปล่อยให้ throw */
  ตั้ง({ ค่า: null });
  const ว่างจริง = await coupons.อ่านโค้ดพร้อมสถานะ(s);
  assert.equal(ว่างจริง.อ่านไม่ได้, false, 'ไม่มีคีย์ = ไม่มีโค้ดจริง ห้ามรายงานว่าอ่านไม่ได้');
});

test('🔴 ถ้อยคำ: "ตรวจไม่ได้" ห้ามพูดว่าโค้ดไม่มี/ผิด/หมดอายุ — และต้องต่างจากคำว่า "ไม่เจอ"', () => {
  const ตรวจไม่ได้ = coupons.ตรวจโค้ดไม่ได้();
  assert.equal(ตรวจไม่ได้.ok, false, 'ตรวจไม่ได้ ⇒ ยังไม่ให้ส่วนลด (ทิศของเงินต้องไม่เปลี่ยน)');
  assert.equal(ตรวจไม่ได้.ตรวจไม่ได้, true, 'ต้องมีธงให้จอแยกกรณีได้ ไม่ใช่ให้จอเดาจากข้อความ');
  for (const คำห้าม of ['ไม่มีโค้ด', 'โค้ดผิด', 'หมดอายุ', 'ใช้ครบ']) {
    assert.ok(!ตรวจไม่ได้.error.includes(คำห้าม),
      `ข้อความ "ตรวจไม่ได้" ห้ามมีคำว่า "${คำห้าม}" — เราไม่รู้ และการเดาผิดทางนี้ไล่ลูกค้าออก`);
  }
  /* ตัวควบคุมฝั่งตรงข้าม: กรณี "ไม่เจอจริง" ต้องยังพูดว่าไม่มีโค้ดนี้
     ⇒ ถ้าใครรวมสองข้อความเป็นอันเดียว ข้อนี้แดง */
  const ไม่เจอ = coupons.validate(undefined, 1000, null);
  assert.equal(ไม่เจอ.ok, false);
  assert.ok(ไม่เจอ.error.includes('ไม่มีโค้ดนี้'),
    'กรณีไม่เจอจริงต้องยังบอกตรง ๆ ว่าไม่มีโค้ดนี้ — สองกรณีต้องพูดไม่เหมือนกัน');
  assert.notEqual(ไม่เจอ.error, ตรวจไม่ได้.error, 'สองกรณีห้ามใช้ข้อความเดียวกัน');
});
