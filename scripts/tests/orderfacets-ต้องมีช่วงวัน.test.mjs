/* ทดสอบ: `list=orderfacets` **ไม่ส่งช่วงวัน ⇒ ต้องประกาศตัว** ห้ามคืนก้อนว่างเงียบ ๆ
 *
 * 🔴 ที่มาของเทสนี้ (15 ต.ค. 2569 · ใบ t_mv8xgvo0) — ความผิดของ CTO เอง:
 *    ยิงเส้นนี้โดยไม่ใส่ `from`/`to` ได้ `byChannel: []` แล้วสรุปว่า "ร้านไม่มีค่าช่องทางเลย"
 *    แล้ว **สั่งฝั่งจอห้ามทำปุ่มช่องทางการขาย** · ฝั่งจอยิงซ้ำแบบใส่ช่วงวันได้ 8 ช่อง ⇒ คำสั่งผิด
 *    📏 วัดจริง: ไม่ใส่ช่วงวัน ⇒ byChannel 0 · byStatus 0 · byPayStatus 0 · stores 0 (ว่างทั้งสี่)
 *
 * 🔑 เทสนี้จับ **การยุบสองสถานะเป็นหนึ่ง**: "ยังไม่ได้ถาม" ต้องไม่หน้าตาเหมือน "ถามแล้วไม่มี"
 * ⚠️ และต้องจับ **ทั้งสองทิศ** ไม่ใช่แค่ทิศเดียว:
 *    ① ไม่ส่งช่วงวัน ⇒ **ห้ามมีคีย์** byChannel/byStatus/byPayStatus/stores · ต้องมีธง `ต้องระบุช่วงวัน`
 *    ② ส่งช่วงวัน    ⇒ **ต้องไม่มีธงนั้น** (ไม่งั้นธงจะติดตลอดกาลแล้วจอเลิกอ่าน)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const ซอร์ส = readFileSync("netlify/functions/core.mjs", "utf8");

test("orderfacets: ไม่ส่งช่วงวัน ⇒ ไม่ส่งคีย์ก้อนว่าง และต้องมีธงบอก", () => {
  /* ⚠️ ยึดหมุดที่ **ตัวด่านเอง** ไม่ใช่ที่บรรทัด `list === "orderfacets"`
     เพราะด่านถูกย้ายไปไว้เหนือบรรทัดนั้น (เพื่อไม่ให้ตัดสายตาของเทสฝั่งจอ)
     ⇒ เทสที่ยึดตำแหน่งแบบ "นับระยะจากบรรทัดอื่น" จะแดงทุกครั้งที่มีคนย้ายโค้ด
        ทั้งที่พฤติกรรมไม่เปลี่ยน · ยึดที่ของจริงแล้วตรวจ **ลำดับ** แทน */
  const ด่าน = ซอร์ส.indexOf('if (p.get("list") === "orderfacets" && !p.get("from") && !p.get("to"))');
  assert.ok(ด่าน > 0, "หาด่าน 'ไม่ส่ง from และ to' ไม่เจอ");

  const เรียกจริง = ซอร์ส.indexOf("...(await listOrderFacets({");
  assert.ok(เรียกจริง > 0, "หาจุดที่เรียก listOrderFacets ไม่เจอ — เทสนี้ชี้ผิดที่แล้ว");
  assert.ok(ด่าน < เรียกจริง, "ด่านต้องอยู่ **ก่อน** การเรียก listOrderFacets ไม่ใช่หลัง");

  /* ⚠️ ตัดให้ **แค่ตัวด่าน** ไม่ใช่ถึงจุดเรียก listOrderFacets
     เพราะระหว่างทางมีทางสำเร็จ (`return okJson({…})`) ของเส้นปกติอยู่
     ⇒ ตัดกว้างเกินทำให้ข้อห้าม "ห้ามใช้ okJson" ไปจับทางที่ถูกต้อง (ผมเหยียบเองรอบแรก) */
  const ปิดด่าน = ซอร์ส.indexOf("\n    }", ด่าน);
  assert.ok(ปิดด่าน > ด่าน && ปิดด่าน < เรียกจริง, "หาจุดปิดบล็อกด่านไม่เจอ");
  const บล็อก = ซอร์ส.slice(ด่าน, ปิดด่าน);
  assert.match(บล็อก, /ต้องระบุช่วงวัน: true/, "ต้องมีฟิลด์ความหมายเดียวบอกว่าต้องมีช่วงวัน");
  /* 🔴 ต้องเป็น **400** ไม่ใช่ 200 (แก้ 16 ต.ค. 2569 — เมื่อวานผมเลือก 200 ด้วยเหตุผลที่วัดผิด)
     เหตุ: 400 ที่ฟังก์ชันเราตอบ **body รอด** (วัด 5,744 ไบต์) ⇒ จอได้อ่านเหตุผล
     และ 400 ไม่มีจอไหนอ่านเป็นข้อมูลได้ ต่างจาก 200 + ธง ที่อ่านข้ามได้ */
  assert.match(บล็อก, /\n\s*400\n/, "ต้องตอบ 400 — 200 + ธง จออ่านข้ามได้แล้วกลับไปโกหกเหมือนเดิม");
  assert.ok(!/okJson\(/.test(บล็อก), "ทางนี้ต้องไม่ใช้ okJson (ok:true อ่านเหมือนสำเร็จ)");

  /* ⚠️ ด่านสำคัญ: ทางที่ไม่มีช่วงวัน **ต้องไม่พูดถึงคีย์ก้อน** เลย
     (ถ้าใครเผลอใส่ byChannel: [] กลับมา เทสนี้ต้องแดง) */
  for (const คีย์ of ["byChannel:", "byStatus:", "byPayStatus:", "stores:"]) {
    assert.ok(!บล็อก.includes(คีย์),
      `ทางที่ไม่มีช่วงวันต้องไม่ส่งคีย์ ${คีย์} เลย — ก้อนว่างแปลว่า "ถามแล้วไม่มี" ซึ่งไม่ใช่ความจริง`);
  }
});

test("orderfacets: ทางที่มีช่วงวันต้องไม่ติดธง ต้องระบุช่วงวัน", () => {
  const i = ซอร์ส.indexOf("return okJson({\n        ...(await listOrderFacets");
  assert.ok(i > 0, "หาทางปกติของ orderfacets ไม่เจอ");
  const ทางปกติ = ซอร์ส.slice(i, i + 1200);
  assert.ok(!ทางปกติ.includes("ต้องระบุช่วงวัน"),
    "ธงนี้ต้องไม่ติดในทางปกติ — ธงที่ขึ้นทุกรอบคือธงที่คนเลิกอ่าน");
});
