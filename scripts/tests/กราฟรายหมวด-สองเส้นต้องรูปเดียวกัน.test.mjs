// `series=day|month` — กราฟเส้นต่อหมวดตามช่วงเวลา · **สองเส้นต้องคืนรูปเดียวกัน**
//
// ที่มา 16–17 ต.ค. 2569 · ท่านประธานติ๊กสั่งใบ t_mvb7r7zc · ฝั่งจออ่านจอ ZORT ทั้งสองหน้าแล้ว
//   (/Dashboard/SalesReport typeoption=2 และ /Dashboard/BuyReport typeoption=1)
// 🔑 เหตุที่ต้องรูปเดียวกัน ไม่ใช่แค่ประหยัดโค้ด:
//    จอใช้ตัววาดกราฟตัวเดียวสองหน้า ⇒ **เอามาวางเทียบกันได้ตรง ๆ ⇒ ข้างไหนเพี้ยนเห็นทันที**
//    = รูปที่ใช้ร่วมกันคือตัวตรวจในตัว · ถ้าวันหนึ่งสองฝั่งหลุดรูปกัน ตัวตรวจนั้นหายไปเงียบ ๆ
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";

const ขาย = fs.readFileSync("netlify/functions/core.mjs", "utf8");
const ซื้อ = fs.readFileSync("netlify/lib/core-purchases.mjs", "utf8");

/** ดึงรายชื่อคีย์ที่แต่ละฝั่งใส่ในแถว series */
const คีย์แถว = (src) => {
  const i = src.indexOf("seriesRows.map((r) => ({");
  assert.ok(i > 0, "ไม่เจอตัวประกอบแถว series");
  const ก้อน = src.slice(i, src.indexOf("}))", i));
  return [...ก้อน.matchAll(/(\w+):/g)].map((m) => m[1]).sort();
};

test("ทั้งสองเส้นคืนคีย์ชุดเดียวกันเป๊ะ", () => {
  const a = คีย์แถว(ขาย);
  const b = คีย์แถว(ซื้อ);
  assert.deepEqual(a, b, `รูปไม่ตรงกัน — ยอดขาย ${a.join(",")} vs ยอดซื้อ ${b.join(",")}`);
  assert.deepEqual(a, ["amount", "category", "period", "qty"]);
});

test("ทั้งสองเส้นรับเฉพาะ day|month และตีกลับค่าอื่น (ไม่เมินเงียบ)", () => {
  for (const [ชื่อ, src] of [["ยอดขาย", ขาย], ["ยอดซื้อ", ซื้อ]]) {
    assert.match(src, /series รับได้เฉพาะ day \| month/, `${ชื่อ} ไม่ตีกลับค่าที่ไม่รู้จัก`);
    assert.match(src, /series= ใช้ได้กับ by=category เท่านั้น/, `${ชื่อ} ไม่กัน by อื่น`);
  }
});

test("ชนเพดานต้องตีกลับพร้อมทางออก ห้ามตัดเงียบ", () => {
  for (const [ชื่อ, src] of [["ยอดขาย", ขาย], ["ยอดซื้อ", ซื้อ]]) {
    /* ดึงเพดาน+1 = รู้ว่าชน · ถ้าดึงเท่าเพดานพอดีจะแยก "พอดี" กับ "ล้น" ไม่ออก */
    assert.match(src, /LIMIT \$\{เพดานแถวกราฟ \+ 1\}/, `${ชื่อ} ไม่ได้ดึงเกินเพดานหนึ่งแถวเพื่อรู้ว่าชน`);
    assert.match(src, /seriesRows\.length > เพดานแถวกราฟ/, `${ชื่อ} ไม่ได้เช็คการชนเพดาน`);
    assert.match(src, /hint:/, `${ชื่อ} ตีกลับแล้วไม่บอกทางออกที่ทำได้`);
  }
});

test("ลำดับต้องมีตัวตัดสินเสมอกันสองชั้น — ไม่งั้นเส้นในกราฟสลับสีกันเอง", () => {
  for (const [ชื่อ, src] of [["ยอดขาย", ขาย], ["ยอดซื้อ", ซื้อ]])
    assert.match(src, /ORDER BY period, category/, `${ชื่อ} ขาดตัวตัดสินเสมอกัน`);
});

test("ไม่ขอ series ⇒ ไม่มีคีย์เลย (ไม่ใช่อาร์เรย์ว่าง)", () => {
  /* [] อ่านได้ว่า "ขอแล้วไม่มีข้อมูล" · ไม่มีคีย์ = "ยังไม่ได้ขอ" ⇒ คนละเรื่อง */
  for (const [ชื่อ, src] of [["ยอดขาย", ขาย], ["ยอดซื้อ", ซื้อ]])
    assert.match(src, /\.\.\.\(seriesRows \? \{ series:/, `${ชื่อ} ไม่ได้ทำให้คีย์หายเมื่อไม่ได้ขอ`);
});

test("ฝั่งยอดขายต้องประกาศว่าเส้นจะไม่ติดลบเหมือน ZORT", () => {
  /* ZORT หักใบคืนลงวันนั้น ⇒ เส้นเขาติดลบได้ · เรายังหักรายบรรทัดไม่ได้
     ⇒ ถ้าไม่ประกาศ จอจะอ่านความไม่ติดลบว่า "ช่วงนั้นไม่มีใบคืน" ซึ่งเป็นคำยืนยันที่เราไม่ได้วัด */
  const i = ขาย.indexOf("seriesScope");
  const ป้าย = ขาย.slice(i, i + 900);
  assert.match(ป้าย, /ไม่ติดลบ/);
  assert.match(ป้าย, /ไม่มียอดจะไม่มีแถว/);
});
