/* ด่าน: Shopee ส่งแถวมาแต่ "อ่านช่องสต็อกไม่ได้" ต้องหยุดก่อนคิดแผนดันสต็อก
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · ใบ t_mu7uzpld (ต่อจาก t_mu7u2c7j)
 *    เส้นทางอ่านสต็อกลึกสี่ชั้น `m.stock_info_v2.seller_stock[0].stock`
 *    **เลข v2 ในชื่อคือหลักฐานว่า Shopee เคยเปลี่ยนชื่อชั้นมาแล้วจริง**
 *    ของเดิมใช้ `num()` ⇒ เส้นทางขาด ⇒ NaN ⇒ **0** ⇒ "Shopee ไม่มีของทั้งร้าน"
 *    ⇒ แผนดันสต็อกสั่งดันทั้ง 1,870 รหัส = ค่าที่ผิด **ออกไปแตะของจริงบนมาร์เก็ตเพลส**
 *    (ต่างจากฝั่งเว็บที่แค่แสดงผลผิด — ที่นี่ค่าออกนอกบ้านไปเปลี่ยนของคนอื่น)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { อ่านสต็อกผู้ขาย, ตัดสินสต็อกอ่านไม่ได้ } from "../../netlify/lib/shopee-stock.mjs";

test("อ่านค่าปกติ — และ 0 ต้องเป็น 0 ไม่ใช่ null", () => {
  assert.equal(อ่านสต็อกผู้ขาย({ stock_info_v2: { seller_stock: [{ stock: 12 }] } }), 12);
  assert.equal(อ่านสต็อกผู้ขาย({ stock_info_v2: { seller_stock: [{ stock: 0 }] } }), 0,
    "ของหมดจริง = 0 ต้องอ่านได้ ห้ามกลายเป็น null ไม่งั้นด่านจะร้องใส่ของปกติ");
});

test("🧪 เส้นทางขาดทีละชั้น ⇒ null ทุกกรณี (ไม่ใช่ 0)", () => {
  for (const [ชื่อ, m] of [
    ["ไม่มี stock_info_v2", { stock_info: { seller_stock: [{ stock: 5 }] } }],
    ["seller_stock เป็นออบเจกต์ไม่ใช่อาเรย์", { stock_info_v2: { seller_stock: { stock: 5 } } }],
    ["อาเรย์ว่าง", { stock_info_v2: { seller_stock: [] } }],
    ["ไม่มีช่อง stock", { stock_info_v2: { seller_stock: [{ reserved: 5 }] } }],
    ["ทั้งก้อนเป็น null", null],
    ["ทั้งก้อนเป็น undefined", undefined],
  ]) {
    assert.equal(อ่านสต็อกผู้ขาย(m), null, `${ชื่อ}: ต้องได้ null — ถ้าได้ 0 คือโกหกว่าของหมด`);
  }
});

test("ตัวเลขมาเป็นข้อความ/มีจุลภาค ต้องอ่านได้", () => {
  assert.equal(อ่านสต็อกผู้ขาย({ stock_info_v2: { seller_stock: [{ stock: "7" }] } }), 7);
  assert.equal(อ่านสต็อกผู้ขาย({ stock_info_v2: { seller_stock: [{ stock: "1,234" }] } }), 1234);
});

test("คำตัดสิน: อ่านไม่ได้ทุกแถว ⇒ หยุด", () => {
  const เหตุ = ตัดสินสต็อกอ่านไม่ได้(1870, 1870);
  assert.match(String(เหตุ), /อ่านช่องสต็อกไม่ได้เลยสักแถว/);
  assert.match(String(เหตุ), /1870/, "ต้องบอกจำนวนแถวที่เห็น ไม่ใช่แค่บอกว่าเสีย");
});

test("🔑 พลังแยกแยะ: ของหมดจริงทั้งร้าน (อ่านได้ทุกแถว) ⇒ **ต้องไม่หยุด**", () => {
  assert.equal(ตัดสินสต็อกอ่านไม่ได้(1870, 0), null,
    "ถ้าข้อนี้แดง = เราสร้างแดงลวงที่จะหยุดแผนดันสต็อกในวันที่ Shopee ถูกต้อง");
});

test("บางแถวอ่านไม่ได้ ⇒ ยังเดินต่อ (ไม่มีเพดานสัดส่วน เพราะยังไม่ได้วัดค่าจริง)", () => {
  assert.equal(ตัดสินสต็อกอ่านไม่ได้(1870, 1869), null);
  assert.equal(ตัดสินสต็อกอ่านไม่ได้(1870, 1), null);
});

test("🔴 ตัวเก็บของรุ่นเก่าไม่ส่งตัวนับมา ⇒ **ไม่รู้ ⇒ ไม่ตัดสิน** (ห้ามแปลว่าอ่านได้ครบ)", () => {
  /* สถานะนี้เกิดจริงตอน deploy คนละรอบ: ตัวเก็บของเก่า + ตัวตัดสินใหม่ อยู่ด้วยกันชั่วครู่
     ถ้าแปลคีย์ที่หายว่า 0 ("อ่านได้ทุกแถว") ด่านจะเงียบพอดีในวันที่มันควรดัง */
  assert.equal(ตัดสินสต็อกอ่านไม่ได้(1870, undefined), null);
  assert.equal(ตัดสินสต็อกอ่านไม่ได้(1870, null), null);
  assert.equal(ตัดสินสต็อกอ่านไม่ได้(1870, "ไม่ใช่เลข"), null);
});

test("ไม่มีแถวเลย ⇒ ไม่ใช่หน้าที่ด่านนี้ (มีด่านกองว่างอยู่ก่อนแล้ว)", () => {
  assert.equal(ตัดสินสต็อกอ่านไม่ได้(0, 0), null);
});
