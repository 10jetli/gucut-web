import assert from 'node:assert/strict';
import { test } from 'node:test';

/* ── หนี้ที่ปิดได้แล้ว (12 ต.ค. 2569) ────────────────────────────────────────
   รอบแรกผมจดไว้ว่า "ข้อ orders.mjs 503 ยังไม่มีเทสครอบ เพราะต้องม็อก 11 โมดูล"
   🔑 ฝั่งท่อชี้ท่าที่ถูกกว่า: **ยกตัวตัดสินออกมาเป็นฟังก์ชันล้วน** แล้วเทสเรียกตรง ๆ
      (ท่าที่รีโปนี้ใช้อยู่แล้ว: `ตัดสินสต็อกอ่านไม่ได้` · `ต้องเขียนใหม่` · `สรุปที่เลือก`)
   ⇒ ไม่ต้องม็อกอะไรเลย · และวัดแล้วว่า `orders.mjs` นำเข้าได้โดยไม่ต้องม็อก */
const { ต้องตีกลับเพราะอ่านบัญชีไม่ได้ } = await import('../../netlify/functions/orders.mjs');

test('🔴 orders: อ่านบัญชีไม่ได้ + ลูกค้าขอใช้แต้ม ⇒ ต้องตีกลับ', () => {
  assert.equal(ต้องตีกลับเพราะอ่านบัญชีไม่ได้('unknown', 50), true,
    'ไม่ตีกลับ = ลูกค้าจ่ายเต็มโดยคิดว่าได้ส่วนลด และไม่มีอะไรฟ้อง');
  assert.equal(ต้องตีกลับเพราะอ่านบัญชีไม่ได้('unknown', '50'), true,
    'ค่าจาก body เป็นสตริงได้ ⇒ ต้องแปลงก่อนเทียบ');
});

test('⚖️ orders: ไม่ขอใช้แต้ม หรืออ่านบัญชีได้ ⇒ **ห้าม** ตีกลับ (พลังแยกแยะ)', () => {
  assert.equal(ต้องตีกลับเพราะอ่านบัญชีไม่ได้('unknown', 0), false,
    'คนที่ไม่ได้ขอใช้แต้มต้องสั่งซื้อได้ — ตีกลับทุกคนตอนถังสะดุด = ปิดร้านเพราะเรื่องที่ไม่เกี่ยวกับเขา');
  assert.equal(ต้องตีกลับเพราะอ่านบัญชีไม่ได้('unknown', undefined), false, 'ไม่ส่งช่องมาเลย ⇒ ไม่ขอใช้แต้ม');
  assert.equal(ต้องตีกลับเพราะอ่านบัญชีไม่ได้('guest', 50), false, 'คนนอกจริงขอใช้แต้ม ⇒ ไม่ใช่กรณีนี้');
  assert.equal(ต้องตีกลับเพราะอ่านบัญชีไม่ได้('user', 50), false, 'อ่านบัญชีได้ ⇒ คิดส่วนลดตามปกติ');
});
