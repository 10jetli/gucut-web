/* ══════════ 🔴 คลาสเดิมซ้ำที่สี่ของวันนี้ — "มีทางออกกี่ทาง" ไม่ใช่ "ทางที่รู้จักยังถูกไหม" ══════════
   ฝั่งจอประกบด่านนี้แล้ว **ทะลุ** (28 ก.ย. 2569): เขาปลูก **ทางออกใหม่** ก่อนทางออกปกติ
     `if (unreadable > list.length) return json({ list, วัดเมื่อ: new Date().toISOString() });`
   ⇒ `node --check` ผ่าน · ด่านยังเขียว เพราะทุกอย่างที่ด่านตรวจ (กิ่ง catch) **ยังถูกต้องครบ**
   📏 เขาพิสูจน์ตามกติกา ⑤ ชั้น ② ว่าผลต่างจริง: ทางปกติส่ง 6 ช่อง · ทางที่ปลูกส่งแค่ `list` + `วัดเมื่อ`
      ⇒ **ตัวนับหายทั้งชุด** = รูปเดียวกับบั๊ก B08 เป๊ะ (200 + list + ไม่มีตัวนับ)
   ⚠️ และมันร้ายในทิศที่กลับกับ B08: ท่อ **มีข้อมูลบางส่วนจริง** แล้วบอกจอว่า "อ่านไม่ได้ทั้งหมด"
      (จออ่านถูกตามสัญญา — ท่อเป็นฝ่ายพูดผิด)
   ✅ ท่าที่ปิดคลาสนี้ (เดียวกับที่ใช้กับฟีดสินค้า): **นับประตู** แล้วบังคับว่าทุกประตูต้องเข้าสองกอง
      ① กองคำตอบปกติ ⇒ ต้องมีตัวนับครบทั้งห้า
      ② กองประกาศว่าไม่รู้ ⇒ ต้องมี `unreadable: null` และสถานะ HTTP ที่ไม่ใช่ 200 */

import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";
import { เลขบรรทัด, ปลูกในโค้ด, โหลดผ่านไหม, คีย์ของก้อน } from "./_src.mjs";

const ไฟล์ = "netlify/functions/returns-feed.mjs";
const โค้ด = ตัดคอมเมนต์(src, ไฟล์, { คงเลขบรรทัด: true });
const ตัวนับทั้งห้า = ["list", "unreadable", "qtyUnreadableLines", "qtyZeroLines", "priceUnreadableLines"];

/** คืนทุกประตู `return json(` พร้อมชุดคีย์และสถานะ HTTP ที่มันตอบ */
function ประตูทั้งหมด(เนื้อ) {
  const ออก = [];
  for (const m of เนื้อ.matchAll(/return json\(/g)) {
    const เริ่มก้อน = เนื้อ.indexOf("{", m.index);
    /* หา `}` ที่ปิดก้อนแรกหลัง json( */
    let ลึก = 0;
    let จบ = เริ่มก้อน;
    for (let i = เริ่มก้อน; i < เนื้อ.length; i += 1) {
      if (เนื้อ[i] === "{") ลึก += 1;
      else if (เนื้อ[i] === "}") { ลึก -= 1; if (ลึก === 0) { จบ = i; break; } }
    }
    const ก้อน = เนื้อ.slice(เริ่มก้อน, จบ + 1);
    /* สถานะ HTTP = อาร์กิวเมนต์ที่สองของ json(...) ถ้ามี */
    const หลังก้อน = เนื้อ.slice(จบ + 1, เนื้อ.indexOf(")", จบ + 1) + 1);
    const ส = หลังก้อน.match(/,\s*(\d{3})/);
    ออก.push({
      บรรทัด: เลขบรรทัด(เนื้อ, m.index),
      คีย์: คีย์ของก้อน(ก้อน),
      สถานะ: ส ? Number(ส[1]) : 200,
    });
  }
  return ออก;
}

test("🔴 ทุกประตูของฟีดใบคืนต้องเข้าหนึ่งในสองกอง — ประตูใหม่ที่ไม่เข้ากอง = แดงทันที", () => {
  const ประตู = ประตูทั้งหมด(โค้ด);
  console.log(
    `   📏 ประตูของฟีดใบคืน ${ประตู.length} จุด:\n` +
      ประตู.map((p) => `      ${ไฟล์}:${p.บรรทัด} · HTTP ${p.สถานะ} · คีย์: ${p.คีย์.join(", ")}`).join("\n")
  );
  assert.ok(ประตู.length >= 2, `ต้องเจอประตูอย่างน้อยสองจุด · เจอ ${ประตู.length} ⇒ ตะแกรงพัง ไม่ใช่ไฟล์ว่าง`);

  const ผิด = [];
  for (const p of ประตู) {
    const มีError = p.คีย์.includes("error");
    if (p.สถานะ !== 200) {
      /* ② กองประกาศว่าไม่รู้ / ปฏิเสธ — ต้องไม่แกล้งส่งตัวนับที่เป็นตัวเลข */
      if (p.คีย์.includes("unreadable") || p.คีย์.includes("list")) {
        if (!p.คีย์.includes("unreadable") || !p.คีย์.includes("list"))
          ผิด.push(`${ไฟล์}:${p.บรรทัด} (HTTP ${p.สถานะ}) ส่ง list/unreadable มาไม่ครบคู่ ⇒ จอเดาไม่ออกว่าอันไหนแปลว่าอะไร`);
      }
      if (!มีError)
        ผิด.push(`${ไฟล์}:${p.บรรทัด} (HTTP ${p.สถานะ}) ไม่มีช่อง error ⇒ ปฏิเสธโดยไม่บอกเหตุ`);
      continue;
    }
    /* ① กองคำตอบปกติ (HTTP 200) — **ต้องมีตัวนับครบทั้งห้า** */
    const ขาด = ตัวนับทั้งห้า.filter((k) => !p.คีย์.includes(k));
    if (ขาด.length)
      ผิด.push(
        `${ไฟล์}:${p.บรรทัด} ตอบ HTTP 200 แต่ขาดตัวนับ: ${ขาด.join(", ")} ` +
          `(ส่งมา: ${p.คีย์.join(", ")}) ⇒ **นี่คือรูปของบั๊ก B08** — จอจะอ่านว่า "ท่ออ่านไม่ได้" ` +
          "ทั้งที่ท่อมีข้อมูลบางส่วนจริง · สัญญาของไฟล์นี้เขียนไว้เองว่า 'ตัวนับระดับฟีด ส่งออกเสมอ (0 ได้)'"
      );
  }
  assert.deepEqual(ผิด, [], `ประตูที่ไม่เข้ากอง:\n- ${ผิด.join("\n- ")}`);
});

test("🧪 ตัวควบคุม: เพิ่มประตู 200 ที่ขาดตัวนับ ⇒ เกณฑ์ต้องจับได้ (เคสที่ฝั่งจอปลูกจริง)", () => {
  const { ปลูก, บรรทัด } = ปลูกในโค้ด(
    src,
    "  list.sort((a, b) => (a.date < b.date ? 1 : -1));",
    '  if (unreadable > list.length) return json({ list, วัดเมื่อ: new Date().toISOString() });\n' +
      "  list.sort((a, b) => (a.date < b.date ? 1 : -1));",
    { ไฟล์ }
  );
  console.log(`   🌱 เพิ่มประตูใหม่ที่บรรทัด ${บรรทัด}`);
  โหลดผ่านไหม(ปลูก, "ปลูก-ประตูไม่มีตัวนับ");
  const โค้ดปลูก = ตัดคอมเมนต์(ปลูก, ไฟล์, { คงเลขบรรทัด: true });
  const ประตู = ประตูทั้งหมด(โค้ดปลูก);
  /* 🔑 กติกา ⑤ ชั้น ② — พิสูจน์ว่าผลต่างจริงด้วยชุดคีย์ ไม่ใช่แค่ข้อความต่าง */
  const ใหม่ = ประตู.find((p) => p.สถานะ === 200 && !p.คีย์.includes("unreadable"));
  assert.ok(ใหม่, `ปลูกแล้วต้องมีประตู 200 ที่ขาดตัวนับ · ได้: ${JSON.stringify(ประตู)}`);
  assert.deepEqual(ใหม่.คีย์, ["list", "วัดเมื่อ"],
    "ชุดคีย์ของประตูที่ปลูกต้องขาดตัวนับทั้งชุด ⇒ ยืนยันว่าการปลูกเปลี่ยนผลจริง");
  const ขาด = ตัวนับทั้งห้า.filter((k) => !ใหม่.คีย์.includes(k));
  assert.equal(ขาด.length, 4, `ต้องขาด 4 ตัวนับ (มีแต่ list) · ขาด: ${ขาด.join(", ")}`);
});

test("🔑 ประตูปฏิเสธ (401) ต้องไม่ปลอมตัวเป็นคำตอบปกติ", () => {
  const ประตู = ประตูทั้งหมด(โค้ด).filter((p) => p.สถานะ === 401);
  assert.ok(ประตู.length >= 1, "ต้องมีประตู 401 (ไม่มีรหัสหลังร้าน)");
  for (const p of ประตู) {
    assert.ok(p.คีย์.includes("error"), `${ไฟล์}:${p.บรรทัด} ต้องมีช่อง error`);
    assert.ok(!p.คีย์.includes("list"),
      `${ไฟล์}:${p.บรรทัด} ห้ามส่ง list มาด้วย — ปฏิเสธแล้วยังส่งรายการ = จอเอาไปแสดงเป็นข้อมูลจริงได้`);
  }
});
