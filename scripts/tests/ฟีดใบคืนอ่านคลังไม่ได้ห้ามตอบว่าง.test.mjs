/* 🔴 ด่าน: **ฟีดใบคืน — อ่านคลังไม่ได้ ห้ามตอบ 200 พร้อม list ว่าง** (ใบ B08 · 28 ก.ย. 2569)
 *
 * ฝั่งจอชี้มา: `catch { return json({ list: [] }) }` ⇒ **HTTP 200 · list ว่าง · ไม่มีตัวนับ**
 * ⇒ จอแยกไม่ออกจาก "ไม่มีใบคืนจริง" ⇒ ยอดขึ้น 0 ใบ 0 บาท **หน้าตาปกติสนิท**
 * 🔑 และมันขัดกับสัญญาที่ไฟล์นี้เขียนไว้เองว่า **"ตัวนับระดับฟีด ส่งออกเสมอ (0 ได้)"**
 *    ⇒ คลาส: **ทางถอยที่ไม่เคารพสัญญาของเส้นตัวเอง** — กิ่งที่วิ่งตอนของพังไม่เดินตามสัญญา
 *       และไม่มีใครเห็น เพราะกิ่งนั้นแทบไม่เคยวิ่ง
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const src = await readFile(new URL("../../netlify/functions/returns-feed.mjs", import.meta.url), "utf8");
const เริ่ม = src.indexOf("await store.list({ prefix");
const ท่อน = src.slice(เริ่ม, src.indexOf("const list = [];", เริ่ม));

test("✅ ตัวปลูกอ่านถูกท่อน (อ่านผิดท่อน = เขียวลวง)", () => {
  assert.ok(เริ่ม > 0 && ท่อน.length > 40, `ต้องอ่านท่อน catch ได้ · ยาว ${ท่อน.length}`);
  assert.match(ท่อน, /catch/, "ท่อนนี้ต้องมีกิ่ง catch");
});

test("🔴 กิ่ง catch ห้ามคืน `list: []` (ว่างแบบที่อ่านเป็น 'ไม่มีใบคืน' ได้)", () => {
  assert.ok(!/list:\s*\[\s*\]/.test(ท่อน), "อ่านคลังไม่ได้ ห้ามตอบ list ว่าง");
});

test("🔑 ต้องตอบสถานะที่ไม่ใช่ 200 — 'ยังไม่รู้' ไม่ใช่ 'รู้แล้วว่าไม่มี'", () => {
  assert.match(ท่อน, /50\d/, "ต้องตอบ 5xx (เสนอ 502) ไม่ใช่ 200");
});

test("🔑 `unreadable` ต้องเป็น null ไม่ใช่ 0 — 0 แปลว่าวัดแล้วไม่มีของเสีย", () => {
  assert.match(ท่อน, /unreadable:\s*null/, "ต้องส่ง unreadable: null");
  assert.ok(!/unreadable:\s*0/.test(ท่อน), "ห้ามส่ง unreadable: 0 ในกิ่งที่อ่านไม่ได้");
});

test("🔑 ต้องบอกเหตุด้วย — จอเอาไปแสดงได้ว่าทำไมไม่รู้", () => {
  assert.match(ท่อน, /เหตุ|error/, "ต้องมีข้อความบอกเหตุ");
});

test("✅ ทางปกติยังต้องส่งตัวนับเสมอ (สัญญาเดิมของไฟล์นี้ต้องไม่ถูกทำลาย)", () => {
  assert.match(src, /ตัวนับระดับฟีด/, "คอมเมนต์สัญญาต้องยังอยู่");
  assert.match(src, /let unreadable = 0;/, "ทางปกตินับจาก 0 เหมือนเดิม");
});
