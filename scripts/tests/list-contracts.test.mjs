/* ด่าน: ทุกเส้น `list=` ต้องประกาศสัญญาของตัวเอง (ไล่หน้าด้วยอะไร · ต้องมีพารามิเตอร์อะไร)
 *
 * 🔴 ที่มา 19 ก.ย. 2569: ฝั่งจอเกือบรายงานว่า "ท่อพัง" 4 ครั้งในวันเดียว
 *    และ **3 ใน 4 เพราะท่อไม่ได้ประกาศว่ารับอะไร** ⇒ เขาเดา แล้วเดาผิด
 *    ผลที่หนักที่สุด: ดึงทะเบียนชุดได้ 200 จาก 360 แล้ว **รายงานตัวเลขที่ต่ำกว่าจริง**
 *    (ถ้าไม่ได้ไล่ต่อ ใบงานจะถูกตั้งจากเลขที่ผิด)
 * 🔑 "ของที่ต้องพึ่งความระวังของคน จะพังอีกแน่ ๆ วันที่คนเปลี่ยน" — คำของฝั่งจอ
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { LIST_CONTRACTS, สัญญาของเส้น } from "../../netlify/lib/list-contracts.mjs";
import { lists } from "../../netlify/lib/endpoints.mjs";

test("ทุกชื่อใน lists ต้องมีแถวในทะเบียนสัญญา", () => {
  const ขาด = lists.filter((l) => !(l in LIST_CONTRACTS)).sort();
  assert.deepEqual(
    ขาด, [],
    "เส้นเหล่านี้ยังไม่ประกาศสัญญา ⇒ ปลายทางต้องเดาว่าไล่หน้าด้วยอะไร: " + ขาด.join(", ") +
      "\n  ⇒ เพิ่มลง LIST_CONTRACTS พร้อม `ไล่หน้า` `ต้องมี` `วัดเมื่อ` (วัดด้วยการยิงจริง ห้ามอ่านซอร์สแล้วเดา)",
  );
});

test("ย้อนทิศ — ชื่อในทะเบียนที่ไม่มีในเส้นจริงแล้ว ต้องถูกถอดออก", () => {
  const ตายแล้ว = Object.keys(LIST_CONTRACTS).filter((k) => !lists.includes(k)).sort();
  /* ⚠️ ทิศนี้กันทะเบียนโตทางเดียว — สัญญาที่ชี้ไปเส้นที่ไม่มีอยู่ ทำให้คนเชื่อว่ามีเส้นนั้น */
  assert.deepEqual(ตายแล้ว, [], "ทะเบียนมีเส้นที่ไม่มีอยู่จริงแล้ว ให้ถอดออก: " + ตายแล้ว.join(", "));
});

test("ค่า `ไล่หน้า` ต้องเป็นค่าที่นิยามไว้เท่านั้น และ null ต้องมีหมายเหตุอธิบาย", () => {
  const ได้ = ["offset", "page", "ทั้งชุด", null];
  for (const [ชื่อ, c] of Object.entries(LIST_CONTRACTS)) {
    assert.ok(ได้.includes(c.ไล่หน้า), `${ชื่อ}: ค่า ไล่หน้า ต้องเป็น offset/page/ทั้งชุด/null`);
    /* 🔑 `null` = ยังไม่ได้วัด ⇒ **ต้องบอกว่าทำไมวัดไม่ได้** ไม่งั้นคนอ่านจะแปลว่า "ไล่หน้าไม่ได้" */
    if (c.ไล่หน้า === null) {
      assert.ok(c.หมายเหตุ && c.หมายเหตุ.length > 5,
        `${ชื่อ}: ไล่หน้า เป็น null ⇒ ต้องเขียนหมายเหตุว่าทำไมวัดไม่ได้ (null ไม่ใช่ "ไล่หน้าไม่ได้")`);
    }
    assert.match(c.วัดเมื่อ || "", /^\d{4}-\d{2}-\d{2}$/, `${ชื่อ}: ต้องมีวันที่วัด — "วัดแล้ว" ที่ไม่มีวันที่ใช้ตัดสินอะไรไม่ได้`);
    assert.ok(Array.isArray(c.ต้องมี), `${ชื่อ}: ต้องมี ต้องเป็นอาเรย์ (ว่างได้)`);
  }
});

test("เส้นที่ยังวัดไม่ได้เพราะต้องมีพารามิเตอร์ ต้องบอกว่าต้องมีอะไร", () => {
  for (const [ชื่อ, c] of Object.entries(LIST_CONTRACTS)) {
    if (c.ไล่หน้า !== null) continue;
    const บอกเหตุ = c.ต้องมี.length > 0 || /ไม่มีแถว|วัดไม่ได้|opt-in/.test(c.หมายเหตุ || "");
    assert.ok(บอกเหตุ, `${ชื่อ}: บอกไม่ได้ว่าทำไมยังวัดไม่ได้ ⇒ คนอ่านจะเดาเอง`);
  }
});

test("คำอธิบายวิธีอ่านต้องเตือนสองข้อที่เคยทำให้เสียเวลาจริง", () => {
  const r = สัญญาของเส้น("bundles");
  const ข้อความ = Object.entries(r).filter(([k]) => k.includes("อ่านยังไง")).map(([, v]) => String(v)).join(" ");
  /* ผูกกับเจตนา ไม่ใช่ถ้อยคำ */
  assert.match(ข้อความ, /nextOffset|nextPage/, "ต้องบอกให้อ่านค่าจากคำตอบ ไม่ใช่บวก limit เอง");
  assert.match(ข้อความ, /ห้ามแปลว่า|ยังไม่ได้วัด/, "ต้องบอกว่า null ไม่เท่ากับ ไล่หน้าไม่ได้");
});

test("ชื่อเส้นที่ไม่รู้จัก ⇒ คืน null ไม่ใช่ออบเจกต์ว่าง", () => {
  /* ออบเจกต์ว่างอ่านได้ว่า "มีสัญญาแต่ไม่มีข้อกำหนด" ซึ่งคนละเรื่องกับ "ไม่รู้จักเส้นนี้" */
  assert.equal(สัญญาของเส้น("ไม่มีเส้นนี้"), null);
  assert.equal(สัญญาของเส้น(""), null);
  assert.equal(สัญญาของเส้น(undefined), null);
});

