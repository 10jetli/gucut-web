// รัน: node --experimental-test-module-mocks --test scripts/tests/หมุดเจ้าภาพสคริปต์.test.mjs
// ใบ S15 — หมุด `ไฟล์ใน ~/bin บนเครื่องเจ้าภาพสคริปต์…` ต้องวัดได้เฉพาะบนเครื่องเจ้าภาพ
//
// 🔴 ของจริง 4 ต.ค. 2569: CEO push จาก Mac ไม่ได้ · หมุดเขียน 6 · เครื่องนั้นวัดได้ 0
//    🔑 และเหตุ **ไม่ใช่** "ไม่มี `~/bin`" — เครื่องแบบนั้นข้ามพร้อมบอกเหตุอยู่แล้ว
//       ของที่พังคือเครื่องที่ **มี `~/bin` ของตัวเอง** (บน Mac เป็นเรื่องปกติ)
//       ⇒ ตัววัดเดิมอนุมานจาก "โฟลเดอร์มีอยู่" ว่า "วัดได้" แล้วตอบ 0
//    ⇒ ⇒ **0 ที่แปลว่า "ไม่มีสคริปต์" กับ 0 ที่แปลว่า "คนละเครื่อง" คนละเรื่องกันสิ้นเชิง**
//       นี่คือคลาส "ไม่มีช่องให้ลง ⇒ ของไปลงช่องที่ผิด" — สภาพ "คนละเครื่อง"
//       ไม่มีช่องของตัวเอง จึงถูกยัดลงช่อง "นับได้ 0"
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join } from 'node:path';
import { วัดสคริปต์ยิงapi, ไฟล์ประกาศเจ้าภาพ, ชื่อหมุด } from '../lib/วัดสคริปต์ยิงapi.mjs';

const ยิงจริง = 'curl -s https://gucut.com/api/core?x=1';

/** สร้างบ้านปลอม — คืนพาธ · `ประกาศ` = วางไฟล์ประกาศเจ้าภาพไหม */
function บ้านปลอม({ มีbin = true, ประกาศ = false, สคริปต์ = [], อื่น = [] } = {}) {
  const h = mkdtempSync(join(tmpdir(), 's15-'));
  if (มีbin) {
    const b = join(h, 'bin');
    mkdirSync(b);
    if (ประกาศ) writeFileSync(join(b, ไฟล์ประกาศเจ้าภาพ), 'เจ้าภาพทดสอบ\n');
    for (const ชื่อ of สคริปต์) writeFileSync(join(b, ชื่อ), `#!/bin/sh\n${ยิงจริง}\n`);
    for (const ชื่อ of อื่น) writeFileSync(join(b, ชื่อ), ยิงจริง + '\n');
  }
  return h;
}

test('① ไม่มี ~/bin ⇒ วัดไม่ได้ พร้อมเหตุที่บอกชื่อเครื่อง', () => {
  const r = วัดสคริปต์ยิงapi(บ้านปลอม({ มีbin: false }));
  assert.ok(r['วัดไม่ได้'], 'ต้องเป็นสถานะวัดไม่ได้');
  assert.ok(!('ค่า' in r), '🔑 ห้ามมีคีย์ค่าเลย — "วัดไม่ได้" ที่มีตัวเลขติดมาจะถูกเอาไปเทียบ');
});

test('② 🔴 หัวใจของใบนี้: มี ~/bin แต่ไม่ใช่เจ้าภาพ ⇒ วัดไม่ได้ **ไม่ใช่ 0**', () => {
  const r = วัดสคริปต์ยิงapi(บ้านปลอม({ ประกาศ: false, อื่น: ['ของผู้ใช้เอง.sh'] }));
  assert.ok(r['วัดไม่ได้'],
    '🔴 นี่คือเคสที่ทำให้ push จาก Mac ไม่ได้ — ต้องเป็น "วัดไม่ได้" ไม่ใช่ตัวเลข');
  assert.ok(!('ค่า' in r), 'มีตัวเลข = จะถูกเอาไปเทียบกับหมุด ⇒ ตกทุกเครื่องที่ไม่ใช่เจ้าภาพ');
  assert.match(r['วัดไม่ได้'], /ไม่ใช่เครื่องเจ้าภาพ/, 'เหตุต้องบอกว่าทำไมวัดไม่ได้');
  assert.match(r['วัดไม่ได้'], new RegExp(ไฟล์ประกาศเจ้าภาพ.replace('.', '\\.')),
    'เหตุต้องบอกวิธีทำให้วัดได้ (ชื่อไฟล์ประกาศ) ไม่ใช่บอกแค่ว่าวัดไม่ได้');
});

test('③ เป็นเจ้าภาพแล้ว ⇒ วัดได้จริง และนับเฉพาะ .py/.sh', () => {
  const r = วัดสคริปต์ยิงapi(บ้านปลอม({
    ประกาศ: true,
    สคริปต์: ['ก.sh', 'ข.py'],
    อื่น: ['ค.txt', 'ง.sh.bak', 'จ.md'],
  }));
  assert.equal(r['ค่า'], 2,
    'นับเฉพาะ .py/.sh ที่รันได้จริง — สำเนาสำรอง/.txt/.md ต้องไม่นับ (เคยทำค่ากระพริบ 13↔16)');
});

test('④ 🔬 ด่านต้องยังกัดบนเจ้าภาพ: เจ้าภาพที่ไม่มีสคริปต์เลย ⇒ ค่า 0 (ไม่ใช่วัดไม่ได้)', () => {
  const r = วัดสคริปต์ยิงapi(บ้านปลอม({ ประกาศ: true }));
  assert.equal(r['ค่า'], 0,
    '🔑 ตัวควบคุมอีกทิศ — ถ้าทำให้ "0 บนเจ้าภาพ" กลายเป็น "วัดไม่ได้" ด่านจะไม่มีใครมาอัปเดตหมุดอีก'
    + ' (ทีมเคยแก้ทางนั้นแล้วถอนคืน · เหตุผลอยู่ใน measured-claims.test.mjs)');
});

test('⑤ เครื่องนี้: ถ้าเป็นเจ้าภาพ เลขต้องตรงกับหมุดในซอร์ส · ถ้าไม่ใช่ ต้องข้ามพร้อมเหตุ', (t) => {
  const r = วัดสคริปต์ยิงapi(homedir());
  if (r['วัดไม่ได้']) {
    t.diagnostic(`ข้ามบนเครื่องนี้: ${r['วัดไม่ได้'].slice(0, 120)}`);
    assert.ok(true);
    return;
  }
  /* 🔑 หาเลขในหมุดด้วย **ชื่อหมุดที่ประกาศในโค้ด** ไม่ใช่ข้อความที่พิมพ์ซ้ำในเทส
     ⇒ เปลี่ยนชื่อหมุดแล้วเทสนี้ยังชี้ที่เดิมได้ · และห้ามพิมพ์ตัวเลขซ้ำในเทส */
  const src = readFileSync('scripts/check-unreferenced-endpoints.mjs', 'utf8');
  const หนี = ชื่อหมุด.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = new RegExp(`📏วัดได้\\(${หนี}\\)=(\\d+)`).exec(src);
  assert.ok(m, 'ไม่เจอหมุดชื่อนี้ในซอร์ส ⇒ ชื่อหมุดกับทะเบียนหลุดจากกัน');
  assert.equal(r['ค่า'], Number(m[1]),
    `เครื่องนี้เป็นเจ้าภาพ ⇒ เลขต้องตรงกับหมุด (วัดได้ ${r['ค่า']} · หมุด ${m[1]})`);
});

test('⑥ 🔑 ขอบเขตต้องอยู่ใน **ชื่อหมุด** ไม่ใช่อยู่แต่ในคอมเมนต์', () => {
  /* 🔴 รุ่นแรกของข้อนี้ผมเขียนเป็นการจับคู่ **ข้อความในซอร์ส** กับคำว่าขอบเขต
     ⇒ `check-source-gates` ตีกลับ และมันถูก: คอมเมนต์ที่ไหนในรีโปก็ทำให้ด่านนั้นเขียวได้
     ⇒ ย้ายมาตรวจ **ค่าคงที่ที่โค้ดใช้จริง** ⇒ หลอกด้วยคอมเมนต์ไม่ได้อีก
     ⚠️ และรุ่นที่สองก็ยังถูกตีกลับ เพราะผม **ยกรูปที่ผิดมาเขียนไว้ในคอมเมนต์นี้เอง**
        (ด่านอ่านเจอรูปนั้นแล้วนับเป็นของจริง) — คลาสบวกลวงเดียวกับที่ด่าน bash
        เคยบล็อกจดหมายที่ยกโค้ดมาอ้าง ⇒ อธิบายด้วยคำพูด ห้ามยกรูปมาวาง */
  assert.ok(ชื่อหมุด.includes('บนเครื่องเจ้าภาพสคริปต์'),
    'ชื่อหมุดต้องบอกขอบเขต — คนอ่านเลขจะอ่านชื่อ ไม่ได้อ่านคอมเมนต์ข้างใต้');
  assert.notEqual(ชื่อหมุด, 'ไฟล์ใน ~/bin ที่ยิง gucut.com/api/',
    '🔴 ชื่อแบบเก่าไม่มีขอบเขต ⇒ อ่านเหมือนเป็นเลขของเครื่องที่ผู้อ่านใช้อยู่');
});
