/* ตัวช่วยอ่านซอร์ส **โดยถอดคอมเมนต์ออกก่อน** — ใช้ในด่านที่ตรวจว่า "โค้ดมีอะไรอยู่"
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ด่านตัวหนึ่งของผม **ถูกทำให้พอใจด้วยคอมเมนต์ที่ผมเขียนกำกับไว้เอง**
 *    ปลูกบั๊กจริงลงไปแล้วด่านยังเขียว เพราะคำที่ด่านค้นหาอยู่ในคำอธิบายข้างบรรทัดนั้น
 *    🔑 **คอมเมนต์ไม่ใช่พฤติกรรม** — ด่านที่อ่านซอร์สต้องตรวจเฉพาะสิ่งที่รันได้
 *    ⚠️ และคนที่เขียนคำอธิบายละเอียดที่สุด (เพราะเพิ่งเจ็บกับเรื่องนั้น) คือคนที่จะเจอกับดักนี้ก่อน
 *
 * ⚠️ **ไม่ใช่ตัวแยกไวยากรณ์** — ถอดด้วย regex ⇒ ข้อความที่มี `/*` หรือ `//` อยู่ในสตริงจะเพี้ยนได้
 *    ⇒ ใช้กับด่านที่ตรวจ "มีโค้ดรูปนี้อยู่ไหม" เท่านั้น **ห้ามใช้เป็นตัวแปลงซอร์สจริง**
 */
import { readFileSync } from "node:fs";

/** อ่านไฟล์แล้วคืนเนื้อที่ **ไม่มีคอมเมนต์** (ยังคงจำนวนบรรทัดไว้ให้เลขบรรทัดตรงเดิม) */
export function ซอร์สไม่เอาคอมเมนต์(path) {
  const raw = readFileSync(path, "utf8");
  /* 🔴 **ลำดับสำคัญ: ต้องลบคอมเมนต์บรรทัดก่อน แล้วค่อยลบคอมเมนต์ก้อน** (แก้ 19 ก.ย. 2569)
     ของเดิมลบก้อนก่อน ⇒ บรรทัดคอมเมนต์ที่มี glob เช่น `// ท่อคุยกับ … /api/shopee/*`
     ทำให้ตัวจับคอมเมนต์ก้อนเห็นเครื่องหมาย **เปิด** คอมเมนต์ แล้วกินไปจนเจอเครื่องหมาย **ปิด** ตัวถัดไป
     ⇒ **ลบโค้ดจริงทั้งไฟล์**
     ⇒ ผลคือด่านที่ใช้ตัวนี้รายงานว่า `shopee.mjs`/`tiktok.mjs` ไม่เรียก `adminGate`
       ทั้งที่ทั้งสองไฟล์ `import { adminGate }` อยู่บรรทัด 14 ⇒ **ผลบวกลวงเรื่องความปลอดภัย**
       ⇒ ถ้าเชื่อ จะไปเพิ่มด่านซ้อนในไฟล์ที่มีด่านอยู่แล้ว หรือไล่หารูที่ไม่มีอยู่
     🔑 คลาสเดียวกับบทเรียนที่ทีมมีอยู่แล้ว [[glob-in-comment-closes-the-comment]] แต่กลับด้าน:
        คราวนั้นเครื่องหมายปิดในคอมเมนต์ทำให้คอมเมนต์จบกลางทาง · คราวนี้เครื่องหมายเปิดในคอมเมนต์ทำให้เกิดคอมเมนต์ปลอม
        🔴 และผมเพิ่งเดินเข้าบทเรียนนั้นเองระหว่างเขียนคำอธิบายนี้ — พิมพ์เครื่องหมายปิดลงไปตรง ๆ แล้วไฟล์พังทันที
        ⇒ ต่อจากนี้ **บรรยายชื่อเครื่องหมาย ห้ามยกสัญลักษณ์มาใส่ในคอมเมนต์ก้อน**
     ⚠️ ยังไม่สมบูรณ์: เครื่องหมายเปิดคอมเมนต์ที่อยู่ใน **สตริง** ก็ยังหลอกได้ ⇒ ดูคำเตือนหัวไฟล์ */
  const ไม่มีคอมเมนต์บรรทัด = raw.replace(
    /(^|[^:])\/\/[^\n]*/g,
    (m, p1) => p1 + " ".repeat(Math.max(0, m.length - p1.length)),
  );
  return ไม่มีคอมเมนต์บรรทัด.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
}

/** อ่านทั้งสองแบบ — ไว้เทียบว่า "เจอเฉพาะในคอมเมนต์หรือเปล่า" */
export function เทียบคอมเมนต์(path) {
  return { ดิบ: readFileSync(path, "utf8"), โค้ด: ซอร์สไม่เอาคอมเมนต์(path) };
}
