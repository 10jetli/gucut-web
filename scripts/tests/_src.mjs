/* ตัวช่วยอ่านซอร์ส **โดยถอดคอมเมนต์ออกก่อน** — ใช้ในด่านที่ตรวจว่า "โค้ดมีอะไรอยู่"
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ด่านตัวหนึ่งของผม **ถูกทำให้พอใจด้วยคอมเมนต์ที่ผมเขียนกำกับไว้เอง**
 *    ปลูกบั๊กจริงลงไปแล้วด่านยังเขียว เพราะคำที่ด่านค้นหาอยู่ในคำอธิบายข้างบรรทัดนั้น
 *    🔑 **คอมเมนต์ไม่ใช่พฤติกรรม** — ด่านที่อ่านซอร์สต้องตรวจเฉพาะสิ่งที่รันได้
 *    ⚠️ และคนที่เขียนคำอธิบายละเอียดที่สุด (เพราะเพิ่งเจ็บกับเรื่องนั้น) คือคนที่จะเจอกับดักนี้ก่อน
 *
 * 🔴🔴 **20 ก.ย. 2569 — ไฟล์นี้เคยถือสำเนาตัวถอดของตัวเอง และสำเนานั้นกินโค้ดจริง**
 *    สตริงที่มี "สแลช-ดาว" ข้างใน ทำให้มันคิดว่าคอมเมนต์เปิดตรงนั้น แล้วกินถึงตัวปิดจริงถัดไป
 *    📏 วัดทั้งรีโป: **76 ไฟล์ · 121 บรรทัด** ที่ด่านซึ่งใช้ตัวนี้ **มองไม่เห็น** (เพดานบน)
 *    ⇒ เขียวของด่านพวกนั้นในช่วงที่ถูกกิน แปลว่า **"ไม่ได้ดู" ไม่ใช่ "ไม่มี"**
 *    ✅ ⇒ **เลิกถือสำเนา** — เรียก `ตัดคอมเมนต์` จาก `scripts/_strip-comments.mjs` (เดินทีละอักษร
 *       รู้จักสตริง/เทมเพลต · พิสูจน์สองทิศ 8 เคสใน `strip-comments.test.mjs`)
 *    🔑 **สองสำเนาของกติกาเดียวกัน จะเพี้ยนแยกกันเสมอ** — ครั้งนี้เป็นครั้งที่สองของไฟล์นี้
 * ⚠️ ยังไม่ใช่ตัวแยกไวยากรณ์เต็มรูป (ไม่รู้จัก regex literal) ⇒ ดูข้อจำกัดที่ประกาศไว้ใน `_strip-comments.mjs`
 */
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

/** อ่านไฟล์แล้วคืนเนื้อที่ **ไม่มีคอมเมนต์** (ยังคงจำนวนบรรทัดไว้ให้เลขบรรทัดตรงเดิม) */
export function ซอร์สไม่เอาคอมเมนต์(path) {
  /* 🔑 `คงเลขบรรทัด: true` — ด่านที่ใช้ไฟล์นี้รายงาน "ไฟล์:บรรทัด" ⇒ เลขบรรทัดต้องไม่ขยับ */
  return ตัดคอมเมนต์(readFileSync(path, "utf8"), path, { คงเลขบรรทัด: true });
}

/** อ่านทั้งสองแบบ — ไว้เทียบว่า "เจอเฉพาะในคอมเมนต์หรือเปล่า" */
export function เทียบคอมเมนต์(path) {
  return { ดิบ: readFileSync(path, "utf8"), โค้ด: ซอร์สไม่เอาคอมเมนต์(path) };
}

/** เลขบรรทัดของตำแหน่งตัวอักษร (ใช้กับผลของ `ซอร์สไม่เอาคอมเมนต์` ได้ตรง ๆ เพราะคงเลขบรรทัดไว้) */
export function เลขบรรทัด(เนื้อ, ดัชนี) {
  return เนื้อ.slice(0, ดัชนี).split("\n").length;
}

/** 🌱 ปลูกบั๊ก **ในโค้ดเท่านั้น** ลงสตริงในหน่วยความจำ (ไม่แตะไฟล์จริง)
 *
 * 🔴 ที่มา 28 ก.ย. 2569 — ฝั่งจอประกบด่านของฝั่งท่อแล้วเจอว่า
 *    ด่านใช้ `String.replace(...)` ซึ่ง **แทนที่ตัวแรก** และตัวแรกในไฟล์นั้นอยู่ใน **คอมเมนต์**
 *    ⇒ ปลูกในคอมเมนต์ · ด่านก็อ่านคอมเมนต์ ⇒ **แดงตามสั่งทุกครั้งโดยไม่เคยดูโค้ด** = tautology
 *    ⇒ เขาปลูกของจริงลงโค้ดแล้วด่านเขียว 7/7 ⇒ พิสูจน์ว่าตาข่ายนั้นไม่มีอยู่
 *
 * วิธี: หาตำแหน่งจากเนื้อที่ถอดคอมเมนต์แล้ว (ตัวถอดคงความยาว ⇒ ตำแหน่งตรงกับซอร์สดิบเป๊ะ)
 *      แล้วต่อสตริงที่ตำแหน่งนั้นในซอร์ส **ดิบ**
 * 🔑 มีข้อยืนยันสามชั้น ⇒ "ปลูกไม่ลง" กับ "ด่านไม่จับ" แยกออกจากกันได้:
 *    ① ตัวถอดต้องคงความยาว ② ต้องเจอในโค้ด ③ ข้อความที่ตำแหน่งนั้นต้องตรงกับที่จะแทน
 * @returns {{ปลูก: string, บรรทัด: number, ดัชนี: number}}
 */
export function ปลูกในโค้ด(ดิบ, ค้นหา, แทนด้วย, { ไฟล์ = "" } = {}) {
  const โค้ด = ตัดคอมเมนต์(ดิบ, ไฟล์, { คงเลขบรรทัด: true });
  if (โค้ด.length !== ดิบ.length)
    throw new Error(
      `ตัวถอดคอมเมนต์ไม่คงความยาวแล้ว (${ดิบ.length} → ${โค้ด.length}) ⇒ เทียบตำแหน่งข้ามกันไม่ได้ ⇒ ต้องแก้ตัวช่วยนี้`
    );
  const i = โค้ด.indexOf(ค้นหา);
  if (i < 0) {
    const ในดิบ = ดิบ.includes(ค้นหา);
    throw new Error(
      `หา "${ค้นหา.slice(0, 60)}" ในโค้ดไม่เจอ` +
        (ในดิบ
          ? " — **แต่เจอในซอร์สดิบ** ⇒ มันอยู่ในคอมเมนต์ ⇒ ปลูกที่นั่นจะได้ผลลวง"
          : " — และไม่มีในซอร์สดิบเลย ⇒ สูตรปลูกล้าสมัย ให้แก้สูตร ไม่ใช่ลบเทส")
    );
  }
  if (ดิบ.slice(i, i + ค้นหา.length) !== ค้นหา)
    throw new Error("ตำแหน่งในโค้ดล้วนกับซอร์สดิบไม่ตรงกัน ⇒ ห้ามเชื่อผลการปลูกนี้");
  return {
    ปลูก: ดิบ.slice(0, i) + แทนด้วย + ดิบ.slice(i + ค้นหา.length),
    บรรทัด: เลขบรรทัด(ดิบ, i),
    ดัชนี: i,
  };
}

/** 🧪 พิสูจน์ว่า "สูตรที่ปลูกแล้ว" ยังเป็นไฟล์ที่โหลดได้ — **กติกาข้อ ② ที่ตกลงกับฝั่งจอ**
 *  ถ้าปลูกแล้วไฟล์พังจนโหลดไม่ได้ ด่านจะแดงจาก **ตัวโหลด** ไม่ใช่จากการจับบั๊ก
 *  ⇒ ได้ข้อสรุปว่า "ด่านจับได้" ทั้งที่มันไม่เคยดูเนื้อหาเลย
 *  🔑 อยู่ที่นี่ที่เดียว — เดิมสำเนาอยู่ในไฟล์เทสตัวเดียว แล้วไฟล์ถัดไปเรียกไม่ได้ (28 ก.ย. 2569)
 *  โยน error เมื่อไฟล์ที่ปลูกแล้วมีไวยากรณ์ผิด
 */
export function โหลดผ่านไหม(เนื้อ, ชื่อ = "ปลูก") {
  const f = join(mkdtempSync(join(tmpdir(), "ปลูก-")), `${String(ชื่อ).replace(/[^\w฀-๿-]/g, "_")}.mjs`);
  writeFileSync(f, เนื้อ);
  execFileSync(process.execPath, ["--check", f]);   // โยนถ้าไฟล์พัง
  return true;
}

/** 🔑 ดึง **ชื่อคีย์ระดับบนสุด** ออกจากข้อความ object literal โดย **ไม่ต้องรัน**
 *  (กติกา ⑤ ชั้น ② ที่ตกลงกับฝั่งจอ 28 ก.ย. 2569 — "ประเมินก้อนคำตอบ")
 *
 * 🔴 ที่มา: ฝั่งจอปลูกบั๊กด้วยการแทรก spread **ไว้ก่อน** คีย์เดิม ⇒ คีย์ที่อยู่หลังเขียนทับ
 *    ⇒ **ข้อความเปลี่ยน แต่ผลลัพธ์เหมือนเดิมเป๊ะ** ⇒ ด่านเขียว ซึ่งถูกต้องแล้ว
 *    ⇒ ถ้าเขารีบรายงานตอนนั้นคือกล่าวหาด่านผิด
 * 🔑 กติกาที่ได้: สูตรปลูกต้องพิสูจน์ว่า **ผลลัพธ์** ต่าง ไม่ใช่แค่ **ข้อความ** ต่าง
 *    และคนที่บอกว่า "ผลต่าง" **ต้องไม่ใช่ด่านตัวที่กำลังถูกทดสอบ** (ไม่งั้นเป็นวงกลม)
 *
 * ⚠️ ตัวนี้เป็นชั้น ② ไม่ใช่ ① — มันตอบได้ว่า "ชุดคีย์ต่างไหม" **ไม่ได้ตอบว่าค่าต่างไหม**
 *    ของที่แข็งกว่าคือยกฟังก์ชันออกมารันจริง (ชั้น ①) · ใช้ตัวนี้เมื่อรันไม่ได้
 * @param {string} ก้อน ข้อความที่เริ่มด้วย `{` และปิดด้วย `}`
 * @returns {string[]} ชื่อคีย์ตามลำดับที่ปรากฏ · คีย์ที่ถูกประกาศซ้ำจะโผล่ซ้ำ (ผู้เรียกดูเองว่าใครชนะ)
 */
export function คีย์ของก้อน(ก้อน) {
  const s = String(ก้อน);
  const ออก = [];
  let ลึก = 0;
  let สตริง = null;
  let คำ = "";
  for (let i = 0; i < s.length; i += 1) {
    const c = s[i];
    if (สตริง) { if (c === สตริง && s[i - 1] !== "\\") สตริง = null; continue; }
    if (c === '"' || c === "'" || c === "`") { สตริง = c; คำ += c; continue; }
    if (c === "{" || c === "[" || c === "(") { ลึก += 1; if (ลึก === 1) คำ = ""; continue; }
    if (c === "}" || c === "]" || c === ")") { ลึก -= 1; continue; }
    if (ลึก !== 1) continue;
    if (c === ",") { คำ = ""; continue; }
    if (c === ":") {
      const ชื่อ = คำ.trim().replace(/^["'`]|["'`]$/g, "");
      if (ชื่อ && !ชื่อ.includes("?") && !ชื่อ.includes(" ")) ออก.push(ชื่อ);
      คำ = "";
      /* ข้ามค่าของคีย์นี้ไปจนเจอจุลภาคระดับเดียวกัน */
      let d2 = 0;
      let st2 = null;
      for (i += 1; i < s.length; i += 1) {
        const c2 = s[i];
        if (st2) { if (c2 === st2 && s[i - 1] !== "\\") st2 = null; continue; }
        if (c2 === '"' || c2 === "'" || c2 === "`") { st2 = c2; continue; }
        if ("{[(".includes(c2)) d2 += 1;
        else if ("}])".includes(c2)) { if (d2 === 0) { i -= 1; break; } d2 -= 1; }
        else if (c2 === "," && d2 === 0) break;
      }
      continue;
    }
    คำ += c;
  }
  return ออก;
}
