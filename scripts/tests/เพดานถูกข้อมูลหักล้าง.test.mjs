/* 🔴 ด่าน: **ท่อต้องบอกเองเมื่อข้อมูลของตัวเองหักล้างค่าคงที่ของตัวเอง**
 *
 * 🔑 ประโยคของฝั่งจอ (21 ก.ย. 2569) ที่กลายเป็นกฎ:
 *    *"ข้อมูลที่ขัดกับค่าคงที่ = ค่าคงที่ผิด ไม่ใช่ข้อมูลผิด"*
 *    *"ฝ่ายที่มีทั้งค่าคงที่และข้อมูล ควรเป็นคนบอกเองเมื่อสองอย่างขัดกัน — ไม่ใช่รอคนมาเทียบ"*
 *
 * 🔴 ของจริงที่ทำให้ต้องมี: จอเอา `เพดานเวลาฟังก์ชัน_ms: 30000` ขึ้นจอเป็น **ข้อเท็จจริง**
 *    (*"ฟังก์ชันถูกตัดกลางทางเมื่อเกิน 30 วินาที"*) ทั้งที่สมุดของเราเองมีรอบ **56,374 ms
 *    ที่ทำงานจบและถูกจดสำเร็จ** ⇒ คนอ่านเชื่อว่า "ใกล้ตายแล้ว" ทั้งที่ยังห่างมาก
 *    ⇒ ⇒ และตาข่ายฝั่งจอดักไว้แค่กรณี "ท่อไม่ส่งเพดานมา" ⇒ กรณี "ส่งมาแต่เลขผิด" **เงียบสนิท**
 */
import { test, mock } from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

const ราก = fileURLToPath(new URL("../../netlify/lib/", import.meta.url));
const สภาพ = { แถว: [] };
mock.module(ราก + "coredb.mjs", {
  namedExports: {
    coreReady: () => true, coreInit: async () => null, withD1Meter: (f) => f(),
    d1Stats: () => null, d1Info: () => null,
    /* 🔑 ตัวอ่านสมุดนี้คาดว่า `coreQuery` คืน **อาร์เรย์ตรง ๆ** (มันเรียก `.map()` ทันที)
       ⇒ ตัวปลอมที่คืน `{results:[…]}` ทำให้พังด้วย "is not iterable" — **รูปของตัวปลอมต้องตรงกับของจริง**
       (คลาส: ตัวปลอมที่ไม่ตรงรูป ⇒ แดงด้วยเหตุที่ไม่ใช่บั๊ก · เจอทันทีรอบแรกวันนี้) */
    coreQuery: async (sql) => {
      if (/ALTER|CREATE/i.test(sql)) return [];
      return สภาพ.แถว;
    },
  },
});
const { อ่านเวลางาน } = await import(ราก + "job-timing.mjs");
const { เพดานเวลาฟังก์ชัน_ms } = await import(ราก + "stock-push-sweep.mjs");

const แถวงาน = (ms) => ({
  job: "returns-sync", at: new Date().toISOString(), ms, outcome: "ok", note: null,
  sub_ok: null, sub_fail: null, caller: "cron",
});

test("มีรอบยาวเกินเพดานที่ประกาศ ⇒ ท่อต้อง **ประกาศว่าเพดานนั้นถูกหักล้าง**", async () => {
  สภาพ.แถว = [แถวงาน(เพดานเวลาฟังก์ชัน_ms + 1_000), แถวงาน(5_000)];
  const r = await อ่านเวลางาน({ ชั่วโมงย้อนหลัง: "24" });
  const ข้อความ = r["🔴 เพดานที่ประกาศถูกข้อมูลหักล้างแล้ว"];
  assert.ok(ข้อความ, "ต้องไม่เป็น null เมื่อข้อมูลขัดกับค่าคงที่");
  assert.match(String(ข้อความ), new RegExp(String(เพดานเวลาฟังก์ชัน_ms + 1_000)), "ต้องบอกเลขที่วัดได้จริง");
  assert.match(String(ข้อความ), /ห้ามใช้เลขเพดานนั้นตัดสิน/, "ต้องบอกด้วยว่าห้ามเอาไปใช้ทำอะไร");
});

test("ทุกรอบอยู่ใต้เพดาน ⇒ **เงียบ** (`null`) — ด่านที่ร้องใส่ของปกติจะถูกปิดใน 1 วัน", async () => {
  สภาพ.แถว = [แถวงาน(5_000), แถวงาน(9_999)];
  const r = await อ่านเวลางาน({ ชั่วโมงย้อนหลัง: "24" });
  assert.equal(r["🔴 เพดานที่ประกาศถูกข้อมูลหักล้างแล้ว"], null);
});

test("ไม่มีแถวเลย ⇒ **null** (ไม่ใช่ประกาศว่าเพดานถูกหักล้าง)", async () => {
  สภาพ.แถว = [];
  const r = await อ่านเวลางาน({ ชั่วโมงย้อนหลัง: "24" });
  assert.equal(r["🔴 เพดานที่ประกาศถูกข้อมูลหักล้างแล้ว"], null,
    "ไม่มีข้อมูล ≠ ข้อมูลขัดกับค่าคงที่ (สามสถานะ)");
});

test("🔬 พลังแยกแยะ: ถ้าเกณฑ์เทียบผิดทิศ (<=) เคสแรกจะเงียบ", () => {
  const ถูกทิศ = (ยาวสุด, เพดาน) => (ยาวสุด > เพดาน ? "ประกาศ" : null);
  const ผิดทิศ = (ยาวสุด, เพดาน) => (ยาวสุด < เพดาน ? "ประกาศ" : null);
  assert.equal(ถูกทิศ(56_374, 30_000), "ประกาศ");
  assert.equal(ผิดทิศ(56_374, 30_000), null, "ทิศผิดจะเงียบใส่ของที่ขัดกันจริง");
});
