/* 🚦 ด่าน: **ด่านความถี่ push ต้องอ่าน "push ที่ถึง remote จริง" ไม่ใช่แสตมป์ในเครื่อง**
 *
 * 🔴 ที่มา 21 ก.ย. 2569 — ฝั่งจอเจอกับตัวเอง: ด่านบอก *"push ครั้งก่อนเพิ่งผ่านไป 4 นาที"*
 *    ทั้งที่ **ไม่มี push ไหนสำเร็จเลยใน 3 ชั่วโมง** ⇒ ต้นตอ: แสตมป์ถูกเขียน **ตอนด่านผ่าน**
 *    ซึ่งเกิด *ก่อน* git เริ่มส่งจริง ⇒ push ที่ถูกฆ่า/ล้มกลางทาง **จุดนาฬิกา 45 นาที**
 *    ⇒ เขาเตือนผมให้เช็ค · ผมเช็คแล้ว **ฝั่งผมมีบั๊กเดียวกันเป๊ะ**
 * 🔑 กติกา: **ตัวนับที่ต้องตอบว่า "เกิดขึ้นจริงไหม" ห้ามเขียนก่อนเหตุการณ์**
 *
 * 🚫 ด่านนี้ตรวจ **ตัวบทในตัวติดตั้ง** เพราะ `.git/hooks/` ไม่อยู่ใน git
 *    ⇒ ของจริงที่รันคือ hook ที่ถูกสร้างจากไฟล์นี้ ⇒ ไฟล์นี้จึงเป็น "ต้นฉบับ" ที่ต้องเฝ้า
 *    (พฤติกรรมทดสอบตรง ๆ ไม่ได้ในชุดเทส เพราะต้องมี remote จริง + reflog จริง
 *     ⇒ ผมทดสอบสองทิศด้วยการ **ตัดโค้ดจาก hook ที่ติดตั้งแล้วมารัน** ตอนแก้: 45 นาที ⇒ ผ่าน ·
 *     เกณฑ์ 100000 นาที ⇒ บล็อก · `ALLOW_FAST_PUSH=1` ⇒ ผ่านพร้อมบอกเหตุ)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ตัวติดตั้ง = readFileSync(fileURLToPath(new URL("../install-pre-push.sh", import.meta.url)), "utf8");

test("ต้องอ่านเวลา push ล่าสุดจาก reflog ของ origin/<branch> รายการ `update by push`", () => {
  assert.match(ตัวติดตั้ง, /git reflog show --date=unix "refs\/remotes\/origin\/\$BR"/,
    "ต้องอ่านจาก reflog ของ remote (ของที่ถึง remote จริงเท่านั้น)");
  assert.match(ตัวติดตั้ง, /grep -m1 'update by push'/, "ต้องนับเฉพาะรายการ push — fetch ไม่นับ");
});

test("🚫 ห้ามเขียนแสตมป์เวลาลงเครื่อง (ต้นตอของการล็อกจากสิ่งที่ไม่เคยเกิด)", () => {
  const บรรทัด = ตัวติดตั้ง.split("\n").filter((l) => /\.last-push-at/.test(l) && !/^\s*#/.test(l));
  assert.deepEqual(บรรทัด, [],
    `🔴 ยังมีบรรทัดที่แตะแสตมป์ในเครื่อง: ${บรรทัด.join(" · ")}\n` +
    "   ⇒ แสตมป์ถูกเขียนก่อน git ส่งจริง ⇒ push ที่ล้มจะล็อกรอบถัดไปโดยไม่มีอะไรถึง remote");
});

test("ไม่มีข้อมูลให้เทียบ ⇒ **ต้องบอกว่าไม่รู้** ไม่ใช่เงียบแล้วปล่อยผ่าน", () => {
  assert.match(ตัวติดตั้ง, /ไม่พบรายการ 'update by push'/,
    "กรณีไม่มี reflog ต้องพิมพ์บอก (สามสถานะ: ห่างพอ · ถี่เกิน · ไม่มีข้อมูล)");
  assert.match(ตัวติดตั้ง, /ALLOW_FAST_PUSH/, "ทางด่วนต้องยังอยู่ — ด่านนี้ให้ 'ถี่' เป็นการตัดสินใจ ไม่ใช่ห้าม");
});
