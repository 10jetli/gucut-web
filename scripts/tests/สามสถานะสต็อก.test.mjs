test("รูปของจริง: ตะไบ NEWWAVE — รหัสระดับสินค้าหมด แต่ตัวเลือกอื่นไม่รู้ ⇒ ห้ามขึ้นป้ายหมด", () => {
  /* ของจริงจาก products.json + stock-live.json วันที่เจอ:
     03409-3 = -8 (ZORT รู้) · อีก 5 รหัสไม่รู้จักเลย */
  const สัญญาณ = [
    สถานะจากค่า(-8),                                   // ระดับสินค้า (= ตัวเลือก 4.0มม)
    สถานะของตัวเลือก({ s: -8, sKnown: true }),          // 03409-3
    สถานะของตัวเลือก({ s: 0, sKnown: false }),          // 03413-3
    สถานะของตัวเลือก({ s: 600, sKnown: false }),        // 03496-3
    สถานะของตัวเลือก({ s: 126, sKnown: false }),        // 03409-12
    สถานะของตัวเลือก({ s: 0, sKnown: false }),          // 03413-12
    สถานะของตัวเลือก({ s: 150, sKnown: false }),        // 03496-12
  ];
  const รวม = รวมสถานะ(สัญญาณ);
  assert.equal(รวม, "ไม่รู้", "ตัวเลือกที่ไม่รู้ ต้องกันการสรุปว่าหมด");
  assert.equal(ขึ้นป้ายหมดได้(รวม), false, "🔴 นี่คือป้ายที่ท่านประธานถ่ายจอมา");
  assert.equal(ยังขายได้(รวม), true, "ต้องยังขายได้ — 3 ตัวเลือกมีของรวม 876 ชิ้น");
});

test("รูปของจริง: บาร์ KINGKONG — รหัสระดับสินค้า -3 แต่ 20 นิ้วมี 164 ชิ้น ⇒ มีของ", () => {
  const รวม = รวมสถานะ([
    สถานะจากค่า(-3),                                    // 02984 ระดับสินค้า
    สถานะของตัวเลือก({ s: -3, sKnown: true }),           // 12"
    สถานะของตัวเลือก({ s: 164, sKnown: true }),          // 20" — ของจริงมี
    สถานะของตัวเลือก({ s: 0, sKnown: false }),           // ตัวเลือกที่ยังไม่รู้
  ]);
  assert.equal(รวม, "มีของ");
  assert.equal(ขึ้นป้ายหมดได้(รวม), false);
});

test("ตัวควบคุมลบของทั้งกอง: สินค้าไม่มีตัวเลือก ยังทำงานเหมือนเดิม", () => {
  /* ไม่มีตัวเลือก + รู้ว่า 0 ⇒ หมดจริง (381 ใบที่ขึ้นป้ายอยู่ ต้องไม่หายไป) */
  assert.equal(รวมสถานะ([สถานะจากค่า(0)]), "หมดจริง");
  assert.equal(รวมสถานะ([สถานะจากค่า(5)]), "มีของ");
  /* ไม่มีตัวเลือก + ไม่รู้ ⇒ ไม่รู้ */
  assert.equal(รวมสถานะ([]), "ไม่รู้");
});
