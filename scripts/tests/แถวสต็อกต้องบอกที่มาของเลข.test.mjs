/* 🔑 ด่าน: **ทุกแถวของ `list=stock` ต้องบอกที่มาของเลข** (ใบ t_mul363qv · ท่านประธานติ๊กสั่ง 28 ก.ย. 2569)
 *
 * 🔴 ปัญหาที่แก้: จอคลังเอาเลข `available` ไปเทียบกับ ZORT แล้วเห็นไม่ตรง ⇒ **สรุปว่าระบบเพี้ยน**
 *    ทั้งที่ของกลุ่มหนึ่ง (เลื่อย/บาร์ 30 รหัส) **ทะเบียนใบอนุญาตทับ ZORT โดยตั้งใจ**
 *    เจ้าของร้านสั่งเอง 25 ก.ย. 2569: "ไม่เชื่อ zort ให้อิงตาม google ชีท"
 *    ⇒ ไม่มีช่องไหนบอกเรื่องนี้เลย ⇒ คนอ่านต้องจำเอง หรือไปเถียงกับข้อมูล
 *
 * ⚠️ ช่องนี้บอก **แหล่งของตัวเลข** ไม่ได้บอกว่าเลขถูกหรือผิด
 * ⚠️ เพิ่มช่องอย่างเดียว — จอที่ยังไม่อัปเกรดต้องไม่พัง (prepare-to-receive)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด } from "./_src.mjs";
import { licensedStock, LICENSED } from "../../netlify/lib/licensed-stock.mjs";

const ไฟล์ = "netlify/lib/core-stock.mjs";
const โค้ด = ซอร์สไม่เอาคอมเมนต์(ไฟล์);

test("✅ ทะเบียนใบอนุญาตมีของจริง (ว่าง = ด่านนี้ทดสอบอะไรไม่ได้เลย)", () => {
  const รหัส = Object.keys(LICENSED);
  console.log(`   📏 รหัสที่ทะเบียนทับ ZORT: ${รหัส.length} รหัส · ตัวอย่าง ${รหัส.slice(0, 4).join(" · ")}`);
  assert.ok(รหัส.length >= 10, `ทะเบียนควรมีหลายรหัส · มี ${รหัส.length}`);
});

test("🔑 แถวต้องติดช่อง `src` — และคิดจากทะเบียนจริง ไม่ใช่ค่าคงที่", () => {
  const i = โค้ด.indexOf("src: licensedStock(");
  assert.ok(i > 0, "แถวของ list=stock ยังไม่ติดที่มาของเลข");
  console.log(`   🔎 ${ไฟล์}:${เลขบรรทัด(โค้ด, i)} ติดที่มาของเลขให้ทุกแถว`);
  const บรรทัด = โค้ด.slice(i, โค้ด.indexOf("\n", i));
  assert.match(บรรทัด, /licensedStock\(r\.sku\) !== null \? "licensed" : "mirror"/,
    "ต้องคิดจาก `licensedStock(r.sku)` ของจริง · และเทียบ `!== null` ไม่ใช่ truthy " +
      "(ทะเบียนที่บอกว่าเหลือ 0 เครื่อง = คำตอบที่ถูกต้อง ห้ามตกไปเป็น mirror)");
  assert.match(โค้ด, /import \{ licensedStock \} from "\.\/licensed-stock\.mjs"/, "ต้อง import ของจริง");
});

test("🔑 แถวที่ทะเบียนทับต้องมีคำอธิบายติดไปด้วย — ไม่ใช่ปล่อยให้จอแปลเอง", () => {
  const i = โค้ด.indexOf("srcNote:");
  assert.ok(i > 0, "ขาดคำอธิบาย ⇒ จอจะแปลคำว่า licensed เอง แล้วคำแปลจะแตกกันสองที่");
  const ก้อน = โค้ด.slice(i, i + 400);
  assert.match(ก้อน, /ไม่ตรงกับ ZORT เป็นเรื่องปกติ/,
    "ต้องบอกตรง ๆ ว่าไม่ตรงกับ ZORT เป็นเรื่องปกติ — นี่คือสิ่งที่คนอ่านต้องรู้");
  assert.match(ก้อน, /ทะเบียนว่า:/, "ควรส่งเลขของทะเบียนมาด้วย ⇒ จอเทียบให้คนเห็นได้เลย");
});

test("🔴 `!== null` ไม่ใช่ truthy — ทะเบียนที่บอกว่าเหลือ 0 ต้องยังนับเป็น licensed", () => {
  /* พฤติกรรมจริงของตัวอ่านทะเบียน: 0 เป็นคำตอบที่วัดได้ ไม่ใช่ "ไม่มีข้อมูล" */
  const มีจริง = Object.keys(LICENSED)[0];
  assert.notEqual(licensedStock(มีจริง), null, `${มีจริง} ต้องอยู่ในทะเบียน`);
  assert.equal(licensedStock("รหัสที่ไม่มีจริง-zzz"), null, "รหัสนอกทะเบียนต้องได้ null");
  /* 🧪 ตัวควบคุม: ถ้าใครเปลี่ยนเป็น truthy check รหัสที่เหลือ 0 จะตกไปเป็น mirror */
  const ศูนย์ = Object.entries(LICENSED).find(([, v]) => v === 0);
  if (ศูนย์) {
    assert.notEqual(licensedStock(ศูนย์[0]), null,
      `${ศูนย์[0]} เหลือ 0 เครื่อง แต่ยังอยู่ในทะเบียน ⇒ ต้องเป็น licensed ไม่ใช่ mirror`);
    console.log(`   🧪 มีรหัสที่ทะเบียนบอกว่าเหลือ 0: ${ศูนย์[0]} ⇒ เคสนี้ทดสอบได้จริง`);
  } else {
    console.log("   ⚠️ วันนี้ไม่มีรหัสที่ทะเบียนบอกว่าเหลือ 0 ⇒ เคส truthy ยังไม่ถูกเดินจริง (ไม่ใช่ว่าผ่าน)");
  }
});

test("🔒 เพิ่มช่องอย่างเดียว — ช่องเดิมของแถวต้องอยู่ครบ", () => {
  for (const ช่อง of ["sku:", "qty:", "price:", "sold:", "buy:", "available:", "unit:", "weight:", "service:", "active:"])
    assert.ok(โค้ด.includes(ช่อง), `ช่อง ${ช่อง} หายจากแถว ⇒ จอที่ยังไม่อัปเกรดจะพัง`);
});
