import { mkdirSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const ล็อก = join(tmpdir(), "gucut-ปลูกไฟล์จริง.lock");
const หมดอายุ = 180_000;   // 3 นาที — นานกว่าเทสหนึ่งไฟล์มาก

const หลับ = (ms) =>
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);

const เริ่ม = Date.now();
for (;;) {
  try {
    mkdirSync(ล็อก);
    break;
  } catch {
    try {
      if (Date.now() - statSync(ล็อก).mtimeMs > หมดอายุ) {
        rmSync(ล็อก, { recursive: true, force: true });
        continue;                      // ล็อกค้างจากโปรเซสที่ตายแล้ว ⇒ ยึดคืน
      }
    } catch { /* ล็อกหายไปเอง — วนลองใหม่ */ }
    if (Date.now() - เริ่ม > หมดอายุ) {
      throw new Error("รอล็อกเทสนานเกิน 3 นาที — มีอะไรค้างใน " + ล็อก);
    }
    หลับ(20);
  }
}

const ปล่อย = () => rmSync(ล็อก, { recursive: true, force: true });
process.on("exit", ปล่อย);
process.on("SIGINT", () => { ปล่อย(); process.exit(130); });
process.on("SIGTERM", () => { ปล่อย(); process.exit(143); });
