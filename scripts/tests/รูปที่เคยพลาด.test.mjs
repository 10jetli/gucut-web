/* เทสคลังตัวควบคุมจากความผิดพลาดจริง
 * 🔑 ข้อของฝั่งจอ: **ความผิดพลาดของอีกฝ่ายคือตัวควบคุมที่ดีที่สุด** เพราะเป็นรูปที่มีคนพลาดจริงแล้ว
 *    ⇒ เทสนี้พิสูจน์ว่าคลังนี้ **แยกแยะได้** ด้วยตะแกรงปลอมสองตัว (ตัวที่ดี · ตัวที่พลาดแบบเดิม)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ตรวจตะแกรงกับรูปที่เคยพลาด, รูปที่ตะแกรงข้อความเคยพลาด, รูปที่ตัววัดเคยหลอก } from "../lib/รูปที่เคยพลาด.mjs";

test("คลังมีทั้งรูปที่ควรจับและตัวควบคุมลบ", () => {
  const บวก = รูปที่ตะแกรงข้อความเคยพลาด.filter((r) => r.ควรจับ).length;
  const ลบ = รูปที่ตะแกรงข้อความเคยพลาด.filter((r) => !r.ควรจับ).length;
  assert.ok(บวก >= 3, "ต้องมีรูปที่ควรจับหลายรูป");
  assert.ok(ลบ >= 3, "ต้องมีตัวควบคุมลบด้วย — ด่านที่ร้องใส่ของปกติจะถูกปิดใน 1 วัน");
  assert.ok(รูปที่ตัววัดเคยหลอก.length >= 5, "คลังตัววัดต้องมีทั้งทิศโหดเกินและใจดีเกิน");
  /* 🔑 ทุกรูปต้องบอกที่มา **รวมถึงรูปที่เรานึกเอา** — เทสข้อนี้จับได้ในรันแรกว่า 3 รูป
     ไม่มีที่มา ⇒ เติมคำว่า "ผมนึกเอา" ให้ตรงความจริง แทนที่จะปล่อยให้ดูเหมือนเคสจริง
     ⇒ คลังนี้มีค่าเพราะ "มีคนพลาดจริง" ⇒ ถ้าปนรูปที่นึกเอาโดยไม่บอก น้ำหนักจะเฟ้อ */
  for (const r of รูปที่ตะแกรงข้อความเคยพลาด) {
    /* 🔒 สามข้อที่ฝั่งจอบังคับในคลังของเขา — ผมยกมาทั้งสามข้อ */
    assert.equal(typeof r.ของจริง, "boolean",
      "ช่อง `ของจริง` ต้องเป็น boolean เสมอ — ห้ามปล่อยว่างให้คนเดา");
    assert.match(r.ที่มา, /\d+ ก\.ย\. 2569/, "ที่มาต้องบอก **เมื่อไหร่**");
    assert.match(r.ที่มา, /ท่อ|จอ/, "ที่มาต้องบอก **ใครพลาด**");
    assert.ok(r.ที่มา.includes("—"), "ที่มาต้องเล่าว่า **อะไรพลาด** (คำอธิบายหลัง —)");
  }
  /* 🔴 เดิมผมแยกเคสจริงด้วย `ที่มา.includes("ผมนึกเอา")` = **จัดประเภทด้วย substring**
     ซึ่งผิดกฎของทีมเราเอง (`no-substring-classification`) — ฝั่งจอใช้ช่อง boolean แยก ผมยกมา
     ⇒ วันที่มีคนเขียน "นึกขึ้นเอง"/"สมมติ" แทน รูปนั้นจะถูกนับเป็นเคสจริงเงียบ ๆ */
  const เคสจริง = รูปที่ตะแกรงข้อความเคยพลาด.filter((r) => r.ของจริง);
  assert.ok(เคสจริง.length >= 6, `ต้องมีเคสจริงอย่างน้อย 6 รูป (มี ${เคสจริง.length})`);
});

test("🔑 ตะแกรงที่พลาดแบบเดิม (รับตัวปิดท้ายแค่ , ; ) ]) ต้องถูกจับได้", () => {
  /* นี่คือความผิดพลาดจริงของฝั่งท่อเมื่อ 19 ก.ย. 2569 ค่ำ */
  const ตะแกรงที่พลาด = (s) => {
    const m = /(?:\?\?|\|\|)\s*([A-Za-z_$][\w$]*|[฀-๿][\w฀-๿]*)\s*[,;)\]]/.exec(s);
    return !!m && new RegExp(`(?:const|let|var)\\s+${m[1]}\\s*=\\s*(true|["']ok["'])`).test(s);
  };
  const { ทดสอบ, ผิด } = ตรวจตะแกรงกับรูปที่เคยพลาด(ตะแกรงที่พลาด, ["ตัวปิดท้าย", "ปิดท้าย"]);
  assert.ok(ทดสอบ >= 3, `ต้องทดสอบอย่างน้อย 3 รูป (ได้ ${ทดสอบ})`);
  assert.ok(ผิด.length >= 1, "คลังต้องจับตะแกรงรุ่นที่พลาดได้ — ไม่งั้นคลังนี้ไม่มีค่า");
});

test("ตะแกรงที่แก้แล้ว (รับ } และท้ายบรรทัด) ต้องผ่านทุกรูป", () => {
  const ตะแกรงที่แก้แล้ว = (s) => {
    const m = /(?:\?\?|\|\|)\s*([A-Za-z_$][\w$]*|[฀-๿][\w฀-๿]*)\s*(?:[,;)\]}]|$)/m.exec(s);
    return !!m && new RegExp(`(?:const|let|var)\\s+${m[1]}\\s*=\\s*(true|["']ok["'])`).test(s);
  };
  const { ทดสอบ, ผิด } = ตรวจตะแกรงกับรูปที่เคยพลาด(ตะแกรงที่แก้แล้ว, ["ตัวปิดท้าย", "ปิดท้าย", "ตัวควบคุมลบ"]);
  assert.deepEqual(ผิด, [], `ตะแกรงที่แก้แล้วต้องผ่านทุกรูป (ทดสอบ ${ทดสอบ})`);
  assert.ok(ทดสอบ > 0, "ผ่าน 0/0 ไม่ใช่ข่าวดี — มันคือ 'ไม่ได้ทดสอบ'");
});

test("ผลลัพธ์ต้องบอกจำนวนที่ทดสอบเสมอ (0/0 ≠ ผ่าน)", () => {
  const { ทดสอบ, ผิด } = ตรวจตะแกรงกับรูปที่เคยพลาด(() => false, ["ไม่มีที่มานี้จริงZZNOPEZZ"]);
  assert.equal(ทดสอบ, 0);
  assert.deepEqual(ผิด, []);
  // 🔑 ผู้เรียกต้องเช็ค `ทดสอบ > 0` เอง — ฟังก์ชันคืนจำนวนให้เพื่อให้เช็คได้
});
