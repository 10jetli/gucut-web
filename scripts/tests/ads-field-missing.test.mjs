/* ด่าน: ค่าโฆษณาอ่านไม่ได้ ต้องไม่ขึ้นเป็น ฿0 เงียบ ๆ — ตรวจด้วย "ความสัมพันธ์ระหว่างสองช่อง"
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · ใบ t_mu7uzpld
 *    ไฟล์นี้เป็นเคสที่ **วิธี "นับจำนวนแถวที่อ่านไม่ได้" ใช้ไม่ได้**
 *    เพราะแคมเปญที่ไม่ได้ยิงจริง ๆ ก็ไม่มีช่อง `spend` และ **0 คือคำตอบที่ถูก**
 *    ⇒ ด่านที่ร้องใส่ของปกติจะถูกปิดภายในวันเดียว
 * 🔑 ตัวชี้ขาดที่แยกได้จริง: **มียอดแสดงผล = โฆษณาถูกส่งออกไปแล้ว ⇒ ต้องมีค่าใช้จ่าย**
 *    ⇒ impressions > 0 แต่ **ไม่มีช่อง spend** = ช่องหาย ไม่ใช่ไม่ได้ใช้เงิน
 *    ⇒ ถ้าปล่อย: ค่าโฆษณา ฿0 ทั้งกระดาน ⇒ ROAS เป็นอนันต์ ⇒ ตัดสินใจเร่งงบจากเลขปลอม
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ตรวจช่องค่าโฆษณาหาย } from "../../netlify/lib/adstats.mjs";

test("🧪 ปลูกบั๊ก: Facebook เปลี่ยนชื่อช่องค่าใช้จ่าย ⇒ ต้องเตือน", () => {
  const เตือน = ตรวจช่องค่าโฆษณาหาย([
    { campaign_name: "A", impressions: "1500", clicks: "40", cost: "300" },   // ชื่อใหม่ที่เราไม่รู้จัก
    { campaign_name: "B", impressions: "800", clicks: "12", cost: "150" },
  ]);
  assert.match(String(เตือน), /มียอดแสดงผลแต่ไม่มีช่องค่าใช้จ่าย/);
  assert.match(String(เตือน), /2 จาก 2/, "ต้องบอกจำนวน ไม่ใช่บอกแค่ว่าเสีย");
});

test("🔑 พลังแยกแยะ ①: แคมเปญที่ไม่ได้ยิง (ไม่มีทั้งแสดงผลและค่าใช้จ่าย) ⇒ **ต้องไม่เตือน**", () => {
  /* นี่คือของปกติที่เกิดทุกวัน — ถ้าข้อนี้แดง ด่านจะร้องทุกวันแล้วคนจะปิดมันทิ้ง */
  assert.equal(ตรวจช่องค่าโฆษณาหาย([
    { campaign_name: "หยุดไว้", impressions: "0", clicks: "0" },
    { campaign_name: "ยังไม่เริ่ม" },
  ]), null);
});

test("🔑 พลังแยกแยะ ②: ใช้เงินจริงแต่เป็น 0 บาท (มีช่อง ค่าเป็น 0) ⇒ **ต้องไม่เตือน**", () => {
  assert.equal(ตรวจช่องค่าโฆษณาหาย([
    { campaign_name: "A", impressions: "1500", spend: "0" },
  ]), null, "\"มีช่องแล้วค่าเป็น 0\" ต่างจาก \"ไม่มีช่อง\" — ด่านต้องแยกสองอย่างนี้ออก");
});

test("ปกติครบทุกช่อง ⇒ ไม่เตือน", () => {
  assert.equal(ตรวจช่องค่าโฆษณาหาย([
    { campaign_name: "A", impressions: "1500", spend: "300.55" },
  ]), null);
});

test("เตือนเฉพาะแถวที่เข้าเงื่อนไข — ไม่เหมารวมทั้งกอง", () => {
  const เตือน = ตรวจช่องค่าโฆษณาหาย([
    { campaign_name: "ปกติ", impressions: "1000", spend: "200" },
    { campaign_name: "ช่องหาย", impressions: "1000" },
    { campaign_name: "ไม่ได้ยิง", impressions: "0" },
  ]);
  assert.match(String(เตือน), /1 จาก 3/);
});

test("ไม่มีข้อมูลมาเลย ⇒ ไม่เตือน (ไม่ใช่หน้าที่ด่านนี้)", () => {
  /* กองว่างมีสาเหตุอื่นได้เยอะ (สิทธิ์ ads_read ไม่ได้ให้ · ช่วงวันไม่มีข้อมูล)
     ⇒ ด่านนี้ต้องไม่แย่งหน้าที่ไปตอบแทน ไม่งั้นเหตุผลจะกระจายอยู่สองที่ */
  assert.equal(ตรวจช่องค่าโฆษณาหาย([]), null);
  assert.equal(ตรวจช่องค่าโฆษณาหาย(null), null);
  assert.equal(ตรวจช่องค่าโฆษณาหาย(undefined), null);
});

test("ยอดแสดงผลที่มีจุลภาค ต้องอ่านได้ (ไม่งั้นด่านเงียบเพราะอ่านตัวชี้ขาดไม่ออก)", () => {
  /* 🔑 ถ้าด่านอ่าน impressions ไม่ออก มันจะไม่ร้อง = **ตัวชี้ขาดพังไปทางเดียวกับปัญหา** */
  const เตือน = ตรวจช่องค่าโฆษณาหาย([{ campaign_name: "A", impressions: "1,500" }]);
  assert.match(String(เตือน), /1 จาก 1/);
});
