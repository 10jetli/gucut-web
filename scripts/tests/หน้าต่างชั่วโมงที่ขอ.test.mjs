/* 🪟 ด่าน: **`hours` ที่ถูกปรับ ต้องประกาศตัว**
 *
 * 🔴 ที่มา 20 ก.ย. 2569 ค่ำ (ของจริง ผมเกือบเชื่อเอง):
 *    ยิง `?jobtiming=1&hours=0.5` เพื่อหาเวลาของแถว ⇒ `parseInt("0.5")` = 0 ⇒ `|| 24`
 *    ⇒ **คืนผลของ 24 ชม. เงียบ ๆ** ⇒ ได้ 17 แถว ซึ่งอ่านได้ว่า "17 แถวใน 30 นาที"
 *    = **การค้นพบใหญ่ที่เป็นเท็จ** · และ `hours=1.5` กลายเป็น 1 โดยไม่บอก
 * 🔑 คลาส: **ทางถอยที่ไม่ประกาศตัวจะกลายเป็นทางหลักโดยไม่มีใครตัดสินใจ** [[fallbacks-must-announce]]
 *    ⇒ หนักกว่าปกติเพราะเส้นนี้คือ **เครื่องมือที่ทั้งสองบัญชีใช้วัดเรื่องความถี่ของงานตามเวลา**
 *
 * 🚫 ด่านนี้ไม่ได้บอกว่า "ค่าที่ปรับถูกต้อง" — มันบอกว่า **คนอ่านจะรู้ว่ามันถูกปรับ**
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ตีความชั่วโมง } from "../../netlify/lib/job-timing.mjs";

test("ค่าปกติใช้ตรง ๆ และ **ไม่ประกาศ** (ไม่ใส่เสียงรบกวน)", () => {
  for (const v of ["6", 6, "24", "168", "1"]) {
    const r = ตีความชั่วโมง(v);
    assert.equal(r.ชม, Number(v));
    assert.equal(r.ปรับเพราะ, null, `hours=${v} ไม่ควรมีคำประกาศ`);
  }
  assert.deepEqual(ตีความชั่วโมง(undefined), { ชม: 24, ปรับเพราะ: null }, "ไม่ส่งมา = ค่าเริ่มต้น 24 ไม่ถือว่าถูกปรับ");
});

test("🔑 ทุกค่าที่ใช้ไม่ได้ ต้องได้คำประกาศกลับไป", () => {
  const เคส = ["0.5", "1.5", "abc", "0", "-3", "999", ""];
  for (const v of เคส) {
    const r = ตีความชั่วโมง(v);
    assert.ok(r.ชม >= 1 && r.ชม <= 168, `hours=${v} ต้องได้ค่าที่ใช้ได้ (ได้ ${r.ชม})`);
    if (v === "") { assert.equal(r.ปรับเพราะ, null); continue; }
    assert.ok(r.ปรับเพราะ, `🔴 hours=${v} ถูกปรับแต่ไม่ประกาศ ⇒ คนวัดจะเทียบคนละหน้าต่างโดยไม่รู้ตัว`);
    assert.match(String(r.ปรับเพราะ), new RegExp(v.replace("-", "\\-")), "คำประกาศต้องบอกค่าที่ขอมาด้วย");
  }
});

test("🔬 พลังแยกแยะ: ของเดิม (parseInt || 24) ต้องทำให้ข้อบนแดง", () => {
  /* 🚫 ไม่ import ของเดิมมาเทียบ (มันถูกลบแล้ว) ⇒ เขียนซ้ำ **รูปเดิม** เป็นตัวเทียบ
     🔑 ถ้าเขียนตัวเทียบไม่ได้ ก็พิสูจน์ไม่ได้ว่าด่านนี้จับอะไรได้จริง */
  const รุ่นเดิม = (v) => ({ ชม: Math.min(168, Math.max(1, Number.parseInt(v ?? "24", 10) || 24)), ปรับเพราะ: null });
  assert.equal(รุ่นเดิม("0.5").ชม, 24, "รูปเดิมถอยไป 24 จริง");
  assert.equal(รุ่นเดิม("0.5").ปรับเพราะ, null, "และเงียบ — นี่คือสิ่งที่ด่านนี้ห้าม");
  assert.notEqual(ตีความชั่วโมง("0.5").ปรับเพราะ, null, "รุ่นใหม่ต้องประกาศ");
  assert.notEqual(ตีความชั่วโมง("0.5").ชม, 24, "และต้องไม่แอบขยายหน้าต่างเป็น 24");
});

test("คำตอบของ `/api/core?jobtiming=1` ต้องส่งช่องประกาศนี้ออกไปให้จอ", () => {
  const s = ตีความชั่วโมง("1.5");
  assert.equal(s.ชม, 2, "1.5 ⇒ ปัดเป็น 2 (ไม่ใช่ตัดเป็น 1 แบบ parseInt)");
  assert.match(String(s.ปรับเพราะ), /ปัด/, "ต้องบอกว่าปัด");
});
