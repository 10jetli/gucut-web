// ทางเข้าหน้าผังจาก "ชื่อสินค้า" — ทดสอบ **กลไก** ไม่ใช่ตัวเลขที่วัดได้วันนี้
//
// 🔑 ทำไมเทสนี้ไม่ยืนยันว่า "ครอบ 1,377 ชิ้น": เลขนั้นโตและหดตามคลังสินค้าทุกวัน
//    เทสที่ตรึงเลขไว้จะแดงทุกครั้งที่ร้านเพิ่มของ ⇒ คนจะแก้เลขให้ตรงโค้ด ⇒ พลังแยกแยะหมดไป
//    (บทเรียน `test-must-discriminate` ข้อ ④) ⇒ ตรึง **กฎการจับคู่** ซึ่งเปลี่ยนเมื่อมีคนตั้งใจเปลี่ยน
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  คำรุ่น, คำเรียกของรุ่น, แยกตำแหน่ง, ตรวจตำแหน่งในคู่มือ, รุ่นที่ลิงก์ได้, ที่อยู่ลิงก์,
} from "../../src/lib/parts-fits.mjs";

const รุ่นตัวอย่าง = [
  { slug: "fmini", ชื่อ: "MINI", คำค้นร้าน: "MINI" },
  { slug: "f038", ชื่อ: "MS 038", คำค้นร้าน: "MS038" },
  { slug: "f440", ชื่อ: "F 440", คำค้นร้าน: "MS440" },
];

/** คู่มือ fmini ของจริงเขียนเลขแถว **ติดตัวอักษรกลุ่ม** (L7) */
const คู่มือMini = {
  กลุ่ม: [
    { ตัวอักษร: "L", อะไหล่: [{ เลข: "L6", รหัส: "23716321000" }, { เลข: "L7", รหัส: "23715483000" }] },
    { ตัวอักษร: "A", อะไหล่: [{ เลข: "A1", รหัส: "x" }] },
  ],
};
/** อีก 15 เล่มเขียนเลขแถว **เปล่า ๆ ต่อกลุ่ม** (7) — รูปคนละแบบกับข้างบน */
const คู่มือ440 = {
  กลุ่ม: [{ ตัวอักษร: "L", อะไหล่: [{ เลข: "6", รหัส: "y" }, { เลข: "7", รหัส: "z" }] }],
};
const คู่มือของรุ่น = (slug) =>
  slug === "fmini" ? คู่มือMini : slug === "f440" ? คู่มือ440 : null;

test("รุ่นที่ยังไม่มีหน้าผัง ห้ามโชว์ลิงก์ (ข้อ ③ ของใบสั่ง)", () => {
  // 9800 มีของในคลังจริงร้อยกว่าชิ้น แต่ไม่มีคู่มือ ⇒ ลิงก์ที่กดแล้ว 404 แย่กว่าไม่มีลิงก์
  assert.deepEqual(รุ่นที่ลิงก์ได้({ fits: ["9800"], pos: ["A1"] }, รุ่นตัวอย่าง, คู่มือของรุ่น), []);
  assert.deepEqual(รุ่นที่ลิงก์ได้({ fits: [] }, รุ่นตัวอย่าง, คู่มือของรุ่น), []);
  assert.deepEqual(รุ่นที่ลิงก์ได้(undefined, รุ่นตัวอย่าง, คู่มือของรุ่น), []);
});

test("เทียบรุ่นต้องเท่ากันเป๊ะ — ชื่อที่ยาวกว่าห้ามผ่านฟรี", () => {
  // 🔴 ข้อที่ต้องแดงถ้าใครเปลี่ยนไปใช้ includes(): MINI-ONE มีของ 142 ชิ้นในคลัง
  //    และท่านประธานสั่งว่า **ไม่ทำรุ่นนั้น** ⇒ หลุดไปคือพาลูกค้าไปดูผังของรุ่นอื่น
  assert.deepEqual(รุ่นที่ลิงก์ได้({ fits: ["MINI-ONE"] }, รุ่นตัวอย่าง, คู่มือของรุ่น), []);
  assert.equal(รุ่นที่ลิงก์ได้({ fits: ["MINI"] }, รุ่นตัวอย่าง, คู่มือของรุ่น).length, 1);
});

test("รับคำเรียกรุ่นทั้งสามรูปที่ตาราง PARTS_MODELS ประกาศเอง", () => {
  // slug (F038) · ชื่อ (MS 038) · คำค้นร้าน (MS440) — ของจริงใช้ครบทั้งสามรูป
  assert.equal(รุ่นที่ลิงก์ได้({ fits: ["F038"] }, รุ่นตัวอย่าง, คู่มือของรุ่น)[0]?.slug, "f038");
  assert.equal(รุ่นที่ลิงก์ได้({ fits: ["MS 038"] }, รุ่นตัวอย่าง, คู่มือของรุ่น)[0]?.slug, "f038");
  assert.equal(รุ่นที่ลิงก์ได้({ fits: ["MS440"] }, รุ่นตัวอย่าง, คู่มือของรุ่น)[0]?.slug, "f440");
  assert.deepEqual([...คำเรียกของรุ่น(รุ่นตัวอย่าง[1])].sort(), ["F038", "MS038"]);
  assert.equal(คำรุ่น(" ms 440 "), "MS440");
});

test("ตำแหน่งต้องยืนยันกับคู่มือเล่มนั้น — เลขแถวสองรูปแบบที่คู่มือใช้จริง", () => {
  // เล่มที่เขียน L7: ยิง L7 ได้ L7
  assert.deepEqual(ตรวจตำแหน่งในคู่มือ(คู่มือMini, "L7"), { กลุ่ม: "L", เลข: "L7" });
  // เล่มที่เขียน 7 เปล่า ๆ: ยิง L7 ต้องถอยไปใช้ 7 **ไม่ใช่ตอบ null**
  assert.deepEqual(ตรวจตำแหน่งในคู่มือ(คู่มือ440, "L7"), { กลุ่ม: "L", เลข: "7" });
  // กลุ่มมีแต่ไม่มีแถวนั้น ⇒ null (ของจริง: f5200 กลุ่ม E ไม่มีแถว 26)
  assert.equal(ตรวจตำแหน่งในคู่มือ(คู่มือMini, "L99"), null);
  // ไม่มีกลุ่มนั้นเลย ⇒ null (ของจริง: f5200 ไม่มีกลุ่ม J)
  assert.equal(ตรวจตำแหน่งในคู่มือ(คู่มือMini, "J1"), null);
  // รูปแบบที่ไม่มีตัวอักษรกลุ่ม ⇒ null (ของจริงในคลัง: "NO.17")
  assert.equal(แยกตำแหน่ง("NO.17"), null);
  assert.equal(ตรวจตำแหน่งในคู่มือ(คู่มือMini, "NO.17"), null);
  // คู่มืออ่านไม่ได้ ⇒ null ไม่ใช่โยน error (ไฟล์หายต้องไม่ทำ build ล้ม)
  assert.equal(ตรวจตำแหน่งในคู่มือ(null, "L7"), null);
});

test("ที่อยู่ลิงก์ติดพารามิเตอร์เฉพาะตำแหน่งที่ยืนยันแล้ว", () => {
  const มี = รุ่นที่ลิงก์ได้({ fits: ["MINI"], pos: ["L7"] }, รุ่นตัวอย่าง, คู่มือของรุ่น)[0];
  assert.equal(ที่อยู่ลิงก์(มี), "/parts/fmini/?g=L&n=L7");
  // 🔑 ยืนยันไม่ได้ ⇒ **ลิงก์เปล่า** ไม่ใช่ติดพารามิเตอร์มั่วไปให้จอเมิน
  const ไม่มี = รุ่นที่ลิงก์ได้({ fits: ["MINI"], pos: ["L99"] }, รุ่นตัวอย่าง, คู่มือของรุ่น)[0];
  assert.equal(ที่อยู่ลิงก์(ไม่มี), "/parts/fmini/");
  assert.equal(ไม่มี.เลข, null);
  // ไม่มี pos เลย ⇒ ลิงก์เปล่า (1,164 ลิงก์ของจริงเป็นแบบนี้ — ถูกต้องแล้ว)
  const เปล่า = รุ่นที่ลิงก์ได้({ fits: ["MINI"] }, รุ่นตัวอย่าง, คู่มือของรุ่น)[0];
  assert.equal(ที่อยู่ลิงก์(เปล่า), "/parts/fmini/");
});

test("ของจริงที่ท่านประธานวงมา: 04554 ยางกันกระแทก MINI L7", async () => {
  const fs = await import("node:fs");
  const pi = JSON.parse(fs.readFileSync("src/data/part-info.json", "utf8"));
  const ps = JSON.parse(fs.readFileSync("src/data/products.json", "utf8"));
  const p = ps.find((x) => x.sku === "04554");
  assert.ok(p, "ไม่เจอสินค้า 04554 ในคลัง — ถ้าร้านลบของจริง ให้เปลี่ยนตัวอย่างในเทสนี้");
  const ชิ้น = pi[p.h];
  assert.deepEqual(ชิ้น.fits, ["MINI"]);
  assert.deepEqual(ชิ้น.pos, ["L7"]);
  const doc = JSON.parse(fs.readFileSync("public/parts/fmini.json", "utf8"));
  const แถว = doc.กลุ่ม.find((g) => g.ตัวอักษร === "L").อะไหล่.find((r) => r.เลข === "L7");
  // 🔑 ข้อที่ทำให้เชื่อว่าตำแหน่งถูก ไม่ใช่แค่ "สตริงตรงกัน":
  //    ชื่อสินค้าบอก "ยางกันกระแทก ... ใช้ 2 ชิ้น" · คู่มือบอก buffer จำนวน 2
  assert.equal(แถว.ชื่อ, "buffer");
  assert.equal(แถว.จำนวน, "2");
  assert.match(p.t, /ใช้ 2 ชิ้น/);
  const ได้ = รุ่นที่ลิงก์ได้(ชิ้น, [{ slug: "fmini", ชื่อ: "MINI", คำค้นร้าน: "MINI" }], () => doc);
  assert.equal(ที่อยู่ลิงก์(ได้[0]), "/parts/fmini/?g=L&n=L7");
});
