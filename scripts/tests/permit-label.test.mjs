/* ด่าน: ป้าย 【ต้องขอ ลซ.2 ก่อน】 ต้องติดถูกตัว — และ **ผิดได้สองทิศ ทั้งสองทิศแพง**
 *
 * 🔴 ที่มา 10 ต.ค. 2569 · ท่านประธานสั่ง "【ต้องขอ ลซ.2 ก่อน】 จัดการ ทุกที่ · ที่เว็บ gucut ด้วย"
 *    เหตุ: ลูกค้าสั่งซื้อได้โดยไม่รู้ว่าต้องขอใบอนุญาตก่อน ⇒ สั่งมาแล้วร้านส่งไม่ได้
 *    และท่านห้ามเองในใบสั่ง: *"ติดผิดตัว = บอกลูกค้าว่าต้องขอใบทั้งที่ไม่ต้อง ⇒ เสียลูกค้าฟรี ๆ"*
 *
 * 🔑 ข้อที่ด่านนี้มีไว้จับ (ไม่ใช่ "เรียกแล้วไม่พัง"):
 *    ① **ติดน้อยไป** — เลื่อยที่ต้องขอแต่ไม่อยู่ในทะเบียน (F038 · F090 · F880 ไม่เคยนำเข้า
 *       และ **ไม่มี sku เลยทั้งสามใบ**) · ตัวเลือกสีที่ไม่อยู่ในทะเบียน (`F660-black`)
 *    ② **ติดเกินไป** — 12″/11.8″ · KK 20″/22″ · กลุ่ม 7800/5800/MINI (EXEMPT_MODELS)
 *    ③ **เทียบรหัสหลวม** — `00073-11.8-NW` ต้องจับได้ แต่ `000731` ต้องไม่ถูกจับ
 *    ④ **รายชื่อในโค้ดหลงจาก licensed-stock.json** ⇒ เทสเทียบสองไฟล์ทุกรอบ
 *    ⑤ **ของควบคุมตัวใหม่เข้ามาแล้วเงียบ** ⇒ สินค้าหมวดเลื่อย/บาร์ทุกใบต้องตอบ
 *       "ต้องขอ" หรือ "ยกเว้น" เท่านั้น **ห้ามมีใบไหนตกมาเป็น "ไม่เกี่ยว"**
 */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import {
  ป้ายลซ2, ขึ้นต้นด้วยรหัส, สถานะป้ายของตัวเลือก, ตัวเลือกต้องขอลซ2, ป้ายของสินค้า,
  ตัวเลือกบาร์ในทะเบียน, รหัสเลื่อยต้องขอ, รหัสยกเว้น, handleเลื่อยต้องขอ,
} from '../../src/lib/permit-label-core.mjs';

const อ่าน = (p) => JSON.parse(readFileSync(p, 'utf8'));
const ทะเบียน = อ่าน('src/data/licensed-stock.json');
const สินค้า = อ่าน('src/data/products.json');
const หา = (ตรง) => สินค้า.find(ตรง);

test('ข้อความป้ายต้องเป็นปีกกาหนา 【 】 ไม่ใช่ [ ] (ท่านสั่งเจาะจง)', () => {
  assert.equal(ป้ายลซ2, '【ต้องขอ ลซ.2 ก่อน】');
  assert.ok(!ป้ายลซ2.includes('['), 'ห้ามใช้วงเล็บเหลี่ยมธรรมดา');
});

test('รายชื่อในโค้ดต้องตรงกับ licensed-stock.json ทั้งสามชุด', () => {
  const บาร์จากjson = Object.keys(ทะเบียน['บาร์ตัวเลือก→ขนาดยี่ห้อ']).filter((k) => !k.startsWith('_'));
  assert.deepEqual([...ตัวเลือกบาร์ในทะเบียน].sort(), บาร์จากjson.sort(),
    'ตัวเลือกบาร์ในทะเบียนต้องตรงกับคีย์ของ บาร์ตัวเลือก→ขนาดยี่ห้อ');
  const เลื่อยจากjson = Object.entries(ทะเบียน['รุ่นเลื่อย→รหัสสินค้า'])
    .filter(([k]) => !k.startsWith('_')).map(([, v]) => v);
  assert.deepEqual([...รหัสเลื่อยต้องขอ].sort(), เลื่อยจากjson.sort(),
    'รหัสเลื่อยต้องขอต้องตรงกับค่าของ รุ่นเลื่อย→รหัสสินค้า');
  const บาร์ยกเว้นจากjson = Object.keys(ทะเบียน['_บาร์ที่ไม่ต้องขึ้นทะเบียน ใช้ ZORT ต่อ'])
    .filter((k) => !k.startsWith('_'));
  for (const รหัส of บาร์ยกเว้นจากjson)
    assert.ok(รหัสยกเว้น.includes(รหัส), `รหัส ${รหัส} อยู่ในรายการยกเว้นของ json แต่ไม่อยู่ในโค้ด`);
});

test('เทียบรหัสต้องมีขอบเขต — จับ 00073-11.8-NW แต่ห้ามจับ 000731', () => {
  assert.equal(ขึ้นต้นด้วยรหัส('00073', '00073'), true);
  assert.equal(ขึ้นต้นด้วยรหัส('00073-11.8-NW', '00073'), true);
  assert.equal(ขึ้นต้นด้วยรหัส('00073-OnlyMachine', '00073'), true);
  /* 🔴 ตัวควบคุมลบที่ทำให้เทสนี้แยกแยะได้ — ถ้าใครเปลี่ยนไปใช้ includes/startsWith เปล่า ๆ ข้อนี้แดง */
  assert.equal(ขึ้นต้นด้วยรหัส('000731', '00073'), false, 'รหัสที่ยาวกว่าต้องไม่ถูกจับ');
  assert.equal(ขึ้นต้นด้วยรหัส('x-00073', '00073'), false, 'ต้องขึ้นต้นเท่านั้น ไม่ใช่เจอที่ไหนก็ได้');
  assert.equal(ขึ้นต้นด้วยรหัส('', '00073'), false);
  assert.equal(ขึ้นต้นด้วยรหัส(null, '00073'), false);
});

test('🔴 บาร์ใบเดียวต้องแยกราย "ขนาด" — 12″ ยกเว้น · 16″ ขึ้นไปต้องขอ', () => {
  const นว = หา((p) => p.sku === '01387');
  const กก = หา((p) => p.sku === '02984');
  assert.ok(นว && กก, 'ต้องเจอสินค้าบาร์ทั้งสองใบ');
  assert.equal(สถานะป้ายของตัวเลือก({ sku: นว.sku, k: '01387', h: นว.h }), 'ยกเว้น');
  assert.equal(สถานะป้ายของตัวเลือก({ sku: นว.sku, k: 'Bar NW 16', h: นว.h }), 'ต้องขอ');
  assert.equal(สถานะป้ายของตัวเลือก({ sku: กก.sku, k: '02984', h: กก.h }), 'ยกเว้น');  // 12″
  assert.equal(สถานะป้ายของตัวเลือก({ sku: กก.sku, k: '02985', h: กก.h }), 'ยกเว้น');  // 20″
  assert.equal(สถานะป้ายของตัวเลือก({ sku: กก.sku, k: '01876', h: กก.h }), 'ยกเว้น');  // 22″
  assert.equal(สถานะป้ายของตัวเลือก({ sku: กก.sku, k: 'Bar KK 36-381', h: กก.h }), 'ต้องขอ');
  /* ⇒ ป้ายระดับสินค้าต้องบอกว่า "บางตัวเลือก" ไม่ใช่เหมารวมทั้งใบ */
  assert.equal(ป้ายของสินค้า(นว), 'บางตัวเลือก');
  assert.equal(ป้ายของสินค้า(กก), 'บางตัวเลือก');
});

test('🔴 เลื่อยตัดสินรายสินค้า — ตัวเลือกสีที่ไม่อยู่ในทะเบียนต้องยังติดป้าย', () => {
  const f660 = หา((p) => p.sku === 'F 660');
  assert.ok(f660);
  assert.equal(ตัวเลือกต้องขอลซ2({ sku: 'F 660', k: 'F 660', h: f660.h }), true);
  /* `F660-black` ไม่อยู่ในทะเบียน (ยังไม่เคยนำเข้าสีนั้น) — ถ้าเกณฑ์ดูแค่ทะเบียน ข้อนี้จะแดง */
  assert.equal(ตัวเลือกต้องขอลซ2({ sku: 'F 660', k: 'F660-black', h: f660.h }), true,
    'ใบอนุญาตผูกกับรุ่นเครื่อง ไม่ใช่สี');
  assert.equal(ป้ายของสินค้า(f660), 'ทุกตัวเลือก');
});

test('🔴 สามรุ่นที่ไม่มี sku เลย (F038 · F090 · F880) ต้องยังติดป้าย', () => {
  for (const h of handleเลื่อยต้องขอ) {
    const p = หา((x) => x.h === h);
    assert.ok(p, `ต้องเจอสินค้า handle ${h} ใน products.json`);
    assert.equal(p.sku || '', '', 'ข้อสมมติของเกณฑ์นี้คือสามใบนี้ไม่มี sku — ถ้ามีแล้วให้ย้ายไปใช้ sku');
    assert.equal(ป้ายของสินค้า(p), 'ทุกตัวเลือก', `${h} ต้องติดป้าย`);
  }
});

test('🚫 กลุ่มที่ไม่ต้องขอใบ ต้องไม่มีป้ายเลย (EXEMPT_MODELS)', () => {
  for (const รหัส of ['00073', '00657', '01780', '01248', '03019']) {
    const p = หา((x) => ขึ้นต้นด้วยรหัส(String(x.sku || ''), รหัส));
    if (!p) continue;                       /* บางรหัสอาจไม่ได้ลงขายในเว็บ — ไม่ใช่ความผิด */
    assert.equal(ป้ายของสินค้า(p), null, `${p.sku} (${p.t}) ไม่ต้องขอใบ ⇒ ห้ามติดป้าย`);
  }
  /* ชื่อหลอก: ใบนี้เขียนว่า "ถูกต้องตามกฎหมาย" และคนกวาดด้วยตามักคิดว่าเป็นของทะเบียน */
  const เจ็ดพันแปด = หา((x) => ขึ้นต้นด้วยรหัส(String(x.sku || ''), '00073'));
  if (เจ็ดพันแปด) assert.equal(ป้ายของสินค้า(เจ็ดพันแปด), null);
});

test('🚫 ของที่ไม่เกี่ยวเลย (โซ่ · อะไหล่) ต้องไม่มีป้าย', () => {
  const โซ่ = หา((x) => String(x.sku || '') === '00817');
  if (โซ่) assert.equal(ป้ายของสินค้า(โซ่), null);
  const ไม่เกี่ยว = สินค้า.filter((p) => ป้ายของสินค้า(p)).length;
  /* กันการติดป้ายทั้งเว็บด้วยความผิดพลาด — ของควบคุมมีไม่กี่สิบใบจากสองพันกว่าใบ */
  assert.ok(ไม่เกี่ยว > 0 && ไม่เกี่ยว < 60,
    `สินค้าที่ติดป้ายควรอยู่ในหลักสิบ ได้ ${ไม่เกี่ยว} ใบ — มากผิดปกติ`);
});

test('⑤ สินค้าหมวดเลื่อยยนต์ทุกใบต้องตอบได้ ห้ามตกมาเป็น "ไม่เกี่ยว"', () => {
  const เลื่อย = สินค้า.filter((p) => (p.cols || []).includes('เลื่อยยนต์'));
  assert.ok(เลื่อย.length >= 17, `ต้องเจอสินค้าเลื่อยยนต์อย่างน้อย 17 ใบ ได้ ${เลื่อย.length}`);
  const ตก = [];
  for (const p of เลื่อย) {
    const ตัวเลือก = (p.v || []).length ? p.v.map((v) => v.k) : [p.sku];
    for (const k of ตัวเลือก) {
      const st = สถานะป้ายของตัวเลือก({ sku: p.sku, k, h: p.h });
      if (st === 'ไม่เกี่ยว') ตก.push(`${p.t} · ตัวเลือก ${k}`);
    }
  }
  assert.deepEqual(ตก, [], 'มีเลื่อยที่เกณฑ์ไม่รู้จัก ⇒ ต้องไปใส่ในรายชื่อก่อน ไม่ใช่ปล่อยเงียบ');
});

