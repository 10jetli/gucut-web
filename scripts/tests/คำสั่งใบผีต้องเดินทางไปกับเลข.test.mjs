/* ทดสอบ: คำตัดสิน "ใบผีให้ปล่อยไว้" ต้องอยู่ใน **คำตอบของ ?pending=1** ไม่ใช่แค่ในความจำ/คอมเมนต์
 *
 * 🔴 ที่มา (16 ต.ค. 2569 · ใบ t_mva4rl49) — ท่านประธานตัดสินว่าใบผี Shopify 246 ใบ
 *    (910,663 บาท) ให้ **ปล่อยไว้ ห้ามยกเลิก ห้ามเสนอซ้ำ**
 *    🔑 เหตุที่ต้องติดไปกับเลข: ใครยิงเส้นนี้แล้วเห็น "ใบผี 246 ใบ · 910,663" จะอ่านว่า
 *       เป็นงานค้างที่ต้องเคลียร์ — **ผมเองก็เพิ่งเสนอให้ตัดสินเรื่องนี้วันนี้**
 *       ⇒ คำสั่งที่อยู่แต่ในความจำของคนคนหนึ่ง จะไม่ไปถึงคนที่อ่านเลขในอีกหกเดือน
 *
 * ⚠️ เทสนี้ไม่ตรึงตัวเลข (246/910,663 เปลี่ยนได้) — ตรึง **การมีอยู่ของคำสั่งและวิธีอ่านเลข**
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const ซอร์ส = readFileSync("netlify/functions/core.mjs", "utf8");
const i = ซอร์ส.indexOf('if (url.searchParams.get("pending"))');
const ตัวเส้น = (() => {
  assert.ok(i > 0, "หาเส้น ?pending=1 ไม่เจอ");
  const j = ซอร์ส.indexOf('if (url.searchParams.get("cardguess"))', i);
  return ซอร์ส.slice(i, j > i ? j : i + 9000);
})();

test("คำตอบของ ?pending=1 ต้องพกคำสั่งเรื่องใบผีไปด้วย", () => {
  assert.match(ตัวเส้น, /🔒 คำสั่งเรื่องใบผี/, "ไม่มีช่องคำสั่งในคำตอบ");
  assert.match(ตัวเส้น, /ห้ามยกเลิก ห้ามเสนอซ้ำ/, "คำตัดสินต้องเป็นคำพูดของท่าน ไม่ใช่สรุปเอง");
  assert.match(ตัวเส้น, /t_mva4rl49/, "ต้องมีเลขใบอ้างอิง ⇒ ตามรอยได้ว่าใครสั่งเมื่อไหร่");
  assert.match(ตัวเส้น, /ใครสั่ง/, "ต้องบอกว่าใครสั่ง — คำสั่งที่ไม่มีเจ้าของจะถูกเถียงภายหลัง");
  assert.match(ตัวเส้น, /เมื่อ: "2026-10-16"/, "ต้องมีวันที่ ⇒ รู้ว่าคำสั่งเก่าแค่ไหน");
});

test("ต้องเขียนวิธีอ่านเลขกำกับ — กันคนอ่าน 'รวม' ว่างานค้าง", () => {
  assert.match(ตัวเส้น, /อ่านเลขยังไง/, "ขาดคำกำกับวิธีอ่านเลข");
  assert.match(ตัวเส้น, /counts\.ต้องส่งของ/, "ต้องชี้ชื่อช่องที่เป็นงานจริง ไม่ใช่บอกลอย ๆ");
  /* 🔑 ต้องเตือนเรื่องการนับรวม — ไม่ใช่แค่บอกว่าช่องไหนคืองานจริง
     เพราะคนที่ทำตัวนับบนจอจะหยิบ `รวม` ก่อนเสมอ (มันชื่อ "รวม") */
  assert.match(ตัวเส้น, /นับรวมเมื่อไหร่/, "ต้องเตือนกรณีเอาไปนับรวม");
});

test("สามกองต้องยังอยู่ครบ — คำสั่งนี้พึ่งการแยกกอง", () => {
  for (const กอง of ["ต้องส่งของ", "รอจ่ายอยู่", "ใบผี"]) {
    assert.ok(ตัวเส้น.includes(กอง), `หายไปกอง ${กอง} ⇒ คำสั่งของท่านอ่านไม่ได้อีก`);
  }
  /* เกณฑ์ต้องตัดสินจากวันของใบล่าสุด ไม่ใช่ชื่อช่องทาง — ถ้าเปลี่ยนไปเช็คชื่อ "Shopify"
     วันที่มีช่องทางอื่นปิดตัว มันจะไม่เข้ากองใบผี แล้วเลขจะเพี้ยนเงียบ ๆ */
  assert.match(ตัวเส้น, /ไม่ใช่จากชื่อช่องทาง/, "เกณฑ์ต้องเป็นวันที่ของใบล่าสุด ไม่ใช่ชื่อช่องทาง");
});
