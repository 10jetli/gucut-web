// แถวผังอะไหล่ที่ไม่มี "รหัส" — ต้องไม่ล้ม build และต้องไม่เงียบ
//
// ของจริง 16 ต.ค. 2569: ไฟล์ f7800sps.json ที่ส่งเข้ามามี 166 แถว **143 แถวไม่มีรหัส**
// ⇒ `คีย์อะไหล่(รหัส)` เรียก `.replace()` บน undefined ⇒ `next build` **ล้มทั้งเว็บ**
//    และข้อความชี้ไปที่ page.js ที่ถูกย่อแล้ว ไม่บอกว่าไฟล์ไหนแถวไหน
// 🔑 สามชั้นคนละหน้าที่ **อย่ายุบรวม**:
//    ① ตัวแปลงคีย์ทนค่าว่าง (กันล้ม) ② จอเขียนว่า "ไม่มีรหัส" (กันเข้าใจผิดว่าครบ)
//    ③ ด่าน build ตีกลับถ้าไม่ประกาศเหตุ (กันข้อมูลไม่ครบขึ้นเว็บเงียบ ๆ)
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import { ตรวจเอกสาร } from "../check-parts-rows.mjs";
import { คีย์อะไหล่ } from "../../src/lib/parts-core.mjs";

test("① ตัวแปลงคีย์ต้องทนค่าว่างทุกรูป — ไม่โยน", () => {
  // ⚠️ นำเข้าจาก .mjs ไม่ใช่ .ts (Node 20 ที่ build ใช้ โหลด .ts ไม่ได้)
  for (const v of [undefined, null, "", "  "]) {
    assert.equal(คีย์อะไหล่(v), "", `คีย์อะไหล่(${JSON.stringify(v)}) ต้องได้ค่าว่าง ไม่ใช่โยน`);
  }
  assert.equal(คีย์อะไหล่("1123 020 1209"), "11230201209");
});

test("② จอต้องเขียนว่าไม่มีรหัส ไม่ใช่ขีดเปล่า", () => {
  /* ช่างเอาไปสั่งของต่อ — "ไม่มีรหัส" กับ "ลืมใส่" คนละเรื่องกันสำหรับเขา */
  const v = fs.readFileSync("src/components/PartsView.tsx", "utf8");
  assert.match(v, /คู่มือไม่ได้ให้รหัสแถวนี้/);
  assert.ok(!/\{row\.รหัส \|\| "—"\}/.test(v), "ยังเป็นขีดเปล่าอยู่");
});

test("③ ด่านต้องตีกลับไฟล์ที่มีแถวไร้รหัสและไม่ประกาศเหตุ", () => {
  const เสีย = { กลุ่ม: [{ ตัวอักษร: "A", อะไหล่: [{ เลข: "1" }, { เลข: "2", รหัส: "x" }] }] };
  const ผล = ตรวจเอกสาร("ทดสอบ", เสีย);
  assert.ok(ผล, "ต้องตีกลับ");
  assert.match(ผล, /1 แถวจาก 2/, "ต้องบอกจำนวนที่ขาดและตัวหาร");
  assert.match(ผล, /A\/1/, "ต้องบอกว่าแถวไหน ไม่ใช่บอกแค่ว่ามีปัญหา");
  // ประกาศเหตุแล้วต้องผ่าน — ว่างได้ แต่ต้องบอกว่าทำไม
  assert.equal(ตรวจเอกสาร("ทดสอบ", { ...เสีย, "บางแถวไม่มีรหัสเพราะ": "คู่มือให้แต่ภาพ" }), null);
});

test("③ ด่านอยู่ในสาย prebuild จริง และมี selftest นำหน้า", () => {
  /* ด่านที่ไม่ถูกเรียกคือด่านที่ไม่มีอยู่ · และด่านที่ไม่เคยถูกป้อนของเสีย
     ให้ผลเขียวที่แปลว่า "ยังไม่เจอ" ไม่ใช่ "ไม่มี" */
  const pkg = JSON.parse(fs.readFileSync("package.json", "utf8"));
  assert.match(pkg.scripts.prebuild, /check-parts-rows\.mjs --selftest/);
  assert.match(pkg.scripts.prebuild, /check-parts-rows\.mjs(?! --selftest)/);
});

test("ของจริงที่ทำให้ build ล้ม ต้องถูกด่านจับได้", () => {
  /* ไฟล์ตัวนั้นยังไม่อยู่ใน main (ผมถอดออกจากกอง) ⇒ จำลองรูปเดียวกันไว้ที่นี่
     เพื่อให้ข้อนี้ยังมีความหมายแม้ไฟล์จริงจะถูกแก้ไปแล้ว */
  const เหมือนของจริง = {
    กลุ่ม: [{ ตัวอักษร: "A", อะไหล่: Array.from({ length: 13 }, (_, i) => ({ เลข: String(i + 1) })) }],
  };
  assert.match(ตรวจเอกสาร("f7800sps.json", เหมือนของจริง), /13 แถวจาก 13/);
});
