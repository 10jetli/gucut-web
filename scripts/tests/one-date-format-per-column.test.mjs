/* ด่าน: **หนึ่งคอลัมน์ = หนึ่งรูปแบบวันที่** — ห้ามเทียบคอลัมน์ที่เก็บเป็น ISO กับ `datetime('now', …)`
 *
 * 🔴 ที่มา 19 ก.ย. 2569 · ฝั่งจอจับได้จากอาการที่ดูเหมือนเรื่องอื่น (อัตราต่อวันเพี้ยน 52 เท่า)
 *    `at` เก็บด้วย `toISOString()` ⇒ `2026-09-19T01:23:45.678Z`
 *    `datetime('now','-3 hours')`  ⇒ `2026-09-18 22:23:45`
 *    เทียบเป็นสตริง อักขระตำแหน่งที่ 11: **`T` (0x54) > ` ` (0x20) เสมอ**
 *    ⇒ **แถวที่วันเดียวกับเส้นตัดผ่านหมด ไม่ว่าเวลาในวันเป็นเท่าไหร่** ⇒ ตัวกรองกลายเป็นรายวัน
 *    🔑 **ไม่มี error สักตัว** และตัวเลขที่ได้ยัง "ดูสมเหตุสมผล" ⇒ ไม่มีใครสงสัยจนไล่พารามิเตอร์
 *
 * 📏 กวาดทั้ง `netlify/` แล้ว (19 ก.ย. 2569) — คลาสนี้มี **2 จุด แก้แล้วทั้งคู่ ไม่มีจุดที่สาม**
 *    ที่ปลอดภัยอยู่แล้วและเป็นแบบที่ถูก:
 *    · `backup.mjs` ครอบทั้งสองข้างด้วย `datetime(col,'+7 hours')` ⇒ **ทำให้รูปแบบตรงกันก่อนเทียบ**
 *    · `pos.mjs` / `core-sync.mjs` เขียน `updated_at` ด้วย `datetime('now')` ⇒ รูปแบบเดียวกันทั้งคอลัมน์
 *    ⚠️ ขอบเขต: ด่านนี้ครอบ **`netlify/` ของ repo นี้เท่านั้น** — ฝั่งจอเป็นอีก repo
 *
 * 🔑 กติกาที่ด่านนี้บังคับ: **คอลัมน์ไหนถูกเขียนด้วย `toISOString()` ห้ามเทียบกับ `datetime()` ตรง ๆ**
 *    ทางที่ถูกมีสองทาง: (ก) คิดเส้นตัดใน JS เป็น ISO แล้วเทียบตรงตัว
 *                      (ข) ครอบทั้งสองข้างด้วย `datetime(...)` ให้รูปแบบตรงกันก่อน
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

/** คอลัมน์ที่ **เก็บเป็น ISO** ในคลังเงา — กวาดจากซอร์สแล้วยืนยันด้วยค่าจริงในฐาน 19 ก.ย. 2569 */
const คอลัมน์ISO = ["skip_first_at", "skip_last_at", "planned_at", "pushed_at", "verified_at", "last_error_at"];
/* ⚠️ `at` ของ `push_sweep_log` ก็เป็น ISO แต่ชื่อสั้นเกินจะ grep ได้แม่น
   ⇒ ตรวจแยกด้วยรูป `at > datetime` / `at < datetime` ที่เจาะจงกว่า */

function ไฟล์ทั้งหมด(ราก = "netlify") {
  const out = [];
  const เดิน = (d) => {
    for (const f of readdirSync(d)) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) { เดิน(p); continue; }
      if (/\.(mjs|js)$/.test(f)) out.push(p);
    }
  };
  เดิน(ราก);
  return out;
}

test("ห้ามเทียบคอลัมน์ที่เก็บเป็น ISO กับ datetime('now', …)", () => {
  const เจอ = [];
  for (const p of ไฟล์ทั้งหมด()) {
    /* ตัดคอมเมนต์ก่อน — ไฟล์พวกนี้มีคำอธิบายบั๊กนี้เขียนไว้เยอะ (กันแดงลวง) */
    const code = readFileSync(p, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    for (const c of [...คอลัมน์ISO, "at"]) {
      /* จับ `<คอลัมน์> <  หรือ >` แล้วตามด้วย datetime( ภายในไม่กี่ตัวอักษร
         ⚠️ ไม่จับกรณีที่คอลัมน์ถูกครอบด้วย datetime(...) ก่อน เพราะนั่นคือท่าที่ถูก */
      const re = new RegExp(`(?<!datetime\\([^)]{0,40})\\b${c}\\s*[<>]=?\\s*datetime\\(`, "g");
      for (const m of code.matchAll(re)) {
        เจอ.push(`${p}: ${code.slice(Math.max(0, m.index - 30), m.index + 60).replace(/\s+/g, " ")}`);
      }
    }
  }
  assert.deepEqual(
    เจอ, [],
    "เทียบคอลัมน์ที่เก็บเป็น ISO กับ datetime() ⇒ อักขระ 'T' > ' ' ทำให้เทียบเวลาในวันไม่ได้ " +
      "**และไม่มี error สักตัว**\n" +
      "  ทางแก้: (ก) คิดเส้นตัดใน JS เป็น ISO แล้วเทียบตรงตัว  หรือ  (ข) ครอบทั้งสองข้างด้วย datetime(...)\n" +
      เจอ.map((x) => "    " + x).join("\n"),
  );
});

test("ท่าที่ถูกต้องยังต้องผ่าน — ครอบทั้งสองข้างด้วย datetime() ไม่ถือว่าผิด", () => {
  /* 🔑 ด่านที่ร้องใส่ของที่ถูก จะถูกปิดภายในวันเดียว ⇒ ต้องพิสูจน์ว่ามันแยกแยะได้
     `backup.mjs` ใช้ท่า (ข) อยู่จริง ⇒ ถ้าด่านนี้ฟ้องมันด้วย แปลว่าด่านหยาบเกินไป */
  const src = readFileSync("netlify/lib/backup.mjs", "utf8");
  assert.match(src, /datetime\(gone_at,\s*'\+7 hours'\)\s*>=\s*datetime\('now'/,
    "backup.mjs ควรยังใช้ท่าครอบสองข้าง — ถ้าหายไปแปลว่ามีคนเปลี่ยนท่า ต้องมาดู");
});
