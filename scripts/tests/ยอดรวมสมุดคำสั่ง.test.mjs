/* 🔢 ด่าน: **เส้นอ่านสมุดคำสั่งต้องส่งยอดรวม + ธง "เห็นครบไหม" — และ "นับไม่ได้" ต้องไม่กลายเป็น 0**
 *
 * 🔴 ที่มา 21 ก.ย. 2569 (ฝั่งจอเจอของจริงในกล่องของตัวเอง · commit `d76c797`)
 *    กล่อง `NegVsPush` คิดเลข **สามตัว** จากแถวที่ได้จาก `?pushstuck=1&limit=200`
 *    **โดยไม่อ่านยอดรวมที่เส้นนั้นส่งมาให้อยู่แล้ว**
 *    ⇒ วันที่แถวเกิน 200 ตัวเลขบนจอจะ **ต่ำกว่าจริงโดยไม่มีอะไรฟ้อง**
 *    🔑 คลาส: **เลขเพื่อการแสดงผล (limit/slice) ถูกเอาไปใช้ตัดสิน** [[display-limits-cant-decide]]
 *
 * 🔑 ด่านนี้ทดสอบ **เส้นทางจริง** (ปลอมเฉพาะ D1) ไม่ใช่การอ่านซอร์ส
 *    ⇒ จับได้ถึงกรณีที่โค้ดมีช่องนั้นอยู่ แต่ **คำนวณผิดทิศ**
 * 🚫 และ "นับไม่ได้" ต้องเป็น `null` ห้ามเป็น 0 — 0 แปลว่า "ไม่มีคำสั่งเลย" ซึ่งคนละเรื่องกัน
 */
import { test, mock } from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

/* 🔴 **ห้าม `.pathname` กับ file URL** — มันเข้ารหัสอักษรไทย/ช่องว่างเป็น `%xx`
   (ด่าน `path-url-roundtrip` จับไฟล์นี้ได้ทันทีตอนผมเขียนครั้งแรก — ด่านทำงานถูกแล้ว) */
const ราก = fileURLToPath(new URL("../../netlify/lib/", import.meta.url));

/* 🔴 **`mock.module` ปลอมได้ครั้งเดียวต่อโมดูล** — ปลอมในทุกเทสจะได้
   `Cannot mock ... already mocked` (เจอทันทีรอบแรก) ⇒ ปลอม **หนึ่งครั้ง** แล้วให้แต่ละเทส
   เปลี่ยน **สภาพ** ที่ตัวปลอมอ่าน · โครงนี้ยังเป็นการทดสอบเส้นทางจริง ไม่ใช่การอ่านซอร์ส */
const สภาพ = { แถว: [], ยอดรวม: 0, นับล้ม: false };
mock.module(ราก + "coredb.mjs", {
  namedExports: {
    coreReady: () => true, coreInit: async () => null, withD1Meter: (f) => f(),
    d1Stats: () => null, d1Info: () => null,
    coreQuery: async (sql) => {
      if (/COUNT\(\*\)/.test(sql)) {
        if (สภาพ.นับล้ม) throw new Error("D1 timeout ตอนนับ");
        return { results: [{ n: สภาพ.ยอดรวม }] };
      }
      if (/^\s*DELETE/.test(sql)) return { results: [] };
      return { results: สภาพ.แถว };
    },
  },
});
const { อ่านคำสั่งแอดมิน } = await import(ราก + "admin-log.mjs");

async function เรียกด้วยD1ปลอม({ แถว, ยอดรวม, นับล้ม = false }) {
  Object.assign(สภาพ, { แถว, ยอดรวม, นับล้ม });
  return อ่านคำสั่งแอดมิน({ ชั่วโมงย้อนหลัง: "24", limit: "3" });
}

const สามแถว = [
  { at: "2026-09-21T02:14:09.881Z", endpoint: "/api/core?move", method: "POST", ref: "A", result: "200", note: null },
  { at: "2026-09-21T01:58:40.102Z", endpoint: "/api/core?movedel", method: "DELETE", ref: "B", result: "200", note: null },
  { at: "2026-09-21T01:41:12.503Z", endpoint: "/api/core?move", method: "POST", ref: "C", result: "409", note: null },
];

test("แถวถูกตัดด้วยเพดาน ⇒ ต้องบอกยอดรวมจริง และธงต้องเป็น **false**", async () => {
  const r = await เรียกด้วยD1ปลอม({ แถว: สามแถว, ยอดรวม: 137 });
  assert.equal(r["แถวที่มี"], 3);
  assert.equal(r["ทั้งหมดที่ตรงเงื่อนไข"], 137, "จอต้องได้ยอดรวม ไม่ใช่เดาจากจำนวนแถว");
  assert.equal(r["เห็นครบทุกแถวไหม"], false, "🔴 ถ้าเป็น true จอจะเขียนเลขขอบล่างเหมือนยอดจริง");
});

test("เห็นครบจริง ⇒ ธงเป็น true (จอจะไม่ขึ้นคำเตือนที่ไม่จำเป็น)", async () => {
  const r = await เรียกด้วยD1ปลอม({ แถว: สามแถว, ยอดรวม: 3 });
  assert.equal(r["เห็นครบทุกแถวไหม"], true);
  /* 🔑 ด่านที่ร้องใส่ของปกติจะถูกปิดใน 1 วัน ⇒ ต้องเงียบตอนครบ [[noise-filters-eat-real-cases]] */
});

test("🚫 นับยอดรวมไม่ได้ ⇒ ยอดรวมและธงต้องเป็น **null** (ไม่ใช่ 0 · ไม่ใช่ true)", async () => {
  const r = await เรียกด้วยD1ปลอม({ แถว: สามแถว, ยอดรวม: 0, นับล้ม: true });
  assert.equal(r["ทั้งหมดที่ตรงเงื่อนไข"], null, "0 จะอ่านว่า 'ไม่มีคำสั่งเลย' ซึ่งคนละเรื่องกับ 'นับไม่ได้'");
  assert.equal(r["เห็นครบทุกแถวไหม"], null, "ไม่รู้ ต้องเป็น null ⇒ จอเขียน 'ยังไม่รู้ว่าครบไหม'");
  assert.equal(r.ok, true, "นับไม่ได้ ไม่ใช่เหตุให้อ่านสมุดไม่ได้");
  assert.equal(r["รายการ"].length, 3, "และต้องยังส่งแถวที่อ่านได้กลับไป");
});

test("ยังไม่มีคำสั่งไหนถูกจด ⇒ `รายการ: []` · ยอดรวม 0 · ธง true (ไม่ใช่ null)", async () => {
  const r = await เรียกด้วยD1ปลอม({ แถว: [], ยอดรวม: 0 });
  assert.deepEqual(r["รายการ"], []);
  assert.equal(r["แถวที่มี"], 0);
  assert.equal(r["ทั้งหมดที่ตรงเงื่อนไข"], 0);
  assert.equal(r["เห็นครบทุกแถวไหม"], true, "ว่างจริง ≠ ไม่รู้ ⇒ สามสถานะต้องแยกกัน");
});

test("🔬 พลังแยกแยะ: ถ้าธงคิดจาก `แถว < เพดาน` (ท่าที่จอเคยทำ) ⇒ เคสแรกจะผิด", async () => {
  /* เขียนสูตรที่ **ผิด** ขึ้นมาเทียบ: 3 แถว < เพดาน 3? ไม่ ⇒ ได้ false ถูกโดยบังเอิญ
     ⇒ ใช้เคสที่แยกได้จริง: แถว 3 · เพดาน 100 · ยอดรวม 137 ⇒ สูตรผิดจะบอกว่า "ครบ" */
  const สูตรผิด = (แถว, เพดาน) => แถว < เพดาน;
  assert.equal(สูตรผิด(3, 100), true, "สูตรผิดบอกว่าเห็นครบ");
  const r = await เรียกด้วยD1ปลอม({ แถว: สามแถว, ยอดรวม: 137 });
  assert.equal(r["เห็นครบทุกแถวไหม"], false, "ของจริงต้องบอกว่าไม่ครบ ⇒ ต่างจากสูตรผิด");
});
