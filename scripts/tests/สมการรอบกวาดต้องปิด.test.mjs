/* 🔴 ด่าน: **สมการปิดของรอบกวาดดันสต็อก** (สเปกฝั่งจอ · ใบ t_mu8i1pu1 · 28 ก.ย. 2569)
 *    planned = fired + not_sent + not_fired   ·   **`skipped` ห้ามเข้าสมการ**
 *
 * 🔑 เหตุที่ต้องมีด่านนี้: ผมเคยส่งสูตร `notSent = fired − pushed − rejected` ให้ฝั่งจอ
 *    ซึ่ง **เป็น 0 ตลอดกาล** (เพราะ fired = pushed + rejected เป๊ะ) — ถ้าเขาเอาไปขึ้นจอ
 *    จอจะเขียนว่า "ไม่มีตัวไหนถูกคัดออก" ทุกวันโดยไม่มีอะไรฟ้อง
 *    ⇒ สูตรที่ถูกเขียนไว้เฉย ๆ เชื่อไม่ได้ · สูตรที่ถูก**คิดทุกรอบ**จับตัวเองได้
 *
 * กติกาที่ตกลงกับฝั่งจอ: ① มีตัวควบคุมลบคู่เสมอ ② สูตรปลูกต้องโหลดผ่าน
 *                        ③ ข้อความตอนตกต้องบอกสิ่งที่ผิด ไม่ใช่ expected true
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { ตรวจสมการรอบกวาด } from "../../netlify/lib/sweep-invariant.mjs";

/** ก้อนผลยิงจำลอง — **ต้องมี `ครบ: true`** เหมือนของจริง (ตัวยิงติดให้ตอนปิดก้อน) */
const ก้อนยิง = (fired, notSent, ไม่ได้ยิง, เพิ่ม = {}) => ({ ครบ: true, fired, notSent, ไม่ได้ยิง, ...เพิ่ม });

test("✅ รอบที่ลงพอดี ⇒ ตรวจได้ + ลง", () => {
  const r = ตรวจสมการรอบกวาด({ planned: 10, ผลยิง: ก้อนยิง(6, 3, 1) });
  assert.equal(r.ตรวจได้, true, `ค่าครบต้องตรวจได้ · ได้ ${JSON.stringify(r)}`);
  assert.equal(r.ลง, true, `10 = 6+3+1 ต้องลง · ได้ ${JSON.stringify(r)}`);
  assert.ok(!("⚠️ สมการไม่ลง" in r), "รอบที่ลงห้ามมีข้อความเตือน");
});

test("🧪 ตัวควบคุมลบ: เกินไป 1 ตัว ⇒ ต้องไม่ลง และข้อความต้องบอกตัวเลขทั้งสี่", () => {
  const r = ตรวจสมการรอบกวาด({ planned: 10, ผลยิง: ก้อนยิง(6, 3, 0) });
  assert.equal(r.ลง, false, "9 ≠ 10 ต้องไม่ลง");
  assert.equal(r.ต่างกัน, 1, `ต้องบอกว่าต่างกันเท่าไร · ได้ ${JSON.stringify(r)}`);
  const ข = r["⚠️ สมการไม่ลง"];
  for (const ต of ["10", "6", "3", "0", "9"])
    assert.ok(ข.includes(ต), `ข้อความต้องมีเลข ${ต} เพื่อให้คนอ่านรู้ว่าหายไปกองไหน · ได้: ${ข}`);
});

test("🔴 `skipped` ห้ามเข้าสมการ — ส่งมาก็ต้องไม่เปลี่ยนผล (กันนับซ้ำ)", () => {
  const ไม่มี = ตรวจสมการรอบกวาด({ planned: 10, ผลยิง: ก้อนยิง(6, 3, 1) });
  const มี = ตรวจสมการรอบกวาด({ planned: 10, ผลยิง: ก้อนยิง(6, 3, 1, { skipped: 99 }) });
  assert.deepEqual(มี, ไม่มี, "ใส่ skipped แล้วผลเปลี่ยน = มีคนเอา skipped เข้าสมการ (นับซ้ำ)");
});

test("⚪ รอบที่ไม่ได้ยิงเลย (`ผลยิง` เป็น null) ⇒ `ตรวจได้:false` และ **ต้องไม่มีคีย์ `ลง`**", () => {
  for (const ว่าง of [null, undefined]) {
    const r = ตรวจสมการรอบกวาด({ planned: 4, ผลยิง: ว่าง });
    assert.equal(r.ตรวจได้, false);
    assert.ok(!("ลง" in r), `"พิสูจน์ไม่ได้" ห้ามมีคีย์ ลง · ได้ ${JSON.stringify(r)}`);
    assert.match(r.เหตุ, /ไม่ได้ยิง/, "ต้องบอกว่าเพราะไม่ได้ยิง");
    assert.match(r.เหตุ, /ไม่ใช่ว่าไม่ผ่าน/, "ต้องเขียนกำกับให้คนอ่านไม่สับสน");
  }
});

test("🔴🔴 รูครึ่งใบที่ฝั่งจอวัดเจอ: **ยิงจริง แต่ช่องหาย** ⇒ ห้ามบอกว่าลง", () => {
  /* เคสที่เขายิงวัด: {ยิงแล้ว:true, planned:5, fired:5, not_sent:0, not_fired:0} ⇒ เคยได้ ลง:true 🔴
     ตอนนี้ตัวคิดอ่านช่องจากก้อนเอง ⇒ ผู้เรียกไม่มีทางแปลง null เป็น 0 ระหว่างทางได้อีก
     และถ้าตัวยิงไม่คืน notSent มาเลย (ทางออกใหม่/error กลางทาง) ⇒ สรุปไม่ได้ */
  const ขาดช่อง = ตรวจสมการรอบกวาด({ planned: 5, ผลยิง: { ครบ: true, fired: 5, ไม่ได้ยิง: 0 } });
  assert.equal(ขาดช่อง.ตรวจได้, false, `ขาด notSent ⇒ ต้องสรุปไม่ได้ · ได้ ${JSON.stringify(ขาดช่อง)}`);
  assert.ok(!("ลง" in ขาดช่อง), "ห้ามมีคีย์ ลง");
  assert.match(ขาดช่อง.เหตุ, /notSent/, "ต้องบอกชื่อช่องที่ขาด");
});

test("🔒 ตัวยิงที่ไม่ประกาศ `ครบ` ⇒ สรุปไม่ได้ (เลิกเชื่อผู้เรียก)", () => {
  for (const ค่า of [undefined, false, 1, "true", null]) {
    const r = ตรวจสมการรอบกวาด({ planned: 10, ผลยิง: { ครบ: ค่า, fired: 6, notSent: 3, ไม่ได้ยิง: 1 } });
    assert.equal(r.ตรวจได้, false, `ครบ = ${String(ค่า)} ต้องสรุปไม่ได้ (ตัวเลขลงพอดีก็ห้ามผ่าน)`);
    assert.ok(!("ลง" in r), `ครบ = ${String(ค่า)} ห้ามมีคีย์ ลง`);
    assert.match(r.เหตุ, /ครบ/, "ต้องบอกว่าเพราะไม่ประกาศความครบ");
  }
});

test("⚪ ค่าที่ไม่ใช่เลข (NaN · สตริง · null) ต้องนับเป็น 'ไม่รู้' ไม่ใช่ 0", () => {
  for (const เสีย of [undefined, NaN, "6", null])
    assert.equal(
      ตรวจสมการรอบกวาด({ planned: 10, ผลยิง: ก้อนยิง(เสีย, 3, 1) }).ตรวจได้,
      false,
      `fired = ${String(เสีย)} ต้องถือว่าไม่รู้ ไม่ใช่ 0 (0 จะทำให้สมการไม่ลงแบบเข้าใจผิด)`
    );
});

test("🔴 ส่งอย่างอื่นที่ไม่ใช่ก้อน (เช่นตัวเลข) ⇒ สรุปไม่ได้ ไม่ใช่พัง", () => {
  const r = ตรวจสมการรอบกวาด({ planned: 10, ผลยิง: 6 });
  assert.equal(r.ตรวจได้, false);
  assert.match(r.เหตุ, /ก้อนผล/, "ต้องบอกว่ารูปที่ส่งมาผิด");
});

/* ── ตัวกวาดต้องเรียกใช้จริง ไม่ใช่มีฟังก์ชันทิ้งไว้ ──
   🔑 คลาส: เขียนตัวคิดเสร็จแล้วไม่ต่อสาย = เท่ากับไม่มี และไม่มีอะไรฟ้อง */
const sweep = await readFile(new URL("../../netlify/lib/stock-push-sweep.mjs", import.meta.url), "utf8");

test("ตัวกวาดต้อง import และเรียก `ตรวจสมการรอบกวาด` จริง", () => {
  assert.match(sweep, /import \{ ตรวจสมการรอบกวาด \} from "\.\/sweep-invariant\.mjs"/,
    "ตัวกวาดยังไม่ import ตัวคิดสมการ");
  assert.match(sweep, /ตรวจสมการรอบกวาด\(\{/, "import มาแล้วแต่ไม่ได้เรียก = เท่ากับไม่มี");
  /* 🔴 ตัวกวาดต้องส่ง **ก้อนผลยิง** ไม่ใช่แกะเลขออกมาส่ง — ที่แกะเลขคือรูที่ฝั่งจอวัดเจอ */
  const i = sweep.indexOf("ตรวจสมการรอบกวาด({");
  const ก้อน = sweep.slice(i, i + 400);
  assert.match(ก้อน, /ผลยิง\s*\}\)/,
    "ตัวกวาดต้องส่ง `{ planned, ผลยิง }` — แกะ fired/notSent ออกมาส่งเอง = เปิดช่องให้ `?? 0` อีกครั้ง");
  assert.ok(!/not_sent:/.test(ก้อน),
    "เจอการแกะช่องออกมาส่งที่ตัวเรียก ⇒ ห้ามทำ (ดูเหตุใน sweep-invariant.mjs)");
  /* 🔒 และตัวยิงต้องติด `ครบ: true` ตอนปิดก้อน ไม่งั้นทุกรอบจะ "สรุปไม่ได้" */
  assert.match(sweep, /รวม\.ครบ = true;\n\s*ผลยิง = รวม;/,
    "ต้องติด `รวม.ครบ = true` ติดกับจุดที่ปิดก้อน (`ผลยิง = รวม`) — แยกกันแล้วจะมีทางออกที่ลืมติด");
});

test("ผลสมการต้องออกไปถึงจอ (`สมการรอบนี้`) และลงสมุด (`note`)", () => {
  assert.match(sweep, /สมการรอบนี้: สมการ/, "คำตอบต้องพ่วงผลสมการ ไม่งั้นจอมองไม่เห็น");
  /* ⚠️ สมุดรอบกวาดมี INSERT **สองที่** (ทางออกเร็ว + รอบเต็ม) — `indexOf` เจอที่แรกซึ่งไม่ใช่ที่ที่ตรวจ
     ⇒ ต้องเจาะเอาที่ที่มีคอลัมน์ not_sent/not_fired (รอบเต็ม) เท่านั้น
     🔑 คลาสเดิมของผม: อ่านแค่ที่แรกแล้วสรุปแทนทั้งไฟล์ (เคยพลาดกับ .match() มาแล้ววันนี้) */
  const ที่ทั้งหมด = [...sweep.matchAll(/INSERT INTO push_sweep_log/g)].map((m) => m.index);
  assert.ok(ที่ทั้งหมด.length >= 2, `คาดว่ามี INSERT หลายที่ · เจอ ${ที่ทั้งหมด.length}`);
  const รอบเต็ม = ที่ทั้งหมด.filter((i) => sweep.slice(i, i + 400).includes("not_sent,not_fired"));
  assert.equal(รอบเต็ม.length, 1, `ต้องมี INSERT ของรอบเต็มที่เดียว · เจอ ${รอบเต็ม.length}`);
  const ก้อน = sweep.slice(รอบเต็ม[0], รอบเต็ม[0] + 2500);
  assert.match(ก้อน, /สมการ\["⚠️ สมการไม่ลง"\]/,
    "note ที่เขียนลงสมุดต้องพ่วงข้อความสมการไม่ลง — ไม่งั้นรอบที่ผิดจะหายไปกับรอบ");
  assert.match(ก้อน, /ผลยิง\?\.error/,
    "และต้องไม่เขียนทับ error ของตัวยิง — สองเรื่องเกิดพร้อมกันได้");
});
