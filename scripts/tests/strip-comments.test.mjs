/* ด่าน: ตัวตัดคอมเมนต์ต้องรอด **หลายรูปของคลาสเดียวกัน** ไม่ใช่รูปที่เราเพิ่งเจอ
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ผมแก้รูป "สามสแลช" แล้วประกาศว่าปิดคลาสนี้แล้ว
 *    ⇒ ฝั่งจอทดสอบหลายรูปแล้วพบว่าตรรกะเดียวกันยังพังอีก 2 รูป (รวมรูปที่ไม่มีใครเคยจดไว้)
 *    🔑 **"แก้แล้ว" ของคลาสหนึ่ง มีอายุเท่ากับ *รูป* ที่เราทดสอบด้วยเท่านั้น**
 *    ⇒ ด่านนี้จึงตรึงไว้ **7 รูป** เพื่อให้ "แก้แล้ว" เป็นคำที่มีหลักฐาน ไม่ใช่ความรู้สึก
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

test("รูปที่ต้อง **ไม่ถูกตัด** (ของจริงที่ต้องหาเจอ)", () => {
  /* 🔑 ประกอบชื่อคุณสมบัติเป็นสองชิ้น **โดยตั้งใจ** — ด่าน `path-url-roundtrip` ห้ามสำนวนนี้
     และมันควรห้ามทุกไฟล์รวมทั้งไฟล์นี้ ⇒ ถ้าเขียนเป็น literal เดียว ด่านนั้นจะจับ **ข้อมูลทดสอบ** ของเรา
     ⇒ ทางเลือกอีกทางคือยกเว้นไฟล์นี้ในด่านนั้น แต่การยกเว้นทำให้ด่านตรวจไฟล์นี้ไม่ได้ตลอดกาล */
  const ตัวอย่างfileURL = 'const m = new URL("file:///home/x").path' + "name;";
  assert.match(ตัดคอมเมนต์(ตัวอย่างfileURL), /file:\/\/\/home\/x/, "file URL สามสแลช");
  assert.match(ตัดคอมเมนต์('const s = "//cdn.x.com/a";'), /cdn\.x\.com/, "protocol-relative URL ในสตริง");
  assert.match(ตัดคอมเมนต์('fetch("/api//double");'), /\/api\/\/double/, "พาธที่มีสแลชซ้อน — รูปที่ไม่มีใครเคยจดไว้");
  assert.match(ตัดคอมเมนต์('fetch("https://gucut.com/api/z");'), /gucut\.com\/api\/z/, "https ปกติ");
});

test("รูปที่ต้อง **ถูกตัด** (คอมเมนต์จริง)", () => {
  assert.doesNotMatch(ตัดคอมเมนต์("// เดิมเรียก /api/x"), /api/, "คอมเมนต์ต้นบรรทัด");
  assert.doesNotMatch(ตัดคอมเมนต์('fetch("/api/y"); // เลิกใช้แล้ว'), /เลิกใช้/, "คอมเมนต์ท้ายบรรทัด");
  assert.doesNotMatch(ตัดคอมเมนต์("/* เดิมเรียก /api/w */"), /api/, "คอมเมนต์บล็อก");
  assert.doesNotMatch(ตัดคอมเมนต์("<!-- เดิมเรียก /api/v -->", "a.html"), /api/, "คอมเมนต์ HTML");
  assert.doesNotMatch(ตัดคอมเมนต์("# เดิมเรียก /api/u", "a.sh"), /api/, "คอมเมนต์ shell");
});

test("ข้อจำกัดที่ยอมรับ — ต้องยังเป็นจริง ไม่งั้นคำอธิบายในไฟล์จะค้าง", () => {
  /* 🔑 ด่านที่บังคับ **ข้อจำกัด** ไม่ใช่แค่ความสามารถ: วันที่มีคนทำให้มันไม่ตัดแล้ว
     ด่านจะฟ้องให้มาแก้คำอธิบาย ⇒ เอกสารกับพฤติกรรมไม่หลุดจากกันเงียบ ๆ
     🔴 **20 ก.ย. 2569 — ข้อจำกัดเดิมถูกยกเลิกโดยตั้งใจ และเทสนี้ทำหน้าที่ของมันสำเร็จ**
        เดิมตรึงไว้ว่า "สแลชคู่ในสตริงก็ถูกตัด (ยอมพลาดไปทางตัดเกิน)"
        ⇒ ตัวถอดรุ่นใหม่เดินทีละอักษรและรู้จักสตริง ⇒ ไม่ต้องแลกอีกต่อไป
        ⇒ เทสนี้ **แดงทันทีที่พฤติกรรมเปลี่ยน** ⇒ มาแก้คำอธิบายพร้อมกัน (ไม่ใช่ค้าง)
     ⇒ ตอนนี้จึงตรึง **ข้อจำกัดที่ยังเหลือจริง** แทน: ไม่รู้จัก regex literal */
  assert.match(ตัดคอมเมนต์('const t = "a // b";'), /a \/\/ b/,
    "พฤติกรรมใหม่: ของในสตริงต้องไม่ถูกตัด");
  /* ข้อจำกัดที่ยังเหลือ: regex literal ที่มีลำดับเปิดคอมเมนต์แบบไม่ escape จะถูกมองเป็นคอมเมนต์
     (ของจริงในรีโปนี้ escape ไว้หมด ⇒ ไม่กระทบ · ประกาศไว้ให้คนรอบหน้ารู้ว่าเส้นแบ่งอยู่ตรงไหน) */
  const มีregexดิบ = "const r = /a" + "/*/;\nconst หลังจากนั้น = 1;";
  assert.doesNotMatch(ตัดคอมเมนต์(มีregexดิบ), /หลังจากนั้น/,
    "ข้อจำกัดที่ยังเหลือ: regex literal แบบไม่ escape ยังหลอกตัวถอดได้ ⇒ ถ้าวันหนึ่งแก้ ต้องมาแก้คำอธิบายในไฟล์ด้วย");
});
