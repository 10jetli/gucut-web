/** ตัวเดินอักษร **รุ่นก่อน 20 ก.ย. เย็น** — รู้จักสตริง/เทมเพลต แต่ **ไม่รู้จัก regex**
 *  🔑 มีไว้เพื่อเทียบทิศที่ `รุ่นเก่าที่พัง` (ซึ่งเป็น regex ล้วน) **แยกแยะไม่ได้**:
 *     ทิศ "คอมเมนต์ต้องถูกตัด" — ตัวที่ใช้ regex ล้วนก็ตัดคอมเมนต์ได้อยู่แล้ว
 *     ⇒ ถ้าเทียบกับตัวนั้น เคสจะเขียวทั้งสองฝ่าย = ไม่ได้เฝ้าอะไรเลย */
function รุ่นก่อนรู้จักregex(s) {
  let out = "", i = 0;
  while (i < s.length) {
    const c = s[i], สอง = s.slice(i, i + 2);
    if (สอง === "/*") { const j = s.indexOf("*/", i + 2); i = j === -1 ? s.length : j + 2; continue; }
    if (สอง === "//") { let j = s.indexOf("\n", i); i = j === -1 ? s.length : j; continue; }
    if (c === '"' || c === "'" || c === "`") {
      let j = i + 1;
      while (j < s.length) {
        if (s[j] === "\\") { j += 2; continue; }
        if (s[j] === c) { j++; break; }
        if (c !== "`" && s[j] === "\n") break;
        j++;
      }
      out += s.slice(i, j); i = j; continue;
    }
    out += c; i++;
  }
  return out;
}

