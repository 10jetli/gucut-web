function กวาด(ราก = "netlify") {
  const เจอ = [];
  const เดิน = (d) => {
    for (const f of readdirSync(d)) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) { เดิน(p); continue; }
      if (!/\.(mjs|js)$/.test(f)) continue;
      if (ยกเว้นไฟล์[p.replace(/\\/g, "/")]) continue;
      const src = readFileSync(p, "utf8");
      const code = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
      for (const re of [/"([^"\n]{6,400})"/g, /`([^`]{6,600})`/g]) {
        for (const m of code.matchAll(re)) {
          const ข้อความ = m[1];
          if (!คำบอกรอบ.test(ข้อความ)) continue;
          if (ยกเว้นข้อความ.some((x) => ข้อความ.includes(x.มีคำว่า))) continue;
          เจอ.push({ ไฟล์: p, ข้อความ: ข้อความ.replace(/\s+/g, " ").slice(0, 120) });
        }
      }
    }
  };
  เดิน(ราก);
  return เจอ;
}

test("ห้ามพิมพ์รอบเวลาของงานตามเวลาลงในข้อความที่ส่งออก", () => {
  const เจอ = กวาด();
  assert.deepEqual(
    เจอ, [],
    "ข้อความเหล่านี้พิมพ์รอบเวลาไว้เอง ⇒ จะเป็นเท็จวันที่ใครแก้ cron โดยไม่มีอะไรฟ้อง\n" +
      "  ⇒ ใช้ `รอบเป็นคำพูด(<job id>)` จาก netlify/lib/core-freshness.mjs แทน (คิดจาก cron จริง)\n" +
      "  ⇒ ถ้าข้อความนั้นไม่ได้พูดถึงรอบงานของเรา ให้เพิ่มใน `ยกเว้นข้อความ` **พร้อมเหตุผล**\n" +
      เจอ.map((x) => `    ${x.ไฟล์}: ${x.ข้อความ}`).join("\n"),
  );
});

test("ทุกข้อในรายการยกเว้นต้องมีเหตุผล และต้องยังเจอในซอร์สจริง", () => {
  for (const x of ยกเว้นข้อความ) {
    assert.ok(x.เหตุผล && x.เหตุผล.length > 10, `ยกเว้น "${x.มีคำว่า}" ไม่มีเหตุผลกำกับ`);
  }
  /* ⚠️ ทิศย้อน: ยกเว้นที่ไม่มีของจริงรองรับแล้ว **ต้องถูกถอดออก**
     ไม่งั้นรายการยกเว้นจะโตทางเดียวจนกลายเป็นที่ซ่อนของ (ด่านที่ยกเว้นทุกอย่าง = ไม่มีด่าน) */
  const ทั้งหมด = [];
  const เดิน = (d) => {
    for (const f of readdirSync(d)) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) { เดิน(p); continue; }
      if (/\.(mjs|js)$/.test(f)) ทั้งหมด.push(readFileSync(p, "utf8"));
    }
  };
  เดิน("netlify");
  const รวม = ทั้งหมด.join("\n");
  const ค้าง = ยกเว้นข้อความ.filter((x) => !รวม.includes(x.มีคำว่า)).map((x) => x.มีคำว่า);
  assert.deepEqual(ค้าง, [], "ข้อยกเว้นเหล่านี้ไม่มีของจริงในซอร์สแล้ว ให้ถอดออก: " + ค้าง.join(" · "));
});

