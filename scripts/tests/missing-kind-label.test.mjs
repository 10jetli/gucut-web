/* ด่าน: กอง "คลังไม่รู้จักรหัสนี้" ต้องแยก **ชุดหลายชิ้น** ออกมา
 *
 * 🔴 ที่มา 19 ก.ย. 2569 — ฝั่งจอเทียบ 26 รหัสกอง `unknown` กับทะเบียนชุด 360 รหัส
 *    แล้วพบว่า **11 รหัสอยู่ในทะเบียนชุดตรงตัว** (00073-11.8-KK · 00277 set ลูกสูบ …)
 *    ⇒ คลังรู้จักมันดี · ที่ทำไม่ได้คือ **ตัวเทียบคิดจำนวนจากสูตรหลายชิ้นไม่ได้**
 *      (โค้ดเขียนไว้ตรง ๆ ว่า `if (count !== 1) continue` — ข้ามโดยตั้งใจ)
 *    ⇒ ป้ายเดิมบอก "คลังไม่รู้จัก" ⇒ ใบงานเกือบกลายเป็น "ไปจัดระเบียบรายการที่ลงขาย"
 *      ทั้งที่ของถูกจดทะเบียนไว้เรียบร้อยแล้ว
 * 🔑 **ป้ายที่ผิดพาคนไปทำงานผิด** และไม่มีอะไรฟ้อง เพราะจำนวนในกองถูกต้องทุกแถว
 *
 * 📌 ตัวติดป้ายถูก **แยกออกมาเป็นฟังก์ชันบริสุทธิ์** เพื่อให้ด่านนี้เรียกของจริงได้
 *    (เดิมฝังกลางลูปที่ต้องยิงเน็ตก่อน ⇒ เทสต์จะเป็นของประดับที่ไม่เคยเรียกโค้ดนั้น)
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ป้ายเหตุจับคู่ไม่ได้ } from "../../netlify/lib/shopee-stock.mjs";

test("ชุดหลายชิ้น ⇒ ห้ามบอกว่าคลังไม่รู้จัก", () => {
  const r = ป้ายเหตุจับคู่ไม่ได้(4);
  assert.equal(r.kind, "bundle_multi_part");
  assert.equal(r.parts, 4);
  assert.match(r.why, /คลังรู้จัก/, "ต้องบอกชัดว่าคลังรู้จัก — คนอ่านจะได้ไม่ไปสร้างของใหม่");
  assert.ok(!/ไม่รู้จักรหัสนี้เลย/.test(r.why), "ห้ามใช้ถ้อยคำของกองที่ไม่รู้จักจริง");
});

test("ไม่อยู่ในทะเบียนชุดเลย ⇒ ยังต้องเป็น not_in_warehouse", () => {
  /* ⚠️ ทิศนี้สำคัญเท่ากัน — ถ้าติดป้าย bundle ให้ทุกตัว กองที่ต้องจัดระเบียบจริงจะหายไป */
  const r = ป้ายเหตุจับคู่ไม่ได้(0);
  assert.equal(r.kind, "not_in_warehouse");
  assert.ok(!("parts" in r), "ไม่ใช่ชุด ⇒ ไม่ควรมีช่องจำนวนชิ้นส่วน");
});

test("ชุดชิ้นเดียว (คิดจำนวนได้) ต้องไม่ถูกเรียกว่าชุดหลายชิ้น", () => {
  /* ชุดชิ้นเดียวถูกคิดจำนวนได้อยู่แล้วก่อนถึงกองนี้ ⇒ ถ้ามาถึงตรงนี้แปลว่าคลังไม่มีม้วนแม่
     ⇒ ป้ายที่ถูกคือ not_in_warehouse ไม่ใช่ bundle_multi_part */
  assert.equal(ป้ายเหตุจับคู่ไม่ได้(1).kind, "not_in_warehouse");
});

test("ค่าที่อ่านไม่ได้ ⇒ ต้องไม่กลายเป็นชุดหลายชิ้น (ไม่รู้ ห้ามเดาไปทางที่ดูดี)", () => {
  for (const v of [null, undefined, "", NaN, "abc"]) {
    assert.equal(ป้ายเหตุจับคู่ไม่ได้(v).kind, "not_in_warehouse", `ค่า ${String(v)} ต้องไม่ถูกนับเป็นชุด`);
  }
});

/* ── ⑤ ขอ `full` ต้องได้รายชื่อครบ — และต้องประกาศว่าครบหรือถูกตัด ─────────────
 * 🔴 ฝั่งจอจับได้ 19 ก.ย. 2569: `?stockpush=1` รายงาน `skipUnknown` รวม **31**
 *    แต่ส่ง `skipUnknownSample` มาแค่ **26 รายชื่อ** ⇒ มี 5 รหัสที่นับแล้วไม่มีชื่อ
 *    ⇒ จอขึ้นคำเตือน "มีเลขแต่ไม่มีรายการ" ได้ แต่ **ไล่ต่อไม่ได้ว่า 5 ตัวนั้นอยู่กองไหน**
 * 🔑 เหตุ: ตัวนับมาจาก `missing` · รายชื่อมาจากตัวอย่างที่ตัดที่ 20
 *    ⇒ **สองค่ามาจากคนละที่ โดยไม่มีใครประกาศ** [[display-limits-cant-decide]]
 * 📌 และของจริงคือ `lazada.mjs` แก้ข้อนี้ไปแล้วก่อนหน้า (`o.full || …`)
 *    ⇒ **แก้ไปแล้ว 1 จาก 3 เจ้า แล้วไม่มีใครรู้ว่าอีกสองเจ้ายังไม่แก้** — กับดักที่ทีมเจอซ้ำที่สุด
 * ⚠️ ด่านนี้ตรวจ **ทั้งสามเจ้า** ไม่ใช่เจ้าที่เพิ่งแก้ ⇒ วันหนึ่งใครเพิ่มเจ้าที่สี่จะถูกจับ
 */
import { readFileSync } from "node:fs";

test("⑤ ทั้งสามเจ้าต้องเคารพ full เวลาเก็บรายชื่อรหัสที่คลังไม่รู้จัก", () => {
  const ไฟล์ = {
    shopee: "netlify/lib/shopee-stock.mjs",
    lazada: "netlify/lib/lazada.mjs",
    tiktok: "netlify/lib/tiktok-stock.mjs",
  };
  for (const [เจ้า, p] of Object.entries(ไฟล์)) {
    const src = readFileSync(p, "utf8");
    const บรรทัด = src.split("\n").filter((l) => /missingSample\.push\(/.test(l) || /missingSample\.length\s*</.test(l));
    assert.ok(บรรทัด.length > 0, `${เจ้า}: หาจุดเก็บรายชื่อไม่เจอ — เปลี่ยนรูปโค้ดแล้วต้องมาแก้ด่านนี้`);
    const รวม = บรรทัด.join(" ");
    assert.match(
      รวม, /o\.full\s*\|\|/,
      `${เจ้า}: ไม่เคารพ full ⇒ ขอรายชื่อครบแล้วยังได้แค่ตัวอย่าง ` +
        "⇒ ตัวนับกับรายชื่อไม่ตรงกันโดยไม่มีอะไรฟ้อง (ของจริงเคยต่างกัน 31 vs 26)",
    );
  }
});

test("⑤ ต้องประกาศว่ารายชื่อครบหรือถูกตัด ไม่ให้ปลายทางเดาจากความยาว", () => {
  /* ผูกกับ **เจตนา**: ต้องมีช่องที่บอกความครบ ไม่ผูกกับชื่อช่องแบบตายตัวเกินไป
     (ยอมรับทั้ง shopee และ tiktok ที่ใช้ชื่อเดียวกัน — lazada ยังไม่มี ⇒ เป็นของค้างที่ประกาศไว้) */
  for (const p of ["netlify/lib/shopee-stock.mjs", "netlify/lib/tiktok-stock.mjs"]) {
    const src = readFileSync(p, "utf8");
    assert.match(src, /missingSampleครบ/, `${p}: ต้องประกาศว่ารายชื่อครบหรือไม่`);
    assert.match(src, /missingSampleเพดาน/, `${p}: ต้องประกาศเพดานที่ใช้ตัด`);
  }
});
