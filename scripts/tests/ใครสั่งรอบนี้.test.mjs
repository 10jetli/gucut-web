import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { ผู้เรียกจากคำขอ } from "../../netlify/lib/job-timing.mjs";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const โค้ดของ = (p) => ตัดคอมเมนต์(readFileSync(p, "utf8"), p);

test("รอบของตัวจัดตาราง (body มี next_run) ⇒ cron", async () => {
  const req = new Request("https://x/.netlify/functions/returns-sync", {
    method: "POST", body: JSON.stringify({ next_run: "2026-09-20T18:07:00Z" }),
  });
  assert.equal(await ผู้เรียกจากคำขอ(req), "cron");
});

test("รอบที่มาทาง URL ⇒ http (ทั้งแบบมี body อื่น และแบบ GET)", async () => {
  const มีbody = new Request("https://x/.netlify/functions/returns-sync", {
    method: "POST", body: JSON.stringify({ pages: 3 }),
  });
  assert.equal(await ผู้เรียกจากคำขอ(มีbody), "http");
  assert.equal(await ผู้เรียกจากคำขอ(new Request("https://x/.netlify/functions/returns-sync")), "http");
});

test("🔑 อ่านไม่ได้ ⇒ **ไม่รู้** ห้ามเดาเป็น cron", async () => {
  /* ⚠️ เดาผิดทางนี้คือทิศที่หลอกตาที่สุด: เลข "รอบ cron" บวมด้วยรอบที่ไม่ใช่ cron
     แล้วคนอ่านจะไปแก้ตาราง ทั้งที่ตารางถูกอยู่แล้ว */
  assert.equal(await ผู้เรียกจากคำขอ(undefined), "ไม่รู้");
  assert.equal(await ผู้เรียกจากคำขอ({}), "ไม่รู้");
  const bodyไม่ใช่json = new Request("https://x/y", { method: "POST", body: "ไม่ใช่ json" });
  assert.equal(await ผู้เรียกจากคำขอ(bodyไม่ใช่json), "ไม่รู้");
});

test("🔬 พลังแยกแยะ: สามขาต้องให้คำตอบ **ต่างกัน** (ถ้าเป็นค่าคงที่ ข้อนี้ต้องแดง)", async () => {
  const ผล = new Set([
    await ผู้เรียกจากคำขอ(new Request("https://x/y", { method: "POST", body: JSON.stringify({ next_run: 1 }) })),
    await ผู้เรียกจากคำขอ(new Request("https://x/y")),
    await ผู้เรียกจากคำขอ(undefined),
  ]);
  assert.equal(ผล.size, 3, `ต้องแยกได้สามสถานะ (ได้ ${[...ผล].join(" · ")})`);
});

test("ค่าเริ่มต้นของ `ผู้เรียก` ห้ามเป็น cron — **ทุกที่ รวมทางเขียนจริง**", () => {
  /* 🔴 รอบแรกผมเขียนข้อนี้ให้ดูแค่ `ผู้เรียก = "..."` (ค่าเริ่มต้นของพารามิเตอร์)
     ⇒ **เขียวทันที ทั้งที่ทางเขียนแถวจริงยังเป็น `String(ผู้เรียก || "cron")`**
     🔑 คลาส: ด่านที่ดูเฉพาะ "ประตูหน้า" ไม่ได้ครอบ **บรรทัดที่ประกอบค่าลงฐานจริง**
     ⇒ เกณฑ์ที่ถูก: **คำว่า `"cron"` ห้ามอยู่ในโค้ดของไฟล์นี้เลย** (คอมเมนต์เล่าได้ตามใจ) */
  const s = โค้ดของ("netlify/lib/job-timing.mjs");
  assert.match(s, /ผู้เรียก = "ไม่รู้"/, "ค่าเริ่มต้นของพารามิเตอร์ต้องเป็น ไม่รู้");
  /* 🚫 **ห้ามเขียนเกณฑ์ว่า "ห้ามมีคำว่า cron ในโค้ดเลย"** — รอบแรกผมเขียนแบบนั้นแล้วมันไปจับ
     บรรทัดที่ **ต้อง** คืน `"cron"` คือตัวอ่านคำขอเอง ⇒ ด่านร้องใส่ของถูก
     🔑 ทิศที่ผิดจริงคือ **การ "เติม" cron ให้ค่าที่ไม่มี**: `= "cron"` · `|| "cron"` · `?? "cron"` */
  const เติมให้เอง = /(=|\|\||\?\?)\s*"cron"/;
  const ที่เหลือ = s.split("\n").map((l, i) => [i + 1, l]).filter(([, l]) => เติมให้เอง.test(l));
  assert.deepEqual(
    ที่เหลือ.map(([n]) => n), [],
    `🔴 ยังมี "cron" เป็นค่าตั้งต้นในโค้ด (บรรทัด ${ที่เหลือ.map(([n, l]) => `${n}: ${l.trim().slice(0, 60)}`).join(" · ")})`,
  );
});

test("🔑 ทุกตัวที่จดสมุด ต้องบอกผู้เรียก — ตัวใหม่ที่ลืมต้องทำให้ตก", () => {
  const ไฟล์ = [];
  for (const d of ["netlify/functions", "netlify/lib"]) {
    for (const n of readdirSync(d)) if (n.endsWith(".mjs")) ไฟล์.push(`${d}/${n}`);
  }
  const ที่จด = ไฟล์.filter((f) => !f.endsWith("job-timing.mjs") && /วัดเวลางาน\(/.test(โค้ดของ(f)));
  assert.ok(ที่จด.length >= 5, `ต้องเจอตัวที่จดสมุดอย่างน้อย 5 ตัว (เจอ ${ที่จด.length}) — เจอน้อยกว่านี้คือ **ตะแกรงพัง ไม่ใช่ครบ**`);
  const ลืม = ที่จด.filter((f) => !/ผู้เรียก/.test(โค้ดของ(f)));
  assert.deepEqual(ลืม, [], `ตัวที่จดสมุดแต่ไม่บอกผู้เรียก ⇒ แถวจะเป็น "ไม่รู้" ตลอดกาล: ${ลืม.join(" · ")}`);
});

test("🔬 พลังแยกแยะของข้อบน: ถอด `ผู้เรียก` ออกจากไฟล์หนึ่ง ⇒ ตะแกรงต้องเห็น", () => {
  const s = โค้ดของ("netlify/functions/returns-sync.mjs");
  assert.match(s, /ผู้เรียก/, "ของจริงต้องมีอยู่ก่อน");
  const ปลอม = s.replace(/ผู้เรียก/g, "ผู้เรียกที่ถูกถอด_");
  assert.doesNotMatch(ปลอม, /ผู้เรียก:/, "ของปลูกต้องไม่มีการส่งผู้เรียกเหลืออยู่");
});
