// รัน: node --experimental-test-module-mocks --test scripts/tests/ต้นทุนรายรหัส-ป้ายที่มา.test.mjs
// ใบ t_mutopb3l ขั้นที่ 4 — ท่านประธานสั่ง "ใช้ราคาซื้อที่ตั้งไว้ พร้อมป้ายบอกที่มา" (4 ต.ค. 2569)
//
// 🔑 เหตุที่ต้องมีด่านนี้: ตัวเลขต้นทุนสองตัวหน้าตาเหมือนกันเป๊ะ แต่เชื่อถือได้ไม่เท่ากัน
//    📏 วัดจริง 4 ต.ค. 2569: ราคาซื้อที่ตั้งไว้ × คงเหลือ **ต่ำกว่า** ต้นทุนเฉลี่ยของ ZORT 34.9%
//    ⇒ ถ้าป้ายหลุด คนจะเอาเลขที่เอียงต่ำ 35% ไปตั้งราคาโดยคิดว่าเป็นต้นทุนจริง (กำไรดูสูงเกินจริง)
import assert from 'node:assert/strict';
import { mock, test } from 'node:test';

let ใบซื้อ = [];
let ทะเบียน = [];
const คำสั่งที่ยิง = [];
mock.module('../../netlify/lib/coredb.mjs', {
  namedExports: {
    coreReady: () => true,
    แถวจากผล: (r) => (Array.isArray(r) ? r : (r?.results ?? [])),
    coreQuery: async (sql) => {
      คำสั่งที่ยิง.push(sql);
      if (/purchase_order_items_v2/i.test(sql)) return ใบซื้อ;
      if (/FROM products/i.test(sql)) return ทะเบียน;
      return [];
    },
  },
});

const { ต้นทุนรายรหัส, ที่มาต้นทุน } = await import('../../netlify/lib/ต้นทุนรายรหัส.mjs');
const หา = (r, sku) => r.รหัส.find((x) => x.sku === sku);

test('① ใบซื้อชนะราคาที่ตั้งไว้ — และถัวเฉลี่ยต้องถ่วงด้วยจำนวน ไม่ใช่เฉลี่ยราคาเปล่า', async () => {
  // 100 ชิ้น @6 + 10 ชิ้น @20 ⇒ ถ่วงน้ำหนัก = 800/110 = 7.2727  (เฉลี่ยราคาเปล่าจะได้ 13 ซึ่งผิด)
  ใบซื้อ = [{ sku: 'A1', มูลค่า: 100 * 6 + 10 * 20, จำนวนรวม: 110, ล็อต: 2, ใบล่าสุด: '2026-03-10' }];
  ทะเบียน = [{ sku: 'A1', purchase_price: 999 }];
  const r = await ต้นทุนรายรหัส();
  const a = หา(r, 'A1');
  assert.equal(a.ที่มา, ที่มาต้นทุน.ใบซื้อ, 'ของที่จ่ายจริงต้องชนะค่าที่คนตั้ง');
  assert.equal(a.ต้นทุน, 7.2727, '🔴 ไม่ได้ถ่วงด้วยจำนวน — เฉลี่ยราคาเปล่าจะได้ 13 ซึ่งผิด 79%');
  assert.equal(a.ล็อตที่ใช้คำนวณ, 2);
  assert.equal(a['⚠️'], undefined, 'สองล็อต ไม่ต้องเตือนเรื่องล็อตเดียว');
});

test('② ล็อตเดียว ต้องเตือนว่า "ไม่ใช่ค่าเฉลี่ยที่เคลื่อนที่"', async () => {
  ใบซื้อ = [{ sku: 'A2', มูลค่า: 50 * 8, จำนวนรวม: 50, ล็อต: 1, ใบล่าสุด: '2025-09-15' }];
  ทะเบียน = [];
  const a = หา(await ต้นทุนรายรหัส(), 'A2');
  assert.equal(a.ต้นทุน, 8);
  assert.match(a['⚠️'], /ใบซื้อใบเดียว/,
    '🔴 "เฉลี่ย" ที่มีของเดียวต้องประกาศตัว ไม่ใช่ปล่อยให้ดูเหมือนค่าเฉลี่ยจริง');
});

test('③ 🔑 ไม่มีใบซื้อ ⇒ ใช้ราคาที่ตั้งไว้ **แต่ต้องติดป้ายบอก**', async () => {
  ใบซื้อ = [];
  ทะเบียน = [{ sku: 'A3', purchase_price: 6.2 }];
  const a = หา(await ต้นทุนรายรหัส(), 'A3');
  assert.equal(a.ต้นทุน, 6.2);
  assert.equal(a.ที่มา, ที่มาต้นทุน.ตั้งไว้,
    '🔴 ป้ายหลุด = คนอ่านจะปฏิบัติกับเลขที่เอียงต่ำ 35% เท่ากับต้นทุนจริง');
});

test('④ 🔑 ไม่มีทั้งสองอย่าง ⇒ ต้นทุนเป็น null **ห้ามเป็น 0**', async () => {
  ใบซื้อ = []; ทะเบียน = [];
  const r = await ต้นทุนรายรหัส({ skus: ['A4'] });
  const a = หา(r, 'A4');
  assert.equal(a.ต้นทุน, null, '🔴 ต้นทุน 0 ทำให้กำไรกลายเป็น 100% ของราคาขาย');
  assert.equal(a.ที่มา, ที่มาต้นทุน.ไม่รู้);
  assert.equal(r.สรุปที่มา[ที่มาต้นทุน.ไม่รู้], 1, 'ต้องนับรหัสที่ไม่รู้ต้นทุนให้เห็น');
});

test('⑤ ราคาที่ตั้งไว้เป็น 0 ในทะเบียน = "ไม่ได้ตั้ง" ไม่ใช่ต้นทุนศูนย์', async () => {
  ใบซื้อ = [];
  ทะเบียน = [{ sku: 'A5', purchase_price: 0 }];
  const a = หา(await ต้นทุนรายรหัส({ skus: ['A5'] }), 'A5');
  assert.equal(a.ต้นทุน, null);
  assert.equal(a.ที่มา, ที่มาต้นทุน.ไม่รู้, '0 ในทะเบียนต้องไม่กลายเป็นต้นทุนที่เชื่อถือได้');
});

test('⑥ ใบซื้อที่ยกเลิกต้องไม่ถูกนับ — ตรวจที่คำสั่ง SQL ที่พ่นจริง', async () => {
  ใบซื้อ = []; ทะเบียน = [];
  คำสั่งที่ยิง.length = 0;
  await ต้นทุนรายรหัส();
  const sql = คำสั่งที่ยิง.find((s) => /purchase_order_items_v2/i.test(s));
  assert.match(sql, /<> 'Voided'/, '🔴 นับใบที่ยกเลิก = ต้นทุนเพี้ยนจากใบที่ไม่เคยเกิดขึ้น');
  assert.match(sql, /i\.price IS NOT NULL AND i\.price > 0/,
    '🔴 บรรทัดที่ไม่มีราคาจะถ่วงค่าเฉลี่ยลงเป็นศูนย์');
});

test('⑦ 🔒 ขอบเขต "ต้นทุนณวันนี้" ต้องติดไปกับคำตอบทุกครั้ง', async () => {
  ใบซื้อ = []; ทะเบียน = [];
  const r = await ต้นทุนรายรหัส({ skus: ['A7'] });
  assert.match(r['🔒 ขอบเขต'], /ไม่ใช่ต้นทุนตอนที่ขายใบนั้นไป/,
    '🔴 ไม่มีขอบเขต = จอจะเอาต้นทุนวันนี้ไปคิดกำไรย้อนหลังรายใบ');
  assert.ok(r.คำอธิบายที่มา[ที่มาต้นทุน.ตั้งไว้].includes('34.9%'),
    'คำอธิบายของแหล่งที่เอียง ต้องบอกขนาดที่วัดได้ ไม่ใช่คำว่า "ไม่แม่น"');
});

test('⑧ 🔬 พลังแยกแยะ: แหล่ง ZORT ต้องยัง **ไม่ถูกใช้** ตอนที่ยังไม่มีข้อมูล', async () => {
  ใบซื้อ = [{ sku: 'A8', มูลค่า: 10, จำนวนรวม: 1, ล็อต: 1, ใบล่าสุด: null }];
  ทะเบียน = [];
  const r = await ต้นทุนรายรหัส();
  assert.ok(!r.รหัส.some((x) => x.ที่มา === ที่มาต้นทุน.zort),
    '🔴 แหล่งที่น่าเชื่อถือที่สุดต้องไม่ชนะเงียบ ๆ ตอนที่ยังไม่มีของจริงรองรับ');
  assert.equal(r.สรุปที่มา[ที่มาต้นทุน.zort], undefined, 'ยังไม่ต่อ ⇒ ต้องไม่โผล่ในสรุป');
});
