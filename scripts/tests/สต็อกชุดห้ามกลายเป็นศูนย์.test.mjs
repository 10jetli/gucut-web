/* 🧪 ตัวควบคุมลบ — ปลูกในโค้ด (ไม่ใช่คอมเมนต์) แล้วด่านต้องแดง */
test("🧪 ตัวควบคุม: เปลี่ยน `break` แทน `return` ตอนได้ไม่ครบ ⇒ ด่านต้องจับได้", () => {
  /* 🔴 ข้อความเดียวกันเคยอยู่ **สองงาน** (syncBundles กับ syncBundleRecipes)
     ⇒ รุ่นแรกของตัวควบคุมนี้ปลูกงานแรก แล้วเช็คว่าข้อความหายจากทั้งไฟล์ ⇒ **ไม่หาย** เพราะอีกงานยังมี
     ⇒ คลาสเดิมอีกรอบ (อ่านที่แรกแล้วสรุปแทนทั้งไฟล์) · แก้สองชั้น:
        ① ติดชื่องานในข้อความของทั้งสองงาน ⇒ เวลาเตือนขึ้น คนรู้ว่างานไหนล้ม
        ② ตัวควบคุมเช็คในก้อนของ syncBundles เท่านั้น */
  /* 🔄 ปลูกของใหม่ (12 ต.ค.): ทางออก "อ่านหน้าไม่ได้" ย้ายไปอยู่ใน `catch` ของผู้เรียกแล้ว
     ⚠️ ข้อความ `ชื่อ: "syncBundles"` **ยังเป็นของเฉพาะงานนี้** ⇒ ยังปลูกตรงจุดได้
        และต้องยืนยันว่าของงานฝาแฝดยังอยู่ (เหตุเดิม: ของเดิมปลูกงานแรกแล้วเช็คทั้งไฟล์ ⇒ ไม่หาย) */
  const { ปลูก, บรรทัด } = ปลูกในโค้ด(
    ดิบ,
    '      return { ok: false, งาน: "syncBundles", error: `${e?.message || e} — รอบนี้ไม่เขียนอะไร` };',
    "      break;",
    { ไฟล์ }
  );
  console.log(`   🌱 ปลูกในโค้ดบรรทัด ${บรรทัด}`);
  const โค้ดปลูก = ตัดคอมเมนต์(ปลูก, ไฟล์, { คงเลขบรรทัด: true });
  const ที่syncBundles = โค้ดปลูก.indexOf('ชื่อ: "syncBundles"');
  assert.ok(ที่syncBundles > 0, "ปลูกแล้วตัว syncBundles ต้องยังเรียกกติกากลางอยู่");
  const ก้อนปลูก = โค้ดปลูก.slice(Math.max(0, ที่syncBundles - 400), ที่syncBundles + 500);
  assert.ok(
    !/catch \(e\) \{[\s\S]{0,200}return \{ ok: false/.test(ก้อนปลูก),
    "ปลูกแล้ว `return` ใน catch ของ syncBundles ต้องหาย ⇒ เกณฑ์ของด่านต้องเป็นเท็จ"
  );
  const ที่recipes = โค้ดปลูก.indexOf('ชื่อ: "syncBundleRecipes"');
  const ก้อนrecipes = โค้ดปลูก.slice(Math.max(0, ที่recipes - 400), ที่recipes + 500);
  assert.match(ก้อนrecipes, /catch \(e\) \{[\s\S]{0,200}return \{ ok: false/,
    "และงานฝาแฝดต้องยังอยู่ ⇒ พิสูจน์ว่าปลูกตรงจุด ไม่ได้ลบเหมารวม");
});

