import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด, ปลูกในโค้ด } from "./_src.mjs";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const ไฟล์ = "netlify/lib/core-products.mjs";
const ดิบ = readFileSync(ไฟล์, "utf8");
const โค้ด = ซอร์สไม่เอาคอมเมนต์(ไฟล์);

/* ── ยกสูตรจริงออกมาเรียก (ไฟล์นี้ไม่ export ตัวช่วยเลข ⇒ ประเมินจากบรรทัดในซอร์ส)
   🔑 **ไม่ได้พิมพ์สูตรใหม่** — ถ้าซอร์สเปลี่ยน บรรทัดที่ยกมาจะเปลี่ยนตาม ⇒ ด่านวัดของจริง
      (ถ้าพิมพ์สูตรใหม่เอง ด่านจะทดสอบความเข้าใจของผม ไม่ใช่โค้ดที่รัน — คลาส tautology) */
function ยกสูตร(ชื่อ) {
  const i = โค้ด.indexOf(`const ${ชื่อ} = `);
  assert.ok(i > 0, `ยกสูตร ${ชื่อ} จากซอร์สไม่ได้ — ไฟล์เปลี่ยนโครง ให้แก้ด่าน ไม่ใช่ลบด่าน`);
  const j = โค้ด.indexOf(";", i);
  const นิพจน์ = โค้ด.slice(i + `const ${ชื่อ} = `.length, j);
  // eslint-disable-next-line no-new-func
  return new Function(`"use strict"; return (${นิพจน์});`)();
}
const num = ยกสูตร("num");
const numOrNull = ยกสูตร("numOrNull");
const sameNum = ยกสูตร("sameNum");

test("✅ ยกสูตรจากซอร์สได้จริง (ยกไม่ได้ = เขียวลวง)", () => {
  for (const [ชื่อ, f] of [["num", num], ["numOrNull", numOrNull], ["sameNum", sameNum]])
    assert.equal(typeof f, "function", `${ชื่อ} ไม่ใช่ฟังก์ชัน`);
});

test("🔴 ZORT ไม่ส่งค่าสต็อกมา ⇒ ต้องได้ `null` ไม่ใช่ `0` (0 = 'ของหมด' ซึ่งเป็นคำอ้างที่เราไม่รู้)", () => {
  for (const ว่าง of [null, undefined, "", "  ", "abc", NaN, {}])
    assert.equal(
      numOrNull(ว่าง),
      null,
      `numOrNull(${JSON.stringify(ว่าง)}) ต้องเป็น null · ได้ ${JSON.stringify(numOrNull(ว่าง))} ` +
        "⇒ ถ้าเป็น 0 จอจะปิดการขายชุดที่ยังขายได้"
    );
});

test("🔴 สต็อกติดลบต้องถูกเก็บตามจริง **ห้ามปัดขึ้น 0**", () => {
  for (const ลบ of [-1, -7, "-3", -0.5])
    assert.equal(numOrNull(ลบ), Number(ลบ), `ค่าติดลบ ${ลบ} ต้องไม่ถูกปัด — ปัดขึ้น = ขายของที่ไม่มี`);
  assert.equal(numOrNull(0), 0, "ศูนย์จริงต้องเป็น 0 (วัดได้ว่าหมด) ไม่ใช่ null");
});

test("🔑 ราคาใช้ `num` (ไม่รู้ ⇒ 0) แต่สต็อกใช้ `numOrNull` — สองช่องนี้ต้องไม่สลับกัน", () => {
  assert.equal(num(undefined), 0, "num ต้องให้ 0 เมื่อไม่รู้ (ราคายอมให้เป็น 0 ได้)");
  assert.notEqual(numOrNull(undefined), 0, "สต็อกห้ามใช้สูตรของราคา");
  /* ตรวจว่าซอร์สยังใช้คู่ที่ถูก — สลับแล้วจะไม่มีอะไรฟ้องเลย เพราะทั้งสองคืนตัวเลขเหมือนกัน */
  /* ⚠️ ต้องจำกัดขอบเขตให้อยู่ใน `syncBundles` เท่านั้น — ไฟล์นี้มีตัวซิงก์หลายตัว
     รุ่นแรกของด่านนี้กวาดทั้งไฟล์แล้วแดง ⇒ **แดงถูกเรื่องแต่ผิดที่** (ดูหมายเหตุกองสินค้าข้างล่าง) */
  const เริ่ม = โค้ด.indexOf("export async function syncBundles");
  assert.ok(เริ่ม > 0, "ไม่เจอ syncBundles");
  const ก้อนชุด = โค้ด.slice(เริ่ม, โค้ด.indexOf("export async function", เริ่ม + 10));
  const i = ก้อนชุด.indexOf("onhand: numOrNull(");
  assert.ok(i > 0, "`onhand` ของสินค้าเป็นชุดต้องใช้ numOrNull");
  console.log(`   🔎 onhand ใช้ numOrNull ที่บรรทัด ${เลขบรรทัด(โค้ด, เริ่ม + i)}`);
  assert.match(ก้อนชุด, /available: numOrNull\(/, "`available` ของชุดต้องใช้ numOrNull");
  assert.ok(!/onhand: num\(|available: num\(/.test(ก้อนชุด),
    "เจอสต็อกของชุดใช้ `num(` ⇒ ค่าที่ไม่รู้จะกลายเป็น 0 เงียบ ๆ");
});

test("🔑 `sameNum` ต้องแยก null จาก 0 — ไม่งั้นค่าที่หายจะถูกมองว่า 'ไม่เปลี่ยน'", () => {
  assert.equal(sameNum(null, 0), false, "ของเดิม null กับของใหม่ 0 **ต่างกัน** ⇒ ต้องเขียนทับ");
  assert.equal(sameNum(0, null), false, "ของเดิม 0 กับของใหม่ null ต่างกัน");
  assert.equal(sameNum(null, null), true, "null กับ null เหมือนกัน");
  assert.equal(sameNum(5, 5), true);
  assert.equal(sameNum("5", 5), true, "ZORT ส่งเลขเป็นสตริงได้ ⇒ ต้องเทียบค่า ไม่ใช่ชนิด");
  assert.equal(sameNum(-1, -1), true, "ค่าติดลบต้องเทียบได้เหมือนค่าอื่น");
});

test("🔴 ถาม ZORT ได้ไม่ครบทุกหน้า ⇒ **ห้ามเขียนอะไรเลย** (ไม่ใช่เขียนชุดสั้นทับของเดิม)", () => {
  const i = โค้ด.indexOf("[syncBundles] ถามรายชื่อชุดจาก ZORT หน้า");
  assert.ok(i > 0, "ไม่เจอทางออก 'หน้าใดถามไม่สำเร็จ' — เส้นนี้เคยมี ห้ามหาย");
  const ที่ = เลขบรรทัด(โค้ด, i);
  console.log(`   🔎 ทางออก 'ได้ไม่ครบ' อยู่บรรทัด ${ที่}`);
  const ก้อน = โค้ด.slice(Math.max(0, i - 300), i + 200);
  assert.match(ก้อน, /return \{ ok: false/, "ต้อง `return` ออกทันที (ไม่ใช่ break แล้วเขียนต่อ)");
  assert.match(ก้อน, /!Array\.isArray\(data\?\.list\)/,
    "เกณฑ์ต้องเป็น 'ไม่ได้อาร์เรย์' — ถ้าเช็คแค่ `res.ok` จะปล่อย 200-แต่-เนื้อว่างผ่าน");
  assert.match(โค้ด, /if \(!all\.length\) return \{ ok: false/,
    "รายชื่อว่างต้องตีกลับด้วย — ว่างเพราะ ZORT สะดุด กับว่างเพราะไม่มีชุด แยกจากผลลัพธ์ไม่ออก");
});

/* 🧪 ตัวควบคุมลบ — ปลูกในโค้ด (ไม่ใช่คอมเมนต์) แล้วด่านต้องแดง */
test("🧪 ตัวควบคุม: เปลี่ยน `break` แทน `return` ตอนได้ไม่ครบ ⇒ ด่านต้องจับได้", () => {
  /* 🔴 ข้อความเดียวกันเคยอยู่ **สองงาน** (syncBundles กับ syncBundleRecipes)
     ⇒ รุ่นแรกของตัวควบคุมนี้ปลูกงานแรก แล้วเช็คว่าข้อความหายจากทั้งไฟล์ ⇒ **ไม่หาย** เพราะอีกงานยังมี
     ⇒ คลาสเดิมอีกรอบ (อ่านที่แรกแล้วสรุปแทนทั้งไฟล์) · แก้สองชั้น:
        ① ติดชื่องานในข้อความของทั้งสองงาน ⇒ เวลาเตือนขึ้น คนรู้ว่างานไหนล้ม
        ② ตัวควบคุมเช็คในก้อนของ syncBundles เท่านั้น */
  const { ปลูก, บรรทัด } = ปลูกในโค้ด(
    ดิบ,
    '      return { ok: false, งาน: "syncBundles", error: `[syncBundles] ถามรายชื่อชุดจาก ZORT หน้า ${page} ไม่สำเร็จ — รอบนี้ไม่เขียนอะไร` };',
    "      break;",
    { ไฟล์ }
  );
  console.log(`   🌱 ปลูกในโค้ดบรรทัด ${บรรทัด}`);
  const โค้ดปลูก = ตัดคอมเมนต์(ปลูก, ไฟล์, { คงเลขบรรทัด: true });
  assert.ok(!/\[syncBundles\] ถามรายชื่อชุด/.test(โค้ดปลูก), "ปลูกแล้วทางออกของ syncBundles ต้องหายจากโค้ด");
  assert.match(โค้ดปลูก, /\[syncBundleRecipes\] ถามรายชื่อชุด/,
    "และงานอีกตัวต้องยังอยู่ ⇒ พิสูจน์ว่าปลูกตรงจุด ไม่ได้ลบเหมารวม");
});

test("🧪 ตัวควบคุม: เปลี่ยนสต็อกไปใช้ `num` ⇒ ด่านต้องจับได้", () => {
  const { ปลูก, บรรทัด } = ปลูกในโค้ด(ดิบ, "onhand: numOrNull(b?.stock)", "onhand: num(b?.stock)", { ไฟล์ });
  console.log(`   🌱 ปลูกในโค้ดบรรทัด ${บรรทัด}`);
  const โค้ดปลูก = ตัดคอมเมนต์(ปลูก, ไฟล์, { คงเลขบรรทัด: true });
  assert.match(โค้ดปลูก, /onhand: num\(/, "ปลูกต้องติดในโค้ด");
  /* เกณฑ์เดียวกับที่ด่านจริงใช้ ⇒ ถ้าเกณฑ์นั้นจับได้ เคสนี้ต้องเป็นจริง */
  assert.ok(/onhand: num\(|available: num\(/.test(โค้ดปลูก),
    "เกณฑ์ของด่านต้องเป็นจริงกับซอร์สที่ปลูกแล้ว — ถ้าไม่จริง เกณฑ์นั้นจับของจริงไม่ได้");
});

