/* 🗄️ ด่าน: **เพดานของเราต้องอยู่ใต้เพดานของ D1 — และการข้ามคีย์ต้องไม่เงียบ**
 *
 * 🔴 ที่มา 21 ก.ย. 2569 (ของจริง · ไล่จากสมุดงานที่ฝั่งจอชี้ว่า `backup-run` ล้ม 6/6)
 *    สั่งรัน `?backup=1` แล้วได้ชื่อถังกับเหตุตรง ๆ:
 *    `gucut-coupon (โค้ดส่วนลด · พิกเซล · กติกาบอต) ⇒ D1 400: statement too long: SQLITE_TOOBIG`
 *    ⇒ อีก 10 ถังสำเร็จครบ ⇒ **"หนึ่งถังใน 11 ล้มมา 7 วัน" ไม่ใช่ "ไม่มีสำรองเลย"**
 *
 * 🔑 เหตุราก **สองชั้น**
 *    ① `MAX_ONE = 180_000` **สูงกว่าเพดานคำสั่งของ D1 (~100 KB)** ⇒ ค่าที่ผ่านด่านของเรา
 *       ยังใหญ่เกินสำหรับปลายทาง ⇒ **ด่านขนาดที่กันอะไรไม่ได้เลย**
 *    ② วัด **ขนาดของค่า** แต่ D1 จำกัด **ขนาดของคำสั่ง SQL** (escape + โครง `(...)` ทำให้ใหญ่กว่า)
 *       และเช็ค `batchBytes >= BATCH_BYTES` **หลัง** ใส่แถวแล้ว ⇒ ก้อนสุดท้ายโตได้ถึง
 *       `BATCH_BYTES + MAX_ONE` ⇒ **เกินเพดานได้ทั้งที่ทุกค่าผ่านด่าน**
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { D1_คำสั่งยาวสุด_ไบต์, SQL_ปลอดภัย, MAX_ONE } from "../../netlify/lib/backup.mjs";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";

const ไฟล์ = fileURLToPath(new URL("../../netlify/lib/backup.mjs", import.meta.url));
const โค้ด = ตัดคอมเมนต์(readFileSync(ไฟล์, "utf8"), ไฟล์);

test("🔑 เพดานของเราต้องอยู่ **ใต้** เพดานของ D1 (ค่าจริง ไม่ใช่ข้อความ)", () => {
  assert.ok(SQL_ปลอดภัย < D1_คำสั่งยาวสุด_ไบต์,
    `เพดานที่เราใช้ (${SQL_ปลอดภัย}) ต้องต่ำกว่าของ D1 (${D1_คำสั่งยาวสุด_ไบต์})`);
  assert.ok(MAX_ONE < SQL_ปลอดภัย, `แถวเดียว (${MAX_ONE}) ต้องไม่เกินก้อน (${SQL_ปลอดภัย})`);
  /* 🔴 ค่าเดิมที่ทำให้ล้มจริง — ถ้าใครตั้งกลับไปสูงกว่าเพดาน D1 ด่านนี้ต้องแดง */
  assert.ok(MAX_ONE < D1_คำสั่งยาวสุด_ไบต์ * 0.8,
    "แถวเดียวต้องเผื่อที่ให้ escape และโครงคำสั่งด้วย (ของเดิม 180,000 = เกินเพดาน D1 เกือบสองเท่า)");
});

test("🔑 ต้อง flush **ก่อน** จะเกิน ไม่ใช่หลังเกิน", () => {
  /* 🚫 พฤติกรรมนี้ทดสอบตรง ๆ ไม่ได้ (ต้องมี Blobs + D1 จริง) ⇒ ตรวจที่ตัวบทของเงื่อนไข
     **พร้อมเหตุผล** ตามกติกาที่เราตกลงกับฝั่งจอ: ด่านที่ตรึงรูปโค้ดต้องเขียนว่าทำไมวัดพฤติกรรมไม่ได้ */
  assert.match(โค้ด, /if \(batchBytes \+ แถวไบต์ > SQL_ปลอดภัย\) await flush\(\)/,
    "ต้องเช็คผลรวมก่อนใส่แถว");
  assert.doesNotMatch(โค้ด, /batchBytes >= BATCH_BYTES\) await flush/,
    "🔴 ท่าเดิม (เช็คหลังใส่) ทำให้ก้อนสุดท้ายโตเกินเพดานได้");
  assert.match(โค้ด, /Buffer\.byteLength\(แถวSQL, "utf8"\)/,
    "ต้องวัดความยาวของ **แถว SQL จริง** (รวม escape) ไม่ใช่ขนาดค่า");
});

test("🚫 ข้ามคีย์เพราะยาวเกิน **ห้ามเงียบ** — ต้องคืนชื่อคีย์ออกไป", () => {
  /* 🔄 **เปลี่ยนเกณฑ์ 4 ต.ค. 2569** — เดิมตรึง **ข้อความตรงตัว** ของนิพจน์
     `คีย์ที่ข้าม.push({ key, bytes: size, sqlBytes: แถวไบต์ })`
     ⇒ ใบ `t_musq1h42` เปลี่ยนทางหลักจาก "ข้าม" เป็น **"หั่นเก็บ"** และเหลือการข้าม
       เฉพาะกรณีกันพลาดชั้นสอง (ชิ้นที่หั่นแล้วยังใหญ่เกิน) ซึ่งเพิ่มช่อง `เหตุ` เข้ามา
     ⇒ เทสเดิมแดงทั้งที่เจตนายังถูกครบ — **เพราะมันตรึงรูปพิมพ์ ไม่ใช่ตรึงพฤติกรรม**
     🔑 เจตนาที่ต้องรักษาไว้คือ **"ข้ามแล้วต้องรู้ว่าข้ามคีย์ไหน"** ไม่ใช่ "ต้องเขียนแบบนี้"
        ⇒ ตรวจว่าทุกจุดที่ `push` เข้ารายการคีย์ที่ข้าม **มี `key` อยู่ในนั้น** */
  const จุดpush = [...โค้ด.matchAll(/คีย์ที่ข้าม\.push\(\{([^}]*)\}\)/g)].map((m) => m[1]);
  assert.ok(จุดpush.length >= 1, "ต้องมีที่เก็บชื่อคีย์ที่ถูกข้ามอย่างน้อยหนึ่งจุด");
  for (const [i, เนื้อ] of จุดpush.entries()) {
    assert.match(เนื้อ, /\bkey\b/, `จุดที่ ${i + 1} ที่ข้ามคีย์ **ไม่ได้เก็บชื่อคีย์** ⇒ ข้ามเงียบ`);
    assert.match(เนื้อ, /sqlBytes/, `จุดที่ ${i + 1} ต้องบอกขนาดแถว SQL ที่ทำให้ข้าม`);
  }
  assert.match(โค้ด, /skippedKeys: คีย์ที่ข้าม\.slice\(0, 10\)/, "รายถังต้องส่งชื่อคีย์ที่ข้าม");
  assert.match(โค้ด, /skippedKeys: out\.flatMap/, "สรุปรวมต้องรวมชื่อคีย์ที่ข้ามจากทุกถัง");
  /* 🔑 เหตุ: ถังที่ล้มคือ **โค้ดส่วนลด · พิกเซล · กติกาบอต** ⇒ ถ้าเปลี่ยนจาก "ล้มทั้งถัง"
     เป็น "ข้ามคีย์" โดยไม่บอกชื่อ เราจะไม่รู้ว่าของที่ไม่ได้สำรองคือกติกาบอต หรือแค่แคชที่สร้างใหม่ได้ */
});

