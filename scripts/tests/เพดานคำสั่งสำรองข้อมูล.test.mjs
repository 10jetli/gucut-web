/* 🔄 **เปลี่ยนเกณฑ์ 4 ต.ค. 2569 — เดิมบังคับว่า "รายการยกเว้นต้องว่าง"**
   เหตุที่เปลี่ยน: เกณฑ์เดิมมีไว้เพราะ **ยังไม่มีใครเห็นชื่อคีย์ที่ถูกข้าม**
   วันนี้เห็นแล้วจาก `/api/core?jobtiming=1` (รอบ cron 3 ต.ค. 12:40)
   ⇒ `marketplace-listings` (67,129 B) = แคช สร้างใหม่ได้ ⇒ จัดเข้ารายการยกเว้นแล้ว
   ⇒ `office/tasks` (303,262 B) = **กระดานงานทั้งใบ สร้างใหม่ไม่ได้** ⇒ ห้ามยกเว้น
   🔑 **แต่ห้ามปลดกับดักทิ้ง** — เปลี่ยนจาก "ต้องว่าง" เป็น **"ทุกรายการต้องมีเหตุผลเขียนกำกับ
      และของที่สร้างใหม่ไม่ได้ต้องไม่อยู่ในนั้น"** ⇒ ด่านแข็งกว่าเดิม ไม่ใช่อ่อนลง
   ⚠️ เกณฑ์ "ต้องว่าง" อ่านง่ายแต่ **ตายตั้งแต่วันที่มีรายการแรกที่ถูกต้อง**
      ⇒ ด่านที่พังเมื่อระบบเดินหน้าอย่างถูกต้อง จะถูกปลดทิ้งทั้งอัน (ไม่ใช่แก้) */
/* 🔄 **เปลี่ยนเกณฑ์รอบสอง 4 ต.ค. 2569 — ด่าน `check-source-gates` ตีกลับรุ่นแรก และมันถูก**
   รุ่นแรกผมให้เทสตรวจว่ามีคำว่า "สร้างใหม่ได้" **ในคอมเมนต์** ของไฟล์
   ⇒ นั่นคือ "ด่านที่บังคับข้อความล้วน" ซึ่ง **คอมเมนต์หลอกได้** — ใครเขียนคำนั้นก็ผ่าน
   ⇒ ย้ายเหตุผลไปเป็น **ฟิลด์บังคับในข้อมูล** แล้วเทสตรวจ **โครงของข้อมูล** ไม่ใช่ตัวหนังสือ
   🔑 กฎที่ได้: **ถ้าจะบังคับให้มีเหตุผล ต้องทำให้เหตุผลเป็นของที่เครื่องชี้ได้ว่าขาด**
      เหตุผลที่อยู่ในคอมเมนต์ บังคับได้แค่ "มีคำนี้อยู่ที่ไหนก็ได้ในไฟล์" */
test("🔑 ทุกรายการยกเว้นต้องมีเหตุผลเป็นฟิลด์ และห้ามมีของที่สร้างใหม่ไม่ได้", async () => {
  const m = await import("../../netlify/functions/backup-run.mjs");
  /* อ่าน **ค่าที่โค้ดใช้จริง** ไม่ใช่ข้อความในไฟล์ ⇒ คอมเมนต์หลอกไม่ได้ */
  const รายการ = m.ข้ามได้โดยตั้งใจ ?? [];
  assert.ok(Array.isArray(รายการ), "ต้อง export รายการยกเว้นออกมาให้ตรวจได้");

  const ห้ามยกเว้น = ["office/tasks", "orders", "permits", "reviews", "staff", "time"];
  for (const r of รายการ) {
    assert.ok(r && typeof r.คีย์ === "string" && r.คีย์,
      `ทุกรายการต้องมีช่อง "คีย์" เป็นข้อความ — ได้ ${JSON.stringify(r)}`);
    assert.ok(typeof r.สร้างใหม่ได้จาก === "string" && r.สร้างใหม่ได้จาก.length > 20,
      `🔴 "${r?.คีย์}" ต้องมีช่อง "สร้างใหม่ได้จาก" ที่บอก **ที่มาจริง** (ยาวกว่า 20 ตัวอักษร)`);
    for (const ห of ห้ามยกเว้น) {
      assert.ok(!r.คีย์.includes(ห),
        `🔴 "${ห}" สร้างใหม่ไม่ได้ ⇒ ห้ามใส่ในรายการยกเว้น (ข้ามมันคือไม่มีสำเนาเลย)`);
    }
  }
});

test("🔬 พลังแยกแยะของด่านรายการยกเว้น: ป้อนของเสียต้องแดง", () => {
  /* ป้อน **โครงข้อมูลปลอม** เข้าเกณฑ์เดียวกับข้อข้างบน ⇒ พิสูจน์ว่ามันแยกแยะได้
     (ไม่ใช่ป้อนข้อความปลอม ซึ่งเป็นสิ่งที่เราเพิ่งเลิกใช้) */
  const เกณฑ์ = (รายการ) => {
    for (const r of รายการ) {
      if (!r?.คีย์) return "ไม่มีช่องคีย์";
      if (!(typeof r.สร้างใหม่ได้จาก === "string" && r.สร้างใหม่ได้จาก.length > 20)) return "ไม่มีเหตุผล";
      if (["office/tasks", "orders"].some((h) => r.คีย์.includes(h))) return "มีของที่สร้างใหม่ไม่ได้";
    }
    return "ผ่าน";
  };
  assert.equal(เกณฑ์([{ คีย์: "office/tasks", สร้างใหม่ได้จาก: "x".repeat(30) }]), "มีของที่สร้างใหม่ไม่ได้");
  assert.equal(เกณฑ์([{ คีย์: "แคชอะไรหนึ่ง" }]), "ไม่มีเหตุผล");
  assert.equal(เกณฑ์([{ คีย์: "แคชอะไรหนึ่ง", สร้างใหม่ได้จาก: "สั้นเกิน" }]), "ไม่มีเหตุผล",
    "เหตุผลสั้น ๆ แบบขอไปที ต้องไม่ผ่าน");
  assert.equal(เกณฑ์([{ คีย์: "แคชอะไรหนึ่ง", สร้างใหม่ได้จาก: "สร้างใหม่ได้จากฟังก์ชัน x ในไฟล์ y" }]), "ผ่าน");
  assert.equal(เกณฑ์([]), "ผ่าน", "รายการว่างยังต้องผ่าน (สถานะเดิมก่อน 4 ต.ค.)");
});

