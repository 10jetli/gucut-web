import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const src = (p) => readFileSync(p, "utf8");

test("คอลัมน์ caller ต้องมีทาง ALTER (ตารางเก่าต้องเติมได้) และอยู่ใน INSERT ชุดเต็ม", () => {
  const s = src("netlify/lib/job-timing.mjs");
  assert.match(s, /ADD COLUMN caller TEXT/, "ต้องมี ALTER สำหรับตารางที่สร้างไปแล้ว");
  assert.match(s, /\(job, at, ms, outcome, note, sub_ok, sub_fail, caller\)/, "INSERT ชุดเต็มต้องมี caller");
  /* 🔑 และต้องยังมี INSERT ชุดสั้นไว้เป็นทางถอย — **ห้ามให้การเพิ่มคอลัมน์ทำให้จดไม่ได้เลย** */
  assert.match(s, /\(job, at, ms, outcome, note\) VALUES \(\?, \?, \?, \?, \?\)/, "ต้องมีทางถอยชุดสั้น");
});

test("🔑 `ผู้เรียก` ต้องถูกส่งต่อ **ทั้งทางสำเร็จและทางล้ม**", () => {
  const s = src("netlify/lib/job-timing.mjs");
  /* ⚠️ ถ้าส่งแค่ทางสำเร็จ ⇒ รอบที่คนสั่งมือแล้วล้มจะถูกจดว่า cron
     ⇒ เลข "รอบ cron" บวมด้วยรอบที่ไม่ใช่ cron = ทิศที่หลอกตาที่สุด */
  /* 🔴 ตะแกรงรอบแรกผมใช้ `จดเวลางาน\(\{[^}]*\}` ⇒ **หยุดที่ `}` ของ template string**
     (`note: \`throw: ${...}\``) ⇒ ตัดก่อนถึง `ผู้เรียก` ⇒ **เทสแดงทั้งที่โค้ดถูก**
     🔑 แดงลวงจากตะแกรงของเทสเอง — ถ้าเชื่อ ผมจะไปแก้โค้ดที่ไม่ได้ผิด
     ⇒ ดู **ทั้งบรรทัด** แทน (การเรียกอยู่บรรทัดเดียวทั้งสองจุด) */
  const ที่เรียกใน_วัดเวลางาน = s.split("\n")
    .filter((ln) => /จดเวลางาน\(\{/.test(ln) && /ms: Date\.now\(\) - t0/.test(ln));
  assert.ok(ที่เรียกใน_วัดเวลางาน.length >= 2, `ต้องเจอการเรียกจดทั้งสองทาง (เจอ ${ที่เรียกใน_วัดเวลางาน.length}) — ถ้าเจอน้อยกว่านี้ ตะแกรงพัง ไม่ใช่โค้ดดีขึ้น`);
  for (const [i, x] of ที่เรียกใน_วัดเวลางาน.entries()) {
    assert.match(x, /ผู้เรียก/, `การเรียกที่ ${i + 1} ไม่ส่ง ผู้เรียก: ${x.slice(0, 90)}`);
  }
});

test("🔬 พลังแยกแยะ: ถอด ผู้เรียก ออกจากทางล้ม ⇒ เทสข้างบนต้องแดง", () => {
  const s = src("netlify/lib/job-timing.mjs");
  const ปลอม = s.replace(/(ผล: "failed", note: `throw[^`]*`), ผู้เรียก/, "$1");
  assert.notEqual(ปลอม, s, "ของปลูกต้องเปลี่ยนเนื้อจริง (ไม่งั้นข้อนี้วัดอะไรไม่ได้)");
  const เรียกจด = ปลอม.split("\n")
    .filter((ln) => /จดเวลางาน\(\{/.test(ln) && /ms: Date\.now\(\) - t0/.test(ln));
  assert.ok(เรียกจด.length >= 2, `ต้องเจอทั้งสองทางในของปลูก (เจอ ${เรียกจด.length})`);
  assert.ok(เรียกจด.some((ln) => !/ผู้เรียก/.test(ln)), "ตะแกรงต้องเห็นทางที่ขาด ผู้เรียก");
});

test("🔑 แถวเก่าที่ไม่มี caller ต้องอ่านว่า **ยังไม่รู้** ไม่ใช่ cron", () => {
  /* ⚠️ นี่คือหัวใจของสามสถานะ: `null` (ไม่รู้) ≠ `"cron"` (รู้ว่า cron)
     ⇒ ถ้าเดาว่าแถวเก่าเป็น cron จะได้เลข cron ที่บวมด้วยแถวที่ไม่รู้ที่มา */
  const s = src("netlify/lib/job-timing.mjs");
  assert.match(s, /รอบแยกตามผู้เรียก/, "ต้องส่งช่องแยกผู้เรียกให้จอ");
  assert.match(s, /r\.caller == null \? "ยังไม่รู้/, "แถวที่ caller เป็น null ต้องกลายเป็น 'ยังไม่รู้'");
  assert.doesNotMatch(s, /r\.caller \?\? "cron"/, "ห้ามเดาว่าแถวเก่าเป็น cron");
});

test("เส้นสั่งมือ ?syncreturns=1 ต้องจดสมุดด้วย ผู้เรียก 'มือ' และคืนรูปคำตอบเดิม", () => {
  const s = src("netlify/functions/core.mjs");
  const เริ่ม = s.indexOf('url.searchParams.get("syncreturns")');
  assert.ok(เริ่ม > 0, "หาเส้น syncreturns ไม่เจอ ⇒ ตะแกรงพัง");
  const เส้น = s.slice(เริ่ม, เริ่ม + 2200);
  assert.match(เส้น, /วัดเวลางาน\("returns-sync"/, "ต้องห่อด้วยตัวจดเวลา");
  assert.match(เส้น, /ผู้เรียก: "มือ"/, "ต้องระบุว่าเป็นการสั่งมือ");
  /* 🔑 เพิ่มการจด **ห้ามเปลี่ยนรูปคำตอบ** — สคริปต์/จอที่เรียกเส้นนี้อยู่ต้องไม่กระทบ */
  assert.match(เส้น, /\.\.\.t\.ผลลัพธ์/, "ต้องคืนผลลัพธ์เดิมครบ ไม่ใช่ห่อใหม่ทั้งก้อน");
});

test("🔬 สมุดต้องส่ง **แถวล่าสุดหลายแถว** — ไม่งั้นตอบไม่ได้ว่ารอบที่ซ้ำกันต่างกันยังไง", () => {
  /* 🔴 ที่มา 21 ก.ย. 2569: `returns-sync` มี 2 แถวต่อ slot · ฝั่งจอชี้ว่า **ต้องเทียบ `ms` ของทั้งคู่**
     (ต่างกันมาก = แย่งทรัพยากร · เท่ากันเป๊ะ = คำขอเดียวถูกจดสองครั้ง)
     ⇒ แต่สมุดส่งมาแค่ `ล่าสุด` แถวเดียว ⇒ ต้องยิงทุก 5 วิ คร่อมนาที cron เพื่อจับจังหวะ "นับได้ 1"
     🔑 **เครื่องมือที่ต้องมีคนเฝ้าและพึ่งโชค คือเครื่องมือที่จะไม่ถูกใช้** ⇒ ให้สมุดตอบเองได้ */
  const s = src("netlify/lib/job-timing.mjs");
  assert.match(s, /"แถวล่าสุด": rs\.slice\(0, 5\)/, "ต้องส่งแถวล่าสุดสูงสุด 5 แถว");
  assert.match(s, /at: r\.at, ms: r\.ms, outcome: r\.outcome/, "แต่ละแถวต้องมี at/ms/outcome ให้เทียบได้");
  assert.match(s, /caller: r\.caller == null \? "ยังไม่รู้/, "และต้องบอกผู้เรียกแบบสามสถานะเหมือนช่องรวม");
  /* 🚫 ห้ามส่งทั้งหมด — ช่องนี้มีไว้วินิจฉัย ไม่ใช่ดึงประวัติ (ประวัติเต็มต้องมีเพดาน+ยอดรวมของตัวเอง) */
  assert.doesNotMatch(s, /"แถวล่าสุด": rs\.map/, "ห้ามส่งทุกแถวมาในช่องวินิจฉัย");
});
