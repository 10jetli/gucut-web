/* 🔴 ด่าน: **ช่อง "หัก" ติดลบไม่ได้ · และงวดเดือนต้องเป็นเดือนที่มีอยู่จริง**
 *    (2 ต.ค. 2569 — ฝั่งจอรีวิวหน้าเงินเดือนเจอ · ฝั่งท่อยิงซ้ำยืนยันแล้วแก้)
 *
 * ① **พิมพ์ลบในช่อง "หัก" แล้วยอดโอนเพิ่มขึ้น** — ของจริงที่ยิงด้วยฟังก์ชันในไฟล์นั้นเอง:
 *    เงินเดือน 20,000 · เพิ่ม 0 · **หัก `-500`** ⇒ `net` = **20,500.00 บาท**
 *    เพราะ `net = salary + add - cut` และ `toSatang` รับเครื่องหมายลบ
 *    ⇒ `ready` ต้องการแค่ `net > 0` ⇒ **เข้าไฟล์โอนปกติ ไม่มีอะไรฟ้อง**
 *    🔑 การพิมพ์ผิดหนึ่งตัวในช่องที่ชื่อว่า "หัก" กลายเป็นการขึ้นเงิน
 *
 * ② **งวดเดือนรับเดือนที่ไม่มีอยู่จริง** — `/^\d{4}-\d{2}$/` ยอม `2026-13` · `2026-00` · `2026-99`
 *    ⇒ รายการที่บันทึกลง `adj/2026-13` **ไม่โผล่ในงวดจริงเดือนไหนเลย**
 *       คนกรอกเห็นว่า "บันทึกสำเร็จ" แล้วเงินก้อนนั้นหายเงียบ
 *    🔑 คลาสเดียวกับที่ปิดไปแล้วในกองบิล — **รูปเดียวกัน คนละไฟล์**
 *
 * 🔑 ทั้งสองข้อตีกลับได้โดยไม่ทำของที่เคยใช้ได้พัง เพราะ **ไม่มีผู้เรียกที่ถูกต้องคนไหน**
 *    พิมพ์ลบในช่อง "หัก" เพื่อให้เงินเพิ่ม (ช่อง "เพิ่ม" มีอยู่แล้ว) หรือจ่ายเงินเดือนงวดเดือนที่ 13
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ตรวจงวดเดือน, saveAdj, toSatang, toBaht } from "../../netlify/lib/payroll.mjs";

test("🔴 เดือนนอกช่วง 01–12 ต้องตีกลับ", () => {
  for (const m of ["2026-13", "2026-00", "2026-99", "2026-1", "", null]) {
    assert.throws(() => ตรวจงวดเดือน(m), /เดือน/, `ควรตีกลับ: ${JSON.stringify(m)}`);
  }
});

/* ⚠️ ตัวควบคุมลบ — ไม่มีข้อนี้ ด่านที่ "ตีกลับทุกเดือน" ก็เขียวสนิท */
test("🧪 ตัวควบคุมลบ: เดือนที่มีอยู่จริงต้องผ่าน (ขอบทั้งสองข้าง)", () => {
  for (const m of ["2026-01", "2026-12", "2026-06", "2569-02"]) {
    assert.equal(ตรวจงวดเดือน(m), m, `ควรผ่าน: ${m}`);
  }
});

test("🔴 ช่อง \"หัก\" ติดลบ ⇒ ต้องตีกลับ **ก่อนแตะที่เก็บ**", async () => {
  /* ด่านอยู่ก่อน `await readAdj()` ⇒ ยิงได้โดยไม่ต้องมีที่เก็บ
     (ถ้าใครย้ายด่านไปหลัง I/O เทสนี้จะล้มด้วย error ของที่เก็บ ไม่ใช่ข้อความของด่าน
      ⇒ ข้อความที่ assert ไว้จึงทำหน้าที่เป็นสมอว่า "ตกเพราะด่าน ไม่ใช่ตกเพราะอย่างอื่น") */
  await assert.rejects(() => saveAdj("2026-10", "emp1", { cut: "-500" }), /ติดลบไม่ได้/);
  await assert.rejects(() => saveAdj("2026-10", "emp1", { add: "-1" }), /ติดลบไม่ได้/);
});

test("🧪 ตัวควบคุมลบ: ค่าปกติต้องผ่านด่าน (ไปตกที่ที่เก็บ ไม่ใช่ที่ด่าน)", async () => {
  /* ค่าที่ถูกต้องต้อง **ไม่** ถูกด่านตีกลับ — ถ้าล้ม ต้องล้มด้วยเรื่องที่เก็บ
     ⇒ พิสูจน์ว่าด่านไม่ได้ตีกลับทุกอย่าง (ซึ่งจะทำให้บันทึกเงินเดือนไม่ได้เลย) */
  await assert.rejects(
    () => saveAdj("2026-10", "emp1", { add: "100", cut: "50" }),
    (e) => !/ติดลบไม่ได้/.test(String(e?.message || e)),
    "ค่าปกติต้องผ่านด่านค่าติดลบ",
  );
});

test("📏 ตรึงเลขของจริงที่ทำให้เจอบั๊กนี้ (ยอดโอนเพิ่มขึ้น 500 บาท)", () => {
  const net = toSatang("20000") + toSatang("0") - toSatang("-500");
  assert.equal(toBaht(net), "20,500.00");
  console.log(`   🔎 เงินเดือน 20,000 · หัก -500 ⇒ net ${toBaht(net)} บาท (ก่อนแก้ ค่านี้เข้าไฟล์โอนได้)`);
});
