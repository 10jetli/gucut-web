/* ━━ ⑥ เกณฑ์ปิดใบที่ผมเขียนไว้เอง: "ปลูกการเปลี่ยนสูตรจริง แล้วตัวนับต้องขึ้นเองโดยไม่มีใครแก้ตัวนับ" ━━
 * ทำแบบ **จำลองฐาน** ที่คิดคำตอบจากแถวปลอมเอง ⇒ วัดพฤติกรรมของตัวนับ ไม่ใช่แค่ดูข้อความ SQL
 * (ด่านข้อ ④ อ่านซอร์ส ซึ่งจับ "เขียนผิด" ได้ แต่จับ "เขียนถูกแล้วไม่ได้ผล" ไม่ได้)
 */
test('⑥ 🔬 ลายเซ็นเปลี่ยน ⇒ แถวทั้งกระจกถูกนับเป็นค้างเอง โดยไม่มีใครแก้ตัวนับ', async () => {
  const { mock } = await import('node:test');
  const ลายเซ็นเก่า = ลายเซ็นจากช่อง(ช่องที่สูตรใช้.slice(1));   // สูตรรุ่นก่อน (ช่องน้อยกว่าหนึ่งช่อง)
  assert.notEqual(ลายเซ็นเก่า, ลายเซ็นสูตร, 'ต้องต่างกันจริง ไม่งั้นการทดสอบนี้ไม่ได้ทดสอบอะไร');

  /* แถวปลอม 466 แถว เก็บลายเซ็น "รุ่นก่อน" ทั้งหมด — คือสภาพหลัง deploy ที่แก้สูตร */
  const แถวในฐาน = Array.from({ length: 466 }, (_, i) => ({ order_sn: `SN${i}`, formula_sig: ลายเซ็นเก่า }));
  let คำสั่งนับ = null, พารามนับ = null;

  mock.module('../../netlify/lib/coredb.mjs', {
    namedExports: {
      coreReady: () => true,
      แถวจากผล: (r) => (Array.isArray(r) ? r : (r?.results ?? [])),
      coreQuery: async (sql, params = []) => {
        if (/COUNT\(\*\) AS n FROM shopee_orders o/.test(sql) && /formula_sig/.test(sql)) {
          คำสั่งนับ = sql; พารามนับ = params;
          /* 🔑 ฐานจำลองคิดคำตอบ **ตามเกณฑ์ที่ SQL ส่งมา** ไม่ใช่คืนเลขที่เราตั้งใจให้ได้
             ⇒ ถ้าตัวนับส่งลายเซ็นผิด/ไม่ส่งเลย เลขจะออกมาผิดเอง ไม่ใช่ผ่านเพราะเราใจดี */
          const สิ่งที่ถาม = params[params.length - 1];
          return [{ n: แถวในฐาน.filter((r) => r.formula_sig !== สิ่งที่ถาม).length }];
        }
        if (/SELECT o\.order_sn, o\.order_date FROM shopee_orders o/.test(sql)) return [];
        if (/COUNT\(\*\) AS n FROM shopee_orders WHERE/.test(sql)) return [{ n: 466 }];
        return [];
      },
    },
  });
  const { mirrorShopeeFees } = await import('../../netlify/lib/mkp-finance-mirror.mjs?สด=' + Date.now());
  const out = await mirrorShopeeFees({ days: 120, limit: 40, refresh: true });

  assert.ok(คำสั่งนับ, 'ตัวนับต้องถูกยิงจริง');
  assert.equal(พารามนับ[พารามนับ.length - 1], ลายเซ็นสูตร,
    'ตัวนับต้องถามด้วยลายเซ็น **ปัจจุบัน** ที่คิดจากซอร์ส ไม่ใช่ค่าที่เขียนตายตัว');
  assert.equal(out['ค้างก่อนรอบนี้'], 466,
    '🔑 แถวที่เก็บลายเซ็นรุ่นก่อนต้องถูกนับเป็นค้างทั้งหมด **โดยไม่มีใครไปแก้ตัวนับ**');
  assert.ok(String(out['ค้างก่อนรอบนี้นับอะไร']).includes(ลายเซ็นสูตร),
    'ป้ายต้องบอกลายเซ็นที่ใช้ตัดสิน ⇒ คนอ่านรู้ว่าเลขนี้เทียบกับอะไร');
  mock.reset();
});

