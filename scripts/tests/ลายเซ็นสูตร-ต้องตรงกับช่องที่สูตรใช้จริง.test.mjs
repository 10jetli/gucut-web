  const ตัวนับดิบ = /const left = refresh[\s\S]*?: await coreQuery\(/.exec(ซอร์ส)?.[0] ?? '';
  const ตัวนับ = ตัวนับดิบ.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');
