import { test } from "node:test";
import assert from "node:assert/strict";
import {
  แปลรายการสินค้า,
  ลายนิ้วมือรายการ,
  ต้องเขียนใหม่,
  ค่าitems_fp,
} from "../../netlify/lib/shopee-orders.mjs";

// ───────────────────────────── ② แปลรายการสินค้า ─────────────────────────────
test("อ่านรายการสินค้าปกติได้ และเลข 0 ต้องเป็น 0", () => {
  const items = แปลรายการสินค้า({
    item_list: [
      { model_sku: "NW-440", item_name: "เลื่อย 440", model_quantity_purchased: 2, model_discounted_price: 3500 },
      { item_sku: "BAR-22", item_name: "บาร์ 22", model_quantity_purchased: 0, model_discounted_price: 0 },
    ],
  });
  assert.equal(items.length, 2);
  assert.deepEqual(items[0], { line: 1, sku: "NW-440", name: "เลื่อย 440", qty: 2, price: 3500 });
  assert.equal(items[1].sku, "BAR-22", "ไม่มี model_sku ⇒ ถอยไป item_sku");
  assert.equal(items[1].qty, 0, "ซื้อ 0 ชิ้นเป็นค่าที่ถูกต้อง ห้ามแปลงเป็นอย่างอื่น");
});

test("🔑 ไม่มีช่อง item_list ⇒ null (ยังไม่รู้) ห้ามเป็น [] (รู้แล้วว่าไม่มี)", () => {
  for (const [ชื่อ, o] of [
    ["ไม่มีช่องเลย", { order_sn: "A1" }],
    ["เป็น null", { item_list: null }],
    ["เป็นออบเจกต์ไม่ใช่อาเรย์", { item_list: { 0: {} } }],
    ["เป็นสตริง", { item_list: "" }],
    ["ทั้งก้อนเป็น undefined", undefined],
  ]) {
    assert.equal(
      แปลรายการสินค้า(o), null,
      `${ชื่อ}: ต้องได้ null — ถ้าได้ [] คือเขียนลง D1 ว่าใบนี้ไม่มีสินค้า ทั้งที่ยังไม่รู้`
    );
  }
});

test("อาเรย์ว่างจริง ⇒ [] ไม่ใช่ null — สองอย่างนี้ต่างกัน", () => {
  assert.deepEqual(แปลรายการสินค้า({ item_list: [] }), [],
    "Shopee บอกชัดว่าไม่มีสินค้า = รู้แล้ว ห้ามเหมารวมกับอ่านไม่ได้");
});

// ──────────────────────────── ลายนิ้วมือรายการ ────────────────────────────
test("🔑 ลายนิ้วมือ: null เข้า ⇒ null ออก (ห้ามยุบเป็นสตริงว่าง)", () => {
  assert.equal(ลายนิ้วมือรายการ(null), null);
  assert.equal(ลายนิ้วมือรายการ(undefined), null);
  assert.equal(ลายนิ้วมือรายการ([]), "", "ไม่มีสินค้าจริง ⇒ สตริงว่าง ซึ่งเป็นค่าที่ 'รู้แล้ว'");
  assert.notEqual(
    ลายนิ้วมือรายการ(null), ลายนิ้วมือรายการ([]),
    "ยุบสองอย่างนี้เมื่อไหร่ ใบที่อ่านไม่ได้จะถูกถือว่า 'ไม่มีสินค้า' แล้วไปลบของจริงทิ้ง"
  );
});

test("ลายนิ้วมือเปลี่ยนเมื่อรายการเปลี่ยน (นี่คือเหตุที่คอลัมน์นี้มีอยู่)", () => {
  const a = ลายนิ้วมือรายการ([{ sku: "X", qty: 1, price: 10 }]);
  const b = ลายนิ้วมือรายการ([{ sku: "X", qty: 2, price: 10 }]);
  const c = ลายนิ้วมือรายการ([{ sku: "Y", qty: 1, price: 10 }]);
  assert.notEqual(a, b); assert.notEqual(a, c);
});

// ───────────────────────────── ③ ต้องเขียนใหม่ ─────────────────────────────
const ใบ = (x = {}) => ({ sn: "A1", status: "READY", amount: 100, buyer: "bob", day: "2026-10-12", fp: "X:1:10", ...x });
const แถวเดิม = (x = {}) => ({ status: "READY", amount: 100, buyer: "bob", order_date: "2026-10-12", items_fp: "X:1:10", ...x });

test("ไม่มีแถวเดิม ⇒ เขียน · ทุกอย่างเท่าเดิม ⇒ ไม่เขียน", () => {
  assert.equal(ต้องเขียนใหม่(undefined, ใบ()), true);
  assert.equal(ต้องเขียนใหม่(แถวเดิม(), ใบ()), false, "ไม่งั้นเขียนทุกใบทุกรอบ = เผาโควตาเขียนของ D1");
});

test("สี่ช่องเดิมเปลี่ยน ⇒ เขียน", () => {
  for (const [ชื่อ, p] of [
    ["สถานะ", แถวเดิม({ status: "SHIPPED" })],
    ["ยอดเงิน", แถวเดิม({ amount: 101 })],
    ["ผู้ซื้อ", แถวเดิม({ buyer: "alice" })],
    ["วัน", แถวเดิม({ order_date: "2026-10-11" })],
  ]) assert.equal(ต้องเขียนใหม่(p, ใบ()), true, ชื่อ);
});

test("🔑 ③ ลายนิ้วมือรายการต่าง ⇒ ต้องเขียนใหม่ (ท่าที่ฝาแฝด TikTok มีตั้งแต่ 6 ก.ย.)", () => {
  assert.equal(
    ต้องเขียนใหม่(แถวเดิม({ items_fp: "X:1:99" }), ใบ()), true,
    "สี่ช่องเดิมไม่ขยับ แต่รายการสินค้าต่าง — ถ้าไม่เขียน รายการที่แปลผิดจะแช่แข็งตลอดกาล"
  );
  assert.equal(
    ต้องเขียนใหม่(แถวเดิม({ items_fp: null }), ใบ()), true,
    "คอลัมน์ว่าง (ใบที่มีอยู่ก่อนเพิ่มคอลัมน์) ⇒ ต้องถูกกวาดย้อนหลังรอบแรก"
  );
});

test("🔑 ② ไม่รู้รายการสินค้า (fp=null) ⇒ **ห้าม**ถือว่าเปลี่ยน", () => {
  assert.equal(
    ต้องเขียนใหม่(แถวเดิม(), ใบ({ fp: null })), false,
    "ถ้าถือว่าเปลี่ยน ใบนี้จะเข้าขั้นที่ 4 ทุกรอบ ⇒ DELETE ของจริงแล้วใส่ความว่างแทน"
  );
  assert.equal(
    ต้องเขียนใหม่(แถวเดิม({ status: "SHIPPED" }), ใบ({ fp: null })), true,
    "แต่ของอื่นเปลี่ยนก็ยังต้องเขียนหัวใบ — ไม่รู้รายการสินค้าไม่ได้แปลว่าห้ามแตะทั้งใบ"
  );
});

// ───────────────────────────── ค่า items_fp ที่จะเขียน ─────────────────────────────
test("🔑 ② ไม่รู้รายการสินค้า ⇒ คงค่าเดิมไว้ ห้ามทับด้วยความว่าง", () => {
  assert.equal(ค่าitems_fp(ใบ({ fp: null }), แถวเดิม()), "'X:1:10'", "ต้องส่งค่าเดิมกลับ");
  assert.equal(ค่าitems_fp(ใบ({ fp: null }), undefined), "NULL", "ไม่มีค่าเดิม ⇒ NULL ไม่ใช่ ''");
  assert.equal(ค่าitems_fp(ใบ({ fp: null }), แถวเดิม({ items_fp: null })), "NULL");
  assert.notEqual(
    ค่าitems_fp(ใบ({ fp: null }), แถวเดิม()), "''",
    "ทับด้วย '' = ลืมว่าเคยรู้ แล้วรอบหน้าจะคิดว่ารายการสินค้าเปลี่ยน แล้วไปลบของจริง"
  );
});

test("รู้รายการสินค้า ⇒ เขียนค่าใหม่ · และค่าว่างที่ 'รู้แล้ว' เขียนเป็น '' ได้", () => {
  assert.equal(ค่าitems_fp(ใบ({ fp: "Y:2:20" }), แถวเดิม()), "'Y:2:20'");
  assert.equal(ค่าitems_fp(ใบ({ fp: "" }), แถวเดิม()), "''",
    "ใบที่ Shopee บอกว่าไม่มีสินค้าจริง ⇒ '' เป็นค่าที่ถูกต้อง (ต่างจากกรณีไม่รู้)");
});

test("ค่าที่มี ' ต้องถูก escape (ป้อนเข้า SQL ตรง ๆ)", () => {
  assert.equal(ค่าitems_fp(ใบ({ fp: "it's:1:10" }), undefined), "'it''s:1:10'");
});
