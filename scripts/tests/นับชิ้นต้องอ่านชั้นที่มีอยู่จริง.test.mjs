/* 🔴 ด่าน: **ตัวนับชิ้นของงานตามเวลา ต้องอ่านชั้นที่ก้อนผลลัพธ์มีอยู่จริง**
 *    (28 ก.ย. 2569 · ฝั่งจอจับได้จากตารางเวลางานบนของจริง)
 *
 * `backup-run` ส่ง `นับชิ้น: (x) => ({สำเร็จ: Number(x?.saved), ล้ม: Number(x?.failed)})`
 * แต่ `runBackup()` คืน `{ stores, totals: { saved, failed, … } }` — **ไม่มี `saved` ที่ระดับบนสุด**
 * ⇒ `Number(undefined)` = `NaN` ⇒ ตัวนับคืน `null` ⇒ **ท่อไม่เคยส่งจำนวนชิ้นของงานนี้เลย**
 *
 * 🔑 ทำไมมันรอดมาได้นาน: **ทางล้มของตัวนับถูกออกแบบให้เงียบ**
 *    `null` = "ท่อไม่ได้นับชิ้นให้งานนี้" ซึ่งเป็นคำตอบที่ถูกต้องในบางกรณีจริง ๆ
 *    ⇒ "อ่านคีย์ผิด" กับ "งานนี้ไม่มีอะไรให้นับ" **ให้ร่องรอยเดียวกันเป๊ะ**
 *    ⇒ และในไฟล์เดียวกัน `อธิบาย()` อ่าน `x.totals.saved` **ถูกอยู่แล้ว**
 *      ⇒ สองฟังก์ชันข้างกันอ่านคนละชั้นของก้อนเดียวกัน โดยอันที่ผิดคืออันที่ไม่มีใครตรวจ
 *
 * ⚠️ ด่านนี้ต้องไม่พึ่ง "ก้อนที่เราปั้นเอง" อย่างเดียว — ตัวปลอมที่เราปั้นจะตรงกับที่เราคิดอยู่แล้ว
 *    ⇒ จึง **อ่านรูปจริงจาก `backup.mjs`** มายืนยันก่อน แล้วค่อยเอาก้อนไปป้อนตัวนับ
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { ซอร์สไม่เอาคอมเมนต์, เลขบรรทัด, ปลูกในโค้ด } from "./_src.mjs";
import { ตัดคอมเมนต์ } from "../_strip-comments.mjs";
import { readFileSync } from "node:fs";

const Bไฟล์ = "netlify/lib/backup.mjs";
const Rไฟล์ = "netlify/functions/backup-run.mjs";
const B = ซอร์สไม่เอาคอมเมนต์(Bไฟล์);
const R = ซอร์สไม่เอาคอมเมนต์(Rไฟล์);
const Rดิบ = readFileSync(Rไฟล์, "utf8");

/** ยกฟังก์ชันลูกศรของคีย์ `<ชื่อ>:` ออกมาเป็นของที่เรียกได้จริง (นับปีกกา/วงเล็บ) */
function ยกฟังก์ชัน(ซอร์ส, ชื่อคีย์, ชื่อตัวแปรนอก = {}) {
  const i = ซอร์ส.indexOf(`${ชื่อคีย์}:`);
  assert.ok(i > 0, `ไม่เจอคีย์ ${ชื่อคีย์}`);
  const เริ่ม = ซอร์ส.indexOf("(", i);
  let ลึก = 0, j = เริ่ม;
  for (; j < ซอร์ส.length; j++) {
    const c = ซอร์ส[j];
    if (c === "(" || c === "{" || c === "[") ลึก++;
    else if (c === ")" || c === "}" || c === "]") { ลึก--; if (ลึก === 0 && ซอร์ส[j] === "}") break; }
  }
  const โค้ด = ซอร์ส.slice(เริ่ม, j + 1);
  const ชื่อ = Object.keys(ชื่อตัวแปรนอก);
  // eslint-disable-next-line no-new-func
  const f = new Function(...ชื่อ, `"use strict"; return (${โค้ด});`)(...ชื่อ.map((k) => ชื่อตัวแปรนอก[k]));
  return { f, บรรทัด: เลขบรรทัด(ซอร์ส, i) };
}

/* ══════════ ① รูปจริงที่ `runBackup()` คืน — อ่านจากซอร์ส ไม่ใช่จากความจำ ══════════ */

test("🔴 `runBackup()` ต้องคืน `totals` ที่มี `saved` และ `failed` อยู่ข้างใน", () => {
  const i = B.lastIndexOf("totals: {");
  assert.ok(i > 0, "ไม่เจอก้อน totals ใน backup.mjs — ตะแกรงพัง ไม่ใช่โค้ดเปลี่ยน");
  const ก้อน = B.slice(i, B.indexOf("\n    },", i));
  console.log(`   🔎 ${Bไฟล์}:${เลขบรรทัด(B, i)} ก้อน totals`);
  for (const k of ["saved:", "keys:", "failed:", "skippedKeys:", "left:"])
    assert.ok(ก้อน.includes(k), `ก้อน totals ขาด ${k}`);
  /* 🔑 และต้อง **ไม่มี** `saved` ที่ระดับบนสุดของก้อนที่คืน — นี่คือข้อที่ทำให้ตัวนับเดิมพัง
     ถ้าวันหนึ่งมีคนแบนรูปให้ saved ขึ้นมาอยู่ระดับบน ด่านนี้จะแดง ⇒ ไปแก้ตัวนับให้ตรง */
  const คืน = B.slice(B.lastIndexOf("return {", i), i);
  assert.ok(!/^\s+saved\s*:/m.test(คืน),
    "เจอ `saved` ที่ระดับบนสุดของก้อนที่คืน ⇒ รูปเปลี่ยน ต้องไปแก้ `นับชิ้น` ให้ตรงกัน");
});

/* ══════════ ② เรียกตัวนับจริง ด้วยก้อนที่มีรูปตามข้อ ① ══════════ */

const ก้อนจริง = {
  stores: [{ store: "gucut-orders", saved: 10, keys: 1147 }],
  totals: { saved: 10, keys: 1147, bytes: 1, failed: 0, skippedKeys: [], left: 0 },
  never: [],
};

test("🔴 `นับชิ้น` ต้องคืนตัวเลขจริง ไม่ใช่ `null` (ของเดิมคืน null ทุกรอบ)", () => {
  const { f, บรรทัด } = ยกฟังก์ชัน(R, "นับชิ้น");
  console.log(`   🔎 ${Rไฟล์}:${บรรทัด} ตัวนับชิ้น`);
  const r = f(ก้อนจริง);
  assert.notEqual(r, null,
    "คืน null กับก้อนที่มีข้อมูลครบ ⇒ อ่านผิดชั้น (นี่คือบั๊กเดิมเป๊ะ ๆ — จอขึ้นขีดตลอดกาล)");
  assert.deepEqual(r, { "สำเร็จ": 10, "ล้ม": 0 });
});

test("🔑 อ่านจำนวนไม่ได้ ⇒ ต้องคืน `null` ห้ามคืน `{0,0}`", () => {
  /* `{สำเร็จ:0, ล้ม:0}` อ่านบนจอว่า "สำรองสำเร็จ 0 ชิ้น" ซึ่งเป็นคำกล่าวอ้างที่เรายังพูดไม่ได้ */
  const { f } = ยกฟังก์ชัน(R, "นับชิ้น");
  assert.equal(f({}), null, "ไม่มี totals ⇒ null");
  assert.equal(f(undefined), null);
  assert.equal(f({ totals: { saved: "ขยะ", failed: 0 } }), null, "อ่านเป็นเลขไม่ได้ ⇒ null");
});

test("🔑 `saved: 0` ที่นับมาแล้วจริง ต้องผ่านเป็น 0 ไม่ถูกกลืนเป็น 'ไม่รู้'", () => {
  const { f } = ยกฟังก์ชัน(R, "นับชิ้น");
  assert.deepEqual(f({ totals: { saved: 0, failed: 0 } }), { "สำเร็จ": 0, "ล้ม": 0 },
    "0 ที่นับมาแล้วคือข้อมูลจริง — ต่างจาก null ที่แปลว่าอ่านไม่ได้");
});

/* ══════════ ③ คำว่า `failed` มีสองความหมาย — บันทึกต้องแยกให้คนอ่าน ══════════ */

test("🔴 ป้าย failed เพราะ **ข้ามคีย์** (ไม่มีถังพัง) ⇒ บันทึกต้องบอกเหตุ **ขึ้นต้นประโยค**", () => {
  const { f, บรรทัด } = ยกฟังก์ชัน(R, "อธิบาย", { "ข้ามได้โดยตั้งใจ": [] });
  console.log(`   🔎 ${Rไฟล์}:${บรรทัด} ตัวอธิบาย`);
  const note = f({
    stores: [{ store: "gucut-coupon", saved: 10 }],
    totals: { saved: 10, keys: 1147, left: 0, failed: 0, skippedKeys: ["gucut-coupon/botrules (900000 B)"] },
  });
  assert.match(String(note), /^⚠️/, `เหตุต้องอยู่ต้นประโยค · ได้: ${String(note).slice(0, 120)}`);
  assert.match(String(note), /ไม่มีถังไหนพัง/,
    "ต้องบอกตรง ๆ ว่าไม่มีถังพัง ไม่งั้นคนไปไล่หาถังที่พังซึ่งไม่มีอยู่");
  assert.match(String(note), /failed 0/, "ยังต้องมีเลขเดิมอยู่ให้ครบ");
});

test("🔑 รอบที่มีถังพังจริง ⇒ **ห้าม** ขึ้นคำนำหน้านั้น (ไม่งั้นกลายเป็นแก้ตัวให้ของที่พังจริง)", () => {
  const { f } = ยกฟังก์ชัน(R, "อธิบาย", { "ข้ามได้โดยตั้งใจ": [] });
  const note = f({
    stores: [{ store: "gucut-live", error: "D1 timeout" }],
    totals: { saved: 3, keys: 10, left: 0, failed: 1, skippedKeys: [] },
  });
  assert.ok(!String(note).startsWith("⚠️"),
    `มีถังพังจริงต้องไม่ขึ้นคำนำหน้า "ไม่มีถังไหนพัง" · ได้: ${String(note).slice(0, 120)}`);
  assert.match(String(note), /D1 timeout/, "ต้องบอกว่าถังไหนพังและเพราะอะไร");
});

test("🔑 รอบที่สะอาด (ไม่ข้าม ไม่พัง) ⇒ บันทึกต้องไม่มีคำเตือนเลย", () => {
  /* ตัวเตือนที่ร้องใส่ของปกติจะถูกปิดทิ้งใน 1 วัน */
  const { f } = ยกฟังก์ชัน(R, "อธิบาย", { "ข้ามได้โดยตั้งใจ": [] });
  const note = f({ stores: [], totals: { saved: 5, keys: 10, left: 0, failed: 0, skippedKeys: [] } });
  assert.ok(!String(note).includes("⚠️"), `รอบสะอาดต้องไม่มีคำเตือน · ได้: ${note}`);
  assert.ok(!String(note).includes("🚫"), "และไม่มีรายการคีย์ที่ถูกข้าม");
});

/* ══════════ ตัวควบคุมลบ — ปลูกบั๊กเดิมกลับ แล้ว **ผล** ต้องเปลี่ยน ══════════ */

test("🧪 ตัวควบคุม: ปลูกให้ `นับชิ้น` อ่านระดับบนสุดเหมือนเดิม ⇒ ต้องกลับไปคืน null", () => {
  const { ปลูก, บรรทัด } = ปลูกในโค้ด(
    Rดิบ,
    "      const ดี = Number(x?.totals?.saved), เสีย = Number(x?.totals?.failed);",
    "      const ดี = Number(x?.saved), เสีย = Number(x?.failed);",
    { ไฟล์: Rไฟล์ }
  );
  console.log(`   🌱 ปลูกบั๊กเดิมที่บรรทัด ${บรรทัด}`);
  const โค้ด = ตัดคอมเมนต์(ปลูก, Rไฟล์, { คงเลขบรรทัด: true });
  const { f } = ยกฟังก์ชัน(โค้ด, "นับชิ้น");
  assert.equal(f(ก้อนจริง), null,
    "ปลูกแล้วต้องคืน null กับก้อนที่มีข้อมูลครบ ⇒ เกณฑ์ข้างบนจะแดง");
  console.log("   📏 โค้ดที่ปลูกคืน null ⇒ จอขึ้นขีด (—) ตลอดกาล โดยไม่มีอะไรฟ้อง");
});

test("🧪 ตัวควบคุม: ถอดคำนำหน้าออก ⇒ เกณฑ์ข้อ ③ ต้องจับได้", () => {
  const { ปลูก, บรรทัด } = ปลูกในโค้ด(Rดิบ, "      return นำหน้า +", "      return \"\" +", { ไฟล์: Rไฟล์ });
  console.log(`   🌱 ถอดคำนำหน้าที่บรรทัด ${บรรทัด}`);
  const โค้ด = ตัดคอมเมนต์(ปลูก, Rไฟล์, { คงเลขบรรทัด: true });
  const { f } = ยกฟังก์ชัน(โค้ด, "อธิบาย", { "ข้ามได้โดยตั้งใจ": [] });
  const note = f({
    stores: [], totals: { saved: 10, keys: 1, left: 0, failed: 0, skippedKeys: ["a/b (9 B)"] },
  });
  assert.ok(!String(note).startsWith("⚠️"), "ปลูกแล้วคำนำหน้าต้องหาย ⇒ เกณฑ์ข้างบนจะแดง");
});
