// จับคู่ "รหัสอะไหล่ในคู่มือ" → "รหัสสินค้าในร้าน" — /api/parts-map (11 ต.ค. 2569)
//
// แผนผังอะไหล่ที่ /parts/ ดึงรหัสมาจากคู่มือ STIHL (เช่น 1123 020 1209)
// แต่รหัสสินค้าของร้านเป็นเลขลำดับ (00001, 04382) — **ไม่มีอะไรตรงกันเลยสักตัว**
// (ยิงเทียบจริง 11 ต.ค. 2569: 325 รหัสอะไหล่ F250 เทียบกับ 2,537 SKU ของร้าน = ตรง 0)
// ⇒ ต้องมีตารางจับคู่ที่ "คนกรอก" และเจ้าของร้านสั่งว่าจะกรอกเอง
//
//   GET  ?model=f250                      → { map: { "11230201209": "04382" } }  สาธารณะ
//   POST ?model=f250  { part, sku }       → จับคู่ทีละชิ้น (sku ว่าง = ลบคู่)
//   POST ?model=f250  { map: {...} }      → เขียนทับทั้งรุ่น (ใช้ตอนนำเข้าเป็นชุด)
//
// 🔑 ทำไมเก็บ "ทั้งรุ่นในคีย์เดียว" ทั้งที่กฎร้านบอกให้ใช้หนึ่งชิ้น-หนึ่งคีย์
//    กฎนั้นมีไว้กัน "คนเขียนพร้อมกันแล้วทับกัน" ซึ่งเกิดกับของที่ลูกค้าหลายคนยิง
//    ตารางนี้มีคนกรอกคนเดียว (เจ้าของร้าน) แต่ฝั่งอ่านคือลูกค้าทุกคน
//    ⇒ แลกเป็นอ่านเร็ว (คีย์เดียวจบ) ดีกว่าไล่ list คีย์ทุกครั้งที่มีคนเปิดหน้า
//    ⚠️ วันไหนมีคนกรอกพร้อมกันหลายคน ต้องเปลี่ยนเป็นหนึ่งชิ้น-หนึ่งคีย์ทันที
import { getStore } from "@netlify/blobs";
import { adminGate } from "../lib/admin-gate.mjs";

const store = () => getStore({ name: "gucut-coupon", consistency: "strong" });
const คีย์ = (model) => `parts-map/${model}`;

const json = (data, status = 200, cache = 0) =>
  new Response(JSON.stringify(data), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      /* 🔑 `Vary` ต้องมีทั้งสองทาง — ไม่ใช่เฉพาะทางที่แคช
         ถ้าใส่เฉพาะทางที่แคช ขอบจะเก็บคำตอบของคนอ่านไว้ใต้คีย์ที่ไม่สนใจหัวนี้
         แล้วเสิร์ฟให้คนเขียนได้ ⇒ คนเขียนเห็นของเก่าเหมือนเดิม (รูที่เรากำลังอุด) */
      vary: "x-admin-key",
      ...(cache
        ? {
            "Cache-Control": "public, max-age=30",
            "Netlify-CDN-Cache-Control": `public, s-maxage=${cache}`,
          }
        : { "cache-control": "no-store", "Netlify-CDN-Cache-Control": "no-store" }),
    },
  });

/** ชื่อรุ่นต้องเป็น slug สั้น ๆ เท่านั้น — กันคนยิงชื่อคีย์แปลก ๆ เข้ามา */
const ล้างรุ่น = (v) => String(v || "").toLowerCase().replace(/[^a-z0-9]/g, "").slice(0, 12);
/** รหัสอะไหล่เก็บแบบไม่มีช่องว่าง เพราะในคู่มือเว้นวรรคไม่เหมือนกันทุกที่ */
const ล้างรหัส = (v) => String(v || "").replace(/\s+/g, "").toUpperCase().slice(0, 24);
/** รหัสสินค้าของร้าน — ตัวอักษร/ตัวเลข/ขีด เท่านั้น */
const ล้างsku = (v) => String(v || "").trim().replace(/[^\w.-]/g, "").slice(0, 32);

export default async function handler(req, context) {
  const url = new URL(req.url);
  const model = ล้างรุ่น(url.searchParams.get("model"));
  if (!model) return json({ error: "ต้องระบุ model" }, 400);

  if (req.method === "GET") {
    /* 🔴 **เส้นเดียวที่มีทั้งคนเขียนและคนอ่าน ตั้งแคชเป็นค่าเดียวไม่ได้** (คุณส้มวัดเจอ 12 ต.ค. 2569)
       เดิมแคชที่ขอบ 60 วิ ⇒ ท่านประธานกรอกคู่ใหม่ (POST) แล้วจอ GET ซ้ำ **ได้ของเก่า**
       ⇒ หน้าจอบอกว่า "ยังไม่จับคู่" ทั้งที่เพิ่งบันทึกสำเร็จ
       🔑 และข้อที่แพงที่สุดคือ **คนกรอกจะโทษตัวเองว่าพิมพ์พลาด แล้วไม่มีใครรายงานบั๊กนี้เลย**
       ⇒ แยกตามบทบาท: มีรหัสหลังร้านมาด้วย = คนเขียน ⇒ ห้ามแคช · ไม่มีรหัส = ลูกค้า ⇒ แคชได้ 60 วิ
       ⚠️ ต้องมี `Vary: x-admin-key` ด้วย ไม่งั้นขอบเครือข่ายจะเอาคำตอบที่แคชไว้ให้คนอ่าน
          มาเสิร์ฟให้คนเขียนโดยไม่แตะฟังก์ชันเลย (no-store กันแค่ "ไม่เก็บของตัวเอง"
          ไม่ได้กัน "ของที่คนอื่นฝากไว้ก่อน") — อันนี้คือรูที่ตั้งใจอุดพร้อมกัน
       ⚠️ `cache-control: no-store` อย่างเดียวไม่พอ มันคุมเบราว์เซอร์ ไม่คุมขอบ
          ⇒ json() ของไฟล์นี้ส่ง `Netlify-CDN-Cache-Control` เฉพาะตอน cache > 0 ⇒ ส่ง 0 = ขอบไม่แคช */
    const คนเขียน = !!req.headers.get("x-admin-key");

    /* 🔴 และอ่านพลาดห้ามกลืนเป็น "ยังไม่จับคู่" — คอมเมนต์เดิมบอกว่าปลอดภัยเพราะ "หน้าร้านต้องยังเปิดได้"
       ซึ่งถูกเรื่องหน้าไม่ล่ม **แต่ผิดเรื่องความจริง**: จอจะเขียนว่า "ยังไม่ได้จับคู่" ให้ทุกแถว
       ⇒ ของที่ท่านกรอกไว้ 368 แถวหายจากสายตา และถ้าโดนแคช 60 วิ ก็หายพร้อมกันทุกคน
       ⇒ คลาสเดียวกับ clip-shop · office · points วันนี้: "ไม่รู้" ต้องไม่ถูกพูดเป็น "ไม่มี" */
    let raw;
    try { raw = await store().get(คีย์(model), { type: "json" }); }
    catch {
      return json({ model, อ่านไม่ได้: true,
        เหตุ: "อ่านตารางจับคู่ไม่ได้ชั่วคราว — ของที่จับคู่ไว้ยังอยู่ครบ ไม่ได้หาย" }, 503, 0);
    }
    return json({ model, map: raw && typeof raw === "object" ? raw : {} }, 200, คนเขียน ? 0 : 60);
  }

  if (req.method === "POST") {
    const gate = await adminGate(req, context);
    // ⚠️ adminGate คืน object ไม่ใช่ Response — เขียน `if (gate) return gate` ไม่ได้
    //    (เคยพลาดมาแล้ว 25 ส.ค. 2569 ทุกคำขอตอบ "unsupported value")
    if (gate.deny) return gate.deny;
    if (!gate.ok) return json({ error: "unauthorized" }, 401);

    let body;
    try {
      body = await req.json();
    } catch {
      return json({ error: "bad json" }, 400);
    }

    /* 🔴 **อันนี้ทำข้อมูลหาย และของที่หายเอาคืนไม่ได้** (แก้ 12 ต.ค. 2569)
       เดิม `.catch(() => null) || {}` แล้วท้ายฟังก์ชัน `setJSON` **เขียนทับทั้งรุ่น**
       ⇒ Blobs สะดุดตอนท่านประธานกรอกคู่ที่ 200 ⇒ ทั้งรุ่นเหลือ **คู่เดียว** แล้วตอบ `ok:true`
       ⇒ ตารางนี้ **พิมพ์ด้วยมือ ไม่มีสำเนาที่อื่น สร้างใหม่จากอะไรไม่ได้เลย**
          (รหัสคู่มือ STIHL ↔ รหัสร้าน ตรงกัน 0 ตัว — ดูหัวไฟล์ ⇒ ไม่มีสูตรคำนวณย้อน)
       ⇒ อ่านไม่ได้ = 503 ไม่เขียน · null = ยังไม่เคยจับคู่ ใช้ {} ได้
       🔑 คลาสเดียวกับ B01/B02/B04 ที่ปิดวันนี้ — ต่างกันที่ "ของที่หาย" ที่นี่เป็นแรงงานคน */
    let เดิม;
    try { เดิม = (await store().get(คีย์(model), { type: "json" })) || {}; }
    catch {
      return json({ error: "อ่านตารางจับคู่เดิมไม่ได้ชั่วคราว — **ยังไม่ได้บันทึก** ของเดิมอยู่ครบ ลองใหม่อีกครั้ง" }, 503);
    }
    let ใหม่;

    if (body && typeof body.map === "object" && body.map) {
      ใหม่ = {};
      for (const [k, v] of Object.entries(body.map).slice(0, 5000)) {
        const a = ล้างรหัส(k);
        const b = ล้างsku(v);
        if (a && b) ใหม่[a] = b;
      }
    } else {
      const part = ล้างรหัส(body?.part);
      if (!part) return json({ error: "ต้องระบุ part" }, 400);
      const sku = ล้างsku(body?.sku);
      ใหม่ = { ...เดิม };
      // sku ว่าง = ตั้งใจลบคู่นี้ทิ้ง — ไม่ใช่ความผิดพลาด
      if (sku) ใหม่[part] = sku;
      else delete ใหม่[part];
    }

    await store().setJSON(คีย์(model), ใหม่);
    /* 🔑 คืน `map` ทั้งก้อนกลับไปด้วย (คุณส้มขอ 12 ต.ค. 2569) — เหตุผลไม่ใช่เรื่องแคช
       แต่เพราะเดิม **จอต้องเชื่อค่าที่ตัวเองพิมพ์** ว่าบันทึกเป็นอะไร
       ⇒ กฎเดียวกับที่ท่อใช้กับ ZORT วันนี้: คืน "ค่าที่อ่านได้หลังเขียน" ไม่ใช่ "ค่าที่ส่งไป"
       ⚠️ แต่ `ใหม่` ที่คืนไปนี้คือ **ค่าที่เราเพิ่งเขียน ไม่ใช่ค่าที่อ่านกลับจาก Blobs**
          ⇒ ยังไม่ใช่การยืนยันเต็มรูป ⇒ ติดธง `อ่านกลับแล้ว: false` ไว้ตรง ๆ ห้ามให้จอเข้าใจผิด
          (จะทำให้เต็มรูปต้องอ่านซ้ำหลัง setJSON ซึ่งกินเวลาอีกรอบ — ยังไม่ทำ บอกไว้ให้รู้) */
    return json({ ok: true, model, จับคู่แล้ว: Object.keys(ใหม่).length,
      map: ใหม่, อ่านกลับแล้ว: false });
  }

  return json({ error: "method not allowed" }, 405);
}

export const config = { path: "/api/parts-map" };
