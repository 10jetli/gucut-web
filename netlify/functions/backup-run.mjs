// ⚠️ งานตั้งเวลาใส่ `path` ไม่ได้ ต้องมีแต่ `schedule` — ใส่ทั้งคู่แล้วจะไม่ถูกตั้งเวลาให้
// ⏱️ จดเวลาตัวเองลงสมุด job_run_log ทุกรอบ (19 ก.ย. 2569 · ใบ S1) — อ่านที่ /api/core?jobtiming=1
import { runBackup } from "../lib/backup.mjs";
import { วัดเวลางาน } from "../lib/job-timing.mjs";

export default async () => {
  /* ⚠️ `failed` ในสรุปคือ "ถังที่สำรองไม่ได้" ⇒ นับเป็นล้มของรอบนี้
     ⚠️ `left > 0` **ไม่ใช่ล้ม** — รอบนี้หมดงบเวลา 18 วิ แล้วรอบถัดไปเก็บต่อเองตามดีไซน์ */
  const t = await วัดเวลางาน("backup-run", () => runBackup(18000), {
    ตัดสินผล: (x) => (x?.totals?.failed ? "failed" : x?.totals ? "ok" : null),
    /* 🔴 **failed ต้องบอกว่า "ถังไหน และเพราะอะไร" ไม่ใช่แค่จำนวน** (แก้ 19 ก.ย. ค่ำ)
       ของจริงเมื่อ 19:40: สมุดจดว่า `failed 1` ⇒ รู้ว่ามีถังพัง **แต่ไม่รู้ว่าถังไหน**
       ⇒ ต้องไปเปิด `?backupstatus=1` เทียบเวลาเองทีละถัง และยังไม่ได้เหตุผลอยู่ดี
       🔑 คลาสเดิมของวันนี้: **เลขที่ไม่มีตัวตนกำกับ ใช้ลงมือต่อไม่ได้**
          (`runBackup` เก็บ `error` ของถังนั้นไว้แล้ว — ผมแค่ไม่ได้เอามาใส่ในสมุด) */
    /* 🆕 **นับชิ้น** — งานนี้สำรองหลายถัง ⇒ `outcome` ป้ายเดียวบอกคนละเรื่องกับความจริง
       ของจริง 20 ก.ย.: `saved 1 · failed 1` แต่ป้ายเป็น `failed` ⇒ **อ่านว่าไม่มีอะไรถูกสำรองเลย**
       🚫 คืน `null` เมื่ออ่านจำนวนไม่ได้ — **ห้ามคืน `{0,0}`** (จะขึ้นจอว่า "สำเร็จ 0 ชิ้น") */
    นับชิ้น: (x) => {
      const ดี = Number(x?.saved), เสีย = Number(x?.failed);
      return Number.isFinite(ดี) && Number.isFinite(เสีย) ? { "สำเร็จ": ดี, "ล้ม": เสีย } : null;
    },
    อธิบาย: (x) => {
      if (!x?.totals) return null;
      const พัง = (x.stores ?? []).filter((s) => s?.error).map((s) => `${s.store}: ${s.error}`);
      return `saved ${x.totals.saved} · keys ${x.totals.keys} · left ${x.totals.left} · failed ${x.totals.failed}` +
        (พัง.length ? ` · ถังที่พัง ⇒ ${พัง.join(" | ")}` : "");
    },
  });
  const r = t.ผลลัพธ์;
  console.log("backup:", JSON.stringify(r?.totals ?? r), "· จดเวลา:", t.จดเวลา, `· ${t.ms} ms`);
  return new Response("ok");
};

// ⚠️ วิ่ง **ทุก 6 ชั่วโมง** โดยตั้งใจ ไม่ใช่วันละครั้ง (ลดจากทุกชั่วโมง 18 ก.ย. 2569 · เหตุผลอยู่ท้ายไฟล์)
//    รอบที่หมดงบเวลาจะเหลือคีย์ค้างไว้ ⇒ ต้องมีรอบถัดไปมาเก็บต่อเองโดยไม่ต้องมีคนสั่ง
//    ถ้าตั้งวันละครั้ง ของที่ค้างจะรอถึงพรุ่งนี้ และถ้าค้างทุกวันก็ไม่มีวันครบสักที
//    รอบที่ไม่มีอะไรเปลี่ยนแทบไม่กินอะไรเลย เพราะข้ามด้วยลายนิ้วมือ (etag)
