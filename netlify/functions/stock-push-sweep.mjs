export default async function handler() {
  try {
    const { กวาดดันสต็อก } = await import("../lib/stock-push-sweep.mjs");
    /* ⚠️ **ต้อง await** — Netlify แช่แข็งฟังก์ชันทันทีที่ตอบเสร็จ
       งานที่ไม่ await ตายกลางทางแบบไม่มี error (กัดมาแล้ว 3 ครั้งในโครงการนี้) */
    const r = await กวาดดันสต็อก({ platform: "lazada" });
    console.log("[กวาดดันสต็อก]", JSON.stringify(r));
  } catch (e) {
    /* พังก็ต้องพังให้เห็น — เงียบไปเฉย ๆ คือสิ่งที่ระบบนี้สร้างมาเพื่อกำจัด */
    console.error("[กวาดดันสต็อก] ล้มเหลว:", e?.message || e);
  }
}

