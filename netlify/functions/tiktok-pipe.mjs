/* 🎬 `/api/tiktok-pipe` — กระจกของท่อกระจายคลิป (Facebook เพจ AJt8888 → TikTok @ajtcut_8)
 *
 * ใบสั่ง CEO 24 ต.ค. 2569 11:4x — จอ `/web/tiktok` ต้องมี "ปุ่มส่งคลิป + รายการที่ส่งไปแล้ว"
 * เพื่ออัดคลิปสาธิตให้ TikTok เห็นขอบเขต `video.upload` / `video.publish` ตอนยื่นรีวิว
 *
 * 🔴 **ท่อจริงไม่ได้อยู่ที่นี่** — อยู่บน g1 (`~/repost-fb-yt/ลงtiktok.py` + timer `tiktok-pipe`)
 *    g1 ไม่มีชื่อโดเมนสาธารณะและไม่ควรเปิดพอร์ตรับ ⇒ **จอห้ามยิงไปหา g1 ตรง ๆ**
 *    ⇒ ที่นี่เป็น "กล่องฝากของ" สองทาง: g1 ดันผลขึ้นมา · จอฝากคำขอไว้ให้ g1 มาหยิบ
 *
 *   GET  ?                 → ของสำหรับจอ: รายการที่ส่งไปแล้ว + คำขอรอบพิเศษที่ค้างอยู่
 *   GET  ?ธง=1             → ของสำหรับ g1: มีคำขอรอบพิเศษค้างไหม (ตัวเดียว เบา ๆ เรียกทุกนาทีได้)
 *   POST {ดัน:{…}}         → g1 ดันผลขึ้น (แทนที่ก้อนเดิมทั้งก้อน)
 *   POST {ขอรอบ:1}         → จอฝากคำขอ "ส่งรอบถัดไปเดี๋ยวนี้"
 *   POST {รับธง:"<เวลา>"}  → g1 เคลียร์ธงที่หยิบไปทำแล้ว **ด้วยโทเคนที่ตรงกันเท่านั้น**
 *
 * 🔒 ทุก method ต้องมี `x-admin-key` — นี่คือข้อมูลหลังบ้านของร้าน ไม่ใช่ของสาธารณะ
 *
 * ⚠️ **สามสถานะ ไม่ใช่สองสถานะ** (กฎ three-states-not-two)
 *    "g1 ยังไม่เคยดันอะไรขึ้นมา" ≠ "ดันแล้วแต่ยังไม่มีคลิปสักใบ" ≠ "อ่านคลังไม่ได้"
 *    ⇒ ตอบ `สถานะข้อมูล` ออกไปตรง ๆ · 🚫 **ห้ามตอบ 200 พร้อมรายการว่างตอนอ่านไม่ได้**
 *       (จอจะอ่านว่า "ยังไม่เคยส่งคลิปเลย" ซึ่งคนละเรื่องกับ "เราอ่านไม่ได้")
 *
 * ⚠️ **`สถานะตอนส่ง` กับ `สถานะล่าสุด` ต้องแยกกันคนละช่อง** — ของจริงที่วัดได้ 24 ต.ค. 2569:
 *    ไฟล์บันทึกของท่อจดไว้ว่า `PROCESSING_UPLOAD` (สถานะ ณ วินาทีที่อัปเสร็จ)
 *    แต่ถามสด ๆ ทีหลังได้ `SEND_TO_USER_INBOX` ⇒ **ค่าที่จดไว้เก่าเสมอโดยไม่มีอะไรฟ้อง**
 *    ⇒ ยุบสองช่องเป็นช่องเดียว = จอรายงานสถานะเมื่อหลายชั่วโมงก่อนเป็นสถานะตอนนี้
 *
 * 🚫 **ห้ามแปลสถานะเป็นคำว่า "สำเร็จ" ที่ชั้นนี้** — ท่อส่งค่าดิบของ TikTok ต่อตามที่ได้มา
 *    `SEND_TO_USER_INBOX` = ถึงกล่องร่างในแอปแล้ว **ไม่ใช่** ขึ้นหน้าโปรไฟล์แล้ว
 *    (ตอนนี้โพสต์ตรงยังถูกบล็อกด้วย `unaudited_client_can_only_post_to_private_accounts`)
 */
import { getStore } from "@netlify/blobs";
import { adminGate } from "../lib/admin-gate.mjs";

const store = () => getStore({ name: "gucut-coupon", consistency: "strong" });
const คีย์รายการ = "tiktok-pipe/รายการ";
const คีย์ขอรอบ = "tiktok-pipe/ขอรอบ";
const สูงสุดต่อก้อน = 500;

const json = (data, status = 200) =>
  new Response(JSON.stringify(data), {
    status,
    headers: {
      "content-type": "application/json; charset=utf-8",
      /* 🔒 ข้อมูลหลังบ้าน + ปุ่มสั่งงาน ⇒ ห้ามให้ขอบเครือข่ายหรือเบราว์เซอร์เก็บ
         (แคชไว้ = กดปุ่มแล้วเห็นรายการเก่า แล้วสรุปว่าปุ่มไม่ทำงาน) */
      "cache-control": "private, no-store",
    },
  });

const ข้อความ = (v, ยาว) => String(v ?? "").slice(0, ยาว);

/** เวลา ISO ที่เชื่อถือได้เท่านั้น — อ่านไม่ออกคืน null (ว่างดีกว่าเดา) */
const เวลาที่อ่านได้ = (v) => {
  const s = String(v ?? "");
  return s && !Number.isNaN(Date.parse(s)) ? s : null;
};

/** ตรวจรูปก้อนที่ g1 ดันขึ้นมา — คืน {ok, เหตุ, ค่า}
 *  🔴 **ก้อนผิดรูปต้องไม่ทับของเดิมที่ยังดี** (กฎ read-before-write-no-swallow)
 *     ⇒ ตรวจให้จบก่อนเขียน · ไม่ผ่าน = ตอบ 400 แล้วไม่แตะคลังเลยสักไบต์ */
function ตรวจก้อน(ดัน) {
  if (!ดัน || typeof ดัน !== "object") return { ok: false, เหตุ: "`ดัน` ต้องเป็นออบเจกต์" };
  const เมื่อ = เวลาที่อ่านได้(ดัน["เมื่อ"]);
  if (!เมื่อ) return { ok: false, เหตุ: "`เมื่อ` ต้องเป็นเวลา ISO ที่อ่านได้ (เวลาที่ g1 วัดของจริง)" };
  if (!Array.isArray(ดัน["รายการ"])) return { ok: false, เหตุ: "`รายการ` ต้องเป็นอาเรย์ (ไม่มีคลิปก็ส่งอาเรย์ว่าง)" };
  if (ดัน["รายการ"].length > สูงสุดต่อก้อน)
    return { ok: false, เหตุ: `รายการเกิน ${สูงสุดต่อก้อน} ใบต่อก้อน — ตัดมาส่งเป็นรอบ ๆ` };

  const รายการ = ดัน["รายการ"].map((v) => ({
    fbid: ข้อความ(v?.fbid, 40),
    ชื่อ: ข้อความ(v?.["ชื่อ"], 200),
    publish_id: ข้อความ(v?.publish_id, 120),
    /* 🔑 สองช่องนี้แยกกันโดยตั้งใจ — ดูคำเตือนหัวไฟล์ */
    สถานะตอนส่ง: ข้อความ(v?.["สถานะตอนส่ง"], 60),
    สถานะล่าสุด: v?.["สถานะล่าสุด"] == null ? null : ข้อความ(v["สถานะล่าสุด"], 60),
    /* ⚠️ ถามสดไม่ได้ (โทเคนหมด/เน็ตล่ม) ⇒ `สถานะล่าสุด: null` + `เหตุถามไม่ได้`
       **ห้ามเติมค่าตอนส่งมาแทน** ไม่งั้น "ของเก่า" จะใส่หน้ากากเป็น "ของสด" */
    เหตุถามไม่ได้: v?.["เหตุถามไม่ได้"] == null ? null : ข้อความ(v["เหตุถามไม่ได้"], 200),
    ถามเมื่อ: เวลาที่อ่านได้(v?.["ถามเมื่อ"]),
    ขึ้นบัญชีแล้ว: v?.["ขึ้นบัญชีแล้ว"] == null ? null : ข้อความ(v["ขึ้นบัญชีแล้ว"], 120),
    ทาง: ข้อความ(v?.["ทาง"], 40),
    ลิงก์fb: ข้อความ(v?.["ลิงก์fb"], 300),
  }));
  const ขาด = รายการ.findIndex((v) => !v.fbid || !v.publish_id);
  if (ขาด >= 0) return { ok: false, เหตุ: `รายการใบที่ ${ขาด + 1} ขาด fbid หรือ publish_id` };

  return {
    ok: true,
    ค่า: {
      เมื่อ,
      บัญชี: ข้อความ(ดัน["บัญชี"], 60) || null,
      โหมด: ข้อความ(ดัน["โหมด"], 40) || null,
      /* 🔑 เพดาน "กี่ใบต่อรอบ" ต้องมาจาก g1 **ห้ามให้จอพิมพ์เลขนี้ไว้เอง**
         ค่าจริงอยู่ที่ `อัปสูงสุดต่อรอบ` ใน ลงtiktok.py ⇒ ใครแก้ที่นั่น จอต้องเปลี่ยนตามเอง
         ⚠️ ไม่ใช่ตัวเลขที่อ่านได้ ⇒ null (จอจะไม่โชว์บรรทัดนั้น) **ห้ามใส่ค่าเริ่มต้นแทน** */
      เพดานต่อรอบ: Number.isFinite(Number(ดัน["เพดานต่อรอบ"])) && Number(ดัน["เพดานต่อรอบ"]) > 0
        ? Math.min(Math.floor(Number(ดัน["เพดานต่อรอบ"])), 1000)
        : null,
      รอบล่าสุด: ข้อความ(ดัน["รอบล่าสุด"], 400) || null,
      รายการ,
    },
  };
}

export default async function handler(req, context) {
  /* 🔒 ด่านเดียวกับหลังร้านทุกเส้น (กันเดารหัสรัว + เทียบเวลาเท่ากัน) */
  const gate = await adminGate(req, context);
  if (gate.deny) return gate.deny;
  if (!gate.ok) return json({ error: "unauthorized" }, 401);

  const url = new URL(req.url);

  if (req.method === "GET") {
    /* ── ของสำหรับ g1: ถามสั้น ๆ ว่ามีคำขอรอบพิเศษค้างไหม ──
       แยกเส้นออกมาเพราะตัวที่เรียกทุกนาทีไม่ควรต้องดึงรายการทั้งก้อนมาด้วย */
    if (url.searchParams.get("ธง") === "1") {
      let ธง;
      try { ธง = await store().get(คีย์ขอรอบ, { type: "json" }); }
      catch (e) {
        /* 🔴 อ่านธงไม่ได้ ⇒ **ห้ามตอบว่าไม่มีธง** — g1 จะข้ามคำขอของท่านประธานไปเงียบ ๆ */
        return json({ error: `อ่านธงจากคลังไม่ได้: ${String(e?.message || e).slice(0, 160)}` }, 503);
      }
      return json({ ok: true, ขอรอบ: ธง?.["ขอเมื่อ"] ? { ขอเมื่อ: ธง["ขอเมื่อ"] } : null,
                    เวลาเซิร์ฟเวอร์: new Date().toISOString() });
    }

    /* ── ของสำหรับจอ ── */
    let ก้อน, ธง;
    try {
      ก้อน = await store().get(คีย์รายการ, { type: "json" });
      ธง = await store().get(คีย์ขอรอบ, { type: "json" });
    } catch (e) {
      /* 🚫 ห้ามกลายเป็น "รายการว่าง" — ดูคำเตือนหัวไฟล์ */
      return json({ สถานะข้อมูล: "อ่านคลังไม่ได้",
                    error: `อ่านคลังไม่ได้: ${String(e?.message || e).slice(0, 160)}` }, 503);
    }

    if (!ก้อน || !Array.isArray(ก้อน["รายการ"])) {
      return json({
        สถานะข้อมูล: "ยังไม่เคยมีใครดัน",
        เหตุ: "g1 ยังไม่เคยดันผลขึ้นมาเลย — ยังไม่ทราบว่าเคยส่งคลิปไปกี่ใบ",
        รายการ: [],
        ขอรอบค้าง: ธง?.["ขอเมื่อ"] ?? null,
        เวลาเซิร์ฟเวอร์: new Date().toISOString(),
      });
    }
    return json({
      สถานะข้อมูล: "มีข้อมูล",
      ...ก้อน,
      ขอรอบค้าง: ธง?.["ขอเมื่อ"] ?? null,
      เวลาเซิร์ฟเวอร์: new Date().toISOString(),
    });
  }

  if (req.method !== "POST") return json({ error: "method not allowed" }, 405);

  let body;
  try { body = await req.json(); } catch { return json({ error: "bad json" }, 400); }

  /* ── ① g1 ดันผลขึ้นมา ── */
  if (body?.["ดัน"] !== undefined) {
    const ผล = ตรวจก้อน(body["ดัน"]);
    if (!ผล.ok) return json({ error: `ก้อนผิดรูป: ${ผล.เหตุ} — ไม่เขียนทับของเดิม` }, 400);
    const ก้อน = { ...ผล.ค่า, ดันเมื่อ: new Date().toISOString() };
    /* 🔑 `ดันเมื่อ` คือนาฬิกาของเซิร์ฟเวอร์ · `เมื่อ` คือนาฬิกาของ g1 — เก็บทั้งคู่
       เพราะถ้า g1 นาฬิกาเพี้ยน จอยังต้องบอกได้ว่า "ตัวดันหยุดไปนานแล้ว" */
    try { await store().setJSON(คีย์รายการ, ก้อน); }
    catch (e) { return json({ error: `เขียนคลังไม่สำเร็จ: ${String(e?.message || e).slice(0, 160)}` }, 503); }
    return json({ ok: true, รับไว้: ก้อน.รายการ.length, ดันเมื่อ: ก้อน.ดันเมื่อ });
  }

  /* ── ② จอขอรอบพิเศษ ── */
  if (body?.["ขอรอบ"]) {
    let เดิม;
    try { เดิม = await store().get(คีย์ขอรอบ, { type: "json" }); }
    catch (e) { return json({ error: `อ่านธงเดิมไม่ได้: ${String(e?.message || e).slice(0, 160)}` }, 503); }
    /* 🔴 มีธงค้างอยู่แล้ว ⇒ **ไม่เขียนเวลาใหม่ทับ** — ไม่งั้นอายุของคำขอจะถูกรีเซ็ตทุกครั้งที่กดซ้ำ
       แล้ว "ค้างมา 20 นาทีแล้วยังไม่มีใครมาหยิบ" จะไม่มีวันปรากฏบนจอ */
    if (เดิม?.["ขอเมื่อ"]) return json({ ok: true, ซ้ำ: true, ขอเมื่อ: เดิม["ขอเมื่อ"],
                                        บอก: "มีคำขอค้างอยู่แล้ว — g1 ยังไม่ได้มาหยิบไปทำ" });
    const ขอเมื่อ = new Date().toISOString();
    try { await store().setJSON(คีย์ขอรอบ, { ขอเมื่อ, โดย: "จอหลังร้าน" }); }
    catch (e) { return json({ error: `ตั้งธงไม่สำเร็จ: ${String(e?.message || e).slice(0, 160)}` }, 503); }
    return json({ ok: true, ซ้ำ: false, ขอเมื่อ,
                  บอก: "ฝากคำขอไว้แล้ว — g1 อ่านธงนี้ทุกนาที" });
  }

  /* ── ③ g1 เคลียร์ธงที่หยิบไปทำแล้ว ──
     🔑 **ลบด้วยโทเคน ไม่ใช่ลบล้าง** — ระหว่างที่ g1 กำลังส่งคลิปอยู่ (เป็นนาที)
        ท่านประธานกดปุ่มใหม่ได้ ⇒ ลบล้างจะกินคำขอใบใหม่ไปด้วยโดยไม่มีใครรู้
        ⇒ ลบเฉพาะเมื่อ `ขอเมื่อ` ตรงกับใบที่ g1 หยิบไป · ไม่ตรง = เก็บไว้ให้รอบหน้า */
  if (body?.["รับธง"] !== undefined) {
    const โทเคน = ข้อความ(body["รับธง"], 60);
    let เดิม;
    try { เดิม = await store().get(คีย์ขอรอบ, { type: "json" }); }
    catch (e) { return json({ error: `อ่านธงไม่ได้: ${String(e?.message || e).slice(0, 160)}` }, 503); }
    if (!เดิม?.["ขอเมื่อ"]) return json({ ok: true, ผล: "ไม่มีธง" });
    if (เดิม["ขอเมื่อ"] !== โทเคน)
      return json({ ok: true, ผล: "ธงเปลี่ยนแล้ว ไม่ลบ", ขอเมื่อ: เดิม["ขอเมื่อ"] });
    try { await store().delete(คีย์ขอรอบ); }
    catch (e) { return json({ error: `ลบธงไม่สำเร็จ: ${String(e?.message || e).slice(0, 160)}` }, 503); }
    return json({ ok: true, ผล: "ลบแล้ว", ขอเมื่อ: โทเคน });
  }

  return json({ error: "ไม่รู้จักคำสั่ง — รับ {ดัน} · {ขอรอบ} · {รับธง} เท่านั้น" }, 400);
}

