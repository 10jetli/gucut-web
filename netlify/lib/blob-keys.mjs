/* กติกาการอ่าน "รายชื่อคีย์" จาก Netlify Blobs — **ที่เดียว** ใช้ร่วมทุกที่ที่กวาดด้วย prefix
 *
 * 🔴 ที่มา: ใบ B24 (4 ต.ค. 2569) — รูปที่ลอกกันไว้หลายที่คือ
 *      `const { blobs } = await s.list({ prefix }).catch(() => ({ blobs: [] }))`
 *    ⇒ Blobs สะดุด ⇒ `blobs = []` ⇒ ลูปไม่วน ⇒ ผลลัพธ์ว่าง **และตัวนับก็ว่าง**
 *    ⇒ หน้าหลังร้านขึ้นว่า "ไม่มีงานทะเบียน" · ตัวตามเตือนไม่เตือนใครแล้วรายงานว่าปกติ
 *
 * 🔑 **"0 เพราะอ่านไม่ได้" กับ "0 เพราะไม่มีของ" ต้องแยกให้ขาด**
 *    และที่นี่อันตรายกว่าที่อื่น เพราะ "ยังไม่มีลูกค้าส่งใบมา" เป็นคำตอบที่
 *    **สมเหตุสมผลจริง ๆ ในหลายวัน** ⇒ ค่าที่ผิดจะกลมกลืนไปกับความจริง
 *
 * ⚠️ รวมกติกามาที่เดียว ⇒ ผิดที่นี่ = ผิดพร้อมกันทุกฝั่ง (parity-cant-see-shared-error)
 *    ⇒ ต้องมีเทสที่ปลูกของเสียเข้าตัวนี้ตรง ๆ ไม่พิสูจน์ผ่านผู้เรียก
 */

/** อ่านรายชื่อคีย์ตาม prefix — คืนอาร์เรย์ของคีย์ หรือ **โยน** เมื่ออ่านรายชื่อไม่ได้
 *  🚫 ห้ามใส่ `.catch()` รอบตัวนี้แล้วแทนด้วย `[]` — นั่นคือบั๊กเดิมในรูปใหม่
 */
export async function อ่านรายชื่อคีย์(s, prefix, ชื่องาน) {
  let out;
  try {
    out = await s.list({ prefix });
  } catch (e) {
    throw new Error(
      `[${ชื่องาน}] อ่านรายชื่อคีย์ (${prefix}) จาก Blobs ไม่ได้: ${String(e?.message || e).slice(0, 80)}`
      + " — ถือว่า **ไม่รู้** ห้ามอ่านว่าไม่มีของ",
    );
  }
  const blobs = out?.blobs;
  if (!Array.isArray(blobs)) {
    throw new Error(`[${ชื่องาน}] Blobs คืนรูปที่ไม่มีช่อง blobs (${prefix}) — ถือว่าไม่รู้`);
  }
  return blobs.map((b) => b?.key).filter((k) => typeof k === "string" && k);
}

/** อ่านทุกแถวตาม prefix — คืน `{ items, unreadable }`
 *
 *  🔑 **คืนเป็นออบเจกต์ ไม่ใช่อาร์เรย์ที่แปะ property**
 *     ของเดิมทำ `items.unreadable = n` ซึ่ง `JSON.stringify` **ทิ้ง property ของอาร์เรย์**
 *     ⇒ ตัวนับไม่เคยถึงจอ = ตัวนับที่ไม่มีใครเห็น (คลาสเดียวกับ `fieldWarning` ใน ad-stats)
 *  🔑 `unreadable` ต้องอยู่ในคำตอบ **แม้เป็น 0** — ไม่มีช่อง ≠ ไม่มีปัญหา
 *     ถ้าซ่อนตอนเป็น 0 จอจะแยก "ท่อรุ่นเก่าไม่ส่งมา" ออกจาก "อ่านได้ครบ" ไม่ได้
 */
export async function อ่านทุกแถว(s, prefix, ชื่องาน, { เรียง } = {}) {
  const คีย์ = await อ่านรายชื่อคีย์(s, prefix, ชื่องาน);
  const items = [];
  let unreadable = 0;
  for (const k of คีย์) {
    const rec = await s.get(k, { type: "json" }).catch(() => null);
    if (rec) items.push(rec);
    else unreadable++;
  }
  if (เรียง) items.sort(เรียง);
  return { items, unreadable };
}
