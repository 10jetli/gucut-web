import { getStore } from "@netlify/blobs";
import { วันไทยจากMs, วันไทยย้อน } from "./thaiday.mjs";

/* ⚠️ คนละถังกับ `gucut-coupon` ที่ตัวกันยิงรัวใช้ — ดูเหตุผลข้อ ① ข้างบน */
const ถัง = "gucut-live";

async function เขียน(ชื่อด่าน, เหตุ) {
  try {
    const s = getStore({ name: ถัง });
    const นาที = Math.floor(Date.now() / 60000);
    await s.setJSON(`gf/${วันไทยจากMs(Date.now())}/${ชื่อด่าน}/${นาที}`, {
      เหตุ: String(เหตุ ?? "").slice(0, 200),
      atUtc: new Date().toISOString(),
    });
  } catch {
    /* จดไม่ได้ก็ต้องไม่ทำให้คำขอของลูกค้าล้ม — ตัวนี้เป็นตัวสังเกตการณ์ ไม่ใช่ทางเดินหลัก
       (และถ้าทั้งสองถังล่มพร้อมกัน ก็ไม่มีที่ไหนให้จดอยู่ดี) */
  }
}

/** จดว่าด่านชื่อนี้อ่านที่เก็บไม่ได้รอบนี้
 *  ⚠️ ต้อง `await` หรือส่ง `context` มาให้ฝาก `waitUntil` — Netlify แช่แข็งฟังก์ชันทันทีที่ตอบเสร็จ
 *     ปล่อยลอย = ตายกลางทางแบบไม่มี error (กติกาเหล็กของ repo นี้) */
export async function จดด่านล่ม(ชื่อด่าน, เหตุ, context) {
  const งาน = เขียน(ชื่อด่าน, เหตุ);
  if (context?.waitUntil) context.waitUntil(งาน);
  else await งาน;
}

/** อ่านบันทึกของวันไทยที่ต้องการ (0 = วันนี้)
 *  @returns `{อ่านได้:true, วัน, นาทีที่ล่ม, ด่าน, ล่าสุด}` หรือ `{อ่านได้:false, เหตุ}`
 *  🔑 **แยกสามสถานะ**: อ่านได้+ไม่มีบันทึก = ด่านทำงานครบ · อ่านได้+มีบันทึก = ช่วงนั้นด่านหาย
 *     · อ่านไม่ได้ = **ยังไม่รู้** ห้ามรายงานเป็น "ไม่มีปัญหา" */
export async function อ่านด่านล่ม(ย้อนกี่วัน = 0) {
  const วัน = ย้อนกี่วัน === 0 ? วันไทยจากMs(Date.now()) : วันไทยย้อน(ย้อนกี่วัน);
  try {
    const s = getStore({ name: ถัง });
    const { blobs } = await s.list({ prefix: `gf/${วัน}/` });
    const รายการ = Array.isArray(blobs) ? blobs : [];
    const ด่าน = {};
    let ล่าสุด = 0;
    for (const b of รายการ) {
      /* คีย์: gf/<วันไทย>/<ชื่อด่าน>/<เลขนาที> */
      const ส่วน = String(b.key).split("/");
      const ชื่อ = ส่วน[2] || "(ไม่ทราบชื่อด่าน)";
      const นาที = Number(ส่วน[3]);
      ด่าน[ชื่อ] = (ด่าน[ชื่อ] ?? 0) + 1;
      if (Number.isFinite(นาที) && นาที > ล่าสุด) ล่าสุด = นาที;
    }
    return {
      อ่านได้: true,
      วัน,
      /* 🔑 ชื่อฟิลด์บอกหน่วยไว้ในตัว — "กี่นาทีที่ต่างกัน" ไม่ใช่ "กี่คำขอ"
         (หนึ่งนาทีอาจมีคำขอที่โดนผลกระทบหลายสิบ) */
      นาทีที่ล่ม: รายการ.length,
      ด่าน,
      ล่าสุดUtc: ล่าสุด ? new Date(ล่าสุด * 60000).toISOString() : null,
    };
  } catch (e) {
    return { อ่านได้: false, วัน, เหตุ: String(e?.message ?? e).slice(0, 160) };
  }
}
