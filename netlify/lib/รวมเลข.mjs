/** ค่าเดียว: คืนตัวเลข หรือ `null` เมื่อ **ยังไม่รู้** — ที่เดียวในระบบที่ตัดสินเรื่องนี้
 *  🔴 `String(v).trim()` สำคัญ: `Number(" ")` เป็น **0 และ finite** ⇒ ช่องว่างล้วนจะกลายเป็น
 *     "วัดได้ว่าศูนย์" ทั้งที่ไม่มีใครวัด (เจอของจริงใน `core-products.mjs` วันเดียวกัน) */
export function เลขหรือไม่รู้(v) {
  if (v === null || v === undefined) return null;
  if (typeof v === "boolean") return null;          // true/false ไม่ใช่จำนวน — กันการนับ true = 1
  if (String(v).trim() === "") return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
}

/**
 * รวมค่าจากแถว แล้วคืน **ผลรวมพร้อมความครบ**
 * @param {Array} แถว        รายการแถว (ไม่ใช่อาร์เรย์ ⇒ ถือว่า "อ่านไม่ได้" ไม่ใช่ว่าง)
 * @param {(r:any, i:number)=>any} เอาค่า  ดึงค่าที่จะรวมจากแถวหนึ่ง
 * @param {{ชื่อ?:string}} o  ชื่อของยอดนี้ สำหรับเขียนในคำเตือน
 */
export function รวมแถว(แถว, เอาค่า = (r) => r, { ชื่อ = "ยอดรวม" } = {}) {
  /* 🔴 **"อ่านแถวไม่ได้" ต้องไม่กลายเป็นยอด 0** — คลาสเดียวกับ `?? []` บนข้อมูลนอกบ้าน */
  if (!Array.isArray(แถว))
    return {
      ผลรวม: null, แถวทั้งหมด: null, นับได้: null, ไม่รู้ค่า: null, ครบ: null,
      "⚠️ อ่านยังไง":
        `${ชื่อ}: อ่านรายการแถวไม่ได้ (ได้ ${แถว === null ? "null" : typeof แถว}) ` +
        "⇒ **ยังไม่รู้ยอด** ไม่ใช่ยอดศูนย์",
    };

  let ผลรวม = 0;
  let นับได้ = 0;
  const ไม่รู้ = [];
  for (let i = 0; i < แถว.length; i += 1) {
    const n = เลขหรือไม่รู้(เอาค่า(แถว[i], i));
    if (n === null) { ไม่รู้.push(i); continue; }
    ผลรวม += n;
    นับได้ += 1;
  }

  /* 🔴 **ทุกแถวไม่รู้ค่า ⇒ ผลรวมเป็น null** — บวกของที่ไม่มีเลยแล้วได้ 0 คือการแต่งคำตอบขึ้นมา
     (แถว 0 แถวต่างกัน: ไม่มีอะไรให้รวมจริง ⇒ 0 ถูกแล้ว และ `แถวทั้งหมด: 0` บอกคนอ่านอยู่แล้ว) */
  const ว่างเปล่าทั้งกอง = แถว.length > 0 && นับได้ === 0;
  return {
    ผลรวม: ว่างเปล่าทั้งกอง ? null : ผลรวม,
    แถวทั้งหมด: แถว.length,
    นับได้,
    ไม่รู้ค่า: ไม่รู้.length,
    ครบ: ไม่รู้.length === 0,
    ...(ไม่รู้.length
      ? {
          "⚠️ ยอดนี้ไม่ครบ":
            `${ชื่อ}: รวมได้ ${นับได้} จาก ${แถว.length} แถว · **${ไม่รู้.length} แถวยังไม่รู้ค่า** ` +
            (ว่างเปล่าทั้งกอง
              ? "⇒ ไม่มีแถวไหนรู้ค่าเลย ⇒ ผลรวมเป็น null (ไม่ใช่ 0)"
              : "⇒ ยอดที่ได้เป็น **ยอดบางส่วน** ห้ามอ่านว่ายอดรวมทั้งหมด"),
          แถวที่ไม่รู้ค่า: ไม่รู้.slice(0, 20),   // ตำแหน่งแถว — ไล่ต่อได้ ไม่ต้องเดา
        }
      : {}),
  };
}

/** รวมหลายช่องจากแถวชุดเดียวกันในครั้งเดียว — คืน `{ <ช่อง>: ผลของ รวมแถว }`
 *  🔑 ใช้กับกองที่ต้องรายงานหลายยอด (จำนวน · เงิน · น้ำหนัก) ⇒ ความครบของแต่ละยอดแยกกัน
 *     เพราะแถวที่ไม่รู้ "น้ำหนัก" อาจรู้ "เงิน" ⇒ ยุบเป็นธงเดียวคือการทิ้งข้อมูล */
export function รวมหลายช่อง(แถว, ช่อง) {
  const ออก = {};
  for (const [ชื่อ, เอาค่า] of Object.entries(ช่อง)) ออก[ชื่อ] = รวมแถว(แถว, เอาค่า, { ชื่อ });
  return ออก;
}
