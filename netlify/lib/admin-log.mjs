/* 📓 สมุด "คำสั่งที่เปลี่ยนข้อมูล" ของหลังร้าน — `admin_action_log`
 *
 * 🔴 ที่มา 20 ก.ย. 2569 (ใบ S3 ของฝั่งจอ) — เขาไปอ่านสมุดของ ZORT มา 4 เล่ม แล้วพบว่า
 *    ZORT มี `Log (ผู้ใช้)` = `วันที่ · ผู้ใช้งาน · รายละเอียด` ⇒ วันที่ร้านถามว่า **"ใครแก้ใบนี้"**
 *    ZORT ตอบได้ · **ฝั่งเราตอบไม่ได้เลย**
 *
 * 🔑 **แต่เราลอกตรง ๆ ไม่ได้ และนี่คือเหตุผลที่ต้องอ่านก่อนแก้ไฟล์นี้**
 *    ฝั่งเรามี **กุญแจแอดมินดอกเดียวใช้ร่วมกันทุกคน** ⇒ ช่อง "ผู้ใช้งาน" จะ **ว่างตลอดกาล**
 *    ⇒ ⇒ คอลัมน์ที่ไม่มีวันมีค่า **แย่กว่าไม่มีคอลัมน์** เพราะทำให้คนเชื่อว่าระบบตอบคำถามนี้ได้
 *    ⇒ ขั้นนี้จึงจดเฉพาะสิ่งที่ **มีจริง**: เวลา · เส้นที่ถูกเรียก · วิธี · ref · ผล
 *    📌 ช่อง "ใครทำ" จะมีความหมายวันที่มี **กุญแจต่อคน** (เสนอท่านประธานแล้ว 20 ก.ย. 2569)
 *
 * 🚫 **ขอบเขตที่ต้องเขียนบนจอ ห้ามละ** (สองบรรทัด ไม่ใช่หนึ่ง — คนละเรื่องกัน)
 *    ① *"ยังไม่รู้ว่าใครทำ — ระบบมีกุญแจแอดมินดอกเดียว"* (ไม่ใช่ *ไม่มีใครทำ*)
 *    ② *"จดคำสั่งที่เข้าทาง API ของเรา **ไม่ครอบการแก้ที่ทำใน ZORT โดยตรง**"*
 *    ③ และเล่มนี้จด **เฉพาะคำขอที่ไม่ใช่ GET** — เส้น GET ที่สั่งซิงก์ (`?syncreturns=1` ฯลฯ)
 *       ถูกจดใน **สมุดเวลางาน** (`job_run_log` · `ผู้เรียก: "มือ"`) แทน
 *       ⇒ ⇒ ต้องอ่านสองเล่มคู่กันจึงเห็นครบ · **เล่มเดียวไม่ใช่ภาพรวม**
 *
 * ⚠️ จดล้ม **ห้ามลากคำสั่งจริงล้มตาม** (สมุดหายดีกว่าคำสั่งไม่ทำงาน) แต่ **ห้ามเงียบ**
 *    ⇒ คืนเหตุกลับไปให้ผู้เรียก log · และ **ต้อง `await`** (Netlify แช่แข็งฟังก์ชันหลังตอบ)
 */
import { coreQuery } from "./coredb.mjs";
/* 🔑 หน้าต่างเวลาใช้ตัวแปลตัวเดียวกับสมุดเวลางาน — ห้ามมีสองสูตร [[one-threshold-one-source]]
   ⚠️ **นำเข้าแบบ dynamic ในเส้นอ่านเท่านั้น** — ไฟล์นี้ถูก import ตรง ๆ จาก `core.mjs`
      ถ้าลาก `job-timing` (ซึ่งลาก `stock-push-sweep` ต่อ) มาที่หัวไฟล์
      **ทุกคำขอ GET จะจ่ายค่าโหลดสายนี้** ทั้งที่เส้นอ่านสมุดถูกเรียกนาน ๆ ครั้ง [[guard-after-the-cost]] */

export const ตารางคำสั่ง = "admin_action_log";

/** เก็บกี่วัน — **ต้องโชว์เลขนี้บนจอ** ไม่งั้นคนอ่านจะคิดว่าเห็นทั้งหมด [[numbers-need-scope]] */
export const เก็บกี่วัน = 90;

const DDL =
  `CREATE TABLE IF NOT EXISTS ${ตารางคำสั่ง} (
     at TEXT NOT NULL, endpoint TEXT NOT NULL, method TEXT NOT NULL,
     ref TEXT NOT NULL DEFAULT '', result TEXT, note TEXT,
     PRIMARY KEY (at, endpoint, ref))`;

const ยังไม่มีตาราง = /no such table/i;

/** 🧪 **ตัวตัดสินล้วน: คำขอนี้ต้องจดไหม** — ไม่แตะเครือข่าย ⇒ เทสเรียกได้ตรง ๆ
 *
 *  📏 เกณฑ์: **ไม่ใช่ GET/HEAD = เปลี่ยนข้อมูล** (ของเราไม่มี POST ที่เป็นการอ่าน)
 *  🚫 **ห้ามขยายเป็น "เดาจากชื่อพารามิเตอร์"** (เช่น /sync|push|del/) — นั่นคือการจัดประเภท
 *     ด้วยชื่อที่คนตั้งเอง ⇒ เส้นใหม่ที่ชื่อไม่เข้ารูปจะหายจากสมุด **เงียบ ๆ** [[no-substring-classification]]
 *     ⇒ เส้น GET ที่เขียนข้อมูลถูกจดในสมุดเวลางานแทน และเราประกาศขอบเขตนี้บนจอ
 */
export function ควรจด(req) {
  const m = String(req?.method || "").toUpperCase();
  return m !== "" && m !== "GET" && m !== "HEAD";
}

/** 🧪 ค่าที่จะถูกเขียนลงแถวจริง — ลำดับต้องตรงกับ VALUES เป๊ะ
 *  (แยกออกมาเพื่อให้ด่านอ่าน **ค่าที่เขียนจริง** ไม่ใช่สิ่งที่เราประกาศไว้ [[tautology-checks-are-always-green]]) */
export function แถวคำสั่ง({ เส้น, method, ref = "", ผล = null, note = null, เมื่อ = new Date() }) {
  return [
    เมื่อ.toISOString(),
    String(เส้น || "?").slice(0, 200),
    String(method || "?").toUpperCase().slice(0, 10),
    ref === null || ref === undefined ? "" : String(ref).slice(0, 120),
    ผล === null || ผล === undefined ? null : String(ผล).slice(0, 40),
    note ? String(note).slice(0, 300) : null,
  ];
}

/** ชื่อเส้นที่อ่านได้ — พารามิเตอร์ตัวแรกคือ "คำสั่ง" ตามสัญญาของ `/api/core`
 *  ⚠️ **เอาแค่ชื่อคำสั่ง ไม่เอาค่า** — ค่ามีเลขเอกสาร/รหัสลูกค้าได้ และสมุดนี้เปิดให้จอเห็น */
export function ชื่อเส้น(url) {
  try {
    const u = new URL(url);
    const คำสั่ง = [...u.searchParams.keys()].filter((k) => k !== "limit" && k !== "offset")[0];
    return คำสั่ง ? `${u.pathname}?${คำสั่ง}` : u.pathname;
  } catch { return "?"; }
}

/** จดหนึ่งแถว — คืน `"ok"` หรือข้อความเหตุ (ไม่โยน error ออกไปหาคำสั่งจริง) */
export async function จดคำสั่งแอดมิน({ เส้น, method, ref = "", ผล = null, note = null, เมื่อ = new Date() }) {
  const แถว = แถวคำสั่ง({ เส้น, method, ref, ผล, note, เมื่อ });
  const sql = `INSERT OR REPLACE INTO ${ตารางคำสั่ง} (at, endpoint, method, ref, result, note) VALUES (?, ?, ?, ?, ?, ?)`;
  try {
    await coreQuery(sql, แถว);
    return "ok";
  } catch (e) {
    const msg = String(e?.message ?? e);
    if (!ยังไม่มีตาราง.test(msg)) return `จดไม่ได้: ${msg.slice(0, 200)}`;
    try {
      await coreQuery(DDL);
      await coreQuery(sql, แถว);
      return "ok";
    } catch (e2) {
      return `จดไม่ได้ (สร้างตารางแล้วยังล้ม): ${String(e2?.message ?? e2).slice(0, 200)}`;
    }
  }
}

/** อ่านสมุด — **อ่านอย่างเดียว** · เก็บกวาดของเก่าตอนเปิดหน้า (กติกาเดียวกับตัวนับคนเข้าเว็บ)
 *  🔑 ไม่ตั้งงานตามเวลาเพิ่มเพื่อลบของเก่า — ของที่ไม่มีอะไรจุดชนวนจะไม่เกิดขึ้นจริง [[nothing-triggers-it]]
 *  ⚠️ ลบล้ม **ห้ามทำให้อ่านไม่ได้** ⇒ บอกออกไปว่าเก็บกวาดไม่สำเร็จ */
export async function อ่านคำสั่งแอดมิน({ ชั่วโมงย้อนหลัง, limit } = {}) {
  const { ตีความชั่วโมง } = await import("./job-timing.mjs");
  const { ชม, ปรับเพราะ } = ตีความชั่วโมง(ชั่วโมงย้อนหลัง);
  const เพดานแถว = Math.min(500, Math.max(1, Number.parseInt(limit ?? "100", 10) || 100));
  const ตั้งแต่ = new Date(Date.now() - ชม * 3600_000).toISOString();

  let แถว = null;
  let อ่านไม่ได้ = null;
  /* 🔢 **ต้องส่งยอดรวมมาด้วย ไม่ใช่แค่แถวที่ตัดแล้ว** (21 ก.ย. 2569)
     🔴 ของจริงฝั่งจอวันนี้: กล่อง `NegVsPush` คิดเลขสามตัวจากแถวที่ได้จาก `?pushstuck=1&limit=200`
        **โดยไม่อ่านยอดรวมที่เส้นนั้นส่งมาให้อยู่แล้ว** ⇒ วันที่แถวเกิน 200 เลขบนจอจะต่ำกว่าจริง
        **โดยไม่มีอะไรฟ้อง** ⇒ คลาส: เลขเพื่อการแสดงผลถูกเอาไปใช้ตัดสิน [[display-limits-cant-decide]]
     ⇒ เส้นนี้จึงส่งทั้ง **ยอดรวม** และ **ธงว่าเห็นครบไหม** (ฟิลด์ความหมายเดียว จอไม่ต้องคำนวณเอง) */
  let ทั้งหมด = null;
  try {
    const r = await coreQuery(
      `SELECT at, endpoint, method, ref, result, note FROM ${ตารางคำสั่ง}
       WHERE at >= ? ORDER BY at DESC LIMIT ?`, [ตั้งแต่, เพดานแถว]);
    แถว = Array.isArray(r?.results) ? r.results : Array.isArray(r) ? r : [];
    /* นับแยกคำขอ — ถ้านับไม่ได้ให้เป็น `null` (**ไม่รู้**) ห้ามเดาเท่ากับจำนวนแถวที่ส่ง */
    try {
      const c = await coreQuery(`SELECT COUNT(*) AS n FROM ${ตารางคำสั่ง} WHERE at >= ?`, [ตั้งแต่]);
      const แถวนับ = Array.isArray(c?.results) ? c.results : Array.isArray(c) ? c : [];
      const n = Number(แถวนับ[0]?.n);
      ทั้งหมด = Number.isFinite(n) ? n : null;
    } catch { ทั้งหมด = null; }
  } catch (e) {
    const msg = String(e?.message ?? e);
    /* ยังไม่มีตาราง = **ยังไม่มีคำสั่งไหนถูกจด** ไม่ใช่ "อ่านไม่ได้" ⇒ สามสถานะ */
    if (ยังไม่มีตาราง.test(msg)) แถว = [];
    else อ่านไม่ได้ = msg.slice(0, 200);
  }

  let เก็บกวาด = null;
  if (แถว) {
    const เก่ากว่า = new Date(Date.now() - เก็บกี่วัน * 86400_000).toISOString();
    try { await coreQuery(`DELETE FROM ${ตารางคำสั่ง} WHERE at < ?`, [เก่ากว่า]); เก็บกวาด = "ok"; }
    catch (e) { เก็บกวาด = `เก็บกวาดไม่สำเร็จ: ${String(e?.message ?? e).slice(0, 120)}`; }
  }

  return {
    ok: !อ่านไม่ได้,
    ...(อ่านไม่ได้ ? { อ่านสมุดไม่ได้: อ่านไม่ได้ } : {}),
    "ชั่วโมงย้อนหลัง": ชม,
    "⚠️ ค่า hours ถูกปรับ": ปรับเพราะ,
    "เพดานแถวที่ส่งกลับ": เพดานแถว,
    "แถวที่มี": แถว ? แถว.length : null,
    /* 🔢 ยอดรวมในช่วงเวลา (ไม่สนเพดานแถว) · `null` = **นับไม่ได้ ไม่ใช่ศูนย์** */
    "ทั้งหมดที่ตรงเงื่อนไข": ทั้งหมด,
    /* 🚦 ฟิลด์ความหมายเดียวให้จอใช้ตัดสิน — `null` = ยังไม่รู้ (ต้องเขียนบนจอว่า "ยังไม่รู้ว่าครบไหม")
       🚫 ห้ามให้จอคิดเองจาก `แถวที่มี < เพดาน` — วันที่ยอดรวมเท่าเพดานพอดีจะอ่านผิด */
    "เห็นครบทุกแถวไหม": แถว === null ? null : (ทั้งหมด === null ? null : แถว.length >= ทั้งหมด),
    "เก็บกี่วัน": เก็บกี่วัน,
    "เก็บกวาด": เก็บกวาด,
    "รายการ": แถว ?? null,
    "⚠️ ขอบเขต":
      "① **ยังไม่รู้ว่าใครทำ** — ระบบมีกุญแจแอดมินดอกเดียว ⇒ ไม่มีช่อง 'ผู้ใช้' " +
      "(ว่าง ≠ ไม่มีใครทำ) · " +
      "② จดคำสั่งที่เข้าทาง API ของเราเท่านั้น **ไม่ครอบการแก้ที่ทำใน ZORT โดยตรง** · " +
      `③ จดเฉพาะคำขอที่ไม่ใช่ GET — เส้น GET ที่สั่งซิงก์อยู่ในสมุดเวลางาน (?jobtiming=1 · ผู้เรียก "มือ") · ` +
      `④ เก็บ ${เก็บกี่วัน} วัน แล้วลบตอนมีคนเปิดหน้านี้ ⇒ ของเก่ากว่านั้นไม่ได้หาย "เพราะไม่มีคำสั่ง"`,
  };
}
