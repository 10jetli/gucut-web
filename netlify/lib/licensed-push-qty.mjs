/* 🔁 ทับจำนวนของ "ของในทะเบียน" ก่อนคิดแผนดันสต็อกไปมาร์เก็ตเพลส
 *
 * ท่านประธานสั่ง 5 ต.ค. 2569: **"ให้ตัวดันสต็อกอ่าน licensed-stock เหมือนหน้าร้าน"**
 *
 * 🔴 **อาการก่อนแก้ — วัดไว้แล้ว**
 *    หน้าร้านอ่านทะเบียน (`/api/stock` ⇒ `src:"licensed"`) แต่ **ตัวดันสต็อกอ่าน ZORT**
 *    ⇒ ZORT ให้ `0` กับ `−1` ⇒ มาร์เก็ตเพลส **ไม่เคยได้เลขจากทะเบียนเลย**
 *    ของจริง: `Bar NW 24-7800` ถูกข้ามติดกัน Shopee 1,765 · TikTok 1,710 · Lazada 530
 *    = **4,005 ครั้งใน 18 วัน** เพราะธง `negative` จากเลข −1 ของ ZORT
 *    ⇒ ไฟล์นี้แก้ที่ต้นเหตุ: ให้แผนใช้เลขทะเบียนสด เหมือนที่หน้าร้านใช้
 *
 * ⚠️ **สิ่งที่ไฟล์นี้ "ไม่" ทำ — อ่านให้ครบก่อนสรุปว่าของจะถูกยิง**
 *    ① **ไม่แตะด่าน ⑥ (reopen)** — ของทะเบียนบนแพลตฟอร์มเป็น 0 อยู่ทุกตัว
 *       ⇒ ทับแล้วทุกแถวกลายเป็น `reopen` (0 → 8/19/4…) ⇒ **ยังต้องมีคนยืนยันรายรหัส**
 *       🔑 **"แผนโชว์เลขถูก" ≠ "ของจะถูกยิง"** — สองอย่างนี้ห้ามเล่าปนกัน
 *    ② **ไม่แตะด่าน ⑧ (ใบค้างส่ง)** — รหัสในใบที่จ่ายแล้วแต่ส่งไม่ออกยังถูกกันเหมือนเดิม
 *    ③ **ไม่แตะราคาเลย** — ท่านสั่งว่า "ราคา gucut.com จะถูกกว่าเสมอ"
 *       ⇒ วันที่จะดันราคาด้วย ต้องเอาจาก**ไฟล์สินค้า** ไม่ใช่ช่อง `p` ของ ZORT
 *         (16" ZORT บอก 1,600 แต่หน้าร้านขาย 2,000 ⇒ ดันเลข ZORT = ขายถูกกว่าตัวเอง 400)
 */
import { ทะเบียนเหลือทุกกลุ่ม, ทะเบียนเหลือของรหัส, รหัสเป็นกลุ่มทะเบียน } from "./core-registry.mjs";

/** รหัสนี้เป็นของในทะเบียนไหม — ถามจากตารางจับคู่ **ไม่เดาจากชื่อ** */
export const เป็นของทะเบียน = (sku) => Boolean(รหัสเป็นกลุ่มทะเบียน[String(sku ?? "").trim()]);

/**
 * ทับ `coreQty` ของแถวที่เป็นของทะเบียน ด้วยจำนวนสดจากทะเบียน
 *
 * 🔴 **อ่านทะเบียนไม่ได้ ⇒ ถอดแถวทะเบียนออกจากแผนทั้งหมด ห้ามถอยไปใช้เลข ZORT**
 *    ZORT ให้ `0`/`−1` กับของกลุ่มนี้ ⇒ ถ้าปล่อยให้ `0` หลุดเข้าแผน วันหนึ่งที่มีคนส่ง
 *    `allowClose:true` มันจะ **ปิดขายของที่มีจริงบนชั้น** · ทิศลงผิดเสียยอดทันที
 * 🚫 **ไม่ยืม `known:false` มาใช้** — ช่องนั้นมีความหมายอยู่แล้วว่า
 *    "แพลตฟอร์มมีรหัสที่คลังไม่รู้จัก" · เอามาใช้ซ้ำจะทำให้สองเรื่องปนกันในกองเดียว
 *    แล้วคนอ่าน `skipUnknown` จะแยกไม่ออกว่าต้องไปแก้ที่ไหน
 *
 * @param {Array} rows แถวที่จะส่งให้ `planFrom` — [{ sku, name, platformQty, coreQty, … }]
 * @returns {Promise<{rows: Array, licensedApplied: number, licensedDropped: Array, licensedReadError: string|null}>}
 */
export async function ทับจำนวนด้วยทะเบียน(rows = [], o = {}) {
  /* 🔑 **ฉีดตัวอ่านเข้ามาได้ เพื่อให้เทสเดินผ่านโค้ดจริง**
     รุ่นแรกของเทสข้อ "ต้องประกาศที่มาของเลข" **เป็นเขียวลวง** — จับได้ด้วยการปลูก (5 ต.ค. 2569)
     เพราะมันสร้างแถว `coreFrom: "licensed"` ขึ้นมาเองแล้วตรวจแถวของตัวเอง
     ⇒ ถอด `coreFrom` ออกจากฟังก์ชันจริง **เทสยังเขียว** = ด่านที่ไม่มีคม
     ⇒ ต้องให้เทสเรียกฟังก์ชันนี้จริงแล้วดูของที่มันผลิต (กฎ test-must-hit-the-path) */
  const อ่านกลุ่ม = o.อ่านกลุ่ม || ทะเบียนเหลือทุกกลุ่ม;
  const อ่านรายรหัส = o.อ่านรายรหัส || ทะเบียนเหลือของรหัส;
  const แถวทะเบียน = rows.filter((r) => เป็นของทะเบียน(r?.sku));
  if (!แถวทะเบียน.length) {
    return { rows, licensedApplied: 0, licensedDropped: [], licensedNotInWarehouse: [], licensedReadError: null };
  }
  let กลุ่มที่เหลือ;
  try {
    กลุ่มที่เหลือ = await อ่านกลุ่ม();
  } catch (e) {
    const เหตุ = `อ่านทะเบียนสดไม่ได้: ${e?.message || e}`;
    return {
      /* ถอดออกจากแผน ไม่ใช่ปล่อยให้ใช้เลข ZORT */
      rows: rows.filter((r) => !เป็นของทะเบียน(r?.sku)),
      licensedApplied: 0,
      licensedDropped: แถวทะเบียน.map((r) => ({ sku: r.sku, platformQty: r.platformQty, เหตุ })),
      licensedNotInWarehouse: [],
      licensedReadError: เหตุ,
    };
  }
  const ออก = [];
  const ตก = [];
  const คลังไม่รู้จัก = [];
  let ทับแล้ว = 0;
  for (const r of rows) {
    if (!เป็นของทะเบียน(r?.sku)) { ออก.push(r); continue; }
    try {
      const n = await อ่านรายรหัส(r.sku, { กลุ่มที่เหลือ });
      if (typeof n !== "number") {
        /* ไม่ควรเกิด (ผ่าน `เป็นของทะเบียน` มาแล้ว) — แต่ถ้าเกิด **ห้ามเดา** */
        ตก.push({ sku: r.sku, platformQty: r.platformQty, เหตุ: "ตารางจับคู่บอกว่าเป็นของทะเบียน แต่หาจำนวนไม่ได้" });
        continue;
      }
      /* 🔴 **แถว `known:false` ทับไปก็ถูกทิ้ง และตัวนับจะโกหก** (คุณ CEO จับได้ 5 ต.ค. 2569
         รันของจริงได้ `licensedApplied: 1` แต่ `wouldPush: 0`)
         `planFrom` ตีตก `!r.known` **ก่อนดู `coreQty`** ⇒ ทับแล้วไม่มีผล แต่ถูกนับว่าสำเร็จ
         ⇒ ตัวนับที่นับความสำเร็จของสิ่งที่ถูกทิ้ง = ข่าวดีปลอม

         🚫 **ไม่ยก `known` เป็น true ให้เอง** — `known` หมายถึง "คลังของเรารู้จักรหัสนี้"
            เป็นช่องของตัวเทียบ ไม่ใช่ของไฟล์นี้ ⇒ เปลี่ยนความหมายจะกระทบคนอ่าน `skipUnknown` ทั้งหมด
            (รอบแรกผมเขียนให้ยก `known` ตามจดหมายที่บอกว่าเลื่อย 4 รุ่นมาในกองนี้
             แต่คุณ CEO แก้จดหมายเองว่า **ข้อนั้นผิด** เขาปน ZORT กับคลัง D1
             ผมยิงวัดเองยืนยัน: `skipUnknown` ของทั้งสามเจ้า **ไม่มีรหัสทะเบียนเลยสักตัว**)
         ⇒ จึง **ไม่ทับ ไม่นับ** แต่ **ต้องมีชื่ออยู่ในกองที่มองเห็น**
            เพราะวันที่คลังหลุดรหัสทะเบียนไปจริง คำสั่งท่านประธานจะไม่มีผลกับรหัสนั้น **และจะเงียบ** */
      if (!r.known) {
        คลังไม่รู้จัก.push({ sku: r.sku, platformQty: r.platformQty ?? null, ทะเบียน: n,
          เหตุ: "ทะเบียนบอกจำนวนได้ แต่คลังเราไม่รู้จักรหัสนี้ (known:false) ⇒ ตัวคิดแผนตีตกก่อนดูจำนวน ⇒ ไม่ทับ ไม่นับ" });
        ออก.push(r);
        continue;
      }
      /* 🔑 **ทุกแถวที่ถูกทับต้องประกาศที่มาของเลข** — ไม่งั้นวันที่เลขต่างจาก ZORT
         จะไม่มีใครตอบได้ว่ามันมาจากไหน (กฎเดียวกับ `src` ของ `/api/stock`) */
      ออก.push({ ...r, coreQty: n, coreFrom: "licensed", coreQtyZort: r.coreQty });
      ทับแล้ว += 1;
    } catch (e) {
      ตก.push({ sku: r.sku, platformQty: r.platformQty, เหตุ: `อ่านจำนวนรายรหัสไม่ได้: ${e?.message || e}` });
    }
  }
  /* `licensedApplied` ต้องนับ **แถวที่เข้าแผนจริง** เท่านั้น — ไม่ใช่จำนวนครั้งที่เราพยายามทับ */
  return { rows: ออก, licensedApplied: ทับแล้ว, licensedDropped: ตก,
           licensedNotInWarehouse: คลังไม่รู้จัก, licensedReadError: null };
}

/** รายชื่อรหัสทะเบียนทั้งหมด — ส่งเป็น `alsoList` ให้ตัวเทียบ เพื่อขอรายชื่อรหัสที่ตกกอง `same` */
export const รหัสทะเบียนทั้งหมด = () => Object.keys(รหัสเป็นกลุ่มทะเบียน);

/**
 * แปลงแถวจากกอง `same` ของตัวเทียบ ให้เข้า `rows` ของ `planFrom` ได้
 *
 * 🔴 **เหตุที่ต้องมี** (วัดบน production 6 ต.ค. 2569 00:05)
 *    แถวที่ส่งเข้า `planFrom` มาจาก `c.diff` = รหัสที่ **แพลตฟอร์มกับคลังไม่ตรงกัน**
 *    ⇒ รหัสทะเบียนที่แพลตฟอร์ม 0 และ ZORT ก็ 0 ถูกจัดเป็น `same` **ก่อนตัวทับจะได้เห็น**
 *    ⇒ `licensedApplied` ได้แค่ 2/1/1 จาก 30 รหัส · 28 รหัสไม่เคยเข้าแผนเลย
 *    🔑 **ตัวกรองที่อยู่ก่อนตัวแก้ ทำให้ตัวแก้ไม่มีของให้แก้**
 *
 * 🔴 **แถวที่จับคู่แบบเดา (`exact: false`) ห้ามเข้า `rows`** (คุณ CEO กำกับ 6 ต.ค. 2569)
 *    Lazada จับคู่บางรหัสด้วยการ **ตัดท้ายรหัส** ⇒ เป็นการเดาว่าเป็นสินค้าตัวเดียวกัน
 *    พอเข้า `rows` แล้ว `planFrom` จะมองเหมือนแถวปกติ ⇒ กลายเป็น `reopen` ที่พร้อมถูกยิง
 *    **เหมือนแถวที่เชื่อได้** ⇒ ความรู้ว่า "ตัวนี้เดา" หายที่รอยต่อ
 *    🔑 รูปเดียวกับที่ `coreFrom` หายที่ขาออกของ `planFrom` — ของที่รู้ต้นทางแล้วไม่ถูกส่งต่อ
 *
 * @param {Array} sameListed แถวจาก `c.sameListed` ของตัวเทียบ
 * @param {"shopee"|"lazada"|"tiktok"} ช่องแพลตฟอร์ม ชื่อช่องที่เก็บจำนวนฝั่งแพลตฟอร์ม
 */
export function แถวจากกองเท่ากัน(sameListed, ช่องแพลตฟอร์ม) {
  const rows = [];
  const เดา = [];
  for (const r of sameListed || []) {
    /* `exact === false` เท่านั้นที่เป็นการเดา — Shopee/TikTok ไม่มีช่องนี้ (จับคู่ตรงตัวอยู่แล้ว)
       ⚠️ เช็ค `=== false` ห้ามใช้ `!r.exact` เพราะ `undefined` จะกลายเป็น "เดา" ทั้งสองเจ้า */
    if (r.exact === false) {
      เดา.push({ sku: r.sku, platformQty: r[ช่องแพลตฟอร์ม] ?? null, matchedAs: r.matchedAs ?? null,
        เหตุ: "ตัวเทียบจับคู่ด้วยการตัดท้ายรหัส = เดาว่าเป็นสินค้าตัวเดียวกัน ⇒ ไม่เข้าแผน ต้องมีคนยืนยันก่อน" });
      continue;
    }
    /* 🔴 **`Number(null)` คือ `0` และ `Number("")` ก็ `0`** ⇒ `isFinite` ผ่านทั้งคู่
       ⇒ เขียนแค่ `Number.isFinite(Number(x))` จะ **เดาว่า 0** กับค่าที่แปลว่า "ไม่รู้"
       ⇒ แถวนั้นจะเข้าแผนเป็น `reopen 0 → N` ทั้งที่ไม่เคยรู้ว่าฝั่งแพลตฟอร์มเป็น 0 จริง
       🔑 คลาสเดียวกับ `Number(x) || 0` ที่ด่าน `check-num-helpers` จับได้เมื่อคืน
          แค่เปลี่ยนหน้า ⇒ ต้องปฏิเสธค่าว่างออกมาก่อน **แล้วค่อย** แปลงเป็นเลข
       (เทสของผมเองจับได้ — รุ่นแรกของบรรทัดนี้ปล่อย null ผ่าน) */
    const ดิบ = r[ช่องแพลตฟอร์ม];
    const n = ดิบ === null || ดิบ === undefined || ดิบ === "" ? NaN : Number(ดิบ);
    if (!Number.isFinite(n)) {
      /* ไม่รู้เลขฝั่งแพลตฟอร์ม ⇒ ไม่เดาว่า 0 (เลข 0 จะทำให้กลายเป็น reopen ทั้งที่ไม่เคยรู้) */
      เดา.push({ sku: r.sku, platformQty: r[ช่องแพลตฟอร์ม] ?? null, matchedAs: null,
        เหตุ: `อ่านจำนวนฝั่งแพลตฟอร์มไม่ได้ (ช่อง ${ช่องแพลตฟอร์ม}) ⇒ ไม่เดาว่า 0` });
      continue;
    }
    rows.push({ sku: r.sku, name: r.name ?? "", platformQty: n, coreQty: r.core,
                directQty: r.directQty ?? null, known: true, มาจากกองเท่ากัน: true });
  }
  return { rows, เดา };
}
