/** อ่านรายการหนึ่งหน้าจาก ZORT — คืนอาร์เรย์ หรือ **โยน** เมื่อผลแปลไม่ได้
 *
 *  @param url      ที่อยู่เต็มของหน้านั้น
 *  @param headers  หัวยืนยันตัวของร้าน
 *  @param หน้า      เลขหน้า (ใช้แยกเคส "หน้าแรกไม่มีช่อง list")
 *  @param ชื่อ      ชื่องานสำหรับข้อความผิดพลาด
 *  @param timeout  มิลลิวินาที
 *  @returns {Promise<any[]>} รายการของหน้านั้น (ว่างได้)
 *
 *  ⚠️ **หน้าแรกที่ไม่มีช่อง `list` ถือว่า "ไม่มีรายการ" ไม่ใช่ความผิดพลาด**
 *     ยังไม่เคยยิง ZORT ตอนช่วงที่ไม่มีข้อมูลเพื่อดูว่าคืน `{list:[]}` หรือ `{}`
 *     (เครื่องที่แก้ไม่มีรหัส ZORT ⇒ **วัดไม่ได้ตอนเขียน**) ⇒ ไม่ตั้งด่านบนรูปที่เดาเอา
 *     เพราะเดาผิด = แดงลวงทุกวันที่ไม่มีข้อมูล แล้วคนจะปิดด่าน
 *  ⚠️ **หน้าที่ 2 ขึ้นไปที่ไม่มีช่อง `list` เป็นไปไม่ได้ถ้าปกติ** — มาถึงหน้านี้ได้
 *     เพราะหน้าก่อนเต็มพอดี ⇒ ปลายทางต้องมีช่อง `list` ให้เสมอ (ว่างได้ แต่ต้องมีช่อง)
 *  📌 วันที่มีรหัส ZORT ให้ยิงช่วงที่ไม่มีข้อมูลหนึ่งครั้ง แล้วรัดด่านหน้าแรกเพิ่ม
 */
export async function อ่านหน้าZort(url, headers, { หน้า, ชื่อ, timeout = 15000 }) {
  const res = await fetch(url, { headers, signal: AbortSignal.timeout(timeout) }).catch(() => null);
  if (!res) throw new Error(`[${ชื่อ}] ถามหน้า ${หน้า} ไม่ถึง ZORT (เน็ตหรือหมดเวลา) — ห้ามนับว่าหมดหน้า`);
  if (!res.ok) throw new Error(`[${ชื่อ}] หน้า ${หน้า} ZORT ตอบ ${res.status} — ห้ามนับว่าหมดหน้า`);
  let d;
  try {
    d = await res.json();
  } catch {
    throw new Error(`[${ชื่อ}] หน้า ${หน้า} ตอบ 200 แต่อ่าน JSON ไม่ได้ — ถือว่า **ไม่รู้** ห้ามนับว่าหมดหน้า`);
  }
  if (!Array.isArray(d?.list)) {
    if (หน้า > 1) {
      throw new Error(
        `[${ชื่อ}] หน้า ${หน้า} ไม่มีช่อง list กลางการไล่หน้า (หน้าก่อนเต็มพอดี)`
        + " — ถือว่าอ่านไม่ครบ ห้ามใช้ของบางส่วน",
      );
    }
    return [];
  }
  return d.list;
}

/** ตรวจตอนออกจากลูป: ออกเพราะ "หมดจริง" หรือ "ชนเพดานของเราเอง"
 *
 *  🔑 **เพดานที่เราตั้งเอง ห้ามกลายเป็นคำตอบเรื่องจำนวนข้อมูลของคนอื่น**
 *     ไม่เจอหน้าสั้นเลย = ยังมีของต่อ ⇒ ของที่ได้ไม่ครบ ⇒ ต้องบอก ไม่ใช่เขียนว่าสำเร็จ
 */
export function ตรวจชนเพดาน({ ถึงหน้าสุดท้ายจริง, เพดานหน้า, ต่อหน้า, ชื่อ, ช่วง = "" }) {
  if (ถึงหน้าสุดท้ายจริง) return null;
  return new Error(
    `[${ชื่อ}] ไล่ครบเพดาน ${เพดานหน้า} หน้า (${เพดานหน้า * ต่อหน้า} รายการ) แล้วหน้าสุดท้ายยังเต็ม`
    + (ช่วง ? ` · ช่วง ${ช่วง}` : "")
    + " — **ของที่ได้ไม่ครบ ห้ามใช้** แบ่งช่วงให้แคบลงหรือขึ้นเพดานอย่างมีเหตุผล",
  );
}
