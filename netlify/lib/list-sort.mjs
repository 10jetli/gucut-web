/* 🔀 ตัวแปล `sort=` + `dir=` ให้เส้น `list=` ทุกเส้นใช้ร่วมกัน
 *
 * 🔑 คุณส้มขอมา 19 ต.ค. 2569 พร้อมผลวัด: ท่อ **เมิน `sort=` เงียบ ๆ**
 *    ยิง `list=bundles` ด้วย `sort=-sku` · `sort=sku&dir=desc` · `order=desc`
 *    ได้แถวแรก `00023-24NW` เท่ากันทุกท่า และ `applied` ไม่สะท้อน sort
 *    ⇒ ZORT เรียงตั้งต้นคนละแบบ (ชุด `00073-30-KK` ขึ้นก่อน) ⇒ **แถวทั้งตารางเป็นคนละชุด**
 *      ตัววัดพิกเซลของฝั่งจอจึงค้างที่ 40–55% ตลอด โดยไม่ใช่ความผิดของจอ
 *
 * 🚫 **ห้ามเมินค่าที่รับมาเงียบ ๆ** — คลาส "ปุ่มหลอก" ที่ทีมเก็บเป็นบทเรียนแล้ว
 *    ⇒ ชื่อช่องที่ไม่รู้จัก **ตอบ 400 พร้อมรายชื่อช่องที่เรียงได้** ไม่ใช่เรียงตามค่าเดิม
 * 🔒 **ห้ามต่อข้อความของผู้ใช้เข้า SQL** — คืนเฉพาะ "นิพจน์คอลัมน์ที่ตรึงไว้ในรายชื่ออนุญาต"
 * 🔑 **ต้องสะท้อนกลับใน `applied.sort` / `applied.dir`** — ฝั่งจอตกลงว่าจะเชื่อเฉพาะตอนเห็นคีย์นี้
 *    (ถ้าไม่สะท้อน จอแยกไม่ออกระหว่าง "ท่อเรียงให้แล้ว" กับ "ท่อเมิน")
 */

/** ทิศที่รับ — ข้อความอื่นถือว่าผิด ไม่ใช่ปรับให้เป็น asc เงียบ ๆ */
const ทิศที่รับ = new Set(["asc", "desc"]);

/**
 * @param {object} ขาเข้า           { sort, dir } ดิบจาก query string
 * @param {object} ช่องที่เรียงได้   { "<ชื่อที่จอส่งมา>": "<นิพจน์ SQL ที่ตรึงไว้>" }
 * @param {object} ตั้งต้น          { sort, dir } ค่าที่ใช้เมื่อจอไม่ส่งอะไรมา (ต้องตรงกับ ORDER BY เดิม)
 * @returns {{error:string}|{sql:string, applied:{sort:string|null,dir:string|null}, คอลัมน์:string, ทิศ:string}}
 */
export function ตีความการเรียง(ขาเข้า, ช่องที่เรียงได้, ตั้งต้น) {
  const รายชื่อ = Object.keys(ช่องที่เรียงได้);
  let ชื่อ = ขาเข้า?.sort == null ? "" : String(ขาเข้า.sort).trim();
  let ทิศ = ขาเข้า?.dir == null ? "" : String(ขาเข้า.dir).trim().toLowerCase();

  /* รองรับรูปย่อ `sort=-sku` (ขีดหน้า = ลง) ที่ฝั่งจอลองใช้มาแล้ว
     ⇒ รับทั้งสองรูป ดีกว่าให้เขาเดาว่าเรารับรูปไหน */
  if (ชื่อ.startsWith("-")) {
    ชื่อ = ชื่อ.slice(1).trim();
    if (!ทิศ) ทิศ = "desc";
  } else if (ชื่อ.startsWith("+")) {
    ชื่อ = ชื่อ.slice(1).trim();
  }

  if (!ชื่อ) {
    /* ไม่ส่ง sort มา ⇒ ใช้ค่าตั้งต้นเดิมของเส้น **และบอกว่าใช้อะไร**
       (จอจะได้รู้ว่าตั้งต้นคืออะไร ไม่ต้องเดา — เป็นเหตุที่ ZORT กับเราเคยคนละชุด) */
    if (ทิศ && !ทิศที่รับ.has(ทิศ)) {
      return { error: `dir ต้องเป็น asc หรือ desc (ได้มา "${ทิศ}")` };
    }
    return {
      sql: ตั้งต้น.sql,
      applied: { sort: ตั้งต้น.sort, dir: ตั้งต้น.dir, sortDefaulted: true },
      /* 📣 **ประกาศรายชื่อช่องที่เรียงได้ออกไปด้วย** (คุณส้มขอ 21 ต.ค. 2569 ~01:0x
         *"จะได้เลิกถามซ้ำ"* — ก่อนนี้เธอต้องยิงลองทีละช่องเพื่อรู้ว่าเส้นไหนเรียงอะไรได้)
         🔑 รายชื่อมาจาก **allowlist ที่ผู้เรียกส่งเข้ามา** ⇒ ไม่มีการพิมพ์ซ้ำที่ไหน
            เพิ่มช่องในเส้นไหน รายชื่อของเส้นนั้นขยับเอง (กฎ one-threshold-one-source)
         ⚠️ จอใช้ค่านี้ตัดสินว่าจะ **ทำหัวคอลัมน์เป็นปุ่มหรือเป็นตัวหนังสือ**
            ⇒ ส่งผิด = จอมีปุ่มที่กดแล้ว error หรือมีช่องที่กดได้แต่ไม่โชว์ปุ่ม */
      sortsSupported: รายชื่อ,
      คอลัมน์: ตั้งต้น.sort,
      ทิศ: ตั้งต้น.dir,
    };
  }

  if (!(ชื่อ in ช่องที่เรียงได้)) {
    return { error: `ไม่รู้จักช่องเรียง "${ชื่อ}" — เส้นนี้เรียงได้: ${รายชื่อ.join(" ")}`,
             sortsSupported: รายชื่อ };
  }
  if (ทิศ && !ทิศที่รับ.has(ทิศ)) {
    return { error: `dir ต้องเป็น asc หรือ desc (ได้มา "${ทิศ}")` };
  }
  const ทิศจริง = ทิศ || "asc";
  const คอลัมน์ = ช่องที่เรียงได้[ชื่อ];
  /* 🔑 ต่อท้ายด้วยคอลัมน์ตั้งต้นเสมอ ⇒ **ลำดับนิ่ง** (stable)
     ไม่งั้นแถวที่ค่าเท่ากันสลับที่กันเองทุกคำขอ แล้วการไล่หน้าจะข้าม/ซ้ำแถวแบบหาสาเหตุไม่เจอ */
  const sql = `ORDER BY ${คอลัมน์} ${ทิศจริง === "desc" ? "DESC" : "ASC"}, ${ตั้งต้น.sql.replace(/^ORDER BY /i, "")}`;
  return { sql, applied: { sort: ชื่อ, dir: ทิศจริง, sortDefaulted: false },
           sortsSupported: รายชื่อ, คอลัมน์, ทิศ: ทิศจริง };
}

/** ตัวเทียบสำหรับเส้นที่เรียงในหน่วยความจำ (เช่น `list=stock` ที่ติดป้ายแล้วค่อยตัดหน้า)
 *  ⚠️ ต้องเรียง **ก่อน** ตัดหน้า — เรียงหลังตัด = เรียงแค่หน้าที่เห็น ซึ่งดูเหมือนทำงาน */
export function ตัวเทียบ(ช่อง, ทิศ) {
  const กลับ = ทิศ === "desc" ? -1 : 1;
  return (a, b) => {
    const x = a?.[ช่อง], y = b?.[ช่อง];
    const ว่างX = x === null || x === undefined || x === "";
    const ว่างY = y === null || y === undefined || y === "";
    if (ว่างX && ว่างY) return 0;
    if (ว่างX) return 1;            // ค่าว่างไปท้ายเสมอ ไม่ว่าทิศไหน
    if (ว่างY) return -1;
    const เลขX = Number(x), เลขY = Number(y);
    if (Number.isFinite(เลขX) && Number.isFinite(เลขY)) return (เลขX - เลขY) * กลับ;
    return String(x).localeCompare(String(y), "th") * กลับ;
  };
}
