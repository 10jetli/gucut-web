/** เพดานของ **ค่าในหนึ่งชิ้น** — ต้องเผื่อโครงแถว SQL และ escape
 *  ⚠️ ของจริงที่ทำให้ D1 ล้มคือ ~100 KB ของ **คำสั่งทั้งคำสั่ง** ไม่ใช่ของค่า
 *  ⇒ ตั้งไว้ 40 KB/ชิ้น: base64 ไม่มีอักขระที่ต้อง escape ⇒ แถวโตกว่าค่าเพียงเล็กน้อย
 *    และยังเหลือที่ให้หลายชิ้นอยู่ในก้อน batch เดียวได้ */
export const ชิ้นละไบต์ = 40_000;

/** ป้ายที่ใส่ใน body ของแถวหลัก — ตัวกู้คืนเห็นป้ายนี้แล้วรู้ว่าต้องไปต่อชิ้น */
export const ป้ายหั่น = "⧉หั่น:";

/** รูปคีย์ของชิ้น: `<คีย์จริง>⧉ชิ้น<ลำดับ>/<จำนวน>`
 *  ⚠️ ใช้ `⧉` (U+29C9) เพราะ **ไม่เคยปรากฏในคีย์ของ Blobs ที่เราใช้**
 *     ถ้าวันหนึ่งมีคีย์จริงที่มีอักขระนี้ ตัวกู้คืนจะเข้าใจผิด ⇒ มีด่านในเทสกันไว้ */
export const PART_RE = /^(.*)⧉ชิ้น(\d+)\/(\d+)$/;

/** หั่นค่าเป็นชิ้น ๆ พร้อมคีย์ — คืน `[{key, body}]` (ค่าเล็กได้ชิ้นเดียว)
 *  @param {string} ค่า   เนื้อค่าดิบ (ข้อความ)
 *  @param {string} คีย์  คีย์จริงใน Blobs
 */
export function หั่นเก็บ(ค่า, คีย์) {
  const b64 = Buffer.from(String(ค่า), "utf8").toString("base64");
  const จำนวน = Math.max(1, Math.ceil(b64.length / ชิ้นละไบต์));
  const out = [];
  for (let i = 0; i < จำนวน; i++) {
    out.push({
      key: `${คีย์}⧉ชิ้น${i}/${จำนวน}`,
      body: b64.slice(i * ชิ้นละไบต์, (i + 1) * ชิ้นละไบต์),
    });
  }
  return out;
}

/** ต่อชิ้นกลับเป็นค่าเดิม
 *  @param {string[]} ชิ้น    เนื้อของแต่ละชิ้น **เรียงตามลำดับแล้ว**
 *  @param {number} [ต้องมี]  จำนวนชิ้นที่ควรมี (จากชื่อคีย์) — ส่งมาแล้วจะตรวจให้
 *  🔴 **ชิ้นไม่ครบ ⇒ โยน ห้ามคืนของครึ่งใบ**
 *     ของครึ่งใบที่ดูเหมือนกู้สำเร็จ แย่กว่ากู้ไม่ได้ เพราะคนจะเอาไปใช้ต่อ
 */
export function ต่อกลับ(ชิ้น, ต้องมี = null) {
  const มี = (ชิ้น || []).filter((x) => typeof x === "string");
  if (!มี.length) throw new Error("ต่อกลับไม่ได้: ไม่มีชิ้นเลย");
  if (ต้องมี !== null && มี.length !== Number(ต้องมี)) {
    throw new Error(`ต่อกลับไม่ได้: ชิ้นไม่ครบ (มี ${มี.length} ต้องมี ${ต้องมี}) — ห้ามคืนของครึ่งใบ`);
  }
  if (มี.length !== (ชิ้น || []).length) {
    throw new Error(`ต่อกลับไม่ได้: ชิ้นไม่ครบ (บางชิ้นอ่านไม่ได้) — ห้ามคืนของครึ่งใบ`);
  }
  return Buffer.from(มี.join(""), "base64").toString("utf8");
}

/** จัดกลุ่มแถวที่อ่านจากตารางเป็น `{ คีย์จริง: {ชิ้น:[...], ต้องมี:n} }`
 *  ⚠️ แถวที่ไม่ใช่ชิ้นจะไม่ถูกแตะ — ผู้เรียกจัดการเอง */
export function จัดกลุ่มชิ้น(rows) {
  const กลุ่ม = new Map();
  for (const r of rows || []) {
    const m = PART_RE.exec(String(r?.key ?? ""));
    if (!m) continue;
    const [, คีย์, ลำดับ, จำนวน] = m;
    if (!กลุ่ม.has(คีย์)) กลุ่ม.set(คีย์, { ชิ้น: [], ต้องมี: Number(จำนวน) });
    กลุ่ม.get(คีย์).ชิ้น[Number(ลำดับ)] = r?.body;
  }
  return กลุ่ม;
}
