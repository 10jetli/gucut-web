/**
 * มีหลักฐานว่าของถึงมือลูกค้าแล้วหรือยัง — **ตัดสินจากกองที่ท่อจัดมา ไม่ใช่จากข้อความ**
 * @param {object} b บรรทัดขาย (ต้องมี `shipStatusGroup` · `shipStatusKnown` · `payStatus`)
 * @param {"ส่งมอบแล้ว"|"จ่ายแล้ว"} จุดปั๊ม
 * @returns {{ปั๊มได้: boolean, ชนิด: string, เหตุ: string}}
 */
export function หลักฐานการส่งมอบ(b, จุดปั๊ม = "ส่งมอบแล้ว") {
  if (!จ่ายแล้ว(b.payStatus)) {
    return { ปั๊มได้: false, ชนิด: "ยังไม่จ่าย", เหตุ: `สถานะเงิน ${b.payStatus || "(ว่าง)"} ⇒ รอจ่ายก่อนทุกกรณี` };
  }
  if (จุดปั๊ม === "จ่ายแล้ว") return { ปั๊มได้: true, ชนิด: "จ่ายแล้ว", เหตุ: "จุดปั๊มตั้งไว้ที่ จ่ายแล้ว" };

  /* 🔴 **ท่อบอกว่าตัวเองไม่รู้ ⇒ เราก็ไม่รู้ ⇒ ไม่ปั๊ม** (ไม่รู้ ≠ ยังไม่ส่ง ≠ ส่งแล้ว) */
  if (b.shipStatusKnown === false) {
    return { ปั๊มได้: false, ชนิด: "ไม่รู้สถานะส่ง", เหตุ: `ท่อบอกว่าอ่านสถานะไม่ออก (${b.shipStatus ?? "—"}) ⇒ ไม่เดา` };
  }
  const g = String(b.shipStatusGroup ?? "");
  if (!g) return { ปั๊มได้: false, ชนิด: "ไม่มีช่องกองสถานะ", เหตุ: "บรรทัดนี้ไม่มี shipStatusGroup ⇒ ยังไม่ได้ถามท่อ ไม่ใช่ว่าไม่มีสถานะ" };
  if (กองที่ห้ามปั๊ม.includes(g)) return { ปั๊มได้: false, ชนิด: "ห้ามปั๊ม", เหตุ: `กอง ${g} (${GROUP_TH[g] ?? "?"})` };
  if (กองที่ส่งมอบแล้ว.includes(g)) return { ปั๊มได้: true, ชนิด: "ส่งมอบแล้ว", เหตุ: `กอง ${g} (${GROUP_TH[g] ?? "?"})` };
  if (กองที่ไม่มีสัญญาณส่ง.includes(g)) {
    return { ปั๊มได้: true, ชนิด: "ไม่มีสัญญาณส่ง ใช้จ่ายแล้ว",
             เหตุ: `กอง ${g} — ช่องทางนี้ไม่มีใครบอกสถานะส่ง (หน้าร้าน/เว็บเรา/แชท) ⇒ รออีกก็ไม่มีสัญญาณมา` };
  }
  if (กองที่ยังไม่ส่งมอบ.includes(g)) return { ปั๊มได้: false, ชนิด: "ยังไม่ส่งมอบ", เหตุ: `กอง ${g} (${GROUP_TH[g] ?? "?"}) ⇒ รอ` };
  /* ชื่อกองที่เราไม่รู้จัก = ท่อเพิ่มกองใหม่แล้วเราไม่รู้ ⇒ **ไม่ปั๊ม และบอกชื่อออกมา** */
  return { ปั๊มได้: false, ชนิด: "กองที่ยังไม่ได้จัด", เหตุ: `ไม่รู้จักกอง "${g}" ⇒ ต้องมีคนมาจัดก่อน ไม่เดา` };
}

/** วันไทย `yyyy-MM-dd` → รูปที่ทะเบียนใช้จริง `d/M/พ.ศ.`
 *  ⚠️ **ต้องเขียนรูปเดียวกับ 311 แถวที่มีอยู่** ไม่ใช่ ISO — ไม่งั้นสมุดเล่มเดียวมีสองรูปแบบวันที่
 *     (ตัวนับที่ใช้ `sold_at IS NULL OR = ''` ยังนับถูก แต่ใครอ่านวันที่ต่อจะพังเงียบ) */
export function วันไทยแบบทะเบียน(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso ?? "").trim());
  if (!m) return null;
  return `${Number(m[3])}/${Number(m[2])}/${Number(m[1]) + 543}`;
}

/** กุญแจของบรรทัดขายหนึ่งบรรทัด — **ผูกกับเลขที่ใบ ไม่ใช่เวลา**
 *  เวลาเปลี่ยนได้เมื่อซิงก์ใหม่ ⇒ ใช้เวลาเป็นกุญแจแล้วจะปั๊มซ้ำ */
export const กุญแจบรรทัด = (b) => `${b.number}|${b.sku}|${b.line ?? 0}`;

/**
 * วางแผนว่าจะปั๊มซีเรียลใบไหน — **ฟังก์ชันบริสุทธิ์ ไม่แตะฐาน** (เทสเรียกตรงได้)
 * @param {object} o
 * @param {Array}  o.บรรทัดขาย  [{number, date, sku, qty, status, payStatus, customer, line}]
 * @param {Map}    o.ซีเรียลว่าง Map(`<kind>|<ชื่อกลุ่ม>` → [{lot, serial, received, seq}] เรียง FIFO แล้ว)
 * @param {Set}    o.ปั๊มแล้ว    Set(กุญแจบรรทัด) ที่เคยปั๊มไปแล้ว
 * @returns {{ปั๊ม: Array, ข้าม: Array, ของไม่พอ: Array}}
 */
export function วางแผนปั๊ม({ บรรทัดขาย = [], ซีเรียลว่าง = new Map(), ปั๊มแล้ว = new Set(), เริ่มตั้งแต่ = เริ่มปั๊มตั้งแต่, จุดปั๊ม = จุดปั๊มปริยาย } = {}) {
  const ปั๊ม = [], ข้าม = [], ของไม่พอ = [];
  /* สำเนาคิวของแต่ละกลุ่ม — ตัดออกเมื่อจองไปแล้ว ⇒ สองบรรทัดในรอบเดียวกันไม่แย่งซีเรียลเดียวกัน
     ⚠️ ถ้าไม่ทำสำเนา จะอ่านคิวเดิมซ้ำแล้วจองซีเรียลเดียวให้สองใบ (ของที่มีมากกว่าหนึ่งใบต่อรอบ) */
  const คิว = new Map([...ซีเรียลว่าง].map(([k, v]) => [k, [...v]]));

  for (const b of บรรทัดขาย) {
    const เหตุ = (ชนิด, ข้อความ) => ข้าม.push({ number: b.number, sku: b.sku, ชนิด, เหตุ: ข้อความ });
    const g = รหัสเป็นกลุ่มทะเบียน[String(b.sku ?? "").trim()];
    if (!g) { เหตุ("ไม่ใช่ของทะเบียน", "รหัสนี้ไม่อยู่ในตารางจับคู่ทะเบียน ⇒ ไม่ใช่งานของตัวปั๊ม"); continue; }
    if (!b.date || String(b.date) < String(เริ่มตั้งแต่)) {
      เหตุ("ก่อนวันเริ่ม", `ใบลงวัน ${b.date || "(ไม่มีวัน)"} ก่อน ${เริ่มตั้งแต่} ⇒ ห้ามปั๊มย้อนหลัง (สองสมุดไม่ตรงกันสองทิศ)`);
      continue;
    }
    if (เป็นใบยกเลิก(b.status) || เป็นใบยกเลิก(b.payStatus)) { เหตุ("ใบยกเลิก", `สถานะ ${b.status}/${b.payStatus}`); continue; }
    /* หลักฐานการส่งมอบ — รวมเงื่อนไข "จ่ายแล้ว" ไว้ข้างในแล้ว (ต้องจ่ายก่อนทุกกรณี)
       ⚠️ ของจริง: ใบ Pending ของบาร์ทะเบียนค้างมาตั้งแต่ 2568 หลายใบ ⇒ ปั๊มไว้ก่อนคือล็อกซีเรียลทิ้งเป็นปี */
    const ส่งมอบ = หลักฐานการส่งมอบ(b, จุดปั๊ม);
    if (!ส่งมอบ.ปั๊มได้) { เหตุ(ส่งมอบ.ชนิด, ส่งมอบ.เหตุ); continue; }
    if (ปั๊มแล้ว.has(กุญแจบรรทัด(b))) { เหตุ("ปั๊มแล้ว", `บรรทัด ${กุญแจบรรทัด(b)} มีในบันทึกแล้ว`); continue; }

    /* 🔴 **ห้ามใช้ `Number(x) || 0`** — ด่าน `check-num-helpers` จับได้ตอน push (5 ต.ค. 2569)
       ท่านั้นกลืน "อ่านไม่ได้" ให้เป็น 0 ⇒ ที่นี่พฤติกรรมยังถูก (0 ถูกตีกลับบรรทัดถัดไป)
       **แต่รูปแบบนั้นเป็นหนี้** — คนที่มาแก้ทีหลังจะเห็น 0 แล้วไม่รู้ว่ามันมาจาก "ไม่มีค่า"
       ⇒ แยกสามอย่างให้ขาดตรงนี้: อ่านไม่ออก · ไม่ใช่จำนวนเต็ม · ไม่เป็นบวก
       ⚠️ เศษส่วนต้องตีกลับด้วย — ของที่นับเป็นเลขซีเรียลขายครึ่งชิ้นไม่ได้
          (ของเดิม `Math.floor` จะปัด 1.5 เป็น 1 **เงียบ ๆ** ซึ่งเป็นการเดาแทนคน) */
    const จำนวนดิบ = Number(b.qty);
    if (!Number.isFinite(จำนวนดิบ) || !Number.isInteger(จำนวนดิบ) || จำนวนดิบ <= 0) {
      เหตุ("จำนวนอ่านไม่ได้", `qty = ${JSON.stringify(b.qty)} ⇒ ต้องเป็นจำนวนเต็มบวก ไม่เดาว่า 1 และไม่ปัดเศษ`);
      continue;
    }
    const จำนวน = จำนวนดิบ;
    const k = คีย์กลุ่ม(g.kind, g.ชื่อ);
    const ว่าง = คิว.get(k) || [];
    const soldAt = วันไทยแบบทะเบียน(b.date);
    if (!soldAt) { เหตุ("วันที่อ่านไม่ได้", `date = ${JSON.stringify(b.date)} ⇒ ไม่เดารูปวันที่`); continue; }
    const หยิบ = ว่าง.splice(0, จำนวน);
    คิว.set(k, ว่าง);
    for (const s of หยิบ) {
      ปั๊ม.push({ lot: s.lot, serial: s.serial, seq: s.seq, กลุ่ม: k, sku: b.sku,
                  number: b.number, customer: b.customer ?? "", soldAt, กุญแจ: กุญแจบรรทัด(b) });
    }
    if (หยิบ.length < จำนวน) {
      /* 🔴 **ขายได้มากกว่าซีเรียลที่มี = ปัญหาจริงที่ต้องมีคนเห็น ไม่ใช่ปั๊มให้ครบแล้วติดลบ**
         ปั๊มเท่าที่มี + รายงานส่วนที่ขาด · ห้ามสร้างซีเรียลใหม่ (เลขซีเรียลออกเองไม่ได้ตามกฎหมาย) */
      ของไม่พอ.push({ number: b.number, sku: b.sku, กลุ่ม: k, ขอ: จำนวน, ได้: หยิบ.length, ขาด: จำนวน - หยิบ.length });
    }
  }
  return { ปั๊ม, ข้าม, ของไม่พอ };
}

/** อ่านซีเรียลที่ยังว่าง จัดเป็นคิว FIFO ต่อกลุ่ม (เก่าสุดออกก่อน) */
export async function ซีเรียลว่างต่อกลุ่ม({ query = coreQuery } = {}) {
  const แถว = await query(
    `SELECT lot, kind, spec, model, serial, seq, received
       FROM registry WHERE sold_at IS NULL OR sold_at = ''
      ORDER BY lot, seq`
  );
  if (!Array.isArray(แถว)) throw new Error("อ่านทะเบียนไม่ได้ (คำตอบไม่ใช่อาร์เรย์) ⇒ ไม่รู้ ห้ามถือว่าไม่มีของว่าง");
  const ตระกูล = (v) => String(v || "").split("/")[0].trim();
  const m = new Map();
  for (const r of แถว) {
    const ชื่อ = r.kind === "saw" ? String(r.model || "") : `${ตระกูล(r.spec)} ${String(r.model || "").trim()}`.trim();
    const k = คีย์กลุ่ม(r.kind, ชื่อ);
    if (!m.has(k)) m.set(k, []);
    m.get(k).push({ lot: r.lot, serial: r.serial, seq: r.seq, received: r.received });
  }
  return m;
}

/** กุญแจบรรทัดที่เคยปั๊มไปแล้ว — ตาข่ายกันซ้ำชั้นที่ 1 */
export async function บรรทัดที่ปั๊มแล้ว({ query = coreQuery } = {}) {
  await query(
    `CREATE TABLE IF NOT EXISTS ${ตารางบันทึกปั๊ม} (
       line_key TEXT, lot INTEGER, serial TEXT, sku TEXT, order_number TEXT,
       sold_at TEXT, stamped_at TEXT, PRIMARY KEY (lot, serial))`
  );
  const แถว = await query(`SELECT line_key FROM ${ตารางบันทึกปั๊ม}`);
  if (!Array.isArray(แถว)) throw new Error("อ่านบันทึกปั๊มไม่ได้ ⇒ ไม่รู้ว่าปั๊มอะไรไปแล้ว ห้ามปั๊มต่อ");
  return new Set(แถว.map((r) => String(r.line_key)));
}

/**
 * ลงมือปั๊มจริง — **ต้องส่ง `ยืนยัน: "ปั๊มจริง"` ไม่งั้นเป็นรอบซ้อมเสมอ**
 * 🔒 ตาข่ายกันปั๊มซ้ำ **สองชั้นที่ไม่พึ่งกัน**:
 *    ① `line_key` ในตารางบันทึก (ชั้นแผน — กันตั้งแต่ยังไม่ยิง)
 *    ② `WHERE sold_at IS NULL OR sold_at = ''` ในตัว UPDATE เอง (ชั้นฐาน — กันแม้บันทึกหาย)
 *    ⇒ ชั้น ② สำคัญกว่า เพราะมันจริงแม้ตารางบันทึกถูกลบทิ้ง
 * ⚠️ ปั๊มทับของที่มี `sold_at` อยู่แล้ว **ทำไม่ได้โดยโครงสร้าง** ไม่ใช่ด้วยความระวัง
 */
export async function ปั๊มจริง({ แผน, query = coreQuery, ยืนยัน = "", ผู้สั่ง = "" } = {}) {
  const รายการ = (แผน?.ปั๊ม || []);
  const ซ้อม = ยืนยัน !== "ปั๊มจริง";
  const ผล = { ซ้อม, ขอปั๊ม: รายการ.length, ปั๊มสำเร็จ: 0, ปั๊มไม่ติด: [], ยืนยันกลับ: [] };
  if (ซ้อม || !รายการ.length) {
    ผล.หมายเหตุ = ซ้อม
      ? 'รอบซ้อม — ไม่ได้เขียนอะไรลงทะเบียน (ต้องส่ง ยืนยัน: "ปั๊มจริง")'
      : "ไม่มีรายการให้ปั๊ม";
    return ผล;
  }
  const เวลา = new Date().toISOString();
  for (const x of รายการ) {
    try {
      await query(
        `UPDATE registry SET sold_at = ?, buyer = COALESCE(NULLIF(buyer,''), ?)
          WHERE lot = ? AND serial = ? AND (sold_at IS NULL OR sold_at = '')`,
        [x.soldAt, x.customer, x.lot, x.serial]
      );
      /* 🔑 **อ่านกลับก่อนนับว่าสำเร็จ** — `UPDATE` ที่ไม่โดนแถวไหนก็ไม่ error
         ⇒ ถ้าไม่อ่านกลับ จะรายงานว่าปั๊มครบทั้งที่ไม่มีอะไรเปลี่ยน [[ข่าวดีปลอมอันตรายกว่าข่าวร้ายปลอม]] */
      const กลับ = await query(`SELECT sold_at FROM registry WHERE lot = ? AND serial = ?`, [x.lot, x.serial]);
      const ค่า = Array.isArray(กลับ) && กลับ[0] ? String(กลับ[0].sold_at ?? "") : "";
      if (ค่า === x.soldAt) {
        ผล.ปั๊มสำเร็จ++;
        ผล.ยืนยันกลับ.push({ lot: x.lot, serial: x.serial, sold_at: ค่า, sku: x.sku, number: x.number });
        await query(
          `INSERT OR IGNORE INTO ${ตารางบันทึกปั๊ม} (line_key, lot, serial, sku, order_number, sold_at, stamped_at)
           VALUES (?, ?, ?, ?, ?, ?, ?)`,
          [x.กุญแจ, x.lot, x.serial, x.sku, x.number, x.soldAt, เวลา]
        );
      } else {
        ผล.ปั๊มไม่ติด.push({ lot: x.lot, serial: x.serial, sku: x.sku, number: x.number,
          เหตุ: ค่า ? `แถวนี้มี sold_at อยู่แล้ว (${ค่า}) ⇒ ด่านชั้นฐานกันไว้ ไม่ทับของเดิม` : "อ่านกลับแล้วยังว่าง ⇒ UPDATE ไม่โดนแถวนี้" });
      }
    } catch (e) {
      ผล.ปั๊มไม่ติด.push({ lot: x.lot, serial: x.serial, sku: x.sku, number: x.number, เหตุ: `ยิงไม่สำเร็จ: ${e?.message || e}` });
    }
  }
  ผล.ผู้สั่ง = String(ผู้สั่ง || "").slice(0, 60);
  ผล.ครบไหม = ผล.ปั๊มสำเร็จ === ผล.ขอปั๊ม
    ? "ครบ"
    : `**สำเร็จบางส่วน** ${ผล.ปั๊มสำเร็จ}/${ผล.ขอปั๊ม} ⇒ ดู ปั๊มไม่ติด`;
  return ผล;
}

/** บรรทัดขายของ "ของในทะเบียน" ตั้งแต่วันเริ่ม — อ่านอย่างเดียว
 *  ⚠️ **กรองรหัสที่ฝั่ง SQL ด้วยรายชื่อจากตารางจับคู่** ไม่ใช่กรองด้วยคำในชื่อสินค้า
 *     (กฎร้าน: ห้ามใช้ includes เดาประเภทจากชื่อ) */
export async function บรรทัดขายของทะเบียน({ query = coreQuery, เริ่มตั้งแต่ = เริ่มปั๊มตั้งแต่ } = {}) {
  const รหัส = Object.keys(รหัสเป็นกลุ่มทะเบียน);
  if (!รหัส.length) throw new Error("ตารางจับคู่ทะเบียนว่าง ⇒ ไม่รู้ว่ารหัสไหนเป็นของทะเบียน ห้ามเดา");
  const ช่อง = รหัส.map(() => "?").join(",");
  const แถว = await query(
    `SELECT o.number AS number, o.order_date AS date, o.status AS status,
            o.pay_status AS payStatus, o.customer AS customer, o.channel AS channel,
            o.integration_status AS integrationStatus,
            i.sku AS sku, i.qty AS qty, i.line AS line
       FROM order_items i JOIN orders o ON o.id = i.order_id
      WHERE o.order_date >= ? AND TRIM(i.sku) IN (${ช่อง})
      ORDER BY o.order_date, o.number, i.line`,
    [เริ่มตั้งแต่, ...รหัส]
  );
  if (!Array.isArray(แถว)) throw new Error("อ่านบรรทัดขายไม่ได้ (คำตอบไม่ใช่อาร์เรย์) ⇒ ไม่รู้ ห้ามถือว่าไม่มีการขาย");
  /* 🔑 **ให้ท่อจัดกองสถานะส่งเอง ห้ามจัดเอง** — `decorateOrderRow` เป็นตัวเดียวกับที่
     จอออเดอร์ใช้ ⇒ เราได้ `shipStatusGroup`/`shipStatusKnown` ชุดเดียวกับที่คนเห็นบนจอ
     ⚠️ เขียนเงื่อนไขซ้ำที่นี่เมื่อไหร่ สองที่จะหลุดจากกันแล้วเงียบ (ท่อเขียนเตือนไว้เองในไฟล์นั้น)
     ⚠️ `chanMap` ไม่ได้ส่ง ⇒ เหตุของกองว่างจะเป็น `none_expected` เสมอ **ไม่กระทบการตัดสิน**
        เพราะกฎของเรานับทั้ง `blank_none_expected` และ `blank_source_empty` เป็นกองเดียวกัน
        (ทั้งคู่แปลว่า "ไม่มีใครบอกสถานะ") — จงใจไม่ไวต่อความต่างนั้น */
  return แถว.map((r) => decorateOrderRow(r));
}

/**
 * รอบปั๊มครบวงจร — **ค่าเริ่มต้นเป็นรอบซ้อม** ต้องส่ง `ยืนยัน: "ปั๊มจริง"` จึงจะเขียน
 * 🔑 ทุกคำตอบบอก **ขอบเขตที่ใช้ตัดสิน** (วันเริ่ม · จำนวนบรรทัดที่ดู) เพราะเลขเปล่า ๆ
 *    ตีความไม่ได้ว่า "ไม่มีอะไรต้องปั๊ม" หรือ "ไม่ได้ไปดู"
 */
export async function รอบปั๊ม({ query = coreQuery, ยืนยัน = "", ผู้สั่ง = "", เริ่มตั้งแต่ = เริ่มปั๊มตั้งแต่, จุดปั๊ม = จุดปั๊มปริยาย } = {}) {
  const บรรทัดขาย = await บรรทัดขายของทะเบียน({ query, เริ่มตั้งแต่ });
  const [ซีเรียลว่าง, ปั๊มแล้ว] = await Promise.all([
    ซีเรียลว่างต่อกลุ่ม({ query }),
    บรรทัดที่ปั๊มแล้ว({ query }),
  ]);
  const แผน = วางแผนปั๊ม({ บรรทัดขาย, ซีเรียลว่าง, ปั๊มแล้ว, เริ่มตั้งแต่, จุดปั๊ม });
  const ผล = await ปั๊มจริง({ แผน, query, ยืนยัน, ผู้สั่ง });
  return {
    ok: true,
    ขอบเขต: {
      ปั๊มเฉพาะใบลงวันตั้งแต่: เริ่มตั้งแต่,
      จุดที่ถือว่าขายขาด: จุดปั๊ม,
      บรรทัดขายที่ดู: บรรทัดขาย.length,
      ซีเรียลว่างทั้งหมด: [...ซีเรียลว่าง.values()].reduce((a, b) => a + b.length, 0),
      บรรทัดที่เคยปั๊ม: ปั๊มแล้ว.size,
      หมายเหตุ: "ห้ามปั๊มย้อนหลัง — สองสมุดไม่ตรงกันสองทิศ (ทะเบียนปั๊ม 35 · ใบขาย 59 · วัด 5 ต.ค. 2569)",
    },
    แผน: { ปั๊ม: แผน.ปั๊ม.length, ข้าม: แผน.ข้าม.length, ของไม่พอ: แผน.ของไม่พอ.length },
    ของไม่พอ: แผน.ของไม่พอ,
    /* จัดกองเหตุที่ข้าม — ถ้ายุบเป็นเลขเดียว คนจะแยกไม่ออกว่า "ยังไม่จ่าย" (รอได้)
       กับ "ของไม่พอ" (ต้องมีคนไปดู) ซึ่งต้องทำต่างกันสิ้นเชิง */
    ข้ามแยกตามเหตุ: แผน.ข้าม.reduce((a, x) => ((a[x.ชนิด] = (a[x.ชนิด] || 0) + 1), a), {}),
    ข้ามรายตัว: แผน.ข้าม.slice(0, 50),
    ผล,
  };
}
