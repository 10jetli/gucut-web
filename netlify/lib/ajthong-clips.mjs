export function อ่านหน้าช่องอธง(html) {
  const เนื้อ = String(html ?? "");
  const ชื่อของ = new Map();
  /* โครงจริงของหน้าช่อง (วัด 12 พ.ย. 2569): ชื่ออยู่ใน lockupMetadataViewModel
     ⚠️ รูปแบบ `"title":{"runs":[...]}` **ไม่มีในหน้านี้** — ลองแล้วได้ 0 คู่
        (รูปนั้นเป็นของหน้าอื่นของ YouTube · เดาจากความคุ้นเคยแล้วพลาด)
     ⚠️ อย่าใช้ `accessibilityText` — เจอ 46 คู่แต่เป็นข้อความปุ่ม ("เพิ่มลงในคิว") */
  const reชื่อ = /"videoId":"([A-Za-z0-9_-]{11})"[\s\S]{0,2000}?"metadata":\{"lockupMetadataViewModel":\{"title":\{"content":"([^"]{1,180})"/g;
  for (let m; (m = reชื่อ.exec(เนื้อ)); ) {
    if (!ชื่อของ.has(m[1])) ชื่อของ.set(m[1], m[2]);
  }
  const คลิป = [];
  const เห็นแล้ว = new Set();
  let ตัดเพราะซ้ำในฟีด = 0;
  let ตัดเพราะอยู่ในรายการซ้ำ = 0;
  const reรหัส = /"videoId":"([A-Za-z0-9_-]{11})"/g;
  for (let m; (m = reรหัส.exec(เนื้อ)); ) {
    const รหัส = m[1];
    if (คลิปซ้ำที่ห้ามโชว์.has(รหัส)) { ตัดเพราะอยู่ในรายการซ้ำ++; continue; }
    if (เห็นแล้ว.has(รหัส)) { ตัดเพราะซ้ำในฟีด++; continue; }
    เห็นแล้ว.add(รหัส);
    คลิป.push({
      id: รหัส,
      ชื่อ: ถอดเอนทิตี(ชื่อของ.get(รหัส) ?? "").slice(0, 180),
      เมื่อ: null,                 // หน้าช่องไม่ได้ให้วันที่แน่นอน — อย่าแต่งขึ้นมา
      ฝังที่: `https://www.youtube-nocookie.com/embed/${รหัส}`,
      ดูที่: `https://www.youtube.com/watch?v=${รหัส}`,
    });
  }
  return { คลิป, ตัดเพราะซ้ำในฟีด, ตัดเพราะอยู่ในรายการซ้ำ };
}

export function อ่านฟีดอธง(xml) {
  const รายการ = String(xml ?? "").split("<entry").slice(1);
  const คลิป = [];
  const เห็นแล้ว = new Set();
  let ตัดเพราะซ้ำในฟีด = 0;
  let ตัดเพราะอยู่ในรายการซ้ำ = 0;
  for (const e of รายการ) {
    const รหัส = ชิ้น(e, "yt:videoId");
    if (!/^[A-Za-z0-9_-]{6,20}$/.test(รหัส)) continue;      // รูปรหัสไม่ถูก ⇒ ทิ้ง ไม่เดา
    if (คลิปซ้ำที่ห้ามโชว์.has(รหัส)) { ตัดเพราะอยู่ในรายการซ้ำ++; continue; }
    if (เห็นแล้ว.has(รหัส)) { ตัดเพราะซ้ำในฟีด++; continue; }
    เห็นแล้ว.add(รหัส);
    คลิป.push({
      id: รหัส,
      ชื่อ: ถอดเอนทิตี(ชิ้น(e, "title")).slice(0, 180),
      เมื่อ: ชิ้น(e, "published") || null,
      ฝังที่: `https://www.youtube-nocookie.com/embed/${รหัส}`,
      ดูที่: `https://www.youtube.com/watch?v=${รหัส}`,
    });
  }
  return { คลิป, ตัดเพราะซ้ำในฟีด, ตัดเพราะอยู่ในรายการซ้ำ };
}
