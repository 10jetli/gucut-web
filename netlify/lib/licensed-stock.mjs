/**
 * จำนวนที่เหลือตามทะเบียน · คืน `null` ถ้า **ไม่ใช่** ของในทะเบียน
 *
 * ⚠️ ต้องแยกสามสถานะให้ขาด — `null` (ไม่ใช่ของในทะเบียน ⇒ ใช้ ZORT ต่อ) ·
 *    `0` (อยู่ในทะเบียนแต่ขายหมดแล้ว ⇒ ห้ามถอยไปใช้ ZORT) · `>0` (มีของ)
 *    ยุบ `0` กับ `null` เป็นค่าเดียวเมื่อไหร่ ของที่หมดจริงจะเด้งกลับไปโชว์เลข ZORT ที่เชื่อไม่ได้
 */
export function licensedStock(sku) {
  if (!sku) return null;
  const n = LICENSED[String(sku).trim()];
  return typeof n === "number" && Number.isFinite(n) ? n : null;
}
