/* 🔎 ค้นคำที่คนพิมพ์ในฐาน D1 — ใช้ตัวนี้ที่เดียว ห้ามเขียน `LIKE '%คำค้น%'` เอง (15 ก.ย. 2569)

   🔴 **D1 จำกัดรูปแบบ LIKE ไว้ 50 ไบต์** — เกินแล้วตอบ
      `LIKE or GLOB pattern too complex: SQLITE_ERROR` ⇒ ทั้งคำขอล้ม (HTTP 500)
      📏 ยิงพิสูจน์บน production: รูปแบบ `%คำค้น%` = คำค้น + 2 ไบต์
         a×48 ผ่าน · a×49 ล้ม · ไทยตัวละ 3 ไบต์ ⇒ **ก×16 ผ่าน ก×17 ล้ม**
      ⇒ ชื่อ+นามสกุลไทยเต็ม ๆ ค้นไม่ได้ในทุกจอ (ผู้ติดต่อ · ขาย · สต็อก · ซื้อ · ใบคืน …)
         เป็นมาตั้งแต่มีช่องค้นหา — gucut2 จับได้ตอนยิงตรวจเส้นใบคืน ไม่มีตัวตรวจไหนเห็นมาก่อน
         เพราะเทสต์ป้อนคำค้นสั้นเสมอ และฐานปลอมไม่มีเพดานนี้

   ✅ `instr(lower(ช่อง), lower(คำค้น)) > 0` — ไม่มีเพดานรูปแบบ
      · ไม่สนตัวพิมพ์เล็ก/ใหญ่อังกฤษ เท่ากับ LIKE เดิม (lower() ของ SQLite แปลงแค่ ASCII เหมือนกัน)
      · ช่องเป็น NULL ⇒ ผลเป็น NULL = ไม่ผ่าน เท่ากับ LIKE เดิม
      · `%` และ `_` ในคำค้นเป็นตัวอักษรธรรมดา — ดีกว่าเดิมที่หลายจุดไม่ได้ escape
        (พิมพ์ `_` แล้วเคยได้ทุกแถว)
      · ใช้ดัชนีไม่ได้ — เท่ากับ LIKE '%…%' เดิมซึ่งก็ใช้ไม่ได้อยู่แล้ว ⇒ ไม่ช้าลง

   ขอบเขตของกฎ: **คำที่คนพิมพ์ (q / term)** เท่านั้น
      ค่าคงที่ในโค้ด เช่น `status NOT LIKE '%void%'` · `channel LIKE '%Shopee%'` สั้นและเราเป็นคนเขียน ⇒ ไม่ต้องย้าย
   🧪 ตัวเฝ้า: scripts/tests/sql-contains-guard.test.mjs สแกนซอร์สหา %…% ที่ห่อตัวแปร */

/** เงื่อนไขแบบพารามิเตอร์ — ส่งคำค้นดิบ (ไม่ต้องห่อ %) ไปใน params หนึ่งตัวต่อหนึ่งครั้งที่เรียก */
export const contains = (col) => `instr(lower(${col}), lower(?)) > 0`;

/** เงื่อนไขแบบฝังค่า — `lit` ต้องเป็นสตริง SQL ที่ escape แล้ว (ผลของ esc() ในไฟล์นั้น) */
export const containsLit = (col, lit) => `instr(lower(${col}), lower(${lit})) > 0`;
