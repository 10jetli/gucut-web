/** true เมื่อ env นั้นมีค่าที่ใช้งานได้จริง (ค่าว่าง/ช่องว่างล้วน = ถือว่าไม่มี) */
function มีค่า(ชื่อ) {
  const v = process.env[ชื่อ];
  return typeof v === "string" && v.trim() !== "";
}

