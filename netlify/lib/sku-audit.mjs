// ตรวจว่า "รหัสสินค้าตรงกันทุกแพลตฟอร์มไหม" — ท่านประธานสั่ง 18 ก.ย. 2569
//
// > *"รหัสต้องตรงกันทุกแพลตฟอร์ม"*
//
// 🔴 ที่มา: ท่านประธานทักว่าจอสินค้ายังขึ้นจุดส้ม "จับคู่จากการเดารหัสฐาน"
//    ยิงตรวจทั้งคลังแล้วพบว่า 26 จาก 34 แถว (76%) **ไม่ควรส้ม** — รหัสบนแพลตฟอร์ม
//    ตรงกับรหัสชุดของเราเป๊ะอยู่แล้ว ⇒ ของที่ต้องตามแก้จริงมีน้อยกว่าที่เห็นมาก
//    แต่ "น้อยกว่า" ไม่ได้แปลว่า "ไม่มี" — ไฟล์นี้จึงมีไว้ชี้ตัวที่ต้องแก้จริง ๆ
//
// 🔑 **แยกให้ชัดว่าใครต้องแก้อะไร** — ทั้งสามกองข้างล่างต้องลงมือคนละทาง
//    ① แพลตฟอร์มใช้รหัสที่คลังเราไม่มี  ⇒ แก้ที่หน้าร้านแพลตฟอร์มนั้น (หรือเปิดรหัสในคลัง)
//    ② แพลตฟอร์มใช้รหัสไม่เหมือนกันเอง  ⇒ ตกลงให้เหลือรหัสเดียวแล้วแก้ที่ร้านที่ผิด
//    ③ รหัสในคลังที่ไม่ได้ลงขายที่ไหนเลย ⇒ เรื่องการขาย ไม่ใช่เรื่องรหัส (แสดงเป็นข้อมูล)
//
// ⚠️ **อ่านอย่างเดียว ไม่แก้อะไรทั้งสิ้น** — การแก้รหัสบนแพลตฟอร์มกระทบของที่ขายอยู่จริง
//    ต้องให้ท่านประธานตัดสินเป็นราย ๆ

import { expandSku } from "./sku-match.mjs";

/**
 * @param {object} deps
 * @param {Record<string,string[]>} deps.listings รหัสบนแพลตฟอร์ม → ช่องทางที่ใช้รหัสนั้น
 * @param {Set<string>} deps.ourSkus รหัสที่คลังเรามี (สินค้า + ชุด)
 * @param {string[]} deps.checked ช่องทางที่ตรวจได้จริงรอบนี้
 */
export function auditSkus({ listings = {}, ourSkus = new Set(), checked = [] } = {}) {
  /* ⚠️ **ช่องทางที่ตรวจไม่ได้รอบนี้ ห้ามนับเป็น "ไม่ได้ลงขาย"**
     ไม่งั้นวันที่แพลตฟอร์มล่ม รายงานจะบอกว่าร้านถอดของออกหมด ซึ่งผิดและน่าตกใจ
     ⇒ ทุกข้อสรุปในไฟล์นี้จำกัดขอบเขตอยู่ที่ `checked` เท่านั้น */
  const ช่องทางที่เชื่อได้ = new Set(checked);

  const ไม่มีในคลัง = [];      // ① แพลตฟอร์มใช้รหัสที่เราไม่มี
  const ตามฐาน = new Map();    // รหัสฐาน → { ช่องทาง → Set(รหัสเต็ม) }

  for (const [code, tags] of Object.entries(listings)) {
    const ใช้จริง = (tags || []).filter((t) => ช่องทางที่เชื่อได้.has(t));
    if (!ใช้จริง.length) continue;

    if (!ourSkus.has(code)) {
      ไม่มีในคลัง.push({
        code,
        channels: ใช้จริง.sort(),
        // ถ้าตัดท้ายแล้วเจอรหัสที่เรามี = น่าจะพิมพ์ผิดหรือยังไม่เปิดชุด (ช่วยชี้ทาง)
        maybeBase: expandSku(code).slice(1).find((k) => ourSkus.has(k)) || null,
      });
    }

    const ฐาน = expandSku(code).slice(1).find((k) => ourSkus.has(k)) || code;
    const m = ตามฐาน.get(ฐาน) || new Map();
    for (const t of ใช้จริง) {
      const set = m.get(t) || new Set();
      set.add(code);
      m.set(t, set);
    }
    ตามฐาน.set(ฐาน, m);
  }

  // ② กลุ่มที่แต่ละแพลตฟอร์มใช้รหัสไม่เหมือนกัน
  const ไม่ตรงกันข้ามแพลตฟอร์ม = [];
  for (const [ฐาน, m] of ตามฐาน) {
    if (m.size < 2) continue;                       // ลงขายเจ้าเดียว = ไม่มีอะไรให้เทียบ
    const ต่อช่องทาง = [...m].map(([t, set]) => [t, [...set].sort()]);
    const ชุดแรก = JSON.stringify(ต่อช่องทาง[0][1]);
    if (ต่อช่องทาง.every(([, arr]) => JSON.stringify(arr) === ชุดแรก)) continue;  // ตรงกันหมด
    ไม่ตรงกันข้ามแพลตฟอร์ม.push({
      base: ฐาน,
      byChannel: Object.fromEntries(ต่อช่องทาง),
      /* เฉพาะรหัสที่ "บางเจ้ามี บางเจ้าไม่มี" — คือของที่ต้องตามเติม/ตามลบจริง ๆ */
      onlySome: (() => {
        const นับ = new Map();
        for (const [, arr] of ต่อช่องทาง) for (const c of arr) นับ.set(c, (นับ.get(c) || 0) + 1);
        return [...นับ].filter(([, n]) => n < ต่อช่องทาง.length).map(([c]) => c).sort();
      })(),
    });
  }

  // ③ รหัสในคลังที่ไม่ได้ลงขายที่ไหนเลย (ข้อมูลประกอบ ไม่ใช่ความผิดพลาด)
  const ลงขายอยู่ = new Set();
  for (const [code, tags] of Object.entries(listings)) {
    if ((tags || []).some((t) => ช่องทางที่เชื่อได้.has(t))) {
      ลงขายอยู่.add(code);
      for (const k of expandSku(code)) if (ourSkus.has(k)) ลงขายอยู่.add(k);
    }
  }
  const ไม่ได้ลงขายเลย = [...ourSkus].filter((s) => !ลงขายอยู่.has(s)).sort();

  return {
    ok: true,
    ขอบเขต: {
      ช่องทางที่ตรวจได้: [...ช่องทางที่เชื่อได้].sort(),
      รหัสบนแพลตฟอร์มที่นับ: Object.keys(listings).length,
      รหัสในคลัง: ourSkus.size,
      หมายเหตุ: "ช่องทางที่ตรวจไม่ได้รอบนี้ถูกกันออกทั้งหมด ไม่ได้นับเป็น 'ไม่ได้ลงขาย'",
    },
    สรุป: {
      ไม่มีในคลัง: ไม่มีในคลัง.length,
      ไม่ตรงกันข้ามแพลตฟอร์ม: ไม่ตรงกันข้ามแพลตฟอร์ม.length,
      ไม่ได้ลงขายเลย: ไม่ได้ลงขายเลย.length,
    },
    ไม่มีในคลัง: ไม่มีในคลัง.sort((a, b) => a.code.localeCompare(b.code)),
    ไม่ตรงกันข้ามแพลตฟอร์ม: ไม่ตรงกันข้ามแพลตฟอร์ม.sort((a, b) => a.base.localeCompare(b.base)),
    ไม่ได้ลงขายเลย,
  };
}
