/** วันนี้ตามเวลาไทย (`yyyy-mm-dd`) — ใช้ตัวนี้ ห้ามเขียน `+ 7 * 3600e3` เอง */
export function วันนี้ไทย() {
  return new Date(Date.now() + 7 * 3600e3).toISOString().slice(0, 10);
}

/** วันไทยของเวลา ms (epoch) — คู่กับ `thaiDayFromUtc` ที่รับสตริง */
export function วันไทยจากMs(ms) {
  return Number.isFinite(ms) ? new Date(ms + 7 * 3600e3).toISOString().slice(0, 10) : null;
}

