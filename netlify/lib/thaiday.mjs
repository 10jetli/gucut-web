/* 📅 แปลงเวลา UTC เป็น "วันไทย" — **แหล่งเดียวของทั้งท่อ** (สร้าง 18 ก.ย. 2569)
 *
 * 🔴 ที่มา: SQLite/D1 เขียนเวลาด้วย `datetime('now')` = **UTC** และชื่อช่องไม่บอกเขตเวลา
 *    ฝั่งจอเอาไปตัด 10 ตัวแรกเป็น "วัน" ⇒ ค่าที่เขียนช่วง **17:00–24:00 UTC ให้อายุแก่เกินจริง 1 วัน**
 *    (ฝั่งจอวัดเอง: 2026-09-17 20:30Z เดิมได้ 1 วัน ที่ถูกคือ 0)
 * 🔑 **ท่อรู้เขตเวลาของค่าตัวเอง ⇒ ท่อต้องเป็นฝ่ายบอก** จอไม่ควรต้องเดา
 *    และชื่อช่องที่ส่งออกไปต้องมี `TH` กำกับ — ของที่ต้องถามคือของที่ตั้งชื่อไม่ดี
 *
 * ⚠️ เดิมตัวแปลงนี้ถูกเขียนซ้ำ 3 ที่ (shopee-stock · core-purchases · core-products)
 *    ⇒ รวมมาที่เดียวตามกฎ "เกณฑ์/สูตรเดียวกันต้องมีแหล่งเดียว" [[one-threshold-one-source]]
 * ⚠️ อ่านไม่ออก = **null** ห้ามคืนวันนี้แทน — จอจะคิดว่าข้อมูลสดทั้งที่ไม่รู้
 * ⚠️ ใช้กับค่าที่เป็น **UTC เท่านั้น** · ค่าที่เป็นเวลาไทยอยู่แล้ว (เช่น order_date · stock_snapshots.day)
 *    ห้ามส่งเข้ามา เพราะจะบวก 7 ชม. ซ้ำแล้วเลื่อนวันผิด
 */
export function thaiDayFromUtc(utcish) {
  const s = String(utcish ?? "").trim();
  if (!s) return null;
  const ms = Date.parse(s.includes("T") ? s : `${s.replace(" ", "T")}Z`);
  return Number.isFinite(ms) ? new Date(ms + 7 * 3600e3).toISOString().slice(0, 10) : null;
}

