/** 🔒 สมการปิดของรอบกวาดดันสต็อก — **ที่เดียวในระบบที่เขียนสมการนี้ไว้**
 *
 *   planned = fired + not_sent + not_fired
 *   fired   = pushed + rejected          (เป๊ะเสมอ — ทุกแถวที่เข้ายิงได้ผลกลับมาหมด)
 *
 * · `not_sent`  = ถูกคัดออก **ก่อน** ยิง (stale_plan · needs_human · ด่านอื่น)
 * · `not_fired` = ยกไปรอบหน้าเพราะงบเวลา
 * 🚫 **`skipped` ห้ามเข้าสมการ** — มันคือแถวที่ถูกกรองออก**ก่อนเข้าแผน** (`แถว.length − p.push.length`)
 *    ไม่ได้อยู่ในตัวตั้ง `planned` ตั้งแต่ต้น ⇒ เอามาบวกคือนับซ้ำ
 *
 * 🔑 เหตุที่ต้องเป็นตัวคิด ไม่ใช่คอมเมนต์: เคยส่งสูตรผิดให้ฝั่งจอ
 *    (`notSent = fired − pushed − rejected` ซึ่ง **เป็น 0 ตลอดกาล** เพราะ fired = pushed + rejected เป๊ะ)
 *    สูตรที่เขียนไว้เฉย ๆ ไม่มีอะไรจับได้ว่าผิด · สูตรที่ถูกคิดทุกรอบจับได้ทันทีที่ไม่ลง
 *
 * ⚠️ **"ไม่รู้" ต้องไม่ถูกอ่านว่า "ไม่ผ่าน"** — รอบที่ไม่ได้ยิงเลย จะไม่มีค่า not_sent/not_fired
 *    ⇒ คืน `{ ตรวจได้: false }` **และต้องไม่มีคีย์ `ลง`** (กติกาเดียวกับ `inconclusive` ที่ตกลงกับฝั่งจอ)
 */
/* 🔴🔴 **ฝั่งจอประกบแล้วเจอรูที่ตัวคิดนี้มองไม่เห็น** (28 ก.ย. 2569)
 *    เขาปลูกที่ **ตัวเรียก**: เปลี่ยน `ผลยิง ? (… ?? null) : null` เป็น `?? 0 : 0` ทั้งสามช่อง
 *    ⇒ รอบที่ไม่ได้ยิงเลยจะได้ `0 = 0 + 0 + 0` ⇒ **"ไม่รู้" ถูกอ่านว่า "ลง"**
 *    ⇒ ด่านทั้ง 8 ตัวเขียว rc=0 หมด (เขาวัดเส้นฐานก่อนปลูกแล้วว่าเขียวอยู่ก่อนจริง)
 *    🔑 เหตุ: ตัวคิดตัดสินจาก **ตัวเลข** เท่านั้น ⇒ มันไม่มีทางรู้ว่า 0 นั้นคือ "วัดได้ศูนย์"
 *       หรือ "ไม่ได้วัด" — คลาส 0/null ที่ไล่กันมาทั้งวัน แต่คราวนี้อยู่ที่ **พารามิเตอร์**
 * ✅ แก้: รับ `ยิงแล้ว` เป็นข้อเท็จจริงแยกจากตัวเลข · ไม่ได้ยิง ⇒ **สรุปไม่ได้** ไม่ว่าตัวเลขจะลงหรือไม่
 *    และ `ยิงแล้ว` ที่ไม่ใช่ boolean ⇒ ถือว่าไม่รู้ (fail closed) ⇒ ผู้เรียกที่ลืมส่งจะได้ "สรุปไม่ได้"
 *    ไม่ใช่ "ผ่าน" ⇒ ท่าที่พลาดได้ง่ายที่สุดเป็นท่าที่ปลอดภัยที่สุด */
/* 🔴🔴🔴 **รอบที่สาม (28 ก.ย. 2569 เที่ยง) — ฝั่งจอวัดเจอว่ายังเหลืออีกครึ่งใบ**
 *    `ยิงแล้ว` ปิดเคส "ไม่ได้ยิงเลยแต่เลขเป็น 0" ได้จริง (เขายิงยืนยันแล้ว)
 *    **แต่เคส "ยิงจริง แล้วช่องใดช่องหนึ่งหาย" ยังหลุด**:
 *      `{ยิงแล้ว:true, planned:5, fired:5, not_sent:0, not_fired:0}` ⇒ `ลง:true` 🔴
 *    ⇒ วันที่มีคนเขียน `?? 0` ที่ตัวเรียก (ท่าที่คนพิมพ์บ่อยที่สุด) สมการจะ "ลง" ด้วยเลขที่แต่งขึ้น
 *      และ **ไม่มีด่านไหนมองเห็นตัวเรียก**
 *
 * ✅ ทางที่เลือก (ข้อเสนอที่สองของฝั่งจอ): **เลิกเชื่อผู้เรียก — รับก้อนผลยิงทั้งก้อน**
 *    ผู้เรียกส่ง `ผลยิง` (ตัวก้อนที่ตัวยิงคืนมา) แล้วตัวคิด **อ่านช่องเอง**
 *    ⇒ ไม่มีช่องให้ผู้เรียกแปลงค่า `null` เป็น `0` ระหว่างทางอีกเลย
 *    ⇒ และตัวยิงต้องประกาศความครบของตัวเอง (`ครบ: true`) · ไม่ประกาศ ⇒ **สรุปไม่ได้**
 *    🔑 หลักเดียวกับ `ยิงแล้ว`: **ท่าที่ผู้เรียกพลาดง่ายที่สุด ต้องเป็นท่าที่ปลอดภัยที่สุด**
 *    🔑 และทดสอบได้ด้วย **พฤติกรรม** ไม่ต้องตรึงรูปโค้ดของตัวเรียก (ข้อเสียของทางเลือกแรก)
 *
 * รูปที่รับ: `ตรวจสมการรอบกวาด({ planned, ผลยิง })`
 *   · `ผลยิง` เป็น null/undefined ⇒ รอบนี้ไม่ได้ยิง ⇒ สรุปไม่ได้
 *   · `ผลยิง.ครบ !== true`       ⇒ ตัวยิงไม่ยืนยันว่านับครบ ⇒ สรุปไม่ได้
 *   · ช่องใดไม่ใช่ตัวเลขจำกัด    ⇒ สรุปไม่ได้ (ไม่ใช่ "ไม่ผ่าน")
 */
export function ตรวจสมการรอบกวาด({ planned, ผลยิง } = {}) {
  const สมการ = "planned = fired + not_sent + not_fired";
  const ไม่รู้ = (เหตุ) => ({ ตรวจได้: false, เหตุ, สมการ });

  if (ผลยิง === null || ผลยิง === undefined)
    return ไม่รู้(
      "รอบนี้ไม่ได้ยิงเลย ⇒ ไม่มีตัวเลขให้ปิดสมการ (ไม่ใช่ว่าไม่ผ่าน) · " +
        "⚠️ ถึงตัวเลขจะเป็น 0 ทุกช่องแล้วสมการ 'ลง' ก็ห้ามอ่านว่าผ่าน"
    );
  if (typeof ผลยิง !== "object")
    return ไม่รู้(`ผลยิง ต้องเป็นก้อนผลของตัวยิง (ได้ ${typeof ผลยิง}) ⇒ สรุปไม่ได้`);
  if (ผลยิง.ครบ !== true)
    return ไม่รู้(
      `ตัวยิงไม่ได้ประกาศว่านับครบ (ครบ = ${String(ผลยิง.ครบ)}) ⇒ สรุปไม่ได้ · ` +
        "ช่องนี้ต้องถูกติดตอนก้อนผลถูกปิด ไม่ใช่ตอนผู้เรียกส่งต่อ"
    );

  const เลข = (v) => (typeof v === "number" && Number.isFinite(v) ? v : null);
  const p = เลข(planned);
  const f = เลข(ผลยิง.fired);
  const ns = เลข(ผลยิง.notSent);
  const nf = เลข(ผลยิง.ไม่ได้ยิง);
  const ขาด = [["planned", p], ["fired", f], ["notSent", ns], ["ไม่ได้ยิง", nf]]
    .filter(([, v]) => v === null)
    .map(([k]) => k);
  if (ขาด.length)
    return ไม่รู้(`ยังไม่รู้ค่า: ${ขาด.join(", ")} ⇒ รอบนี้พิสูจน์สมการไม่ได้ (ไม่ใช่ว่าไม่ผ่าน)`);

  const ผลรวม = f + ns + nf;
  return {
    ตรวจได้: true,
    ลง: p === ผลรวม,
    สมการ,
    ...(p === ผลรวม
      ? {}
      : {
          ต่างกัน: p - ผลรวม,
          "⚠️ สมการไม่ลง":
            `planned ${p} ≠ fired ${f} + not_sent ${ns} + not_fired ${nf} = ${ผลรวม}` +
            " ⇒ มีแถวที่หลุดออกจากทั้งสามกอง หรือถูกนับสองกอง · ห้ามอ่านตัวเลขรอบนี้ว่าครอบคลุมครบ",
        }),
  };
}
