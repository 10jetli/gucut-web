/* 🕰️ ติดหัว "ยุคของท่อ" ให้คำตอบที่ยังไม่มี — **ตาข่ายชั้นโครงสร้าง ไม่ใช่ชั้นวินัย**
 *
 * 🔴 ที่มา 21 ก.ย. 2569 — ผมเจอว่า `?ping=1` เป็นเส้นเดียวที่ไม่มีหัว `x-core-build`
 *    (และมันคือเส้นที่คนใช้เช็คยุคมากที่สุดเพราะไม่ต้องมีรหัส) ⇒ หัวหาย = อ่านว่า "ท่อรุ่นเก่า"
 *    = **แดงลวงทิศเดียวกับปัญหาที่หัวนี้มีไว้แก้** [[probe-fails-toward-alarm]]
 *    ⇒ รอบแรกผมแก้แบบ **ตั้งรับ**: ไล่ใส่ทีละจุดครบ 6 จุด + ด่านเพดาน 0 กันหลุดซ้ำ
 *
 * 🔑 **แล้วฝั่งจอทำเรื่องเดียวกันด้วยท่าที่ดีกว่า** (`cbb05c8`): middleware ของเขามีทางออก **11 ทาง**
 *    เขาจึง **ห่อที่เดียว** แทนการไล่ใส่ทีละ `return` ด้วยเหตุผลตรงประเด็น:
 *    *"วันหน้ามีคนเพิ่มทางออกที่ 12 แล้วลืม ⇒ หัวหายเฉพาะบางเส้น"*
 *    ⇒ ⇒ ผมรับท่านั้นมาใช้ฝั่งนี้ด้วย: ตัวห่อชั้นนอกสุดเติมหัวให้คำตอบที่ยังไม่มี
 *    ⇒ **ด่านเพดาน 0 ยังอยู่** แต่เปลี่ยนบทบาทจาก "กำแพงหลักเดียว" เป็น **ตาข่ายชั้นสอง**
 *    🔑 คลาส: **ตาข่ายที่พึ่งคนจำได้ จะพังวันที่คนใหม่เพิ่มทางออก** — ท่าที่ถูกคือทำให้ลืมไม่ได้
 *
 * ⚠️ ค่าใช้จ่าย: ห่อใหม่ **เฉพาะคำตอบที่ยังไม่มีหัว** ⇒ หลังแก้ครบแล้วแทบไม่มีการห่อเลย
 *    (ถ้าห่อทุกคำตอบ = จ่ายค่าคัดลอก body ฟรี ๆ ทุกคำขอ [[guard-after-the-cost]])
 * ⚠️ 204/304 **ห้ามมี body** ⇒ ต้องส่ง `null` ไม่ใช่ `res.body` ไม่งั้นรันไทม์โยน error
 */

/** คืนคำตอบเดิมถ้ามีหัวแล้ว · ไม่มี ⇒ คืนตัวใหม่ที่เหมือนเดิมทุกอย่าง + หัวยุค
 *  @param {Response} res
 *  @param {string} build ค่าที่จะใส่ — **ว่าง ⇒ ไม่ใส่** (ส่งค่าว่างแย่กว่าไม่ส่ง: จอจะอ่านว่ามีหัวแล้วแต่ไม่มีค่า)
 */
export function ติดหัวยุคถ้าขาด(res, build) {
  if (!res || typeof res !== "object" || typeof res.headers?.get !== "function") return res;
  if (!build) return res;
  if (res.headers.get("x-core-build")) return res;
  /* 🔴 **ตาข่ายห้ามล้มท่อ — และทางที่มันล้มได้มีจริง** (เจอตอนเขียนเทสนี้เอง 21 ก.ย. 2569)
     ค่าหัว HTTP ต้องเป็น ByteString (Latin-1) ⇒ ใส่อักขระไทยลงไปจะโยนทันที:
     *"Cannot convert argument to a ByteString … value of 3586"*
     ⇒ ⇒ วันไหน build stamp เพี้ยนเป็นข้อความอื่น (หรือมีคนส่งค่าไทยมา)
        ตาข่ายที่ตั้งใจ "ทำให้ลืมไม่ได้" จะกลายเป็น **ตัวที่ทำให้ทุกคำตอบพัง**
     🔑 คลาส: ตาข่ายที่ล้มเอง อันตรายกว่าไม่มีตาข่าย ⇒ พังแล้ว **ต้องคืนของเดิม** */
  try {
    const หัว = new Headers(res.headers);
    หัว.set("x-core-build", build);
    const ไม่มีbodyได้ = res.status === 204 || res.status === 304 || res.status === 101;
    return new Response(ไม่มีbodyได้ ? null : res.body, {
      status: res.status,
      statusText: res.statusText,
      headers: หัว,
    });
  } catch {
    return res;
  }
}
