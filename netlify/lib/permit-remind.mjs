/** ขั้นที่ต้องตามเตือน — ขั้นอื่นเป็นหน้าที่ร้านหรือจบแล้ว */
const NUDGE = Object.keys(MESSAGE);

/** ขั้นที่ **ทวงได้ครั้งเดียวต่อเรื่อง** (ใบสั่ง 25 ต.ค. 2569: "ทวงครั้งเดียวต่อใบ ติดธงในบันทึก")
 *
 *  🔴 เหตุที่ขั้นนี้ต่างจากขั้นอื่น: ขั้นอื่นคือ "ของอยู่ในมือคุณแล้ว ส่งมาให้ร้าน" ⇒ ทวงซ้ำได้ผล
 *     ขั้น `printed` คือ "ต้องหาวันว่างไปอำเภอ/จังหวัด" ⇒ ทวงซ้ำไม่ได้ทำให้เขาว่างขึ้น
 *     มีแต่ทำให้รำคาญ ⇒ **โดนบล็อก LINE = เสียช่องทางถาวร** (เสียมากกว่าที่ได้)
 *  🔑 ด่านของขั้นนี้คือ **ธงรายขั้น** (`remindedStages`) ไม่ใช่ `remindCount`/`lastRemind`
 *     (สองตัวนั้นเป็นงบรวมของเรื่อง ⇒ ถ้าเอามาเป็นด่าน ขั้นนี้จะกลับมาทวงอีกเมื่องบรีเซ็ต) */
const ONCE_ONLY = new Set(["printed"]);

export async function runReminders() {
  const s = store();
  /* 🔴 **B24 (แก้ 4 ต.ค. 2569)** — ของเดิมกลืน `list()` ที่ล้มเป็น `blobs: []`
     ⇒ รอบนั้น **ไม่เตือนใครเลย** แล้วรายงานกลับว่าทำงานปกติ (pushed 0 · forShop 0)
     ⇒ ลูกค้าที่รอใบ ลซ.๒ ไม่ได้รับการตามเตือน และไม่มีใครรู้ว่าพลาดไปรอบไหน
     🔑 "ไม่มีใครต้องเตือน" กับ "อ่านรายชื่อไม่ได้" ให้ผลเหมือนกันเป๊ะ ⇒ ต้องแยก
        ⇒ โยน ให้ผู้เรียกจดว่ารอบนี้ทำไม่ได้ (ดีกว่าจดว่าทำแล้ว) */
  const คีย์ = await อ่านรายชื่อคีย์(s, "c/", "ตามเตือนทะเบียน");
  const blobs = คีย์.map((key) => ({ key }));

  const pushed = [];
  const forShop = [];
  /* 🔴 **B24 ภาคสอง (12 ต.ค. 2569)** — รอบ 4 ต.ค. แก้ **ขาอ่านรายชื่อ** (list ล้ม ⇒ โยน)
     แต่ **ขาอ่านรายแถว** ยังกลืนเหมือนเดิม: `.catch(() => null)` แล้ว `continue`
     ⇒ เรื่องที่อ่านไม่ได้ถูกนับเป็น **"ไม่ต้องเตือน"** เงียบ ๆ
     ⇒ และรายงานคืน `checked: blobs.length` ⇒ **นับรวมแถวที่อ่านไม่ได้ว่าตรวจแล้ว**
     🔑 คลาสเดียวกับที่ `อ่านทุกแถว()` ใน `blob-keys.mjs` แก้ไว้แล้ว — ไฟล์นี้ใช้แค่ครึ่งเดียว
        (ยืมแต่ `อ่านรายชื่อคีย์` ไม่ได้ยืมตัวนับ `unreadable`)
     ⚠️ ที่นี่ยืม `อ่านทุกแถว()` มาตรง ๆ ไม่ได้ เพราะลูปต้องใช้ **คีย์** เขียนกลับ
        (`s.setJSON(b.key, rec)`) ส่วนตัวนั้นคืนแต่ตัวแถว ⇒ จึงนับเองด้วยกติกาเดียวกัน
        📌 ถ้าวันไหนมีคนที่สามต้องการทั้งคีย์และตัวนับ ให้เพิ่มทางเลือกคืนคีย์ใน `อ่านทุกแถว()`
           **ไม่ใช่ลอกลูปนี้เป็นสำเนาที่สาม** */
  let อ่านแถวไม่ได้ = 0;

  for (const b of blobs) {
    let rec = null;
    let อ่านได้ = true;
    try { rec = await s.get(b.key, { type: "json" }); }
    catch { อ่านได้ = false; }
    if (!อ่านได้) { อ่านแถวไม่ได้++; continue; }
    if (!rec || !NUDGE.includes(rec.stage)) continue;

    // นับจากตอนที่เข้าขั้นนี้ ไม่ใช่ตอนเปิดเรื่อง
    const since = rec.history?.[rec.stage] || rec.updatedAt || rec.at;
    const waited = days(since);
    if (waited < WAIT_DAYS) continue;

    /* 🔴 ขั้นที่ทวงครั้งเดียว: ธงรายขั้นเป็นด่าน **ตัวเดียว** และมาก่อนด่านงบรวม
       (ติดธงแล้ว = จบ · ยังไม่ติดธง = ส่งได้ ไม่ต้องรอ REPEAT_DAYS ของเรื่องอื่น) */
    const ทวงครั้งเดียว = ONCE_ONLY.has(rec.stage);
    if (ทวงครั้งเดียว && rec.remindedStages?.[rec.stage]) continue;

    const sent = rec.remindCount || 0;
    if (!ทวงครั้งเดียว) {
      if (sent >= MAX_REMINDS) continue;
      if (rec.lastRemind && days(rec.lastRemind) < REPEAT_DAYS) continue;
    }

    const msg = MESSAGE[rec.stage];
    const link = `${SITE_URL}/permit/`;
    const reached = [];

    // ---- ชั้น 1: LINE
    // ⚠️ อ่าน userId จากบัญชีลูกค้า ไม่ได้เก็บซ้ำไว้ในตัวเรื่อง
    //    เก็บซ้ำเมื่อไหร่ = วันที่ลูกค้าเปลี่ยน LINE แล้วสองที่ไม่ตรงกัน
    let lineId = "";
    try {
      const u = await usersStore().get(`u/${rec.phone}`, { type: "json" });
      lineId = u?.social?.line?.id || "";
    } catch { /* อ่านบัญชีไม่ได้ก็ข้ามชั้นนี้ไป */ }

    if (lineId) {
      const r = await linePush(lineId, `${msg.title}\n${msg.body}`, link).catch(() => "error");
      if (r === "sent") reached.push("LINE");
      else if (r === "blocked") reached.push("LINE ส่งไม่ได้ (ยังไม่ได้เพิ่มเพื่อน)");
      /* 🔴 **B24 ภาคสอง** — ของเดิมตกกรณีอื่นทิ้งเงียบ ("error" หรือค่าที่ไม่รู้จัก)
         ⇒ ร้านเห็น "ไม่ถึงเลย" เหมือนกรณีที่ลูกค้าไม่มี LINE ซึ่งคนละเรื่องกันโดยสิ้นเชิง
         (ลูกค้ามี LINE อยู่ แต่เรายิงไม่ออก ⇒ ลองใหม่ได้ · ไม่มี LINE ⇒ ต้องโทร) */
      else reached.push(`LINE ยิงไม่ออก — ยังไม่รู้ผล (${String(r).slice(0, 20)})`);
    }

    // ---- ชั้น 2: Web Push
    /* 🔴 **B24 ภาคสอง** — `pushToUser` คืน `null` = **ยังไม่รู้ว่าส่งถึงไหม** (แก้ไว้ใน B11 วันนี้)
       ของเดิม `.catch(() => 0)` + `if (n)` ยุบ **null · 0 · ข้อผิดพลาด** เป็น "ไม่ถึง" ก้อนเดียว
       ⇒ ⇒ ขาผลิตบอกความจริงแล้ว แต่ **ขาใช้โยนข้อมูลนั้นทิ้ง** ⇒ ร้านอ่านว่า "ไม่ถึงเลย"
          ทั้งที่ความจริงคือ "อ่านรายชื่อเครื่องไม่ได้" ⇒ ร้านโทรตามฟรี หรือแย่กว่า: ไปตั้งค่าใหม่ */
    let n = null;
    try { n = await pushToUser(rec.phone, { title: msg.title, body: msg.body, url: "/permit/" }); }
    catch { n = null; }
    if (n === null) reached.push("แจ้งเตือนมือถือ — **ยังไม่รู้ผล** (อ่านรายชื่อเครื่องไม่ได้)");
    else if (n) reached.push("แจ้งเตือนมือถือ");

    rec.lastRemind = new Date().toISOString();
    rec.remindCount = sent + 1;
    /* 🔑 **ธงรายขั้น** — จดไว้ทุกขั้น ไม่ใช่แค่ขั้นที่ทวงครั้งเดียว
       ① ขั้น `printed` ใช้เป็นด่านกันทวงซ้ำ (ใบสั่งข้อ [ค])
       ② ขั้นอื่นได้ประโยชน์ด้วย: หน้าหลังร้านจะบอกได้ว่า "ขั้นนี้ทวงไปเมื่อไหร่"
          ซึ่ง `lastRemind` ก้อนเดียวบอกไม่ได้ (มันคือครั้งล่าสุดของทั้งเรื่อง ข้ามขั้นได้)
       ⚠️ เขียนทับไม่ได้ ⇒ ใช้การรวมออบเจกต์ ไม่ใช่ตั้งค่าใหม่ทั้งก้อน */
    rec.remindedStages = { ...(rec.remindedStages || {}), [rec.stage]: rec.lastRemind };
    /* 🔴 เขียนธงไม่สำเร็จ ⇒ **ห้ามนับว่าทวงแล้ว** สำหรับขั้นที่ทวงครั้งเดียว
       (กลืน error แล้วรายงานว่าส่งแล้ว ⇒ รอบหน้าจะทวงซ้ำ เพราะธงไม่เคยลง
        ⇒ ลูกค้าโดนทวงรัว ซึ่งเป็นสิ่งเดียวที่ใบสั่งห้ามไว้ตรง ๆ) */
    let ธงลง = true;
    try { await s.setJSON(b.key, rec); } catch { ธงลง = false; }

    // ---- ชั้น 3: บอกร้านเสมอ พร้อมบอกว่าถึงทางไหนบ้าง
    // ⚠️ ต้องบอกด้วยว่า "ไม่ถึงเลย" เพื่อให้ร้านรู้ว่าต้องโทรเอง
    //    ถ้าเขียนแค่รายชื่อ ร้านจะเดาว่าระบบเตือนไปแล้วเรียบร้อย
    const how = reached.length ? reached.join(" · ") : "ไม่ถึงเลย — ต้องโทรตามเอง";
    /* ⚠️ โชว์ **รหัสขั้นดิบ** อย่างเดียวตามเดิม — ไม่เอาตารางคำแปลขั้นมาไว้ที่นี่
       (คำแปลของจริงอยู่ที่ `src/lib/permit.ts` ซึ่งไฟล์ .mjs import ตรง ๆ ไม่ได้
        ⇒ เขียนตารางที่สองที่นี่ = วันที่ใครแก้คำแปล สองที่จะไม่ตรงกันเงียบ ๆ) */
    forShop.push(
      `${rec.name || "-"} · ${rec.phone} — ค้าง "${rec.stage}" มา ${Math.floor(waited)} วัน\n   ↳ ${how}`
      + (ทวงครั้งเดียว ? "\n   ↳ ขั้นนี้ทวงครั้งเดียวต่อเรื่อง — ครั้งต่อไปต้องโทร/ทักเอง" : "")
      + (ธงลง ? "" : "\n   ↳ ⚠️ **จดธงไม่สำเร็จ** รอบหน้าอาจทวงซ้ำ — ดูที่เรื่องนี้ด้วย"),
    );
    if (reached.length) pushed.push(rec.phone);
  }

  // ⚠️ ไม่มีใครค้าง = ไม่ต้องส่งอะไรเข้ากลุ่ม
  //    ส่ง "วันนี้ไม่มีใครค้าง" ทุกวัน คนจะเลิกอ่านข้อความจากบอตนี้ไปเลย
  if (forShop.length) {
    await tell(
      `🔔 <b>ลูกค้าค้างเรื่องขอทะเบียน ${forShop.length} ราย</b>\n` +
      `ทักไลน์หรือโทรตามได้เลย\n\n` +
      forShop.join("\n"),
    );
  }

  /* ⚠️ `อ่านแถวไม่ได้` ต้องอยู่ในคำตอบ **แม้เป็น 0** — ไม่มีช่อง ≠ ไม่มีปัญหา
     (กติกาเดียวกับ `unreadable` ใน `blob-keys.mjs`) · และ `checked` ต้องไม่นับแถวที่อ่านไม่ได้
     ไม่งั้นรายงานจะบอกว่าตรวจครบทั้งที่บางเรื่องไม่เคยถูกเปิดอ่าน */
  return {
    checked: blobs.length - อ่านแถวไม่ได้,
    อ่านแถวไม่ได้,
    nudged: forShop.length,
    pushed: pushed.length,
  };
}

