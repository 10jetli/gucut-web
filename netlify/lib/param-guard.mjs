            "(วัดได้ 16 ต.ค. 2569: 1,750 วัน ⇒ 500 ที่ 16.5 วินาที · 654 วัน ⇒ 200 ที่ 7.7 วินาที) ⇒ " +
            `แบ่งเป็นช่วงละไม่เกิน ${เพดานวัน} วัน` +
            (รหัสสินค้า ? " หรือถอด `product=` ออกเพื่อขอช่วงได้ถึง 731 วัน" : "")
