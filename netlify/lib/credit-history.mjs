/** ISO พร้อมโซนเวลา จาก epoch ms — คืน `null` เมื่อไม่มีค่า
 *  🚫 **ห้ามคืนเวลาปัจจุบันแทนเมื่อไม่มีตัวอย่าง** (ฝั่งจอกำชับ) — จอจะเห็นว่าสดตลอดกาล
 *  🚫 **ห้ามส่งเป็น "อายุกี่ชั่วโมง"** — ค่าที่คิดจากเวลาปัจจุบันจะเก่าเงียบ ๆ ทันทีที่คำตอบถูกแคช
 *     ⇒ ส่งเวลาดิบ ให้จอคิดอายุเองตอนวาด */
export function เวลาISO(ms) {
  const n = Number(ms);
  if (!Number.isFinite(n) || n <= 0) return null;
  return new Date(n).toISOString();   // ลงท้าย Z = UTC · จอบวก 7 แล้วเขียนกำกับว่าเวลาไทยเอง
}
