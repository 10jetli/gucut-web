      cron,
      "รอบต่อวันตามตาราง": ต่อวัน,
      "แถวที่มี": rs.length,
      "รอบที่ควรมีในช่วง": ควรมีในช่วง,
      /* 🔑 ครอบคลุม < 1 = มีรอบที่ **ไม่ได้จดเลย** ⇒ น่าจะถูกตัดตายที่เพดาน หรือ deploy ทับกลางช่วง
         🔴 **แก้ 20 ก.ย. 2569 — บรรทัดนี้เคยเขียนว่า "> 1 … ไม่ใช่ความผิด" ซึ่งทำให้ไม่มีตาข่ายฝั่งเกิน**
            ฝั่งจอยิงอ่านแล้วเจอ `returns-sync` **ครอบคลุม 1.75 · ok ทั้ง 14 แถว** นั่งอยู่ในคำตอบเฉย ๆ
            ⇒ cron ว่า 8 รอบ/วัน แต่มี 14 แถว ⇒ **มีตัวเรียกอยู่นอกตาราง** (หรือ cron ไม่ใช่ของจริง)
            ⇒ ⇒ **โมเดลต้นทุนที่คิดจาก cron จะต่ำกว่าความจริงเสมอ** — ไม่ใช่เรื่องเล็ก
         🔑 คลาส: **ตัวเลขที่มีเกณฑ์ข้างเดียว = ไม่มีตาข่ายอีกข้างหนึ่ง** ⇒ ฝั่งนั้นเขียวตลอดกาล
            และคอมเมนต์ที่เขียนว่า "ไม่ใช่ความผิด" **ทำหน้าที่เป็นคำสั่งให้คนมองข้าม** */
