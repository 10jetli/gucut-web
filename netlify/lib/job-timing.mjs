/** รอบต่อวันจากสตริง cron — **คืน `null` เมื่อรูปแบบไม่รองรับ ห้ามเดา**
 *  รองรับเท่าที่งานของร้านใช้จริง: ตัวเลข · `*` · `*​/n` ในช่องนาที/ชั่วโมง และวัน/เดือน/สัปดาห์ต้องเป็น `*`
 *  🚫 เดาไม่ได้แล้วคืนเลขมั่ว = ตัวหารของ "นาที/วัน" ผิดทั้งตาราง โดยหน้าตาเหมือนคำตอบสมบูรณ์ */
export function รอบต่อวันจากcron(cron) {
  const f = String(cron || "").trim().split(/\s+/);
  if (f.length !== 5) return null;
  const [นาที, ชั่วโมง, วัน, เดือน, สัปดาห์] = f;
  if (วัน !== "*" || เดือน !== "*" || สัปดาห์ !== "*") return null;
  const นับ = (ช่อง, ทั้งหมด) => {
    if (ช่อง === "*") return ทั้งหมด;
    const step = /^\*\/(\d+)$/.exec(ช่อง);
    if (step) {
      const n = Number(step[1]);
      return n > 0 ? Math.ceil(ทั้งหมด / n) : null;
    }
    if (/^\d+(,\d+)*$/.test(ช่อง)) return ช่อง.split(",").length;
    return null;
  };
  const m = นับ(นาที, 60);
  const h = นับ(ชั่วโมง, 24);
  return m == null || h == null ? null : m * h;
}

const กลาง = (a) => {
  if (!a.length) return null;
  const s = [...a].sort((x, y) => x - y);
  return s[Math.floor(s.length / 2)];
};

/** 🪟 **แปลค่า `hours` ที่ขอมา — และ *ประกาศ* เมื่อไม่ได้ใช้ค่านั้น**
 *
 * 🔴 ของจริง 20 ก.ย. 2569 ค่ำ — ผมยิง `?jobtiming=1&hours=0.5` เพื่อหาเวลาของแถว
 *    `Number.parseInt("0.5")` = 0 ⇒ `|| 24` ⇒ **ถอยไป 24 ชม. เงียบ ๆ**
 *    ⇒ ⇒ ได้ **17 แถว** กลับมา ซึ่งหน้าตาเหมือน "มี 17 แถวใน 30 นาที" = **การค้นพบใหญ่ที่เป็นเท็จ**
 *    และ `hours=1.5` ก็กลายเป็น 1 โดยไม่บอก ⇒ คนวัดจะเทียบเลขคนละหน้าต่างกันโดยไม่รู้ตัว
 * 🔑 คลาส: **ทางถอยที่ไม่ประกาศตัว** [[fallbacks-must-announce]] — และมันอยู่ใน
 *    **เส้นที่ทั้งสองบัญชีใช้วัดเรื่องนี้อยู่** ⇒ ผลวัดทุกตัวที่ผ่านมาต้องอ่านคู่กับค่านี้
 * 🚫 ห้ามแก้เป็น "รับทศนิยม" — ตัวอ่านใช้หน่วยชั่วโมงเต็มใน SQL · รับแล้วต้องแก้ทั้งเส้น
 *    ⇒ ทางที่ถูกตอนนี้: ใช้ค่าที่ปัดแล้ว **แต่บอกออกมาว่าปัด**
 */
export function ตีความชั่วโมง(ค่า) {
  if (ค่า === undefined || ค่า === null || ค่า === "") return { ชม: 24, ปรับเพราะ: null };
  const ดิบ = String(ค่า).trim();
  const n = Number(ดิบ);
  if (!Number.isFinite(n)) return { ชม: 24, ปรับเพราะ: `อ่าน "${ดิบ}" เป็นตัวเลขไม่ได้ ⇒ ใช้ 24` };
  if (!Number.isInteger(n)) return { ชม: Math.min(168, Math.max(1, Math.round(n))), ปรับเพราะ: `"${ดิบ}" ไม่ใช่ชั่วโมงเต็ม ⇒ ปัดเป็น ${Math.min(168, Math.max(1, Math.round(n)))}` };
  if (n < 1) return { ชม: 1, ปรับเพราะ: `"${ดิบ}" น้อยกว่า 1 ⇒ ใช้ 1` };
  if (n > 168) return { ชม: 168, ปรับเพราะ: `"${ดิบ}" เกิน 168 (7 วัน) ⇒ ใช้ 168` };
  return { ชม: n, ปรับเพราะ: null };
}

/** อ่านการกระจายเวลาของงานตามเวลา — **อ่านอย่างเดียว ไม่ยิงงานใด** */
