/** ครอบ handler ของงานตามเวลา **ทั้งตัว** — แก้ไฟล์ละบรรทัดเดียว
 *  `export default ครอบงานตามเวลา("beam-sweep", handler)`
 *
 *  🔑 ทำไมต้องมีตัวนี้ ทั้งที่มี `วัดเวลางาน` อยู่แล้ว: งานตามเวลาแต่ละตัวมีโครงข้างในไม่เหมือนกัน
 *     (บางตัวจับ error เอง บางตัวมี try ซ้อนสามชั้น) ⇒ แทรกทีละตัวคือแก้ของที่ทำงานอยู่ 5 ที่
 *     ⇒ ครอบข้างนอกได้ **เวลารวมของรอบ ซึ่งคือสิ่งที่กินงบฟังก์ชันจริง** และแตะโค้ดเดิมน้อยที่สุด
 *
 *  🚫 **ห้ามตัดสินผลจาก HTTP status เอง** — งานหลายตัวตอบ 200 พร้อมคีย์ `error` ข้างใน
 *     ⇒ ถ้าเดาว่า 200 = สำเร็จ สมุดจะเต็มไปด้วย `ok` ปลอม ซึ่งแย่กว่าไม่รู้
 *     ⇒ ค่าปริยายคือ **`ไม่ได้ตัดสิน`** และเก็บ status ไว้ใน `note` ให้คนอ่านตีความเอง
 *     ⇒ ตัวไหนอยากได้ผลจริง ส่ง `ตัดสินผล` มา (ต้องอ่านจากเนื้อคำตอบของตัวเอง)
 *  ⚠️ `ms` ที่ได้คือ **เวลาของ handler** ไม่รวมเวลาที่ Netlify ใช้ปลุกฟังก์ชัน (cold start)
 *     ⇒ ต่ำกว่าเวลาที่ถูกคิดเงินเล็กน้อยเสมอ — เขียนกำกับไว้เพื่อไม่ให้ใครเอาไปเทียบตรง ๆ กับบิล
 */
export function ครอบงานตามเวลา(ชื่องาน, fn, { ตัดสินผล = null } = {}) {
  return async (...args) => {
    const t = await วัดเวลางาน(ชื่องาน, () => fn(...args), {
      ตัดสินผล,
      อธิบาย: (r) => (r && typeof r.status === "number" ? `HTTP ${r.status}` : null),
    });
    if (t.จดเวลา !== "ok") console.log(`⏱️ จดเวลา ${ชื่องาน} ไม่ได้: ${t.จดเวลา}`);
    return t.ผลลัพธ์;
  };
}
