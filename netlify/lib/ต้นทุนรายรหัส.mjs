/** ถัวเฉลี่ยถ่วงน้ำหนักจากใบซื้อ — `{sku: {ต้นทุน, ล็อต, จำนวนรวม, ใบล่าสุด}}`
 *  🔴 ไม่นับใบที่ยกเลิก (`Voided`) — ตามที่รายงานยอดซื้อของเราทำอยู่แล้ว
 *  🔴 ตัดบรรทัดที่ `qty <= 0` หรือ `price IS NULL` ออก — บรรทัดที่ไม่มีราคาจะถ่วงค่าเฉลี่ยลงเป็นศูนย์
 *     (คนละเรื่องกับราคา 0 ที่ตั้งใจ ซึ่งเราก็ยังตัดออก เพราะใบซื้อราคา 0 คือของแถม ไม่ใช่ต้นทุน) */
/** ล็อตของเข้าที่บันทึกต้นทุนไว้เอง (`stock_moves.unit_cost`) — `{sku: {มูลค่า, จำนวน, ล็อต}}`
 *  🔴 **ต้องมี ไม่ใช่ของแถม** — ขั้นที่ 3 เพิ่มช่อง `unit_cost` ให้ใบของเข้า แต่ตัวคิดต้นทุน
 *     (ไฟล์นี้) อ่านแต่ใบซื้อกับทะเบียนสินค้า ⇒ ค่าที่คนกรอกจะ **ไม่มีผลกับอะไรเลย**
 *     = ช่องที่เขียนลงได้แต่ไม่มีใครอ่าน · เจอ 4 ต.ค. 2569 ตอนจะทำวงทดสอบ เขียน→อ่าน→ลบ
 *  🔴 เอาเฉพาะ **เหตุผลที่เป็นของเข้า** และ `unit_cost IS NOT NULL`
 *     (NULL = ไม่ได้บอกต้นทุน · เอามาเฉลี่ยจะถ่วงลงเป็นศูนย์) · qty > 0 เท่านั้น */
async function จากใบของเข้า() {
  const rows = await coreQuery(
    `SELECT sku,
            SUM(qty * unit_cost) AS มูลค่า,
            SUM(qty)             AS จำนวนรวม,
            COUNT(*)             AS ล็อต,
            MAX(at)              AS ใบล่าสุด
     FROM stock_moves
     WHERE unit_cost IS NOT NULL AND qty > 0
       AND reason IN (${เหตุผลที่รับต้นทุนได้.map((r) => `'${r}'`).join(",")})
     GROUP BY sku`
  );
  const m = new Map();
  for (const r of rows || []) {
    const q = Number(r?.จำนวนรวม);
    const v = Number(r?.มูลค่า);
    if (!Number.isFinite(q) || q <= 0 || !Number.isFinite(v)) continue;
    m.set(String(r.sku), { มูลค่า: v, จำนวน: q, ล็อต: Number(r.ล็อต) || 0, ใบล่าสุด: r.ใบล่าสุด ?? null });
  }
  return m;
}

async function จากใบซื้อ(store = "z1") {
  const rows = await coreQuery(
    `SELECT i.sku AS sku,
            SUM(i.qty * i.price) AS มูลค่า,
            SUM(i.qty)           AS จำนวนรวม,
            COUNT(*)             AS ล็อต,
            MAX(po.po_date)      AS ใบล่าสุด
     FROM purchase_order_items_v2 i
     LEFT JOIN purchase_orders_v2 po ON po.id = i.po_id
     WHERE i.source = ? AND COALESCE(po.status,'') <> 'Voided'
       AND i.qty > 0 AND i.price IS NOT NULL AND i.price > 0
     GROUP BY i.sku`,
    [store]
  );
  const m = new Map();
  for (const r of rows || []) {
    const q = Number(r?.จำนวนรวม);
    const v = Number(r?.มูลค่า);
    if (!Number.isFinite(q) || q <= 0 || !Number.isFinite(v)) continue;
    m.set(String(r.sku), { มูลค่า: v, จำนวน: q, ล็อต: Number(r.ล็อต) || 0, ใบล่าสุด: r.ใบล่าสุด ?? null });
  }
  return m;
}

/** รวม "ต้นทุนที่จ่ายจริง" สองแหล่งเป็นถัวเฉลี่ยถ่วงน้ำหนักเดียว
 *  🔑 ถ่วงด้วย **จำนวน** ไม่ใช่เฉลี่ยราคาเปล่า — และต้องรวม **ก่อน** หาร
 *     หารแยกแหล่งแล้วเฉลี่ยผลลัพธ์อีกที = เฉลี่ยของค่าเฉลี่ย ซึ่งผิดเมื่อจำนวนไม่เท่ากัน
 *  🔑 ป้าย `ที่มา` ยังเป็นค่าเดิม (ฝั่งจอยิงยืนยันไปแล้ว ห้ามเปลี่ยนสตริง)
 *     แต่คืน `ที่มาของล็อต` บอกว่าล็อตมาจากใบซื้อกี่ล็อต/ใบของเข้ากี่ล็อต ⇒ ไม่เสียความโปร่งใส */
function รวมสองแหล่ง(ก, ข) {
  const out = new Map();
  for (const sku of new Set([...ก.keys(), ...ข.keys()])) {
    const a = ก.get(sku);
    const b = ข.get(sku);
    const มูลค่า = (a?.มูลค่า ?? 0) + (b?.มูลค่า ?? 0);
    const จำนวน = (a?.จำนวน ?? 0) + (b?.จำนวน ?? 0);
    if (!(จำนวน > 0)) continue;
    const วัน = [a?.ใบล่าสุด, b?.ใบล่าสุด].filter(Boolean).sort();
    out.set(sku, {
      ต้นทุน: Math.round((มูลค่า / จำนวน) * 10000) / 10000,
      ล็อต: (a?.ล็อต ?? 0) + (b?.ล็อต ?? 0),
      จำนวนรวม: จำนวน,
      ใบล่าสุด: วัน.length ? วัน[วัน.length - 1] : null,
      ที่มาของล็อต: { ใบซื้อ: a?.ล็อต ?? 0, ใบของเข้า: b?.ล็อต ?? 0 },
    });
  }
  return out;
}

/** รหัสทั้งหมดในทะเบียนสินค้า — ใช้เป็น **ตัวหาร** ของตัวนับ "ยังไม่รู้"
 *  อ่านไม่ได้ ⇒ คืน null แล้วผู้เรียกถอยไปใช้รายชื่อจากสองแหล่ง (พร้อมบอกว่าตัวหารไม่ใช่ทั้งคลัง) */
async function รหัสทั้งหมด() {
  try {
    const rows = await coreQuery(`SELECT sku FROM products WHERE sku IS NOT NULL AND sku <> ''`);
    return [...new Set((rows || []).map((r) => String(r.sku)))];
  } catch {
    return null;
  }
}

/** ราคาซื้อที่ตั้งไว้จากทะเบียนสินค้า — `{sku: number}`
 *  ⚠️ `purchase_price = 0` **ไม่เอา** ⇒ 0 ในทะเบียนแปลว่า "ไม่ได้ตั้ง" ไม่ใช่ "ต้นทุนศูนย์"
 *     (ต่างจาก `unit_cost` ของใบของเข้า ซึ่ง 0 เป็นค่าที่คนตั้งใจกรอก — คนละตารางคนละกติกา) */
async function จากทะเบียน() {
  const rows = await coreQuery(
    `SELECT sku, purchase_price FROM products WHERE purchase_price IS NOT NULL AND purchase_price > 0`
  );
  const m = new Map();
  for (const r of rows || []) {
    const v = Number(r?.purchase_price);
    if (Number.isFinite(v) && v > 0) m.set(String(r.sku), v);
  }
  return m;
}

/** ต้นทุนรายรหัสพร้อมป้ายที่มา
 *  @param {{skus?: string[], store?: string}} o  ไม่ส่ง `skus` = ทุกรหัสที่หาต้นทุนได้
 *  @returns {Promise<{ok:boolean, รหัส:object[], สรุปที่มา:object, ...}>}
 */
export async function ต้นทุนรายรหัส(o = {}) {
  if (!coreReady()) return { ok: false, error: "ยังไม่ได้ตั้ง CLOUDFLARE_D1_TOKEN" };
  const store = o.store === "z2" ? "z2" : "z1";
  const ขอ = Array.isArray(o.skus) && o.skus.length ? o.skus.map(String) : null;

  const [ซื้อดิบ, ของเข้า, ทะเบียน, ทุกรหัส] = await Promise.all([
    จากใบซื้อ(store),
    จากใบของเข้า(),
    จากทะเบียน(),
    ขอ ? Promise.resolve(null) : รหัสทั้งหมด(),
  ]);
  const ซื้อ = รวมสองแหล่ง(ซื้อดิบ, ของเข้า);

  /* 🔴 **ตัวนับ "ยังไม่รู้" ที่นับจากกองของตัวเองเท่านั้น จะได้ 0 ตลอดกาล** (แก้ 4 ต.ค. 2569 ทันทีหลังยิงของจริง)
     รุ่นแรกผมใช้ `union(ซื้อ, ทะเบียน)` เป็นรายชื่อ ⇒ รหัสที่ไม่มีต้นทุนทั้งสองแหล่ง
     **ไม่เคยอยู่ในรายชื่อตั้งแต่แรก** ⇒ `ยังไม่รู้` เป็น 0 ได้อย่างเดียว
     ⇒ ยิงของจริงได้ `{ใบซื้อ:217, ตั้งไว้:2404, ยังไม่รู้:0}` ซึ่งอ่านว่า "ทุกรหัสมีต้นทุน"
        ทั้งที่กระจกสินค้ามี 2,674 รหัส ⇒ หายไป ~53 รหัสโดยไม่มีอะไรฟ้อง
     🔑 คลาส `tautology-checks-are-always-green`: ตัวนับที่สองข้างมาจากที่เดียวกัน = ถามซ้ำ ไม่ใช่วัด
     ⇒ ไม่ส่ง `skus` มา ⇒ ไล่จาก **ทะเบียนสินค้าทั้งตาราง** เพื่อให้ "ยังไม่รู้" นับได้จริง */
  const keys = ขอ ?? (ทุกรหัส?.length
    ? ทุกรหัส
    : [...new Set([...ซื้อ.keys(), ...ทะเบียน.keys()])]);
  const out = [];
  const นับ = { [ที่มาต้นทุน.ใบซื้อ]: 0, [ที่มาต้นทุน.ตั้งไว้]: 0, [ที่มาต้นทุน.ไม่รู้]: 0 };

  for (const sku of keys) {
    const ก = ซื้อ.get(sku);
    if (ก) {
      out.push({
        sku,
        ต้นทุน: ก.ต้นทุน,
        ที่มา: ที่มาต้นทุน.ใบซื้อ,
        ล็อตที่ใช้คำนวณ: ก.ล็อต,
        จำนวนที่ซื้อรวม: ก.จำนวนรวม,
        ใบซื้อล่าสุด: ก.ใบล่าสุด,
        ที่มาของล็อต: ก.ที่มาของล็อต,
        /* ล็อตเดียว = "เฉลี่ย" ที่ไม่มีอะไรให้เฉลี่ย ⇒ ต้องบอก ไม่ใช่ปล่อยให้ดูเหมือนค่าเฉลี่ยจริง */
        ...(ก.ล็อต <= 1 ? { "⚠️": "มีใบซื้อใบเดียว — เป็นราคาของใบนั้น ไม่ใช่ค่าเฉลี่ยที่เคลื่อนที่" } : {}),
      });
      นับ[ที่มาต้นทุน.ใบซื้อ]++;
      continue;
    }
    const ข = ทะเบียน.get(sku);
    if (ข !== undefined) {
      out.push({ sku, ต้นทุน: ข, ที่มา: ที่มาต้นทุน.ตั้งไว้ });
      นับ[ที่มาต้นทุน.ตั้งไว้]++;
      continue;
    }
    /* 🔴 ต้นทุน null ไม่ใช่ 0 — 0 จะทำให้กำไรกลายเป็น 100% */
    out.push({ sku, ต้นทุน: null, ที่มา: ที่มาต้นทุน.ไม่รู้ });
    นับ[ที่มาต้นทุน.ไม่รู้]++;
  }

  return {
    ok: true,
    store,
    รหัส: out,
    สรุปที่มา: นับ,
    /* 🔑 **"ยังไม่ได้ต่อ" ต้องเป็นข้อมูล ไม่ใช่สิ่งที่คนอ่านต้องอนุมานจากคีย์ที่หายไป**
       (เพิ่ม 4 ต.ค. 2569 — ฝั่งจอยิงของจริงแล้วเจอ ไม่ได้อ่านจากจดหมาย)
       `คำอธิบายที่มา` มี 4 ป้าย แต่ `สรุปที่มา` มี 3 (ไม่มีแหล่ง ZORT เพราะยังไม่ได้ต่อ)
       ⇒ จอที่ไล่ป้ายจากคำอธิบาย แล้วอ่านจำนวนจากสรุป จะได้ `undefined`
          แล้วถ้าเผลอ `?? 0` จะขึ้นเลข **0** ซึ่งอ่านว่า "มีแหล่งนี้แต่ไม่มีรหัสไหนใช้"
          ทั้งที่ความจริงคือ **ยังไม่ได้ต่อเลย** — สองอย่างนี้คนละเรื่อง
       🔴 **ทางแก้ที่ไม่เอา: ใส่คีย์นั้นเป็น 0** — นั่นคือการยุบ "ศูนย์" กับ "ยังไม่รู้" เข้าด้วยกัน
          ซึ่งเป็นกับดักเดิมที่ไฟล์นี้ทั้งไฟล์พยายามหลีกเลี่ยง (ฝั่งจอเสนอเองว่าไม่ควร — ถูกแล้ว)
       ✅ ทางที่เอา: ประกาศรายชื่อแหล่งที่ยังไม่ได้ต่อออกมาตรง ๆ ⇒ จอไม่ต้องเดาจากความว่าง */
    "แหล่งที่ยังไม่ได้ต่อ": Object.values(ที่มาต้นทุน).filter((ป) => !(ป in นับ)),
    /* ขอบเขตของตัวนับ — ไม่มีบรรทัดนี้ คนอ่าน "ยังไม่รู้: 0" จะแปลว่าทุกรหัสมีต้นทุน */
    "ตัวหารของสรุปที่มา": ขอ
      ? `เฉพาะ ${keys.length} รหัสที่ขอมา`
      : ทุกรหัส?.length
        ? `ทะเบียนสินค้าทั้งตาราง (${keys.length} รหัส)`
        : `⚠️ อ่านทะเบียนไม่ได้ ⇒ ไล่จากรหัสที่ **มีต้นทุน** เท่านั้น (${keys.length}) ` +
          `⇒ "ยังไม่รู้" จะเป็น 0 เสมอ อ่านว่าทุกรหัสมีต้นทุนไม่ได้`,
    คำอธิบายที่มา,
    ...ขอบเขตที่ต้องติดไปทุกคำตอบ,
  };
}
