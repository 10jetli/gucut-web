//    ③ ยังไม่ได้ถาม → { ปิดอยู่: true }               ← ยังไม่ได้ตั้งคีย์ / ถูกปิดสวิตช์
//    ⚠️ "ตัดสินไม่ได้" ห้ามถูกแปลเป็นตัวเลือกใดตัวเลือกหนึ่งโดยอัตโนมัติ
//      ปลายทางต้องเขียนเองว่าจะทำยังไงเมื่อไม่รู้ ([[blank-input-invents-output]])
//
// 🚫 **ห้ามใช้ตัดสินใจเรื่องเงินโดยไม่มีคนยืนยัน**
//    เงินเดือน · ออเดอร์ · สต็อก · คืนเงิน · ราคา — ใช้ได้แค่ "เสนอ" ให้คนกดยืนยัน
//    ท่านประธานสั่งว่าใช้กับทุกอย่าง ⇒ ใช้ได้ทุกเรื่อง **แต่เรื่องเงินต้องผ่านมือคน**
//    เพราะตัดสินผิดเรื่องคอมเมนต์ = ลบคอมเมนต์ผิดหนึ่งอัน · ตัดสินผิดเรื่องเงิน = เงินหาย
//    และ **ไม่มีตัวตรวจไหนจับได้ย้อนหลัง** ([[fixes-can-destroy-truth]])
// ═══════════════════════════════════════════════════════════════════════════

const MODEL = "typesafe/jev-router";
const URL_ = "https://openrouter.ai/api/v1/chat/completions";

/** เพดานกันเผาเงิน — เรียกเกินนี้ต่อการรันฟังก์ชันหนึ่งครั้ง = หยุด */
const เพดานต่อรอบ = 60;
let นับรอบนี้ = 0;

const คีย์ = () => process.env.OPENROUTER_API_KEY || "";

/**
 * ถาม Jev ให้เลือกหนึ่งตัวเลือก
 *
 * @param {object} p
 * @param {string}   p.เรื่อง      สิ่งที่กำลังตัดสิน (เอาไปขึ้นต้นคำถาม)
 * @param {string}   p.ข้อมูล      สถานะ/ข้อความที่ให้ดู
 * @param {string[]} p.ตัวเลือก    รายการคำตอบที่ยอมรับ — ต้องมีอย่างน้อย 2
 * @param {string}   [p.เกณฑ์]     อธิบายว่าควรเลือกอันไหนเมื่อไหร่
 * @returns {Promise<{เลือก?:string, ตัดสินไม่ได้?:true, ปิดอยู่?:true, เหตุ?:string, ดิบ?:string}>}
 */
export async function เลือก({ เรื่อง, ข้อมูล, ตัวเลือก, เกณฑ์ = "" }) {
  if (!Array.isArray(ตัวเลือก) || ตัวเลือก.length < 2)
    throw new Error("ต้องมีตัวเลือกอย่างน้อย 2 อย่าง — ถามแบบปลายเปิดใช้ตัวนี้ไม่ได้");

  if (!คีย์()) return { ปิดอยู่: true, เหตุ: "ยังไม่ได้ตั้ง OPENROUTER_API_KEY" };
  if (นับรอบนี้ >= เพดานต่อรอบ)
    return { ตัดสินไม่ได้: true, เหตุ: `ถามครบเพดาน ${เพดานต่อรอบ} ครั้งแล้วในรอบนี้` };
  นับรอบนี้++;

  const คำสั่ง = [
    `${เรื่อง}`,
    เกณฑ์ ? `เกณฑ์: ${เกณฑ์}` : "",
    `ข้อมูล: ${String(ข้อมูล ?? "").slice(0, 4000)}`,
    // 🔑 บังคับรูปแบบคำตอบให้แคบที่สุด — ยิ่งเปิดกว้าง ยิ่งต้องมาเดาทีหลังว่ามันหมายถึงอะไร
    `ตอบด้วยคำเดียวจากรายการนี้เท่านั้น ห้ามอธิบาย ห้ามมีเครื่องหมายอื่น: ${ตัวเลือก.join(" / ")}`,
    `ถ้าข้อมูลไม่พอจะตัดสิน ให้ตอบว่า ไม่แน่ใจ`,
  ].filter(Boolean).join("\n");

  let ดิบ = "";
  try {
    const res = await fetch(URL_, {
      method: "POST",
      headers: { Authorization: "Bearer " + คีย์(), "Content-Type": "application/json" },
      body: JSON.stringify({
        model: MODEL,
        // ⚠️ **ห้ามตั้งต่ำกว่านี้** — วัดจริง 1 ต.ค. 2569: ตั้ง 16 แล้ว **ได้คำตอบว่างเปล่าทุกครั้ง**
        //    เพราะ Jev Router ส่งต่อให้โมเดลที่ "คิดก่อนตอบ" โควตาหมดไปกับการคิด
        //    ไม่เหลือที่พิมพ์คำตอบ ⇒ หน้าตาเหมือน "ตัดสินไม่ได้" ทั้งที่มันตัดสินได้
        //    🔑 เพดานที่ตั้งเพื่อประหยัด กลายเป็นตัวทำให้ระบบไม่ทำงานเลย โดยไม่มี error ฟ้อง
        max_tokens: 120,
        messages: [{ role: "user", content: คำสั่ง }],
      }),
    });
    if (!res.ok) return { ตัดสินไม่ได้: true, เหตุ: `ปลายทางตอบ HTTP ${res.status}` };
    const d = await res.json();
    ดิบ = String(d?.choices?.[0]?.message?.content ?? "").trim();
  } catch (e) {
    return { ตัดสินไม่ได้: true, เหตุ: `เรียกไม่สำเร็จ: ${String(e).slice(0, 80)}` };
  }

  // ── ตรวจแบบตรงตัว ── ⚠️ ห้ามใช้ includes() จับคู่ ([[no-substring-classification]])
  //    "เก็บ" เป็นสตริงย่อยของคำอื่นได้ และตัวเลือกที่ชื่อคล้ายกันจะจับคู่ผิดเงียบ ๆ
  const สะอาด = ดิบ.replace(/[\s."'`*]/g, "");
  const ตรง = ตัวเลือก.find((o) => o.replace(/\s/g, "") === สะอาด);
  if (ตรง) return { เลือก: ตรง, ดิบ };

  // 🔑 แยก "ตอบว่าง" ออกจาก "ตอบนอกรายการ" — คนละสาเหตุ คนละวิธีแก้
  //    ตอบว่าง = ฝั่งเรา/ปลายทางมีปัญหา (เพดาน token · ปลายทางล่ม)
  //    ตอบนอกรายการ = มันเข้าใจคำถามแต่ตอบไม่ตรงรูปแบบ (ต้องแก้คำสั่ง)
  //    รวมสองอย่างเป็นข้อความเดียว = วันหนึ่งจะไล่หาสาเหตุผิดทาง ([[empty-field-two-causes]])
  return {
    ตัดสินไม่ได้: true,
    เหตุ: !ดิบ ? "ปลายทางตอบว่างเปล่า"
      : สะอาด.includes("ไม่แน่ใจ") ? "บอกเองว่าข้อมูลไม่พอ"
        : "ตอบนอกรายการตัวเลือก",
    ดิบ,
  };
}

/** สถานะสำหรับหน้าตรวจระบบ — ไม่เรียก Jev จริง แค่บอกว่าพร้อมไหม */
export const พร้อมไหม = () => ({
  ตั้งค่าแล้ว: Boolean(คีย์()),
  โมเดล: MODEL,
  ถามไปแล้วรอบนี้: นับรอบนี้,
  เพดานต่อรอบ,
});
