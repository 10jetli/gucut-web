//    ⇒ ไฟล์นี้จึงต้อง **บังคับให้ตอบได้แค่ตัวเลือกที่เรากำหนด แล้วตรวจแบบตรงตัวอักษร**
//    ⚠️ ห้ามแต่งตัวเลข "ความมั่นใจ" ขึ้นมาเอง — ตัวเลขที่ไม่ได้มาจากของจริงอันตรายกว่าไม่มีเลย
