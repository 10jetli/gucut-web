/** จำนวนที่เหลือของทุกกลุ่ม อ่านสดจากทะเบียน
 *  @param {{query?: Function}} o `query` ฉีดเข้ามาได้เพื่อให้เทสเรียกฟังก์ชันจริงได้ (ไม่ใช่ regex)
 *  @returns {Promise<Map<string, number>>} คีย์ `<kind>|<ชื่อกลุ่ม>` → จำนวนที่เหลือ */
export async function ทะเบียนเหลือทุกกลุ่ม({ query = coreQuery } = {}) {
  /* 🔑 **บอกเหตุให้ตรงตัวตั้งแต่ต้น** — ไม่ได้ตั้งโทเคน ≠ ฐานล่ม ≠ ทะเบียนว่าง
     ทั้งสามจบที่ "ใช้ค่าแช่แข็ง" เหมือนกัน แต่ **ทางแก้คนละเรื่องสิ้นเชิง**
     ⇒ ถ้าเหตุเหมารวมเป็น "อ่านไม่ได้" คนจะไปไล่ฐานข้อมูลทั้งที่แค่ลืมตั้ง env
     (เฉพาะตอนใช้ท่อจริง — เทสที่ฉีด `query` เข้ามาต้องไม่ติดด่านนี้) */
  if (query === coreQuery && !coreReady()) {
    throw new ทะเบียนอ่านไม่ได้("ยังไม่ได้ตั้ง CLOUDFLARE_D1_TOKEN ในฟังก์ชันนี้ ⇒ อ่านทะเบียนสดไม่ได้");
  }
  let แถว;
  try {
    แถว = await query(SQL_กลุ่มทะเบียน);
  } catch (e) {
    throw new ทะเบียนอ่านไม่ได้(`อ่านทะเบียนไม่สำเร็จ: ${e?.message || e}`);
  }
  /* 🔴 **ตอบกลับที่ไม่ใช่อาร์เรย์ = ไม่รู้ ห้ามตีเป็นชุดว่าง**
     ชุดว่างจะทำให้ทุกรหัสกลายเป็น "หมด" พร้อมกันทั้งเว็บ โดยไม่มี error
     [[ไม่รู้ห้ามกลายเป็นศูนย์ที่ชั้นจอ]] */
  if (!Array.isArray(แถว)) throw new ทะเบียนอ่านไม่ได้("ทะเบียนตอบกลับไม่ใช่อาร์เรย์");
  if (!แถว.length) throw new ทะเบียนอ่านไม่ได้("ทะเบียนไม่มีแถวเลย — ยังไม่นำเข้า หรืออ่านไม่ครบ");
  const m = new Map();
  for (const g of รวมกลุ่มทะเบียน(แถว).values()) m.set(คีย์กลุ่ม(g.kind, g.ชื่อ), Number(g.left_ || 0));
  return m;
}

/** จำนวนที่เหลือของรหัสเดียว อ่านสดจากทะเบียน — **สามสถานะต้องแยกให้ขาด**
 *  · `null`  = ไม่ใช่ของในทะเบียน ⇒ ผู้เรียกไปใช้ ZORT ต่อได้
 *  · `>= 0`  = เลขจากทะเบียนจริง (0 = อยู่ในทะเบียนแต่ขายหมด **ห้ามถอยไปใช้ ZORT**)
 *  · โยน `ทะเบียนอ่านไม่ได้` = **ไม่รู้** ⇒ ผู้เรียกต้องตัดสินเองและ **ประกาศว่าไม่ใช่เลขสด**
 *    🚫 ห้ามแปลงกรณีนี้เป็น 0 หรือเป็น null เงียบ ๆ — 0 ปิดขายของที่มี · null เด้งไป ZORT ที่เชื่อไม่ได้
 *  @param {{กลุ่มที่เหลือ?: Map<string,number>, query?: Function}} o ส่ง `กลุ่มที่เหลือ` มาได้ถ้าอ่านไว้แล้ว */
export async function ทะเบียนเหลือของรหัส(sku, o = {}) {
  const g = รหัสเป็นกลุ่มทะเบียน[String(sku ?? "").trim()];
  if (!g) return null;
  const m = o.กลุ่มที่เหลือ || (await ทะเบียนเหลือทุกกลุ่ม(o));
  const คีย์ = คีย์กลุ่ม(g.kind, g.ชื่อ);
  const n = m.get(คีย์);
  /* อ่านฐานได้ แต่ไม่มีกลุ่มนี้ในทะเบียน = **ไม่รู้** ไม่ใช่ศูนย์
     (กลุ่มที่ขายหมดจริงยังมีแถวอยู่ ⇒ SUM ให้ 0 ⇒ มาถึงบรรทัดนี้ไม่ได้)
     ⇒ ถ้าเงียบแล้วตอบ 0 ที่นี่ รหัสที่ยังไม่ได้นำเข้าทะเบียนจะกลายเป็น "สินค้าหมด" ตลอดกาล */
  if (typeof n !== "number" || !Number.isFinite(n)) {
    throw new ทะเบียนอ่านไม่ได้(`ทะเบียนไม่มีกลุ่ม ${คีย์} (รหัส ${sku}) — อ่านได้แต่หากลุ่มไม่เจอ`);
  }
  return n;
}
